/**
 * Indicators about risk rules and policy overrides for the admin risk overview.
 *
 * This summary DTO provides a compact view of how the risk engine is configured
 * at a given point in time. It reports how many rules exist in total, how many
 * are active in production, how many are disabled, and how many explicit policy
 * overrides are in effect.
 *
 * The metrics are derived from configuration entities such as the
 * `shopping_mall_risk_rules` and `shopping_mall_policy_overrides` tables. They
 * help risk and governance teams understand whether the rule set is
 * sufficiently rich, whether there are many dormant or experimental rules, and
 * how heavily the platform depends on ad‑hoc overrides.
 *
 * Typical usage includes rendering an admin dashboard card in the risk overview
 * page, feeding governance reports about rule coverage, and supporting
 * operational reviews of how consistently policies are enforced across the
 * marketplace.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallRiskRuleStatsSummary = {
  /**
   * Total number of risk rules configured in the platform’s risk engine at
   * the time of aggregation.
   *
   * This count includes all rules regardless of whether they are currently
   * active or disabled. It reflects the overall size and complexity of the
   * rule set defined in configuration tables such as
   * `shopping_mall_risk_rules`.
   *
   * Administrators use this value to understand the breadth of risk coverage,
   * to track growth in rule definitions over time, and to compare the
   * configured rule surface area across environments (for example, staging
   * versus production).
   */
  totalRiskRuleCount: number & tags.Type<"int32">;

  /**
   * Number of risk rules that are currently active and evaluated by the risk
   * engine in production.
   *
   * Only rules that are enabled and meet activation criteria are counted
   * here. These rules directly participate in evaluating transactions,
   * accounts, or events and can produce risk scores or flags in real time.
   *
   * A healthy configuration typically keeps this number aligned with business
   * needs: too few active rules may indicate gaps in coverage, while too many
   * poorly-managed active rules may be harder to monitor and tune
   * effectively.
   */
  activeRiskRuleCount: number & tags.Type<"int32">;

  /**
   * Number of risk rules that are configured but currently disabled or not
   * evaluated by the risk engine.
   *
   * Disabled rules can represent experiments that have been turned off,
   * retired rules that are kept for historical reference, or temporarily
   * paused rules under investigation. They remain present in configuration
   * tables but are excluded from live evaluation.
   *
   * Monitoring this value helps governance teams identify configuration
   * clutter, track how many rules are pending review, and decide whether
   * disabled rules should be cleaned up, reactivated, or archived according
   * to internal policy.
   */
  disabledRiskRuleCount: number & tags.Type<"int32">;

  /**
   * Number of explicit policy overrides that modify or bypass the default
   * behavior of risk rules.
   *
   * Policy overrides are higher-level configurations, often stored in a table
   * such as `shopping_mall_policy_overrides`, that selectively change how
   * certain risk rules or policy decisions are applied for specific actors,
   * segments, or scenarios.
   *
   * A high override count can signal that default policies are being heavily
   * customized or frequently bypassed, which may warrant a governance review.
   * Administrators use this metric to reason about policy consistency and the
   * potential need to consolidate overrides into more maintainable core
   * rules.
   */
  policyOverrideCount: number & tags.Type<"int32">;
};
