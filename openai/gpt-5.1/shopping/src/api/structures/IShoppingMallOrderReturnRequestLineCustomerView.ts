import { tags } from "typia";

/**
 * Customer-facing view of a single order line that is part of an order return
 * request.
 *
 * This DTO links a specific `shopping_mall_order_lines` record to its
 * participation in an order return request and is always embedded inside
 * `IShoppingMallOrderReturnRequestCustomerView.lines`. It provides a compact
 * subset of line information—product identity, SKU code, the originally ordered
 * quantity, the quantity the customer is requesting to return, and an optional
 * per-line requested refund amount—so that customers and support staff can see
 * exactly which items are affected by the return without loading the full order
 * line entity.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallOrderReturnRequestLineCustomerView = {
  /**
   * Unique identifier of the order line in the `shopping_mall_order_lines`
   * table that this return request line refers to.
   *
   * This value maps directly to the `id` column of the underlying order line
   * record and allows backends and clients to correlate the return entry with
   * other views and operations that reference the same line, such as full
   * order details, shipment breakdowns, and per-line fulfillment or refund
   * histories.
   */
  order_line_id: string & tags.Format<"uuid">;

  /**
   * Human-readable SKU code of the product variant for this line, suitable
   * for display in customer-facing UIs.
   *
   * Typically this value originates from a snapshot field such as
   * `sku_code_snapshot` on the order line or from the SKU `code` at the time
   * the order was placed. Storing it here ensures that the correct variant
   * identifier is shown even if catalog metadata or SKU definitions change
   * later.
   */
  sku_code: string;

  /**
   * Name of the product for the order line, as captured at the time of
   * checkout.
   *
   * This usually corresponds to a snapshot column (for example,
   * `product_name_snapshot`) on the `shopping_mall_order_lines` record and
   * preserves the product name as the customer saw it when they placed the
   * order. This guarantees that return request views remain stable and
   * understandable even if the product name is edited in the catalog after
   * the order was created.
   */
  product_name: string;

  /**
   * Total quantity originally ordered for this line.
   *
   * This value maps to the `quantity` column on the associated
   * `shopping_mall_order_lines` record and represents the number of units
   * that were successfully ordered for this SKU in the original order. It
   * does not take returns or cancellations into account by itself; it is the
   * baseline against which `quantity_requested_return` is interpreted.
   */
  quantity_ordered: number & tags.Type<"int32">;

  /**
   * Quantity from this line that the customer has requested to return in this
   * order return request.
   *
   * This number is always less than or equal to `quantity_ordered` and
   * indicates how many units from the original line are included in this
   * specific return request. It supports partial returns where only a subset
   * of the originally ordered items are being sent back, and it allows
   * back-office workflows to reconcile returns with the underlying order and
   * inventory records.
   */
  quantity_requested_return: number & tags.Type<"int32">;

  /**
   * Requested refund amount for this particular order line within the return
   * request, expressed in the same currency as the parent order.
   *
   * When present, this value represents the portion of the overall
   * `requested_refund_amount` that is attributable to this line, after any
   * distribution of discounts, taxes, and shipping costs that the business
   * rules apply. Some implementations may leave this field undefined or
   * exclude it from the response when per-line monetary breakdowns are not
   * calculated or stored; in those cases, clients should rely on the
   * aggregate `requested_refund_amount` on the parent return request instead
   * of per-line amounts.
   */
  line_requested_refund_amount?: number | undefined;
};
