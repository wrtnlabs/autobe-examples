import { IReviewModerationState } from "./IReviewModerationState";

/**
 * Filter options for restricting review analytics based on moderation and
 * visibility states.
 *
 * This helper type allows clients to express which visibility_status and
 * moderation_state values from shopping_mall_reviews should be considered when
 * computing analytics. It can be used to focus on visible reviews, pending
 * items, or specific flagged subsets.
 *
 * Filters in this structure are optional and can be combined to express more
 * precise slices, such as only visible reviews that are in a particular
 * moderation state.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IReviewModerationFilter = {
  /**
   * List of visibility_status values to include.
   *
   * Values must match the application-defined codes stored in
   * shopping_mall_reviews.visibility_status, such as visible, hidden,
   * pending_moderation, or removed.
   */
  visibilityStatuses?: string[] | undefined;

  /**
   * List of moderation_state values to include in analytics.
   *
   * Values must match the business-defined moderation states tracked in
   * shopping_mall_reviews.moderation_state, enabling focused views on
   * specific phases of the moderation lifecycle.
   */
  moderationStates?: IReviewModerationState[] | undefined;
};
