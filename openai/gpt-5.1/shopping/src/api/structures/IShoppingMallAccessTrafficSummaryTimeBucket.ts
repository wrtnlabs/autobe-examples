import { tags } from "typia";

/**
 * Time-bucketed access traffic metrics for a single contiguous time slice
 * within a larger analysis window.
 *
 * Each instance of this type represents one bucket in a time series that
 * summarizes HTTP access traffic derived from the `shopping_mall_access_logs`
 * table. Buckets are aligned to the time-bucket granularity selected in the
 * parent `IShoppingMallAccessTrafficSummary.IRequest` (for example minute,
 * hour, or day).
 *
 * All counts in this structure are calculated **after** the server has applied
 * every filter specified in the parent request, such as actor type, HTTP
 * method, status-code family, and route pattern. As a result, clients can
 * safely treat each bucket as an already-filtered view of traffic for
 * visualization and analytics purposes.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallAccessTrafficSummaryTimeBucket = {
  /**
   * Start timestamp of the time bucket in ISO 8601 `date-time` format (UTC).
   *
   * This value represents the **inclusive lower bound** of the bucket. It is
   * aligned to the configured analytics granularity (for example, the start
   * of the minute, hour, or day) and always falls within the overall analysis
   * window requested by the client.
   *
   * When aggregating records from `shopping_mall_access_logs`, any log entry
   * with a timestamp greater than or equal to `bucketStart` and strictly less
   * than `bucketEnd` will be counted in this bucket.
   */
  bucketStart: string & tags.Format<"date-time">;

  /**
   * End timestamp of the time bucket in ISO 8601 `date-time` format (UTC).
   *
   * This value represents the **exclusive upper bound** of the bucket. In a
   * typical series it is equal to `bucketStart` plus one unit of the selected
   * time-bucket duration (for example, one minute, one hour, or one day).
   * Records with timestamps in the half-open interval `[bucketStart,
   * bucketEnd)` belong to this bucket.
   *
   * For the last bucket in an analysis window, `bucketEnd` may be equal to
   * the overall analysis end time even if the bucket does not represent a
   * full period, allowing partially filled trailing buckets to be returned in
   * a consistent way.
   */
  bucketEnd: string & tags.Format<"date-time">;

  /**
   * Number of access log entries observed within this time bucket after all
   * analytics filters have been applied.
   *
   * The server computes this value from the `shopping_mall_access_logs` table
   * by counting log records whose timestamps fall within `[bucketStart,
   * bucketEnd)` and that match every filter provided in
   * `IShoppingMallAccessTrafficSummary.IRequest` (such as actor type, HTTP
   * method, status-code family, and route pattern).
   *
   * Any internal de-duplication, exclusion of health checks, or bot filtering
   * is performed before this aggregation step. Therefore, `requestCount`
   * reflects the effective traffic level that should be presented to
   * operators in dashboards, charts, or export reports.
   */
  requestCount: number & tags.Type<"int32"> & tags.Minimum<0>;
};
