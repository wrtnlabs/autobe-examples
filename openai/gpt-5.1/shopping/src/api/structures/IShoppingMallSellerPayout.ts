  /**
   * Summary representation of a seller payout batch in the shopping mall
   * platform.
   *
   * This DTO is a read-optimized projection of a single row in the
   * `shopping_mall_seller_payouts` Prisma model and is primarily used for
   * payout history lists, finance dashboards, and links from related
   * financial entities. It exposes the main identifiers, status, monetary
   * totals, and key provider and failure diagnostics without expanding into
   * line-level payout items.
   *
   * The monetary amounts map 1:1 to the corresponding database columns:
   * `gross_amount` represents the sum of all positive earnings in the batch,
   * `fee_amount` aggregates platform commissions and fees,
   * `adjustment_amount` captures manual or exceptional adjustments, and
   * `net_amount` is the final amount actually paid out to the seller.
   */
  export type ISummary = {
    /**
     * Unique identifier of the seller payout batch.
     *
     * This is the primary key of the `shopping_mall_seller_payouts` record
     * and is used by internal services and external API consumers to
     * reference a specific payout across APIs, logs, and reports.
     */
    id: string & tags.Format<"uuid">;

    /**
     * Business identifier of the payout batch, unique per seller for
     * reconciliation and communication.
     *
     * This value is typically more human-friendly than the UUID `id` and
     * may be used on statements, exports, and emails as the primary
     * reference when communicating about a payout with the seller and
     * internal finance staff.
     */
    payout_number: string;

    /**
     * Current status of the payout, as stored in the `payout_status` column
     * of `shopping_mall_seller_payouts`.
     *
     * Common values include states such as `payout_pending`,
     * `payout_in_progress`, `payout_failed`, or `payout_sent`. Integrators
     * should treat this as the source of truth for whether a payout is
     * still pending, has been successfully sent, or encountered errors that
     * require manual intervention.
     */
    payout_status: string;

    /**
     * ISO currency code of the payout, as stored in the `currency` column
     * of `shopping_mall_seller_payouts`.
     *
     * This is an ISO 4217 code such as `USD`, `EUR`, or `KRW` and
     * determines the unit in which all monetary fields of this summary
     * (`gross_amount`, `fee_amount`, `adjustment_amount`, and `net_amount`)
     * are expressed.
     */
    currency: string;

    /**
     * Total gross amount of all positive earnings included in this payout
     * before fees and adjustments.
     *
     * The value maps directly to the `gross_amount` column of
     * `shopping_mall_seller_payouts` and typically aggregates item revenue,
     * shipping revenue, and other seller-credited components for the
     * covered period and orders.
     */
    gross_amount: number;

    /**
     * Total amount of platform fees or commissions deducted from the seller
     * as part of this payout.
     *
     * This corresponds to the nullable `fee_amount` column in
     * `shopping_mall_seller_payouts`. When present, it represents the sum
     * of all platform fees and commissions that reduce the gross earnings
     * before arriving at the net payout. When absent, either there were no
     * fees or they were not broken out at this level.
     */
    fee_amount?: number | undefined;

    /**
     * Net effect of manual adjustments included in this payout, mapped from
     * the nullable `adjustment_amount` column.
     *
     * Adjustments may include manual credits or debits applied by
     * operations or finance teams, such as goodwill credits, corrections,
     * or retroactive adjustments. A positive value increases the payout to
     * the seller, whereas a negative value reduces it.
     */
    adjustment_amount?: number | undefined;

    /**
     * Net amount actually paid out to the seller after fees and
     * adjustments.
     *
     * This value is taken from the `net_amount` column of
     * `shopping_mall_seller_payouts` and represents the final amount sent
     * to the seller via the configured provider. In finance and
     * reconciliation views, this is the figure that should match bank
     * statements or provider settlement reports.
     */
    net_amount: number;

    /**
     * Optional start of the earnings period covered by this payout.
     *
     * This corresponds to the nullable `period_start` column and is
     * typically used when payouts are batched over a specific time window
     * (for example, a weekly or monthly period). When provided, it helps
     * finance teams and sellers understand which transactions are expected
     * to be included.
     */
    period_start?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Optional end of the earnings period covered by this payout.
     *
     * It maps to the nullable `period_end` column in
     * `shopping_mall_seller_payouts`. Together with `period_start`, it
     * describes the time interval whose transactions were aggregated into
     * this payout batch for reporting and reconciliation.
     */
    period_end?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Name or code of the external payment provider or bank used to send
     * this payout.
     *
     * This maps to the nullable `provider_name` column and may contain
     * values such as a payment processor name, internal clearing system, or
     * bank identifier. It is primarily used by operations and finance teams
     * when reconciling payouts with external settlement channels.
     */
    provider_name?: string | undefined;

    /**
     * Identifier for this payout at the external provider or bank.
     *
     * The value maps to the nullable `provider_payout_id` column and is
     * typically a reference or transaction ID returned by the payment
     * provider. It enables precise tracing of payouts when investigating
     * disputes, reconciliation mismatches, or provider-side issues.
     */
    provider_payout_id?: string | undefined;

    /**
     * Optional machine-readable code describing why the payout failed.
     *
     * This field corresponds to the nullable `failure_reason_code` column
     * on `shopping_mall_seller_payouts`. It is populated when
     * `payout_status` indicates a failure and allows automated systems or
     * dashboards to categorize and aggregate failure causes.
     */
    failure_reason_code?: string | undefined;

    /**
     * Optional human-readable message with more detail about a payout
     * failure.
     *
     * The value is taken from the nullable `failure_reason_message` column
     * and is designed to be shown in internal tools or logs to help
     * operators quickly understand what went wrong when a payout could not
     * be completed successfully.
     */
    failure_reason_message?: string | undefined;

    /**
     * Timestamp when this payout record was created.
     *
     * This is the `created_at` column from `shopping_mall_seller_payouts`
     * and is generally set when the payout batch is first generated by the
     * settlement logic. It is useful for sorting payout history and for
     * understanding when the batch entered the system.
     */
    created_at: string & tags.Format<"date-time">;

    /**
     * Timestamp when this payout record was last updated.
     *
     * This maps to the `updated_at` column and changes whenever the payout
     * batch status, amounts, or associated metadata are modified. It allows
     * operators to see when the latest state transition or correction was
     * applied.
     */
    updated_at?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Summary information about the seller that receives this payout batch.
     *
     * The embedded `IShoppingMallSeller.ISummary` DTO provides concise
     * seller identification and display information, so list and dashboard
     * consumers can render meaningful seller context alongside payout rows
     * without issuing additional seller lookups.
     */
    seller: IShoppingMallSeller.ISummary;
  };
