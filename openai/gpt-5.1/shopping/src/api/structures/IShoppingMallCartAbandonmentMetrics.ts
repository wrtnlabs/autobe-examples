/**
 * Aggregated cart abandonment metrics for a specific analysis window and cohort
 * of shoppers.
 *
 * This schema represents how often carts are abandoned at different stages of
 * the checkout funnel, together with a normalized abandonment rate. It is
 * designed for use in analytics dashboards and reporting views, rather than as
 * a direct persistence model.
 *
 * The metrics are typically computed over a well-defined analytics window, such
 * as a day, week, or campaign period, and may be scoped to particular segments
 * (for example, country, device type, or traffic source). Implementations can
 * derive these metrics from cart, order, and checkout event logs while ensuring
 * consistent filtering criteria.
 *
 * The structure is intentionally compact so that it can be embedded inside
 * higher-level friction analytics responses or combined with additional
 * dimensions such as geography, seller, or marketing campaign without excessive
 * payload size.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCartAbandonmentMetrics = {
  /**
   * Overall cart abandonment rate as a fraction between 0 and 1 for the
   * selected analysis window.
   *
   * In most implementations this is computed as `(number of carts that did
   * not convert to completed orders) / (total number of carts considered in
   * the cohort)`. The definition of "conversion" should be stable and clearly
   * documented in the analytics pipeline to keep this metric comparable over
   * time.
   *
   * The value is provided as a unitless ratio rather than a percentage so
   * that clients can render it as either a fraction or a percentage according
   * to their presentation needs.
   */
  cartAbandonmentRate: number & tags.Minimum<0> & tags.Maximum<1>;

  /**
   * Average elapsed time in seconds from cart creation to first checkout
   * attempt for carts that reached the checkout stage at least once within
   * the analysis window.
   *
   * Only carts that actually attempt checkout are included in this average;
   * carts abandoned before checkout are excluded from the denominator. This
   * makes the metric useful for understanding friction within the active
   * checkout funnel, separate from early-stage browsing abandonment.
   *
   * Consumers can use this metric alongside abandonment counts to spot
   * unusually long pre-checkout intervals that might signal UX issues or
   * performance problems.
   */
  averageTimeToCheckoutSeconds: number & tags.Minimum<0>;

  /**
   * Number of carts that were abandoned before ever reaching the checkout
   * stage in the selected analysis window.
   *
   * These are carts where users added items but never initiated a checkout
   * workflow. High values can indicate issues such as unclear pricing,
   * missing shipping information, or general lack of purchase intent.
   *
   * This count is a raw integer and is typically interpreted together with
   * cartAbandonmentRate and overall cart population metrics to understand
   * top-of-funnel friction.
   */
  abandonedBeforeCheckoutCount: number & tags.Type<"int32"> & tags.Minimum<0>;

  /**
   * Number of carts that reached the checkout stage at least once but did not
   * complete an order in the selected analysis window.
   *
   * These abandonment events happen after the user has already committed to
   * the checkout flow and therefore are often more critical from a conversion
   * perspective. Common causes include payment failures, shipping cost
   * surprises, or validation errors discovered late in the process.
   *
   * This count is a raw integer and is often broken down further in other
   * analytics models by payment method, shipping method, or validation
   * failure types for root-cause analysis.
   */
  abandonedDuringCheckoutCount: number & tags.Type<"int32"> & tags.Minimum<0>;
};
