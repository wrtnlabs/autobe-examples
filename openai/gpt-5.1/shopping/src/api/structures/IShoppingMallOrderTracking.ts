import { tags } from "typia";

/**
 * Logistics-focused tracking view for a customer-facing order in the shopping
 * mall platform.
 *
 * This DTO composes read-only data from shipment-oriented tables such as
 * shopping_mall_shipments and shopping_mall_shipment_events, while also
 * including contextual information from shopping_mall_orders,
 * shopping_mall_shipping_addresses, and shopping_mall_shipping_methods where
 * necessary.
 *
 * The purpose of this type is to provide customers with a clear, concise
 * picture of the current shipping state of their order, including shipment
 * summaries, carrier and tracking information, destination address snapshot,
 * and a chronological list of carrier or logistics events per shipment.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallOrderTracking = {
  /**
   * High-level summary of the order contextual information used in the
   * tracking view.
   *
   * This summary is similar to the timeline order summary but is tailored for
   * logistics, emphasizing status, totals, and the presence or absence of
   * active shipments.
   */
  order: IShoppingMallOrderTracking.IOrderSummary;

  /**
   * List of shipment-level tracking views associated with this order.
   *
   * Each shipment entry describes a seller-specific fulfillment unit,
   * including carrier and tracking information, destination address snapshot,
   * shipping method, and a chronological list of shipment events as seen by
   * the logistics system.
   */
  shipments: IShoppingMallOrderTracking.IShipment[];
};
export namespace IShoppingMallOrderTracking {
  /**
   * Condensed order summary specifically tailored for use within the
   * logistics tracking view.
   *
   * This type exposes the business order code, currency, overall order
   * status, grand total, and placed_at timestamp, providing sufficient
   * context for customers to confirm which order they are tracking.
   *
   * It is derived from shopping_mall_orders and intentionally avoids exposing
   * internal technical identifiers while mirroring the key customer-facing
   * attributes needed for shipping and delivery tracking pages.
   */
  export type IOrderSummary = {
    /**
     * Business-facing order code stored on shopping_mall_orders.order_code.
     *
     * This is the same value used in path parameter {orderCode} and in
     * customer communications such as emails, receipts, and support
     * references.
     */
    order_code: string;

    /**
     * ISO 4217 currency code for this order as stored in
     * shopping_mall_orders.currency_code.
     *
     * All displayed amounts in the tracking view correspond to this
     * currency.
     */
    currency_code: string;

    /**
     * Current high-level business status of the order taken from
     * shopping_mall_orders.current_status.
     *
     * Even though this view focuses on logistics, this status provides a
     * quick overview of the broader order lifecycle, especially during
     * pre-shipment phases.
     */
    current_status: string;

    /**
     * Grand total amount charged for the order, mapped from
     * shopping_mall_orders.grand_total_amount.
     *
     * It gives customers and support agents a quick sense of the monetary
     * size of the shipment being tracked.
     */
    grand_total_amount: number;

    /**
     * Timestamp when the order was placed by the customer, corresponding to
     * shopping_mall_orders.placed_at.
     *
     * This timestamp is helpful to validate that the tracking view matches
     * the expected order age and lifecycle stage.
     */
    placed_at: string & tags.Format<"date-time">;
  };

  /**
   * Shipment-level tracking view associated with a particular order.
   *
   * This type aggregates fields from shopping_mall_shipments, including
   * shipping_status, carrier and tracking identifiers, and fulfillment
   * timestamps, together with contextual information from
   * shopping_mall_shipping_addresses and shopping_mall_shipping_methods.
   *
   * It also contains an ordered list of shipment events based on
   * shopping_mall_shipment_events, enabling clients to present a detailed
   * shipment history, including carrier scans, status transitions, and
   * exception handling steps.
   */
  export type IShipment = {
    /**
     * Business-facing shipment code, taken from
     * shopping_mall_shipments.shipment_code.
     *
     * This identifier is used in internal and seller-facing tools and can
     * also be shown to customers when multiple shipments exist for a single
     * order.
     */
    shipment_code: string;

    /**
     * Current shipping status for this shipment, reflecting
     * shopping_mall_shipments.shipping_status.
     *
     * Common values include pending, preparing, ready_for_pickup, shipped,
     * in_transit, out_for_delivery, delivered, delivery_failed, returned,
     * or cancelled. They summarize the logistics lifecycle for this
     * shipment.
     */
    shipping_status: string;

    /**
     * Name of the carrier handling this shipment, derived from
     * shopping_mall_shipments.carrier_name.
     *
     * This value is typically a courier company or logistics provider name
     * and may be null when the shipment has not yet been assigned to a
     * specific carrier.
     */
    carrier_name?: string | undefined;

    /**
     * Tracking number assigned by the carrier, mapped from
     * shopping_mall_shipments.tracking_number.
     *
     * Customers can use this identifier on external carrier portals when
     * available; the platform may also use it to poll carrier APIs for
     * updated events.
     */
    tracking_number?: string | undefined;

    /**
     * Optional expected ship date for this shipment, matching
     * shopping_mall_shipments.expected_ship_date.
     *
     * It indicates when the shipment is planned to leave the seller or
     * warehouse and is useful for displaying promised dispatch time frames.
     * This field may be null if not defined by the business process.
     */
    expected_ship_date?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Timestamp when the shipment was actually shipped, mapped from
     * shopping_mall_shipments.shipped_at.
     *
     * This field becomes non-null once the shipment has entered the carrier
     * network or is otherwise marked as shipped.
     */
    shipped_at?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Timestamp when the shipment was confirmed delivered, matching
     * shopping_mall_shipments.delivered_at.
     *
     * This field is null until delivery is completed or confirmed.
     */
    delivered_at?: (string & tags.Format<"date-time">) | undefined;

    /**
     * Snapshot of the destination shipping address associated with this
     * shipment.
     *
     * This object is derived from shopping_mall_shipping_addresses and
     * optionally shopping_mall_customer_address_snapshots and is used to
     * show where the shipment is destined without exposing underlying
     * identity tables directly.
     */
    shipping_address: IShoppingMallOrderTracking.IShippingAddressSummary;

    /**
     * Snapshot of the shipping method information for this shipment.
     *
     * Derived from shopping_mall_shipping_methods, it includes the method
     * code and display name used to present the service level to
     * customers.
     */
    shipping_method: IShoppingMallOrderTracking.IShippingMethodSummary;

    /**
     * Chronologically ordered list of shipment events associated with this
     * shipment.
     *
     * These events are composed from shopping_mall_shipment_events and
     * contain detailed tracking information such as carrier scans, status
     * changes, and internal logistics notes.
     */
    events: IShoppingMallOrderTracking.IShipmentEvent[];
  };

  /**
   * Snapshot summary of the destination shipping address used for a shipment.
   *
   * This type maps to shopping_mall_shipping_addresses and exposes only the
   * fields necessary for customer-facing tracking views, such as the
   * recipient name, key address lines, city, postal code, country, and
   * optional region and contact phone.
   *
   * The goal is to present where the shipment is going without exposing
   * internal address identifiers or identity-specific linkage details.
   */
  export type IShippingAddressSummary = {
    /**
     * Name of the recipient for this shipment, mapped from
     * shopping_mall_shipping_addresses.recipient_name.
     *
     * This value is what carriers and delivery personnel use to identify
     * the consignee at the destination.
     */
    recipient_name: string;

    /**
     * First line of the street address, matching
     * shopping_mall_shipping_addresses.line1.
     *
     * This typically contains the primary street and building information
     * for the destination.
     */
    line1: string;

    /**
     * Second line of the street address, matching
     * shopping_mall_shipping_addresses.line2.
     *
     * This field is optional and may contain apartment, suite, unit, or
     * additional location details when provided.
     */
    line2?: string | undefined;

    /**
     * City or locality component of the shipping address, as stored in
     * shopping_mall_shipping_addresses.city.
     *
     * Displayed to the customer and support for verification and routing
     * clarity.
     */
    city: string;

    /**
     * Postal or ZIP code for the shipping destination, mapped from
     * shopping_mall_shipping_addresses.postal_code.
     *
     * This value is used by carriers and logistics systems for routing and
     * delivery.
     */
    postal_code: string;

    /**
     * ISO 3166-1 alpha-2 country code for the shipping address, taken from
     * shopping_mall_shipping_addresses.country_code.
     *
     * It identifies the destination country in a standardized format,
     * enabling both UI display and downstream integration with carriers.
     */
    country_code: string;

    /**
     * Optional region, state, or province for the shipping address,
     * matching shopping_mall_shipping_addresses.region.
     *
     * This value supplements city and postal code to clarify the
     * destination, especially in countries where regions are critical for
     * logistics.
     */
    region?: string | undefined;

    /**
     * Optional contact phone number associated with this shipping address,
     * matching shopping_mall_shipping_addresses.phone_number.
     *
     * Used for carrier notifications or delivery coordination with the
     * recipient when permitted by policy.
     */
    phone_number?: string | undefined;
  };

  /**
   * Snapshot summary of the shipping method applied to a shipment.
   *
   * This type maps to shopping_mall_shipping_methods and provides the method
   * code and display name, along with an optional service level description,
   * enabling customers to understand whether the shipment uses standard,
   * express, or another configured delivery service.
   *
   * It is designed as a compact, read-only view for tracking pages and order
   * detail screens.
   */
  export type IShippingMethodSummary = {
    /**
     * Machine-readable shipping method code from
     * shopping_mall_shipping_methods.method_code.
     *
     * Typical values include labels such as standard, express, or
     * provider-specific codes, and they are primarily used internally for
     * routing and pricing logic.
     */
    method_code: string;

    /**
     * Human-readable shipping method name, mapped from
     * shopping_mall_shipping_methods.display_name.
     *
     * This label is presented to customers and sellers to describe the
     * delivery service, for example "Standard Shipping" or "Express
     * Courier".
     */
    display_name: string;

    /**
     * Optional description for the shipping service level, taken from
     * shopping_mall_shipping_methods.service_level_description.
     *
     * This text can outline expected delivery windows, handling
     * characteristics, or other information relevant to customer
     * expectations.
     */
    service_level_description?: string | undefined;
  };

  /**
   * Detailed event from the shipping and tracking timeline of a specific
   * shipment.
   *
   * This type maps to shopping_mall_shipment_events and provides an
   * event_type, optional shipping status, an optional human-friendly
   * description, and the event_time stored in the database.
   *
   * It is used to build the per-shipment tracking history shown in order
   * tracking and support tooling, and may reflect both carrier-originated and
   * system-originated updates.
   */
  export type IShipmentEvent = {
    /**
     * Machine-readable event type, matching
     * shopping_mall_shipment_events.event_type.
     *
     * Typical values include status_change, carrier_scan,
     * address_correction, manual_override, or other domain-specific codes
     * that categorize the kind of tracking event.
     */
    event_type: string;

    /**
     * Optional shipping status value associated with this event, mapped
     * from shopping_mall_shipment_events.status.
     *
     * When present, this status should mirror or refine values used in
     * shopping_mall_shipments.shipping_status, such as in_transit,
     * out_for_delivery, or delivered.
     */
    status?: string | undefined;

    /**
     * Optional human-readable description providing more detail about this
     * shipment event, matching shopping_mall_shipment_events.description.
     *
     * This may contain carrier messages, internal logistics notes, or
     * customer-visible text suitable for tracking UIs.
     */
    description?: string | undefined;

    /**
     * Timestamp when the event occurred, taken from
     * shopping_mall_shipment_events.event_time.
     *
     * The shipment’s event history is usually ordered by this field to
     * present a chronological view of tracking updates.
     */
    event_time: string & tags.Format<"date-time">;
  };
}
