import { tags } from "typia";

/**
 * Administrative view of the authentication credential state associated with a
 * specific customer account on the shoppingMall platform.
 *
 * This DTO represents an aggregated projection that combines the linkage
 * between a customer and their credential record with selected attributes from
 * the core credentials model, risk configuration, and authentication history.
 * It is intentionally designed as a read-only view for platform administrators
 * and security operators rather than a direct mirror of any single underlying
 * database table.
 *
 * The structure purposely omits sensitive material such as password hashes, raw
 * auth tokens, cryptographic secrets, and low-level implementation details.
 * Only high-level, administratively safe indicators—such as login identifier,
 * credential type, lockout status, MFA enrollment, and risk flags—are exposed.
 * All changes to credentials must occur through dedicated authentication and
 * account-management workflows, not through this DTO.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IShoppingMallCustomerCredential = {
  /**
   * Unique identifier of the customer account to which this credential view
   * belongs.
   *
   * This identifier corresponds to the primary key of the customer entity and
   * allows administrators to correlate credential status with the owning
   * customer profile and activity.
   */
  customer_id: string & tags.Format<"uuid">;

  /**
   * Unique identifier of the underlying core credential record associated
   * with this customer.
   *
   * This value typically corresponds to the primary key of a shared
   * credentials entity that may have subtype links for multiple actor roles
   * such as customers, sellers, or platform administrators.
   */
  credential_id: string & tags.Format<"uuid">;

  /**
   * Primary login handle used by the customer for authentication, as modeled
   * in the credentials subsystem.
   *
   * This is often an email address or username string and is the value the
   * customer enters when attempting to sign in. The precise semantics (for
   * example, whether it must be unique, or whether it must be an email) are
   * defined by the core credential model and business rules.
   */
  login_identifier: string;

  /**
   * Type of authentication credential associated with this customer.
   *
   * Examples include values such as `password`, `oauth`, or `sso`, reflecting
   * how the customer proves their identity. This field helps administrators
   * understand which authentication mechanisms are configured and can
   * influence policy enforcement and troubleshooting steps.
   */
  credential_type: string;

  /**
   * Flag indicating whether this credential is currently locked for
   * authentication attempts.
   *
   * When this value is true, the authentication layer should deny login
   * attempts using this credential until an appropriate administrative or
   * automated process clears the lock according to configured policy (for
   * example, after investigation or a cooldown period).
   */
  is_locked: boolean;

  /**
   * Flag indicating whether the customer has multi-factor authentication
   * (MFA) enrolled and active for this credential.
   *
   * This value is derived from the MFA configuration associated with the
   * underlying credentials and gives administrators a quick view of whether
   * strong authentication is in place for the account.
   */
  mfa_enrolled: boolean;

  /**
   * Array of risk or fraud-related flags currently associated with this
   * customer's credential linkage.
   *
   * Each element is a symbolic code or identifier that corresponds to risk
   * configuration entries (for example, rules, lists, or manual annotations).
   * These flags inform how strictly subsequent authentication or transaction
   * flows should be treated and are useful during investigations and risk
   * reviews.
   */
  risk_flags?: string[] | undefined;

  /**
   * Timestamp of the most recent successful authentication using this
   * credential, if available.
   *
   * Expressed as an ISO 8601 date-time value in UTC. This helps
   * administrators understand how recently the account was used and whether
   * it may be dormant or recently accessed during suspicious activity.
   */
  last_successful_login_at?: (string & tags.Format<"date-time">) | undefined;

  /**
   * Timestamp of the most recent failed authentication attempt associated
   * with this credential, if available.
   *
   * Expressed as an ISO 8601 date-time value in UTC. This value, combined
   * with failure counts and security events, helps detect brute-force
   * attempts or other anomalous login behavior.
   */
  last_failed_login_at?: (string & tags.Format<"date-time">) | undefined;

  /**
   * Number of consecutive failed login attempts recorded against this
   * credential since the last successful login or administrative reset.
   *
   * This counter is commonly used by lockout and throttling policies to
   * determine when to temporarily or permanently block further attempts and
   * is surfaced here for administrative visibility.
   */
  failed_login_attempts?: (number & tags.Type<"int32">) | undefined;

  /**
   * Timestamp when the linkage between the customer and the underlying
   * credential record was established.
   *
   * Expressed as an ISO 8601 date-time value in UTC. This is typically set at
   * customer registration time or when credentials were first attached to the
   * customer account.
   */
  created_at?: (string & tags.Format<"date-time">) | undefined;

  /**
   * Timestamp when this aggregated credential view or its underlying linkage
   * metadata was last updated.
   *
   * Expressed as an ISO 8601 date-time value in UTC. Changes that may update
   * this value include lockout state changes, MFA enrollment updates, risk
   * flag adjustments, or other credential-related administrative actions.
   */
  updated_at?: (string & tags.Format<"date-time">) | undefined;
};
