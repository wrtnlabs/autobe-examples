export async function test_api_time_report_rows_list_by_organization(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "P@ssw0rd1234!",
      displayName: RandomGenerator.name(),
      href: "https://example.com/erp/hrm/time-report",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(joined);
  TestValidator.predicate("member id is a uuid", joined.id.length > 0);
  TestValidator.predicate("member email is present", joined.email.length > 0);
  TestValidator.predicate(
    "access token is present",
    joined.token.access.length > 0,
  );
}
