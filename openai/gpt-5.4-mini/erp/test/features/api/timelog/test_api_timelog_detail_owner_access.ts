export async function test_api_timelog_detail_owner_access(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(joined);
  const timelogId = typia.random<string & tags.Format<"uuid">>();
  const timelog = await api.functional.hrmTimeTracking.member.timelogs.at(
    memberConnection,
    { timelogId },
  );
  typia.assert(timelog);
  TestValidator.equals("timelog id matches request", timelog.id, timelogId);
  TestValidator.predicate(
    "timelog has organization reference",
    timelog.organization.id.length > 0,
  );
  TestValidator.predicate(
    "timelog has employee reference",
    timelog.employee.id.length > 0,
  );
  TestValidator.predicate(
    "timelog has project reference",
    timelog.project.id.length > 0,
  );
  TestValidator.predicate(
    "timelog work date is present",
    timelog.work_date.length > 0,
  );
  TestValidator.predicate(
    "timelog duration is positive",
    timelog.duration_minutes > 0,
  );
}
