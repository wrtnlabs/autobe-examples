export async function test_api_timelog_delete_by_manager_access(
  connection: api.IConnection,
): Promise<void> {
  const managerConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(managerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  await TestValidator.httpError(
    "manager timelog delete should reject unknown timelog id",
    [400, 401, 403, 404],
    async () => {
      await api.functional.hrmTimeTracking.member.timelogs.erase(
        managerConnection,
        {
          timelogId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
