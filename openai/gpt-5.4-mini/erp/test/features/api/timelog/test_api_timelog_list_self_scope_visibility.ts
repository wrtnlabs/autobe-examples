export async function test_api_timelog_list_self_scope_visibility(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(authorized);
  const organizationConnection: api.IConnection = { host: connection.host };
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      organizationConnection,
      {
        body: {
          name: RandomGenerator.name(),
          description: RandomGenerator.paragraph({ sentences: 2 }),
          currency: "USD",
          timezone: "Asia/Seoul",
          fiscalStartMonth: 1,
        },
      },
    );
  typia.assert(organization);
  const response = await api.functional.hrmTimeTracking.member.timelogs.index(
    memberConnection,
    {
      body: {
        page: 1,
        limit: 100,
        sort: "work_date_desc",
      } satisfies IHrmTimeTrackingTimelog.IRequest,
    },
  );
  typia.assert(response);
  TestValidator.equals(
    "timelog pagination should start at first page",
    response.pagination.current,
    1,
  );
  TestValidator.equals(
    "timelog pagination limit should match request",
    response.pagination.limit,
    100,
  );
  TestValidator.predicate(
    "timelog list should be an array",
    Array.isArray(response.data),
  );
  TestValidator.predicate(
    "all returned timelogs should be valid summary records",
    response.data.every((item) => item.id.length > 0),
  );
}
