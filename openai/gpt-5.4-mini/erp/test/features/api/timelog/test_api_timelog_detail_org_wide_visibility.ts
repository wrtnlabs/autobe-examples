export async function test_api_timelog_detail_org_wide_visibility(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const viewerConnection: api.IConnection = { host: connection.host };
  const ownerAuthorized = await authorize_member_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(ownerAuthorized);
  const viewerAuthorized = await authorize_member_join(viewerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(viewerAuthorized);
  await TestValidator.error(
    "member timelog detail requires a real timelog id",
    async () => {
      await api.functional.hrmTimeTracking.member.timelogs.at(
        viewerConnection,
        {
          timelogId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
