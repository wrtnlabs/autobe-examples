export async function test_api_role_can_assign_protected_role(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      displayName: RandomGenerator.name(),
      href: "https://example.com/onboarding",
      referrer: "https://example.com/landing",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(joined);
  const roleId = typia.random<string & tags.Format<"uuid">>();
  const capability = await api.functional.erpHrmTime.member.roles.canAssign(
    memberConnection,
    { roleId },
  );
  typia.assert(capability);
}
