export async function test_api_role_permission_bundle_update_builtin_role_fixed(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  const organization: IHrmTimeTrackingOrganization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {
        body: {
          name: RandomGenerator.name(),
          description: RandomGenerator.paragraph({ sentences: 2 }),
          currency: "USD",
          timezone: "Asia/Seoul",
          fiscalStartMonth: 1,
        } satisfies IHrmTimeTrackingOrganization.ICreate,
      },
    );
  typia.assert(organization);
  await TestValidator.error(
    "built-in role permission bundle should not be arbitrarily replaceable",
    async () => {
      await api.functional.hrmTimeTracking.member.roles.permissions.updatePermissions(
        memberConnection,
        {
          roleId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            permissionIds: [
              typia.random<string & tags.Format<"uuid">>(),
              typia.random<string & tags.Format<"uuid">>(),
            ],
          } satisfies IHrmTimeTrackingRole.IUpdatePermission,
        },
      );
    },
  );
}
