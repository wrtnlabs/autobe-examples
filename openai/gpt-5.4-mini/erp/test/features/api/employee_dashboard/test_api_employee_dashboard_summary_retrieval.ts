export async function test_api_employee_dashboard_summary_retrieval(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      displayName: RandomGenerator.name(),
      href: "https://example.com/onboarding",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  TestValidator.predicate(
    "authorization token issued",
    authorized.token.access.length > 0 && authorized.token.refresh.length > 0,
  );
  TestValidator.equals(
    "member email is preserved",
    authorized.email,
    authorized.email,
  );
  TestValidator.equals(
    "member display name is preserved",
    authorized.displayName,
    authorized.displayName,
  );
}
