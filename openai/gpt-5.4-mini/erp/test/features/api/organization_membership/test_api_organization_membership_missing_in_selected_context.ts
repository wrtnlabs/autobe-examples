export async function test_api_organization_membership_missing_in_selected_context(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234Abcd!",
      name: RandomGenerator.name(),
      href: "https://example.com/signup",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  await TestValidator.httpError(
    "organization membership missing in selected context",
    404,
    async () => {
      await api.functional.erpHrmTime.member.organizationMemberships.at(
        memberConnection,
        {
          organizationMembershipId: typia.random<
            string & tags.Format<"uuid">
          >(),
        },
      );
    },
  );
}
