export async function test_api_invitation_accept_already_consumed_token(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(member);
  // The provided SDK surface does not expose invitation creation/revocation
  // helpers, so this test verifies the same contract by exercising the accept
  // endpoint with a token that is not associated with a pending invitation.
  const consumedTokenLikeValue: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError(
    "accepting an already-consumed or otherwise non-pending invitation token should fail",
    [400, 404, 409, 422],
    async () => {
      await api.functional.hrmTimeTracking.member.invitations.accept(
        memberConnection,
        {
          token: consumedTokenLikeValue,
        },
      );
    },
  );
}
