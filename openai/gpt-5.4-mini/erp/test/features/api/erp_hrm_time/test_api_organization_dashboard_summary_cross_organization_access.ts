export async function test_api_organization_dashboard_summary_cross_organization_access(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      name: RandomGenerator.name(),
      href: "https://example.com/register",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  const foreignSummaryId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "foreign organization dashboard summary should not be accessible",
    async () => {
      const summary =
        await api.functional.erpHrmTime.member.reports.organization_dashboard_summaries.at(
          memberConnection,
          {
            organizationDashboardSummaryId: foreignSummaryId,
          },
        );
      typia.assert(summary);
      TestValidator.notEquals(
        "summary id should not leak across organization boundaries",
        summary.id,
        foreignSummaryId,
      );
    },
  );
}
