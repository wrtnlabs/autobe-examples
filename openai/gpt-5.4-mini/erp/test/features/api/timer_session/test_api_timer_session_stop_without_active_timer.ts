export async function test_api_timer_session_stop_without_active_timer(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: `${RandomGenerator.alphaNumeric(12)}Aa1!`,
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  const timerConnection: api.IConnection = {
    host: connection.host,
    headers: {
      Authorization: authorized.token.access,
    },
  };
  await TestValidator.httpError(
    "stop timer session without an active timer",
    [400, 404, 409],
    async () => {
      await api.functional.hrmTimeTracking.member.me.timer_session.stop(
        timerConnection,
      );
    },
  );
}
