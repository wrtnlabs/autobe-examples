export async function test_api_timer_session_absent_when_no_active_timer(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const signed = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(signed);
  const organization =
    await generate_random_hrm_time_tracking_member_organizations_create(
      memberConnection,
      {
        body: {
          name: RandomGenerator.name(),
          description: RandomGenerator.paragraph({ sentences: 2 }),
          currency: "USD",
          timezone: "Asia/Seoul",
          fiscalStartMonth: 1,
        } satisfies IHrmTimeTrackingOrganization.ICreate,
      },
    );
  typia.assert(organization);
  try {
    await api.functional.hrmTimeTracking.member.me.timer_session.discard(
      memberConnection,
    );
  } catch {
    // Intentionally ignore: the endpoint under test must still be exercised
    // in the empty-state path when there is no active timer to discard.
  }
  await TestValidator.httpError(
    "timer session should not exist when no active timer is running",
    [404, 409],
    async () => {
      await api.functional.hrmTimeTracking.member.me.timer_session.at(
        memberConnection,
      );
    },
  );
}
