export async function test_api_timer_session_discard_own_running_timer(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(joined);
  const discarded =
    await api.functional.hrmTimeTracking.member.me.timer_session.discard(
      memberConnection,
    );
  typia.assert(discarded);
  TestValidator.equals(
    "discarded timer owner matches authenticated member",
    discarded.employee.id,
    discarded.employee.id,
  );
  TestValidator.predicate(
    "discarded timestamp is populated",
    discarded.discarded_at !== null,
  );
  TestValidator.equals(
    "discard does not produce ended timestamp",
    discarded.ended_at,
    null,
  );
  TestValidator.equals(
    "discarded session remains present as a historical record",
    discarded.deleted_at,
    null,
  );
}
