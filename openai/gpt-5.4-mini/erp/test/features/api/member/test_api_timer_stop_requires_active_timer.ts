export async function test_api_timer_stop_requires_active_timer(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      name: RandomGenerator.name(),
      href: "http://localhost/erpHrmTime/member/timers/stop",
      referrer: "http://localhost/erpHrmTime",
      ip: "127.0.0.1",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  await TestValidator.httpError(
    "stopping a timer without an active timer should fail",
    [404, 409],
    async () => {
      const timelog =
        await api.functional.erpHrmTime.member.timers.stop(memberConnection);
      typia.assert(timelog);
    },
  );
  await TestValidator.httpError(
    "stopping again without an active timer should still fail",
    [404, 409],
    async () => {
      const timelog =
        await api.functional.erpHrmTime.member.timers.stop(memberConnection);
      typia.assert(timelog);
    },
  );
}
