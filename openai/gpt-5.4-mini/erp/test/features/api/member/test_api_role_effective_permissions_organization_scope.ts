export async function test_api_role_effective_permissions_organization_scope(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234abcd!",
      name: RandomGenerator.name(),
      href: "https://example.com/join",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  const scopedConnection: api.IConnection = {
    host: connection.host,
    headers: memberConnection.headers,
  };
  await TestValidator.httpError(
    "effective permissions for an unknown role in the current organization should return not found",
    404,
    async () => {
      await api.functional.erpHrmTime.member.roles.permissions.effective.at(
        scopedConnection,
        {
          roleId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
