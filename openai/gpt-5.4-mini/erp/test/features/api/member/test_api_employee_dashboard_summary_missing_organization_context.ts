export async function test_api_employee_dashboard_summary_missing_organization_context(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: `${RandomGenerator.alphaNumeric(12)}@example.com`,
      password: "P@ssw0rd1234!",
      name: RandomGenerator.name(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  const organizationlessConnection: api.IConnection = { host: connection.host };
  await TestValidator.httpError(
    "employee dashboard summary should reject missing organization context",
    [401, 403, 404],
    async () => {
      await api.functional.erpHrmTime.member.employee_dashboard_summary.at(
        organizationlessConnection,
      );
    },
  );
}
