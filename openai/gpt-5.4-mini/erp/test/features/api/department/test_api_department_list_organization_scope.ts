export async function test_api_department_list_organization_scope(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const auth = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      displayName: RandomGenerator.name(),
      href: "https://example.com/onboarding",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(auth);
  const response = await api.functional.erpHrmTime.member.departments.index(
    memberConnection,
    {
      body: {
        page: 1,
        limit: 10,
        sortBy: "name",
        sortOrder: "asc",
      } satisfies IErpHrmTimeDepartment.IRequest,
    },
  );
  typia.assert(response);
  TestValidator.equals(
    "pagination current page",
    response.pagination.current,
    1,
  );
  TestValidator.equals("pagination limit", response.pagination.limit, 10);
  TestValidator.predicate(
    "records is non-negative",
    response.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pages is non-negative",
    response.pagination.pages >= 0,
  );
  TestValidator.predicate(
    "data length is within limit",
    response.data.length <= response.pagination.limit,
  );
  for (const department of response.data) {
    typia.assert(department);
    if (department.parentDepartment !== null)
      typia.assert(department.parentDepartment);
  }
}
