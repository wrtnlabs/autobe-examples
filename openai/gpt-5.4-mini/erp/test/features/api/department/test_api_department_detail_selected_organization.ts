export async function test_api_department_detail_selected_organization(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      name: RandomGenerator.name(),
      href: "https://example.com/register" as string & tags.Format<"uri">,
      referrer: "https://example.com/" as string & tags.Format<"uri">,
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  const departmentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "missing department should be rejected",
    async () => {
      await api.functional.erpHrmTime.member.departments.at(memberConnection, {
        departmentId,
      });
    },
  );
}
