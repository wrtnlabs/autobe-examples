export async function test_api_department_update_organization_scope(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  const departmentId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    name: RandomGenerator.name(),
    description: RandomGenerator.paragraph({ sentences: 2 }),
    parentDepartmentId: null,
  } satisfies IHrmTimeTrackingDepartment.IUpdate;
  await TestValidator.httpError(
    "department update should be rejected when the target department is outside the active organization scope",
    [400, 401, 403, 404],
    async () => {
      await api.functional.hrmTimeTracking.member.departments.update(
        memberConnection,
        {
          departmentId,
          body,
        },
      );
    },
  );
}
