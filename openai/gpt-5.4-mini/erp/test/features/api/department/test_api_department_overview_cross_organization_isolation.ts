export async function test_api_department_overview_cross_organization_isolation(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  await TestValidator.httpError(
    "department overview should not expose data for an unknown foreign department id",
    [403, 404],
    async () => {
      await api.functional.hrmTimeTracking.member.departments.overview(
        memberConnection,
        {
          departmentId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
