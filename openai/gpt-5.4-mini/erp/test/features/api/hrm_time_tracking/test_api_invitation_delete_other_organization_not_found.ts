import { authorize_member_refresh } from "../../../authorize/authorize_member_refresh";

export async function test_api_invitation_delete_other_organization_not_found(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(member);
  const wrongOrganizationInvitationId = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError(
    "delete invitation from other organization should be not found",
    404,
    async () => {
      await api.functional.hrmTimeTracking.member.invitations.erase(
        memberConnection,
        {
          invitationId: wrongOrganizationInvitationId,
        },
      );
    },
  );
}
