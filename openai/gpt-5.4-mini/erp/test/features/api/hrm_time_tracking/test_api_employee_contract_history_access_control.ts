export async function test_api_employee_contract_history_access_control(
  connection: api.IConnection,
): Promise<void> {
  const selfConnection: api.IConnection = { host: connection.host };
  const selfAuthorized = await authorize_member_join(selfConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(selfAuthorized);
  const otherConnection: api.IConnection = { host: connection.host };
  const otherAuthorized = await authorize_member_join(otherConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(otherAuthorized);
  const employeeId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "forbidden or not found for contract history access without visibility permission",
    async () => {
      await api.functional.hrmTimeTracking.member.employees.contracts.getByEmployeeid(
        otherConnection,
        {
          employeeId,
        },
      );
    },
  );
}
