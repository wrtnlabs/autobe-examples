export async function test_api_invitation_create_requires_employee_management_access(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(authorized);
  const invitationBody = {
    email: typia.random<string & tags.Format<"email">>(),
  } satisfies IHrmTimeTrackingInvitation.ICreate;
  await TestValidator.httpError(
    "member without employee-management access cannot create invitation",
    [401, 403],
    async () => {
      await api.functional.hrmTimeTracking.member.invitations.create(
        memberConnection,
        {
          body: invitationBody,
        },
      );
    },
  );
}
