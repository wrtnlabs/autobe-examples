export async function test_api_organization_delete_blocked_by_pending_timesheets(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      displayName: RandomGenerator.name(),
      avatarImageUrl: null,
      phoneNumber: null,
      href: "https://example.com/onboarding",
      referrer: "https://example.com/referrer",
      ip: "127.0.0.1",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  const organizationId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "organization deletion should not succeed without proper deletable organization state",
    async () => {
      await api.functional.erpHrmTime.member.organizations.erase(
        ownerConnection,
        {
          organizationId,
        },
      );
    },
  );
}
