export async function test_api_organization_settings_context_isolation(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "P@ssw0rd123!",
      displayName: RandomGenerator.name(),
      href: "https://example.com/onboarding",
      referrer: "https://example.com/referrer",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  const organizationId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    currencyCode: "USD",
    timezone: "Asia/Seoul",
    fiscalStartMonth: 4,
  } satisfies IErpHrmTimeOrganizationSetting.IUpdate;
  await TestValidator.error(
    "mismatched organization context should reject unauthorized cross-tenant settings update",
    async () => {
      await api.functional.erpHrmTime.member.organizations.settings.update(
        memberConnection,
        {
          organizationId,
          body,
        },
      );
    },
  );
}
