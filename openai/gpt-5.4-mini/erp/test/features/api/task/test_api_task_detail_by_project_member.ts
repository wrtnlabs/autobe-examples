export async function test_api_task_detail_by_project_member(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(authorized);
  const task = await api.functional.hrmTimeTracking.member.projects.tasks.at(
    memberConnection,
    {
      projectId: typia.random<string & tags.Format<"uuid">>(),
      taskId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  typia.assert(task);
  TestValidator.predicate("task has an id", task.id.length > 0);
  TestValidator.predicate("task has a title", task.title.length > 0);
  TestValidator.predicate(
    "task project has an organization",
    task.project.organization.id.length > 0 &&
      task.project.organization.name.length > 0,
  );
  TestValidator.predicate(
    "task audit timestamps exist",
    (task.createdAt ?? "").length > 0 && (task.updatedAt ?? "").length > 0,
  );
}
