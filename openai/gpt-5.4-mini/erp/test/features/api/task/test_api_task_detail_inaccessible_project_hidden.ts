export async function test_api_task_detail_inaccessible_project_hidden(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(authorized);
  TestValidator.predicate(
    "member token issued",
    authorized.token.access.length > 0,
  );
  await TestValidator.httpError(
    "inaccessible project task detail should be blocked",
    [401, 403, 404],
    async () => {
      await api.functional.hrmTimeTracking.member.projects.tasks.at(
        memberConnection,
        {
          projectId: typia.random<string & tags.Format<"uuid">>(),
          taskId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
