export async function test_api_task_detail_project_mismatch_hidden(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(authorized);
  const projectId = typia.random<string & tags.Format<"uuid">>();
  const taskId = typia.random<string & tags.Format<"uuid">>();
  const mismatchedProjectId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "task detail should not leak across mismatched project context",
    [400, 401, 403, 404],
    async () => {
      await api.functional.hrmTimeTracking.member.projects.tasks.at(
        memberConnection,
        {
          projectId:
            projectId === mismatchedProjectId
              ? typia.random<string & tags.Format<"uuid">>()
              : mismatchedProjectId,
          taskId,
        },
      );
    },
  );
}
