export async function test_api_project_archive_active_project(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      displayName: RandomGenerator.name(),
      href: "https://example.com/onboarding",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  const authorizedConnection: api.IConnection = {
    host: connection.host,
    headers: {
      Authorization: authorized.token.access,
    },
  };
  const project = await api.functional.erpHrmTime.member.projects.archive(
    authorizedConnection,
    {
      projectId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  typia.assert(project);
  TestValidator.equals("archived project status", project.status, "archived");
  TestValidator.predicate("project id is preserved", project.id.length > 0);
  TestValidator.predicate(
    "project remains linked to organization",
    project.organization.id.length > 0 && project.organization.name.length > 0,
  );
}
