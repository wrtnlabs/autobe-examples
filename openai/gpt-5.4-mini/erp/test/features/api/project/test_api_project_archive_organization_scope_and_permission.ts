export async function test_api_project_archive_organization_scope_and_permission(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      displayName: RandomGenerator.name(),
      href: "http://localhost" satisfies string & tags.Format<"uri">,
      referrer: "http://localhost" satisfies string & tags.Format<"uri">,
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(joined);
  await TestValidator.httpError(
    "member without project management permission cannot archive a project",
    [401, 403, 404],
    async () => {
      await api.functional.erpHrmTime.member.projects.archive(
        memberConnection,
        {
          projectId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
