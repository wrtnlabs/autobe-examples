export async function test_api_project_complete_active_project(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "P@ssw0rd1234!",
      displayName: RandomGenerator.name(),
      avatarImageUrl: null,
      phoneNumber: null,
      href: "https://example.com/onboarding",
      referrer: "https://example.com/",
      ip: "127.0.0.1",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  typia.assert(authorized);
  memberConnection.headers = {
    ...(memberConnection.headers ?? {}),
    Authorization: authorized.token.access,
  };
  await TestValidator.httpError(
    "completing a nonexistent project should be rejected",
    [404, 409],
    async () => {
      await api.functional.erpHrmTime.member.projects.complete(
        memberConnection,
        {
          projectId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
