export async function test_api_timesheet_submitted_review_visibility(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  const timesheetId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "timesheet detail should reject access when the record is not visible in the current organization context",
    [403, 404],
    async () => {
      await api.functional.hrmTimeTracking.member.timesheets.at(
        memberConnection,
        {
          timesheetId,
        },
      );
    },
  );
}
