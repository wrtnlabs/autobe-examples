export async function test_api_project_budget_report_row_retrieve_by_organization(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: `${RandomGenerator.alphaNumeric(10)}@test.com` as string &
        tags.Format<"email">,
      password: `P@ssw0rd${RandomGenerator.alphaNumeric(8)}` as string &
        tags.Format<"password">,
      displayName: RandomGenerator.name(),
      href: "https://example.com/onboarding",
      referrer: "https://example.com/",
    } satisfies IErpHrmTimeMember.IJoin,
  });
  const row = typia.random<IErpHrmTimeProjectBudgetReportRow>();
  const output =
    await api.functional.erpHrmTime.member.organizations.projectBudgetReportRows.at(
      memberConnection,
      {
        organizationId: row.organization.id,
        projectBudgetReportRowId: row.id,
      },
    );
  typia.assert(output);
}
