export async function test_api_employee_contract_detail_retrieval(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  const contract =
    await api.functional.hrmTimeTracking.member.employees.contracts.getByEmployeeidAndContractid(
      memberConnection,
      {
        employeeId: member.id,
        contractId: member.id,
      },
    );
  typia.assert(contract);
  TestValidator.predicate("contract identifier exists", contract.id.length > 0);
  TestValidator.predicate(
    "contract employee summary exists",
    contract.employee !== null && contract.employee !== undefined,
  );
  TestValidator.predicate(
    "contract start date exists",
    contract.startDate.length > 0,
  );
  TestValidator.predicate(
    "contract pay rate is positive",
    contract.payRate > 0,
  );
  TestValidator.predicate(
    "contract working hours are positive",
    contract.workingHoursPerWeek > 0,
  );
}
