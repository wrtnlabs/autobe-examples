export async function test_api_employee_contract_history_organization_scope(
  connection: api.IConnection,
): Promise<void> {
  const sourceConnection: api.IConnection = { host: connection.host };
  const sourceAuthorized = await authorize_member_join(sourceConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IHrmTimeTrackingMember.IJoin,
  });
  typia.assert(sourceAuthorized);
  const targetEmployeeId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "cross-organization contract history lookup should fail with not found",
    404,
    async () => {
      await api.functional.hrmTimeTracking.member.employees.contracts.getByEmployeeid(
        sourceConnection,
        {
          employeeId: targetEmployeeId,
        },
      );
    },
  );
}
