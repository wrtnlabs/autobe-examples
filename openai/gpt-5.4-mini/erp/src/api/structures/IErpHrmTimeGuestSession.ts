import { tags } from "typia";

import { IAuthorizationToken } from "./IAuthorizationToken";

export namespace IErpHrmTimeGuestSession {
  /**
   * Request body used to renew a guest authorization session by exchanging an existing refresh token for a new token bundle.
   */
  export type IRefresh = {
    /**
     * Opaque refresh token used to renew a guest session.
     *
         * @x-autobe-specification Send the opaque guest refresh token
         *   previously issued by the auth service. The backend validates this
         *   token, checks that it is still active and unexpired, and uses it to
         *   issue a new guest authorization bundle. Do not include any member
         *   IDs, guest IDs, session IDs, or organization context.
     */
    refreshToken: string & tags.Format<"password">;
  };

  /**
   * Authorization response returned after a successful guest join or refresh. It contains the issued access token, refresh token, access-token expiration time, and the nested authorization token payload used by the guest authentication flow.
   */
  export type IAuthorized = {
    /**
     * Short-lived access token used to authenticate subsequent API requests.
     *
         * @x-autobe-specification Return the newly issued short-lived access
         *   token created during guest join or refresh. This is derived from
         *   the authentication issuance process, not from a database column. It
         *   should match the access credential carried in the authorization
         *   bundle for the guest session.
     */
    access: string;

    /**
     * Refresh token used to obtain a new guest authorization bundle without rejoining.
     *
         * @x-autobe-specification Return the newly issued refresh token created
         *   during guest join or refresh. This token is generated by the
         *   authentication workflow and used for later refresh exchanges; it is
         *   not read directly from the guest session table.
     */
    refresh: string;

    /**
     * Timestamp when the current access token expires.
     *
         * @x-autobe-specification Expose the access-token expiration time
         *   calculated when the guest authorization bundle is issued. This
         *   timestamp comes from token issuance metadata and must align with
         *   the access token's lifetime; it is not sourced from a persisted
         *   guest-session field.
     */
    expiredAt: string & tags.Format<"date-time">;

    /**
     * Authorization token.
     *
         * @x-autobe-specification Authorization token comes from the session
         *   table.
     */
    token: IAuthorizationToken;
  };

  /**
   * Request body for a visitor joining as a guest. It captures the page context and optional client IP used during guest session creation.
   */
  export type IJoin = {
    /**
     * The current page URI where the guest join request was initiated.
     *
         * @x-autobe-specification Use the current page URI from the visitor as
         *   join context when creating or associating a guest session. Do not
         *   persist it as a guest table column; it is consumed by the
         *   authentication flow only.
     */
    href: string & tags.Format<"uri">;

    /**
     * The referring page URI that led the visitor into the guest join flow.
     *
         * @x-autobe-specification Use the referring page URI from the visitor
         *   as join context when creating or associating a guest session. Do
         *   not persist it as a guest table column; it is consumed by the
         *   authentication flow only.
     */
    referrer: string & tags.Format<"uri">;

    /**
     * Optional client IP address for the guest join request.
     *
         * @x-autobe-specification Use the optional client IPv4 address when
         *   available to attribute the guest join request. If unavailable, null
         *   is allowed and the server may infer network context independently.
         *   This is contextual data only, not a guest table field.
     */
    ip?: (string & tags.Format<"ipv4">) | null | undefined;
  };
}
