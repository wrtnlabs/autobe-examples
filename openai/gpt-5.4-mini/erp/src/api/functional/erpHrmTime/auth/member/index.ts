/**
 * Registers a new member account for the ERP HRM and time tracking platform. The operation creates the authenticated user record identified by the member actor and returns the authorization payload needed to start using the system.
 *
 * This endpoint is the entry point for users who are joining the platform with email and password credentials. It is part of the authentication flow that precedes organization-scoped actions such as switching into a tenant context, managing organization memberships, or using time tracking features.
 *
 * If the submitted email is already in use, the operation must fail with a conflict-style error. Validation errors for malformed email or weak passwords should be returned clearly so clients can correct the request before retrying.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Registration payload for creating a new member account with email and password credentials.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Implement member registration by validating the
 *   submitted email and password, creating the member account, and issuing the
 *   initial authenticated token set in a single transaction. Check for
 *   duplicate email addresses before insertion and reject already-registered
 *   emails with a conflict error. If account creation must also initialize
 *   session state or profile linkage, do so only after the member row is
 *   successfully created. Return a JWT authorization payload containing the
 *   access token, refresh token, and any standard expiration metadata expected
 *   by IErpHrmTimeMember.IAuthorized. Ensure password handling uses secure
 *   hashing and never persists plaintext credentials.
 * @path /erpHrmTime/auth/member/join
 * @accessor api.functional.erpHrmTime.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
