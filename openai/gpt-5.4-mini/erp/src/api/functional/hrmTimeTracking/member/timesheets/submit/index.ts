export async function process(
  connection: IConnection,
  props: process.Props,
): Promise<process.Response> {
  return true === connection.simulate
    ? process.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...process.METADATA,
          path: process.path(props),
          status: null,
        },
      );
}
export namespace process {
  export type Props = {
    /**
     * The timesheet to submit.
     */
    timesheetId: string & tags.Format<"uuid">;
  };
  export type Response = IHrmTimeTrackingTimesheet;

  export const METADATA = {
    method: "POST",
    path: "/hrmTimeTracking/member/timesheets/:timesheetId/submit",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/hrmTimeTracking/member/timesheets/${encodeURIComponent(props.timesheetId ?? "null")}/submit`;
  export const random = (): IHrmTimeTrackingTimesheet =>
    typia.random<IHrmTimeTrackingTimesheet>();
  export const simulate = (
    connection: IConnection,
    props: process.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: process.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("timesheetId")(() => typia.assert(props.timesheetId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
