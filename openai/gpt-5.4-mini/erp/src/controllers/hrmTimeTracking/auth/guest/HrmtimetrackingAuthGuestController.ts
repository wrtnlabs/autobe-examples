import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingGuest } from "../../../../api/structures/IHrmTimeTrackingGuest";
import { postHrmTimeTrackingAuthGuestJoin } from "../../../../providers/postHrmTimeTrackingAuthGuestJoin";
import { postHrmTimeTrackingAuthGuestRefresh } from "../../../../providers/postHrmTimeTrackingAuthGuestRefresh";

@Controller("/hrmTimeTracking/auth/guest")
export class HrmtimetrackingAuthGuestController {
  /**
   * Creates the guest authorization entry point for a visitor who is not yet an authenticated member of the platform. This operation is designed for the guest actor only and supports the initial access or registration flow defined for anonymous users in the hrm_time_tracking domain.
   *
   * The request body must follow the IHrmTimeTrackingGuest.IJoin contract, and the response returns IHrmTimeTrackingGuest.IAuthorized so the client can continue with authenticated access after successful guest onboarding. This operation is intentionally limited to the guest actor and does not expose member login behavior, because the system requirements define guests as a separate unauthenticated actor kind with its own access path.
   *
   * Because this endpoint belongs to the authentication boundary, it should be treated as a public entry point and protected only by the guest authentication rules that apply to initial access. Any required guest identity persistence, token issuance, or session bootstrap should be coordinated with the guest session model used by the platform so the generated authorization state remains valid for subsequent refresh operations.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join payload used to create an authorized guest session.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implement a public guest registration entry point that creates a temporary or initial guest-authenticated identity flow and issues authorization tokens after successful validation. The service should validate the incoming guest join payload according to the IHrmTimeTrackingGuest.IJoin contract, enforce any required uniqueness or format checks defined by the guest authentication workflow, and then generate a new authorized response using IHrmTimeTrackingGuest.IAuthorized. If the guest flow creates a guest identity record or session, persist it atomically so token issuance and guest state remain consistent. Return clear validation errors for malformed input and business-rule errors for duplicate or otherwise invalid guest join attempts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackingGuest.IJoin,
  ): Promise<IHrmTimeTrackingGuest.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews authorization for an existing guest session so the client can continue using the system without re-running the guest join flow. This operation is specific to the guest actor and is part of the supported authentication lifecycle for anonymous access in the hrm_time_tracking platform.
   *
   * The request body must follow IHrmTimeTrackingGuest.IRefresh, and the successful response must return IHrmTimeTrackingGuest.IAuthorized. This endpoint exists because guest access is temporary and token-based, and the system requires a dedicated refresh flow for renewing access when the original authorization state is nearing expiration or has been rotated.
   *
   * This operation should be used only with a valid guest refresh credential issued by the platform. If the underlying guest session is expired, revoked, or otherwise invalid, the endpoint must reject the request and return an appropriate authentication failure rather than creating a new guest session implicitly.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest refresh payload used to renew an existing guest authorization.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implement a token renewal endpoint for guest authorization that accepts the current guest refresh credentials, validates them, and returns a fresh authorized token bundle. The service should verify the refresh payload against the IHrmTimeTrackingGuest.IRefresh contract, confirm that the refresh token or equivalent guest session marker is still valid, and then rotate or reissue authorization tokens according to the guest session lifecycle rules. If refresh token rotation is supported, update the underlying guest session atomically to prevent reuse and maintain consistency between stored session state and issued tokens. Return validation and authorization errors for expired, revoked, or otherwise invalid refresh attempts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmTimeTrackingGuest.IRefresh,
  ): Promise<IHrmTimeTrackingGuest.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
