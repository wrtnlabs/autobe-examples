import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IHrmTimeTrackingMember } from "../../../../api/structures/IHrmTimeTrackingMember";
import { postHrmTimeTrackingAuthMemberJoin } from "../../../../providers/postHrmTimeTrackingAuthMemberJoin";
import { postHrmTimeTrackingAuthMemberLogin } from "../../../../providers/postHrmTimeTrackingAuthMemberLogin";
import { postHrmTimeTrackingAuthMemberRefresh } from "../../../../providers/postHrmTimeTrackingAuthMemberRefresh";

@Controller("/hrmTimeTracking/auth/member")
export class HrmtimetrackingAuthMemberController {
  /**
   * Creates a new member account for the platform and returns the initial authenticated token set.
   *
   * This endpoint represents the member sign-up flow for the `member` actor, who is an authenticated user that can later belong to one or more organizations. The operation is responsible for establishing the global authentication identity that will be used across all organization contexts. It should validate the incoming registration payload, ensure the login identity is unique, and create the member record needed for subsequent organization-scoped access.
   *
   * The registration flow is part of the authentication lifecycle and should be documented as the starting point for a member who does not yet have platform credentials. After successful creation, the API returns the authorized response payload containing the tokens required for immediate authenticated access. Because this endpoint is focused on account creation, it must not require an existing authenticated actor.
   *
   * The implementation should align with the member account and session concepts described in the project requirements: member identity is global, while organization membership is handled separately after authentication. Any password value must be processed securely before storage, and validation errors should be reported clearly when the submitted email or password does not satisfy the account creation rules.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration credentials and initial account information.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement member registration as a public authentication endpoint that creates a new member identity, validates the email/password payload, and issues the initial authorized token set on success. The service should verify uniqueness of the member login identity before inserting the new member record, create any required authentication/session rows in the member session lifecycle store, and return access/refresh credentials in the authorized response shape. Password handling must use secure hashing before persistence, and the operation should fail cleanly when the email already exists or the payload violates validation rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackingMember.IJoin,
  ): Promise<IHrmTimeTrackingMember.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing member with email and password and returns the authorized token set.
   *
   * This endpoint is the main sign-in flow for the `member` actor. A member uses this operation after registration or when returning to the platform with an existing account. It establishes a trusted authenticated session that can be used to access organization-scoped business APIs according to the currently selected organization context.
   *
   * The login operation belongs to the authentication boundary rather than the business domain. It should verify the member’s credentials against the stored authentication identity and, on success, produce the token response required for secured API access. The endpoint must remain independent from organization data because a member can belong to multiple organizations and choose context separately after authentication.
   *
   * Error handling should be strict and security-conscious: invalid credentials must be rejected without leaking sensitive information, and the response must only expose the authorized token structure. This endpoint is used together with token refresh to maintain continuous access across sessions.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login credentials used to validate the account and issue tokens.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement member login by validating the submitted credentials against the stored member authentication record, then issuing a fresh authorized token set when the credentials are correct. The service should verify the email exists, compare the provided password using the configured password verification strategy, and create or update the active member session record as required by the session lifecycle design. Failed authentication attempts should return a clear authorization error without exposing whether the email or password was incorrect.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IHrmTimeTrackingMember.ILogin,
  ): Promise<IHrmTimeTrackingMember.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the member’s authenticated token set using a valid refresh token.
   *
   * This endpoint supports the long-lived authentication lifecycle for the `member` actor by allowing the client to obtain new access credentials without re-entering the password. It is part of the member session management flow and should be used when the current access token is near expiration or has expired but the refresh token remains valid.
   *
   * The operation depends on the session record associated with the member authentication identity. It should confirm that the refresh token is valid and belongs to an active session before generating a new authorized response. This keeps authentication stateless at the API layer while still allowing controlled session continuity through the database-backed session model.
   *
   * The refresh flow is especially important for members who work across multiple organizations, because the authenticated identity persists while organization context may change independently. The response must match the same authorized token bundle used by the login and registration endpoints so client handling remains consistent across the auth lifecycle.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token payload used to obtain a new authorized token set.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement token refresh by validating the submitted refresh token, confirming it belongs to an active member session, and issuing a renewed authorized token set. The service should rotate or reissue refresh credentials according to the session policy, reject expired or revoked tokens, and keep the refresh flow independent from email/password validation. If the stored session is no longer active, the endpoint must return an authentication failure and refuse to issue new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IHrmTimeTrackingMember.IRefresh,
  ): Promise<IHrmTimeTrackingMember.IAuthorized> {
    try {
      return await postHrmTimeTrackingAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
