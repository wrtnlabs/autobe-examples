import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IHrmTimeTrackingMember } from "../../../../api/structures/IHrmTimeTrackingMember";
import { IHrmTimeTrackingMemberPasswordReset } from "../../../../api/structures/IHrmTimeTrackingMemberPasswordReset";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getHrmTimeTrackingMemberPasswordResetsPasswordResetId } from "../../../../providers/getHrmTimeTrackingMemberPasswordResetsPasswordResetId";
import { patchHrmTimeTrackingMemberPasswordResets } from "../../../../providers/patchHrmTimeTrackingMemberPasswordResets";

@Controller("/hrmTimeTracking/member/password-resets")
export class HrmtimetrackingMemberPassword_resetsController {
  /**
   * Reset a member account password using a valid recovery token.
   *
   * This endpoint allows an authenticated or recovering user to replace the current password secret for an existing member account after proving access through a valid password reset token. The operation updates only the account credential and preserves the same user identity, profile, and organization memberships. It does not create a new account and does not alter any organization-scoped employee records.
   *
   * The reset flow is tied to the member password recovery lifecycle stored in the password reset token record. The system must validate that the token exists, belongs to the intended member account, has not expired or been used, and matches the submitted reset request. After a successful reset, the account continues to be recognized as the same member identity for future sign-in attempts with the new password.
   *
   * This operation is independent of organization context because password recovery is a global account concern rather than an organization-scoped action. It should be accessible without selecting an organization, and it must not expose any profile, role, employee, or organization data beyond what is necessary to confirm the reset succeeded. If the token is invalid, expired, or already consumed, the request must be rejected with a clear validation or authorization error.
   *
   * @param connection
   * @param body Password reset token and the new password to apply to the member account.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement a password recovery workflow that accepts a reset token and a new password, then updates the target member account password atomically.
   *
   * Service flow:
   * 1. Validate the request body shape and password policy.
   * 2. Look up the member password reset record by token value.
   * 3. Ensure the reset record exists, is bound to a member account, is not expired, and has not already been consumed.
   * 4. Verify the token corresponds to the intended account and that the account is active and allowed to receive a new password.
   * 5. Hash the new password using the platform password hashing strategy.
   * 6. Update the hrm_time_tracking_members credential fields for that account only.
   * 7. Mark the reset token record as used/consumed or otherwise invalidate it according to the schema lifecycle.
   * 8. Return the updated member summary without exposing password-related fields.
   *
   * Use a transaction so the password update and reset-token consumption succeed or fail together. If the reset token is missing, expired, invalid, or already used, reject the request before modifying the account. If the new password does not satisfy strength/confirmation rules, return a validation error. Do not modify profile, organization memberships, employee records, or sessions here; those are separate lifecycle concerns. If the schema supports session invalidation after credential changes, revoke existing member sessions as a follow-up side effect after the password update commits.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IHrmTimeTrackingMember.IResetPassword,
  ): Promise<IHrmTimeTrackingMember> {
    try {
      return await patchHrmTimeTrackingMemberPasswordResets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a password reset record for the signed-in member.
   *
   * This operation returns one password recovery record from the `hrm_time_tracking_member_password_resets` table, which stores the owning member account, the secure reset token, the expiration timestamp, and the optional consumed timestamp. It is used to inspect the current state of a recovery request and to determine whether the token is still available for use.
   *
   * Access is restricted to the authenticated member who owns the record. The service must confirm that the selected `passwordResetId` belongs to the current member context before returning any data. Requests for another member's reset record must be rejected. The record is part of account recovery, so it is independent of organization membership and must be handled at the global account level.
   *
   * The response reflects the record lifecycle derived from `expires_at` and `consumed_at`. A record may be expired when the expiration time has passed, and it may be consumed when `consumed_at` is set. The endpoint does not modify the record; it only provides the current state so the client can present the appropriate recovery flow. Use this endpoint together with password reset submission flows that validate the token and replace the account password.
   *
   * @param connection
   * @param passwordResetId Password reset record ID.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement a single-record lookup against hrm_time_tracking_member_password_resets using the path UUID as the primary key.
   *
   * Load the record by id and ensure it is not deleted if the project uses deleted_at filtering for this table. Verify the authenticated member matches the record's member_id before returning the payload. If the record is not found, return a not-found error. If the record belongs to another member, return a forbidden or not-found response to avoid leaking recovery token existence.
   *
   * Do not expose the raw token in any client-facing field unless the product explicitly requires it; prefer returning a safe view model with id, memberId, expiresAt, consumedAt, createdAt, updatedAt, and a derived status value computed in the service layer. If the token must be included for a specific recovery UI, guard it carefully and only for the owning member.
   *
   * Compute state from expires_at and consumed_at at read time. expired = now >= expires_at; consumed = consumed_at is not null. The endpoint is read-only and should not start a transaction unless the surrounding framework requires one for consistent access checks. No request body is needed. Keep the response schema aligned with the actual table fields and account-recovery use case.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":passwordResetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("passwordResetId")
    passwordResetId: string & tags.Format<"uuid">,
  ): Promise<IHrmTimeTrackingMemberPasswordReset> {
    try {
      return await getHrmTimeTrackingMemberPasswordResetsPasswordResetId({
        member,
        passwordResetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
