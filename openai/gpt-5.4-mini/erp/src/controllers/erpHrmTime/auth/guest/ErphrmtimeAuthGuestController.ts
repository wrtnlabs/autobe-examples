import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmTimeGuestSession } from "../../../../api/structures/IErpHrmTimeGuestSession";
import { postErpHrmTimeAuthGuestJoin } from "../../../../providers/postErpHrmTimeAuthGuestJoin";
import { postErpHrmTimeAuthGuestRefresh } from "../../../../providers/postErpHrmTimeAuthGuestRefresh";

@Controller("/erpHrmTime/auth/guest")
export class ErphrmtimeAuthGuestController {
  /**
   * Creates a guest authorization session for an unauthenticated visitor who is joining the platform. This endpoint is part of the authentication flow for temporary visitors and returns the authorized token bundle needed to continue using the API.
   *
   * The operation is public and does not require an existing authenticated actor. It should validate the join payload and, on success, issue the standard authorized response described by the `IErpHrmTimeGuest.IAuthorized` contract. Any invalid registration or join attempt must fail with an authentication error rather than creating a partial session.
   *
   * This endpoint is intended to support the guest actor workflow only. It does not perform login for existing member accounts, and it should not expose organization-scoped data until a valid organization context is established through later business operations.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join request payload used to create or activate a guest authorization session.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implement guest registration/join by validating
     *   the submitted guest credentials and establishing a new authenticated
     *   session for the visitor. The service must create or associate the guest
     *   identity according to the join workflow, then issue fresh access and
     *   refresh tokens in the authorized response. Enforce input validation,
     *   reject duplicate or invalid join attempts, and return a clear
     *   authentication error when the join request cannot be completed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmTimeGuestSession.IJoin,
  ): Promise<IErpHrmTimeGuestSession.IAuthorized> {
    try {
      return await postErpHrmTimeAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the authorization state for a guest session using a refresh token. This endpoint is public and exists so a guest can continue an active authorization session without re-running the join flow.
   *
   * On success, the service returns the standard `IErpHrmTimeGuest.IAuthorized` token bundle. The refresh operation must validate the supplied refresh token carefully and must refuse to issue new credentials when the token is expired, invalid, or otherwise unusable.
   *
   * This endpoint is part of the guest authentication lifecycle only. It does not require a logged-in member, and it should not be used to switch organization context or access business data directly.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest refresh request payload containing the refresh token to exchange for a new authorized session.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implement refresh-token exchange for guest
     *   sessions by validating the incoming refresh token, verifying that it is
     *   still active and unexpired, and issuing a new authorized token bundle.
     *   Reject expired, revoked, malformed, or replayed refresh tokens. If the
     *   refresh token cannot be trusted, return an authentication error and do
     *   not issue new credentials.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmTimeGuestSession.IRefresh,
  ): Promise<IErpHrmTimeGuestSession.IAuthorized> {
    try {
      return await postErpHrmTimeAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
