import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTimePermission } from "../../../../api/structures/IErpHrmTimePermission";
import { IPageIErpHrmTimePermission } from "../../../../api/structures/IPageIErpHrmTimePermission";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmTimeMemberPermissionsPermissionId } from "../../../../providers/getErpHrmTimeMemberPermissionsPermissionId";
import { patchErpHrmTimeMemberPermissions } from "../../../../providers/patchErpHrmTimeMemberPermissions";

@Controller("/erpHrmTime/member/permissions")
export class ErphrmtimeMemberPermissionsController {
  /**
   * Retrieve the approved organization permission catalog.
   *
   * This endpoint returns the platform-defined permissions that can be assigned to custom roles within the currently selected organization. It is intended for role creation and role editing flows, where organization owners and other authorized members must choose from the approved permission list rather than inventing new access rights.
   *
   * The returned permission records represent the fixed business abilities used across the ERP HRM and time tracking platform, including organization management, employee management and viewing, project management and viewing, time management, time approval, viewing all time records, and report viewing. These records are reference data and are not created or edited through this API.
   *
   * Access to this endpoint follows the organization’s active context and the caller’s authorization rules. If the organization context is missing or the caller lacks permission to manage or inspect role configuration, the request should be rejected. Filtering, pagination, and sorting should be applied consistently so the permission catalog can be reused in UI role selectors and admin tools.
   *
   * @param connection
   * @param body Search, pagination, and sorting criteria for browsing the approved permission catalog.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Read the approved permission catalog from erp_hrm_time_permissions.
   * Apply organization context checks even though the permission set is global/reference data, because the caller must still be authorized within the selected organization to use role-management UI flows.
   * Support pagination, search, and sorting in the request body to satisfy the index contract. Search should match permission code/name/description fields exposed by the schema. Sorting should allow stable ordering, defaulting to a deterministic field such as name or code if present in the schema; do not assume fields that do not exist.
   * Return only permissions from the approved list used for custom roles. Do not expose any mechanism to create, update, or delete permissions. If the organization context is absent, return a validation/authorization error. If the request references unsupported filters or sort fields, reject it as invalid input.
   * Use a service query that is lightweight and cache-friendly because permissions are static reference data. If the schema includes audit or status columns, preserve them in the response only if they are part of the permission definition; otherwise return summary fields only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimePermission.IRequest,
  ): Promise<IPageIErpHrmTimePermission.ISummary> {
    try {
      return await patchErpHrmTimeMemberPermissions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single approved permission from the platform’s canonical permission catalog.
   *
   * This operation returns the permission key and human-readable description for one permission record so role-management screens can inspect the exact access capability before assigning it to an organization role. The permission catalog is the source of truth for valid permission values used by custom roles and access control rules.
   *
   * The permission record is identified by its UUID primary key. If the permission does not exist, the server must return a not-found error. Because this endpoint reads from the global approved permission catalog, it does not depend on organization context and does not accept a request body.
   *
   * @param connection
   * @param permissionId Permission identifier (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Load a single row from erp_hrm_time_permissions by id using the UUID path parameter.
   * Return the permission only if it exists and is not deleted_at-marked inactive; otherwise return not found.
   * Do not join to other tables because the permission catalog is self-contained.
   * The endpoint is read-only and must not require organization context.
   * Keep the response stable for role-editing workflows by returning the canonical permission entity fields only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":permissionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("permissionId")
    permissionId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTimePermission> {
    try {
      return await getErpHrmTimeMemberPermissionsPermissionId({
        member,
        permissionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
