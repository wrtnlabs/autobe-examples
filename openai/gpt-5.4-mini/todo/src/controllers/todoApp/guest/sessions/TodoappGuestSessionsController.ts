import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getTodoAppGuestSessionsSessionId } from "../../../../providers/getTodoAppGuestSessionsSessionId";
import { patchTodoAppGuestSessions } from "../../../../providers/patchTodoAppGuestSessions";

@Controller("/todoApp/guest/sessions")
export class TodoappGuestSessionsController {
  /**
   * Retrieve a paginated list of the current member's session records.
   *
   * This operation is intended for the signed-in account holder who needs to review their own session activity within the private todo application. The session collection belongs to the member account and represents the authenticated access state associated with the account. Because sessions are tied to the active member identity, this endpoint only exposes records that belong to the current user and must not reveal session data for any other account.
   *
   * The response is based on the session records stored in the member session table, which holds JWT session records used to manage login, refresh, and logout behavior. The API returns session information in a paginated form so clients can safely display a manageable list of active or recent sessions without loading the entire dataset at once.
   *
   * Access is limited to the member actor. Guests and unauthenticated callers must not be able to use this operation. If the current session is no longer active or the account cannot be resolved, the operation should return an empty or otherwise safe paginated result rather than exposing unrelated account data.
   *
   * This endpoint is commonly used together with account security features such as password change and logout flows. It provides visibility into the current member's own session state and supports account-security user experiences without allowing cross-account inspection.
   *
   * @param connection
   * @param body Search, filtering, and pagination criteria for the current member's session list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the todo_app_member_sessions table for session records owned by the current authenticated member.
   *
   * Apply member scoping from the authenticated principal, not from any client-supplied account identifier. The service must ensure that every returned row belongs to the current member account only. Filter by optional request criteria such as session state, creation time window, or last activity window only if those fields exist in the schema and are supported by the request DTO.
   *
   * Use pagination at the database query layer with a stable sort order, typically newest sessions first, so the list remains consistent across requests. Return a paginated container with summary session data rather than full low-level token material. Any sensitive token values should remain internal and must not be serialized in the response.
   *
   * If the current member context is missing, invalid, or no longer resolvable, return an authorization failure or an empty safe result according to the service's auth middleware contract. Do not attempt to infer another account, and do not expose whether another member has sessions. If the query yields no rows, return an empty page structure with pagination metadata.
   *
   * Because this is a read-only list endpoint, no transaction is required beyond the standard read operation. Any future logout or session invalidation flows should be handled by their own dedicated endpoint and must not be mixed into this retrieval operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single member session record by session ID.
   *
   * This operation returns the stored session metadata for one authenticated member session, including the IP address used when the session was created, the request URL or client location associated with that event, the referrer URL, the creation timestamp, and the expiration timestamp. The data comes directly from the member session record and is intended for private account-security and session-management use.
   *
   * Access to this endpoint is restricted to the member who owns the session record. The session entity is linked to the member account through the todo_app_member_id relation, so the server must confirm that the requested session belongs to the currently signed-in member before returning the record. If the session is missing or does not belong to the current member, the operation must fail safely and expose no private session information.
   *
   * @param connection
   * @param sessionId The unique identifier of the session record.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Load todo_app_member_sessions by primary key id and require that the authenticated principal is a member. After fetching the session row, verify that todo_app_member_id matches the current member account id from the active session context. If no row is found, or ownership does not match, return a not-found or forbidden-style failure without revealing whether another member's session exists.
   *
   * Return the full session detail payload using the existing schema fields only: id, todo_app_member_id, ip, href, referrer, created_at, and expired_at. Do not invent audit fields or status flags that are not present in the schema. No mutation or side effects are allowed. The endpoint is read-only and should not extend session lifetime or update last-seen metadata.
   *
   * Because the table is append-only in practice and tied to member account security, implementation should preserve strict privacy boundaries and avoid listing or joining unrelated account data. Any persistence access should be a simple indexed lookup by id, followed by an ownership check against the current member context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
