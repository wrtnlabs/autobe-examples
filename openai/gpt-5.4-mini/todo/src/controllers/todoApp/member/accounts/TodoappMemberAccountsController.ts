import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberAccountsAccountId } from "../../../../providers/getTodoAppMemberAccountsAccountId";
import { patchTodoAppMemberAccounts } from "../../../../providers/patchTodoAppMemberAccounts";
import { putTodoAppMemberAccountsAccountId } from "../../../../providers/putTodoAppMemberAccountsAccountId";

@Controller("/todoApp/member/accounts")
export class TodoappMemberAccountsController {
  /**
   * Delete the signed-in member's own account.
   *
   * This endpoint is available only to the authenticated owner of the account. It removes the active member account and performs the required cleanup of the owner’s private profile and todos, including todos that are already in the trash.
   *
   * The application is private, so the target account is always the current session holder. Requests for any other account must be rejected, and deleted accounts must not remain usable for future access or sign-in.
   *
   * The underlying member record is stored with a unique email address, a password hash, and lifecycle timestamps. Those stored fields are managed internally and are not exposed by this endpoint.
   *
   * @param connection
   * @param body Request body for deleting the signed-in member's own account. No additional account identifier is required because the current authenticated session determines the target account.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Authenticate the request using the current member
     *   session and verify that the caller is the account owner before taking
     *   any action. Reject unauthenticated requests and any request that does
     *   not belong to the active member.
   *
   * Execute the deletion as a single transactional account-lifecycle operation. Remove the member record and permanently remove the member's private profile and all todos owned by that member, including todos currently in trash. Ensure dependent todo edit history records are also removed so no orphaned private data remains after account deletion.
   *
   * Do not return member identity, credential, or timestamp data in the response. The endpoint should succeed with no content or a minimal confirmation body if the service convention requires one; for this operation, no response body is needed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMember.IRequest,
  ): Promise<void> {
    try {
      return await patchTodoAppMemberAccounts({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the authenticated member's private account record.
   *
   * This operation returns the account identity data for one member only, using the unique account identifier in the path. The account belongs to a single person and is part of the private todo application boundary.
   *
   * Only the owning authenticated member may access this resource. The service must not expose other users' account information, and it must not return accounts that have been deleted. If the account does not exist, is deleted, or does not belong to the requester, the service must return the appropriate not-found or forbidden response according to the application's error handling policy.
   *
   * @param connection
   * @param accountId The unique UUID of the member account to retrieve in global scope.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Fetch the todo_app_members record by id and
     *   verify that it belongs to the authenticated caller. Reject access when
     *   the requested account id does not match the caller's account or when
     *   deleted_at is set. Return the full member entity contract for the API,
     *   but never expose the raw password_hash in the serialized response.
     *   Preserve the private-account boundary and use the account's unique UUID
     *   as the lookup key. If no accessible record is found, respond with the
     *   standard not-found or forbidden error used by the service.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":accountId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("accountId")
    accountId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMember> {
    try {
      return await getTodoAppMemberAccountsAccountId({
        member,
        accountId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated member account.
   *
   * This endpoint lets a member modify their own account identity in the private todo application. The service must verify that the account identified by the path parameter belongs to the current authenticated member before applying any changes.
   *
   * Only member-account fields may be processed here. The profile display name belongs to the separate profile entity and is not updated by this operation. If the requested email conflicts with another member account, or if the request targets another user's account, the service must reject the request with an appropriate error.
   *
   * @param connection
   * @param accountId The UUID of the member account to update in private account scope.
   * @param body Fields to update on the authenticated member account.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Load the todo_app_members row by id and verify
     *   that it belongs to the authenticated requester. Reject the request if
     *   the member does not exist, is deleted, or is not owned by the current
     *   member. Apply only supported account-level fields from the update
     *   payload, specifically the fields defined by the member schema. Enforce
     *   the unique email constraint before persisting email changes. If the
     *   password is updated, hash the new password before storing it in
     *   password_hash and never persist raw credentials. Update updated_at on
     *   successful persistence. Do not touch todo_app_profiles in this
     *   operation. Return not found or forbidden-style errors for missing
     *   records or ownership violations, and conflict errors for duplicate
     *   email values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":accountId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("accountId")
    accountId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppMember.IUpdate,
  ): Promise<ITodoAppMember> {
    try {
      return await putTodoAppMemberAccountsAccountId({
        member,
        accountId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
