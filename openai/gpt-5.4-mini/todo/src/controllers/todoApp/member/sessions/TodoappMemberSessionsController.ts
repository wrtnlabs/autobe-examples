import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageITodoAppMemberSession } from "../../../../api/structures/IPageITodoAppMemberSession";
import { ITodoAppMemberSession } from "../../../../api/structures/ITodoAppMemberSession";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberSessionsSessionId } from "../../../../providers/getTodoAppMemberSessionsSessionId";
import { patchTodoAppMemberSessions } from "../../../../providers/patchTodoAppMemberSessions";

@Controller("/todoApp/member/sessions")
export class TodoappMemberSessionsController {
  /**
   * Returns the authenticated member's session records.
   *
   * This endpoint lets a signed-in member browse their own login sessions in a paginated list. Each result represents a session record stored for security and auditing purposes, including the member reference, IP address, request URL, referrer URL, creation timestamp, and expiration timestamp.
   *
   * The service must scope every query to the current authenticated member and must not expose any session that belongs to another member. Session validity and expiration rules should be enforced consistently when assembling the result set, and invalid search or pagination input should be rejected as a validation error.
   *
   * @param connection
   * @param body Search, filter, pagination, and sorting criteria for the authenticated member's session list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query todo_app_member_sessions using the authenticated member id from the security context and never accept a member id from the request body. Support pagination, search, and sorting in the request DTO. Default ordering should be newest first by created_at unless overridden.
   *
   * Use the schema columns exactly as stored: id, todo_app_member_id, ip, href, referrer, created_at, and expired_at. Return only a summary projection suitable for list browsing. Do not expose any secret token value because none exists in the schema. Reject unauthorized access, expired sessions in an unauthenticated context, and malformed list parameters with the appropriate auth or validation error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberSession.IRequest,
  ): Promise<IPageITodoAppMemberSession.ISummary> {
    try {
      return await patchTodoAppMemberSessions({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a member session by its UUID identifier.
   *
   * This endpoint returns the stored session record for a single logged-in member, including the owning member reference and the audit metadata captured when the session was issued. It is intended for session inspection and security-related workflows that need to verify a specific session instance.
   *
   * The returned data includes the owning member reference, the source IP address, the request URL, the referrer URL, the creation timestamp, and the expiration timestamp. If the session does not exist, the service must return a not found error. Callers must only be able to access sessions they are authorized to inspect.
   *
   * @param connection
   * @param sessionId The UUID of the session to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Load todo_app_member_sessions by primary key id and return the matching row. Validate that sessionId is a UUID and return 404 when no session exists.
   *
   * Do not mutate the session record, refresh expiration, or trigger logout behavior. Preserve the stored ip, href, referrer, created_at, and expired_at values as-is. If authorization is enforced at this layer, verify the caller may inspect the requested session before returning the entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberSession> {
    try {
      return await getTodoAppMemberSessionsSessionId({
        member,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
