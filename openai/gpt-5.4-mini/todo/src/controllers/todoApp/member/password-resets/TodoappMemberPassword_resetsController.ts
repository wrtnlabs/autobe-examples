import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { ITodoAppMemberPasswordReset } from "../../../../api/structures/ITodoAppMemberPasswordReset";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberPasswordResetsResetId } from "../../../../providers/getTodoAppMemberPasswordResetsResetId";
import { patchTodoAppMemberPasswordResets } from "../../../../providers/patchTodoAppMemberPasswordResets";

@Controller("/todoApp/member/password-resets")
export class TodoappMemberPassword_resetsController {
  /**
   * Reset a member account password using a valid recovery token.
   *
   * The service must resolve the supplied token against the password reset records, ensure it is still valid, and then update the password credential for the linked member account. The reset applies only to the owning account and must not change email, ownership, or account lifecycle data.
   *
   * If the token is unknown, expired, already consumed, or does not belong to an existing member, the request must be rejected. On success, the new password replaces the previous password hash for future sign-in attempts, and the reset record should be invalidated so it cannot be reused.
   *
   * @param connection
   * @param body The password reset token and the new password to apply to the linked account.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Look up the password reset request by its unique token in todo_app_member_password_resets. Reject the request when the token is missing, invalid, expired, deleted, or not linked to an existing member. Validate the new password against the account password policy before hashing it.
   *
   * Update todo_app_members.password_hash for the linked member in the same transaction as invalidating the reset record. If the schema supports deleted_at-based invalidation for reset records, set deleted_at on successful consumption; otherwise, use the service's existing consumption logic without inventing new fields. Do not alter member email, created_at, deleted_at, or any unrelated account fields. Return the updated member entity without exposing password_hash.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async reset(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppMemberPasswordReset.IRequest,
  ): Promise<ITodoAppMember> {
    try {
      return await patchTodoAppMemberPasswordResets({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a password reset request by its identifier.
   *
   * This endpoint returns the full password reset record associated with the supplied reset identifier, including the linked member reference, reset token, expiration time, and audit timestamps. It is intended for password recovery and security workflows that need to inspect a single reset request record.
   *
   * The record belongs to exactly one member account through the todo_app_member_id relation. If the identifier does not exist, or the record is no longer available, the request should be rejected with a not-found response.
   *
   * @param connection
   * @param resetId The password reset request identifier (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Load the todo_app_member_password_resets row by id and return it only when it exists. If needed for ownership context, join the related todo_app_members row through todo_app_member_id, but do not expose any member fields unless the response schema explicitly includes them. Return the actual stored columns only: id, todo_app_member_id, token, expired_at, created_at, updated_at, and deleted_at. Do not invent password fields, because this table stores reset requests rather than password credentials. Treat unavailable records as not found.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppMemberPasswordReset> {
    try {
      return await getTodoAppMemberPasswordResetsResetId({
        member,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
