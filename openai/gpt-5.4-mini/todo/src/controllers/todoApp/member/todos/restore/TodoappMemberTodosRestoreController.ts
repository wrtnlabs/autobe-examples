import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { ITodoAppTodo } from "../../../../../api/structures/ITodoAppTodo";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { postTodoAppMemberTodosTodoIdRestore } from "../../../../../providers/postTodoAppMemberTodosTodoIdRestore";

@Controller("/todoApp/member/todos/:todoId/restore")
export class TodoappMemberTodosRestoreController {
  /**
   * Restore a deleted todo back to the active list.
   *
   * This operation is available only to the owning member and only for a todo that is currently in trash. When restoration succeeds, the todo becomes visible again in the normal todo list while keeping its existing completion status.
   *
   * Ownership and lifecycle rules are enforced strictly. Requests for another member's todo, for a todo that is not deleted, or for a todo that has already been permanently removed must be rejected.
   *
   * @param connection
   * @param todoId The identifier of the todo to restore within the authenticated member's own todo collection.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Load the todo by id and verify that it belongs to
     *   the current authenticated member. Reject the request if the todo does
     *   not exist, belongs to another member, or is not currently soft-deleted.
   *
   * On success, clear the deleted_at value so the todo returns to the active list. Preserve all other todo fields, especially is_completed, title, description, start_date, due_date, created_at, and updated_at semantics. Update the modified timestamp as part of the restore workflow if the service convention requires it.
   *
   * Do not create or modify any todo edit history records during restore. If the todo has been permanently deleted, return a not-found or invalid-state style error consistent with the service conventions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTodo> {
    try {
      return await postTodoAppMemberTodosTodoIdRestore({
        member,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
