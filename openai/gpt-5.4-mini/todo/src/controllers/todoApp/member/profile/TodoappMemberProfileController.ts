import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { ITodoAppProfile } from "../../../../api/structures/ITodoAppProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getTodoAppMemberProfile } from "../../../../providers/getTodoAppMemberProfile";
import { patchTodoAppMemberProfile } from "../../../../providers/patchTodoAppMemberProfile";

@Controller("/todoApp/member/profile")
export class TodoappMemberProfileController {
  /**
   * Retrieve the authenticated member’s own private profile.
   *
   * This endpoint returns only the profile record that belongs to the current signed-in account. The profile is account-linked and private, so the response is limited to the member’s own display name record and does not expose any other user’s profile data.
   *
   * Use this operation when the UI needs to display the member’s profile label. If the caller is not authenticated, the member account is inactive, or the profile cannot be resolved for the current account, the request must fail with the appropriate authorization or not-found response used by the service layer.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Fetch the profile row associated with the current authenticated member from todo_app_profiles using the active session’s member identity. Enforce ownership through the session context, and do not accept a path parameter because this resource always represents the caller’s own profile.
   *
   * Return only the profile fields stored in the table and never expose credential data or another user’s profile. If the request is unauthenticated, the member is deleted/inactive, or the profile is inaccessible for the current account, return the corresponding authorization or not-found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<ITodoAppProfile> {
    try {
      return await getTodoAppMemberProfile({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the current member's profile display name.
   *
   * This operation updates only the authenticated member's own profile and is limited to the display name field. The profile remains private to the owning member, and the request must not target any other user's profile.
   *
   * If the display name is invalid or unchanged, the request must be rejected. No other profile attributes are in scope for this operation. On success, the response returns the updated profile so the client can immediately show the member's current identity label in the app.
   *
   * @param connection
   * @param body The new display name for the current member's own profile. No other profile fields are allowed.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Resolve the authenticated member from the current session and load that member's profile record. Apply an update only to the display_name column, and reject any request body properties other than displayName.
   *
   * Validate the new display name according to the profile rules and business requirements, including rejecting empty or blank values. If the new value matches the existing display name, return a validation error because the update must change the display name in this unit. Preserve the private ownership boundary by never allowing a profile identifier to be provided in the path or request body. Persist the change in a single profile update and return the updated profile entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: ITodoAppProfile.IUpdate,
  ): Promise<ITodoAppProfile> {
    try {
      return await patchTodoAppMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
