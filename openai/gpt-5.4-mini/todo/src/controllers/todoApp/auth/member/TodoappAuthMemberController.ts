import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Create a new member account and return authorization tokens.
   *
   * This endpoint registers a private app member using the required sign-up credentials and returns the authorized token payload on success. It is the entry point for first-time access to the authenticated todo area and establishes the member identity used for profile, todo, trash, and history operations.
   *
   * The request body must match the member join contract exactly. If the submitted credentials are invalid or already in use, the request must fail without creating a partial account. On success, the response returns the authorized authentication payload for the newly created member.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration credentials for creating a new authenticated account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate the member sign-up payload, create the member account, initialize the authentication state required for token issuance, and return the authorized token bundle. Reject duplicate or invalid credentials without creating a partial account.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing member and return authorization tokens.
   *
   * This endpoint validates the member's login credentials and issues the authorized token payload needed to access private todo features. It is used by returning users who already have an account and need a new authenticated session.
   *
   * If the credentials are invalid, the operation must fail with an authentication error and must not reveal whether the email address is registered. On success, the response contains the standard authorized authentication payload for the member.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login credentials used to authenticate an existing account.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Verify the member's credentials against the stored account record, issue fresh authentication tokens on success, and reject invalid credentials without revealing whether the email exists. Ensure the response contains the standard authorized token bundle only after successful password verification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the member's authorization tokens.
   *
   * This endpoint exchanges a valid refresh token for a new authorized token payload so the member can continue using the private todo application without re-entering credentials. It is part of the standard token renewal flow for authenticated members.
   *
   * The request body must match the member refresh contract exactly. If the token is invalid, expired, revoked, or no longer tied to an active session, the request must fail without issuing new tokens. On success, the response returns the updated authorized authentication payload for the member.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member token refresh payload used to renew an active authentication session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Validate the refresh token, confirm it belongs to an active member session, and issue a new authorized token bundle. Reject expired, malformed, revoked, or mismatched tokens. If the implementation stores session state, use it to prevent token reuse.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
