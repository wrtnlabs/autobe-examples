import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppMember } from "../../../../api/structures/ITodoAppMember";
import { postTodoAppAuthMemberJoin } from "../../../../providers/postTodoAppAuthMemberJoin";
import { postTodoAppAuthMemberLogin } from "../../../../providers/postTodoAppAuthMemberLogin";
import { postTodoAppAuthMemberRefresh } from "../../../../providers/postTodoAppAuthMemberRefresh";

@Controller("/todoApp/auth/member")
export class TodoappAuthMemberController {
  /**
   * Registers a new member account for the private todo application. This operation creates the authenticated account entry that represents a signed-in user and enables access to private todo, profile, history, and account-management features.
   *
   * The request body must supply the member credentials required to create the account. The server must validate the supplied identity information, ensure the account does not already exist, securely store the credential material, and then issue the authorization result for the new member. The operation is part of the public account-entry flow and does not require an existing authenticated session.
   *
   * This endpoint corresponds to the member account creation workflow and is the first step in the login/refresh lifecycle. It should be used together with the login endpoint for returning members and the refresh endpoint for renewing an active session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration credentials.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Implement member registration by validating the submitted email/password payload, creating a new member account record, and establishing any required default account state before issuing tokens. The service should enforce uniqueness on the member identity field used for login, hash the password securely, and create the initial authenticated response only after the account is persisted successfully. If the schema supports downstream verification or session tracking, those records should be created in the same transactional flow so that the account and its initial authentication state remain consistent.
   *
   * This endpoint is the public entry point for a new member to join the private todo application. It must reject duplicate registrations, invalid email formats, and weak passwords according to the application rules. On success, it returns the authorized token bundle so the newly created member can immediately access protected member resources.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.IJoin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing member using their login credentials and returns the authorization tokens needed to access private todo application features.
   *
   * This operation is the primary sign-in endpoint for returning members. It validates the submitted credentials against the member account data, then issues the authenticated response that allows the caller to continue into protected member-only areas such as todo management, profile editing, history browsing, and trash recovery.
   *
   * The endpoint is part of the standard authentication lifecycle and should be used after registration or whenever an existing session expires. It is separate from registration because it operates on an already existing account rather than creating a new one.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Implement member login by validating the submitted credentials against the stored member account record, verifying that the account exists and the password matches the securely stored hash, and issuing fresh authorization tokens on success. The service should apply the same credential verification rules used by the member account authentication flow and must not expose whether a specific account is present beyond the standard authentication failure behavior.
   *
   * If the schema includes member session support, the implementation should record or rotate the session state at the point of successful login so token lifecycle management remains consistent. Invalid credentials, blocked accounts if such a state exists, or malformed payloads must be rejected with the appropriate authentication error. On success, return the authorized token bundle for the member.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppMember.ILogin,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews an authenticated member session by exchanging refresh credentials for a new authorization token bundle.
   *
   * This operation is used when a member's access token has expired or is close to expiring, but the underlying authenticated session is still valid. It supports the ongoing private todo workflow by allowing the caller to remain signed in while preserving access to member-only resources.
   *
   * The endpoint belongs to the token lifecycle portion of the authentication flow and should be used only with valid refresh credentials issued by a prior successful registration or login response. It does not create a new account and does not validate primary login credentials again; instead, it renews the existing authenticated session state.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member refresh credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Implement token refresh by validating the submitted refresh token or refresh credential material, confirming it belongs to a valid member session, and issuing a new authorization token set when the refresh token is still active. The service should rotate or update session state if the schema supports member session persistence, and it should reject expired, revoked, malformed, or mismatched refresh credentials.
   *
   * This endpoint preserves uninterrupted access for authenticated members without requiring them to re-enter their password. It is especially important for long-lived todo usage sessions because members need continued access to their private task lists, history, and account settings. The implementation must be careful to distinguish between a valid refresh request and an invalid or expired session so that security boundaries remain intact.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppMember.IRefresh,
  ): Promise<ITodoAppMember.IAuthorized> {
    try {
      return await postTodoAppAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
