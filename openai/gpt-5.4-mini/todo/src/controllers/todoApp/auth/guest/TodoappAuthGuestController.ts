import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../providers/postTodoAppAuthGuestJoin";
import { postTodoAppAuthGuestRefresh } from "../../../../providers/postTodoAppAuthGuestRefresh";

@Controller("/todoApp/auth/guest")
export class TodoappAuthGuestController {
  /**
   * Register a guest and issue authorization tokens.
   *
   * This endpoint creates a temporary guest identity for an unauthenticated visitor in the private todo application and returns the authorized token payload needed for continued access. It is the guest entry point for starting an authenticated session without signing in as a registered member.
   *
   * The request body must be validated strictly before any token is issued. Because guest access is temporary and token-based, the operation is public and does not depend on an existing account, profile, or session.
   *
   * Use this endpoint as the first step in the guest authentication flow. Clients should store the returned tokens and later use the refresh endpoint to renew access when needed.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload used to create a guest identity and begin a guest authorization session.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Create a guest identity and return authorization tokens in a single public request. Validate the guest join payload, persist the guest record, and issue the authorized token response on success. Reject malformed input with validation errors and do not require an existing session or credentials.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest authorization tokens.
   *
   * This endpoint exchanges a valid guest refresh token for a new authorized token payload so a guest session can continue without creating a new guest identity. It is the renewal path for guest access in the private todo application.
   *
   * The request body must include the refresh token, and the server must verify that it belongs to a valid guest authorization context before issuing new tokens. If validation fails, the request must be rejected as unauthorized.
   *
   * Use this endpoint whenever guest access needs to be extended after the current token expires or is about to expire.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Payload containing the guest refresh token used to obtain renewed authorization.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Validate the guest refresh token and issue a new authorized token payload if the token is valid. Reject expired, malformed, revoked, or otherwise invalid tokens with an unauthorized response. The operation should remain stateless aside from whatever token storage is needed to verify refresh validity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoAppGuest.IRefresh,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
