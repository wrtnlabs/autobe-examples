/**
 * Restore a deleted todo back to the active list.
 *
 * This operation is available only to the owning member and only for a todo that is currently in trash. When restoration succeeds, the todo becomes visible again in the normal todo list while keeping its existing completion status.
 *
 * Ownership and lifecycle rules are enforced strictly. Requests for another member's todo, for a todo that is not deleted, or for a todo that has already been permanently removed must be rejected.
 *
 * @param props.connection
 * @param props.todoId The identifier of the todo to restore within the authenticated member's own todo collection.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Load the todo by id and verify that it belongs to the
 *   current authenticated member. Reject the request if the todo does not
 *   exist, belongs to another member, or is not currently soft-deleted.
 *
 * On success, clear the deleted_at value so the todo returns to the active list. Preserve all other todo fields, especially is_completed, title, description, start_date, due_date, created_at, and updated_at semantics. Update the modified timestamp as part of the restore workflow if the service convention requires it.
 *
 * Do not create or modify any todo edit history records during restore. If the todo has been permanently deleted, return a not-found or invalid-state style error consistent with the service conventions.
 * @path /todoApp/member/todos/:todoId/restore
 * @accessor api.functional.todoApp.member.todos.restore.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
      );
}
export namespace create {
  export type Props = {
    /**
     * The identifier of the todo to restore within the authenticated member's own todo collection.
     */
    todoId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppTodo;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/member/todos/:todoId/restore",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/restore`;
  export const random = (): ITodoAppTodo => typia.random<ITodoAppTodo>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
