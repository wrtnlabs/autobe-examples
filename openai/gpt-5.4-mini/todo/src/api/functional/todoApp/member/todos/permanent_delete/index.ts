import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

/**
 * Permanently deletes one of the authenticated member's todos.
 *
 * This operation removes the selected todo from the application and is intended for items that are already in trash. The todo must belong to the current member; attempts to access another user's todo are rejected.
 *
 * When the todo is removed, its edit history entries are also removed through the database relationship. After deletion, the todo is no longer available in the normal todo list, trash view, or history views.
 *
 * @param props.connection
 * @param props.todoId The identifier of the todo to permanently delete (UUID scope within the authenticated member's own data).
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Verify the authenticated caller is a member and load the target todo by id with ownership enforcement using todo_app_todos.id and todo_app_todos.todo_app_member_id.
 * Reject the request with a not-found or forbidden style error when the todo does not exist or does not belong to the current member.
 * Only allow this operation for a todo that is being permanently removed; do not perform a status update or move it back to active state.
 * Delete the todo row permanently from todo_app_todos. The associated todo_app_todo_edit_histories rows must be removed automatically by the existing cascade relation on todo_app_todo_histories.todo_app_todo_id -> todo_app_todos.id.
 * Do not return edit history data. Ensure the deletion is idempotent from a privacy perspective: after successful deletion the todo must not appear in any list, trash, or detail lookup.
 * @path /todoApp/member/todos/:todoId/permanent-delete
 * @accessor api.functional.todoApp.member.todos.permanent_delete.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * The identifier of the todo to permanently delete (UUID scope within the authenticated member's own data).
     */
    todoId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoApp/member/todos/:todoId/permanent-delete",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/member/todos/${encodeURIComponent(props.todoId ?? "null")}/permanent-delete`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("todoId")(() => typia.assert(props.todoId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
