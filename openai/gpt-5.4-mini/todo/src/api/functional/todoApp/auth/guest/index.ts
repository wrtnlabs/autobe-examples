/**
 * Register a guest and issue authorization tokens.
 *
 * This endpoint creates a temporary guest identity for an unauthenticated visitor in the private todo application and returns the authorized token payload needed for continued access. It is the guest entry point for starting an authenticated session without signing in as a registered member.
 *
 * The request body must be validated strictly before any token is issued. Because guest access is temporary and token-based, the operation is public and does not depend on an existing account, profile, or session.
 *
 * Use this endpoint as the first step in the guest authentication flow. Clients should store the returned tokens and later use the refresh endpoint to renew access when needed.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Payload used to create a guest identity and begin a guest authorization session.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Create a guest identity and return authorization tokens in a single public request. Validate the guest join payload, persist the guest record, and issue the authorized token response on success. Reject malformed input with validation errors and do not require an existing session or credentials.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Payload used to create a guest identity and begin a guest authorization session.
     */
    body: ITodoAppGuest.IJoin;
  };
  export type Body = ITodoAppGuest.IJoin;
  export type Response = ITodoAppGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/guest/join";
  export const random = (): ITodoAppGuest.IAuthorized =>
    typia.random<ITodoAppGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

