export async function test_api_member_session_detail_missing_session_hidden(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await api.functional.todoApp.auth.member.join(
    memberConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: true,
      } satisfies ITodoAppMember.IJoin,
    },
  );
  typia.assert(member);
  const missingSessionId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "missing or inaccessible session detail should fail safely",
    async () => {
      await api.functional.todoApp.guest.sessions.at(memberConnection, {
        sessionId: missingSessionId,
      });
    },
  );
}
