export async function test_api_member_sessions_private_access_boundary(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await api.functional.todoApp.auth.member.join(
    memberConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: true,
      } satisfies ITodoAppMember.IJoin,
    },
  );
  typia.assert(member);
  const page = await api.functional.todoApp.guest.sessions.index(
    memberConnection,
    {
      body: {
        page: 1,
        limit: 10,
      } satisfies ITodoAppMemberSession.IRequest,
    },
  );
  typia.assert(page);
  TestValidator.predicate(
    "pagination records should not be smaller than returned rows",
    page.pagination.records >= page.data.length,
  );
  TestValidator.predicate(
    "pagination pages should be consistent with record count",
    page.pagination.records === 0 || page.pagination.pages >= 1,
  );
}
