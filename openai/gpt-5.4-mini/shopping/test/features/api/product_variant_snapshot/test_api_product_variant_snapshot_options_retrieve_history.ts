export async function test_api_product_variant_snapshot_options_retrieve_history(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  typia.assert(authorized);
  const request = {
    search: RandomGenerator.alphabets(3),
    page: 1,
    limit: 10,
    sort: "+optionKey",
  } satisfies IMallPlatformProductVariantSnapshotOption.IRequest;
  const productId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "administrator variant snapshot option history with invalid identifiers",
    [400, 401, 403, 404],
    async () => {
      await api.functional.mallPlatform.administrator.products.variantSnapshots.options.index(
        adminConnection,
        {
          productId,
          snapshotId,
          body: request,
        },
      );
    },
  );
}
