export async function test_api_customer_order_items_list_empty_order(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/join",
      referrer: "https://example.com",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(authorized);
  await TestValidator.httpError(
    "nonexistent order should not expose unrelated order items",
    [404],
    async () => {
      await api.functional.mallPlatform.customer.orders.orderItems.index(
        customerConnection,
        {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformOrderItem.IRequest,
        },
      );
    },
  );
}
