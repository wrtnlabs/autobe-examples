export async function test_api_wishlist_items_exclude_deleted_products(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(customer);
  const wishlist =
    await api.functional.mallPlatform.customer.wishlists.items.index(
      customerConnection,
      {
        body: {
          page: 1,
          limit: 10,
        } satisfies IMallPlatformWishlistItem.IRequest,
      },
    );
  typia.assert(wishlist);
  TestValidator.equals(
    "wishlist response uses requested page",
    wishlist.pagination.current,
    1,
  );
  TestValidator.predicate(
    "wishlist data contains only current catalog items",
    wishlist.data.every((item) => item.product.deletedAt === null),
  );
}
