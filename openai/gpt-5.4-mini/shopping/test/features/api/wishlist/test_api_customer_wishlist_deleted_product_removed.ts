export async function test_api_customer_wishlist_deleted_product_removed(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com",
      referrer: "https://example.com",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const output = await api.functional.shoppingMall.customer.wishlists.index(
    customerConnection,
    {
      body: {
        page: 1,
        limit: 10,
        sort: "newest",
      } satisfies IShoppingMallWishlist.IRequest,
    },
  );
  typia.assert(output);
  for (const item of output.data) {
    typia.assert(item);
    typia.assert(item.product);
    TestValidator.predicate(
      "wishlist product is active",
      item.product.deletedAt === null,
    );
  }
}
