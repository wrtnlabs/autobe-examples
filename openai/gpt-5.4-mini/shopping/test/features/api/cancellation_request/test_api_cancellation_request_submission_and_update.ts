export async function test_api_cancellation_request_submission_and_update(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(authorized);
  const actorConnection: api.IConnection = {
    host: connection.host,
    headers: {
      Authorization: authorized.token.access,
    },
  };
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const requestBody = {
    reason: RandomGenerator.paragraph({ sentences: 2 }),
  } satisfies IMallPlatformCancellationRequest.IUpdate;
  await TestValidator.error(
    "cancellation request submission or update should be rejected for ineligible or unknown order items",
    async () => {
      const response =
        await api.functional.mallPlatform.seller.orderItems.cancellationRequests.patchByOrderitemid(
          actorConnection,
          {
            orderItemId,
            body: requestBody,
          },
        );
      typia.assert(response);
    },
  );
}
