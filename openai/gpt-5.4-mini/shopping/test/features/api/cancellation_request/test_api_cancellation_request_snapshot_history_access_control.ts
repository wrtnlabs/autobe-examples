export async function test_api_cancellation_request_snapshot_history_access_control(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const otherConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(otherConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const orderItemId: string = typia.random<string & tags.Format<"uuid">>();
  await generate_random_shopping_mall_customer_order_items_cancellation_request_create(
    ownerConnection,
    {
      params: { orderItemId },
      body: {
        reason: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IShoppingMallCancellationRequest.ICreate,
    },
  );
  const ownerSnapshots =
    await api.functional.shoppingMall.customer.order_items.cancellation_request.snapshots.index(
      ownerConnection,
      {
        orderItemId,
        body: {
          page: 1,
          limit: 10,
        },
      },
    );
  typia.assert(ownerSnapshots);
  await TestValidator.error(
    "other customer cannot access another customer's cancellation-request snapshot history",
    async () => {
      await api.functional.shoppingMall.customer.order_items.cancellation_request.snapshots.index(
        otherConnection,
        {
          orderItemId,
          body: {
            page: 1,
            limit: 10,
          },
        },
      );
    },
  );
}
