export async function test_api_cancellation_request_retrieve_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  const administratorEmail = typia.random<string & tags.Format<"email">>();
  const administratorPassword = RandomGenerator.alphaNumeric(16);
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: administratorEmail,
      password: administratorPassword,
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const output =
    await api.functional.shoppingMall.seller.order_items.cancellation_request.at(
      administratorConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(output);
}
