export async function test_api_cancellation_request_cross_item_access_blocked(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) satisfies string,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const mismatchedOrderItemId = typia.random<string & tags.Format<"uuid">>();
  const cancellationRequestId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "cross-item cancellation request access should be blocked",
    async () => {
      await api.functional.mallPlatform.customer.orderItems.cancellationRequests.at(
        customerConnection,
        {
          orderItemId: mismatchedOrderItemId,
          cancellationRequestId,
        },
      );
    },
  );
}
