export async function test_api_cancellation_request_ownership_access_denied(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(owner);
  const intruderConnection: api.IConnection = { host: connection.host };
  const intruder = await authorize_customer_join(intruderConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(intruder);
  await TestValidator.httpError(
    "customer cannot access another customer's cancellation request",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.customer.orderItems.cancellationRequests.at(
        intruderConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
