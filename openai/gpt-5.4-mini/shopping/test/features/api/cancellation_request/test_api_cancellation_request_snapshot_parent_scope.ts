export async function test_api_cancellation_request_snapshot_parent_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123!" satisfies string,
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  await TestValidator.httpError(
    "cancellation-request snapshot should not be accessible with unrelated parent scope",
    [400, 401, 403, 404],
    async () => {
      await api.functional.shoppingMall.seller.order_items.cancellation_request.snapshots.at(
        sellerConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
