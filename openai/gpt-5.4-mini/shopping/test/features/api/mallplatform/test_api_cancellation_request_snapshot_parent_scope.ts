export async function test_api_cancellation_request_snapshot_parent_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "http://localhost/register",
      referrer: "http://localhost/",
      ip: null,
    } satisfies IMallPlatformSeller.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const cancellationRequestId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should reject lookup for a snapshot when the parent cancellation scope is inconsistent",
    [400, 404],
    async () => {
      await api.functional.mallPlatform.seller.orderItems.cancellationRequests.snapshots.at(
        sellerConnection,
        {
          orderItemId,
          cancellationRequestId,
          snapshotId,
        },
      );
    },
  );
}
