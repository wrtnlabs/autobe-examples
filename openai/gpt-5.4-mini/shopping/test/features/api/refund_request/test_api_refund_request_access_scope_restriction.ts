export async function test_api_refund_request_access_scope_restriction(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/signup",
      referrer: "https://example.com/landing",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const strangerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(strangerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/signup",
      referrer: "https://example.com/landing",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    page: 1,
    limit: 10,
  } satisfies IMallPlatformRefundRequest.IRequest;
  await TestValidator.httpError(
    "refund requests must not be accessible across customer account boundaries",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.customer.orderItems.refundRequests.index(
        strangerConnection,
        {
          orderItemId,
          body,
        },
      );
    },
  );
}
