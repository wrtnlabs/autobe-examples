export async function test_api_refund_request_snapshot_history_empty_page(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: `${RandomGenerator.alphabets(8)}@test.com`,
      password: RandomGenerator.alphabets(12),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const response =
    await api.functional.mallPlatform.administrator.orderItems.refundRequests.snapshots.index(
      administratorConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
        refundRequestId: typia.random<string & tags.Format<"uuid">>(),
        body: {} satisfies IMallPlatformRefundRequestSnapshot.IRequest,
      },
    );
  typia.assert(response);
  TestValidator.equals(
    "snapshot history should be empty",
    response.data.length,
    0,
  );
  TestValidator.equals(
    "pagination current page should default to 1",
    response.pagination.current,
    1,
  );
  TestValidator.equals(
    "pagination records should be zero",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages should be zero",
    response.pagination.pages,
    0,
  );
}
