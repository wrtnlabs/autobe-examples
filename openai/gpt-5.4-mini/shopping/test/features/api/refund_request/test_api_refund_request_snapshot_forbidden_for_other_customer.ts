/**
 * Rejects refund-request snapshot access for a customer who does not own the order item.
 *
 * This test verifies that refund dispute history remains private to the owning customer by checking that a different authenticated customer cannot read the same refund-request snapshot endpoint. It focuses on authorization boundaries for the snapshot route and ensures the server returns a forbidden response rather than exposing historical refund data.
 *
 * 1. Register two independent customer accounts.
 * 2. Use the second customer as the unauthorized caller.
 * 3. Request a refund-request snapshot through the customer-scoped endpoint.
 * 4. Assert the non-owning customer receives a forbidden response.
 */
export async function test_api_refund_request_snapshot_forbidden_for_other_customer(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(owner);
  const otherConnection: api.IConnection = { host: connection.host };
  const other = await authorize_customer_join(otherConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(other);
  await TestValidator.httpError(
    "other customer cannot read refund-request snapshot",
    403,
    async () => {
      await api.functional.mallPlatform.customer.orderItems.refundRequests.snapshots.at(
        otherConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          refundRequestId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
