export async function test_api_refund_request_snapshot_history_authorization(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IMallPlatformSeller.IJoin,
  });
  await TestValidator.error(
    "unauthorized refund request snapshot history access should be rejected",
    async () => {
      await api.functional.mallPlatform.seller.refundRequests.snapshots.index(
        sellerConnection,
        {
          refundRequestId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
            sort: "-createdAt",
          } satisfies IMallPlatformRefundRequestSnapshot.IRequest,
        },
      );
    },
  );
}
