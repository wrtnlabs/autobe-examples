export async function test_api_refund_request_approve_refunded_item(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/customer/join",
      referrer: "https://example.com/",
      ip: null,
    },
  });
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password"> & tags.MinLength<1>>(),
    },
  });
  const output =
    await api.functional.shoppingMall.customer.orderItems.refundRequest.processRefundRequest(
      sellerConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
        body: {
          decision: "approve",
          reviewedReason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IShoppingMallRefundRequest.IProcess,
      },
    );
  typia.assert(output);
}
