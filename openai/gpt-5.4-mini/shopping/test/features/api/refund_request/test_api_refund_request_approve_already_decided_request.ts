export async function test_api_refund_request_approve_already_decided_request(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IMallPlatformSeller.IJoin,
  });
  sellerConnection.headers = {
    Authorization: authorized.token.access,
  };
  await TestValidator.error(
    "approval on a non-prepared refund request should fail",
    async () => {
      const output =
        await api.functional.mallPlatform.seller.refundRequests.approve.create(
          sellerConnection,
          {
            refundRequestId: typia.random<string & tags.Format<"uuid">>(),
          },
        );
      typia.assert(output);
    },
  );
}
