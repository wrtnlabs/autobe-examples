export async function test_api_refund_request_access_control_by_owner_seller_and_admin(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const intruderConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(intruderConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: null,
    },
  });
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const refundRequestId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "unrelated customer cannot access refund request",
    async () => {
      await api.functional.mallPlatform.customer.refundRequests.at(
        intruderConnection,
        {
          refundRequestId,
        },
      );
    },
  );
  await TestValidator.error(
    "seller cannot access unknown refund request without leakage",
    async () => {
      await api.functional.mallPlatform.customer.refundRequests.at(
        sellerConnection,
        {
          refundRequestId,
        },
      );
    },
  );
  await TestValidator.error(
    "administrator cannot access unknown refund request without leakage",
    async () => {
      await api.functional.mallPlatform.customer.refundRequests.at(
        adminConnection,
        {
          refundRequestId,
        },
      );
    },
  );
}
