export async function test_api_cancellation_request_submit_paid_item(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await api.functional.shoppingMall.auth.seller.join(
    sellerConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphabets(12),
      } satisfies IShoppingMallSeller.IJoin,
    },
  );
  typia.assert(seller);
  const reason = RandomGenerator.paragraph({ sentences: 2 });
  await TestValidator.error(
    "cancellation request should reject an unknown order item",
    async () => {
      await api.functional.shoppingMall.seller.orderItems.cancellation_request.update(
        sellerConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            reason,
          } satisfies IShoppingMallCancellationRequest.IUpdate,
        },
      );
    },
  );
}
