export async function test_api_cancellation_request_block_ineligible_item(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123",
    } satisfies IShoppingMallSeller.IJoin,
  });
  typia.assert(seller);
  const body = {
    reason: RandomGenerator.paragraph({ sentences: 2 }),
  } satisfies IShoppingMallCancellationRequest.IUpdate;
  await TestValidator.error(
    "should reject cancellation request update for an ineligible order item",
    async () => {
      await api.functional.shoppingMall.seller.orderItems.cancellation_request.update(
        sellerConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          body,
        },
      );
    },
  );
}
