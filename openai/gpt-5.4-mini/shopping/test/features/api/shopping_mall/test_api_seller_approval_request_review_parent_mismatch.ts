export async function test_api_seller_approval_request_review_parent_mismatch(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  await TestValidator.httpError(
    "seller approval request review should not leak across different parents",
    [404, 400],
    async () => {
      await api.functional.shoppingMall.administrator.seller_approval_requests.reviews.at(
        adminConnection,
        {
          sellerApprovalRequestId: typia.random<string & tags.Format<"uuid">>(),
          sellerApprovalRequestReviewId: typia.random<
            string & tags.Format<"uuid">
          >(),
        },
      );
    },
  );
}
