export async function test_api_refund_request_snapshot_history_access_boundary(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
    } satisfies IShoppingMallSeller.IJoin,
  });
  const orderItemId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.error(
    "seller cannot inspect refund-request snapshot history outside fulfillment scope",
    async () => {
      await api.functional.shoppingMall.seller.order_items.refund_request.snapshots.index(
        sellerConnection,
        {
          orderItemId,
          body: {
            page: 1,
            limit: 10,
            sort: "createdAt",
            order: "desc",
          } satisfies IShoppingMallRefundRequestSnapshot.IRequest,
        },
      );
    },
  );
}
