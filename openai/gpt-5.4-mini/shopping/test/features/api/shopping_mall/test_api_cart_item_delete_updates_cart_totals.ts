export async function test_api_cart_item_delete_updates_cart_totals(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234!@#$",
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const cartItemId = typia.random<string & tags.Format<"uuid">>();
  await api.functional.shoppingMall.customer.items.erase(customerConnection, {
    cartItemId,
  });
  TestValidator.predicate(
    "customer connection should be isolated from the base connection",
    customerConnection.host === connection.host,
  );
  TestValidator.predicate(
    "delete target should be a uuid string",
    typeof cartItemId === "string" && cartItemId.length > 0,
  );
}
