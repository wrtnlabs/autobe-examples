export async function test_api_order_item_snapshots_visibility_protection(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const response =
    await api.functional.shoppingMall.administrator.orderItems.snapshots.index(
      adminConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
        body: {
          page: 1,
          limit: 10,
          sort: "-createdAt",
          search: RandomGenerator.alphabets(3),
        } satisfies IShoppingMallOrderItemSnapshot.IRequest,
      },
    );
  typia.assert(response);
}
