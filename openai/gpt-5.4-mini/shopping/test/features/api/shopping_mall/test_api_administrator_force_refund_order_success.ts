export async function test_api_administrator_force_refund_order_success(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const invalidOrderId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "force refund rejects unknown order identifiers",
    [400, 404],
    async () => {
      await api.functional.shoppingMall.administrator.orders.force_refund.process(
        administratorConnection,
        {
          orderId: invalidOrderId,
        },
      );
    },
  );
}
