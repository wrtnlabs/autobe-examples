export async function test_api_order_item_snapshots_empty_history(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const output =
    await api.functional.shoppingMall.administrator.orderItems.snapshots.index(
      adminConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
        body: {} satisfies IShoppingMallOrderItemSnapshot.IRequest,
      },
    );
  typia.assert(output);
  TestValidator.equals("snapshot list should be empty", output.data.length, 0);
  TestValidator.equals(
    "snapshot records should be zero",
    output.pagination.records,
    0,
  );
  TestValidator.equals(
    "snapshot pages should be zero",
    output.pagination.pages,
    0,
  );
}
