export async function test_api_cancellation_request_snapshot_history_empty_state(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const response =
    await api.functional.shoppingMall.administrator.order_items.cancellation_request.snapshots.index(
      adminConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
        body: {},
      },
    );
  typia.assert(response);
  TestValidator.equals("empty cancellation snapshot data", response.data, []);
  TestValidator.predicate(
    "pagination metadata exists",
    response.pagination.current !== undefined &&
      response.pagination.limit !== undefined &&
      response.pagination.records !== undefined &&
      response.pagination.pages !== undefined,
  );
}
