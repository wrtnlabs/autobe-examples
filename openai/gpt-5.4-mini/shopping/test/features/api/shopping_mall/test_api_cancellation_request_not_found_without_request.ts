export async function test_api_cancellation_request_not_found_without_request(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  typia.assert(authorized);
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return not found when cancellation request does not exist",
    [404, 422],
    async () => {
      await api.functional.shoppingMall.administrator.order_items.cancellation_request.at(
        adminConnection,
        {
          orderItemId,
        },
      );
    },
  );
}
