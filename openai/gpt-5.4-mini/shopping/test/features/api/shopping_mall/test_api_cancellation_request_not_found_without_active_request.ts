export async function test_api_cancellation_request_not_found_without_active_request(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: `${RandomGenerator.alphabets(8)}@test.com` satisfies string &
        tags.Format<"email">,
      password: RandomGenerator.alphabets(12),
    } satisfies IShoppingMallSeller.IJoin,
  });
  await TestValidator.httpError(
    "cancellation request lookup should return not found when no active request exists",
    404,
    async () => {
      await api.functional.shoppingMall.seller.order_items.cancellation_request.at(
        sellerConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
