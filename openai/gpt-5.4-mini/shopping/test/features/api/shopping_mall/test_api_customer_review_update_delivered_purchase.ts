export async function test_api_customer_review_update_delivered_purchase(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphabets(12),
      href: "https://example.com/join",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(joined);
  await TestValidator.error(
    "updating a non-existent or unauthorized review should fail",
    async () => {
      await api.functional.shoppingMall.customer.reviews.update(
        customerConnection,
        {
          reviewId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            rating: 5,
            content: RandomGenerator.paragraph({ sentences: 3 }),
          } satisfies IShoppingMallReview.IUpdate,
        },
      );
    },
  );
}
