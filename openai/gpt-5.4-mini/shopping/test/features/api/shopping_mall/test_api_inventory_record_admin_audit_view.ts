export async function test_api_inventory_record_admin_audit_view(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_login(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.ILogin,
  });
  const inventoryRecord =
    await api.functional.shoppingMall.seller.productVariants.inventoryRecords.at(
      administratorConnection,
      {
        productVariantId: typia.random<string & tags.Format<"uuid">>(),
        inventoryRecordId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(inventoryRecord);
  TestValidator.predicate(
    "inventory record quantity change is signed",
    inventoryRecord.quantityChange !== 0,
  );
  TestValidator.predicate(
    "inventory record reason is non-empty",
    inventoryRecord.reason.length > 0,
  );
  TestValidator.predicate(
    "inventory record timestamps are ordered",
    inventoryRecord.createdAt <= inventoryRecord.updatedAt,
  );
}
