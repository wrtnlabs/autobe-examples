export async function test_api_customer_order_items_preserved_after_account_deletion(
  connection: api.IConnection,
): Promise<void> {
  // Test that an authenticated customer context can be established for preserved-order history workflows.
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234!Aa",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(authorized);
  TestValidator.predicate(
    "customer authorization token exists",
    customerConnection.headers !== undefined,
  );
  TestValidator.predicate(
    "customer authorization header is set",
    customerConnection.headers?.Authorization !== undefined,
  );
}
