export async function test_api_administrator_force_refund_order_item_success(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_login(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.ILogin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  await api.functional.shoppingMall.administrator.order_items.force_refund.forceRefund(
    administratorConnection,
    {
      orderItemId,
      body: {
        reason: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IShoppingMallOrderItem.IForceRefund,
    },
  );
}
