export async function test_api_administrator_force_refund_access_restricted(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      href: "",
      referrer: "",
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const administratorOrderId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "customer cannot force-refund an order",
    [401, 403],
    async () => {
      await api.functional.shoppingMall.administrator.orders.force_refund.process(
        customerConnection,
        {
          orderId: administratorOrderId,
        },
      );
    },
  );
  const anonymousConnection: api.IConnection = { host: connection.host };
  await TestValidator.httpError(
    "anonymous user cannot force-refund an order",
    [401, 403],
    async () => {
      await api.functional.shoppingMall.administrator.orders.force_refund.process(
        anonymousConnection,
        {
          orderId: administratorOrderId,
        },
      );
    },
  );
}
