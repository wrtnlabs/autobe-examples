export async function test_api_administrator_approval_request_review_queue(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(
    administratorConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: typia.random<string & tags.Format<"password">>(),
      } satisfies IMallPlatformAdministrator.IJoin,
    },
  );
  typia.assert(authorized);
  const response =
    await api.functional.mallPlatform.administrator.administrators.index(
      administratorConnection,
      {
        body: {
          page: 1,
          limit: 10,
        } satisfies IMallPlatformAdministratorApprovalRequest.IRequest,
      },
    );
  typia.assert(response);
  TestValidator.predicate(
    "pagination current page should be at least 1",
    response.pagination.current >= 1,
  );
  TestValidator.predicate(
    "pagination limit should be positive",
    response.pagination.limit > 0,
  );
  TestValidator.predicate(
    "pagination records should be non-negative",
    response.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages should be non-negative",
    response.pagination.pages >= 0,
  );
  TestValidator.predicate(
    "response data should be an array",
    Array.isArray(response.data),
  );
}
