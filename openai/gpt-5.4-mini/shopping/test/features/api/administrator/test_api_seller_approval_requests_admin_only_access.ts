export async function test_api_seller_approval_requests_admin_only_access(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/",
      referrer: "https://example.com/",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const request = {
    status: null,
    shoppingMallSellerId: null,
    rejectionReason: null,
    createdAtFrom: null,
    createdAtTo: null,
    updatedAtFrom: null,
    updatedAtTo: null,
    page: 1,
    limit: 10,
    sort: null,
  } satisfies IShoppingMallSellerApprovalRequest.IRequest;
  await TestValidator.error(
    "non-administrator cannot access seller approval requests",
    async () => {
      await api.functional.shoppingMall.administrator.seller_approval_requests.index(
        customerConnection,
        { body: request },
      );
    },
  );
}
