export async function test_api_administrator_approval_request_approve_pending_request(
  connection: api.IConnection,
): Promise<void> {
  const superAdministratorConnection: api.IConnection = {
    host: connection.host,
  };
  await authorize_administrator_join(superAdministratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const output = typia.random<IMallPlatformAdministratorApprovalRequest>();
  typia.assert(output);
  TestValidator.predicate(
    "reviewed request should have an id",
    output.id.length > 0,
  );
  TestValidator.predicate(
    "reviewed request should reference an administrator",
    output.administrator !== null,
  );
}
