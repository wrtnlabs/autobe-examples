export async function test_api_administrator_approval_requests_empty_page(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const response =
    await api.functional.mallPlatform.administrator.approval_requests.index(
      administratorConnection,
      {
        body: {
          search: RandomGenerator.alphabets(32),
          page: 1,
          limit: 1,
        } satisfies IMallPlatformAdministratorApprovalRequest.IRequest,
      },
    );
  typia.assert(response);
  TestValidator.equals("empty page records", response.pagination.records, 0);
  TestValidator.equals("empty page pages", response.pagination.pages, 0);
  TestValidator.equals("empty page data length", response.data.length, 0);
}
