export async function test_api_order_item_snapshot_history_empty_page(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "P@ssw0rd1234",
      href: "https://example.com/register",
      referrer: "https://example.com/",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(customer);
  const output =
    await api.functional.mallPlatform.customer.orders.orderItems.snapshots.index(
      customerConnection,
      {
        orderId: customer.id,
        orderItemId: customer.id,
        body: {
          page: 1,
          limit: 10,
        } satisfies IMallPlatformOrderItemSnapshot.IRequest,
      },
    );
  typia.assert(output);
  TestValidator.equals(
    "snapshot history should be empty",
    output.data.length,
    0,
  );
  TestValidator.equals(
    "snapshot record count should be zero",
    output.pagination.records,
    0,
  );
  TestValidator.equals(
    "snapshot page count should be zero",
    output.pagination.pages,
    0,
  );
}
