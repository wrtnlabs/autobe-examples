export async function test_api_order_item_snapshot_history_for_seller_access_control(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const request = {
    page: 1,
    limit: 10,
    sort: "snapshotAt_desc",
  } satisfies IMallPlatformOrderItemSnapshot.IRequest;
  await TestValidator.error(
    "seller access control rejects unauthorized snapshot history access",
    async () => {
      await api.functional.mallPlatform.customer.orderItems.snapshots.index(
        sellerConnection,
        {
          orderItemId,
          body: request,
        },
      );
    },
  );
}
