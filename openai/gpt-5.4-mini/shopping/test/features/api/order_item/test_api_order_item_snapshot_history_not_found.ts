/**
 * Verifies snapshot history lookup for a missing order item returns not found.
 *
 * This test covers the seller-authenticated snapshot history endpoint for order items.
 * It confirms the service resolves the parent order item before returning snapshot data and that a nonexistent identifier is rejected with a 404 response instead of an empty page.
 *
 * 1. Authenticate as a seller through the dedicated join utility using a fresh connection.
 * 2. Call the order-item snapshot history endpoint with a randomly generated UUID that does not correspond to any existing order item.
 * 3. Assert that the call fails with a not found HTTP error.
 */
export async function test_api_order_item_snapshot_history_not_found(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const missingOrderItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "missing order item snapshot history should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.seller.orderItems.snapshots.getByOrderitemid(
        sellerConnection,
        {
          orderItemId: missingOrderItemId,
        },
      );
    },
  );
}
