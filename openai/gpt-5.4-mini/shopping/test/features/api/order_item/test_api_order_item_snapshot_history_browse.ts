export async function test_api_order_item_snapshot_history_browse(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email:
        `seller_${RandomGenerator.alphabets(8)}@test.com` satisfies string &
          tags.Format<"email">,
      password: `P@ssw0rd_${RandomGenerator.alphabets(8)}` satisfies string &
        tags.Format<"password">,
    } satisfies IMallPlatformSeller.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const page =
    await api.functional.mallPlatform.seller.orderItems.snapshots.index(
      sellerConnection,
      {
        orderItemId,
        body: {
          page: 1,
          limit: 10,
          sort: "-snapshotAt",
        } satisfies IMallPlatformOrderItemSnapshot.IRequest,
      },
    );
  typia.assert(page);
  TestValidator.equals("pagination current page", page.pagination.current, 1);
  TestValidator.equals("pagination limit", page.pagination.limit, 10);
  TestValidator.predicate(
    "pagination records is non-negative",
    page.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages is non-negative",
    page.pagination.pages >= 0,
  );
  for (let i = 1; i < page.data.length; i++) {
    TestValidator.predicate(
      "snapshots are sorted newest first",
      page.data[i - 1].snapshotAt >= page.data[i].snapshotAt,
    );
  }
  for (const snapshot of page.data) {
    TestValidator.equals(
      "order item id context",
      snapshot.orderItem.id,
      orderItemId,
    );
  }
}
