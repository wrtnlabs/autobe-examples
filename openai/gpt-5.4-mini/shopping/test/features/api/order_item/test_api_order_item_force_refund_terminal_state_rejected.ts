export async function test_api_order_item_force_refund_terminal_state_rejected(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "force-refund should be rejected for a non-refundable terminal order item",
    async () => {
      await api.functional.mallPlatform.administrator.orderItems.force_refund.forceRefund(
        administratorConnection,
        {
          orderItemId,
        },
      );
    },
  );
}
