export async function test_api_order_item_snapshot_variant_option_scope_protection(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const optionId = orderItemId;
  await TestValidator.httpError(
    "scope protection should reject mismatched preserved snapshot option access",
    404,
    async () => {
      await api.functional.mallPlatform.customer.order_items.snapshots.variant_options.at(
        customerConnection,
        {
          orderItemId,
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
          optionId,
        },
      );
    },
  );
}
