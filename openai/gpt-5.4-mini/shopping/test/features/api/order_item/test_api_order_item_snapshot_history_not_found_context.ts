export async function test_api_order_item_snapshot_history_not_found_context(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  await TestValidator.httpError(
    "administrator order item snapshot history should return not found for mismatched order and order item context",
    404,
    async () => {
      await api.functional.mallPlatform.administrator.orders.orderItems.snapshots.index(
        adminConnection,
        {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformOrderItemSnapshot.IRequest,
        },
      );
    },
  );
}
