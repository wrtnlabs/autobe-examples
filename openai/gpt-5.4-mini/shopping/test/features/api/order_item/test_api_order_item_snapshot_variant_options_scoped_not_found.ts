/**
 * Verify scoped variant options return not found when the snapshot scope is invalid.
 *
 * This test checks that administrator-only access to preserved order-item snapshot variant options is correctly constrained to the exact order item and snapshot pairing. It uses a deliberately missing or mismatched UUID scope to confirm the endpoint does not expose preserved option rows outside the immutable snapshot context.
 *
 * 1. Authenticate an isolated administrator connection through the required join utility.
 * 2. Request variant options for random order item and snapshot UUIDs that do not correspond to a real scoped snapshot.
 * 3. Assert the API returns the standard 404 not-found response and no option payload is produced.
 */
export async function test_api_order_item_snapshot_variant_options_scoped_not_found(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  await TestValidator.httpError(
    "scoped variant options should not be found for an invalid snapshot scope",
    404,
    async () => {
      await api.functional.mallPlatform.administrator.orderItems.snapshots.variantOptions.index(
        adminConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          orderItemSnapshotId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformOrderItemSnapshotVariantOption.IRequest,
        },
      );
    },
  );
}
