export async function test_api_order_item_snapshot_variant_option_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "variant option should return not found for a missing order item snapshot chain",
    404,
    async () => {
      await api.functional.mallPlatform.customer.order_items.snapshots.variant_options.at(
        customerConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
          optionId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
