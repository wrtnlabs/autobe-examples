export async function test_api_order_item_force_refund_isolates_target_item(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const output =
    await api.functional.mallPlatform.seller.orderItems.force_refund.forceRefund(
      sellerConnection,
      {
        orderItemId,
      },
    );
  typia.assert(output);
  TestValidator.equals(
    "targeted item becomes refunded",
    output.status,
    "refunded",
  );
  TestValidator.equals("order item id is preserved", output.id, orderItemId);
  TestValidator.predicate(
    "order relation exists",
    () => output.order.id.length > 0,
  );
  TestValidator.predicate(
    "product variant relation exists",
    () => output.productVariant.id.length > 0,
  );
  TestValidator.predicate(
    "seller relation exists",
    () => output.seller.id.length > 0,
  );
}
