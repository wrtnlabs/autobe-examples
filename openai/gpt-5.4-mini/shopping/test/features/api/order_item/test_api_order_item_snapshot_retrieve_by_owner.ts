export async function test_api_order_item_snapshot_retrieve_by_owner(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.mallPlatform.customer.order_items.snapshots.at(
      customerConnection,
      { orderItemId, snapshotId },
    );
  typia.assert(snapshot);
  TestValidator.equals(
    "order item id preserved",
    snapshot.orderItem.id,
    snapshot.orderItem.id,
  );
  TestValidator.equals("snapshot id preserved", snapshot.id, snapshot.id);
  TestValidator.predicate(
    "snapshot timestamp exists",
    snapshot.snapshotAt.length > 0,
  );
  TestValidator.predicate(
    "created timestamp exists",
    snapshot.createdAt.length > 0,
  );
  TestValidator.predicate(
    "updated timestamp exists",
    snapshot.updatedAt.length > 0,
  );
}
