export async function test_api_cart_item_delete_other_customer_item(
  connection: api.IConnection,
): Promise<void> {
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234!@#$",
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234!@#$",
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  await TestValidator.httpError(
    "should reject deleting another customer's cart item",
    [401, 403, 404],
    async () => {
      await api.functional.shoppingMall.customer.items.erase(
        customerAConnection,
        {
          cartItemId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
