/**
 * Verifies that a customer cannot access another customer's shipment detail.
 *
 * This test validates the customer shipment access-control boundary by creating
 * an authenticated customer session and then requesting a shipment detail using
 * a valid UUID that is outside the caller's ownership scope. The endpoint must
 * reject the request according to the platform's authorization convention
 * without exposing carrier, tracking, order, or shipment item data.
 *
 * 1. Register and authenticate a fresh customer session.
 * 2. Request a shipment detail with a syntactically valid UUID not owned by the caller.
 * 3. Assert that the API rejects the request with an HTTP authorization-style error.
 */
export async function test_api_customer_shipment_detail_other_customer_access_denied(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Test1234!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "other customer shipment detail should be inaccessible",
    [403, 404],
    async () => {
      await api.functional.mallPlatform.customer.shipments.at(
        customerConnection,
        {
          shipmentId,
        },
      );
    },
  );
}
