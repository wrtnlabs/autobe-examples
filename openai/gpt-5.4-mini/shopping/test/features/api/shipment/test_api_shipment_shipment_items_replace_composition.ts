export async function test_api_shipment_shipment_items_replace_composition(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const output =
    await api.functional.mallPlatform.customer.shipments.shipmentItems.index(
      customerConnection,
      {
        shipmentId: typia.random<string & tags.Format<"uuid">>(),
        body: {
          orderItemIds: [typia.random<string & tags.Format<"uuid">>()],
        } satisfies IMallPlatformShipmentItem.IUpdate,
      },
    );
  typia.assert(output);
  TestValidator.predicate(
    "shipment items response includes pagination metadata",
    () => output.pagination.current >= 0 && output.pagination.limit >= 0,
  );
  TestValidator.predicate("shipment items response includes a data array", () =>
    Array.isArray(output.data),
  );
}
