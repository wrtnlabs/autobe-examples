export async function test_api_shipment_detail_not_found_for_unavailable_shipment(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const unavailableShipmentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "shipment detail should return not found for an unavailable shipment",
    404,
    async () => {
      await api.functional.mallPlatform.seller.shipments.at(sellerConnection, {
        shipmentId: unavailableShipmentId,
      });
    },
  );
}
