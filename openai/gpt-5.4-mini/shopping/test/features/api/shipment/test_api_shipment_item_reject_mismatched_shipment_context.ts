export async function test_api_shipment_item_reject_mismatched_shipment_context(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Test shipment-item lookup rejects a mismatched shipment context.
   *
   * Verifies that shipment-item retrieval remains scoped to the shipment in the
   * request path and does not leak data when the shipment-item identifier does
   * not belong to that shipment.
   *
   * 1. Register and authenticate a customer account.
   * 2. Call the shipment-item endpoint with mismatched shipment identifiers.
   * 3. Assert that the API responds with a not-found error.
   */
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Test1234!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  const shipmentItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "shipment item must not be readable through a mismatched shipment context",
    404,
    async () => {
      await api.functional.mallPlatform.customer.shipments.items.getByShipmentidAndShipmentitemid(
        customerConnection,
        {
          shipmentId,
          shipmentItemId,
        },
      );
    },
  );
}
