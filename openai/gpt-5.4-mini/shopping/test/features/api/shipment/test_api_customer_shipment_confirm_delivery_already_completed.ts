/**
 * Reject repeated delivery confirmation attempts for a shipment endpoint target.
 *
 * Validates that the customer shipment delivery confirmation endpoint does not allow a second completion attempt on the same shipment target. Because the provided test surface does not include shipment creation or lookup APIs, this test uses a typed shipment identifier and verifies that the endpoint rejects the request through the authenticated customer flow.
 *
 * 1. Register and authenticate a customer using the join utility.
 * 2. Call shipment delivery confirmation with a typed shipment identifier.
 * 3. Confirm the request is rejected as an unavailable or conflict-style business failure.
 */
export async function test_api_customer_shipment_confirm_delivery_already_completed(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(customer);
  await TestValidator.httpError(
    "shipment delivery confirmation should reject an already completed or unavailable shipment",
    [400, 404, 409],
    async () => {
      await api.functional.mallPlatform.customer.shipments.confirm_delivery.create(
        customerConnection,
        {
          shipmentId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
