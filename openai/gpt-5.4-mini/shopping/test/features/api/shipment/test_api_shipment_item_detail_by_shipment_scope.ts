export async function test_api_shipment_item_detail_by_shipment_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(authorized);
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  const shipmentItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "shipment item detail should reject unknown shipment scope",
    404,
    async () => {
      await api.functional.mallPlatform.seller.shipments.items.at(
        sellerConnection,
        {
          shipmentId,
          shipmentItemId,
        },
      );
    },
  );
}
