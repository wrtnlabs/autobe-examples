export async function test_api_shipment_detail_retrieve_by_seller(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/seller/join",
      referrer: "https://example.com/",
      ip: "127.0.0.1",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerAuth);
  await TestValidator.httpError(
    "shipment detail should return not found for an unavailable shipment",
    404,
    async () => {
      await api.functional.mallPlatform.seller.shipments.at(sellerConnection, {
        shipmentId: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
