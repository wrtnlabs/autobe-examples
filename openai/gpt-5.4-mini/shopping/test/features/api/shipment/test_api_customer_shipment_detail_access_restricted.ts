export async function test_api_customer_shipment_detail_access_restricted(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password1234",
      href: "https://example.com/register/customer",
      referrer: "https://example.com/signup",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "customer shipment detail should reject access to a shipment not owned by the authenticated customer",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.customer.shipments.at(
        customerConnection,
        {
          shipmentId,
        },
      );
    },
  );
}
