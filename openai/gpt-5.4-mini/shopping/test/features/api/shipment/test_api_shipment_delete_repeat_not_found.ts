export async function test_api_shipment_delete_repeat_not_found(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerAuth);
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  await api.functional.mallPlatform.seller.shipments.erase(sellerConnection, {
    shipmentId,
  });
  await TestValidator.httpError(
    "repeated shipment deletion should return not found",
    [404, 410],
    async () => {
      await api.functional.mallPlatform.seller.shipments.erase(
        sellerConnection,
        {
          shipmentId,
        },
      );
    },
  );
}
