/**
 * Verifies administrator shipment-item visibility protection for inaccessible shipment IDs.
 *
 * This test validates that the administrator shipment-items endpoint does not leak shipment membership data when the requested shipment identifier is not accessible or does not exist.
 *
 * 1. Create an administrator-authenticated connection using the provided join utility.
 * 2. Request shipment items for a syntactically valid UUID that is expected to be missing from the platform.
 * 3. Assert that the endpoint responds with the platform's standard not-found or authorization failure.
 */
export async function test_api_shipment_items_visibility_protection(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "administrator shipment items should reject inaccessible shipment id",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.administrator.shipments.items.getByShipmentid(
        adminConnection,
        {
          shipmentId,
        },
      );
    },
  );
}
