export async function test_api_shipment_detail_not_found(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234" satisfies string,
    } satisfies IShoppingMallSeller.IJoin,
  });
  await TestValidator.httpError(
    "seller shipment detail should return not found for missing shipment",
    404,
    async () => {
      await api.functional.shoppingMall.seller.shipments.at(sellerConnection, {
        shipmentId: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
