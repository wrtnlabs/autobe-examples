export async function test_api_shipment_update_completed_shipment_blocked(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  const body: IMallPlatformShipment.IUpdate = {
    carrierName: RandomGenerator.name(),
    trackingNumber: RandomGenerator.alphaNumeric(12),
    trackingUrl: `https://example.com/track/${RandomGenerator.alphaNumeric(8)}`,
    status: "shipped",
  };
  await TestValidator.error(
    "completed shipment update is rejected",
    async () => {
      await api.functional.mallPlatform.seller.shipments.update(
        sellerConnection,
        {
          shipmentId,
          body,
        },
      );
    },
  );
}
