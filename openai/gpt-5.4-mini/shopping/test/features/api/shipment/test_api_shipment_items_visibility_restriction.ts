export async function test_api_shipment_items_visibility_restriction(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/register",
      referrer: "https://example.com/",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "shipment items should not be visible to an unauthorized customer for an arbitrary shipment id",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.customer.shipments.items.getByShipmentid(
        customerConnection,
        {
          shipmentId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
