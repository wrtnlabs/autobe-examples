/**
 * Verifies that shipment details cannot be read outside the owning seller scope.
 *
 * This test authenticates a seller account and then attempts to retrieve a shipment detail using an identifier that is not guaranteed to belong to that seller. It validates the platform's protected-resource convention by ensuring the request is rejected rather than exposing carrier data, tracking information, order context, or shipment items.
 *
 * 1. Authenticate as a seller using an isolated seller connection.
 * 2. Request a shipment detail for an out-of-scope shipment identifier.
 * 3. Confirm the API denies access with an authorization-style HTTP error.
 */
export async function test_api_shipment_detail_forbidden_outside_seller_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123!",
    } satisfies IMallPlatformSeller.IJoin,
  });
  await TestValidator.httpError(
    "seller cannot access another seller's shipment detail",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.seller.shipments.at(sellerConnection, {
        shipmentId: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
