export async function test_api_customer_shipment_items_list(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(authorized);
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  const output =
    await api.functional.mallPlatform.customer.shipments.items.index(
      customerConnection,
      {
        shipmentId,
        body: {
          page: 1,
          limit: 10,
        } satisfies IMallPlatformShipmentItem.IRequest,
      },
    );
  typia.assert(output);
  TestValidator.equals("pagination current page", output.pagination.current, 1);
  TestValidator.equals("pagination limit", output.pagination.limit, 10);
  TestValidator.predicate(
    "pagination records non-negative",
    output.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages non-negative",
    output.pagination.pages >= 0,
  );
  TestValidator.predicate(
    "shipment items contain shipment context",
    output.data.every((item) => item.shipment.id === shipmentId),
  );
  TestValidator.predicate(
    "shipment items contain nested order item context",
    output.data.every(
      (item) =>
        item.orderItem.id.length > 0 &&
        item.orderItem.quantity >= 0 &&
        item.orderItem.seller.id.length > 0,
    ),
  );
}
