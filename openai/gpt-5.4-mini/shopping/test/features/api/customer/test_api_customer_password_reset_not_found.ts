export async function test_api_customer_password_reset_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "ChangeMe123!",
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: null,
    } satisfies IShoppingMallCustomer.IJoin,
  });
  await TestValidator.httpError(
    "missing customer password reset should return not found",
    404,
    async () => {
      await api.functional.shoppingMall.customer.password_resets.at(
        customerConnection,
        {
          passwordResetId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
