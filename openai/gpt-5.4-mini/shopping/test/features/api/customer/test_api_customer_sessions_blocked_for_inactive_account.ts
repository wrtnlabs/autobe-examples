export async function test_api_customer_sessions_blocked_for_inactive_account(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "http://localhost",
      referrer: "http://localhost",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(authorized);
  const blockedConnection: api.IConnection = { host: connection.host };
  await TestValidator.httpError(
    "unauthorized customer session listing is rejected",
    [401, 403],
    async () => {
      await api.functional.shoppingMall.customer.sessions.index(
        blockedConnection,
        {
          body: {
            page: 1,
            limit: 10,
          } satisfies IShoppingMallCustomerSession.IRequest,
        },
      );
    },
  );
}
