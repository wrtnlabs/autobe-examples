export async function test_api_customer_account_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const accountId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  TestValidator.notEquals(
    "unknown account id should differ from the authenticated customer id",
    accountId,
    authorized.id,
  );
  await TestValidator.httpError(
    "customer account lookup should return not found for unknown account id",
    404,
    async () => {
      await api.functional.mallPlatform.customer.accounts.at(
        customerConnection,
        {
          accountId,
        },
      );
    },
  );
}
