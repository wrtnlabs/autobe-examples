export async function test_api_customer_password_reset_lookup(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.error(
    "unknown password reset record should be rejected",
    async () => {
      await api.functional.mallPlatform.customer.password_resets.at(
        customerConnection,
        {
          passwordResetId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
