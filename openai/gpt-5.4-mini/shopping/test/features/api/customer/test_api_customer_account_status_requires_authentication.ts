export async function test_api_customer_account_status_requires_authentication(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!" satisfies string & tags.Format<"password">,
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "unauthenticated customer account status request should be rejected",
    [401, 403],
    async () => {
      await api.functional.mallPlatform.customer.account.status.at({
        host: connection.host,
      });
    },
  );
}
