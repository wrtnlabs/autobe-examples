export async function test_api_customer_email_verification_unknown_token_integrity(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      href: "https://example.com/signup",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  await TestValidator.error(
    "unknown verification token should be rejected",
    async () => {
      await api.functional.shoppingMall.customer.email_verifications.validate(
        customerConnection,
        {
          body: {
            token: typia.random<string>(),
          } satisfies IShoppingMallCustomerEmailVerification.IRequest,
        },
      );
    },
  );
}
