export async function test_api_review_detail_own_review(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password1234",
      href: "https://example.com/join",
      referrer: "https://example.com/referrer",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(customer);
  const review = await api.functional.shoppingMall.reviews.at(
    customerConnection,
    {
      reviewId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  typia.assert(review);
  TestValidator.equals("review customer id", review.customer.id, customer.id);
  TestValidator.equals("active review deleted_at", review.deleted_at, null);
  TestValidator.predicate(
    "review has valid live timestamps",
    review.created_at <= review.updated_at,
  );
  TestValidator.predicate(
    "review contains linked product summary",
    review.product.id.length > 0 && review.product.name.length > 0,
  );
  TestValidator.predicate(
    "review contains linked order item summary",
    review.orderItem.id.length > 0 && review.orderItem.quantity > 0,
  );
}
