export async function test_api_review_detail_foreign_customer_forbidden(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const foreignConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/register/owner",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(owner);
  const foreign = await authorize_customer_join(foreignConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/register/foreign",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(foreign);
  const review = await api.functional.shoppingMall.reviews.at(ownerConnection, {
    reviewId: typia.random<string & tags.Format<"uuid">>(),
  });
  typia.assert(review);
  await TestValidator.httpError(
    "foreign customer should be forbidden from viewing another customer's review",
    [401, 403, 404],
    async () => {
      await api.functional.shoppingMall.reviews.at(foreignConnection, {
        reviewId: review.id,
      });
    },
  );
}
