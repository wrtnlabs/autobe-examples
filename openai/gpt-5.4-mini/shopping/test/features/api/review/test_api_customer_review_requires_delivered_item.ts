export async function test_api_customer_review_requires_delivered_item(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(customer);
  const body = {
    orderItemId: typia.random<string & tags.Format<"uuid">>(),
    productId: typia.random<string & tags.Format<"uuid">>(),
    rating: 5,
    content: RandomGenerator.paragraph({ sentences: 2 }),
  } satisfies IMallPlatformReview.ICreate;
  await TestValidator.error(
    "cannot create a review before the order item is delivered",
    async () => {
      await generate_random_mall_platform_customer_reviews_create(
        customerConnection,
        {
          body,
        },
      );
    },
  );
}
