export async function test_api_review_snapshot_retrieve_requires_matching_review_scope(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const validReviewId = typia.random<string & tags.Format<"uuid">>();
  const mismatchedSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should reject snapshot retrieval when snapshot does not belong to review",
    [404, 400],
    async () => {
      await api.functional.mallPlatform.administrator.reviews.snapshots.at(
        adminConnection,
        {
          reviewId: validReviewId,
          snapshotId: mismatchedSnapshotId,
        },
      );
    },
  );
}
