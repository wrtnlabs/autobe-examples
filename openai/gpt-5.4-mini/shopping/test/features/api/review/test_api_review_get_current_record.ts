export async function test_api_review_get_current_record(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password1234",
    } satisfies IMallPlatformSeller.IJoin,
  });
  const reviewId = typia.random<string & tags.Format<"uuid">>();
  const output = await api.functional.mallPlatform.seller.reviews.at(
    sellerConnection,
    {
      reviewId,
    },
  );
  typia.assert(output);
  TestValidator.equals(
    "review id should be returned",
    output.reviewId,
    reviewId,
  );
  TestValidator.predicate(
    "display state should be a valid current ownership indicator",
    output.displayState === "activeCustomer" ||
      output.displayState === "deletedUser",
  );
}
