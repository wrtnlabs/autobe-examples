export async function test_api_review_snapshot_retrieve_by_administrator(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const reviewId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.mallPlatform.administrator.reviews.snapshots.at(
      administratorConnection,
      {
        reviewId,
        snapshotId,
      },
    );
  typia.assert(snapshot);
  TestValidator.equals("snapshot id", snapshot.id, snapshotId);
  TestValidator.equals("snapshot review id", snapshot.review.id, reviewId);
  TestValidator.predicate(
    "snapshot action is present",
    snapshot.snapshotAction.length > 0,
  );
  TestValidator.predicate(
    "snapshot rating is valid",
    snapshot.rating >= 1 && snapshot.rating <= 5,
  );
  TestValidator.predicate(
    "snapshot createdAt is present",
    snapshot.createdAt.length > 0,
  );
}
