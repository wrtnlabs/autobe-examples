export async function test_api_review_snapshot_retrieve_own_history(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(authorized);
  const snapshot =
    await api.functional.mallPlatform.customer.reviews.snapshots.at(
      customerConnection,
      {
        reviewId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
  TestValidator.predicate("snapshot has id", snapshot.id.length > 0);
  TestValidator.predicate(
    "snapshot references review",
    snapshot.review.id.length > 0,
  );
  TestValidator.predicate(
    "snapshot references customer",
    snapshot.customer.id.length > 0,
  );
  TestValidator.predicate(
    "snapshot has action",
    snapshot.snapshotAction.length > 0,
  );
  TestValidator.predicate(
    "snapshot rating is valid",
    snapshot.rating >= 1 && snapshot.rating <= 5,
  );
  TestValidator.predicate(
    "snapshot createdAt exists",
    snapshot.createdAt.length > 0,
  );
}
