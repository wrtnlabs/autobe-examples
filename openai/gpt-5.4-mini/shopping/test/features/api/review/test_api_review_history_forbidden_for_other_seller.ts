export async function test_api_review_history_forbidden_for_other_seller(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customerJoin = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(customerJoin);
  const review = await generate_random_mall_platform_customer_reviews_create(
    customerConnection,
    {
      body: {
        rating: 5,
        content: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(review);
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerJoin = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerJoin);
  await TestValidator.httpError(
    "non-owner seller cannot access review history",
    [401, 403],
    async () => {
      await api.functional.mallPlatform.seller.reviews.history.at(
        sellerConnection,
        {
          reviewId: review.reviewId,
        },
      );
    },
  );
}
