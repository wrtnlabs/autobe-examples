export async function test_api_review_browse_empty_result_set(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const request = {
    productId: typia.random<string & tags.Format<"uuid">>(),
    rating: 5,
    search: RandomGenerator.alphabets(32),
    page: 1,
    limit: 10,
  } satisfies IMallPlatformReview.IRequest;
  const output = await api.functional.mallPlatform.customer.reviews.index(
    customerConnection,
    {
      body: request,
    },
  );
  typia.assert(output);
  TestValidator.equals("empty review data", output.data, []);
  TestValidator.equals("empty review records", output.pagination.records, 0);
  TestValidator.equals("empty review pages", output.pagination.pages, 0);
  TestValidator.equals("review page current", output.pagination.current, 1);
  TestValidator.equals("review page limit", output.pagination.limit, 10);
}
