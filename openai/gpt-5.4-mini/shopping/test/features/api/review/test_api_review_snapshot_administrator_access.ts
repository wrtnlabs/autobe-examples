export async function test_api_review_snapshot_administrator_access(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_login(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.ILogin,
  });
  const reviewId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot = await api.functional.shoppingMall.reviews.snapshots.at(
    administratorConnection,
    {
      reviewId,
      snapshotId,
    },
  );
  typia.assert(snapshot);
  TestValidator.equals(
    "snapshot review reference exists",
    snapshot.review.id,
    reviewId,
  );
  TestValidator.predicate(
    "snapshot rating is within range",
    snapshot.rating >= 1 && snapshot.rating <= 5,
  );
  TestValidator.predicate(
    "snapshot content is preserved or empty",
    snapshot.content === null || typeof snapshot.content === "string",
  );
}
