export async function test_api_customer_profile_view_current_profile(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const joined = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(joined);
  const profile =
    await api.functional.mallPlatform.customer.profile.at(customerConnection);
  typia.assert(profile);
  TestValidator.equals(
    "profile owner id matches signed-in customer",
    profile.customer.id,
    joined.id,
  );
  TestValidator.equals(
    "profile owner email matches signed-in customer",
    profile.customer.email,
    joined.email,
  );
  TestValidator.equals(
    "profile deletedAt is null for active profile",
    profile.deletedAt,
    null,
  );
}
