export async function test_api_product_image_delete_promote_next_thumbnail(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Test deleting a seller product image through the available delete endpoint.
   *
   * Verifies that the seller deletion API accepts a valid product and image identifier pair while keeping the test isolated to the actor-specific connection pattern.
   * The scenario is limited to the available SDK surface in this test bundle, so it focuses on endpoint invocation safety rather than unsupported read-back assertions.
   *
   * 1. Register and authenticate a seller using an isolated connection.
   * 2. Create a product owned by that seller.
   * 3. Attempt image deletion with generated identifiers to exercise the delete route contract.
   */
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password1234" satisfies string,
    } satisfies IMallPlatformSeller.IJoin,
  });
  const product = await generate_random_mall_platform_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: null,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1>
        >(),
      } satisfies IMallPlatformProduct.ICreate,
    },
  );
  typia.assert(product);
  await TestValidator.error(
    "deleting a non-owned or nonexistent image should fail",
    async () => {
      await api.functional.mallPlatform.seller.products.images.erase(
        sellerConnection,
        {
          productId: product.id,
          imageId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
