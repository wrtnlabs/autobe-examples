export async function test_api_product_snapshot_access_after_product_deletion(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/seller/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerAuth);
  const administratorConnection: api.IConnection = { host: connection.host };
  const administratorAuth = await authorize_administrator_join(
    administratorConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
      } satisfies IMallPlatformAdministrator.IJoin,
    },
  );
  typia.assert(administratorAuth);
  const snapshot =
    await api.functional.mallPlatform.administrator.products.snapshots.at(
      administratorConnection,
      {
        productId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
  TestValidator.predicate(
    "snapshot has preserved product name",
    snapshot.productName.length > 0,
  );
  TestValidator.predicate(
    "snapshot has preserved product description",
    snapshot.productDescription.length > 0,
  );
  TestValidator.predicate(
    "snapshot has non-negative image count",
    snapshot.imageCount >= 0,
  );
  TestValidator.predicate(
    "snapshot has non-negative variant count",
    snapshot.variantCount >= 0,
  );
  TestValidator.predicate(
    "snapshot has createdAt timestamp",
    snapshot.createdAt.length > 0,
  );
}
