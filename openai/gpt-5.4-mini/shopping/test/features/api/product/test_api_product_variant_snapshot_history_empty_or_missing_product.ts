export async function test_api_product_variant_snapshot_history_empty_or_missing_product(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const missingProductId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "missing product should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.seller.products.variantSnapshots.index(
        sellerConnection,
        {
          productId: missingProductId,
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformProductVariantSnapshot.IRequest,
        },
      );
    },
  );
}
