export async function test_api_product_image_snapshot_retrieve_cross_seller_denied(
  connection: api.IConnection,
): Promise<void> {
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  await TestValidator.httpError(
    "cross-seller product image snapshot access should be denied",
    [403, 404],
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.images.getByProductidAndSnapshotidAndImagesnapshotid(
        sellerBConnection,
        {
          productId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
          imageSnapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
