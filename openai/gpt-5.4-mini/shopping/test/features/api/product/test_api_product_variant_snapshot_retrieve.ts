export async function test_api_product_variant_snapshot_retrieve(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const snapshot =
    await api.functional.mallPlatform.administrator.products.variantSnapshots.at(
      adminConnection,
      {
        productId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
  TestValidator.equals(
    "snapshot product id preserved",
    snapshot.product.id,
    snapshot.product.id,
  );
  TestValidator.equals(
    "snapshot variant product id preserved",
    snapshot.productVariant.product.id,
    snapshot.product.id,
  );
  TestValidator.predicate("snapshot id present", snapshot.id.length > 0);
  TestValidator.predicate(
    "snapshot sku preserved",
    snapshot.skuCode.length > 0,
  );
  TestValidator.predicate(
    "snapshot option summary preserved",
    snapshot.optionSummary.length > 0,
  );
  TestValidator.predicate(
    "snapshot createdAt present",
    snapshot.createdAt.length > 0,
  );
}
