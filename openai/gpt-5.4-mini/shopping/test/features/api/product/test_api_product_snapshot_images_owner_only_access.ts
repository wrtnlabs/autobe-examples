export async function test_api_product_snapshot_images_owner_only_access(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  const owner = await authorize_seller_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(owner);
  const otherConnection: api.IConnection = { host: connection.host };
  const other = await authorize_seller_join(otherConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(other);
  await TestValidator.httpError(
    "non-owner seller cannot inspect another seller's product snapshot images",
    [401, 403, 404],
    async () =>
      await api.functional.mallPlatform.seller.products.snapshots.images.index(
        otherConnection,
        {
          productId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
          body: {} satisfies IMallPlatformProductSnapshotImage.IRequest,
        },
      ),
  );
}
