export async function test_api_product_image_update_by_owner(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: `${RandomGenerator.alphaNumeric(10)}@test.com`,
      password: "password123!",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerAuthorized);
  const product = await generate_random_mall_platform_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: null,
        basePrice: typia.random<number>(),
      },
    },
  );
  typia.assert(product);
  TestValidator.equals(
    "created product should be owned by the seller",
    product.sellerAccount.id,
    sellerAuthorized.id,
  );
  const imageId = typia.random<string & tags.Format<"uuid">>();
  const updatedImage =
    await api.functional.mallPlatform.seller.products.images.update(
      sellerConnection,
      {
        productId: product.id,
        imageId,
        body: {
          imageUrl: `https://example.com/${RandomGenerator.alphaNumeric(12)}.png`,
        } satisfies IMallPlatformProductImage.IUpdate,
      },
    );
  typia.assert(updatedImage);
  TestValidator.equals(
    "updated image should use the requested product",
    updatedImage.product.id,
    product.id,
  );
}
