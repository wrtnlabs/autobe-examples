export async function test_api_seller_product_creation_requires_seller_auth(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallSeller.IJoin,
  });
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const body = {
    name: RandomGenerator.name(),
    description: RandomGenerator.paragraph({ sentences: 3 }),
    base_price: typia.random<number & tags.Type<"uint32"> & tags.Minimum<1>>(),
  } satisfies IShoppingMallProduct.ICreate;
  await TestValidator.error(
    "administrator must not be able to create seller products",
    async () => {
      await api.functional.shoppingMall.seller.products.create(
        administratorConnection,
        { body },
      );
    },
  );
  const product = await generate_random_shopping_mall_seller_products_create(
    sellerConnection,
    { body },
  );
  typia.assert(product);
  TestValidator.equals("product name", product.name, body.name);
  TestValidator.equals(
    "product description",
    product.description,
    body.description,
  );
  TestValidator.equals(
    "product base price",
    product.basePrice,
    body.base_price,
  );
}
