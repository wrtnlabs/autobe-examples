export async function test_api_product_reviews_product_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "ValidPass123!",
      href: "http://localhost/test",
      referrer: "http://localhost/",
      ip: undefined,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "product reviews should return not found for a missing product",
    404,
    async () => {
      await api.functional.mallPlatform.customer.products.reviews.index(
        customerConnection,
        {
          productId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformReview.IRequest,
        },
      );
    },
  );
}
