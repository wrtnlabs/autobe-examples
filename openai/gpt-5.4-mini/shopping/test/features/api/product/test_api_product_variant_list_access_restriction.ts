/**
 * Verifies seller-level access restriction for variant listing on product management.
 *
 * This test covers two security and routing scenarios for the seller variant list endpoint.
 *
 * 1. A seller attempts to access the variant list of a product owned by another seller and must receive a forbidden error.
 * 2. The same seller attempts to access a variant list for a nonexistent product identifier and must receive a not found error.
 * 3. The endpoint must not expose variant list data when ownership checks or product resolution fail.
 */
export async function test_api_product_variant_list_access_restriction(
  connection: api.IConnection,
): Promise<void> {
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password1234" satisfies string,
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerA);
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password5678" satisfies string,
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerB);
  const product = await api.functional.mallPlatform.seller.products.create(
    sellerBConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: null,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1>
        >(),
      } satisfies IMallPlatformProduct.ICreate,
    },
  );
  typia.assert(product);
  await TestValidator.httpError(
    "forbidden when listing variants of another seller's product",
    403,
    async () => {
      await api.functional.mallPlatform.seller.products.variants.index(
        sellerAConnection,
        {
          productId: product.id,
          body: {} satisfies IMallPlatformProductVariant.IRequest,
        },
      );
    },
  );
  await TestValidator.httpError(
    "not found when listing variants of a nonexistent product",
    404,
    async () => {
      await api.functional.mallPlatform.seller.products.variants.index(
        sellerAConnection,
        {
          productId: typia.random<string & tags.Format<"uuid">>(),
          body: {} satisfies IMallPlatformProductVariant.IRequest,
        },
      );
    },
  );
}
