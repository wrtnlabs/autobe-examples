export async function test_api_product_snapshot_require_matching_product_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234!@#$",
    } satisfies IMallPlatformSeller.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const otherProductId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "snapshot lookup must fail when the snapshot does not belong to the supplied product",
    [400, 403, 404],
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.at(
        sellerConnection,
        {
          productId: otherProductId,
          snapshotId,
        },
      );
    },
  );
  TestValidator.predicate(
    "scope mismatch should use different product identifiers",
    productId !== otherProductId,
  );
}
