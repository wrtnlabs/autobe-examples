export async function test_api_product_variant_admin_missing_product_not_found(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: `${RandomGenerator.alphabets(10)}@test.com` satisfies string &
        tags.Format<"email">,
      password: "Test1234!" satisfies string & tags.Format<"password">,
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const variantId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "administrator variant lookup should return not found for missing product",
    404,
    async () => {
      await api.functional.mallPlatform.administrator.products.variants.at(
        adminConnection,
        {
          productId,
          variantId,
        },
      );
    },
  );
}
