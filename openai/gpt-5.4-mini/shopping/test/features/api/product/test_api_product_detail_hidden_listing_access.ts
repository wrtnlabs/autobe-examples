export async function test_api_product_detail_hidden_listing_access(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password1234",
      href: "https://example.com",
      referrer: "https://example.com",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  await TestValidator.httpError(
    "hidden or unavailable product detail should not be exposed to customers",
    [401, 403, 404],
    async () => {
      await api.functional.shoppingMall.products.at(customerConnection, {
        productId: typia.random<string & tags.Format<"uuid">>(),
      });
    },
  );
}
