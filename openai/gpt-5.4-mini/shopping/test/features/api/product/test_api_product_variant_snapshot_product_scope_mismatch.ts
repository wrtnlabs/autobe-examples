/**
 * Verifies product-scoped isolation for administrator variant snapshot lookup.
 *
 * This test ensures the administrator variant snapshot endpoint does not leak
 * snapshot data from another product's history when the route contains a valid
 * product identifier but a snapshot identifier that belongs to a different
 * product context.
 *
 * 1. Registers and authenticates an administrator using the dedicated utility.
 * 2. Calls the product-scoped variant snapshot endpoint with a mismatched
 *    snapshot identifier.
 * 3. Confirms the API responds with not-found instead of exposing cross-product
 *    historical data.
 */
export async function test_api_product_variant_snapshot_product_scope_mismatch(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  typia.assert(authorized);
  const productId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "administrator variant snapshot lookup should reject snapshot ids outside the requested product scope",
    404,
    async () => {
      await api.functional.mallPlatform.administrator.products.variantSnapshots.at(
        adminConnection,
        {
          productId,
          snapshotId,
        },
      );
    },
  );
}
