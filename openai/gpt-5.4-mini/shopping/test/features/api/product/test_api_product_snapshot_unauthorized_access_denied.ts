export async function test_api_product_snapshot_unauthorized_access_denied(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: "https://example.com/register",
      referrer: "https://example.com",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const otherSellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(otherSellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const productId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  const snapshotId: string & tags.Format<"uuid"> = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.httpError(
    "customer access to seller product snapshot should be denied",
    [401, 403],
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.at(
        customerConnection,
        {
          productId,
          snapshotId,
        },
      );
    },
  );
  await TestValidator.httpError(
    "non-owning seller access to seller product snapshot should be denied",
    [401, 403],
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.at(
        otherSellerConnection,
        {
          productId,
          snapshotId,
        },
      );
    },
  );
}
