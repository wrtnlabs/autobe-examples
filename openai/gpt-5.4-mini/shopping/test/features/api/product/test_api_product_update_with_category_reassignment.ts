export async function test_api_product_update_with_category_reassignment(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    categoryId: typia.random<string & tags.Format<"uuid">>(),
    basePrice: typia.random<number & tags.Type<"uint32"> & tags.Minimum<1>>(),
  } satisfies IMallPlatformProduct.IUpdate;
  await TestValidator.error(
    "unavailable product update should fail",
    async () => {
      await api.functional.mallPlatform.administrator.products.update(
        administratorConnection,
        {
          productId,
          body,
        },
      );
    },
  );
}
