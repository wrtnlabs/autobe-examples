export async function test_api_product_snapshot_history_after_deletion(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const product = await generate_random_mall_platform_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        basePrice: 1000,
      } satisfies IMallPlatformProduct.ICreate,
    },
  );
  typia.assert(product);
  const administratorConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_administrator_join(
    administratorConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
      } satisfies IMallPlatformAdministrator.IJoin,
    },
  );
  typia.assert(adminAuth);
  const snapshots =
    await api.functional.mallPlatform.administrator.products.snapshots.index(
      administratorConnection,
      {
        productId: product.id,
        body: {
          page: 1,
          limit: 20,
        } satisfies IMallPlatformProductSnapshot.IRequest,
      },
    );
  typia.assert(snapshots);
  TestValidator.equals(
    "snapshot history should belong to the created product",
    snapshots.data[0]?.product.id,
    product.id,
  );
  TestValidator.predicate(
    "snapshot history should be paginated",
    snapshots.pagination.current === 1 && snapshots.pagination.limit === 20,
  );
}
