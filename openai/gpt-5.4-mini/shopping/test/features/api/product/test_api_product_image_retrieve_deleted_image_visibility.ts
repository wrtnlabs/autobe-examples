export async function test_api_product_image_retrieve_deleted_image_visibility(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const imageId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "deleted or inactive product image should not be visible through scoped retrieval",
    [404],
    async () => {
      await api.functional.shoppingMall.products.images.at(adminConnection, {
        productId,
        imageId,
      });
    },
  );
}
