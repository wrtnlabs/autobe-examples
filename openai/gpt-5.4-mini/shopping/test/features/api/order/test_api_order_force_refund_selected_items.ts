export async function test_api_order_force_refund_selected_items(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const response =
    await api.functional.mallPlatform.administrator.orders.force_refund.forceRefund(
      adminConnection,
      {
        orderId: typia.random<string & tags.Format<"uuid">>(),
        body: {
          orderItemIds: ArrayUtil.repeat(2, () =>
            typia.random<string & tags.Format<"uuid">>(),
          ),
        } satisfies IMallPlatformOrder.IForceRefund,
      },
    );
  typia.assert(response);
}
