export async function test_api_order_item_history_mixed_status_visibility(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16) as string &
        tags.Format<"password">,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const item =
    await api.functional.mallPlatform.customer.orders.history.items.at(
      customerConnection,
      {
        orderId,
      },
    );
  typia.assert(item);
  TestValidator.predicate("quantity is positive", item.quantity > 0);
  TestValidator.predicate("status is present", item.status.length > 0);
  TestValidator.predicate("order id is valid", item.order.id.length > 0);
  TestValidator.predicate(
    "variant sku is present",
    item.productVariant.skuCode.length > 0,
  );
  TestValidator.predicate(
    "seller email is present",
    item.seller.email.length > 0,
  );
}
