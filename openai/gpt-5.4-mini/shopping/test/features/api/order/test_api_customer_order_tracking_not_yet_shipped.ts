export async function test_api_customer_order_tracking_not_yet_shipped(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com",
      referrer: "https://example.com",
    } satisfies IShoppingMallCustomer.IJoin,
  });
  typia.assert(authorized);
  const order = await api.functional.shoppingMall.customer.orders.at(
    customerConnection,
    {
      orderId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  typia.assert(order);
  const tracking =
    await api.functional.shoppingMall.customer.orders.tracking.at(
      customerConnection,
      {
        orderId: order.id,
      },
    );
  typia.assert(tracking);
  TestValidator.predicate(
    "tracking payload should be empty when no shipments exist yet",
    tracking.shipments.length === 0,
  );
}
