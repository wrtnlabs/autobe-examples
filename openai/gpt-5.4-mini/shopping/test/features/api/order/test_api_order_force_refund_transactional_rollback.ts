export async function test_api_order_force_refund_transactional_rollback(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "password123!" satisfies string & tags.Format<"password">,
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    orderItemIds: [typia.random<string & tags.Format<"uuid">>()],
  } satisfies IMallPlatformOrder.IForceRefund;
  await TestValidator.error(
    "force-refund should fail when the targeted order or item scope is invalid",
    async () => {
      await api.functional.mallPlatform.administrator.orders.force_refund.forceRefund(
        adminConnection,
        {
          orderId,
          body,
        },
      );
    },
  );
}
