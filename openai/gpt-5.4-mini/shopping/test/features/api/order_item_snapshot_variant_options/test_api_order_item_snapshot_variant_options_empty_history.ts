export async function test_api_order_item_snapshot_variant_options_empty_history(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const response =
    await api.functional.mallPlatform.seller.orderItems.snapshots.variantOptions.index(
      sellerConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
        orderItemSnapshotId: typia.random<string & tags.Format<"uuid">>(),
        body: {
          page: 1,
          limit: 10,
        } satisfies IMallPlatformOrderItemSnapshotVariantOption.IRequest,
      },
    );
  typia.assert(response);
  TestValidator.equals(
    "variant option history should be empty",
    response.data.length,
    0,
  );
  TestValidator.equals(
    "empty snapshot page should report zero records",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "empty snapshot page should report zero pages",
    response.pagination.pages,
    0,
  );
  TestValidator.equals(
    "empty snapshot page should start at the first page",
    response.pagination.current,
    1,
  );
  TestValidator.equals(
    "empty snapshot page should preserve requested limit",
    response.pagination.limit,
    10,
  );
}
