export async function test_api_product_snapshot_images_after_product_deletion(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const productId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const image =
    await api.functional.mallPlatform.seller.products.snapshots.images.getByProductidAndSnapshotid(
      sellerConnection,
      {
        productId,
        snapshotId,
      },
    );
  typia.assert(image);
  TestValidator.predicate(
    "snapshot image uri is preserved",
    image.imageUri.length > 0,
  );
  TestValidator.predicate(
    "snapshot image sort order is non-negative",
    image.sortOrder >= 0,
  );
  TestValidator.predicate(
    "snapshot image belongs to a snapshot",
    image.productSnapshot.id.length > 0,
  );
}
