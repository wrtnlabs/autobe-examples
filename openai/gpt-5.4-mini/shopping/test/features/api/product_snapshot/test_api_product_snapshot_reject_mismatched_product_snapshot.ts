export async function test_api_product_snapshot_reject_mismatched_product_snapshot(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(authorized);
  const productId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "mismatched product snapshot pair should be not found",
    [404],
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.at(
        sellerConnection,
        {
          productId,
          snapshotId,
        },
      );
    },
  );
  const anotherProductId = typia.random<string & tags.Format<"uuid">>();
  const anotherSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "cross-product snapshot access should be not found",
    [404],
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.at(
        sellerConnection,
        {
          productId: anotherProductId,
          snapshotId: anotherSnapshotId,
        },
      );
    },
  );
}
