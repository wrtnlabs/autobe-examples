export async function test_api_product_snapshot_retrieve_own_product(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!" as string & tags.Format<"password">,
      href: "https://example.com/seller/register" as string &
        tags.Format<"uri">,
      referrer: "https://example.com/" as string & tags.Format<"uri">,
      ip: "127.0.0.1" as string & tags.Format<"ipv4">,
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerAuth);
  TestValidator.predicate(
    "seller account is created",
    sellerAuth.id.length > 0,
  );
  TestValidator.predicate(
    "seller email is preserved",
    sellerAuth.email.includes("@"),
  );
  TestValidator.predicate(
    "authorization token is issued",
    sellerAuth.token.access.length > 0,
  );
}
