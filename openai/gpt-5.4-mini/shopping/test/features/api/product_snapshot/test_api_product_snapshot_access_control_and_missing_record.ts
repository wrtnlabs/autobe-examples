export async function test_api_product_snapshot_access_control_and_missing_record(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Test access control and missing-record handling for product snapshot retrieval.
   *
   * Validates the platform's historical-record protections for product snapshots by checking both forbidden
   * access for a non-administrator caller and not-found behavior for a snapshot identifier that does not exist.
   * The test uses isolated actor connections so authentication state remains separated across customer, seller,
   * and administrator sessions.
   *
   * 1. Create isolated administrator, seller, and customer connections.
   * 2. Authenticate each actor independently.
   * 3. Verify that a missing snapshot id returns not found.
   * 4. Verify that a non-privileged actor cannot access the administrator snapshot endpoint.
   */
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: null,
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const missingSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "missing product snapshot should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.administrator.productSnapshots.at(
        administratorConnection,
        {
          productSnapshotId: missingSnapshotId,
        },
      );
    },
  );
  await TestValidator.httpError(
    "customer should be forbidden from reading product snapshots",
    403,
    async () => {
      await api.functional.mallPlatform.administrator.productSnapshots.at(
        customerConnection,
        {
          productSnapshotId: missingSnapshotId,
        },
      );
    },
  );
  await TestValidator.httpError(
    "seller should be forbidden from reading administrator product snapshots",
    403,
    async () => {
      await api.functional.mallPlatform.administrator.productSnapshots.at(
        sellerConnection,
        {
          productSnapshotId: missingSnapshotId,
        },
      );
    },
  );
}
