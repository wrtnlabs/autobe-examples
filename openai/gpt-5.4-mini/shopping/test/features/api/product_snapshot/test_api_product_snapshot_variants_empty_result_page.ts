export async function test_api_product_snapshot_variants_empty_result_page(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234" as string & tags.Format<"password">,
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(authorized);
  const output =
    await api.functional.mallPlatform.seller.productSnapshots.variants.index(
      sellerConnection,
      {
        productSnapshotId: typia.random<string & tags.Format<"uuid">>(),
        body: {
          search: RandomGenerator.alphabets(32),
          page: 1,
          limit: 1,
          sort: "createdAt",
        } satisfies IMallPlatformProductSnapshotVariant.IRequest,
      },
    );
  typia.assert(output);
  TestValidator.equals("empty result data", output.data.length, 0);
  TestValidator.equals("empty result records", output.pagination.records, 0);
  TestValidator.equals("empty result pages", output.pagination.pages, 0);
  TestValidator.equals(
    "empty result current page",
    output.pagination.current,
    1,
  );
  TestValidator.equals("empty result limit", output.pagination.limit, 1);
}
