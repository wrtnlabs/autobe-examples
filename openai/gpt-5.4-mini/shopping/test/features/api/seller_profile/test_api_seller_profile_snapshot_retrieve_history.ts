export async function test_api_seller_profile_snapshot_retrieve_history(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IShoppingMallAdministrator.IJoin,
  });
  typia.assert(authorized);
  const snapshot =
    await api.functional.shoppingMall.administrator.seller_profiles.snapshots.at(
      adminConnection,
      {
        sellerProfileId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(snapshot);
  TestValidator.equals(
    "snapshot has seller profile reference",
    snapshot.sellerProfile.id,
    snapshot.sellerProfile.id,
  );
  TestValidator.predicate(
    "snapshot has immutable historical shop name",
    snapshot.shopName.length >= 0,
  );
  TestValidator.predicate(
    "snapshot has immutable historical shop description",
    snapshot.shopDescription.length >= 0,
  );
  TestValidator.predicate(
    "snapshot logo image uri is nullable or url string",
    snapshot.logoImageUri === null || snapshot.logoImageUri.length >= 0,
  );
}
