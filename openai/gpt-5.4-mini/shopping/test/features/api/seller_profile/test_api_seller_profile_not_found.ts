export async function test_api_seller_profile_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const sellerProfileId = "00000000-0000-4000-8000-000000000000" as string &
    tags.Format<"uuid">;
  await TestValidator.httpError("seller profile not found", 404, async () => {
    await api.functional.mallPlatform.customer.sellerProfiles.at(
      customerConnection,
      {
        sellerProfileId,
      },
    );
  });
}
