export async function test_api_product_variant_snapshot_option_retrieve(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/",
      ip: "127.0.0.1",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(authorized);
  const output =
    await api.functional.mallPlatform.seller.products.variantSnapshots.options.at(
      sellerConnection,
      {
        productId: typia.random<string & tags.Format<"uuid">>(),
        snapshotId: typia.random<string & tags.Format<"uuid">>(),
        optionId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(output);
  TestValidator.equals(
    "product variant snapshot option should preserve the normalized snapshot row",
    output,
    {
      id: output.id,
      mallPlatformProductVariantSnapshotId:
        output.mallPlatformProductVariantSnapshotId,
      optionKey: output.optionKey,
      optionValue: output.optionValue,
    } satisfies IMallPlatformProductVariantSnapshotOption,
  );
}
