export async function test_api_cancellation_request_final_state_preserved(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const cancellationRequestId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "cancellation request lookup for nonexistent identifiers should fail in an empty fixture environment",
    async () => {
      await api.functional.mallPlatform.administrator.orderItems.cancellationRequests.at(
        adminConnection,
        {
          orderItemId,
          cancellationRequestId,
        },
      );
    },
  );
}
