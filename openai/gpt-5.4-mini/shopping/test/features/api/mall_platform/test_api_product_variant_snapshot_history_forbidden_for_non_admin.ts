export async function test_api_product_variant_snapshot_history_forbidden_for_non_admin(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "non-administrator cannot access product variant snapshot history",
    403,
    async () => {
      await api.functional.mallPlatform.administrator.productVariants.snapshots.at(
        customerConnection,
        {
          productVariantId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
