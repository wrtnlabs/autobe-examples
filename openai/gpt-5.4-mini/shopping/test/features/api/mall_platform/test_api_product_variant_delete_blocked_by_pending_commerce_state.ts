export async function test_api_product_variant_delete_blocked_by_pending_commerce_state(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformSeller.IJoin,
  });
  await TestValidator.httpError(
    "variant deletion should be blocked for protected commerce state",
    [400, 401, 403, 404, 409],
    async () => {
      await api.functional.mallPlatform.seller.products.variants.erase(
        sellerConnection,
        {
          productId: typia.random<string & tags.Format<"uuid">>(),
          variantId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
