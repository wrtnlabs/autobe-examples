export async function test_api_product_snapshot_retrieve_forbidden_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  const nonOwnerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(nonOwnerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  await TestValidator.httpError(
    "non-owner seller cannot retrieve a product snapshot",
    [403, 404],
    async () => {
      await api.functional.mallPlatform.seller.productSnapshots.at(
        nonOwnerConnection,
        {
          productSnapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
