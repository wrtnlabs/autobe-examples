export async function test_api_product_snapshot_images_forbidden_for_unauthorized_seller(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com",
      ip: "127.0.0.1",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const productId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "unauthorized seller cannot access product snapshot images",
    403,
    async () => {
      await api.functional.mallPlatform.seller.products.snapshots.images.index(
        sellerConnection,
        {
          productId,
          snapshotId,
          body: {
            page: 1,
            limit: 10,
            sort: "desc",
          } satisfies IMallPlatformProductSnapshotImage.IRequest,
        },
      );
    },
  );
}
