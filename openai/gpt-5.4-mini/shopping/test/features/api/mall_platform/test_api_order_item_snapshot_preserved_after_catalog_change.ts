export async function test_api_order_item_snapshot_preserved_after_catalog_change(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(customer);
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.mallPlatform.customer.order_items.snapshots.at(
      customerConnection,
      {
        orderItemId,
        snapshotId,
      },
    );
  typia.assert(snapshot);
  TestValidator.equals("snapshot id preserved", snapshot.id, snapshotId);
  TestValidator.equals(
    "snapshot order item id preserved",
    snapshot.orderItem.id,
    orderItemId,
  );
  TestValidator.predicate(
    "snapshot captured at exists",
    snapshot.snapshotAt.length > 0,
  );
  TestValidator.predicate(
    "snapshot reason exists",
    snapshot.snapshotReason.length > 0,
  );
  TestValidator.predicate(
    "snapshot product name exists",
    snapshot.productName.length > 0,
  );
  TestValidator.predicate(
    "snapshot seller shop name exists",
    snapshot.sellerShopName.length > 0,
  );
  TestValidator.predicate(
    "snapshot seller logo url exists",
    snapshot.sellerLogoImageUrl.length > 0,
  );
}
