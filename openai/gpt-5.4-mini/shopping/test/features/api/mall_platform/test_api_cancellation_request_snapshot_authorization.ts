export async function test_api_cancellation_request_snapshot_authorization(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "customer cannot access cancellation request snapshots without a valid owned order item and cancellation request pair",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.customer.orderItems.cancellationRequests.snapshots.index(
        customerConnection,
        {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          cancellationRequestId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformCancellationRequestSnapshot.IRequest,
        },
      );
    },
  );
}
