/**
 * Verifies that sellers cannot read protected order item snapshot variant options.
 *
 * This test authenticates a seller account and then attempts to access preserved variant option data for a historical order item snapshot that the caller is not permitted to view. It validates that the endpoint enforces purchase-history authorization and blocks disclosure of immutable snapshot content.
 *
 * 1. Register and authenticate a seller account using a dedicated seller connection.
 * 2. Request variant options for a random historical order item snapshot identifier.
 * 3. Assert the endpoint rejects the unauthorized access attempt.
 */
export async function test_api_order_item_snapshot_variant_options_access_control(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const orderItemSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "seller should not access historical order item snapshot variant options",
    [401, 403],
    async () => {
      await api.functional.mallPlatform.seller.orderItemSnapshots.variantOptions.getByOrderitemsnapshotid(
        sellerConnection,
        {
          orderItemSnapshotId,
        },
      );
    },
  );
}
