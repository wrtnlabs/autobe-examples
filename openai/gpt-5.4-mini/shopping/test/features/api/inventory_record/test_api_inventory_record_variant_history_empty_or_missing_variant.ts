export async function test_api_inventory_record_variant_history_empty_or_missing_variant(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  typia.assert(admin);
  await TestValidator.httpError(
    "missing inventory variant should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.administrator.productVariants.inventoryRecords.index(
        adminConnection,
        {
          productVariantId: typia.random<string & tags.Format<"uuid">>(),
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformInventoryRecord.IRequest,
        },
      );
    },
  );
}
