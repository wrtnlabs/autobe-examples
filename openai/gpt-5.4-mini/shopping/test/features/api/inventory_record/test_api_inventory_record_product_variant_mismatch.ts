export async function test_api_inventory_record_product_variant_mismatch(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const variantId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "inventory record creation rejects mismatched product and variant",
    [400, 404, 409, 422],
    async () => {
      await generate_random_mall_platform_seller_products_variants_inventory_records_create(
        sellerConnection,
        {
          params: {
            productId,
            variantId,
          },
          body: {
            quantityChange: 1,
            reason: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IMallPlatformInventoryRecord.ICreate,
        },
      );
    },
  );
}
