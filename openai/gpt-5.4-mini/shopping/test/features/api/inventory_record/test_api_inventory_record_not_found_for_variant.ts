export async function test_api_inventory_record_not_found_for_variant(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  typia.assert(authorized);
  const productVariantId = typia.random<string & tags.Format<"uuid">>();
  const inventoryRecordId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "inventory record should not be found for the specified variant",
    [404],
    async () => {
      await api.functional.mallPlatform.administrator.productVariants.inventoryRecords.at(
        adminConnection,
        {
          productVariantId,
          inventoryRecordId,
        },
      );
    },
  );
}
