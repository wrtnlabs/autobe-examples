export async function test_api_inventory_records_product_variant_scope_mismatch(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const variantId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "variant scoped under mismatched product should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.seller.products.variants.inventoryRecords.index(
        sellerConnection,
        {
          productId,
          variantId,
          body: {
            page: 1,
            limit: 10,
          } satisfies IMallPlatformInventoryRecord.IRequest,
        },
      );
    },
  );
}
