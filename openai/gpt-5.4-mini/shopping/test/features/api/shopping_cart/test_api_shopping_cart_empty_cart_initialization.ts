export async function test_api_shopping_cart_empty_cart_initialization(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(authorized);
  const cart =
    await api.functional.mallPlatform.customer.shopping_carts.at(
      customerConnection,
    );
  typia.assert(cart);
  TestValidator.equals("cart owner id", cart.customer.id, authorized.id);
  TestValidator.equals(
    "cart owner email",
    cart.customer.email,
    authorized.email,
  );
  TestValidator.equals(
    "new customer cart item count",
    cart.cartItems.length,
    0,
  );
}
