/**
 * Verifies administrator-only access to preserved order item snapshot variant options.
 *
 * This test prepares an authenticated administrator session for contrast and then
 * confirms that the historical snapshot variant-option endpoint rejects requests
 * made without valid administrator authorization. The scenario focuses on access
 * control for immutable purchase-history data used in dispute review.
 *
 * 1. Register an administrator and establish an authenticated administrator connection.
 * 2. Attempt to access order item snapshot variant options without valid administrator authorization.
 * 3. Confirm the endpoint returns an authorization error for the unauthorized request.
 */
export async function test_api_order_item_snapshot_variant_options_authorization_required(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(administratorConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const unauthorizedConnection: api.IConnection = { host: connection.host };
  const orderItemSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "unauthorized access to order item snapshot variant options should be rejected",
    async () => {
      await api.functional.mallPlatform.administrator.orderItemSnapshots.variantOptions.getByOrderitemsnapshotid(
        unauthorizedConnection,
        {
          orderItemSnapshotId,
        },
      );
    },
  );
}
