/**
 * Test that a missing order item snapshot lookup returns not found.
 *
 * Validates the authenticated customer failure path for reading a preserved
 * order item snapshot by identifier when the snapshot does not exist.
 *
 * The test ensures the endpoint safely fails without mutating data, without
 * returning unrelated purchase-history information, and without requiring any
 * pre-existing order item snapshot fixtures.
 *
 * 1. Authenticate a customer in an isolated connection.
 * 2. Request a random, non-existent order item snapshot identifier.
 * 3. Assert the endpoint responds with a not-found HTTP error.
 */
export async function test_api_order_item_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password1234!",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const orderItemSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "missing order item snapshot should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.customer.orderItemSnapshots.at(
        customerConnection,
        {
          orderItemSnapshotId,
        },
      );
    },
  );
}
