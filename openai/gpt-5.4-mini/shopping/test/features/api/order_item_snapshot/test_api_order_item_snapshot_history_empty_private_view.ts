export async function test_api_order_item_snapshot_history_empty_private_view(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/signup",
      referrer: "https://example.com/",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const output =
    await api.functional.mallPlatform.customer.orderItemSnapshots.history(
      customerConnection,
    );
  typia.assert(output);
  TestValidator.equals(
    "empty order item snapshot history",
    output.data.length,
    0,
  );
  TestValidator.equals("no snapshot records", output.pagination.records, 0);
  TestValidator.equals("no snapshot pages", output.pagination.pages, 0);
  TestValidator.predicate(
    "non-negative page current",
    output.pagination.current >= 0,
  );
  TestValidator.predicate(
    "non-negative page limit",
    output.pagination.limit >= 0,
  );
}
