/**
 * Rejects mismatched order item snapshot lookups for administrators.
 *
 * Verifies that the preserved order-item snapshot endpoint does not expose
 * immutable purchase history when the order, order item, and snapshot identifiers
 * do not form a valid hierarchy. The test authenticates a dedicated
 * administrator session, then requests the snapshot endpoint with deliberately
 * unrelated UUIDs and expects a not-found style HTTP error.
 *
 * This covers the full order → order item → snapshot chain enforcement and
 * ensures unrelated historical purchase details are not leaked through path
 * manipulation.
 *
 * 1. Authenticate as an administrator using a dedicated connection.
 * 2. Call the preserved snapshot endpoint with mismatched UUIDs.
 * 3. Assert the request fails with a not-found style HTTP error.
 */
export async function test_api_order_item_snapshot_mismatched_snapshot_not_found(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  await TestValidator.httpError(
    "mismatched order item snapshot should not be found",
    [404],
    async () => {
      await api.functional.mallPlatform.administrator.orders.orderItems.snapshots.at(
        adminConnection,
        {
          orderId: typia.random<string & tags.Format<"uuid">>(),
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
