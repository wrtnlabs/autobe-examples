export async function test_api_order_item_snapshot_history_empty_page(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Verify administrator order item snapshot history returns an empty page.
   *
   * Validates that a newly authenticated administrator can read the order item snapshot history endpoint and receive a well-formed empty paginated response when no preserved history records exist.
   *
   * 1. Authenticate an administrator on an isolated connection.
   * 2. Call the order item snapshot history endpoint.
   * 3. Assert the response contains no data and zero pagination counts.
   */
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const output =
    await api.functional.mallPlatform.administrator.orderItemSnapshots.history(
      adminConnection,
    );
  typia.assert(output);
  TestValidator.equals("empty history data", output.data, []);
  TestValidator.equals("pagination records", output.pagination.records, 0);
  TestValidator.equals("pagination pages", output.pagination.pages, 0);
  TestValidator.equals("pagination data size", output.data.length, 0);
}
