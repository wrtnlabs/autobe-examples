/**
 * Verifies that order item snapshots remain private across customer accounts.
 *
 * This test checks the protected snapshot lookup path for cross-customer access control.
 * It validates that a customer cannot read another customer's preserved purchase-history
 * snapshot and that the endpoint responds with a denial-style failure without exposing
 * preserved product, variant, seller, or pricing details.
 *
 * 1. Create two isolated customer sessions using separate connection objects.
 * 2. Attempt to access a protected order item snapshot from the non-owner session.
 * 3. Assert that the request is rejected with authorization-style or not-found behavior.
 */
export async function test_api_order_item_snapshot_cross_customer_private_access(
  connection: api.IConnection,
): Promise<void> {
  const ownerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(ownerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const intruderConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(intruderConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "cross-customer access to order item snapshot should be denied",
    [401, 403, 404],
    async () => {
      await api.functional.mallPlatform.customer.orderItemSnapshots.at(
        intruderConnection,
        {
          orderItemSnapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
