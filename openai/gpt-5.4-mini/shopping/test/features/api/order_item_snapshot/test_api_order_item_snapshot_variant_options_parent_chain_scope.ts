export async function test_api_order_item_snapshot_variant_options_parent_chain_scope(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Verifies that preserved variant option data cannot be read unless the
   * order, order item, and snapshot identifiers belong to the same historical
   * lineage.
   *
   * This negative-path test authenticates a customer and then calls the
   * order-item snapshot variant-options endpoint with unrelated UUIDs so the
   * server must refuse to resolve mismatched parent relationships instead of
   * leaking preserved snapshot rows from another purchase.
   *
   * 1. Register and authenticate a customer session.
   * 2. Call the snapshot variant-options endpoint with unrelated identifiers.
   * 3. Assert that the request fails with a not-found style HTTP error.
   */
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "http://localhost",
      referrer: "http://localhost",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "not found for mismatched order item snapshot parent chain",
    [404],
    async () => {
      await api.functional.mallPlatform.customer.orders.orderItems.snapshots.variantOptions.index(
        customerConnection,
        {
          orderId,
          orderItemId,
          snapshotId,
        },
      );
    },
  );
}
