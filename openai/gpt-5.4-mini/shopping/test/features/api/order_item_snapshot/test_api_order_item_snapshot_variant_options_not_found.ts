export async function test_api_order_item_snapshot_variant_options_not_found(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  await TestValidator.httpError(
    "missing order item snapshot should return not found",
    404,
    async () => {
      await api.functional.mallPlatform.customer.orderItemSnapshots.variantOptions.index(
        customerConnection,
        {
          orderItemSnapshotId: typia.random<string & tags.Format<"uuid">>(),
          body: {} satisfies IMallPlatformOrderItemSnapshotVariantOption.IRequest,
        },
      );
    },
  );
}
