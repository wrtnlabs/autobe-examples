export async function test_api_order_item_snapshots_filter_by_reason_and_time(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
      ip: "127.0.0.1",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const snapshotAtTo = new Date().toISOString();
  const snapshotAtFrom = new Date(Date.now() - 60 * 60 * 1000).toISOString();
  const request = {
    snapshotReason: "purchase completion",
    snapshotAtFrom,
    snapshotAtTo,
    page: 1,
    limit: 10,
    sort: "-snapshotAt",
  } satisfies IMallPlatformOrderItemSnapshot.IRequest;
  const output =
    await api.functional.mallPlatform.customer.orderItemSnapshots.index(
      customerConnection,
      {
        body: request,
      },
    );
  typia.assert(output);
  TestValidator.equals(
    "pagination current reflects request",
    output.pagination.current,
    request.page,
  );
  TestValidator.equals(
    "pagination limit reflects request",
    output.pagination.limit,
    request.limit,
  );
  TestValidator.predicate(
    "pagination records is non-negative",
    output.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages is non-negative",
    output.pagination.pages >= 0,
  );
  TestValidator.predicate(
    "response is paginated within requested limit",
    output.data.length <= request.limit,
  );
}
