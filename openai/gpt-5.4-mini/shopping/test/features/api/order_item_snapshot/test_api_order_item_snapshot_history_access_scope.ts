export async function test_api_order_item_snapshot_history_access_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const output =
    await api.functional.mallPlatform.seller.orderItemSnapshots.index(
      sellerConnection,
      {
        body: {
          page: 1,
          limit: 10,
          sort: "-snapshotAt",
        } satisfies IMallPlatformOrderItemSnapshot.IRequest,
      },
    );
  typia.assert(output);
  TestValidator.equals(
    "snapshot page limit is preserved",
    output.pagination.limit,
    10,
  );
  TestValidator.equals(
    "snapshot page current is preserved",
    output.pagination.current,
    1,
  );
  for (const snapshot of output.data) {
    typia.assert(snapshot);
    TestValidator.predicate(
      "snapshot has immutable order item context",
      snapshot.orderItem.id.length > 0 && snapshot.orderItem.quantity > 0,
    );
  }
}
