/**
 * Verifies access control for order item snapshot hierarchy lookup.
 *
 * This test authenticates a seller, then requests an order item snapshot using
 * unrelated order, order item, and snapshot identifiers to ensure the endpoint
 * does not leak historical purchase data outside the valid ownership chain.
 *
 * The expected behavior is a not-found or forbidden-style denial when the
 * requested orderId, orderItemId, and snapshotId do not belong to the same
 * hierarchy or fall outside the authenticated seller's scope.
 *
 * 1. Authenticate a seller using the registration endpoint.
 * 2. Call the snapshot endpoint with mismatched random UUID identifiers.
 * 3. Validate the request is denied with an access-control HTTP error.
 */
export async function test_api_order_item_snapshot_hierarchy_access_control(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "seller order item snapshot access should be denied for mismatched hierarchy",
    [403, 404],
    async () => {
      await api.functional.mallPlatform.seller.orders.orderItems.snapshots.at(
        sellerConnection,
        {
          orderId,
          orderItemId,
          snapshotId,
        },
      );
    },
  );
}
