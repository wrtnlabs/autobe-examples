export async function test_api_product_variant_delete_wrong_product_scope(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const productId = typia.random<string & tags.Format<"uuid">>();
  const variantId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "variant deletion should be rejected for mismatched product scope",
    [400, 403, 404],
    async () => {
      await api.functional.mallPlatform.seller.products.variants.erase(
        sellerConnection,
        {
          productId,
          variantId,
        },
      );
    },
  );
}
