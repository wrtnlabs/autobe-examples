export async function test_api_seller_approval_request_rejection_reason_visibility(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const approvalRequestId = typia.random<string & tags.Format<"uuid">>();
  const request = await api.functional.mallPlatform.seller.approvalRequests.at(
    sellerConnection,
    {
      approvalRequestId,
    },
  );
  typia.assert(request);
  TestValidator.equals("approval request id", request.id, approvalRequestId);
}
