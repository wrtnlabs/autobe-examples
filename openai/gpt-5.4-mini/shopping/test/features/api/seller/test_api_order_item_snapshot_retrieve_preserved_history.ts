export async function test_api_order_item_snapshot_retrieve_preserved_history(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const orderItemSnapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.mallPlatform.seller.orderItemSnapshots.at(
      sellerConnection,
      {
        orderItemSnapshotId,
      },
    );
  typia.assert(snapshot);
  TestValidator.equals(
    "snapshot id matches request id",
    snapshot.id,
    orderItemSnapshotId,
  );
  TestValidator.predicate(
    "snapshot retains preserved historical data",
    snapshot.snapshotReason.length > 0 && snapshot.productName.length > 0,
  );
  TestValidator.predicate(
    "snapshot includes related order item summary",
    snapshot.orderItem.id.length > 0,
  );
}
