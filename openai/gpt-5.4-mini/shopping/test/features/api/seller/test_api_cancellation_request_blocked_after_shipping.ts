export async function test_api_cancellation_request_blocked_after_shipping(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerJoin = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(sellerJoin);
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const body = {
    reason: RandomGenerator.paragraph({ sentences: 2 }),
  } satisfies IMallPlatformCancellationRequest.ICreate;
  await TestValidator.error(
    "cancellation request should be blocked after shipping",
    async () => {
      await generate_random_mall_platform_seller_order_items_cancellation_requests_create(
        sellerConnection,
        {
          params: { orderItemId },
          body,
        },
      );
    },
  );
}
