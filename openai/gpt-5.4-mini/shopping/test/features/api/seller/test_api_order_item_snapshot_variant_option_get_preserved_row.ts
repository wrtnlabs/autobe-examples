export async function test_api_order_item_snapshot_variant_option_get_preserved_row(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: `${RandomGenerator.alphaNumeric(10)}@test.com` satisfies string &
        tags.Format<"email">,
      password: `P@ssw0rd${RandomGenerator.alphaNumeric(8)}` satisfies string &
        tags.Format<"password">,
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const output =
    await api.functional.mallPlatform.seller.orderItemSnapshots.variantOptions.getByOrderitemsnapshotidAndVariantoptionid(
      sellerConnection,
      {
        orderItemSnapshotId: typia.random<string & tags.Format<"uuid">>(),
        variantOptionId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  typia.assert(output);
}
