export async function test_api_order_item_snapshots_history_empty_page(
  connection: api.IConnection,
): Promise<void> {
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234!",
    } satisfies IMallPlatformSeller.IJoin,
  });
  const output: IPageIMallPlatformOrderItemSnapshot.ISummary =
    await api.functional.mallPlatform.seller.orderItemSnapshots.history(
      sellerConnection,
    );
  typia.assert(output);
  TestValidator.equals("empty page record count", output.pagination.records, 0);
  TestValidator.equals("empty page total pages", output.pagination.pages, 0);
  TestValidator.equals("empty page data length", output.data.length, 0);
  TestValidator.equals("empty page current page", output.pagination.current, 1);
}
