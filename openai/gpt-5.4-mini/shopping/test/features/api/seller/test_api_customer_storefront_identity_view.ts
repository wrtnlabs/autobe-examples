export async function test_api_customer_storefront_identity_view(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "1234",
      href: "https://example.com/signup",
      referrer: "https://example.com/landing",
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IMallPlatformCustomer.IJoin,
  });
  typia.assert(authorized);
  await TestValidator.httpError(
    "nonexistent seller storefront identity should be rejected",
    [404],
    async () => {
      await api.functional.mallPlatform.customer.sellers.storefront_identity.at(
        customerConnection,
        {
          sellerId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
