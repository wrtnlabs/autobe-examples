export async function test_api_seller_account_retrieve_without_shop_profile(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_administrator_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IMallPlatformAdministrator.IJoin,
  });
  const seller = await api.functional.mallPlatform.administrator.sellers.at(
    adminConnection,
    {
      sellerId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  typia.assert(seller);
  TestValidator.predicate("seller id exists", seller.id.length > 0);
  TestValidator.predicate("seller email exists", seller.email.length > 0);
  TestValidator.predicate("seller status exists", seller.status.length > 0);
  TestValidator.predicate(
    "seller profile is absent or undefined when no shop profile exists",
    seller.sellerProfile === undefined || seller.sellerProfile === null,
  );
}
