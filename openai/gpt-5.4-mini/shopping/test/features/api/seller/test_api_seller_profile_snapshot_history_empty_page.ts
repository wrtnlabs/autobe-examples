export async function test_api_seller_profile_snapshot_history_empty_page(
  connection: api.IConnection,
): Promise<void> {
  const administratorConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  const administrator = await authorize_administrator_join(
    administratorConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
      } satisfies IMallPlatformAdministrator.IJoin,
    },
  );
  typia.assert(administrator);
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IMallPlatformSeller.IJoin,
  });
  typia.assert(seller);
  const response =
    await api.functional.mallPlatform.administrator.sellers.profile.snapshots.index(
      administratorConnection,
      {
        sellerId: seller.id,
        body: {} satisfies IMallPlatformSellerProfileSnapshot.IRequest,
      },
    );
  typia.assert(response);
  TestValidator.equals(
    "empty snapshot history records",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "empty snapshot history pages",
    response.pagination.pages,
    0,
  );
  TestValidator.equals("empty snapshot history data", response.data, []);
  TestValidator.equals(
    "empty snapshot history current page",
    response.pagination.current,
    1,
  );
}
