export async function test_api_product_image_retrieve_success(
  connection: api.IConnection,
): Promise<void> {
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://example.com/register",
      referrer: "https://example.com/landing",
    } satisfies IMallPlatformCustomer.IJoin,
  });
  const productId = typia.random<string & tags.Format<"uuid">>();
  const imageId = typia.random<string & tags.Format<"uuid">>();
  const image = await api.functional.mallPlatform.customer.products.images.at(
    customerConnection,
    {
      productId,
      imageId,
    },
  );
  typia.assert(image);
  TestValidator.equals("response id", image.id, imageId);
  TestValidator.predicate("has image url", image.imageUrl.length > 0);
  TestValidator.predicate("has non-negative sort order", image.sortOrder >= 0);
  TestValidator.predicate("has product summary", image.product.id.length > 0);
}
