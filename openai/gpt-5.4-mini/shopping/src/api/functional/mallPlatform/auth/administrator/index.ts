/**
 * Register a new administrator account and return authentication tokens.
 *
 * This endpoint creates a new administrator identity for the mall platform and returns the authorized token payload on success. It is the registration entry point for administrator accounts when the system allows creating them.
 *
 * If the request fails validation or conflicts with an existing administrator account, the endpoint must return an appropriate client error. On success, the response contains the administrator's authorization payload for subsequent authenticated requests.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Validate administrator registration input, create the administrator account record, and issue authorized tokens when registration succeeds. Enforce uniqueness and password validation, and return a client error for invalid or conflicting credentials.
 * @path /mallPlatform/auth/administrator/join
 * @accessor api.functional.mallPlatform.auth.administrator.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
