/**
 * Register a new seller account with email and password.
 *
 * This operation creates the seller's authentication identity for the marketplace and starts the merchant onboarding flow. It returns the standard authorized token response immediately after a successful registration so the seller can continue into seller-specific features.
 *
 * The server must validate credential format and uniqueness before creating the account. If the email is already in use or the payload is invalid, the operation fails with a client error.
 *
 * The response uses the platform's standard authorized format for authenticated seller access.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Seller registration payload containing the credentials required to create a new seller account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Validate seller registration credentials, create the seller account record, and return a newly issued authenticated token set. The service must reject duplicate emails, malformed passwords, and any account state that makes registration invalid. Registration should not depend on approval workflow state beyond creating the seller identity; seller approval is handled by separate business processes.
 * @path /mallPlatform/auth/seller/join
 * @accessor api.functional.mallPlatform.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
