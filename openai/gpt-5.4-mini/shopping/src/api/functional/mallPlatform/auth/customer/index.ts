/**
 * Register a new customer account using email and password credentials. This operation creates the authenticated shopper identity that is required before any marketplace features can be used.
 *
 * The customer actor is the member-level shopper account in the platform, so this endpoint starts the lifecycle for an account that will later own shopping carts, shipping addresses, orders, wishlists, and reviews. The response returns the authorized token payload after successful registration.
 *
 * If the email is already registered or the input fails validation, the request must be rejected with a clear client error. The endpoint should remain limited to authentication setup and should not expose any profile, order, or browsing data.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration request containing email and password credentials.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Validate the customer's registration payload, ensure the email is unique, create the customer account, initialize any required linked customer profile/session state, and issue JWT tokens on success. Reject duplicate email addresses and invalid credentials with appropriate 4xx responses. The operation must not create any public profile or domain records beyond what account registration requires.
 * @path /mallPlatform/auth/customer/join
 * @accessor api.functional.mallPlatform.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
