/**
 * Register a new customer account and issue authentication tokens.
 *
 * This operation creates a new customer identity in the marketplace so the user can access customer features that require authentication. The submitted email and password are used to create the account, and the system returns token credentials for immediate sign-in.
 *
 * The account is stored in the customer actor table, and the resulting authentication state is returned as an authorized payload. Duplicate email addresses and invalid credential values are rejected to preserve account uniqueness and security.
 *
 * Use this endpoint as the first step in the customer authentication workflow before accessing shopping, order, wishlist, cart, or profile features.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration credentials used to create a new account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Create a customer account by validating the submitted
 *   email and password against the customer registration rules, ensuring the
 *   email is unique in mall_platform_customers and that the password meets the
 *   platform's credential policy. On success, create the customer record and
 *   any required session/auth state in a single transactional flow, then return
 *   freshly issued access and refresh tokens in the authorized response. Reject
 *   duplicate emails, invalid credential formats, and any persistence failures
 *   with appropriate 4xx or 5xx errors.
 * @path /mallPlatform/auth/customer/join
 * @accessor api.functional.mallPlatform.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
