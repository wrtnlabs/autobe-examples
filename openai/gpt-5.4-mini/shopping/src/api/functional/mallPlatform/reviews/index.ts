import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../structures/IMallPlatformReview";

/**
 * Return a single review with its linked purchase and product context.
 *
 * This endpoint retrieves one review by identifier so clients can display the review detail, including the star rating and optional written content. The review is tied to a specific customer, order item, and product, which supports product detail pages, ownership validation, and dispute review.
 *
 * Only the review owner and administrators should be able to access this resource when privacy rules apply. If the review has been deleted, the historical record may still exist in storage, but clients must respect its active state and display rules. A missing identifier should produce a not-found response.
 *
 * @param props.connection
 * @param props.reviewId Unique identifier of the review in global scope.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query mall_platform_reviews by primary key and load
 *   the related customer, order item, and product references required for the
 *   detail response. Enforce access control so the owning customer can read
 *   their own review and administrators can read any review. Preserve deleted
 *   review records as historical data, but do not expose snapshot history here;
 *   snapshots are handled by the review snapshot subsystem. Return not found
 *   when the review id does not exist or is not accessible.
 * @path /mallPlatform/reviews/:reviewId
 * @accessor api.functional.mallPlatform.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the review in global scope.
     */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IMallPlatformReview;

  export const METADATA = {
    method: "GET",
    path: "/mallPlatform/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/mallPlatform/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): IMallPlatformReview =>
    typia.random<IMallPlatformReview>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
