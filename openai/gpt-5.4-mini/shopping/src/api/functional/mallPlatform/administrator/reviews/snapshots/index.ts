/**
 * List the immutable snapshot history for a specific review.
 *
 * This endpoint returns preserved review snapshots so the review owner and administrators can inspect how the rating, content, and deletion state changed over time. It is intended for dispute resolution and historical review, and every snapshot returned is read-only.
 *
 * Results are scoped to the review identified by `reviewId` and should be ordered by `created_at` descending so the newest change appears first. Because a review may accumulate multiple snapshots, the response is paginated and may be filtered by snapshot action, content, or time range.
 *
 * @param props.connection
 * @param props.reviewId Identifier of the review whose snapshot history is being listed.
 * @param props.body Pagination, search, and sorting criteria for review snapshot history.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Query mall_platform_review_snapshots for rows where mall_platform_review_id equals the provided reviewId. Enforce authorization so only the customer who owns the source review and administrators can read the history.
 *
 * Support pagination, search, and sorting in the request body. Allow filters for snapshot_action, content text, is_deleted, and created_at range, with default ordering by created_at descending. Return summary rows only. If the review does not exist, return not found. If the caller lacks permission, return forbidden. If no snapshots exist, return an empty page.
 * @path /mallPlatform/administrator/reviews/:reviewId/snapshots
 * @accessor api.functional.mallPlatform.administrator.reviews.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
