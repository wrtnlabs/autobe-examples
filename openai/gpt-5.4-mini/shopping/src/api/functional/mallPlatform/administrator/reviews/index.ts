/**
 * Retrieve a single review by its identifier.
 *
 * This endpoint returns the current active review record used on product detail pages and in review-management screens. The review includes the customer’s rating and optional written text, and it remains visible even if the original customer account has later been deleted, in which case consumers should render the author as a deleted user.
 *
 * The response reflects the active review state only and does not include snapshot history. If the review cannot be found, the service should return a not-found response. Authorization should follow the platform’s review visibility rules for authenticated users and administrators.
 *
 * @param props.connection
 * @param props.reviewId The review identifier in UUID format.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor administrator
 * @x-autobe-specification Fetch the review from mall_platform_reviews by its primary identifier. Return the current review row only; do not hydrate snapshot history from this endpoint.
 *
 * If the review does not exist, return a not-found error. If the linked customer account has been deleted, still return the review record and let the presentation layer label the author as deleted user.
 *
 * No mutation is allowed. Keep access control aligned with the platform’s review visibility policy, and ensure the response supports product detail pages that display rating, text, and review ownership context.
 * @path /mallPlatform/administrator/reviews/:reviewId
 * @accessor api.functional.mallPlatform.administrator.reviews.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * The review identifier in UUID format.
     */
    reviewId: string & tags.Format<"uuid">;
  };
  export type Response = IMallPlatformReview;

  export const METADATA = {
    method: "GET",
    path: "/mallPlatform/administrator/reviews/:reviewId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/mallPlatform/administrator/reviews/${encodeURIComponent(props.reviewId ?? "null")}`;
  export const random = (): IMallPlatformReview =>
    typia.random<IMallPlatformReview>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
