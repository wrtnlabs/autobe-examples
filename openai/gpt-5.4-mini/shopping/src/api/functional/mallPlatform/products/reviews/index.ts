import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../../structures/IMallPlatformReview";
import { IPageIMallPlatformReview } from "../../../../structures/IPageIMallPlatformReview";

/**
 * Lists the active public reviews for a product, ordered by newest first.
 *
 * This endpoint scopes review browsing to a single product and returns the review feed that appears on the product detail page. Reviews are purchase-based feedback from customers, so the data is intended for public reputation display rather than private account management.
 *
 * The response is paginated because a product may accumulate many reviews. Deleted reviews must be excluded from the active listing and from any visible count used by the product detail page. The service should preserve the newest-first browsing rule so the latest feedback appears first.
 *
 * @param props.connection
 * @param props.productId The UUID of the product whose public reviews should be listed.
 * @param props.body Review list criteria including pagination and any supported sort or filter options for the requested product.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Validate that the product exists, then query
 *   mall_platform_reviews for rows matching the product id. Exclude rows with a
 *   deleted_at value so only active reviews are returned. Sort by created_at
 *   descending to satisfy the newest-first display requirement. Apply
 *   pagination and any supported list filters from the request body according
 *   to the platform browsing rules. If customer display data is needed for the
 *   summary DTO, join the owning customer only for public-safe fields. Return a
 *   paginated summary response suitable for the product detail page. If the
 *   product does not exist, return the standard not-found error. Do not expose
 *   deleted review rows in this endpoint.
 * @path /mallPlatform/products/:productId/reviews
 * @accessor api.functional.mallPlatform.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * The UUID of the product whose public reviews should be listed.
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Review list criteria including pagination and any supported sort or filter options for the requested product.
     */
    body: IMallPlatformReview.IRequest;
  };
  export type Body = IMallPlatformReview.IRequest;
  export type Response = IPageIMallPlatformReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/mallPlatform/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/mallPlatform/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IPageIMallPlatformReview.ISummary =>
    typia.random<IPageIMallPlatformReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
