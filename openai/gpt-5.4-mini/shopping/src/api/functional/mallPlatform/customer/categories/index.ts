/**
 * Returns the browseable category collection for customers.
 *
 * This endpoint exposes the active marketplace taxonomy so customers can discover categories and their direct subcategories. Each result should include the category name and description maintained by administrators, reflecting the one-level hierarchy used by the platform.
 *
 * Deleted categories must be excluded from browsing results. The endpoint does not return products directly; it is intended for category navigation and for driving storefront pages that later resolve products by category.
 *
 * @param props.connection
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query mall_platform_categories for records where
 *   deleted_at is null so deleted categories are not shown to customers. Load
 *   direct subcategories through the self-referential parent_category_id
 *   relation, but do not recurse beyond one level because the taxonomy only
 *   allows direct child categories. Return the taxonomy in a stable browse
 *   order suitable for customer navigation, and omit any category whose parent
 *   is missing or deleted to avoid exposing broken hierarchy. This endpoint is
 *   read-only and must not mutate category records.
 * @path /mallPlatform/customer/categories
 * @accessor api.functional.mallPlatform.customer.categories.get
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function get(connection: IConnection): Promise<get.Response> {
  return true === connection.simulate
    ? get.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...get.METADATA,
          path: get.path(),
          status: null,
        },
      );
}
