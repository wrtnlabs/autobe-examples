/**
 * Retrieve the historical snapshot timeline for a single customer review.
 *
 * This operation returns the immutable change history stored in `shopping_mall_review_snapshots` for the review identified by `reviewId`. Each snapshot preserves the review rating, optional text content, deletion state, and creation timestamp at the moment the historical version was recorded, allowing the caller to inspect how the review changed over time.
 *
 * The live review record remains in `shopping_mall_reviews`, while this endpoint exposes the append-only history used for dispute resolution and moderation. Review snapshots remain available even after the active review has been edited or deleted, so the caller can still inspect prior versions of the review state. The response should present the snapshots in chronological order, typically newest first for UI review timelines, while preserving the underlying creation order for comparison purposes.
 *
 * Access is intended for the review owner and administrators who are within the review scope. The owner can inspect the history of their own review, and administrators can inspect review histories when handling disputes or platform moderation. Callers must provide the target review identifier in the path; no additional lookup of the live review is required beyond verifying that the review exists and that the caller is authorized to view its snapshot trail.
 *
 * This endpoint is read-only from the business perspective, but it is modeled as a PATCH query because it supports list retrieval with paging and sorting controls. Use it together with the review detail endpoint when the client needs both the current review state and the review's historical state changes.
 *
 * @param props.connection
 * @param props.reviewId Target review identifier.
 * @param props.body Paging and sorting options for review snapshot history.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Load the target review by reviewId, then query shopping_mall_review_snapshots filtered by review_id.
 *
 * Validate that the review exists and that the caller is either the review owner or an administrator with permission to inspect review history. If the review does not exist, return not found. If the caller lacks scope, return forbidden.
 *
 * Support pagination in the request body because snapshot histories can grow over time. Order results by created_at descending for UI display, and preserve a stable secondary ordering by id if needed. The query should only target the snapshot table; do not reconstruct history from the live review table except for authorization checks.
 *
 * Return snapshot records with id, review_id, rating, content, is_deleted, created_at, and deleted_at. The response should be a paginated collection DTO. No mutation should occur. If the live review has been deleted, history should still be queryable because snapshots are immutable and independent of the review's active visibility state.
 * @path /shoppingMall/reviews/:reviewId/snapshots
 * @accessor api.functional.shoppingMall.reviews.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
