import { tags } from "typia";

import { IMallPlatformCustomer } from "./IMallPlatformCustomer";

/**
 * An immutable snapshot of a customer profile.
 *
 * This type represents one historical version of a customer’s profile preserved for auditability and dispute review. It exposes the snapshot identity, the owning customer account, the preserved profile values, and the timestamps that show when the change was captured and when the snapshot record was created.
 *
 * Consumers should treat this as read-only history rather than the customer’s current live profile. The snapshot exists to support traceability, inspection of past values, and dispute resolution.
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IMallPlatformCustomerProfileSnapshot = {
  /**
   * The unique identifier of this customer profile snapshot.
   *
   * Use this value to reference a specific preserved historical profile record.
   *
   * @x-autobe-specification Map directly from the immutable customer profile snapshot identifier stored with the snapshot record. This value uniquely identifies one historical snapshot and is read-only.
   */
  id: string & tags.Format<"uuid">;

  /**
   * The customer account that owns this profile snapshot.
   *
   * This is a summary reference to the customer associated with the preserved profile state.
   *
   * @x-autobe-specification Resolve the owning customer summary from the stored snapshot relation. Return the linked customer summary, not the live profile state, and keep the relation read-only.
   */
  customer: IMallPlatformCustomer.ISummary;

  /**
   * The preserved display name for the profile at the time this snapshot was recorded.
   *
   * This reflects the historical value captured when the profile changed.
   *
   * @x-autobe-specification Map directly from the display name value stored in the snapshot history row. This is the historical value captured at the time of the profile change.
   */
  displayName: string;

  /**
   * The preserved phone number for the profile at the time this snapshot was recorded.
   *
   * This value may be null when no phone number was stored in the preserved profile state.
   *
   * @x-autobe-specification Map directly from the phone value stored in the snapshot history row. Preserve null exactly when the historical value is absent.
   */
  phone: string | null;

  /**
   * The time when the profile change captured by this snapshot occurred.
   *
   * This timestamp indicates when the preserved state was taken for history and audit purposes.
   *
   * @x-autobe-specification Map directly from the timestamp recorded for the underlying profile change event that created this snapshot. Do not recalculate it from the current profile state.
   */
  changedAt: string & tags.Format<"date-time">;

  /**
   * The time when this snapshot record was created.
   *
   * This timestamp marks when the immutable history row was stored in the system.
   *
   * @x-autobe-specification Map directly from the timestamp recorded when the immutable snapshot row was persisted. This is distinct from the underlying profile-change time.
   */
  createdAt: string & tags.Format<"date-time">;
};
