/**
 * Ownership and display-state information for a review.
 *
 * This DTO identifies the review, the customer who owns it, and how the review should be presented based on whether the owning customer account is still active.
 *
 * The ownership relationship is preserved even when the customer account has been deleted so the platform can continue to support dispute resolution and historical viewing. This type does not include review text, rating details, order context, or snapshot history.
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IMallPlatformReview = {
  /**
   * The unique identifier of the review.
   *
   * Use this value to reference the review in ownership and history-related responses.
   *
   * @x-autobe-specification Use the review's UUID identifier from mall_platform_reviews.id as the source for this read-only field. It identifies the review record whose ownership and display state are being resolved.
   */
  reviewId: string & tags.Format<"uuid">;

  /**
   * The customer who owns the review.
   *
   * This is the review author's customer summary, preserved for historical viewing and dispute resolution even when the account is no longer active.
   *
   * @x-autobe-specification Join mall_platform_reviews.customer_id to mall_platform_customers.id and return the owning customer as IMallPlatformCustomer.ISummary. Preserve the relationship even when the customer account has been deleted so the ownership context remains available for dispute resolution and history viewing.
   */
  customer: IMallPlatformCustomer.ISummary;

  /**
   * The display state for the review owner.
   *
   * This tells consumers whether the review should be shown under an active customer account or as content from a deleted user.
   *
   * @x-autobe-specification Compute the display state from the owning customer account's existence and active status. Return activeCustomer when the linked customer exists and is active; return deletedUser when the customer account is missing or deleted. This value is read-only and never persisted.
   */
  displayState: "activeCustomer" | "deletedUser";
};
