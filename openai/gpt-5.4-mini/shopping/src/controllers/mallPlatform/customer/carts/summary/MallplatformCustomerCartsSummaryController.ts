import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformShoppingCart } from "../../../../../api/structures/IMallPlatformShoppingCart";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerCartsSummary } from "../../../../../providers/getMallPlatformCustomerCartsSummary";

@Controller("/mallPlatform/customer/carts/summary")
export class MallplatformCustomerCartsSummaryController {
  /**
   * Return the current shopping cart summary for the authenticated customer.
   *
   * This endpoint provides the pre-checkout view of the customer’s cart, including each selected product variant, its quantity, its subtotal, and the cart-wide total price. It is intended for purchase review before checkout and keeps unavailable items visible so the customer can resolve them before placing an order.
   *
   * The response reflects the cart pricing rules used across the platform: each line subtotal is derived from the item quantity and current cart price, and the total price is the sum of all visible cart item subtotals. If any item is unavailable or has insufficient stock, that state must be represented in the summary so the customer can make an informed purchase decision.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch the authenticated customer’s current shopping cart summary in a single read query.
   *
   * Load the customer-owned shopping cart and its cart items, then join the referenced product variant, product, and seller data required to render the summary view. Compute each cart item subtotal from the item quantity and displayed unit price, and compute the cart total as the sum of all item subtotals, including items that remain visible but are unavailable.
   *
   * Include availability indicators for deleted or out-of-stock variants, and include stock warning state when the variant stock is lower than the selected quantity. Do not allow cross-account access: the result must be scoped strictly to the current authenticated customer. If the customer has no cart, return the empty cart summary shape expected by the UI rather than an error, unless the platform’s auth layer rejects unauthenticated access before this service is reached.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IMallPlatformShoppingCart.ISummary> {
    try {
      return await getMallPlatformCustomerCartsSummary({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
