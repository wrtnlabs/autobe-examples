import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrderItemSnapshot } from "../../../../../api/structures/IMallPlatformOrderItemSnapshot";
import { IPageIMallPlatformOrderItemSnapshot } from "../../../../../api/structures/IPageIMallPlatformOrderItemSnapshot";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerOrderItemsOrderItemIdSnapshots } from "../../../../../providers/getMallPlatformCustomerOrderItemsOrderItemIdSnapshots";
import { getMallPlatformCustomerOrderItemsOrderItemIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformCustomerOrderItemsOrderItemIdSnapshotsSnapshotId";
import { patchMallPlatformCustomerOrderItemsOrderItemIdSnapshots } from "../../../../../providers/patchMallPlatformCustomerOrderItemsOrderItemIdSnapshots";

@Controller("/mallPlatform/customer/orderItems/:orderItemId/snapshots")
export class MallplatformCustomerOrderitemsSnapshotsController {
  /**
   * Returns the immutable snapshot history for a specific order item.
   *
   * This endpoint exposes preserved historical records for the order item so customers, sellers, and administrators can review the purchase context as it existed at each recorded change. Order item snapshots are retained for dispute resolution, auditability, and historical reconstruction, and they remain available even if the source order item or related source records have since changed or been removed.
   *
   * The response is scoped to the specified order item and contains only snapshots that belong to that parent. Because snapshot history can grow over time, the result is paginated. If the parent order item does not exist, the service should return not found. If the caller is not allowed to view the preserved history, the service should return forbidden.
   *
   * @param connection
   * @param orderItemId The identifier of the order item whose snapshot history should be returned.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Resolve the parent order item by orderItemId and verify access according to the caller's role and ownership rules. Query mall_platform_order_item_snapshots for rows linked to that order item, ordering newest first by the snapshot timestamp or creation timestamp defined by the schema. Return a paginated summary list and do not allow mutation because snapshots are immutable by business rule.
   *
   * If the parent order item does not exist, return not found. If the caller lacks permission to view the history, return forbidden. Do not reconstruct, update, or delete snapshot rows. If the schema contains related preserved fields for product or seller context, expose them only through the snapshot summary type, not through any write behavior. Follow standard pagination and sorting behavior for list-style retrieval of historical data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByOrderitemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
    try {
      return await getMallPlatformCustomerOrderItemsOrderItemIdSnapshots({
        customer,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Returns the preserved snapshot history for a specific order item.
   *
   * This operation exposes immutable historical records for the selected order item so callers can inspect how the purchased item, its product context, and related preserved purchase data changed over time. The records remain available for dispute resolution and historical reconstruction even if the live order item or related entities have been removed.
   *
   * Access is limited to the customer who owns the order, the seller who owns the item, and administrators with oversight privileges. Results are paginated and can be filtered and sorted according to the platform's browsing rules. If the order item is missing or the caller is not authorized to view it, the service must return the appropriate not-found or forbidden response.
   *
   * Snapshots are read-only and immutable. This endpoint must never create, update, or delete snapshot records.
   *
   * @param connection
   * @param orderItemId The order item identifier whose snapshot history is being requested (UUID).
   * @param body Pagination, sorting, and filter criteria for browsing snapshots belonging to a single order item.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Verify that the caller can access the target order item through ownership or administrative privilege before querying snapshot rows. Load only snapshots that belong to the supplied orderItemId, and return them in descending creation order unless the request specifies another allowed sort.
   *
   * Apply pagination and any supported snapshot filters from the request body. If the stored snapshot structure includes preserved child rows or normalized history details, include them only as required by the summary response contract. Do not mutate snapshot data; snapshot records are immutable by business rule.
   *
   * If the order item has been deleted, still return its preserved snapshots when retention rules require them to remain available. If the order item does not exist or is not accessible to the caller, return the correct 404 or 403 style error as appropriate.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformOrderItemSnapshot.IRequest,
  ): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
    try {
      return await patchMallPlatformCustomerOrderItemsOrderItemIdSnapshots({
        customer,
        orderItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves one preserved order item snapshot for a specific order item.
   *
   * This endpoint returns the immutable historical record captured for the order item, including the preserved product name, description, SKU, variant SKU code, seller shop identity, unit price, quantity, line total, item status, and snapshot reason. It is intended for dispute resolution, purchase history review, and administrative inspection rather than for editing live order data.
   *
   * The snapshot remains available even if the related order item or source catalog data changes later. If the order item or snapshot cannot be found under the provided identifiers, the request must fail with a not-found error.
   *
   * @param connection
   * @param orderItemId The identifier of the order item that owns the snapshot (UUID scope).
   * @param snapshotId The identifier of the preserved snapshot record (UUID scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the order item snapshot by matching the parent order item id and snapshot id.
   * Verify that the snapshot row belongs to the requested order item before returning it; do not allow cross-order-item access by snapshot id alone.
   * Use a single indexed lookup on order_item_id and id, and return 404 when no matching preserved snapshot exists.
   * Return the full immutable snapshot record including all preserved purchase-state fields.
   * Do not mutate any data. Do not exclude deleted historical records if they are still retained for business history.
   * This endpoint is read-only and must not expose any editing or deletion behavior.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async getByOrderitemidAndSnapshotid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrderItemSnapshot> {
    try {
      return await getMallPlatformCustomerOrderItemsOrderItemIdSnapshotsSnapshotId(
        {
          customer,
          orderItemId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
