import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../../api/structures/IMallPlatformReview";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteMallPlatformCustomerReviewsReviewId } from "../../../../providers/deleteMallPlatformCustomerReviewsReviewId";
import { postMallPlatformCustomerReviews } from "../../../../providers/postMallPlatformCustomerReviews";
import { putMallPlatformCustomerReviewsReviewId } from "../../../../providers/putMallPlatformCustomerReviewsReviewId";

@Controller("/mallPlatform/customer/reviews")
export class MallplatformCustomerReviewsController {
  /**
   * Create a new review for a delivered purchase item.
   *
   * A customer may submit a review only after the related order item has been delivered, and only once per product within the same order. The review becomes visible on the product detail page and contributes to the product’s review count and average rating while it remains active.
   *
   * The service must verify that the authenticated customer owns the purchase context, that the referenced order item is eligible for review, and that no other review already exists for the same product within the same order. If any eligibility check fails, the request must be rejected without creating a review.
   *
   * @param connection
   * @param body Review content and purchase context for a delivered order item, including the rating, optional text, and references needed to verify that the caller is allowed to review the product.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Use the authenticated customer session to resolve
     *   ownership and enforce review eligibility. Validate that the request
     *   references a delivered order item belonging to the current customer,
     *   and confirm that no active review already exists for the same product
     *   within the same order.
   *
   * Create the review in mall_platform_reviews and, if the implementation persists historical state at creation time, also create the corresponding snapshot record in mall_platform_review_snapshots in the same transaction. Do not accept system-managed fields from the client; derive identity, ownership, and timestamps server-side.
   *
   * Return a conflict error for duplicate reviews, a forbidden or validation error for unauthorized or ineligible purchases, and a not-found error when the purchase context cannot be resolved. Preserve deleted-user review visibility by keeping review identity separate from customer account deletion behavior.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformReview.ICreate,
  ): Promise<IMallPlatformReview> {
    try {
      return await postMallPlatformCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing customer review.
   *
   * This endpoint lets the original author change the star rating and optional written comment for a previously submitted review. The review remains linked to the purchase context, and the prior state must be preserved in a snapshot before the active record is updated.
   *
   * Only the customer who created the review may update it. If the review does not exist, belongs to another customer, or fails validation, the request must be rejected with the appropriate error response. Because reviews appear on product detail pages and contribute to rating summaries, the updated review should be returned so clients can refresh the displayed content immediately.
   *
   * @param connection
   * @param reviewId Unique identifier of the review to update.
   * @param body Editable fields for an existing customer review. Immutable identifiers such as the customer, product, and order context are derived from the stored review and are not included here.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Look up the active review by reviewId and ensure
     *   it exists. Verify the authenticated customer is the review owner before
     *   allowing the edit; unauthorized attempts must be rejected without
     *   exposing another user's review data.
   *
   * Validate the request body fields. The rating must satisfy the review rating constraints, and the text content, if present, should be persisted as the review body. Do not allow changes to immutable context fields such as the customer, product, or order-item linkage.
   *
   * Before saving the new values, create an immutable review snapshot containing the previous state so edit history is preserved. Then update the active review record and return the updated entity. Return not found when the review does not exist and validation errors when the payload is invalid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":reviewId")
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformReview.IUpdate,
  ): Promise<IMallPlatformReview> {
    try {
      return await putMallPlatformCustomerReviewsReviewId({
        customer,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a review while preserving its historical snapshot trail.
   *
   * This endpoint removes the active review record for a single review identified by reviewId. The system must verify that the current customer owns the review before allowing deletion. If the review has already been deleted or the caller is not allowed to delete it, the request must fail with the appropriate authorization or not-found error.
   *
   * Review deletion must preserve historical data. The previous review state remains available through snapshot records, and deleted reviews must no longer contribute to active review listings or product average rating calculations. Preserved review history must continue to display as written by a deleted user when the original customer account no longer exists.
   *
   * @param connection
   * @param reviewId The review identifier (global scope).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Load the review by reviewId and verify it exists.
     *   Check the authenticated actor against the review owner; reject the
     *   operation if the caller does not own the review unless the platform's
     *   authorization layer explicitly grants moderation rights for this route.
     *   Before removing the active review, create a review snapshot that
     *   preserves the current review state for history and dispute review. Keep
     *   the snapshot immutable. Delete or deactivate the active review row so
     *   it no longer appears in normal product detail review listings and no
     *   longer affects average rating calculations. If the review is already
     *   removed or inaccessible, return a not-found style error. If ownership
     *   validation fails, return a forbidden-style error. Do not alter the
     *   preserved snapshot history on failure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":reviewId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMallPlatformCustomerReviewsReviewId({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
