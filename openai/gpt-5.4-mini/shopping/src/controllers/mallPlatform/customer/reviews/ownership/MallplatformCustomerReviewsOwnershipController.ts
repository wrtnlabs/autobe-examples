import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../../../api/structures/IMallPlatformReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerReviewsReviewIdOwnership } from "../../../../../providers/getMallPlatformCustomerReviewsReviewIdOwnership";

@Controller("/mallPlatform/customer/reviews/:reviewId/ownership")
export class MallplatformCustomerReviewsOwnershipController {
  /**
   * Resolve the ownership identity and display status for a single review.
   *
   * This endpoint is used when the platform needs to determine how a review should be presented to customers, sellers, or administrators. A review always remains owned by the customer who wrote it, and if that customer account has been deleted, the review must continue to be shown as written by a deleted user while preserving the ownership relationship for dispute resolution and history viewing.
   *
   * The operation does not modify review data or create snapshots. If the review does not exist, the server must return not found. If the caller is not allowed to inspect review ownership information, the request must be rejected according to the platform’s access rules.
   *
   * @param connection
   * @param reviewId The review identifier whose ownership and display state should be resolved.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch the review row by reviewId and derive ownership presentation from the stored customer ownership reference plus the current existence of the customer account. If the customer account is missing or deleted, return a deleted-user presentation state while preserving the ownership relationship in the response.
   *
   * This endpoint is read-only and must not update review records, customer records, or snapshots. Return 404 when the review cannot be found. Enforce authorization before returning the result so only permitted parties can view ownership details, consistent with review visibility, owner access, and administrative oversight rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformReview> {
    try {
      return await getMallPlatformCustomerReviewsReviewIdOwnership({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
