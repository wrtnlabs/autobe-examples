import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../../../api/structures/IMallPlatformReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerReviewsReviewIdHistory } from "../../../../../providers/getMallPlatformCustomerReviewsReviewIdHistory";

@Controller("/mallPlatform/customer/reviews/:reviewId/history")
export class MallplatformCustomerReviewsHistoryController {
  /**
   * Returns the immutable history for a single review.
   *
   * This endpoint exposes the preserved snapshot timeline for a review so the caller can inspect prior ratings, text content, and deletion-preservation state. It is intended for dispute resolution, owner self-service, and administrative review, while keeping the active review entity separate from its historical versions.
   *
   * The service must return the full set of snapshots associated with the review in chronological order, including the values captured before and after each edit or deletion event when available. If the review does not exist, return not found. If the caller is neither the review owner nor an administrator, return forbidden. If the review exists but no snapshots have been created yet, return an empty history collection.
   *
   * @param connection
   * @param reviewId The review identifier whose preserved history is being requested.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch the target review by review_id and verify the caller is authorized to view its history. Authorization should allow the original review owner and administrators; other callers must be rejected.
   *
   * Query mall_platform_review_snapshots for all rows linked to the review, ordered by snapshot timestamp or snapshot identifier ascending so the response reconstructs the full change timeline. Do not attempt to synthesize live review state; return only immutable history records. If the review is missing, return not found. If there are no snapshots, return an empty collection with a successful response.
   *
   * Keep the response read-only and do not expose any write paths here. The endpoint must not alter review status, ownership, or deletion flags.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformReview> {
    try {
      return await getMallPlatformCustomerReviewsReviewIdHistory({
        customer,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
