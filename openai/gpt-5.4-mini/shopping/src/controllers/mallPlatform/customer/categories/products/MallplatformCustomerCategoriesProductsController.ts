import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIMallPlatformProduct } from "../../../../../api/structures/IPageIMallPlatformProduct";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerCategoriesCategoryIdProducts } from "../../../../../providers/getMallPlatformCustomerCategoriesCategoryIdProducts";

@Controller("/mallPlatform/customer/categories/:categoryId/products")
export class MallplatformCustomerCategoriesProductsController {
  /**
   * Retrieve the products assigned to a specific category.
   *
   * This operation is used by customers when browsing the marketplace taxonomy. It returns the products that belong to the requested category, allowing the category page to show the catalog items organized by the administrator-managed category structure.
   *
   * The result should respect platform visibility rules: deleted categories must not be exposed through browsing, deleted products must not appear in category listings, and products from suspended sellers must be hidden from customer-facing results. The returned product summaries should be suitable for category browsing views, including the product’s main image, name, pricing information, seller shop name, and average rating when reviews exist.
   *
   * If the category does not exist, is not browseable, or has been removed, the service should respond with the appropriate not-found or forbidden error according to platform rules. Pagination and sorting should be applied consistently with other product browsing endpoints.
   *
   * @param connection
   * @param categoryId The category identifier whose products should be listed.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Resolve the category by categoryId and verify it exists and is visible for customer browsing.
   * Query products that belong to the category, excluding deleted products and products whose seller account is suspended or otherwise not eligible for public browsing.
   * Join or project the minimal browsing fields needed for a product summary: main image, product name, base price or price range, seller shop name, and average rating if available.
   * Apply stable ordering appropriate for category browsing, then paginate the result set.
   * If the category is missing or deleted, return 404. If the caller is not allowed to browse the category, return the standard authorization error. Do not expose product snapshot history here; this endpoint is for current browseable product summaries only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IPageIMallPlatformProduct.ISummary> {
    try {
      return await getMallPlatformCustomerCategoriesCategoryIdProducts({
        customer,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
