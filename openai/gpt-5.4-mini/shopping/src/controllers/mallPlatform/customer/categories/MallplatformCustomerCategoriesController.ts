import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCategory } from "../../../../api/structures/IMallPlatformCategory";
import { IPageIMallPlatformCategory } from "../../../../api/structures/IPageIMallPlatformCategory";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerCategories } from "../../../../providers/getMallPlatformCustomerCategories";
import { getMallPlatformCustomerCategoriesCategoryId } from "../../../../providers/getMallPlatformCustomerCategoriesCategoryId";

@Controller("/mallPlatform/customer/categories")
export class MallplatformCustomerCategoriesController {
  /**
   * Returns the browseable category collection for customers.
   *
   * This endpoint exposes the active marketplace taxonomy so customers can discover categories and their direct subcategories. Each result should include the category name and description maintained by administrators, reflecting the one-level hierarchy used by the platform.
   *
   * Deleted categories must be excluded from browsing results. The endpoint does not return products directly; it is intended for category navigation and for driving storefront pages that later resolve products by category.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query mall_platform_categories for records where deleted_at is null so deleted categories are not shown to customers. Load direct subcategories through the self-referential parent_category_id relation, but do not recurse beyond one level because the taxonomy only allows direct child categories. Return the taxonomy in a stable browse order suitable for customer navigation, and omit any category whose parent is missing or deleted to avoid exposing broken hierarchy. This endpoint is read-only and must not mutate category records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async get(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIMallPlatformCategory.ISummary> {
    try {
      return await getMallPlatformCustomerCategories({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single category for browsing or administration.
   *
   * Categories organize products into browsable groups and may contain only one level of subcategories. This endpoint returns the full category record so clients can display the category name, description, and direct child category context when present. It must not imply deeper nesting because the platform does not support category chains beyond one parent-to-child step.
   *
   * Customer-facing browsing should not surface deleted categories, while administrator-facing management may inspect category records according to authorization rules. If the category cannot be found, the service should return a not-found response.
   *
   * @param connection
   * @param categoryId The category identifier in global scope.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch one category row from mall_platform_categories by its primary identifier. Verify that the record exists and return not found when it does not. Do not load products in this operation; product listing belongs to separate endpoints. Preserve the one-level hierarchy rule by exposing only direct subcategory context if the response model includes it, and never traverse recursively. Apply authorization in the service layer so customer browsing excludes deleted categories while administrators can inspect category management records as allowed by policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async getByCategoryid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformCategory> {
    try {
      return await getMallPlatformCustomerCategoriesCategoryId({
        customer,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
