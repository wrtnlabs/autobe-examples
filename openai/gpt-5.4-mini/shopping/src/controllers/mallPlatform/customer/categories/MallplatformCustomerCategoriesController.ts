import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCategory } from "../../../../api/structures/IMallPlatformCategory";
import { IPageIMallPlatformCategory } from "../../../../api/structures/IPageIMallPlatformCategory";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerCategoriesCategoryId } from "../../../../providers/getMallPlatformCustomerCategoriesCategoryId";
import { getMallPlatformCustomerCategoriesCategoryIdSubcategories } from "../../../../providers/getMallPlatformCustomerCategoriesCategoryIdSubcategories";
import { patchMallPlatformCustomerCategories } from "../../../../providers/patchMallPlatformCustomerCategories";

@Controller("/mallPlatform/customer/categories")
export class MallplatformCustomerCategoriesController {
  /**
   * Retrieve the browsable list of marketplace categories.
   *
   * This endpoint returns administrator-managed categories for customer browsing, including each category's name, description, and any direct subcategories. It is intended for navigation and product discovery across the catalog, where customers need to understand how products are grouped within the mall.
   *
   * Only categories that are available for browsing should be included in the response. Deleted categories must be excluded from the listing, and the returned structure must respect the one-level subcategory rule used by the platform. If a category no longer contains products, the category structure should still remain understandable to customers through its name, description, and direct child categories.
   *
   * If the category set cannot be retrieved, the service should return an appropriate not-found or server error response according to the platform's standard error handling. This operation is read-only and does not modify any category records.
   *
   * @param connection
   * @param body Search, filter, pagination, and sorting criteria for browsing categories.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the mall_platform_categories table for all browsable categories managed by administrators.
   * Return only active category records and their direct child categories; do not attempt to traverse deeper than one level, because the domain allows only parent-to-child nesting.
   * Use ordering that keeps browsing stable and intuitive, typically by display order or creation order if the schema supports it; otherwise use a deterministic default sort.
   * Exclude categories that are not meant to be shown in customer browsing results.
   * Do not include any write behavior, and do not require request-body filters unless the schema or search requirements explicitly provide them.
   * If the implementation materializes parent-child relations, assemble the category tree in memory after fetching the category rows and group children beneath their parent category.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformCategory.IRequest,
  ): Promise<IPageIMallPlatformCategory.ISummary> {
    try {
      return await patchMallPlatformCustomerCategories({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single category and its direct subcategory context.
   *
   * This operation returns the category record used to organize products in the mall catalog. Categories are managed by administrators and may contain only one level of direct subcategories, so the response is intended to help customers understand the structure of the catalog and the grouping of products inside it.
   *
   * The returned category can be used by category browsing screens and administrator review tools. Clients should expect the category name and description to describe the browsing purpose of the category, and the relationship information to reflect only the allowed direct child category structure. If the category does not exist, the server should return a not-found error.
   *
   * @param connection
   * @param categoryId The unique identifier of the category to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the category by its primary identifier from mall_platform_categories.
   * Return the full category entity for a single record lookup, including its direct parent/child relationship data only if the category schema exposes those fields. Do not attempt to infer deeper nesting because category hierarchy is limited to one level.
   *
   * Enforce access according to actor rules: authenticated customers may read categories for browsing, and administrators may read categories for management. Deleted categories must not be treated as browseable category targets for customer-facing flows. If the requested category does not exist, return a not-found error. If the category is unavailable for browsing due to deletion or removal from the active catalog, handle it according to the platform's category visibility rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformCategory> {
    try {
      return await getMallPlatformCustomerCategoriesCategoryId({
        customer,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the direct subcategories of a category.
   *
   * This operation returns only the immediate child categories for the specified category so customers can navigate the marketplace taxonomy in the supported one-level hierarchy. Each returned category includes the catalog-facing name and description used for browsing and product classification.
   *
   * The result reflects the administrator-managed category structure and does not include deeper descendants, because subcategories are limited to one nesting level. If the category does not exist or has no direct subcategories, the response will return the appropriate empty or not-found result according to the service rules.
   *
   * @param connection
   * @param categoryId Identifier of the parent category whose direct subcategories should be returned.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the category by id and verify it exists and is not deleted according to service-layer rules. Query mall_platform_categories for rows where parent_category_id equals the requested category id, returning only direct children. Order results deterministically, preferably by name ascending then id, so browsing is stable.
   *
   * Do not traverse grandchildren or any deeper hierarchy, because the domain only allows one level of nesting. The response should be built from category summary data suitable for browse screens. If the parent category does not exist, return a not-found error. If the parent category exists but has no children, return an empty array or empty collection payload as defined by the shared summary/page schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId/subcategories")
  public async subcategories(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformCategory.ISummary> {
    try {
      return await getMallPlatformCustomerCategoriesCategoryIdSubcategories({
        customer,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
