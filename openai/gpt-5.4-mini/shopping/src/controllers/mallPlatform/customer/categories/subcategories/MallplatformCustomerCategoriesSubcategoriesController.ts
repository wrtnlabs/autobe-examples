import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCategory } from "../../../../../api/structures/IMallPlatformCategory";
import { IPageIMallPlatformCategory } from "../../../../../api/structures/IPageIMallPlatformCategory";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerCategoriesCategoryIdSubcategoriesSubcategoryId } from "../../../../../providers/getMallPlatformCustomerCategoriesCategoryIdSubcategoriesSubcategoryId";
import { patchMallPlatformCustomerCategoriesCategoryIdSubcategories } from "../../../../../providers/patchMallPlatformCustomerCategoriesCategoryIdSubcategories";

@Controller("/mallPlatform/customer/categories/:categoryId/subcategories")
export class MallplatformCustomerCategoriesSubcategoriesController {
  /**
   * List the direct subcategories of a category.
   *
   * This endpoint returns only the immediate child categories for the specified parent category. It is used to support customer browsing and administrator review of category structure, while preserving the marketplace rule that category nesting is limited to one level.
   *
   * The response never includes grandchildren or deeper descendants. If the category has no direct subcategories, the endpoint returns an empty page rather than an error. If the category does not exist, the service must return a not-found response. Access control should allow category browsing for customers, while category modification remains restricted to administrators elsewhere in the API.
   *
   * @param connection
   * @param categoryId The parent category identifier whose direct subcategories will be listed.
   * @param body Search, pagination, and sorting criteria for browsing direct subcategories under the selected category.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Resolve the parent category by categoryId first.
     *   If no category exists, return 404. Query only rows whose parent
     *   reference points to that category, and do not recurse beyond a single
     *   level. Apply request pagination and sorting consistently so the list is
     *   stable for browsing. Do not expose unrelated category-management
     *   metadata in the list response. If persisted data somehow violates the
     *   one-level nesting rule, fail the request with an integrity error rather
     *   than attempting to synthesize or flatten deeper relationships.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformCategory.IRequest,
  ): Promise<IPageIMallPlatformCategory.ISummary> {
    try {
      return await patchMallPlatformCustomerCategoriesCategoryIdSubcategories({
        customer,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a direct subcategory under a specific parent category.
   *
   * This endpoint returns the full category record for the requested subcategory and verifies that it belongs directly to the specified parent category. It is intended for customer browsing and category navigation within the marketplace's one-level category hierarchy.
   *
   * The parent category identifier scopes the lookup, and the subcategory identifier must resolve to a category whose parent_category_id matches that parent. If the parent category does not exist, the subcategory does not exist, or the relationship is not direct, the request must fail with a not-found response. Deleted categories should be excluded from normal browsing if the service applies deleted-record filtering.
   *
   * @param connection
   * @param categoryId The parent category identifier that scopes the subcategory lookup (UUID).
   * @param subcategoryId The direct subcategory identifier under the specified parent category (UUID).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Load the parent category by categoryId, then load
     *   the child category by subcategoryId and verify that
     *   child.parent_category_id equals the parent category id. If either
     *   record is missing or the child is not a direct subcategory of the
     *   parent, return not found.
   *
   * Do not traverse beyond one level because the domain only permits direct subcategories. Return the complete category entity using the category table fields only. No request body is required. If the service excludes deleted categories from browsing, apply that filter consistently here.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":subcategoryId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedParam("subcategoryId")
    subcategoryId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformCategory> {
    try {
      return await getMallPlatformCustomerCategoriesCategoryIdSubcategoriesSubcategoryId(
        {
          customer,
          categoryId,
          subcategoryId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
