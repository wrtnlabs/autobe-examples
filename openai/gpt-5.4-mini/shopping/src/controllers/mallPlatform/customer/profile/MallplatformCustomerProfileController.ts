import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformCustomerProfile } from "../../../../api/structures/IMallPlatformCustomerProfile";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerProfile } from "../../../../providers/getMallPlatformCustomerProfile";
import { putMallPlatformCustomerProfile } from "../../../../providers/putMallPlatformCustomerProfile";

@Controller("/mallPlatform/customer/profile")
export class MallplatformCustomerProfileController {
  /**
   * Returns the signed-in customer's current profile information.
   *
   * This operation is limited to the authenticated customer account and exposes the customer-facing identity details stored in the customer profile, specifically the display name and phone number. It does not include credentials, addresses, or order history.
   *
   * The customer must be signed in to access this resource. If authentication is missing or invalid, the request must be rejected. If the profile cannot be resolved for the current customer account, the service should return the appropriate not-found response.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Resolve the current customer from the authentication context and load the related row from mall_platform_customer_profiles. Do not accept any client-supplied customer identifier because the endpoint is scoped to the current session.
   *
   * Return the profile fields that exist in the schema and are intended for customer-facing identity: display name and phone number. If authentication fails, return 401. If the authenticated customer has no profile row, return 404. Do not query or mutate any other tables for this operation unless middleware requires session validation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IMallPlatformCustomerProfile> {
    try {
      return await getMallPlatformCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the signed-in customer’s profile information.
   *
   * This operation lets an authenticated customer change the display name and phone number stored in their customer profile. The profile represents the customer’s personal identity details on the platform, and the update applies only to those profile fields.
   *
   * The server must resolve the profile from the current authenticated customer account rather than accepting an identifier in the path. Validation must reject incomplete or unsuitable profile data, and the profile must remain unchanged when validation fails. This operation does not modify account credentials, shipping addresses, or order records.
   *
   * @param connection
   * @param body The new customer profile values to apply to the signed-in customer’s profile.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Resolve the customer profile from the authenticated session context and load the single profile owned by that customer account.
   * Validate the request body before persisting any change. Only display name and phone number are allowed to change. Reject the request if either value is missing, malformed, or otherwise unsuitable for normal customer use.
   * Apply the update only to the customer profile row and do not touch the customer account, addresses, orders, or authentication data. If the profile is unavailable because the account was deleted or the profile no longer exists, return a not-found or unavailable error and do not recreate the record.
   * Persist the new values atomically and return the updated profile after success.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformCustomerProfile.IUpdate,
  ): Promise<IMallPlatformCustomerProfile> {
    try {
      return await putMallPlatformCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
