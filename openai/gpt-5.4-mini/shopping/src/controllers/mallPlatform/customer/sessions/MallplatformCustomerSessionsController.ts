import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformAdministratorSession } from "../../../../api/structures/IMallPlatformAdministratorSession";
import { IMallPlatformCustomerSession } from "../../../../api/structures/IMallPlatformCustomerSession";
import { IPageIMallPlatformCustomerSession } from "../../../../api/structures/IPageIMallPlatformCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerSessionsSessionId } from "../../../../providers/getMallPlatformCustomerSessionsSessionId";
import { patchMallPlatformCustomerSessions } from "../../../../providers/patchMallPlatformCustomerSessions";

@Controller("/mallPlatform/customer/sessions")
export class MallplatformCustomerSessionsController {
  /**
   * Retrieve a paginated list of authentication sessions for customer accounts.
   *
   * This operation is intended for session inspection and account security workflows, such as viewing currently active or recently created sessions associated with a customer account. It returns summary information suitable for list views and supports filtering, pagination, and sorting so clients can manage long session histories efficiently.
   *
   * The response is based on the customer session records stored in the authentication layer. Because sessions are account-specific security data, callers must only receive sessions they are authorized to inspect, and the service must reject requests that attempt to access sessions outside that scope. If no matching sessions exist, the response should return an empty page rather than an error.
   *
   * @param connection
   * @param body Search, filter, sorting, and pagination criteria for customer sessions.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the customer session table with filtering, pagination, and sorting.
   * Use the authenticated principal to restrict results to the caller's own sessions unless the authorization layer explicitly grants broader inspection rights.
   * Support filters such as account identifier, session status, and creation time range if present in the request DTO.
   * Return a paginated summary projection only; do not expose sensitive session secrets.
   * Validate pagination parameters and reject invalid or out-of-range values.
   * If no sessions match, return an empty page.
   * Apply stable sorting for deterministic pagination.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformCustomerSession.IRequest,
  ): Promise<IPageIMallPlatformCustomerSession.ISummary> {
    try {
      return await patchMallPlatformCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the current session record by session identifier.
   *
   * This endpoint returns the authenticated session metadata for the signed-in account, including the session's creation time, expiration time, and the request context that was captured when the session was issued. It is intended for session inspection and account security flows, not for credential management.
   *
   * The returned session belongs to the current actor type and must be resolved against the matching session store for customers, sellers, or administrators. The session remains available only while it is active and has not expired. If the session does not exist, has expired, or does not belong to the current authenticated account, the request must be rejected.
   *
   * This operation does not modify any account data. It is useful for clients that need to confirm the current signed-in state or show session details as part of security settings and logout-related behavior.
   *
   * @param connection
   * @param sessionId Identifier of the session to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the session record by primary key from the actor-specific session table that matches the authenticated account type. Determine the effective table from the caller's identity: customer sessions, seller sessions, or administrator sessions.
   *
   * Validate that the requested session exists and belongs to the current authenticated account. Reject the request with not found or unauthorized semantics if the session is missing, belongs to another account, or has already expired. Do not leak whether a foreign session ID exists.
   *
   * Return only non-sensitive session metadata: session id, created timestamp, expiration timestamp, IP address, href, referrer, and the owning account reference as allowed by the response DTO. Do not return credentials, cookies, or any token material. No write operations are performed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformAdministratorSession> {
    try {
      return await getMallPlatformCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
