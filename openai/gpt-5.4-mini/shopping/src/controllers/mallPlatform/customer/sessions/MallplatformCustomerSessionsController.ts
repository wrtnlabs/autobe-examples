import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCustomerSession } from "../../../../api/structures/IMallPlatformCustomerSession";
import { IPageIMallPlatformCustomerSession } from "../../../../api/structures/IPageIMallPlatformCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerSessionsSessionId } from "../../../../providers/getMallPlatformCustomerSessionsSessionId";
import { patchMallPlatformCustomerSessions } from "../../../../providers/patchMallPlatformCustomerSessions";
import { postMallPlatformCustomerSessions } from "../../../../providers/postMallPlatformCustomerSessions";

@Controller("/mallPlatform/customer/sessions")
export class MallplatformCustomerSessionsController {
  /**
   * Creates a new authenticated session for an existing customer, seller, or administrator.
   *
   * The platform validates the submitted credentials, checks that the matched account is allowed to sign in, and then establishes the current authenticated session for that actor. It does not create a new account, and it must not return password secrets or other sensitive credential material.
   *
   * If authentication fails or the account is not eligible to sign in, the request is rejected and no session is created. A successful response returns the active session context so the client can continue using protected features.
   *
   * @param connection
   * @param body Login credentials for an existing account. The server uses these values to authenticate the actor and create a new session.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate the submitted credentials against
     *   the registered account records for customers, sellers, and
     *   administrators. Determine the actor type from the verified account,
     *   then enforce platform eligibility rules before creating a session:
     *   reject banned, suspended, rejected, or otherwise unavailable accounts
     *   according to actor-specific policy.
   *
   * On success, create a new session record for the authenticated actor and return the session context. Do not expose password hashes, raw tokens, or any other secret data beyond what the API contract requires. On failure, return an authentication or account-state error and do not create any session row. Preserve the actor identity and role in the response so downstream clients can route the user correctly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformCustomerSession.ICreate,
  ): Promise<IMallPlatformCustomerSession> {
    try {
      return await postMallPlatformCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and list authenticated sessions with pagination and filtering.
   *
   * This operation returns session records in a paginated form so callers can inspect login activity and manage active access. It is intended for account security and operational review, not for authentication itself.
   *
   * The result is limited to the caller's permitted scope. Customers may only view their own customer sessions, sellers may only view their own seller sessions, and administrators may only view sessions they are authorized to inspect. The response never includes sensitive session secrets or password reset material, and an empty result page is returned when no sessions match the criteria.
   *
   * @param connection
   * @param body Search criteria, pagination settings, and sorting options for listing authenticated sessions.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the session persistence tables for the
     *   current actor type and apply the request-body filters, pagination, and
     *   sorting. Return summary rows only; do not expose session tokens,
     *   password reset credentials, or other secret material.
   *
   * Enforce strict authorization by actor scope. A customer must only receive their own customer sessions, a seller must only receive their own seller sessions, and an administrator must only receive sessions allowed by platform policy. If the request targets an unauthorized scope, return an authorization error rather than leaking session existence. Keep the implementation read-only and avoid any side effects on session state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformCustomerSession.IRequest,
  ): Promise<IPageIMallPlatformCustomerSession.ISummary> {
    try {
      return await patchMallPlatformCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Returns a single authentication session record.
   *
   * This endpoint is used to inspect one active or historical session entry, including the owning account reference, client context captured at creation time, and the expiration timestamp that determines whether the session is still valid.
   *
   * Access is limited to the owning signed-in account or to administrators when the platform authorization rules permit session review. If the session does not exist, belongs to another account without permission, or is otherwise inaccessible under account status rules, the request must fail with an appropriate not-found or forbidden response.
   *
   * @param connection
   * @param sessionId The session identifier (global UUID).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Look up the session by its UUID primary key and
     *   return the record only when the requester is authorized to inspect it.
     *   Use the current authenticated actor context to verify ownership or
     *   administrator-level access before exposing any data.
   *
   * Return the session fields defined by the underlying session schema: id, owner foreign key, ip, href, referrer, created_at, and expired_at. Do not modify the session. If the row is missing, return not found. If access is denied, return forbidden. If the runtime session belongs to a different actor type than the current context and policy does not allow cross-actor inspection, treat it as inaccessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformCustomerSession> {
    try {
      return await getMallPlatformCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
