import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformShipment } from "../../../../../api/structures/IMallPlatformShipment";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerShipmentsShipmentIdTracking } from "../../../../../providers/getMallPlatformCustomerShipmentsShipmentIdTracking";

@Controller("/mallPlatform/customer/shipments/:shipmentId/tracking")
export class MallplatformCustomerShipmentsTrackingController {
  /**
   * Returns the tracking details for a single shipment.
   *
   * A shipment is the package delivery unit for one seller, so its carrier name, tracking number, optional tracking URL, and delivery timestamps apply to every order item included in that shipment. This endpoint is used to present shipment-level tracking information from the order detail view and other shipment lookup screens.
   *
   * The response maps directly to the shipment record stored in `mall_platform_shipments`, including the shipment status and the shipped and delivered timestamps when available. Because tracking is shared at the shipment level, the endpoint does not expose per-item tracking differences.
   *
   * If the shipment does not exist, the request must fail with a not-found error. If the caller is not allowed to view the shipment, the service must reject the request according to platform authorization rules. Soft-deleted shipments should not be returned if the implementation excludes records with a populated `deleted_at` value.
   *
   * @param connection
   * @param shipmentId The shipment identifier in UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch one shipment by its UUID from mall_platform_shipments and return its tracking-related fields.
   * Include carrier_name, tracking_number, tracking_url, status, shipped_at, delivered_at, created_at, and updated_at in the response mapping if supported by the response DTO.
   * Enforce access control so the owning customer, the owning seller, or an administrator can access the record according to the platform's authorization rules.
   * Reject missing shipments with not found. Do not accept a request body. Do not query order-item tracking separately because tracking is defined only at the shipment level and shared by all items in the shipment.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformShipment> {
    try {
      return await getMallPlatformCustomerShipmentsShipmentIdTracking({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
