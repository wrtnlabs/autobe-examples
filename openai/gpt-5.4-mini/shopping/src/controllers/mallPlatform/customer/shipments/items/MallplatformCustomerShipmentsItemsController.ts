import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformShipment } from "../../../../../api/structures/IMallPlatformShipment";
import { IMallPlatformShipmentItem } from "../../../../../api/structures/IMallPlatformShipmentItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerShipmentsShipmentIdItems } from "../../../../../providers/getMallPlatformCustomerShipmentsShipmentIdItems";
import { getMallPlatformCustomerShipmentsShipmentIdItemsShipmentItemId } from "../../../../../providers/getMallPlatformCustomerShipmentsShipmentIdItemsShipmentItemId";
import { patchMallPlatformCustomerShipmentsShipmentIdItems } from "../../../../../providers/patchMallPlatformCustomerShipmentsShipmentIdItems";

@Controller("/mallPlatform/customer/shipments/:shipmentId/items")
export class MallplatformCustomerShipmentsItemsController {
  /**
   * Returns the order items assigned to a shipment.
   *
   * This endpoint is used by shipment detail and order history screens to show which purchased items were packed together, along with the item-level purchase context needed for tracking and delivery confirmation.
   *
   * The shipment is always treated as a seller-scoped package, so the returned items must all belong to the same shipment and therefore the same seller. If the shipment does not exist or the requester is not allowed to view it, the service must return the platform's standard not-found or authorization response. The endpoint does not infer items from the order; it only exposes explicit shipment-item membership stored by the system.
   *
   * @param connection
   * @param shipmentId The shipment identifier (UUID scope) used to load the shipment item membership.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the shipment identified by shipmentId, then verify the current actor is permitted to view it according to shipment visibility rules. Query mall_platform_shipment_items for rows belonging to that shipment and join them to mall_platform_order_items so the response can include the purchase-line context needed by shipment and order-detail screens.
   *
   * Return only items explicitly linked to the shipment. Preserve any stored ordering if the service layer or database maintains one. Do not merge items from other shipments, and do not infer additional items from the parent order. If the shipment is valid but has no items, return an empty collection. If the shipment is missing, return 404. If access is denied, return the standard authorization response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async getByShipmentid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformShipmentItem.ISummary> {
    try {
      return await getMallPlatformCustomerShipmentsShipmentIdItems({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the order items assigned to a shipment.
   *
   * This endpoint supports seller fulfillment by reconciling the membership of an existing shipment package. A shipment is the delivery unit for one seller, and every order item in that shipment must belong to the same seller and the same order. The server must validate those ownership and eligibility rules before applying any change.
   *
   * The request is treated as the desired final set of order items for the shipment. The service should add missing shipment-item rows and remove rows that are no longer included, all inside one transaction. It must reject items that already belong to another shipment, items that belong to a different seller, items from a different order, or items that are not in a shippable state. If the resulting shipment would be empty, the request should be rejected.
   *
   * Shipment header data such as carrier name, tracking number, tracking URL, shipped time, delivered time, and status must not be modified by this operation. Only the shipment-item junction table should change, and the update should fail atomically if any requested item is invalid.
   *
   * @param connection
   * @param shipmentId The shipment identifier (UUID) whose item membership is being updated.
   * @param body The desired final set of order item identifiers to include in the shipment.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the shipment by id and verify that it exists and is not deleted. Use the shipment's seller id and order id as the validation scope.
   *
   * Interpret the request body as the desired final set of order item identifiers for the shipment. Compare the requested set with the current mall_platform_shipment_items rows for that shipment. Insert missing rows and remove rows not present in the request within a single transaction.
   *
   * For every requested order item, confirm that mall_platform_order_items.mall_platform_order_id matches the shipment's order, mall_platform_order_items.mall_platform_seller_id matches the shipment's seller, and the item is eligible for shipment. Also confirm that the item is not already assigned to another shipment-item row, since mall_platform_shipment_items enforces uniqueness on mall_platform_order_item_id. If any item fails validation, reject the entire request.
   *
   * Do not update shipment carrier or status fields here. Do not allow cross-seller or cross-order composition. Reject requests that would leave the shipment with zero items if business rules require shipments to contain at least one order item. Return the updated shipment entity after commit.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformShipment.IUpdateItem,
  ): Promise<IMallPlatformShipment> {
    try {
      return await patchMallPlatformCustomerShipmentsShipmentIdItems({
        customer,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one item assignment inside a shipment.
   *
   * This operation returns the relationship row that links a shipment to one purchased order item. It is used by shipment detail screens and order history screens to show which order item belongs to a specific shipment, along with the shipment context and the linked order item record.
   *
   * The requested shipment item must belong to the shipment identified by the path. If the shipment item does not exist, is deleted, or is not associated with the given shipment, the server must return not found. This prevents leaking shipment-item assignments across different shipments.
   *
   * Access is limited to the shipment owner, the customer who owns the order containing the shipment, and administrators according to the platform's authorization rules.
   *
   * @param connection
   * @param shipmentId The shipment identifier that scopes the shipment-item relationship.
   * @param shipmentItemId The shipment-item identifier within the specified shipment.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load mall_platform_shipment_items by id and verify that mall_platform_shipment_items.mall_platform_shipment_id matches the shipmentId path parameter.
   * Join the related shipment and order item records so the client can render shipment grouping and the purchased item context.
   * Validate both path parameters as UUIDs.
   * Return 404 if the shipment item is missing, deleted, or belongs to a different shipment.
   * Enforce authorization so only the shipment's customer, the shipment's seller, or an administrator can read the record.
   * Use the shipment-item row as the primary resource and include related shipment and order-item data in the response model.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentItemId")
  public async getByShipmentidAndShipmentitemid(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("shipmentItemId")
    shipmentItemId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformShipmentItem> {
    try {
      return await getMallPlatformCustomerShipmentsShipmentIdItemsShipmentItemId(
        {
          customer,
          shipmentId,
          shipmentItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
