import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformWishlist } from "../../../../api/structures/IMallPlatformWishlist";
import { IPageIMallPlatformWishlist } from "../../../../api/structures/IPageIMallPlatformWishlist";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { patchMallPlatformCustomerWishlists } from "../../../../providers/patchMallPlatformCustomerWishlists";

@Controller("/mallPlatform/customer/wishlists")
export class MallplatformCustomerWishlistsController {
  /**
   * Returns the authenticated customer's wishlist as a paginated list of saved products.
   *
   * This endpoint is used to browse products the customer saved for later consideration. It returns product-level wishlist entries only, not variant-level rows, and the result is limited to the caller's own wishlist. Deleted products must not appear in the response because wishlist maintenance keeps saved items aligned with products that still exist in the catalog.
   *
   * Pagination is required so customers can browse large saved-product lists in manageable groups. If the customer is not authenticated or does not own a wishlist, the request must be rejected by the authorization layer.
   *
   * @param connection
   * @param body Wishlist browsing criteria including pagination, optional product search filters, and sorting options for the authenticated customer's saved products.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Resolve the current customer from the authenticated session, load that customer's wishlist container, and query wishlist items joined to the current product records used for browsing. Exclude wishlist entries whose referenced product no longer exists so deleted products do not surface in the list. Support pagination, search, and sorting in the request body, and return only product-level summary data suitable for a wishlist view.
   *
   * Do not expose variant-level fields in this operation. The list must be scoped to the authenticated customer only, and cross-customer access is prohibited. If the customer is unauthenticated, return an authorization failure. If the wishlist container cannot be found for the authenticated customer, return the standard not-found behavior for that scope. This endpoint is read-only and must not modify wishlist rows.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformWishlist.IRequest,
  ): Promise<IPageIMallPlatformWishlist.ISummary> {
    try {
      return await patchMallPlatformCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
