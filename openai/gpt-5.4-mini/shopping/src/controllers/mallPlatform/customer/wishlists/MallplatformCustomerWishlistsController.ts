import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformWishlist } from "../../../../api/structures/IMallPlatformWishlist";
import { IPageIMallPlatformWishlist } from "../../../../api/structures/IPageIMallPlatformWishlist";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { deleteMallPlatformCustomerWishlists } from "../../../../providers/deleteMallPlatformCustomerWishlists";
import { getMallPlatformCustomerWishlists } from "../../../../providers/getMallPlatformCustomerWishlists";
import { postMallPlatformCustomerWishlists } from "../../../../providers/postMallPlatformCustomerWishlists";
import { putMallPlatformCustomerWishlists } from "../../../../providers/putMallPlatformCustomerWishlists";

@Controller("/mallPlatform/customer/wishlists")
export class MallplatformCustomerWishlistsController {
  /**
   * Returns the authenticated customer's wishlist as a paginated list of saved products.
   *
   * This endpoint provides the customer-facing browsing view for wishlist content. Each result represents a saved product rather than a variant-level entry, so customers can revisit products they marked for later consideration. Deleted products must not appear in the response because wishlist maintenance keeps saved items aligned with products that still exist in the catalog.
   *
   * Access is limited to registered customer accounts and the wishlist owned by the current customer. The service must enforce ownership checks and return an authorization error if the caller is not an authenticated customer. The response is intended for repeat browsing and should support pagination and sorting consistent with wishlist browsing behavior.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Verify that the caller is an authenticated
     *   customer before reading wishlist data.
   *
   * Load the wishlist entries owned by the current customer and join them to the related product records so the response can present browsable saved products. Exclude any entries whose products were deleted, because wishlist cleanup rules require deleted products to be removed from all wishlists and they must not appear in browsing results.
   *
   * Return a paginated result set using the platform page type pattern. Keep ordering stable for the customer experience, and return an empty page when the customer has no saved products. Do not expose any wishlist records belonging to other customers.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IPageIMallPlatformWishlist.ISummary> {
    try {
      return await getMallPlatformCustomerWishlists({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Create the authenticated customer’s wishlist container.
   *
   * This operation initializes the one wishlist resource owned by the signed-in customer so saved products can be managed at the product level. The wishlist belongs to the customer account and is used for later product-interest browsing rather than immediate purchase.
   *
   * Only registered customer accounts may use this operation. If the customer already has a wishlist, the request must fail instead of creating a duplicate container. The wishlist itself does not store product selections; those are handled by wishlist item records.
   *
   * @param connection
   * @param body No client-provided fields are required because the wishlist owner is derived from the authenticated customer context.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Authenticate the caller as a customer and resolve
     *   the owner from the security context. Do not accept any owner identifier
     *   from the client. Check mall_platform_wishlists for an existing row for
     *   the current customer account; if one exists, return a conflict-style
     *   error and do not insert another record.
   *
   * If no wishlist exists, insert a new wishlist row linked to the authenticated customer and return the persisted entity. Enforce customer-only access; unauthenticated callers and non-customer actors must be rejected. Do not create wishlist items here. Keep the implementation consistent with the one-wishlist-per-customer rule implied by the domain model and wishlist operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformWishlist.ICreate,
  ): Promise<IMallPlatformWishlist> {
    try {
      return await postMallPlatformCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the authenticated customer's wishlist contents.
   *
   * This endpoint lets a registered customer maintain the list of products saved for later consideration. Wishlist entries are stored at the product level, so each saved item represents a product rather than a specific variant.
   *
   * Only the owning customer may use this operation. The update must be processed atomically so that a failure leaves the existing wishlist unchanged. If a referenced product no longer exists, the request should be rejected instead of preserving a stale wishlist entry.
   *
   * @param connection
   * @param body Wishlist update payload containing the customer's saved products. The list must reference products only and must not include product variants.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Resolve the authenticated customer and load that
     *   customer's wishlist container. Validate that the request contains
     *   product references only and does not attempt to store variant-level
     *   data.
   *
   * Apply the wishlist changes in a single transaction so that any validation or persistence failure leaves the current saved products unchanged. Deduplicate repeated product references if necessary. Reject requests from unauthenticated callers and from non-customer actors.
   *
   * If the customer's wishlist container is created lazily in this service, create it as part of the transaction; otherwise, update the existing container only. Ensure deleted products cannot remain in the final saved list because wishlist maintenance must not expose catalog items that no longer exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformWishlist.IUpdate,
  ): Promise<IMallPlatformWishlist> {
    try {
      return await putMallPlatformCustomerWishlists({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete the current customer's wishlist.
   *
   * This operation removes the authenticated customer's wishlist container and all saved product entries in it. It does not affect any product records, product variants, or other customers' wishlists.
   *
   * The request is scoped to the current authenticated customer account. The service must verify ownership before removing the wishlist data. If the wishlist does not exist, the operation should be treated as idempotent and succeed without changing other data.
   *
   * If the customer has saved items, they are removed together with the wishlist so the account no longer has a persisted wishlist state. Catalog data remains unchanged, and future product deletions continue to be handled by the automatic cleanup rules elsewhere in the system.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Load the authenticated customer identity from the
     *   session context, then locate the wishlist owned by that customer. If no
     *   wishlist exists for the customer, return success without modifying
     *   other records. If a wishlist exists, delete the wishlist record and its
     *   dependent wishlist item rows in the same transaction to avoid orphaned
     *   entries. Do not delete or modify any product rows, category rows, or
     *   customer profile rows. Enforce ownership so one customer cannot delete
     *   another customer's wishlist. Return no response body on success. If the
     *   customer is not authenticated or does not own the targeted wishlist
     *   context, respond with the appropriate authorization error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<void> {
    try {
      return await deleteMallPlatformCustomerWishlists({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
