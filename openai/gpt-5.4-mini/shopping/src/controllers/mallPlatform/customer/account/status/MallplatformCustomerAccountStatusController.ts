import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformSellerAccount } from "../../../../../api/structures/IMallPlatformSellerAccount";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerAccountStatus } from "../../../../../providers/getMallPlatformCustomerAccountStatus";

@Controller("/mallPlatform/customer/account/status")
export class MallplatformCustomerAccountStatusController {
  /**
   * Returns the current approval status of the authenticated seller account.
   *
   * This endpoint exposes the seller registration state as one of the platform visibility values: pending, approved, or rejected. If the seller has been rejected, the response also includes the rejection reason so the seller can understand the decision and decide whether to submit a new registration request.
   *
   * The operation is restricted to the caller’s own seller account and does not modify approval state, seller profile data, or any other account fields.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Authenticate the caller as a seller and load the seller account associated with the current session. Return the seller approval status directly from mall_platform_seller_accounts, including the rejection reason when the stored status is rejected.
   *
   * Reject unauthenticated requests and any request that is not made by a valid seller principal. Do not expose unrelated seller fields, do not modify any records, and do not create snapshots because this endpoint is read-only. If the authenticated seller account cannot be resolved, return the appropriate authorization or not-found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IMallPlatformSellerAccount> {
    try {
      return await getMallPlatformCustomerAccountStatus({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
