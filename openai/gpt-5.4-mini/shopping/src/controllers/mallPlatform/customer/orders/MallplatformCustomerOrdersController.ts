import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrder } from "../../../../api/structures/IMallPlatformOrder";
import { IPageIMallPlatformOrder } from "../../../../api/structures/IPageIMallPlatformOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerOrdersOrderId } from "../../../../providers/getMallPlatformCustomerOrdersOrderId";
import { patchMallPlatformCustomerOrders } from "../../../../providers/patchMallPlatformCustomerOrders";

@Controller("/mallPlatform/customer/orders")
export class MallplatformCustomerOrdersController {
  /**
   * List the authenticated customer's orders with pagination, filtering, and sorting.
   *
   * This endpoint returns the current customer's order history only. It is intended for browsing past purchases, checking the derived overall order status, and navigating to a separate order detail view when more information is needed. The overall status shown in the list is derived from the statuses of the order items, so the list reflects the platform's order-state rules.
   *
   * The request body supports the browsing criteria defined for orders, including pagination and any allowed filters or sort options. Results must be ordered according to the requested sort, with a sensible default of newest first. The service must reject attempts to access other customers' orders and must not mutate any order data.
   *
   * If invalid pagination or unsupported criteria are supplied, the request should fail with a business validation error. Full item details, shipment details, and preserved snapshot information belong to the order detail endpoint rather than this list endpoint.
   *
   * @param connection
   * @param body Filtering, sorting, and pagination criteria for the authenticated customer's order history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query mall_platform_orders for the authenticated customer only.
   * Apply request-body filters and sorting for the order browsing use case, then paginate the result set.
   * Return a summary projection suitable for list pages, including order identity, date, total price, and the overall status derived from mall_platform_order_items according to the order status rules.
   * Do not include full item rows, shipment details, or snapshot payloads in the list response.
   * Reject unauthorized cross-account access. Validate paging and filter criteria before querying, and return a business error if the request is invalid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformOrder.IRequest,
  ): Promise<IPageIMallPlatformOrder.ISummary> {
    try {
      return await patchMallPlatformCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Returns the full detail view of one order owned by the current customer.
   *
   * This endpoint is used from the customer order history flow to open a single order and inspect its complete purchase record. The response includes the order header, shipping destination, item-level purchase history, and shipment information needed to understand progress at both the order and order-item level.
   *
   * Access is restricted to the authenticated customer who owns the order. If the order does not exist or does not belong to the current customer, the service must respond as not found to avoid exposing another customer's purchase history. The order's preserved historical item information must remain intact even if seller profiles or product data change later.
   *
   * @param connection
   * @param orderId The order identifier (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the order by primary key and verify that the authenticated customer owns it before returning data. Join the order with its order items, preserved order-item snapshot data, shipping address, and any shipments/items associated with the order so the detail page can render the full history.
   *
   * Return the preserved item-level purchase context exactly as stored at checkout time, including product and variant references captured in the order item snapshots, rather than resolving only current catalog data. Include shipment tracking data when present, and ensure the response remains stable even if the seller profile, product, or variant has since changed.
   *
   * If the order is missing or belongs to another customer, return a not found response. Do not leak whether another customer's order exists. Do not allow modification through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrder> {
    try {
      return await getMallPlatformCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
