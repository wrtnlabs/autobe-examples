import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrder } from "../../../../api/structures/IMallPlatformOrder";
import { IPageIMallPlatformOrder } from "../../../../api/structures/IPageIMallPlatformOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerOrdersOrderId } from "../../../../providers/getMallPlatformCustomerOrdersOrderId";
import { patchMallPlatformCustomerOrders } from "../../../../providers/patchMallPlatformCustomerOrders";

@Controller("/mallPlatform/customer/orders")
export class MallplatformCustomerOrdersController {
  /**
   * Searches the authenticated customer's order history.
   *
   * This operation returns a paginated list of the customer's own orders. Each result includes the order number, placement date, total price, and the overall order status derived from its order items. The list is intended for browsing completed and in-progress purchases, so it shows summary information rather than full item-level details.
   *
   * Filtering and sorting follow the platform browsing rules. Clients may narrow results by order status and date range and may sort by the supported order-history sort options. If there are no matching orders, the response returns an empty page rather than an error.
   *
   * @param connection
   * @param body Pagination, filtering, and sorting criteria for the authenticated customer's order history.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query mall_platform_orders for the authenticated
     *   customer only. Apply pagination, optional filters, and sorting from the
     *   request body. Use the derived overall order status from order items
     *   when producing each summary row, consistent with the order status
     *   rules. Do not expose orders belonging to other customers. Return a
     *   paginated summary projection for history browsing; do not return full
     *   order item or shipment detail here. If the customer has no matching
     *   orders, return an empty page with valid pagination metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformOrder.IRequest,
  ): Promise<IPageIMallPlatformOrder.ISummary> {
    try {
      return await patchMallPlatformCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves the full details of a single order.
   *
   * This endpoint returns one persisted order record together with the data needed to display the customer-facing order detail page, including the shipping destination, item-level purchase history, and shipment information. Customers can only view their own orders, while sellers and administrators may access orders according to their oversight and fulfillment permissions.
   *
   * The returned order should reflect preserved historical data rather than current catalog state, so item details, product information, variant information, and seller profile information remain stable even if the source records change later. If the order cannot be found, the service should return not found; if the caller is not allowed to view it, the service should return forbidden.
   *
   * @param connection
   * @param orderId The unique identifier of the order to retrieve.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Fetch the order by its UUID and load all related
     *   data required for a full detail view. Enforce ownership so a customer
     *   can only access their own orders, while seller and administrator access
     *   follows platform authorization rules.
   *
   * Include the preserved order items, the shipping address, and shipment data. For item-level history, return the stored purchase-time product and variant data together with the preserved seller profile information so historical review and dispute workflows remain accurate even after the underlying product or seller profile changes.
   *
   * Do not expose other customers' orders. Return 404 when the order does not exist. Return 403 when the caller is authenticated but not allowed to view the order. This is a read-only operation and must not mutate any order, item, shipment, or snapshot data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrder> {
    try {
      return await getMallPlatformCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
