import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrder } from "../../../../api/structures/IMallPlatformOrder";
import { IPageIMallPlatformOrder } from "../../../../api/structures/IPageIMallPlatformOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerOrdersOrderId } from "../../../../providers/getMallPlatformCustomerOrdersOrderId";
import { patchMallPlatformCustomerOrders } from "../../../../providers/patchMallPlatformCustomerOrders";

@Controller("/mallPlatform/customer/orders")
export class MallplatformCustomerOrdersController {
  /**
   * Retrieve a paginated list of the authenticated customer's orders.
   *
   * This endpoint is used to browse order history and search past purchases. Each returned order reflects the customer-owned checkout record stored in the order header, including the order number, total amount, creation time, and the derived overall order status computed from its order items.
   *
   * The list is intended for customer order history screens, so results must be paginated and sorted by newest first by default. Filtering and search should respect the authenticated customer scope and never expose orders belonging to other customers. Related order-item, shipment, and preserved shipping-address details are available through the corresponding order detail endpoint.
   *
   * If the requested page is out of range or the criteria match no orders, the response should still be a valid empty page. Any invalid filter or sort option must be rejected with a business validation error.
   *
   * @param connection
   * @param body Search, filter, sort, and pagination criteria for customer order history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query mall_platform_orders for the authenticated customer only.
   * Apply pagination, newest-first default sorting, and optional search/filter criteria from the request body.
   * Support filtering by order status and date range if provided by the request DTO. Do not expose orders from other customers.
   * Use the derived overall order status stored on the order row, which is computed from related order items by business rules. Include total_amount and created_at in summary output, and order_number for identification.
   * Return a paginated list of summary records ordered consistently. If no rows match, return an empty page rather than an error. Validate request sort fields and filter enums strictly; reject unknown criteria. Do not join heavy nested data such as full order items or shipments in this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformOrder.IRequest,
  ): Promise<IPageIMallPlatformOrder.ISummary> {
    try {
      return await patchMallPlatformCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of a single order for the authenticated customer.
   *
   * This endpoint returns one order record together with the preserved purchase context needed to display the order detail page, including the item list, item statuses, shipping address, and shipment information. It is intended for customers opening an order from their own order history, where the platform shows the complete checkout result and the per-item progress of the purchase.
   *
   * The returned order must include the item-level history that captures the product name, variant, quantity, price, and status for each purchased line. It must also expose shipment tracking data when shipments exist, so the customer can review delivery progress for each seller-specific package. If the order does not belong to the current customer, the service must reject the request rather than exposing another customer's purchase history.
   *
   * Because this is a money-related record, the response must preserve historical values exactly as stored on the order and order-item snapshot records. Any missing order ID, unauthorized access, or nonexistent order should result in an appropriate not-found or forbidden response from the service layer.
   *
   * @param connection
   * @param orderId The order identifier within the customer's own order history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the order by its identifier for the authenticated customer only.
   * Join or hydrate the related order items, item snapshots, shipment records, shipment items, and preserved shipping address so the consumer receives the complete detail view in one call.
   *
   * Enforce ownership validation before returning data: the requested order must belong to the current customer account unless the caller has an administrative override permission. If the caller is a customer, reject access to any order that belongs to another customer.
   *
   * Return the preserved order data exactly as recorded at checkout time. Do not reconstruct historical product or seller values from current product tables; use the stored snapshot rows for item names, variant options, prices, and seller profile presentation.
   *
   * If the order is not found, return a not-found error. If ownership validation fails, return a forbidden error. If related shipment data is absent, return the order with an empty shipment collection rather than failing the request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrder> {
    try {
      return await getMallPlatformCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
