import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrder } from "../../../../../api/structures/IMallPlatformOrder";
import { IPageIMallPlatformOrder } from "../../../../../api/structures/IPageIMallPlatformOrder";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getMallPlatformCustomerOrdersHistoryOrderId } from "../../../../../providers/getMallPlatformCustomerOrdersHistoryOrderId";
import { patchMallPlatformCustomerOrdersHistory } from "../../../../../providers/patchMallPlatformCustomerOrdersHistory";

@Controller("/mallPlatform/customer/orders/history")
export class MallplatformCustomerOrdersHistoryController {
  /**
   * Retrieve the authenticated customer's paginated order history.
   *
   * This operation returns a condensed list of orders owned by the current customer account. Each list item exposes the order number, order date, total price, and overall order status so the UI can render an order history page without loading full order details for every row.
   *
   * The result is sorted by newest order first and supports pagination and filtering for browsing history safely within the customer's own data scope. If the customer has no orders, the response returns an empty page without exposing any other customer's records. Full order details, including items, shipping address, and shipment information, must be retrieved through the order detail endpoint.
   *
   * @param connection
   * @param body Pagination and optional search/filter criteria for the authenticated customer's order history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query mall_platform_orders for the authenticated customer only. Join or aggregate from mall_platform_order_items as needed to derive the overall order status and summary fields, but never return orders belonging to another customer.
   *
   * Implement pagination, sorting, and optional search/filter criteria in the request body. Default ordering must be newest first. The summary result must include order number, order date, total price, and derived overall order status only.
   *
   * Reject requests from unauthenticated users. Do not leak existence of other customers' orders in empty, filtered, or paginated responses. Use the existing order model's preserved values for historical display, and compute overall status consistently with the order history summary rules.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IMallPlatformOrder.IRequest,
  ): Promise<IPageIMallPlatformOrder.ISummary> {
    try {
      return await patchMallPlatformCustomerOrdersHistory({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full details of one order from the customer’s order history.
   *
   * This endpoint lets an authenticated customer open a specific order from the history list and inspect the complete purchase record, including the order number, total price, overall status, shipping destination, purchased items, and shipment information. It is intended for order history review, delivery tracking, and post-purchase support.
   *
   * The returned order data must remain consistent with the preserved purchase-time records. Item-level details should reflect the associated order item records and their snapshots so the customer can see the product name, variant, quantity, price, and item status exactly as captured when the order was placed. Shipment data should include the items assigned to each shipment and the tracking information stored for that shipment.
   *
   * Only the owning customer may access this resource. If the order does not exist or does not belong to the current customer, the service should return an authorization-safe not found response. The operation must not expose other customers’ order history, even when the identifier is valid.
   *
   * @param connection
   * @param orderId Order identifier within the customer’s own order history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Fetch the order by primary order identifier and verify that the authenticated customer owns it before returning any data.
   * Use a single order query joined with order items, order item snapshots, shipment records, shipment items, and shipping address data as needed to assemble the full detail view. Preserve and return the stored purchase-time snapshots for order items so product name, variant, seller profile, and item pricing remain historically accurate even if source entities changed later.
   *
   * Apply customer ownership filtering at the database or service layer; do not reveal whether an order exists for another customer. If no matching order is found for the current customer, return a not-found style response. Ensure read-only behavior with no side effects and no history mutation.
   *
   * Include related shipment information grouped by shipment, with the items included in each shipment and their tracking fields. Use the preserved shipping address attached to the order record. Handle orders with multiple sellers and mixed item statuses by returning all associated items and derived order status as stored or computed from the order record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrder> {
    try {
      return await getMallPlatformCustomerOrdersHistoryOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
