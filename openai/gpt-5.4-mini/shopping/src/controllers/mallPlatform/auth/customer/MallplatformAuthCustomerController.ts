import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformCustomer } from "../../../../api/structures/IMallPlatformCustomer";
import { postMallPlatformAuthCustomerJoin } from "../../../../providers/postMallPlatformAuthCustomerJoin";
import { postMallPlatformAuthCustomerLogin } from "../../../../providers/postMallPlatformAuthCustomerLogin";
import { postMallPlatformAuthCustomerRefresh } from "../../../../providers/postMallPlatformAuthCustomerRefresh";

@Controller("/mallPlatform/auth/customer")
export class MallplatformAuthCustomerController {
  /**
   * Register a new customer account and issue authentication tokens.
   *
   * This operation creates a new customer identity in the marketplace so the user can access customer features that require authentication. The submitted email and password are used to create the account, and the system returns token credentials for immediate sign-in.
   *
   * The account is stored in the customer actor table, and the resulting authentication state is returned as an authorized payload. Duplicate email addresses and invalid credential values are rejected to preserve account uniqueness and security.
   *
   * Use this endpoint as the first step in the customer authentication workflow before accessing shopping, order, wishlist, cart, or profile features.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials used to create a new account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Create a customer account by validating the submitted email and password against the customer registration rules, ensuring the email is unique in mall_platform_customers and that the password meets the platform's credential policy. On success, create the customer record and any required session/auth state in a single transactional flow, then return freshly issued access and refresh tokens in the authorized response. Reject duplicate emails, invalid credential formats, and any persistence failures with appropriate 4xx or 5xx errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformCustomer.IJoin,
  ): Promise<IMallPlatformCustomer.IAuthorized> {
    try {
      return await postMallPlatformAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing customer and issue tokens.
   *
   * This operation verifies the customer's email and password and returns authentication tokens for accessing customer-only features. It is the standard sign-in entry point for shopper accounts.
   *
   * The login flow should respect account status controls stored in the customer table, including blocked or otherwise ineligible accounts. The response contains the authorized authentication payload used by the client to continue the session.
   *
   * Use this endpoint together with registration and refresh to manage the customer authentication lifecycle.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials used to authenticate an existing account.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the submitted email and password against mall_platform_customers. Confirm that the account exists, is active, and is not blocked by account status rules before issuing new tokens. If the credentials are invalid or the account is disabled, return an authentication error without revealing which part failed. On success, create or rotate the customer session/auth state as required by the token service and return the new authorized payload.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformCustomer.ILogin,
  ): Promise<IMallPlatformCustomer.IAuthorized> {
    try {
      return await postMallPlatformAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew a customer's authentication tokens.
   *
   * This operation exchanges a valid refresh token for a new authorized token set so the customer can remain signed in without re-entering credentials. It supports the stateless JWT authentication lifecycle for shopper accounts.
   *
   * The refresh flow depends on the customer session records used by the authentication system. Invalid, expired, or revoked tokens are rejected to prevent session misuse.
   *
   * Use this endpoint when the client needs to silently continue a customer session after access token expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer refresh token payload used to renew authentication.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the provided refresh token for the customer session flow, confirm it is not expired or revoked, and issue a new access token pair. The operation should bind the token to the customer session records in mall_platform_customer_sessions as needed by the implementation. If the refresh token is invalid, expired, or does not belong to the customer, return an authorization error and do not issue new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformCustomer.IRefresh,
  ): Promise<IMallPlatformCustomer.IAuthorized> {
    try {
      return await postMallPlatformAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
