import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformCustomer } from "../../../../api/structures/IMallPlatformCustomer";
import { postMallPlatformAuthCustomerJoin } from "../../../../providers/postMallPlatformAuthCustomerJoin";
import { postMallPlatformAuthCustomerLogin } from "../../../../providers/postMallPlatformAuthCustomerLogin";
import { postMallPlatformAuthCustomerRefresh } from "../../../../providers/postMallPlatformAuthCustomerRefresh";

@Controller("/mallPlatform/auth/customer")
export class MallplatformAuthCustomerController {
  /**
   * Register a new customer account and return authorization tokens.
   *
   * This operation creates the customer authentication record for a shopper who must sign up before using the platform. It is the entry point for the customer account lifecycle and leads directly into the authenticated shopping experience.
   *
   * The request must provide valid registration credentials. If the email is already registered or the input is invalid, the service must return a validation or authentication error. On success, the response returns the authorized customer payload used for immediate access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials for creating a new account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate customer registration credentials, create a new customer account, and issue authorization tokens on success. Reject duplicate email addresses, malformed emails, weak passwords, and any account-state conflicts that would prevent onboarding.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformCustomer.IJoin,
  ): Promise<IMallPlatformCustomer.IAuthorized> {
    try {
      return await postMallPlatformAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Log in an existing customer and return authorization tokens.
   *
   * This operation validates the shopper's identity using the stored customer credentials and starts an authenticated session for marketplace use. It supports the required sign-in flow for all customer actions.
   *
   * Invalid credentials, unknown accounts, and blocked accounts must be rejected with authentication errors. A successful login returns the same authorized payload structure used by registration and refresh.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials used to authenticate an existing account.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Verify the customer's email and password against the customer authentication record. Deny access for missing accounts, invalid passwords, or blocked account states. Issue fresh authorization tokens on success without modifying profile or commerce data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformCustomer.ILogin,
  ): Promise<IMallPlatformCustomer.IAuthorized> {
    try {
      return await postMallPlatformAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh a customer's authorization tokens.
   *
   * This operation lets a signed-in customer continue using the platform without re-entering credentials. It is part of the customer authentication lifecycle and produces a fresh authorized payload when the refresh token remains valid.
   *
   * If the refresh token is invalid, expired, or not associated with an active customer session, the request must fail with an authentication error. Successful refresh returns the same authorized structure used by login and registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer refresh token used to obtain a new authorization pair.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the provided refresh token and confirm it belongs to a valid customer session or token lifecycle. Reject expired, revoked, malformed, or mismatched tokens. Issue a new authorization pair on success without changing customer account data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformCustomer.IRefresh,
  ): Promise<IMallPlatformCustomer.IAuthorized> {
    try {
      return await postMallPlatformAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
