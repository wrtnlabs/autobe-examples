import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformAdministrator } from "../../../../api/structures/IMallPlatformAdministrator";
import { postMallPlatformAuthAdministratorJoin } from "../../../../providers/postMallPlatformAuthAdministratorJoin";
import { postMallPlatformAuthAdministratorLogin } from "../../../../providers/postMallPlatformAuthAdministratorLogin";
import { postMallPlatformAuthAdministratorRefresh } from "../../../../providers/postMallPlatformAuthAdministratorRefresh";

@Controller("/mallPlatform/auth/administrator")
export class MallplatformAuthAdministratorController {
  /**
   * Register a new administrator account and return authorization tokens.
   *
   * This endpoint creates an administrator sign-in account from the submitted registration credentials and returns the standard authorized payload after successful account creation. It is the entry point for provisioning a new privileged administrator identity in the mall platform.
   *
   * The request must satisfy the administrator registration rules, and the response contains the authorized token set used by the application after sign-up. If the account already exists or the submitted data is invalid, the request is rejected without creating a partial account record.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials used to create a new administrator account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement administrator registration by validating the submitted credentials, ensuring the administrator identifier is unique, storing the password as a secure hash, and creating a new administrator account record when registration is permitted. After successful creation, issue the standard authorization tokens and return them in the authorized payload. Reject duplicate identifiers, malformed input, and any account-creation policy violations without creating partial records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformAdministrator.IJoin,
  ): Promise<IMallPlatformAdministrator.IAuthorized> {
    try {
      return await postMallPlatformAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing administrator account and return authorization tokens.
   *
   * This endpoint validates administrator credentials against the stored account record and issues a new authorized token set when the credentials are correct. It is the standard sign-in operation for the administrator actor.
   *
   * If the identifier or password is invalid, or if the administrator account is not allowed to sign in, the request is rejected. Successful authentication returns the standard authorized DTO used throughout the mall platform authentication flow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator sign-in credentials used to validate the account and create an authenticated session.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement administrator login by locating the administrator account using the submitted identifier, verifying the password against the stored hash, and confirming the account is eligible to sign in. Reject banned, suspended, or otherwise restricted administrator accounts according to account status rules. On success, issue a new authorization token payload and return it to the client. Use a generic authentication failure response for invalid credentials to avoid account enumeration.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformAdministrator.ILogin,
  ): Promise<IMallPlatformAdministrator.IAuthorized> {
    try {
      return await postMallPlatformAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an administrator's authentication tokens.
   *
   * This endpoint exchanges a valid administrator refresh token for a new authorized token payload. It is used to continue an authenticated session without requiring the administrator to log in again.
   *
   * The request is rejected when the refresh token is expired, invalid, revoked, or not associated with a valid administrator session. A successful refresh returns the standard authorized DTO for the administrator actor.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator refresh-token request used to obtain a new authorized token payload.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Implement administrator token refresh by validating the submitted refresh token, confirming that it belongs to a valid administrator session, and issuing a new token pair. Reject expired, revoked, malformed, or mismatched refresh tokens. Rotate the refresh token if the session policy requires it, and preserve the administrator identity and claims in the newly issued authorization payload. Do not accept access tokens in place of refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformAdministrator.IRefresh,
  ): Promise<IMallPlatformAdministrator.IAuthorized> {
    try {
      return await postMallPlatformAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
