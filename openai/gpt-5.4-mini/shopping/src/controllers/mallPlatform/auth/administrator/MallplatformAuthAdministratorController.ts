import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformAdministrator } from "../../../../api/structures/IMallPlatformAdministrator";
import { postMallPlatformAuthAdministratorJoin } from "../../../../providers/postMallPlatformAuthAdministratorJoin";
import { postMallPlatformAuthAdministratorLogin } from "../../../../providers/postMallPlatformAuthAdministratorLogin";
import { postMallPlatformAuthAdministratorRefresh } from "../../../../providers/postMallPlatformAuthAdministratorRefresh";

@Controller("/mallPlatform/auth/administrator")
export class MallplatformAuthAdministratorController {
  /**
   * Register a new administrator account and return authentication tokens.
   *
   * This endpoint creates a new administrator identity for the mall platform and returns the authorized token payload on success. It is the registration entry point for administrator accounts when the system allows creating them.
   *
   * If the request fails validation or conflicts with an existing administrator account, the endpoint must return an appropriate client error. On success, the response contains the administrator's authorization payload for subsequent authenticated requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator registration credentials.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate administrator registration input, create the administrator account record, and issue authorized tokens when registration succeeds. Enforce uniqueness and password validation, and return a client error for invalid or conflicting credentials.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformAdministrator.IJoin,
  ): Promise<IMallPlatformAdministrator.IAuthorized> {
    try {
      return await postMallPlatformAuthAdministratorJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an administrator with email and password and return tokens.
   *
   * This endpoint verifies the administrator's credentials and produces the authorized token payload on success. It is the standard sign-in flow for administrator users.
   *
   * If the credentials are invalid or the account is blocked from access, the endpoint must fail with an authentication or authorization error. A successful response returns the token pair needed for subsequent authenticated requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate administrator login credentials against the administrator account store, verify that the account is allowed to sign in, and issue authorized tokens. Reject invalid credentials and account states that block access, such as bans or other sign-in restrictions.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformAdministrator.ILogin,
  ): Promise<IMallPlatformAdministrator.IAuthorized> {
    try {
      return await postMallPlatformAuthAdministratorLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an administrator session and return new authentication tokens.
   *
   * This endpoint renews administrator access when the client presents a valid refresh token. It is used to continue an existing session without requiring the administrator to sign in again.
   *
   * If the refresh token is expired, invalid, or no longer associated with a valid administrator session, the endpoint must fail with an authentication error. On success, the response contains a fresh authorized token payload.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator refresh token payload.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate the administrator refresh token, confirm it is still usable for the administrator session, and issue a new authorized token payload. Reject expired, revoked, malformed, or otherwise invalid refresh tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformAdministrator.IRefresh,
  ): Promise<IMallPlatformAdministrator.IAuthorized> {
    try {
      return await postMallPlatformAuthAdministratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
