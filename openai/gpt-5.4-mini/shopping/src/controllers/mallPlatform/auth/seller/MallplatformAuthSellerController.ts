import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformSeller } from "../../../../api/structures/IMallPlatformSeller";
import { postMallPlatformAuthSellerJoin } from "../../../../providers/postMallPlatformAuthSellerJoin";
import { postMallPlatformAuthSellerLogin } from "../../../../providers/postMallPlatformAuthSellerLogin";
import { postMallPlatformAuthSellerRefresh } from "../../../../providers/postMallPlatformAuthSellerRefresh";

@Controller("/mallPlatform/auth/seller")
export class MallplatformAuthSellerController {
  /**
   * Register a new seller account with email and password.
   *
   * This operation creates the seller's authentication identity for the marketplace and starts the merchant onboarding flow. It returns the standard authorized token response immediately after a successful registration so the seller can continue into seller-specific features.
   *
   * The server must validate credential format and uniqueness before creating the account. If the email is already in use or the payload is invalid, the operation fails with a client error.
   *
   * The response uses the platform's standard authorized format for authenticated seller access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration payload containing the credentials required to create a new seller account.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate seller registration credentials, create
     *   the seller account record, and return a newly issued authenticated
     *   token set. The service must reject duplicate emails, malformed
     *   passwords, and any account state that makes registration invalid.
     *   Registration should not depend on approval workflow state beyond
     *   creating the seller identity; seller approval is handled by separate
     *   business processes.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformSeller.IJoin,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Sign in an existing seller account with email and password.
   *
   * This operation validates seller credentials and returns the authenticated token pair used for subsequent seller API calls. It is intended for merchants who already have an account and need access to seller operations such as product management, inventory updates, order processing, and shop profile management.
   *
   * If the seller account is banned or otherwise not permitted to sign in, the operation fails even when the credentials are correct. Invalid credentials also fail with an authentication error.
   *
   * On success, the response provides the seller's authorization data in the standard authorized format used across the platform.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login payload containing the credentials required to authenticate an existing seller account.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Verify seller login credentials against the
     *   stored seller account data and issue a fresh authenticated token set on
     *   success. Reject unknown emails, invalid passwords, banned accounts, and
     *   any seller account that is not eligible to sign in according to current
     *   moderation state. Keep authentication failures generic to avoid
     *   revealing whether the account exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformSeller.ILogin,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew the seller's authentication tokens using a valid refresh token.
   *
   * This operation keeps an authenticated seller session alive without requiring the seller to re-enter their password. It uses the seller session and account state to determine whether the refresh token is still valid and whether the seller is still eligible to access the platform.
   *
   * Expired, revoked, malformed, or account-mismatched refresh tokens are rejected. If the seller account can no longer sign in because of account status restrictions, token renewal fails as well.
   *
   * When successful, the operation returns a new authorized response so the seller can continue using authenticated endpoints without interruption.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller refresh payload containing the refresh token used to obtain a new authenticated session.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate the seller refresh token, confirm that
     *   it belongs to an active seller session, and issue renewed tokens
     *   according to the platform's token rotation policy. Reject expired,
     *   revoked, malformed, or account-mismatched refresh tokens. If the seller
     *   account has been banned or otherwise invalidated, token renewal must
     *   fail even if the token is otherwise structurally valid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformSeller.IRefresh,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
