import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformSeller } from "../../../../api/structures/IMallPlatformSeller";
import { postMallPlatformAuthSellerJoin } from "../../../../providers/postMallPlatformAuthSellerJoin";
import { postMallPlatformAuthSellerLogin } from "../../../../providers/postMallPlatformAuthSellerLogin";
import { postMallPlatformAuthSellerRefresh } from "../../../../providers/postMallPlatformAuthSellerRefresh";

@Controller("/mallPlatform/auth/seller")
export class MallplatformAuthSellerController {
  /**
   * Register a new seller account with email and password.
   *
   * This operation creates the authentication identity for a merchant account and starts the seller onboarding flow. It is the first step for a seller to gain access to seller-only features.
   *
   * The request body uses the seller join DTO. On success, the server returns the authorized seller token payload. If the email is already registered or the credentials are invalid, the request must fail with an appropriate validation or conflict error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials for creating a new merchant account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate seller registration credentials, create a new seller authentication record, securely hash the password, and return authorized tokens after successful account creation. Reject duplicate emails and invalid credentials. The implementation must not assume approval is granted by registration; approval lifecycle is handled separately from authentication.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformSeller.IJoin,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Log in an existing seller account with email and password.
   *
   * This operation authenticates a merchant who already has a seller account and wants to start a signed-in session. It is the normal sign-in step after registration and any approval workflow.
   *
   * The request body contains the seller login DTO. If credentials are valid and the account is allowed to sign in, the server returns the authorized seller token payload. Authentication failures must not reveal whether the email address exists or the password was wrong.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials for authenticating an existing merchant account.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Authenticate the seller by verifying the submitted credentials against the seller account store and issuing authorized tokens on success. Use secure password comparison and avoid leaking whether the email or password was incorrect. Deny access for accounts that are blocked from sign-in by account status or moderation rules before tokens are issued.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformSeller.ILogin,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew a seller's authentication tokens using a refresh token.
   *
   * This operation keeps a seller session active without requiring the merchant to sign in again with email and password. It is part of the standard token renewal flow for the seller actor.
   *
   * The request body uses the seller refresh DTO. When the refresh token is valid and tied to an active seller session, the server returns a new authorized token payload. Invalid or expired tokens must be rejected.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller refresh token payload used to obtain new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate the seller refresh token, ensure it is unexpired and tied to a valid seller session, and issue a new authorized token set. Reject malformed, expired, revoked, or otherwise invalid refresh tokens. Do not require the password again when the refresh token is valid.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformSeller.IRefresh,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
