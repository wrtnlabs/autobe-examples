import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformSeller } from "../../../../api/structures/IMallPlatformSeller";
import { postMallPlatformAuthSellerJoin } from "../../../../providers/postMallPlatformAuthSellerJoin";
import { postMallPlatformAuthSellerLogin } from "../../../../providers/postMallPlatformAuthSellerLogin";
import { postMallPlatformAuthSellerRefresh } from "../../../../providers/postMallPlatformAuthSellerRefresh";

@Controller("/mallPlatform/auth/seller")
export class MallplatformAuthSellerController {
  /**
   * Register a new seller account using email and password credentials.
   *
   * This operation creates the authenticated merchant identity for the marketplace seller actor. It is the entry point for sellers who need to manage products, variants, inventory, shop profile data, and order fulfillment after approval. The request body must follow the seller join contract exactly, and the response returns the authorized token payload defined for the seller actor.
   *
   * The operation must enforce uniqueness of the seller email and validate the credential format before any account record is created. If the platform uses seller approval status during onboarding, the implementation should initialize that state consistently so the seller can later sign in according to the account lifecycle rules. Authentication tokens should only be issued after successful persistence of the account creation flow.
   *
   * Any duplicate email, invalid credential format, or failed onboarding persistence must return a clear error response without creating a partial account.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate seller registration credentials, ensure the email is not already in use by any existing seller account, and create the seller account record with its initial authentication state. If the domain requires an approval workflow, create or link the corresponding seller approval request so the new account can be tracked through pending review. Return the authorized token payload only after the account is successfully created and the initial auth/session state is established. Reject malformed email addresses, weak passwords, and duplicate registrations with clear validation errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformSeller.IJoin,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing seller account with email and password.
   *
   * This operation is used by merchant users who already have a seller account and need to access seller-only functionality such as product management, inventory updates, shipment processing, and response handling for cancellation or refund requests. The request body must match the seller login contract exactly, and the response returns the seller authorized token payload.
   *
   * The implementation must respect seller account lifecycle restrictions and deny access to accounts that are not allowed to sign in. Credential failures should be handled safely and consistently so that the response does not disclose sensitive account existence details. When authentication succeeds, the caller receives the tokens required for subsequent seller-authenticated requests.
   *
   * This endpoint is part of the standard seller authentication workflow alongside registration and token refresh.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Verify the seller's email and password against the seller account store, reject banned or otherwise ineligible accounts, and issue a new authenticated token set when credentials are valid. The implementation should compare the supplied password against the stored credential hash and enforce any account status restrictions before issuing tokens. Invalid credentials must not reveal whether the email exists. Successful login should update or create the seller session state if the platform stores refresh/session metadata.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMallPlatformSeller.ILogin,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew seller authentication tokens using a valid refresh credential.
   *
   * This operation exists so authenticated sellers can continue using the platform without signing in again after access token expiration. It returns the same authorized seller token payload used by login and registration, enabling uninterrupted access to seller-specific features such as catalog management, inventory history, and order workflow handling.
   *
   * The request body must follow the seller refresh contract exactly. The server must verify that the token is still active and belongs to the seller actor before issuing a new authorization response. If refresh-token rotation or session tracking is enabled, the old credential should be invalidated as part of the refresh process to preserve account security.
   *
   * Expired, revoked, malformed, or otherwise invalid refresh tokens must be rejected with an authentication error.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller token refresh credentials.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Accept a seller refresh token, validate its integrity, expiry, and revocation state, then issue a fresh access token pair when the token is still valid. The implementation should consult the seller session or refresh-token persistence layer if present, and reject expired, revoked, or malformed refresh tokens. A refresh request must not require a password, only a valid refresh credential. If rotation is used, invalidate the previous refresh token atomically after minting the new one.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMallPlatformSeller.IRefresh,
  ): Promise<IMallPlatformSeller.IAuthorized> {
    try {
      return await postMallPlatformAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
