import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../api/structures/IMallPlatformReview";
import { getMallPlatformReviewsReviewId } from "../../../providers/getMallPlatformReviewsReviewId";

@Controller("/mallPlatform/reviews/:reviewId")
export class MallplatformReviewsController {
  /**
   * Return a single review with its linked purchase and product context.
   *
   * This endpoint retrieves one review by identifier so clients can display the review detail, including the star rating and optional written content. The review is tied to a specific customer, order item, and product, which supports product detail pages, ownership validation, and dispute review.
   *
   * Only the review owner and administrators should be able to access this resource when privacy rules apply. If the review has been deleted, the historical record may still exist in storage, but clients must respect its active state and display rules. A missing identifier should produce a not-found response.
   *
   * @param connection
   * @param reviewId Unique identifier of the review in global scope.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query mall_platform_reviews by primary key and load the related customer, order item, and product references required for the detail response. Enforce access control so the owning customer can read their own review and administrators can read any review. Preserve deleted review records as historical data, but do not expose snapshot history here; snapshots are handled by the review snapshot subsystem. Return not found when the review id does not exist or is not accessible.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformReview> {
    try {
      return await getMallPlatformReviewsReviewId({
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
