import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCategory } from "../../../../api/structures/IMallPlatformCategory";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteMallPlatformAdministratorCategoriesCategoryId } from "../../../../providers/deleteMallPlatformAdministratorCategoriesCategoryId";
import { postMallPlatformAdministratorCategories } from "../../../../providers/postMallPlatformAdministratorCategories";
import { putMallPlatformAdministratorCategoriesCategoryId } from "../../../../providers/putMallPlatformAdministratorCategoriesCategoryId";

@Controller("/mallPlatform/administrator/categories")
export class MallplatformAdministratorCategoriesController {
  /**
   * Create a new marketplace category or direct subcategory.
   *
   * This operation lets an administrator add a category record used to organize products across the platform. Categories are centrally managed and visible to customers for browsing, while the system enforces the one-level nesting rule so a subcategory can belong only to a top-level category.
   *
   * Only administrators may call this endpoint. If the request attempts to create an invalid hierarchy, such as a deeper nested subcategory or a structurally inconsistent parent-child relationship, the request must be rejected and no category data should be persisted. The created category becomes immediately available for product assignment and category browsing once validation succeeds.
   *
   * @param connection
   * @param body Category details to create, including the category name, description, and optional parent category reference when creating a direct subcategory.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Insert a new row into mall_platform_categories after validating administrator privileges and category structure rules. Validate the category name and description against the category rules, and if a parent reference is provided, ensure it points to an existing top-level category so only one level of nesting is possible. Reject any attempt to create deeper nesting or an inconsistent parent-child structure before writing to the database. If the schema supports a parent category foreign key, persist it; otherwise, create a top-level category only. Return the created category entity after commit. Use a transaction if additional integrity checks are required. Surface authorization failures as forbidden, missing parent or category references as not found, and structural violations as validation errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformCategory.ICreate,
  ): Promise<IMallPlatformCategory> {
    try {
      return await postMallPlatformAdministratorCategories({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing marketplace category.
   *
   * Administrators use this operation to change a category's name or description while preserving the platform's one-level category hierarchy. Categories are part of the browsing structure for products, so any update must keep the hierarchy valid and must not introduce deeper nesting.
   *
   * This operation is restricted to administrators. If the category does not exist, the server should return not found. If the requested change would violate the category structure rules, the server should reject the request with a validation error before saving any changes.
   *
   * @param connection
   * @param categoryId The category identifier (UUID) of the category to update.
   * @param body Category fields to update, including the category name, description, and any permitted hierarchy-related fields supported by the category update model.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Authenticate the caller as an administrator before processing the request. Load the category by category_id and return 404 if it does not exist.
   *
   * Validate the update payload against the category rules. The category may be updated for its editable fields, and any hierarchy-related values must preserve the one-level nesting rule. A subcategory must never be converted into a deeper descendant structure, and any invalid parent-child assignment must be rejected before persistence.
   *
   * Apply the change in a transaction and return the updated category record. No product rows are directly modified by this endpoint, but category changes must remain consistent for browsing and product assignment. Return validation errors for malformed input and 404 for missing categories.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformCategory.IUpdate,
  ): Promise<IMallPlatformCategory> {
    try {
      return await putMallPlatformAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a category that is managed by administrators.
   *
   * This operation removes the category from the taxonomy used for browsing and organization. Products that were assigned to the deleted category must remain available and become uncategorized, so product browsing is preserved even after the category record is removed.
   *
   * Only administrators may call this endpoint. Customers and sellers must be rejected. If the category does not exist, return a not-found error. If deleting the category would violate the validated one-level subcategory structure rules, reject the request before any data is changed.
   *
   * Because this action affects catalog organization, the service should ensure category listings no longer include the deleted category after the transaction completes.
   *
   * @param connection
   * @param categoryId The category identifier to delete (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Verify the caller is an administrator before performing any database changes. Load the target category by its ID and confirm it exists.
   *
   * Perform the deletion in a transaction. Remove the category record, then update all products that reference the deleted category so they no longer point to the removed taxonomy entry and are treated as uncategorized by browsing queries. Do not delete the products themselves, and do not alter product snapshots or other historical records.
   *
   * If the category has dependent subcategory structure or any deletion would violate the one-level nesting constraints, abort without mutating data and return a validation error. If the category is missing, return 404. If the caller lacks permission, return 403.
   *
   * Return no body on success, since clients can refresh category lists and product listings to reflect the deletion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMallPlatformAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
