import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCategory } from "../../../../api/structures/IMallPlatformCategory";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { deleteMallPlatformAdministratorCategoriesCategoryId } from "../../../../providers/deleteMallPlatformAdministratorCategoriesCategoryId";
import { postMallPlatformAdministratorCategories } from "../../../../providers/postMallPlatformAdministratorCategories";
import { putMallPlatformAdministratorCategoriesCategoryId } from "../../../../providers/putMallPlatformAdministratorCategoriesCategoryId";

@Controller("/mallPlatform/administrator/categories")
export class MallplatformAdministratorCategoriesController {
  /**
   * Create a new marketplace category for catalog organization.
   *
   * This operation is reserved for administrators and creates either a top-level category or a direct subcategory. Categories define the central taxonomy used for browsing and product classification across the platform.
   *
   * The service validates the category structure before saving the record. If the request would violate the one-level nesting rule or references a missing parent category, the operation is rejected and no data is created.
   *
   * @param connection
   * @param body Administrator-provided category creation data, including the category name, description, and optional parent category reference for a direct subcategory.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Insert a new row into mall_platform_categories
     *   after confirming the caller is an administrator.
   *
   * Validate the submitted name and description, then validate any optional parent relationship against the category model. A parent may be used only for a direct subcategory; deeper nesting must be rejected. If the parent category does not exist, return not found. If the structure is invalid, return a client validation error.
   *
   * Persist only the category record. Do not modify products directly; products remain associated with categories through their own foreign keys and browsing logic. Return the created entity in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformCategory.ICreate,
  ): Promise<IMallPlatformCategory> {
    try {
      return await postMallPlatformAdministratorCategories({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a marketplace category.
   *
   * Administrators can edit an existing category's name, description, and hierarchy placement within the single-level category structure used for browsing and product organization. Categories support only one level of subcategories, so any change that would create deeper nesting must be rejected.
   *
   * This operation is restricted to administrators. If the category does not exist, the caller is not authorized, or the requested structure would violate the category hierarchy rules, the request must fail with an appropriate error response.
   *
   * @param connection
   * @param categoryId The category identifier in global scope.
   * @param body Editable category fields for updating the category name, description, and any allowed hierarchy reference.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Load the target category by category_id and
     *   verify it exists before applying any changes. Enforce administrator
     *   authorization before attempting the update.
   *
   * Apply only editable fields from the category update DTO and the actual schema. Support updates to category name and description, and if the schema includes a parent reference, validate that the resulting relationship still respects the one-level nesting rule.
   *
   * Reject any update that would create deeper nesting, assign a subcategory beneath another subcategory, or otherwise break the category structure. Perform validation and persistence in a single transaction so partial updates cannot occur.
   *
   * Return 404 when the category does not exist, 403 when the caller is not an administrator, and 400 or 422 when the proposed structure is invalid. On success, return the updated category entity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformCategory.IUpdate,
  ): Promise<IMallPlatformCategory> {
    try {
      return await putMallPlatformAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a category and detach its products from the removed classification.
   *
   * This operation is reserved for administrators. It removes the category record from the marketplace taxonomy while preserving product visibility by making affected products uncategorized instead of removing them from browsing or purchase history.
   *
   * Category deletion must respect the one-level subcategory structure rules and reject invalid structural changes before any data is modified. Deleted categories must no longer appear in customer browsing results, and products previously assigned to the deleted category must remain available through their own product listings and search flows.
   *
   * If the category does not exist, return a not-found error. If the caller is not an administrator, return an authorization error. If the category cannot be removed because of structural constraints, return a validation error.
   *
   * @param connection
   * @param categoryId The identifier of the category to delete.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Look up the category by its identifier and verify
     *   the caller has administrator privileges. If the category is missing,
     *   return a not found error. Before deletion, validate that removing the
     *   category will not violate the one-level category/subcategory structure
     *   rules. Delete the category record permanently. Reassign any products
     *   that reference the deleted category so they become uncategorized,
     *   preserving product records and browse availability. Do not delete
     *   products, variants, orders, reviews, or snapshots as part of this
     *   operation. Return a successful empty response on completion. If the
     *   database enforces foreign keys or cascading behavior, handle it
     *   explicitly so product browsing remains intact after the category row is
     *   removed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMallPlatformAdministratorCategoriesCategoryId({
        administrator,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
