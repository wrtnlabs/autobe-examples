import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReviewSnapshot } from "../../../../../api/structures/IMallPlatformReviewSnapshot";
import { IPageIMallPlatformReviewSnapshot } from "../../../../../api/structures/IPageIMallPlatformReviewSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorReviewsReviewIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformAdministratorReviewsReviewIdSnapshotsSnapshotId";
import { patchMallPlatformAdministratorReviewsReviewIdSnapshots } from "../../../../../providers/patchMallPlatformAdministratorReviewsReviewIdSnapshots";

@Controller("/mallPlatform/administrator/reviews/:reviewId/snapshots")
export class MallplatformAdministratorReviewsSnapshotsController {
  /**
   * List the immutable snapshot history for a specific review.
   *
   * This endpoint returns preserved review snapshots so the review owner and administrators can inspect how the rating, content, and deletion state changed over time. It is intended for dispute resolution and historical review, and every snapshot returned is read-only.
   *
   * Results are scoped to the review identified by `reviewId` and should be ordered by `created_at` descending so the newest change appears first. Because a review may accumulate multiple snapshots, the response is paginated and may be filtered by snapshot action, content, or time range.
   *
   * @param connection
   * @param reviewId Identifier of the review whose snapshot history is being listed.
   * @param body Pagination, search, and sorting criteria for review snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query mall_platform_review_snapshots for rows where mall_platform_review_id equals the provided reviewId. Enforce authorization so only the customer who owns the source review and administrators can read the history.
   *
   * Support pagination, search, and sorting in the request body. Allow filters for snapshot_action, content text, is_deleted, and created_at range, with default ordering by created_at descending. Return summary rows only. If the review does not exist, return not found. If the caller lacks permission, return forbidden. If no snapshots exist, return an empty page.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformReviewSnapshot.IRequest,
  ): Promise<IPageIMallPlatformReviewSnapshot.ISummary> {
    try {
      return await patchMallPlatformAdministratorReviewsReviewIdSnapshots({
        administrator,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one immutable snapshot of a review.
   *
   * This endpoint returns a preserved point-in-time record of a review change for history inspection, dispute resolution, and audit purposes. The snapshot includes the review's preserved rating and text content, the deletion state at the time of capture, the snapshot action, and the owning customer reference.
   *
   * The snapshot is scoped to the parent review and must belong to the review identified in the path. Because review snapshots are immutable preservation records, this endpoint does not support updating or deleting them. If the review or snapshot does not exist, or if the snapshot does not belong to the specified review, the request should return not found.
   *
   * @param connection
   * @param reviewId The review identifier that scopes the snapshot within a specific review history.
   * @param snapshotId The review snapshot identifier within the specified review history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load one row from mall_platform_review_snapshots using both id = snapshotId and mall_platform_review_id = reviewId. If the snapshot does not match the requested review, return not found to avoid leaking cross-review history. Return the immutable fields id, mall_platform_review_id, mall_platform_customer_id, snapshot_action, rating, content, is_deleted, and created_at. Do not attempt any mutation, and do not join mutable review state unless needed for authorization or existence checks. Preserve the immutability guarantee by exposing this as a read-only detail operation only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformReviewSnapshot> {
    try {
      return await getMallPlatformAdministratorReviewsReviewIdSnapshotsSnapshotId(
        {
          administrator,
          reviewId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
