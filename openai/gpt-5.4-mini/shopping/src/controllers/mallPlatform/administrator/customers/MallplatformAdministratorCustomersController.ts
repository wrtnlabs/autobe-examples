import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformCustomer } from "../../../../api/structures/IMallPlatformCustomer";
import { IPageIMallPlatformCustomer } from "../../../../api/structures/IPageIMallPlatformCustomer";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorCustomersCustomerId } from "../../../../providers/getMallPlatformAdministratorCustomersCustomerId";
import { patchMallPlatformAdministratorCustomers } from "../../../../providers/patchMallPlatformAdministratorCustomers";

@Controller("/mallPlatform/administrator/customers")
export class MallplatformAdministratorCustomersController {
  /**
   * Search and list customer accounts with pagination and filtering.
   *
   * This endpoint provides a paginated customer account directory for administrative browsing and user management. It is intended for finding registered customers by account criteria such as status or identity-related search terms, while keeping authentication credentials and session data out of the response.
   *
   * The result set should respect the requested pagination and sorting options, and empty searches should return an empty page rather than an error. This operation supports platform oversight workflows only and does not permit anonymous access to customer data.
   *
   * @param connection
   * @param body Search criteria for filtering, sorting, and paginating customer accounts.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the mall_platform_customers table as a paginated search endpoint.
   * Apply filtering and sorting from the request body against customer account fields that are available in the schema, and return summary rows only.
   * Do not include passwords, reset tokens, or session records in the response.
   * Use stable pagination ordering so repeated searches with the same criteria yield consistent results.
   * If no customers match the filters, return an empty page.
   * If the request contains invalid pagination or unsupported filter values, reject it before running the query.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformCustomer.IRequest,
  ): Promise<IPageIMallPlatformCustomer.ISummary> {
    try {
      return await patchMallPlatformAdministratorCustomers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single customer account and its current profile information.
   *
   * This endpoint returns the customer account identified by customerId together with the associated customer profile when one exists. It is intended for account detail views and administrative inspection workflows, and it must not include unrelated customer-owned resources such as carts, wishlists, orders, addresses, or sessions.
   *
   * The service must confirm that the target customer account exists and that the caller is allowed to view it under the platform's access rules. If the account cannot be found, return a not-found error. If the caller lacks permission, return a forbidden error. If the profile row is absent because it was removed or has not been created yet, return the customer account data without fabricating profile fields.
   *
   * @param connection
   * @param customerId The unique identifier of the customer account to retrieve (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the customer account by its UUID primary identifier and, if present, join the related customer profile in the same read path. Treat this as a read-only lookup: do not mutate any tables and do not assemble data from other customer-owned aggregates.
   *
   * Use mall_platform_customers as the primary source and mall_platform_customer_profiles as the optional related source. Return only actual stored fields from those schemas. If the profile does not exist, the account should still be returned. If the customer does not exist, return not found. Enforce authorization according to actor rules so regular customers can only view their own account while administrators may inspect customer accounts according to moderation policy.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("customerId")
    customerId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformCustomer> {
    try {
      return await getMallPlatformAdministratorCustomersCustomerId({
        administrator,
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
