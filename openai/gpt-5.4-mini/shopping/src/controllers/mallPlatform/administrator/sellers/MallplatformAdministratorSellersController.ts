import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformSeller } from "../../../../api/structures/IMallPlatformSeller";
import { IPageIMallPlatformSeller } from "../../../../api/structures/IPageIMallPlatformSeller";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorSellersSellerId } from "../../../../providers/getMallPlatformAdministratorSellersSellerId";
import { patchMallPlatformAdministratorSellers } from "../../../../providers/patchMallPlatformAdministratorSellers";

@Controller("/mallPlatform/administrator/sellers")
export class MallplatformAdministratorSellersController {
  /**
   * Retrieve a paginated list of seller accounts for administrative browsing and moderation.
   *
   * This endpoint returns seller account summaries so administrators can review registration outcomes, current account state, and onboarding progress across the platform. It is intended for searching and filtering seller identities by email, approval state, suspension state, deletion state, and creation time, using the seller account records as the source of truth.
   *
   * The list is paginated and sorted for operational review workflows. Results should reflect the current seller account lifecycle fields, including approval status, rejection reason, suspension timestamp, and deletion timestamp. When records are filtered by a state that is no longer available, the response should simply omit them from the result set rather than fabricate alternate records.
   *
   * @param connection
   * @param body Search, filter, pagination, and sorting criteria for seller account browsing.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query mall_platform_sellers with pagination, keyword filtering, and sort controls.
   * Support filtering by email, approval/status state, suspension state, deletion state, and created_at range.
   * Use the unique email index and the status/created_at index for efficient search when applicable.
   * Return seller summaries only; do not expose password hashes.
   * Include rejection_reason, suspended_at, and deleted_at in the summary data when needed for moderation views.
   * Apply stable sorting with a deterministic secondary sort by primary key to avoid duplicate or missing rows across pages.
   * If the request contains invalid pagination or unsupported sort values, reject it with validation error before querying the database.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformSeller.IRequest,
  ): Promise<IPageIMallPlatformSeller.ISummary> {
    try {
      return await patchMallPlatformAdministratorSellers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller account and its public shop profile by seller ID.
   *
   * This operation returns the current seller identity used for marketplace access control together with the public shop presentation data shown to customers. The seller account includes the current approval state and, when relevant, the rejection reason so the UI can present the correct registration status.
   *
   * The linked seller profile provides the shop name, shop description, and logo image reference. Password hashes, sessions, and other internal authentication data are not exposed. If the seller does not exist or is not accessible, the service must return a not-found error.
   *
   * @param connection
   * @param sellerId Seller account ID in UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the seller account by UUID primary key from mall_platform_seller_accounts.
   * Join or separately load the related mall_platform_seller_profiles row through the one-to-one relationship on seller_account_id.
   * Return the seller account fields needed for read views together with the public profile fields.
   * Do not expose password_hash, and do not include session, reset-token, or other auth tables.
   * If the seller is missing, return 404. If the seller account exists but the profile row is absent, the operation may still succeed with a null profile only if the response schema supports it; otherwise treat it as a data integrity error.
   * Use the account's approval_status and rejection_reason exactly as stored so consumers can show pending, approved, or rejected status correctly.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformSeller> {
    try {
      return await getMallPlatformAdministratorSellersSellerId({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
