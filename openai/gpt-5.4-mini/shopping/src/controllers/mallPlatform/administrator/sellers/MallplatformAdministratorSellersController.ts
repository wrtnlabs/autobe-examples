import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformSeller } from "../../../../api/structures/IMallPlatformSeller";
import { IPageIMallPlatformSeller } from "../../../../api/structures/IPageIMallPlatformSeller";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorSellersSellerId } from "../../../../providers/getMallPlatformAdministratorSellersSellerId";
import { patchMallPlatformAdministratorSellers } from "../../../../providers/patchMallPlatformAdministratorSellers";

@Controller("/mallPlatform/administrator/sellers")
export class MallplatformAdministratorSellersController {
  /**
   * Search and page through seller accounts.
   *
   * This operation returns a paginated list of seller summaries for administrative review and platform browsing use cases. It is intended for filtering by seller state and related search criteria, not for retrieving a single seller record.
   *
   * The response contains summary data only, so clients can render list screens without loading the full seller account entity. Results should respect the current seller lifecycle state and any access-control rules applied by the service layer, including unavailable states such as banned or otherwise restricted accounts.
   *
   * Validation and error handling should reject malformed pagination or filter input, and return a not-found style error only when the requested page or scoped data cannot be resolved by the service logic.
   *
   * @param connection
   * @param body Search, pagination, and sorting criteria for seller list browsing.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Query the mall_platform_sellers collection with
     *   pagination, search, and sorting. Apply the request body criteria to
     *   filter by seller account state and any supported textual search fields
     *   exposed by the seller listing use case. Sort deterministically and
     *   return a paginated result set of seller summaries.
   *
   * The implementation should not expose password credentials or session data. Include only list-safe fields from the seller account and any directly related summary data needed for browsing. If seller approval status or availability is represented in related tables, join only the fields needed for list presentation. Ensure unavailable seller states are handled according to business rules, and do not silently include records that the current actor is not permitted to see.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformSeller.IRequest,
  ): Promise<IPageIMallPlatformSeller.ISummary> {
    try {
      return await patchMallPlatformAdministratorSellers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a seller account and its linked shop profile by seller ID.
   *
   * This endpoint returns the seller’s current account state together with the public shop information owned by that seller account. It is suitable for seller profile pages, administrative review screens, and other detail views that need the seller’s approval status and rejection reason when present.
   *
   * The seller account is identified by its UUID primary key. The response should reflect the current live seller account record and the associated seller profile if it exists. If the seller account cannot be found, return a not found error. If the seller has been deleted or is otherwise unavailable, the response should follow the platform’s standard access and lifecycle error handling.
   *
   * @param connection
   * @param sellerId Seller account identifier (UUID primary key).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor administrator
     * @x-autobe-specification Load the seller account by its UUID primary key
     *   from mall_platform_seller_accounts and join the optional
     *   mall_platform_seller_profiles relation to include public shop data.
     *   Return the current account fields including email, approval status,
     *   rejection reason, suspended_at, deleted_at, created_at, and updated_at,
     *   plus the linked seller profile when present.
   *
   * Do not expose password_hash. Preserve the current lifecycle state exactly as stored; do not infer approval from related tables. If the record does not exist, return 404. If the caller is not permitted to view the seller, return the platform’s standard authorization error. When the related profile is missing, return the seller record with a null or absent profile component according to the response schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformSeller> {
    try {
      return await getMallPlatformAdministratorSellersSellerId({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
