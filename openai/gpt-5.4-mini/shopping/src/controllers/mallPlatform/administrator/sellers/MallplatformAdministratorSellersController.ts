import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformSeller } from "../../../../api/structures/IMallPlatformSeller";
import { IPageIMallPlatformSeller } from "../../../../api/structures/IPageIMallPlatformSeller";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorSellersSellerId } from "../../../../providers/getMallPlatformAdministratorSellersSellerId";
import { patchMallPlatformAdministratorSellers } from "../../../../providers/patchMallPlatformAdministratorSellers";

@Controller("/mallPlatform/administrator/sellers")
export class MallplatformAdministratorSellersController {
  /**
   * Search and paginate seller accounts.
   *
   * This endpoint provides a filtered seller list for moderation and administrative browsing. It is designed to surface seller identity, approval state, rejection information, and lifecycle visibility without exposing authentication secrets.
   *
   * Use this operation when a client needs to browse sellers by status, creation time, or other supported list criteria. The implementation must respect account visibility rules, return stable paginated results, and reject invalid pagination, search, or sort inputs. Password hashes must never be included in the response.
   *
   * @param connection
   * @param body Seller search criteria including pagination, keyword search, status filters, and sort options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the mall_platform_sellers table for browseable seller accounts.
   * Apply search and filters against email, status, rejection_reason, created_at, updated_at, and deleted_at visibility according to the request schema and authorization context. Support sorting and pagination for large result sets, defaulting to newest-first when no sort is provided.
   * Return summary rows only and never expose password_hash. Include moderation fields such as status and rejection_reason so administrators can distinguish pending, approved, rejected, suspended, and banned sellers. Validate unsupported filter values, malformed pagination, and unknown sort keys with standard input errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformSeller.IRequest,
  ): Promise<IPageIMallPlatformSeller.ISummary> {
    try {
      return await patchMallPlatformAdministratorSellers({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one seller account together with its public shop profile.
   *
   * This endpoint returns the merchant account used across the marketplace and the public profile information shown to customers on seller pages and product pages. It is useful for profile display, order-history context, and administrative review because it exposes the current seller status and public shop identity in one read.
   *
   * The seller account represents the merchant identity, while the related shop profile contains the editable branding data such as shop name, description, and logo. If the seller is pending, approved, or rejected, clients can use the returned status to render that state, and they can display the rejection reason when the approval workflow has one. If the seller does not exist, the service must return a not-found response.
   *
   * @param connection
   * @param sellerId The seller account identifier in UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the seller account by sellerId and join the associated public seller profile for presentation. Return the seller entity with its current approval/status information and any public profile fields needed by the UI. Do not include password hashes, sessions, reset tokens, or other authentication artifacts. If the seller is missing, return 404. If the current actor is not permitted to view the seller, return 403. This operation must be read-only and must not modify seller approval, profile, suspension, or snapshot data. If historical shop identity is needed for order history, it should be sourced from preserved snapshots rather than the live profile record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformSeller> {
    try {
      return await getMallPlatformAdministratorSellersSellerId({
        administrator,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
