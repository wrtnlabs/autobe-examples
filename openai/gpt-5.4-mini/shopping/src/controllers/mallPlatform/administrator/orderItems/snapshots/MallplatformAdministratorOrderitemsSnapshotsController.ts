import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrderItemSnapshot } from "../../../../../api/structures/IMallPlatformOrderItemSnapshot";
import { IPageIMallPlatformOrderItemSnapshot } from "../../../../../api/structures/IPageIMallPlatformOrderItemSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorOrderItemsOrderItemIdSnapshotsOrderItemSnapshotId } from "../../../../../providers/getMallPlatformAdministratorOrderItemsOrderItemIdSnapshotsOrderItemSnapshotId";
import { patchMallPlatformAdministratorOrderItemsOrderItemIdSnapshots } from "../../../../../providers/patchMallPlatformAdministratorOrderItemsOrderItemIdSnapshots";

@Controller("/mallPlatform/administrator/orderItems/:orderItemId/snapshots")
export class MallplatformAdministratorOrderitemsSnapshotsController {
  /**
   * Retrieve the immutable snapshot history for a single order item.
   *
   * This endpoint returns preserved historical records for the specified order item so the customer, the seller, and administrators can review how the item changed over time. The snapshots are read-only and remain available for audit and dispute resolution even if the source order item or related active records are later removed.
   *
   * The request is scoped by the order item identifier in the path. Clients can page through the history and sort the results to inspect the sequence of preserved states without changing any stored data.
   *
   * @param connection
   * @param orderItemId The order item identifier whose snapshot history is being requested.
   * @param body Search, pagination, and sorting criteria for the order item snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the order item snapshot records filtered by orderItemId, then apply pagination, sorting, and any allowed search criteria supplied in the request body. Return newest-first ordering by default unless the request explicitly specifies another sort order.
   *
   * Never modify snapshot rows because they are immutable. If the order item does not exist, return a not-found error. If the authenticated user is not allowed to view snapshots for this order item, return a forbidden error. If there are no snapshots, return an empty page. Include the preserved summary data needed for historical review, but do not attempt to reconstruct or alter active order item state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformOrderItemSnapshot.IRequest,
  ): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
    try {
      return await patchMallPlatformAdministratorOrderItemsOrderItemIdSnapshots(
        {
          administrator,
          orderItemId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one immutable order item snapshot for historical purchase review.
   *
   * This endpoint returns the preserved state of an order item at the time the snapshot was created. It is used for order history, dispute resolution, and reconstruction of the original purchase context even if the live order item, product, variant, or seller profile has changed or been deleted later.
   *
   * The snapshot cannot be modified or deleted through this API. Access should be restricted to users who are allowed to inspect preserved order history, including the purchasing customer, the selling party, and administrators. If the specified order item does not exist, the snapshot does not exist, or the snapshot does not belong to the specified order item, the service should return not found.
   *
   * @param connection
   * @param orderItemId The order item identifier that scopes the snapshot to its parent order item.
   * @param orderItemSnapshotId The snapshot identifier within the specified order item scope.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Validate the parent order item ID and snapshot ID together so the snapshot is only returned when it belongs to the requested order item. Use a single read path that joins or otherwise verifies the parent-child relationship before returning data.
   *
   * Return the full immutable snapshot record, including preserved purchase context and any normalized child data required by the snapshot model, such as stored option rows. Do not recompute snapshot values from current product or seller data. Do not allow updates or deletes through this endpoint. If the snapshot is missing or mismatched to the parent order item, return not found. Enforce the platform's access rules for preserved order history before returning the record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemSnapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedParam("orderItemSnapshotId")
    orderItemSnapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrderItemSnapshot> {
    try {
      return await getMallPlatformAdministratorOrderItemsOrderItemIdSnapshotsOrderItemSnapshotId(
        {
          administrator,
          orderItemId,
          orderItemSnapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
