import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductSnapshot } from "../../../../api/structures/IMallPlatformProductSnapshot";
import { IPageIMallPlatformProductSnapshot } from "../../../../api/structures/IPageIMallPlatformProductSnapshot";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorProductSnapshotsProductSnapshotId } from "../../../../providers/getMallPlatformAdministratorProductSnapshotsProductSnapshotId";
import { patchMallPlatformAdministratorProductSnapshots } from "../../../../providers/patchMallPlatformAdministratorProductSnapshots";

@Controller("/mallPlatform/administrator/productSnapshots")
export class MallplatformAdministratorProductsnapshotsController {
  /**
   * Browse immutable product snapshots with pagination and filtering.
   *
   * This endpoint returns preserved product history records for review, audit, and dispute resolution. Each snapshot represents the state of a product at a point in time, including the product fields that were captured when a change succeeded. Because snapshots are immutable, this operation is read-only and does not modify any product, variant, or image data.
   *
   * Access is intended for administrators and other authorized viewers who need to inspect historical product state, including the preserved product presentation and variant context captured in the snapshot. If the requested page exceeds the available history, an empty page is returned. If filters do not match any records, the response contains no items rather than an error.
   *
   * @param connection
   * @param body Pagination, sorting, and snapshot-history filters for browsing immutable product snapshot records.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query mall_platform_product_snapshots as the root data set and apply pagination, sorting, and snapshot-history filters from the request body. Return a paginated list of snapshot summaries ordered by the requested sort, defaulting to the most recently created snapshot records first.
   *
   * Support filtering by product identity and any snapshot-history criteria defined in the request DTO. If the implementation needs to expose related snapshot details, join or hydrate the preserved product snapshot relations only for summary-safe fields; do not attempt to reconstruct mutable current product state. Keep the operation read-only and never create, update, or delete snapshot rows because snapshot records are immutable by business rule.
   *
   * When no records match, return an empty page. When the requested page is beyond the available data, still return a valid page object with zero items. Do not infer deleted-current-product state as a failure, because historical snapshot records remain available even after the live product changes or is removed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformProductSnapshot.IRequest,
  ): Promise<IPageIMallPlatformProductSnapshot.ISummary> {
    try {
      return await patchMallPlatformAdministratorProductSnapshots({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single immutable product snapshot by its identifier.
   *
   * This endpoint returns the preserved historical state of a product at the moment the snapshot was created, including the product data and its related snapshot content for images and variants. It is intended for audit review, historical inspection, and dispute resolution, and it never mutates the stored snapshot.
   *
   * Access should be limited to the owning seller of the original product and administrators. If the snapshot does not exist, the service should return a not-found response. Because snapshots are immutable records, the response must reflect exactly what was stored when the snapshot was created and must not recalculate current product data.
   *
   * @param connection
   * @param productSnapshotId The product snapshot identifier to retrieve (UUID).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the product snapshot row by productSnapshotId and return the full immutable snapshot record.
   * Include the preserved nested snapshot data needed to reconstruct the product's historical presentation, especially the image history and variant-state history captured with the snapshot.
   *
   * Authorize access for the owning seller of the original product and administrators only. If the identifier is invalid or no snapshot exists, return not found. If the caller is not permitted to view the snapshot, return forbidden.
   *
   * Do not read from the live products or product_variants tables to compose historical state. The snapshot itself is the source of truth, and no mutation is allowed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productSnapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productSnapshotId")
    productSnapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProductSnapshot> {
    try {
      return await getMallPlatformAdministratorProductSnapshotsProductSnapshotId(
        {
          administrator,
          productSnapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
