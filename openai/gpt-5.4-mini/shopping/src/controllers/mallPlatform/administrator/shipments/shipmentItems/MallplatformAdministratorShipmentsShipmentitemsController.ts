import { patchMallPlatformAdministratorShipmentsShipmentIdShipmentItems } from "../../../../../providers/patchMallPlatformAdministratorShipmentsShipmentIdShipmentItems";

@Controller("/mallPlatform/administrator/shipments/:shipmentId/shipmentItems")
export class MallplatformAdministratorShipmentsShipmentitemsController {
  /**
   * Update the order items assigned to a shipment.
   *
   * This endpoint lets a seller revise which eligible order items are grouped into an existing shipment. A shipment may contain one or more order items, but all items must belong to the same seller, and items from different sellers cannot be combined into one shipment.
   *
   * The update is validated as an all-or-nothing change. If any requested item is already assigned to another active shipment, is not eligible for shipping, or belongs to a different seller, the entire request is rejected and no changes are applied. If the shipment has already been completed or is otherwise unavailable, the request fails without modifying any associations.
   *
   * The response returns the updated shipment item list so clients can refresh the shipment details and keep the tracking view in sync with the persisted shipment composition.
   *
   * @param connection
   * @param shipmentId The shipment identifier whose item composition will be updated.
   * @param body The desired order-item composition for the target shipment. Provide the order items that should remain grouped in this shipment after the update.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the target shipment by shipmentId and verify it exists and is still editable. Use the shipment's seller ownership to validate every requested item.
   *
   * Ensure that every requested order item belongs to the same seller as the shipment, is still in a ship-ready state, and is not already committed to another active shipment. Reject the entire request if any item fails validation. Do not partially apply the update.
   *
   * Perform the association changes inside a transaction. Remove shipment-item links that are no longer requested and create links for newly requested items. Prevent updates when the shipment is already completed or unavailable.
   *
   * Return the refreshed shipment item page after persistence so downstream clients can render the updated package composition immediately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformShipmentItem.IUpdate,
  ): Promise<IPageIMallPlatformShipmentItem.ISummary> {
    try {
      return await patchMallPlatformAdministratorShipmentsShipmentIdShipmentItems(
        {
          administrator,
          shipmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one shipment item within a specific shipment.
   *
   * This operation returns the association record that links a shipment to one order item. It is intended for shipment detail pages and tracking views where the client needs to confirm which purchased item belongs to the selected seller-specific package.
   *
   * The lookup is strictly scoped by both the shipment and shipment-item identifiers. If the record does not exist, belongs to another shipment, or has been removed, the request must return a not-found response.
   *
   * @param connection
   * @param shipmentId The shipment identifier that scopes the shipment-item lookup.
   * @param shipmentItemId The shipment-item identifier within the specified shipment.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the shipment-item row by UUID and verify that mall_platform_shipment_items.mall_platform_shipment_id matches the shipmentId path parameter. This prevents cross-shipment access and keeps the endpoint aligned with the seller-specific shipment grouping rules.
   *
   * Return the shipment-item entity only. Do not update shipment status, order item status, inventory, or tracking information. If the record is missing or does not belong to the specified shipment, return not found. Respect logical deletion by excluding rows with deleted_at when the application treats them as unavailable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentItemId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("shipmentItemId")
    shipmentItemId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformShipmentItem> {
    try {
      return await getMallPlatformAdministratorShipmentsShipmentIdShipmentItemsShipmentItemId(
        {
          administrator,
          shipmentId,
          shipmentItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Removes one order item from a shipment.
   *
   * This operation deletes the junction record that links a shipment to an order item, so the shipment can be adjusted without deleting the shipment itself or the purchased order item.
   *
   * The server must confirm that the shipment-item association belongs to the requested shipment, that the caller is allowed to modify the shipment, and that the shipment is still available for shipping actions. Completed shipments are unavailable for further shipping actions, so their shipment-item links cannot be removed. If the link does not exist, the request must fail with a not-found error. The deletion must be atomic to keep the shipment package and its item membership consistent.
   *
   * @param connection
   * @param shipmentId The shipment identifier (UUID scope) for the seller-specific package.
   * @param shipmentItemId The shipment-item association identifier (UUID scope) to remove from that shipment.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the mall_platform_shipment_items row by shipmentItemId and verify that mall_platform_shipment_id equals shipmentId. If the row is missing or belongs to another shipment, return not-found.
   *
   * Before deleting, check the parent shipment record in mall_platform_shipments. Reject the mutation when the shipment is completed or otherwise unavailable for shipping actions. Enforce authorization so only the owning seller or an administrator can remove items from the shipment, according to platform access rules.
   *
   * Perform the delete on mall_platform_shipment_items only. Do not delete the shipment, the order item, or any order data. If business logic requires recalculating shipment completeness after removing the last item, do so inside the same transaction. Keep the operation idempotent only in the sense that a missing association should still return not-found rather than silently succeeding.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":shipmentItemId")
  public async erase(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedParam("shipmentItemId")
    shipmentItemId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMallPlatformAdministratorShipmentsShipmentIdShipmentItemsShipmentItemId(
        {
          administrator,
          shipmentId,
          shipmentItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
