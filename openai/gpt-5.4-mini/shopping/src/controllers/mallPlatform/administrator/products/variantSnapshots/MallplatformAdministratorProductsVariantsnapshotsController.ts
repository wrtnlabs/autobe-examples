import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductVariantSnapshot } from "../../../../../api/structures/IMallPlatformProductVariantSnapshot";
import { IPageIMallPlatformProductVariantSnapshot } from "../../../../../api/structures/IPageIMallPlatformProductVariantSnapshot";
