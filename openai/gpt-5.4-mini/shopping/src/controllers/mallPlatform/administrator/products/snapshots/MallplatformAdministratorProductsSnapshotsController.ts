import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductSnapshot } from "../../../../../api/structures/IMallPlatformProductSnapshot";
import { IPageIMallPlatformProductSnapshot } from "../../../../../api/structures/IPageIMallPlatformProductSnapshot";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformAdministratorProductsProductIdSnapshotsSnapshotId";
import { patchMallPlatformAdministratorProductsProductIdSnapshots } from "../../../../../providers/patchMallPlatformAdministratorProductsProductIdSnapshots";

@Controller("/mallPlatform/administrator/products/:productId/snapshots")
export class MallplatformAdministratorProductsSnapshotsController {
  /**
   * Retrieve a paginated history of preserved snapshots for a product.
   *
   * This operation returns immutable snapshot records that capture the product’s prior state whenever the product or its images were edited. The history is intended for the product owner and administrators so they can review how the product looked at a specific point in time, including its editable fields, images, and variant state captured in each snapshot.
   *
   * Snapshots are preserved even if the active product is later deleted. The endpoint is useful for dispute resolution, historical inspection, and audit review. If the product does not exist or the caller is not allowed to view its history, the request must be rejected.
   *
   * @param connection
   * @param productId The identifier of the product whose snapshot history will be listed.
   * @param body Pagination and optional search criteria for browsing a product's snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the target product by productId and verify that it exists. Enforce access control so only the owning seller and administrators can view the snapshot history.
   *
   * Query the product snapshot data for the requested product, ordering newest snapshots first. Apply pagination and any supported search or filter criteria from the request body. Do not include mutable product data directly from the live product record when a snapshot record exists; return the historical snapshot rows instead.
   *
   * Because snapshots are immutable, this endpoint must be read-only and must never create, update, or delete snapshot records. If the product has been deleted, continue to return preserved snapshots when the caller is authorized. Return a paginated summary response suitable for list screens, with snapshot identity, created time, and high-level change information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformProductSnapshot.IRequest,
  ): Promise<IPageIMallPlatformProductSnapshot.ISummary> {
    try {
      return await patchMallPlatformAdministratorProductsProductIdSnapshots({
        administrator,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a preserved snapshot of a product at a specific point in time.
   *
   * This operation returns the immutable historical record for one snapshot belonging to the specified product. The snapshot preserves the product's name, description, category label, base price, main image location, image count, variant count, and creation time so that the product's prior state can be inspected later for dispute resolution or audit review.
   *
   * The snapshot remains available even if the live product has been deleted. Access is intended for the product owner and administrators, and the server should verify that the requested snapshot belongs to the requested product before returning it. If the product or snapshot does not exist, or if the snapshot does not belong to the product, the request must fail with a not-found style error.
   *
   * @param connection
   * @param productId Identifier of the product whose snapshot is being retrieved.
   * @param snapshotId Identifier of the snapshot to retrieve within the specified product.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the snapshot row by snapshotId and ensure mall_platform_product_id matches productId. Return the immutable snapshot record directly from mall_platform_product_snapshots; do not join mutable product state for the historical values because the snapshot already stores the preserved fields. Enforce access control so only the owning seller of the product and administrators can read the snapshot. If the product was deleted, still allow access as long as the snapshot row exists. Return a not-found error when either identifier is invalid, when the snapshot does not belong to the product, or when the caller is unauthorized to view the record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProductSnapshot> {
    try {
      return await getMallPlatformAdministratorProductsProductIdSnapshotsSnapshotId(
        {
          administrator,
          productId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
