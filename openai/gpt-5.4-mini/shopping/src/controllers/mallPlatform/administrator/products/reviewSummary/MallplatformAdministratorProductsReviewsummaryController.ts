import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductReview } from "../../../../../api/structures/IMallPlatformProductReview";
import { AdministratorAuth } from "../../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorProductsProductIdReviewSummary } from "../../../../../providers/getMallPlatformAdministratorProductsProductIdReviewSummary";

@Controller("/mallPlatform/administrator/products/:productId/reviewSummary")
export class MallplatformAdministratorProductsReviewsummaryController {
  /**
   * Returns the review summary for a product.
   *
   * This endpoint supports product detail pages by providing the aggregate review information needed to display product reputation, including the average rating and total review count, without loading the full list of reviews.
   *
   * Only active reviews should be counted in the summary. If the product has no active reviews, the endpoint should still return a valid summary with zero counts or equivalent empty-state values defined by the response schema. If the product does not exist, the service must return a not-found error.
   *
   * @param connection
   * @param productId The product identifier (UUID) for the product whose review summary is being requested.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the product by product_id and verify that it exists before computing any aggregate values.
   *
   * Query mall_platform_reviews for the requested product and include only reviews that are still active. Exclude deleted reviews from both the average rating calculation and the review count so the returned data matches the public product detail page behavior.
   *
   * Return a single summary object only; do not include the full review list. This operation must not mutate products, reviews, or snapshot records. If no active reviews exist, return a valid empty summary instead of an error. If the product is missing, return a not-found response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProductReview> {
    try {
      return await getMallPlatformAdministratorProductsProductIdReviewSummary({
        administrator,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
