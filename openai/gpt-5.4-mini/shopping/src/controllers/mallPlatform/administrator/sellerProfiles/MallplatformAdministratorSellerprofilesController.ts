import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformSellerProfile } from "../../../../api/structures/IMallPlatformSellerProfile";
import { IPageIMallPlatformSellerProfile } from "../../../../api/structures/IPageIMallPlatformSellerProfile";
import { AdministratorAuth } from "../../../../decorators/AdministratorAuth";
import { AdministratorPayload } from "../../../../decorators/payload/AdministratorPayload";
import { getMallPlatformAdministratorSellerProfilesSellerProfileId } from "../../../../providers/getMallPlatformAdministratorSellerProfilesSellerProfileId";
import { patchMallPlatformAdministratorSellerProfiles } from "../../../../providers/patchMallPlatformAdministratorSellerProfiles";

@Controller("/mallPlatform/administrator/sellerProfiles")
export class MallplatformAdministratorSellerprofilesController {
  /**
   * Retrieve a paginated list of seller profiles for browsing and selection.
   *
   * This endpoint returns the current public-facing shop profile data for sellers, including the shop name, shop description, and logo image URI that customers see on storefront pages. It is intended for search and browse scenarios where clients need to display seller identities and navigate to individual seller profile pages.
   *
   * The response reflects the live seller profile records owned by seller accounts. Consumers should use the returned summaries for listing views only; profile editing is handled by the seller-owned update endpoint, and historical changes are preserved separately in seller profile snapshots for dispute review and audit purposes.
   *
   * If filters, sorting, or pagination are invalid, the request must be rejected. Deleted seller profiles must not appear in normal browse results.
   *
   * @param connection
   * @param body Search, filtering, sorting, and pagination criteria for seller profile browsing.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Query the mall_platform_seller_profiles table for current, non-deleted seller profile records.
   * Support paginated search, text filtering, and sorting according to the seller profile browsing rules.
   * Return summary fields suitable for list rendering: seller profile identity, shop name, shop description, and logo image URI, while excluding snapshot/history data.
   * Apply deleted_at filtering so logically deleted profiles are not included in browse results.
   * Use a stable ordering for pagination and ensure the search remains consistent across pages. Validate request parameters for page bounds, sort fields, and search constraints; reject invalid requests with a validation error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedBody()
    body: IMallPlatformSellerProfile.IRequest,
  ): Promise<IPageIMallPlatformSellerProfile.ISummary> {
    try {
      return await patchMallPlatformAdministratorSellerProfiles({
        administrator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single seller profile by its identifier.
   *
   * This operation returns the public storefront identity for one seller, including the shop name, shop description, and logo image that customers see when browsing products or opening a seller page. The data supports a consistent merchant presentation across catalog browsing, product detail pages, and historical order context.
   *
   * The seller profile is the customer-visible identity of a seller account, so this read operation should expose the current profile state only. If the seller profile is unavailable or the identifier does not match an existing record, the service should return a not-found response. Access control should ensure that only authorized customers, sellers, and administrators can read the profile according to the platform’s visibility rules.
   *
   * @param connection
   * @param sellerProfileId The seller profile identifier (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor administrator
   * @x-autobe-specification Load the seller profile by primary identifier and return the complete current profile entity. Query the seller profile table by sellerProfileId, including the fields needed to render public storefront information: shop name, shop description, and logo image reference.
   *
   * If the record does not exist, return a not-found error. Do not fabricate fallback data. If the profile is linked to a seller account that is unavailable under business rules, still return the profile only if the platform’s visibility rules allow historical or public viewing; otherwise reject with the appropriate authorization or availability error.
   *
   * This endpoint is read-only and must not modify seller profile data or create snapshots. Snapshot creation belongs to update operations only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerProfileId")
  public async at(
    @AdministratorAuth()
    administrator: AdministratorPayload,
    @TypedParam("sellerProfileId")
    sellerProfileId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformSellerProfile> {
    try {
      return await getMallPlatformAdministratorSellerProfilesSellerProfileId({
        administrator,
        sellerProfileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
