import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../../api/structures/IMallPlatformReview";
import { IPageIMallPlatformReview } from "../../../../api/structures/IPageIMallPlatformReview";
import { patchMallPlatformProductsProductIdReviews } from "../../../../providers/patchMallPlatformProductsProductIdReviews";

@Controller("/mallPlatform/products/:productId/reviews")
export class MallplatformProductsReviewsController {
  /**
   * Lists the active public reviews for a product, ordered by newest first.
   *
   * This endpoint scopes review browsing to a single product and returns the review feed that appears on the product detail page. Reviews are purchase-based feedback from customers, so the data is intended for public reputation display rather than private account management.
   *
   * The response is paginated because a product may accumulate many reviews. Deleted reviews must be excluded from the active listing and from any visible count used by the product detail page. The service should preserve the newest-first browsing rule so the latest feedback appears first.
   *
   * @param connection
   * @param productId The UUID of the product whose public reviews should be listed.
   * @param body Review list criteria including pagination and any supported sort or filter options for the requested product.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Validate that the product exists, then query mall_platform_reviews for rows matching the product id. Exclude rows with a deleted_at value so only active reviews are returned. Sort by created_at descending to satisfy the newest-first display requirement. Apply pagination and any supported list filters from the request body according to the platform browsing rules. If customer display data is needed for the summary DTO, join the owning customer only for public-safe fields. Return a paginated summary response suitable for the product detail page. If the product does not exist, return the standard not-found error. Do not expose deleted review rows in this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformReview.IRequest,
  ): Promise<IPageIMallPlatformReview.ISummary> {
    try {
      return await patchMallPlatformProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
