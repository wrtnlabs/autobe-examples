import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReview } from "../../../../api/structures/IMallPlatformReview";
import { IPageIMallPlatformReview } from "../../../../api/structures/IPageIMallPlatformReview";
import { patchMallPlatformProductsProductIdReviews } from "../../../../providers/patchMallPlatformProductsProductIdReviews";

@Controller("/mallPlatform/products/:productId/reviews")
export class MallplatformProductsReviewsController {
  /**
   * List the public reviews for a specific product.
   *
   * This endpoint returns the review feed shown on the product detail page. Results are restricted to the product identified in the path, ordered by newest first, and paginated so the client can render a stable review section even when the product has many reviews.
   *
   * The returned reviews must follow the platform's public review rules. Reviews written by customers whose accounts were later removed must still be shown according to the deleted-user display rule, and deleted reviews must not be included in the active display set or the rating summary. If the product does not exist, the request must fail with a not-found error. If there are no reviews, the endpoint should return an empty page.
   *
   * @param connection
   * @param productId The identifier of the product whose reviews are being requested.
   * @param body Paging, sorting, and optional display criteria for the product review list.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Load the product by productId first and return a not-found error if it does not exist. Query reviews only for that product, apply the active-review filter used by the product detail page, sort by newest first, and then paginate according to the request body.
   *
   * Use the review table as the main source. Preserve the display rule for removed customer accounts so historical feedback remains visible, but do not include deleted reviews in the active list or count. Do not mutate review records or snapshot rows. Return an empty page when the product has no reviews. Ensure the total count in the page response matches the same active review set used for the list items.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformReview.IRequest,
  ): Promise<IPageIMallPlatformReview.ISummary> {
    try {
      return await patchMallPlatformProductsProductIdReviews({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
