import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProduct } from "../../../api/structures/IMallPlatformProduct";
import { IPageIMallPlatformProduct } from "../../../api/structures/IPageIMallPlatformProduct";
import { getMallPlatformProductsProductId } from "../../../providers/getMallPlatformProductsProductId";
import { patchMallPlatformProducts } from "../../../providers/patchMallPlatformProducts";

@Controller("/mallPlatform/products")
export class MallplatformProductsController {
  /**
   * Search and browse marketplace products with pagination, filtering, and sorting.
   *
   * This operation returns customer-visible product listings across all sellers, including the results shown on search pages and category browsing pages. It supports keyword search, category filtering, minimum and maximum price filtering, in-stock-only filtering, and ordering options so clients can build consistent product discovery screens.
   *
   * The response is paginated because product lists can exceed a single page. Products that are deleted or otherwise unavailable for browsing must not appear in the result set. Each summary item should contain the information needed for a listing card, including the main image, seller shop name, pricing summary, and average rating when reviews exist.
   *
   * @param connection
   * @param body Search, filtering, sorting, and pagination criteria for browsing marketplace products.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query mall_platform_products as the root catalog table for browsing.
   * Join related seller profile and product image data needed for customer-facing summaries, and include review aggregation data required for average rating and review count display.
   * Apply keyword search against product name, category filtering, minimum and maximum price filtering, and in-stock-only filtering according to the browsing rules. If the request targets a category that does not exist, reject the request.
   * Support sorting by newest first, price ascending, and price descending. Apply pagination consistently and return a page object containing product summaries only.
   * Exclude products that are deleted, hidden, suspended-seller owned, or otherwise unavailable for customer browsing. If a product has no available variants, it may still be returned only when the request does not require in-stock-only filtering, but its availability must be represented consistently in the summary data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IMallPlatformProduct.IRequest,
  ): Promise<IPageIMallPlatformProduct.ISummary> {
    try {
      return await patchMallPlatformProducts({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get a single product’s current catalog record.
   *
   * This endpoint returns the live product entity used on product detail pages and by administrative oversight workflows. The product is the marketplace’s primary sellable listing, owned by a seller and optionally assigned to a category, so the response reflects the current browsing state of that listing.
   *
   * The returned record includes the product’s stored fields: seller reference, category reference, name, description, base price, and timestamps. Related live data such as images, variants, and reviews may be included by the implementation when assembling the full entity response, but snapshot history is not the primary purpose of this route.
   *
   * If the product does not exist or is no longer available, the operation should return a not-found error. This is a read-only endpoint and must not mutate any data.
   *
   * @param connection
   * @param productId The product identifier in UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query mall_platform_products by id and return the current live record. Validate the path parameter as a UUID and load the product from the active catalog table only; do not read from snapshot tables for this endpoint.
   *
   * Use only actual schema columns: id, seller_account_id, category_id, name, description, base_price, created_at, updated_at, and deleted_at. If the record is missing or deleted, return not found. If the response assembler includes current images, variants, or reviews, it must respect the current live rows and exclude deleted rows according to the application’s read rules.
   *
   * Keep the operation strictly read-only. Do not add pagination, filters, or update behavior to this route because it is a single-entity detail endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":productId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProduct> {
    try {
      return await getMallPlatformProductsProductId({
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
