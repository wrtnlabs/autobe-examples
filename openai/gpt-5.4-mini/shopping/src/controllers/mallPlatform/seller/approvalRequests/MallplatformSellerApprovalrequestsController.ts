import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformAdministratorApprovalRequest } from "../../../../api/structures/IMallPlatformAdministratorApprovalRequest";
import { IPageIMallPlatformAdministratorApprovalRequest } from "../../../../api/structures/IPageIMallPlatformAdministratorApprovalRequest";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerApprovalRequestsApprovalRequestId } from "../../../../providers/getMallPlatformSellerApprovalRequestsApprovalRequestId";
import { patchMallPlatformSellerApprovalRequests } from "../../../../providers/patchMallPlatformSellerApprovalRequests";
import { postMallPlatformSellerApprovalRequests } from "../../../../providers/postMallPlatformSellerApprovalRequests";

@Controller("/mallPlatform/seller/approvalRequests")
export class MallplatformSellerApprovalrequestsController {
  /**
   * Submit a new administrator approval request for governance review.
   *
   * An authenticated customer or seller can use this operation to formally request administrator access by providing a reason. The system creates a pending approval record that preserves the applicant's justification and becomes part of the platform's governance history.
   *
   * The backend derives the applicant from the active session, so the request body does not include an account identifier. The request remains available for super administrator review until it is approved or rejected, and duplicate active requests should be rejected according to the request lifecycle rules.
   *
   * @param connection
   * @param body The information required to submit an administrator approval request, including the applicant's reason for seeking administrator access.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Create a new
     *   mall_platform_administrator_approval_requests row for the currently
     *   authenticated account. Validate that the caller is a logged-in customer
     *   or seller and reject unauthenticated access. Populate the applicant
     *   reference from the session context rather than from the request body.
     *   Persist the submitted reason and initialize the review status as
     *   pending. If business rules prohibit multiple active requests from the
     *   same account, check for an existing pending request and return a
     *   validation error when one already exists. Return the created request
     *   entity after persistence so the client can display its current status.
   *
   * This operation only submits the request. Review decisions, approval, and rejection history are handled by separate governance operations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformAdministratorApprovalRequest.ICreate,
  ): Promise<IMallPlatformAdministratorApprovalRequest> {
    try {
      return await postMallPlatformSellerApprovalRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search administrator approval requests with pagination and review-state filters.
   *
   * This endpoint is intended for administrator oversight of user applications for administrator status. It supports browsing requests by status and other list criteria so reviewers can focus on pending applications while still being able to inspect approved and rejected records.
   *
   * The returned list reflects the approval trail recorded for each request, including the applicant's reason and the request status. Requests remain visible in their current state until they are reviewed, and validation errors should be returned when the requested filters or paging values are invalid.
   *
   * @param connection
   * @param body Search criteria for browsing administrator approval requests, including pagination, sorting, and status filters.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query
     *   mall_platform_administrator_approval_requests with pagination, sorting,
     *   and filter criteria from the request body. Support status filtering for
     *   pending, approved, and rejected requests, with default sorting that
     *   prioritizes newest or pending-first review queues according to the
     *   implemented business rules. Return only summary fields needed for list
     *   review, not the full approval request graph.
   *
   * Do not perform any update in this operation. If the requested filters produce no matches, return an empty page rather than an error. Validate page size, page number, and filter enum values before querying. If a request references a missing or invalid state, reject the request with a validation error. Preserve the current record state exactly as stored; this endpoint is strictly read-only.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformAdministratorApprovalRequest.IRequest,
  ): Promise<IPageIMallPlatformAdministratorApprovalRequest.ISummary> {
    try {
      return await patchMallPlatformSellerApprovalRequests({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves a single administrator approval request for governance review and status tracking.
   *
   * This endpoint returns the current administrator approval request record, including the applicant administrator reference, submitted reason, review status, optional rejection reason, reviewer reference, and review timestamps. It is intended for oversight workflows where a super administrator or privileged reviewer needs to inspect the latest state of one request.
   *
   * Immutable snapshot history is stored separately in the administrator approval request snapshot table and is not included in this response. If the record does not exist, the service should return a not-found error.
   *
   * @param connection
   * @param approvalRequestId The administrator approval request UUID in global scope.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Fetch one row from
     *   mall_platform_administrator_approval_requests by id using the
     *   approvalRequestId UUID path parameter. Return the request's current
     *   fields: id, administrator_id, reviewer_administrator_id, reason,
     *   status, rejection_reason, reviewed_at, created_at, updated_at, and
     *   deleted_at. Do not include snapshot rows in the response; snapshots
     *   belong to a separate historical operation. If the record is missing,
     *   return not found. If retrieval policy treats deleted rows as
     *   inaccessible, honor that policy instead of exposing deleted data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":approvalRequestId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("approvalRequestId")
    approvalRequestId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformAdministratorApprovalRequest> {
    try {
      return await getMallPlatformSellerApprovalRequestsApprovalRequestId({
        seller,
        approvalRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
