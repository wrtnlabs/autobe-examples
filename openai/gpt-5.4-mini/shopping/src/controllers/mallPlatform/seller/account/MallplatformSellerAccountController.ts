import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformCustomer } from "../../../../api/structures/IMallPlatformCustomer";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerAccount } from "../../../../providers/getMallPlatformSellerAccount";
import { patchMallPlatformSellerAccount } from "../../../../providers/patchMallPlatformSellerAccount";

@Controller("/mallPlatform/seller/account")
export class MallplatformSellerAccountController {
  /**
   * Retrieve the currently authenticated customer's account information.
   *
   * This endpoint returns the signed-in customer's own account-level identity and status so the user can confirm which account is active in the platform. It is intended for registered customers only, because guest access is not allowed for customer features.
   *
   * The response supports account-level screens that need to display the customer's login identity and current availability for platform usage. If the account has been deleted or banned, the request must be rejected according to account access rules.
   *
   * This operation does not expose other users' accounts and does not manage authentication sessions or password recovery.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Read the authenticated customer record from the current security context, not from a path parameter.
   * Verify that the requester is a registered customer and that the account is neither deleted nor inaccessible due to ban status.
   * Join the customer account with its profile if the response DTO requires profile summary fields, but do not include session data or password data.
   * Return a not-found or forbidden-style error when the caller is not an authenticated customer or when the account is unavailable.
   * Keep the query read-only and avoid any side effects.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IMallPlatformCustomer> {
    try {
      return await getMallPlatformSellerAccount({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated customer's own account information.
   *
   * This operation allows a registered customer to modify account-owned profile data while preserving the same customer identity and credential protection. The customer must already be authenticated, and guest or anonymous access is not permitted.
   *
   * The update is limited to the customer’s own account scope and must not affect unrelated customer profile records, shipping addresses, orders, or reviews. If a password change is included, the new credential must replace the existing login secret for future sign-in without changing ownership of the account.
   *
   * Validation failures must leave the existing account state unchanged. If the caller is not the account owner, the request must be rejected.
   *
   * @param connection
   * @param body Editable fields for the authenticated customer's own account update, including profile changes and optional credential changes.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the authenticated customer from the current session context and reject the request if no valid customer session exists. Apply a partial update to the current customer's own account-related fields only, using a single transaction so that profile and credential changes succeed or fail together.
   *
   * Allow updates to the customer profile fields that belong to the account owner, especially display name and phone number, and allow password updates only for the current authenticated customer. Do not permit updates to ownership, account status, or any unrelated customer records. Preserve existing shipping addresses, orders, and reviews unchanged.
   *
   * If the password is included, validate the current credential when required by the business layer, hash the new password, and replace the stored credential atomically. If validation fails, return a client error and do not persist any partial data. Return the updated customer account representation after a successful commit.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformCustomer.IUpdate,
  ): Promise<IMallPlatformCustomer> {
    try {
      return await patchMallPlatformSellerAccount({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
