import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformSellerAccount } from "../../../../../api/structures/IMallPlatformSellerAccount";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerAccountStatus } from "../../../../../providers/getMallPlatformSellerAccountStatus";

@Controller("/mallPlatform/seller/account/status")
export class MallplatformSellerAccountStatusController {
  /**
   * Returns the current approval status of the authenticated seller account.
   *
   * This endpoint lets a signed-in seller check whether the account is pending, approved, or rejected. If the account is rejected, the response should include the rejection reason so the seller can understand why approval was denied and whether a new registration request is needed.
   *
   * The approval status is an account-level concern, separate from the public seller profile. Requests without a valid seller session, or requests made by a non-seller identity, must be rejected.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Resolve the current authenticated principal to a seller account and load its current approval status from the seller account record or linked approval workflow state. Return only the seller's own status data. The accepted status values are pending, approved, and rejected. If the status is rejected, include the rejection reason; otherwise return null for the reason if the response model permits it. Reject unauthenticated requests and any request not associated with a seller identity. Do not expose session, password, or unrelated profile fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IMallPlatformSellerAccount> {
    try {
      return await getMallPlatformSellerAccountStatus({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
