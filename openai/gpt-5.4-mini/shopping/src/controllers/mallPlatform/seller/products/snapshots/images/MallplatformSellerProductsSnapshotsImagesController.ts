import typia, { tags } from "typia";

import { IMallPlatformProductSnapshotImage } from "../../../../../../api/structures/IMallPlatformProductSnapshotImage";
import { IPageIMallPlatformProductSnapshotImage } from "../../../../../../api/structures/IPageIMallPlatformProductSnapshotImage";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
