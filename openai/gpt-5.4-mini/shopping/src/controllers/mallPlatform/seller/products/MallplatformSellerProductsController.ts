import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProduct } from "../../../../api/structures/IMallPlatformProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteMallPlatformSellerProductsProductId } from "../../../../providers/deleteMallPlatformSellerProductsProductId";
import { postMallPlatformSellerProducts } from "../../../../providers/postMallPlatformSellerProducts";
import { putMallPlatformSellerProductsProductId } from "../../../../providers/putMallPlatformSellerProductsProductId";

@Controller("/mallPlatform/seller/products")
export class MallplatformSellerProductsController {
  /**
   * Create a new sellable product in the marketplace catalog.
   *
   * This endpoint lets an authenticated seller register a product that customers can discover in search results and category listings. The product becomes owned by the seller account that submits the request, and that seller is responsible for later edits, visibility, and availability.
   *
   * The request must provide the product name, description, category, and base price. The category may be a subcategory, but it must exist and be valid. If the seller is not approved or is otherwise unavailable, or if validation fails, the product must not be created.
   *
   * A new product does not create a prior-state snapshot because snapshots are used to preserve changes to existing records, not initial creation.
   *
   * @param connection
   * @param body Product creation data including the name, description, category, and base price.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Insert a new row into mall_platform_products for the authenticated seller. Validate that the seller account is active and allowed to sell, and reject creation if the seller is banned, suspended, rejected, or otherwise unavailable. Validate that the referenced category exists and can be assigned to a product, including subcategories.
   *
   * Persist only the fields defined by the create DTO. Do not accept client-provided ownership fields, timestamps, or other system-managed values. Do not create a snapshot on insert. If any validation or persistence step fails, roll back the transaction and return an error without partial writes. Return the created product after successful insertion.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformProduct.ICreate,
  ): Promise<IMallPlatformProduct> {
    try {
      return await postMallPlatformSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a seller-owned product and preserve its previous state in a snapshot.
   *
   * This operation modifies the canonical product record, including the product name, description, category assignment, and base price. The selected category may be a subcategory, and the update must keep the product tied to its owning seller.
   *
   * Only the owning seller may perform this update unless an administrator intervenes under platform oversight rules. When the update succeeds, the system must create an immutable product snapshot that preserves the prior product state for audit, dispute review, and historical reconstruction. If validation fails, authorization fails, or the product is unavailable for editing, the product record must remain unchanged and no snapshot should be created.
   *
   * @param connection
   * @param productId The unique identifier of the product to update.
   * @param body The product fields that can be edited by the owning seller or an authorized administrator.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the target product by productId and verify that it exists and is editable. Enforce ownership so that only the seller who owns the product can update it, unless the calling actor has administrator override privileges defined by the platform rules.
   *
   * Validate the incoming fields against the product update contract. Apply updates to the product name, description, category, and base price only. Ensure the referenced category exists and is valid, including subcategories. Do not alter seller ownership through this operation.
   *
   * Before persisting the new product state, create the product snapshot required by the platform snapshot policy so the previous state is preserved. If the database transaction fails, roll back both the product update and the snapshot creation so the prior state remains intact. Return the updated product after the transaction commits. Handle not-found, forbidden, validation, and conflict-style conditions using the platform’s standard error handling.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformProduct.IUpdate,
  ): Promise<IMallPlatformProduct> {
    try {
      return await putMallPlatformSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a product from active marketplace use.
   *
   * This operation removes a product from search results, category listings, and other customer-facing browsing surfaces. It is intended for sellers deleting their own products and for administrators enforcing platform policy.
   *
   * Before deletion, the service must verify that none of the product's variants have pending order items in paid or shipped status, and that none of the variants have pending cancellation requests or refund requests. If any of those conditions are not satisfied, the request must fail and the product must remain unchanged.
   *
   * When deletion succeeds, the product's variants are removed from active use and their inventory records are also removed from active use. Snapshot history must remain preserved so authorized sellers and administrators can review past product states for disputes and audit purposes. Deleting a product must not break order history or historical snapshot references.
   *
   * @param connection
   * @param productId The identifier of the product to delete.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the product by productId and authorize the caller as either the owning seller or an administrator.
   *
   * Reject the request with not found when the product does not exist. Reject with forbidden when the caller is neither the owner nor an administrator with product oversight authority.
   *
   * Before deleting, check all variants of the product for any order items whose status is paid or shipped, and for any pending cancellation or refund requests. If any blocking record exists, reject the request with a business validation error and do not modify the database.
   *
   * If validation passes, delete the product in a transaction together with its variants and any inventory records tied to those variants. The delete should remove them from active use, not from preserved snapshot history tables. After commit, ensure any derived browse/index caches are refreshed so the product no longer appears in search or category listings.
   *
   * Do not attempt to delete or rewrite snapshot tables. Historical snapshots must remain queryable for authorized dispute review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteMallPlatformSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
