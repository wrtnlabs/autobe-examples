import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductImageSnapshot } from "../../../../../api/structures/IMallPlatformProductImageSnapshot";
import { IPageIMallPlatformProductImageSnapshot } from "../../../../../api/structures/IPageIMallPlatformProductImageSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerProductsProductIdImageSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformSellerProductsProductIdImageSnapshotsSnapshotId";
import { patchMallPlatformSellerProductsProductIdImageSnapshots } from "../../../../../providers/patchMallPlatformSellerProductsProductIdImageSnapshots";

@Controller("/mallPlatform/seller/products/:productId/imageSnapshots")
export class MallplatformSellerProductsImagesnapshotsController {
  /**
   * List the historical snapshots for a product's images.
   *
   * This operation returns immutable records that preserve how a product's image set changed over time, including uploads, reordering, and deletions. It is intended for dispute review, audit inspection, and historical reconstruction of product presentation.
   *
   * The history is scoped to one product identified in the path. Only successful image changes appear in the results; failed image operations do not create snapshots and therefore do not appear here. Because image order affects listing presentation, each snapshot should preserve the image ordering and main image state as captured at the time of the successful change.
   *
   * @param connection
   * @param productId The unique identifier of the product whose image snapshot history is being requested.
   * @param body Pagination, filtering, and sorting criteria for browsing a product's image snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Verify that the product exists and that the caller is allowed to view its history under product visibility and role-based access rules. Query the product image snapshot records for the given productId, ordered newest first by default.
   *
   * Use the request body for pagination and any supported filtering or sorting criteria. Return an empty page when no snapshots exist. If the product does not exist, return a not-found error. If the caller is not authorized to view the historical records, return a forbidden error.
   *
   * Do not synthesize snapshot entries from the current image state. Return only snapshots that were created after successful image changes, and preserve the historical ordering and main-image selection recorded in each snapshot.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformProductImageSnapshot.IRequest,
  ): Promise<IPageIMallPlatformProductImageSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerProductsProductIdImageSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one historical image snapshot for a product.
   *
   * This endpoint returns the immutable record of a product image at the moment it was captured, including the image URL, display order, main-image flag, and timestamps. It is intended for seller maintenance review, administrator oversight, and dispute investigation where the exact visual state of a product must be examined.
   *
   * The snapshot is scoped to a single product, so the product identifier and snapshot identifier must refer to the same parent-child relationship in storage. If the product does not exist, the snapshot does not exist, or the snapshot belongs to another product, the request must fail with a not-found error. The operation does not modify data and does not create a new snapshot.
   *
   * @param connection
   * @param productId The UUID of the product whose image snapshot history is being queried.
   * @param snapshotId The UUID of the product image snapshot to retrieve within that product scope.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query mall_platform_product_image_snapshots for a single row using snapshotId and verify that mall_platform_product_id matches productId before returning it. Return the complete snapshot entity with id, mall_platform_product_id, image_url, image_order, is_main, changed_at, created_at, updated_at, and deleted_at.
   *
   * Use a scoped lookup or an equivalent existence check on the parent product to ensure the snapshot cannot be fetched outside its product context. If either identifier is invalid or no matching row exists, return a not-found error. Do not update product images, do not regenerate snapshots, and do not alter history records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProductImageSnapshot> {
    try {
      return await getMallPlatformSellerProductsProductIdImageSnapshotsSnapshotId(
        {
          seller,
          productId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
