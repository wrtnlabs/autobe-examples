import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductSnapshot } from "../../../../../api/structures/IMallPlatformProductSnapshot";
import { IPageIMallPlatformProductSnapshot } from "../../../../../api/structures/IPageIMallPlatformProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformSellerProductsProductIdSnapshotsSnapshotId";
import { patchMallPlatformSellerProductsProductIdSnapshots } from "../../../../../providers/patchMallPlatformSellerProductsProductIdSnapshots";

@Controller("/mallPlatform/seller/products/:productId/snapshots")
export class MallplatformSellerProductsSnapshotsController {
  /**
   * List the preserved snapshot history for a specific product.
   *
   * This endpoint returns immutable product snapshots so the owning seller and administrators can review earlier product states for disputes, policy checks, and historical inspection. Product snapshots remain available even after the active product has been deleted, and each snapshot represents the product state that existed when the snapshot was recorded.
   *
   * The records are scoped to the product identified by `productId`. Access is limited to the product owner and administrators. If the product does not exist or the caller is not authorized to view its history, the request must fail with the appropriate not-found or forbidden response. Snapshot data is read-only and must never be modified through this API.
   *
   * @param connection
   * @param productId The UUID of the product whose snapshot history should be listed.
   * @param body Search and paging criteria for the product snapshot list, including pagination, sorting, and any permitted historical filters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Resolve the product by `productId`, then verify that the caller is either the owning seller or an administrator before querying snapshot history. Read the immutable snapshot rows for that product and return them in descending chronological order, using the snapshot timestamp or stored creation order.
   *
   * Support pagination and any allowed list filters through the request body. Do not expose mutation behavior, and do not attempt to reconstruct historical values from the live product once a snapshot exists; the snapshot table is the source of truth. Preserve access after product deletion, since historical snapshots must remain available for review. Return an empty page when no snapshots exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformProductSnapshot.IRequest,
  ): Promise<IPageIMallPlatformProductSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerProductsProductIdSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one immutable snapshot of a product's preserved historical state.
   *
   * This operation returns the full snapshot record for a specific product, including the product data captured at that moment and the preserved image and variant state required for later dispute review or historical inspection. It is intended for the product owner and administrators, who are allowed to view snapshots even when the active product has already changed or been deleted.
   *
   * The snapshot is scoped by both `productId` and `snapshotId`, and the snapshot must belong to the specified product. If the snapshot does not exist, belongs to another product, or the caller is not authorized to view it, the request must fail with the appropriate not-found or forbidden response according to the platform's access rules. Because snapshots are immutable, this endpoint never modifies data.
   *
   * @param connection
   * @param productId The product identifier that scopes the snapshot lookup.
   * @param snapshotId The snapshot identifier of the preserved product history record.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch the product snapshot by `snapshotId` and verify that it is associated with `productId` before returning it. Read the preserved snapshot record and any related preserved image/variant snapshot rows needed to construct the complete historical view. Do not substitute the current product record; the response must reflect the exact preserved state stored in the snapshot.
   *
   * Authorize access for the owning seller and administrators only. If the active product has been deleted, the snapshot remains retrievable when the caller has permission. The endpoint is strictly read-only and must not create, update, or delete any rows. Return not-found when the snapshot cannot be located or does not belong to the given product, and forbidden when the caller lacks access.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProductSnapshot> {
    try {
      return await getMallPlatformSellerProductsProductIdSnapshotsSnapshotId({
        seller,
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
