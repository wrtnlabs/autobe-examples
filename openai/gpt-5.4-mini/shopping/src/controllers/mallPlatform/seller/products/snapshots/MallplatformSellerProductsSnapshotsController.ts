import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformProductSnapshot } from "../../../../../api/structures/IMallPlatformProductSnapshot";
import { IPageIMallPlatformProductSnapshot } from "../../../../../api/structures/IPageIMallPlatformProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformSellerProductsProductIdSnapshotsSnapshotId";
import { patchMallPlatformSellerProductsProductIdSnapshots } from "../../../../../providers/patchMallPlatformSellerProductsProductIdSnapshots";

@Controller("/mallPlatform/seller/products/:productId/snapshots")
export class MallplatformSellerProductsSnapshotsController {
  /**
   * Returns the preserved snapshot history for a specific product.
   *
   * This operation lists immutable product snapshot records that capture previous product states, including the product's fields and related image and variant state as preserved by the snapshot rules. It is intended for the product owner and administrators to review historical changes, compare prior states, and inspect dispute-related records even if the active product has been deleted.
   *
   * The snapshots are read-only records and are never modified by this operation. Results should be paginated and sorted so users can browse long histories efficiently. If the product does not exist or the caller is not allowed to view the product's snapshot history, the request must be rejected. If the product has been deleted, any preserved snapshots must still be returned when access is permitted.
   *
   * @param connection
   * @param productId The product identifier whose snapshot history is being requested.
   * @param body Search and pagination criteria for browsing product snapshot history.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Load the target product by product_id and verify
     *   that it exists or that historical snapshots are still allowed to be
     *   read after deletion. Enforce access control so only the product owner
     *   seller and administrators can browse this history. Query the product
     *   snapshot table by product_id, order records by snapshot timestamp
     *   descending unless the request specifies another supported sort order,
     *   and apply pagination and any allowed filters from the request body.
     *   Include related preserved image and variant snapshot data if the
     *   summary contract requires it, but do not mutate any data. Return a
     *   paginated collection of snapshot summaries. If the product is missing
     *   and no preserved snapshots exist, return a not-found error. If the
     *   caller lacks permission, return a forbidden error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformProductSnapshot.IRequest,
  ): Promise<IPageIMallPlatformProductSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerProductsProductIdSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one immutable snapshot for a specific product.
   *
   * This operation returns the preserved historical state of a product, including the product data captured at the time the snapshot was created. It is used for dispute review, historical inspection, and policy enforcement by the product owner seller and administrators.
   *
   * The snapshot remains available even if the active product has been edited or deleted. If the snapshot is not associated with the specified product, or if the caller is not authorized to view it, the service must respond with not found or forbidden according to the platform's access rules.
   *
   * @param connection
   * @param productId The product identifier that scopes the snapshot in the path.
   * @param snapshotId The snapshot identifier within the specified product scope.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Load the product snapshot identified by
     *   snapshotId within the product identified by productId. Verify that the
     *   snapshot belongs to the given product before returning data.
   *
   * Enforce access control so that the owning seller and administrators can read the snapshot. Other users must be denied. Do not require the active product to still exist, because snapshots are preserved after deletion.
   *
   * Return the immutable snapshot entity with its preserved product state, including preserved image and variant snapshot content if those are part of the snapshot schema. Do not allow updates through this endpoint.
   *
   * If the product or snapshot does not exist, or the snapshot does not belong to the specified product, return not found. If the caller lacks permission, return forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformProductSnapshot> {
    try {
      return await getMallPlatformSellerProductsProductIdSnapshotsSnapshotId({
        seller,
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
