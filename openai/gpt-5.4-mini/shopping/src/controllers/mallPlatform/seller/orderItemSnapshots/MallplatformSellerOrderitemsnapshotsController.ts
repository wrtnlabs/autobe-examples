import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrderItemSnapshot } from "../../../../api/structures/IMallPlatformOrderItemSnapshot";
import { IPageIMallPlatformOrderItemSnapshot } from "../../../../api/structures/IPageIMallPlatformOrderItemSnapshot";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerOrderItemSnapshotsHistory } from "../../../../providers/getMallPlatformSellerOrderItemSnapshotsHistory";
import { getMallPlatformSellerOrderItemSnapshotsOrderItemSnapshotId } from "../../../../providers/getMallPlatformSellerOrderItemSnapshotsOrderItemSnapshotId";
import { patchMallPlatformSellerOrderItemSnapshots } from "../../../../providers/patchMallPlatformSellerOrderItemSnapshots";

@Controller("/mallPlatform/seller/orderItemSnapshots")
export class MallplatformSellerOrderitemsnapshotsController {
  /**
   * Lists preserved order item snapshots with filtering and pagination.
   *
   * This endpoint returns immutable historical records captured for order item changes so authorized users can review purchase-state history during disputes, refunds, cancellations, and administrative review. Each snapshot belongs to one order item and preserves the item status, product details, seller shop identity, quantity, and line totals at the time the snapshot was recorded.
   *
   * Filtering and sorting are intended for browsing historical records, not for modifying them. The response is paginated because snapshot history can grow over time, and consumers may need to narrow results by order item, snapshot time, or reason. The records are immutable and cannot be created, edited, or deleted through this endpoint.
   *
   * @param connection
   * @param body Search criteria for filtering order item snapshots, including pagination, sorting, and optional order item or snapshot metadata filters.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query mall_platform_order_item_snapshots as immutable history records.
   * Apply filters from the request body to support order item scope, snapshot time ranges, snapshot reason text search, and ordering by created timestamp or snapshot timestamp when available in the request contract.
   * Join to mall_platform_order_items only as needed for scope validation or display enrichment, but keep the response as summary rows to avoid overfetching full snapshot payloads.
   * Return paginated results ordered by most recent snapshots first by default.
   * Never modify snapshot rows here. If a caller requests an inaccessible order item scope, return the normal authorization or not-found error from the access layer. Because snapshots are immutable, do not allow update or delete semantics through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformOrderItemSnapshot.IRequest,
  ): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerOrderItemSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a preserved order item snapshot by its identifier.
   *
   * This endpoint returns the immutable historical record captured for an order item at a specific moment in time. The snapshot preserves the purchased product details, variant code, seller shop information, quantity, and pricing so disputes and historical reconstruction can rely on the exact state that existed when the snapshot was created.
   *
   * The record is read-only and is never modified by this operation. If the snapshot identifier does not exist, the request should fail with a not-found error. Access should be limited to parties allowed to view preserved purchase history, such as the order owner, the relevant seller, or an administrator, according to platform authorization rules.
   *
   * @param connection
   * @param orderItemSnapshotId The order item snapshot identifier (UUID primary key).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load a single row from mall_platform_order_item_snapshots by id using the UUID path parameter.
   * Join only if necessary for authorization checks; the response itself should be built from the snapshot row because it already contains the preserved historical fields.
   * Enforce access control so only authorized viewers can read the snapshot. Return a not-found error when the id does not exist and avoid leaking whether inaccessible records exist.
   * Do not mutate any data. This endpoint must remain read-only and must not create or alter snapshots, order items, inventory, or related records.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemSnapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemSnapshotId")
    orderItemSnapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrderItemSnapshot> {
    try {
      return await getMallPlatformSellerOrderItemSnapshotsOrderItemSnapshotId({
        seller,
        orderItemSnapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Returns the immutable history of order item snapshots for audit review and dispute resolution.
   *
   * This operation exposes preserved historical records for order items, including the state captured when the snapshot was created. It is intended for browsing how a purchased item was represented over time, not for changing any stored history.
   *
   * The history is returned in newest-first order and is paginated because the number of preserved records can grow over time. Viewing the history does not modify any snapshot data, and errors while reading must not alter the preserved history.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Read from mall_platform_order_item_snapshots and return the results ordered by creation time descending so the newest preserved state appears first.
   * Apply pagination to the result set because snapshot history can grow large. Enforce authorization so customers can only view histories they are permitted to access, sellers can only view histories related to their own sold items, and administrators can view platform-wide history.
   * Do not create, update, or delete any snapshot records during this read. If no history exists, return an empty page. If access is denied or the related order item cannot be resolved, return the appropriate authorization or not-found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("history")
  public async history(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
    try {
      return await getMallPlatformSellerOrderItemSnapshotsHistory({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
