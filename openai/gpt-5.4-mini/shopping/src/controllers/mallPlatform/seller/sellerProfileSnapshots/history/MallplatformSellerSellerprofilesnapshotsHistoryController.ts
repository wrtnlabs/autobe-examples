import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IPageIMallPlatformSellerProfileSnapshot } from "../../../../../api/structures/IPageIMallPlatformSellerProfileSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerSellerProfileSnapshotsHistory } from "../../../../../providers/getMallPlatformSellerSellerProfileSnapshotsHistory";

@Controller("/mallPlatform/seller/sellerProfileSnapshots/history")
export class MallplatformSellerSellerprofilesnapshotsHistoryController {
  /**
   * Returns the preserved history of seller profile changes.
   *
   * This operation retrieves immutable seller profile snapshot records so authorized users can review prior shop name, shop description, logo image URI, and snapshot creation time values. It is intended for audit, dispute resolution, and historical reference, and it does not modify the live seller profile record.
   *
   * The history comes from the seller profile snapshot table and should be ordered from newest to oldest by default. When the history is long, the implementation should apply pagination so the response remains usable in the UI.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query mall_platform_seller_profile_snapshots as an append-only history source.
   * Return rows ordered by created_at descending by default so the newest profile edit appears first.
   * Expose the preserved fields shop_name, shop_description, logo_image_uri, and created_at in the summary payload.
   * Do not allow create, update, or delete behavior because snapshots are immutable and preserved for audit/dispute review.
   * If no history exists, return an empty page result rather than an error.
   * If future filtering is introduced, it must not alter the immutability or ordering guarantees of the stored snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IPageIMallPlatformSellerProfileSnapshot.ISummary> {
    try {
      return await getMallPlatformSellerSellerProfileSnapshotsHistory({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
