import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformSellerProfileSnapshot } from "../../../../api/structures/IMallPlatformSellerProfileSnapshot";
import { IPageIMallPlatformSellerProfileSnapshot } from "../../../../api/structures/IPageIMallPlatformSellerProfileSnapshot";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerSellerProfileSnapshotsSellerProfileSnapshotId } from "../../../../providers/getMallPlatformSellerSellerProfileSnapshotsSellerProfileSnapshotId";
import { patchMallPlatformSellerSellerProfileSnapshots } from "../../../../providers/patchMallPlatformSellerSellerProfileSnapshots";

@Controller("/mallPlatform/seller/sellerProfileSnapshots")
export class MallplatformSellerSellerprofilesnapshotsController {
  /**
   * Search seller profile snapshots with pagination and sorting.
   *
   * This endpoint returns immutable history records for seller profile edits so authorized users can review previous shop names, shop descriptions, and logo images for dispute resolution, audit review, and storefront history reconstruction. Snapshot records are created only after successful seller profile changes and preserve the prior state of the profile.
   *
   * The list is paginated because snapshot history can grow over time. Consumers can filter and sort the results using the supported request criteria, and should use the detail endpoint when they need the complete preserved contents of a single snapshot record.
   *
   * @param connection
   * @param body Pagination, sorting, and filter criteria for searching seller profile snapshot history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query mall_platform_seller_profile_snapshots as a read-only history collection.
   * Apply pagination, filtering, and sorting from the request body. Default sorting should favor the most recent snapshots first when no explicit sort is provided.
   *
   * This operation must not modify seller profiles or create snapshots. It should only read existing immutable snapshot rows and return summary records suitable for list views. If no records match the filters, return an empty page with valid pagination metadata.
   *
   * Enforce authorization so only permitted parties can inspect snapshot history for a seller profile. If the request references data outside the caller's access scope, reject it using the standard authorization failure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformSellerProfileSnapshot.IRequest,
  ): Promise<IPageIMallPlatformSellerProfileSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerSellerProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one immutable seller profile snapshot by its identifier.
   *
   * This endpoint exposes the preserved historical state of a seller profile after a successful edit. It is intended for audit review, storefront history inspection, and dispute resolution, and it does not modify the live seller profile or any other record.
   *
   * The snapshot should contain the seller's shop identity as it was preserved at the time of change, including the shop name, shop description, and logo image reference if those values are stored in the snapshot. If the snapshot does not exist, the server should return a not found response.
   *
   * @param connection
   * @param sellerProfileSnapshotId The seller profile snapshot identifier (global scope).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load a single seller profile snapshot by seller_profile_snapshot id and return it as an immutable read model. Do not attempt to update the live seller profile or create any new snapshot from this read operation.
   *
   * Validate that sellerProfileSnapshotId is a valid UUID and query the snapshot table by its primary identifier. If no row exists, return 404. Because snapshots are immutable, there is no write-side behavior, no partial update handling, and no cascading modifications. If related live seller profile records have later changed or been deleted, still return the snapshot itself as long as it exists in the snapshot table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sellerProfileSnapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerProfileSnapshotId")
    sellerProfileSnapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformSellerProfileSnapshot> {
    try {
      return await getMallPlatformSellerSellerProfileSnapshotsSellerProfileSnapshotId(
        {
          seller,
          sellerProfileSnapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
