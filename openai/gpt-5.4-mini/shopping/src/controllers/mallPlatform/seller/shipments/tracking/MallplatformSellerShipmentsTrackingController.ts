import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformShipment } from "../../../../../api/structures/IMallPlatformShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerShipmentsShipmentIdTracking } from "../../../../../providers/getMallPlatformSellerShipmentsShipmentIdTracking";

@Controller("/mallPlatform/seller/shipments/:shipmentId/tracking")
export class MallplatformSellerShipmentsTrackingController {
  /**
   * Retrieve the shared tracking details for a single shipment.
   *
   * A shipment is the platform's delivery unit, so this endpoint returns the carrier name and tracking number that apply to the entire package. The same tracking information is used for every order item included in that shipment.
   *
   * This data is used in the customer order detail view to follow delivery progress for grouped items. If the shipment does not exist, the service must return a not found error. If the caller is not authorized to view the shipment, the service must return an authorization error.
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment whose tracking details are being retrieved.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Look up the shipment by shipmentId and verify
     *   that the caller is allowed to view it according to ownership and
     *   role-based access rules. Return the shipment-level tracking
     *   information, including carrier name and tracking number, and keep the
     *   response aligned with the shipment delivery unit concept. Do not
     *   introduce item-level tracking differences because all items in the
     *   shipment share the same tracking data. Return 404 when the shipment is
     *   missing and 403 when access is denied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformShipment.IInvert> {
    try {
      return await getMallPlatformSellerShipmentsShipmentIdTracking({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
