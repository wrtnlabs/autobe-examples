import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformShipment } from "../../../../../api/structures/IMallPlatformShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { postMallPlatformSellerShipmentsFulfillment } from "../../../../../providers/postMallPlatformSellerShipmentsFulfillment";

@Controller("/mallPlatform/seller/shipments/fulfillment")
export class MallplatformSellerShipmentsFulfillmentController {
  /**
   * Create a seller-specific shipment for eligible order items.
   *
   * This endpoint groups one or more order items from the same seller into a single shipment and stores the shared carrier name and tracking number for that delivery package. It is used during seller fulfillment after the seller selects items that still need shipping.
   *
   * The request must only include order items owned by the authenticated seller and all selected items must belong to the same seller. Items that are already shipped, delivered, cancelled, refunded, completed, or otherwise unavailable for shipping must be rejected. If any selected item is invalid or the shipment is no longer available, the entire request fails and no shipment is created.
   *
   * The created shipment is the customer-visible delivery record used in order details and order history. All included items must be associated with the shipment in the same transaction so the shipment grouping and item shipping status remain consistent.
   *
   * @param connection
   * @param body Shipment creation data including the selected order item identifiers and the shared carrier and tracking information.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate that the authenticated seller owns every
     *   requested order item and that every item is eligible for shipping.
     *   Enforce that all selected items belong to one seller only and reject
     *   any request that mixes sellers or references items that are already
     *   shipped, delivered, cancelled, refunded, or otherwise unavailable.
   *
   * Create the shipment and its shipment-item links in a single transaction. Persist the carrier name and tracking number on the shipment record, then insert one shipment-item association for each included order item. Update each included order item to shipped in the same transaction so the shipment and order-item states cannot diverge.
   *
   * If the schema includes additional metadata columns such as timestamps, populate them only when they actually exist in the loaded schema. On validation failure, unavailable item detection, or concurrency conflict, roll back the transaction and return a clear error indicating that the shipment cannot be created because the selected items are unavailable or already completed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformShipment.ICreate,
  ): Promise<IMallPlatformShipment> {
    try {
      return await postMallPlatformSellerShipmentsFulfillment({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
