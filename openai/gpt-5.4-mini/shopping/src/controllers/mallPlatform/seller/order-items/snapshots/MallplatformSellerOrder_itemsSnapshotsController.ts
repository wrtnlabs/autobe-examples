import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrderItemSnapshot } from "../../../../../api/structures/IMallPlatformOrderItemSnapshot";
import { IPageIMallPlatformOrderItemSnapshot } from "../../../../../api/structures/IPageIMallPlatformOrderItemSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerOrderItemsOrderItemIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformSellerOrderItemsOrderItemIdSnapshotsSnapshotId";
import { patchMallPlatformSellerOrderItemsOrderItemIdSnapshots } from "../../../../../providers/patchMallPlatformSellerOrderItemsOrderItemIdSnapshots";

@Controller("/mallPlatform/seller/order-items/:orderItemId/snapshots")
export class MallplatformSellerOrder_itemsSnapshotsController {
  /**
   * Retrieve the preserved snapshot history for a single order item.
   *
   * This operation returns immutable historical records that capture how the purchased item looked at meaningful moments in its lifecycle. Each snapshot preserves the purchased product name, description, product SKU, variant SKU code, seller shop name, seller shop description, seller logo image URL, unit price, quantity, line total, the order item status at the time, and the timestamp when the snapshot was captured.
   *
   * The snapshot history is scoped to one order item and is intended for dispute review, historical reconstruction, and purchase verification by the buyer, the seller responsible for the item, and administrators. Because these records are immutable, they remain available even if the live order item or its related product or seller data changes later. If the requested order item does not exist or the caller is not allowed to view its history, the request must be rejected.
   *
   * @param connection
   * @param orderItemId Identifier of the order item whose immutable snapshot history is being requested.
   * @param body Search, paging, and sorting criteria for browsing the snapshot history of a single order item.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the target order item by id and verify the caller is allowed to inspect it. Buyers may access only their own order items, sellers may access only order items for their own products, and administrators may access any order item. Reject the request if the order item does not exist or the caller has no permission.
   *
   * Query mall_platform_order_item_snapshots filtered by mall_platform_order_item_id, ordered by snapshot_at descending and then created_at descending for stable history browsing. Support pagination and any search/filter inputs defined in the request DTO, but keep the query scoped to the single path order item. Do not join mutable live product or seller tables for the returned snapshot content because the snapshot rows already contain preserved historical values.
   *
   * Return a paginated summary list of snapshot records. The summary should expose immutable history metadata and the preserved purchase context needed for review, while keeping the payload compact for timeline browsing. No snapshot rows may be created, updated, or deleted by this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformOrderItemSnapshot.IRequest,
  ): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerOrderItemsOrderItemIdSnapshots({
        seller,
        orderItemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a preserved snapshot of an order item.
   *
   * This operation returns the immutable historical record captured for a purchased order item, including the product state, variant state, seller profile state, and other preserved details needed to understand what was bought at the time of checkout. It is intended for purchase history review, dispute resolution, and order audit purposes.
   *
   * The snapshot is read-only and may still be available even when the related product, variant, or active order item has changed later. Access is restricted to the customer who owns the order, the seller associated with the item, and administrators who are reviewing the transaction history.
   *
   * @param connection
   * @param orderItemId The identifier of the order item whose snapshot history is being accessed.
   * @param snapshotId The identifier of the preserved snapshot within the scope of the order item.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the order item by orderItemId and verify that the snapshotId belongs to that order item.
   * Ensure the caller is authorized to view the order item history: the owning customer, the item’s seller, or an administrator.
   * Return the full immutable snapshot record and its preserved relations, including any normalized snapshot option rows if the implementation exposes them through the snapshot component schema.
   * Do not allow modification, creation, or deletion through this endpoint.
   * If the order item does not exist, the snapshot does not belong to the given order item, or the caller is not authorized, return the appropriate error without leaking unrelated record existence.
   * Because snapshots are immutable history records, never attempt to refresh them from current product or seller data; always return the preserved stored values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrderItemSnapshot> {
    try {
      return await getMallPlatformSellerOrderItemsOrderItemIdSnapshotsSnapshotId(
        {
          seller,
          orderItemId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
