import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrderItem } from "../../../../api/structures/IMallPlatformOrderItem";
import { IPageIMallPlatformOrderItem } from "../../../../api/structures/IPageIMallPlatformOrderItem";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerOrderItemsOrderItemId } from "../../../../providers/getMallPlatformSellerOrderItemsOrderItemId";
import { patchMallPlatformSellerOrderItems } from "../../../../providers/patchMallPlatformSellerOrderItems";

@Controller("/mallPlatform/seller/orderItems")
export class MallplatformSellerOrderitemsController {
  /**
   * Search and paginate order items for operational browsing.
   *
   * This endpoint returns a filtered list of purchased order items, including their quantity, status, and foreign-key references to the parent order, product variant, and seller. It is intended for seller dashboards and administrator review screens where order items must be found by status, order, seller, product variant, or creation time.
   *
   * The result is paginated because order item lists can be large. Sorting and filtering must follow the platform browsing rules, and the service must return an empty page when no records match. This endpoint does not modify any data.
   *
   * If a request contains invalid pagination values or unsupported filters, the service must reject it with a validation error.
   *
   * @param connection
   * @param body Search, filter, sort, and pagination criteria for order item browsing.
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query mall_platform_order_items with pagination,
     *   filtering, and sorting support. Apply request filters to
     *   mall_platform_order_id, mall_platform_product_variant_id,
     *   mall_platform_seller_id, status, and created_at range as available in
     *   the request DTO. Use indexed columns where possible, especially the
     *   composite indexes on order_id/status, seller_id/status, and
     *   product_variant_id/status, to keep the query efficient. Sort by newest
     *   first by default unless the request specifies another valid sort order.
     *   Return a paginated summary page and never mutate any data. If no rows
     *   match, return an empty page. Reject unsupported filters, invalid
     *   pagination, and malformed sort instructions with validation errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformOrderItem.IRequest,
  ): Promise<IPageIMallPlatformOrderItem.ISummary> {
    try {
      return await patchMallPlatformSellerOrderItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full detail view of a single order item.
   *
   * This endpoint returns one purchased product variant line within an order, including the item-level status, quantity, price, and preserved purchase context needed for order history, shipping, cancellation, refund, and dispute review.
   *
   * Customers use this view to inspect the progress of a specific purchase line even when other items in the same order have different statuses. Sellers and administrators use the same detail data to process fulfillment and review after-sales issues. If the item is missing or the caller is not allowed to access it, the service must return a normal business error response.
   *
   * @param connection
   * @param orderItemId The unique identifier of the order item to retrieve (UUID).
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Load one row from mall_platform_order_items by
     *   its primary identifier. Join the related order, product, product
     *   variant, seller profile snapshot, shipment, cancellation request,
     *   refund request, and order-item snapshot data needed to render the full
     *   detail page. Return the current item status together with the preserved
     *   purchase-context fields so the caller can see product name, variant,
     *   quantity, price, seller identity at purchase time, and shipment
     *   linkage. Enforce access control so customers can read only their own
     *   order items, sellers can read order items belonging to their products,
     *   and administrators can read any order item. If the order item does not
     *   exist or is not visible to the caller, return a standard not-found or
     *   forbidden business error. Do not mutate order state, inventory,
     *   shipment, or request records in this operation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrderItem> {
    try {
      return await getMallPlatformSellerOrderItemsOrderItemId({
        seller,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
