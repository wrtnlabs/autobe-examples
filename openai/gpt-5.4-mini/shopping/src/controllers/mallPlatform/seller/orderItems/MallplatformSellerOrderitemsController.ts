import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformOrderItem } from "../../../../api/structures/IMallPlatformOrderItem";
import { IPageIMallPlatformOrderItem } from "../../../../api/structures/IPageIMallPlatformOrderItem";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerOrderItemsOrderItemId } from "../../../../providers/getMallPlatformSellerOrderItemsOrderItemId";
import { patchMallPlatformSellerOrderItems } from "../../../../providers/patchMallPlatformSellerOrderItems";

@Controller("/mallPlatform/seller/orderItems")
export class MallplatformSellerOrderitemsController {
  /**
   * Search and page through order items for operational workflows.
   *
   * This endpoint returns live order item records so sellers and administrators can inspect purchased variant lines, fulfillment status, and request-related states in a paginated list. It is intended for collection browsing, status monitoring, and workflow triage rather than full record retrieval.
   *
   * The search can be filtered by order, seller, product variant, and item status, and it should support stable sorting with newest items first by default. If no rows match the criteria, the endpoint should return an empty page. Deleted rows must be handled consistently with platform browsing rules and should not alter stored order history.
   *
   * @param connection
   * @param body Search criteria for paging, filtering, and sorting order items by order, seller, product variant, and status.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query mall_platform_order_items with pagination, filtering, and sorting support.
   * Use mall_platform_order_id, mall_platform_seller_id, mall_platform_product_variant_id, and status as supported filters.
   * Apply a deterministic sort order, defaulting to created_at descending when the request does not specify otherwise.
   * Return a paginated summary projection for list views; do not expose the entire order item entity in the collection payload.
   * Leverage the existing indexes on (mall_platform_order_id, status), (mall_platform_seller_id, status), and (mall_platform_product_variant_id, status) for efficient filtering.
   * If the requested page is beyond the available range or no rows match, return an empty page instead of an error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformOrderItem.IRequest,
  ): Promise<IPageIMallPlatformOrderItem.ISummary> {
    try {
      return await patchMallPlatformSellerOrderItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one order item together with its purchase context and current status.
   *
   * This operation returns a single line item from a completed order. It is used for customer order history, seller fulfillment screens, shipment review, cancellation and refund handling, and administrator dispute review. The order item must remain scoped to its parent order and its preserved historical purchase data.
   *
   * The response should expose the item’s quantity, item status, purchased product and variant references, seller context, and any preserved snapshot-based history required to understand the line item at the time of purchase. If the item does not exist, the service should return a standard not-found error. Access control must ensure that customers can only read their own order items, sellers can only read items related to their products, and administrators can read any order item.
   *
   * @param connection
   * @param orderItemId The order item identifier to retrieve.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the order item by its identifier and return the full detail representation for the line item. Use the order items table as the source of truth for the current state, and include any preserved purchase-context fields needed by the application layer for product, variant, seller, and status history.
   *
   * Authorize the request before returning data: the owning customer may view the item, the seller associated with the item may view it, and administrators may view any item. If the row is missing, return a standard not-found response. Do not return sibling order items or mutate any data.
   *
   * Keep the response aligned with the current persisted state and preserve snapshot-derived historical context where the system stores it for later review.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderItemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("orderItemId")
    orderItemId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformOrderItem> {
    try {
      return await getMallPlatformSellerOrderItemsOrderItemId({
        seller,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
