import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMallPlatformSellerProfile } from "../../../../api/structures/IMallPlatformSellerProfile";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerStorefrontIdentity } from "../../../../providers/getMallPlatformSellerStorefrontIdentity";
import { putMallPlatformSellerStorefrontIdentity } from "../../../../providers/putMallPlatformSellerStorefrontIdentity";

@Controller("/mallPlatform/seller/storefront-identity")
export class MallplatformSellerStorefront_identityController {
  /**
   * Returns the current storefront identity for the authenticated seller account.
   *
   * The storefront identity is the customer-visible representation of a seller and is defined by the shop name, shop description, and logo image stored in the seller profile. This operation is used by storefront pages and customer-facing product views to display the merchant's brand consistently.
   *
   * The response reflects the seller profile as it exists now. Historical storefront versions are preserved separately through seller profile snapshots and are not modified by this request. If the caller is not authenticated as a seller, or if the seller profile cannot be resolved, the request must fail with the appropriate authorization or not-found error.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Resolve the seller profile for the current authenticated seller account and return only the storefront identity fields required for customer-facing display: shop name, shop description, and logo image reference. Do not include credentials, approval metadata, or other internal seller account fields. No write action occurs. If the caller is unauthorized, return an authorization error. If the seller profile does not exist, return a not-found error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<IMallPlatformSellerProfile> {
    try {
      return await getMallPlatformSellerStorefrontIdentity({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated seller’s storefront identity.
   *
   * This operation changes the seller profile values that define the public shop identity shown to customers: shop name, shop description, and logo image. It is restricted to the currently authenticated seller and does not change account credentials or approval status.
   *
   * A successful edit must create a seller profile snapshot that preserves the previous storefront identity alongside the updated values. If validation, authorization, or persistence fails, the seller profile must remain unchanged and no snapshot may be recorded.
   *
   * The updated storefront identity is used in customer-facing pages such as product listings, product detail pages, and historical order records. Clients should expect authorization errors when the caller is not the owner of the seller profile.
   *
   * @param connection
   * @param body The storefront identity fields to update for the authenticated seller’s own profile.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Resolve the authenticated seller from the security context and load that seller’s profile. Validate the incoming storefront identity fields against seller profile rules before making any database change.
   *
   * Apply the update inside a single transaction. After the profile is updated successfully, create a seller profile snapshot capturing the prior and current storefront identity values so the edit history is preserved. If any validation, authorization, or persistence step fails, roll back the transaction and do not create a snapshot.
   *
   * Return the updated seller profile after commit. Reject requests when the caller is not a seller, when the seller profile does not exist, or when the caller is not allowed to edit its own storefront identity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IMallPlatformSellerProfile.IUpdate,
  ): Promise<IMallPlatformSellerProfile> {
    try {
      return await putMallPlatformSellerStorefrontIdentity({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
