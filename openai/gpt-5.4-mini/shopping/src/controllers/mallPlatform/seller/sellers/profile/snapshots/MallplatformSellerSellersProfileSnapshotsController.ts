import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformSellerProfileSnapshot } from "../../../../../../api/structures/IMallPlatformSellerProfileSnapshot";
import { IPageIMallPlatformSellerProfileSnapshot } from "../../../../../../api/structures/IPageIMallPlatformSellerProfileSnapshot";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerSellersSellerIdProfileSnapshotsSnapshotId } from "../../../../../../providers/getMallPlatformSellerSellersSellerIdProfileSnapshotsSnapshotId";
import { patchMallPlatformSellerSellersSellerIdProfileSnapshots } from "../../../../../../providers/patchMallPlatformSellerSellersSellerIdProfileSnapshots";

@Controller("/mallPlatform/seller/sellers/:sellerId/profile/snapshots")
export class MallplatformSellerSellersProfileSnapshotsController {
  /**
   * List immutable seller profile snapshots for one seller account.
   *
   * This endpoint returns the preserved history of changes made to the seller's public profile, including shop name, shop description, and logo image updates. Each snapshot represents a completed profile edit and records the state before and after the change so sellers and administrators can review storefront identity history for dispute resolution.
   *
   * The snapshots are read-only and cannot be created, updated, or deleted through this API. Results are scoped to the seller identified by the path parameter and should only include snapshots that belong to that seller profile. Support pagination, sorting by snapshot time, and optional filtering by changed fields or date range to help consumers browse long histories efficiently.
   *
   * @param connection
   * @param sellerId The seller identifier whose profile snapshot history is being requested.
   * @param body Pagination, sorting, and optional snapshot-history filters for browsing seller profile snapshots.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the seller profile snapshot history for the seller identified by sellerId. Join the seller profile snapshot records to the owning seller profile through the seller ownership relationship, then return only snapshots belonging to that seller. Support pagination, ordering by snapshot timestamp descending by default, and optional filters such as changed field name and created-at range if those fields are available in the snapshot schema.
   *
   * Because snapshots are immutable history records, do not allow mutation operations here. Return 404 when the seller does not exist or does not own a profile, and return an empty page when the seller exists but has no snapshots. Ensure authorization allows the owning seller and administrators to read the history, while preventing access to other sellers' snapshots.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformSellerProfileSnapshot.IRequest,
  ): Promise<IPageIMallPlatformSellerProfileSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerSellersSellerIdProfileSnapshots({
        seller,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one seller profile snapshot for historical review.
   *
   * This operation returns a single immutable snapshot of a seller profile taken after a successful edit. The snapshot preserves the shop name, shop description, logo image URI, and creation timestamp so the seller’s storefront identity can be reviewed as it existed at that point in time.
   *
   * Access is limited to the seller who owns the profile and to administrators who need the preserved history for dispute resolution or oversight. If the snapshot does not exist, or if it does not belong to the specified seller profile, the request should be treated as not found.
   *
   * @param connection
   * @param sellerId The seller profile owner identifier in UUID format.
   * @param snapshotId The snapshot identifier in UUID format.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the seller profile snapshot by joining seller_profile_snapshots to seller_profiles through seller_profile_id and confirming the snapshot belongs to the seller profile identified by sellerId. Verify the authenticated actor is either the owning seller account or an administrator before returning the record.
   *
   * Return the snapshot row as stored, including id, seller_profile_id, shop_name, shop_description, logo_image_uri, and created_at. Do not attempt to reconstruct or merge with the live seller profile because this endpoint is specifically for preserved history.
   *
   * If the seller profile does not belong to sellerId, or if the snapshot id is missing under that seller profile, return not found. If access is denied, return forbidden. This is read-only and must not modify any data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformSellerProfileSnapshot> {
    try {
      return await getMallPlatformSellerSellersSellerIdProfileSnapshotsSnapshotId(
        {
          seller,
          sellerId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
