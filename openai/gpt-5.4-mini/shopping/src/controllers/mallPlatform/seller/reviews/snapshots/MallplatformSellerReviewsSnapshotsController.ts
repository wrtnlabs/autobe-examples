import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMallPlatformReviewSnapshot } from "../../../../../api/structures/IMallPlatformReviewSnapshot";
import { IPageIMallPlatformReviewSnapshot } from "../../../../../api/structures/IPageIMallPlatformReviewSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getMallPlatformSellerReviewsReviewIdSnapshotsSnapshotId } from "../../../../../providers/getMallPlatformSellerReviewsReviewIdSnapshotsSnapshotId";
import { patchMallPlatformSellerReviewsReviewIdSnapshots } from "../../../../../providers/patchMallPlatformSellerReviewsReviewIdSnapshots";

@Controller("/mallPlatform/seller/reviews/:reviewId/snapshots")
export class MallplatformSellerReviewsSnapshotsController {
  /**
   * Lists immutable snapshots recorded for a review.
   *
   * This endpoint returns the preserved history of review edits and deletion-related state changes for the specified review. It is intended for the review owner and administrators to compare previous values, inspect when changes occurred, and support dispute resolution or historical review.
   *
   * The response is paginated because a review may accumulate multiple snapshots over time. Results should be ordered according to the requested sorting rules, with the most recent snapshots typically shown first. If the review does not exist or the caller is not allowed to view its history, the request must be rejected with the appropriate authorization or not-found error.
   *
   * @param connection
   * @param reviewId The review identifier whose snapshot history should be listed.
   * @param body Search, pagination, and sorting criteria for browsing review snapshot history for a single review.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the review by reviewId and verify the caller can access its snapshot history. Access is allowed to the review owner and administrators only. Query the mall_platform_review_snapshots table for rows related to the review, ordered by the requested sort fields, with pagination applied. If the underlying review has been deleted, continue to return preserved snapshots when the business rules require retained history. Do not allow any mutation of snapshot rows. If the reviewId is invalid or no matching review exists, return not-found. If the caller lacks permission, return forbidden. Include search/filter support only for snapshot-related browsing fields if those are defined in the request DTO; do not infer unsupported filters.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IMallPlatformReviewSnapshot.IRequest,
  ): Promise<IPageIMallPlatformReviewSnapshot.ISummary> {
    try {
      return await patchMallPlatformSellerReviewsReviewIdSnapshots({
        seller,
        reviewId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one immutable snapshot for a specific review.
   *
   * This endpoint returns a preserved point-in-time record of a review so authorized consumers can inspect historical rating, text content, and change metadata for dispute resolution or audit review. Snapshots remain available even after the live review is edited or deleted.
   *
   * Access is restricted to the review owner, administrators, and any other actors allowed by the platform's visibility rules. If the review does not exist, the snapshot does not exist, or the snapshot does not belong to the specified review, the service must return not found. If the caller is not permitted to view preserved review history, the service must return forbidden.
   *
   * @param connection
   * @param reviewId The review identifier that scopes the snapshot lookup.
   * @param snapshotId The snapshot identifier within the specified review.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch the review snapshot by reviewId and snapshotId, and verify the snapshot is scoped to the requested review before returning it. Use the immutable review snapshot table as the source of truth and do not perform any mutation.
   *
   * If either the review or snapshot cannot be found, or the snapshot is not associated with the given review, return a not-found response. If the authenticated actor lacks permission to view preserved review history, return forbidden according to ownership and administrator visibility rules.
   *
   * Return the full snapshot entity with preserved review state and snapshot metadata, including the change timestamp and before/after values required for historical inspection.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
    @TypedParam("snapshotId")
    snapshotId: string & tags.Format<"uuid">,
  ): Promise<IMallPlatformReviewSnapshot> {
    try {
      return await getMallPlatformSellerReviewsReviewIdSnapshotsSnapshotId({
        seller,
        reviewId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
