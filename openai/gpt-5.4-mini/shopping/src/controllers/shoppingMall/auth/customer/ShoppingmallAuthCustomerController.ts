import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallCustomer } from "../../../../api/structures/IShoppingMallCustomer";
import { postShoppingMallAuthCustomerJoin } from "../../../../providers/postShoppingMallAuthCustomerJoin";
import { postShoppingMallAuthCustomerLogin } from "../../../../providers/postShoppingMallAuthCustomerLogin";
import { postShoppingMallAuthCustomerRefresh } from "../../../../providers/postShoppingMallAuthCustomerRefresh";

@Controller("/shoppingMall/auth/customer")
export class ShoppingmallAuthCustomerController {
  /**
   * Create a new customer account using the registration credentials defined for the shopping mall platform.
   *
   * This operation is the entry point for a registered shopper identity and is aligned with the customer actor described in the system requirements. It is responsible for creating the account that will later participate in profile management, shipping addresses, wishlist, cart, orders, and reviews. The operation must respect the customer account security model, which centers on email-and-password credentials and the account security state stored for customer actors.
   *
   * The registration flow must validate that the submitted email is unique and that the password satisfies the platform’s security requirements. After successful creation, the service should return an authorization payload that allows the newly created customer to continue into authenticated flows. If the platform’s customer verification flow is enabled by the underlying schema, the registration process should also integrate with the email-verification support tables used by customer authentication.
   *
   * This endpoint is part of the required authentication trio for the customer actor and is distinct from all business CRUD operations. It must not expose profile, order, or wishlist functionality. Related follow-up operations include customer login for returning users and token refresh for renewing an active session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials for creating a new shopper account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer account registration by validating the submitted email and password payload, ensuring the email is not already registered, creating the customer account record, and initializing the authentication session response in a single transaction. The service should also trigger any required account-verification or security side effects that are supported by the customer authentication workflow, such as issuing verification-related records when the platform requires email confirmation. Return a standardized authorized response containing access and refresh tokens or equivalent authorization payload after successful creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.IJoin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing customer using the email-and-password account credentials defined for the shopping mall platform.
   *
   * This operation is used by a registered shopper who already has an account and needs to regain authenticated access to customer-only features such as address management, cart checkout, order history, and review management. The customer actor is a member actor, so login is a required authentication operation and must be available alongside registration and token refresh.
   *
   * The login process must verify the provided credentials against the customer account records and respect the account security state stored for customers. If the account is not permitted to log in, the operation must fail with an authentication error. When successful, the response should return the platform’s authorized payload so the client can proceed with authenticated requests.
   *
   * This endpoint should be treated as a pure authentication boundary and should not be mixed with business actions like profile editing or order operations. It is designed to work together with customer session storage and token refresh flows, allowing the client to continue a secure session without re-entering credentials each time.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials used to authenticate an existing shopper account.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer login by validating the submitted email and password against the customer credential store, rejecting banned or otherwise disabled accounts, and creating or updating the customer session state as appropriate for JWT-based authentication. The service should issue an access token and a refresh token, persist session-tracking data when the schema supports it, and ensure that login failure cases do not leak whether the email exists beyond standard authentication error handling.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallCustomer.ILogin,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew a customer’s authenticated session using the refresh credentials issued by the platform.
   *
   * This operation supports the customer actor’s JWT-based authentication lifecycle and is required so that a signed-in shopper can continue using authenticated features without re-entering their email and password. The platform’s customer session support, including the dedicated customer session table and related account security structures, makes token renewal a first-class authentication operation.
   *
   * The refresh flow must verify that the submitted refresh token is still valid and associated with the customer session state. If the token is expired, revoked, or otherwise invalid, the request must be rejected. On success, the response must provide a fresh authorized payload so the client can continue calling protected customer endpoints such as cart checkout, address management, order history, and review actions.
   *
   * This endpoint is intentionally limited to authentication renewal. It does not expose any business data and should be used together with login and registration as part of the customer’s full authentication lifecycle.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer refresh-token payload used to renew an active authenticated session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer token refresh by validating the provided refresh-token payload, verifying that the token matches an active customer session when session tracking is supported, and issuing a new authorized token set. The service must reject expired, revoked, or mismatched refresh credentials and should rotate or update stored session state according to the platform’s JWT session policy. This operation should not create a new account or re-check passwords; it exists solely to renew authentication for an already signed-in customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallCustomer.IRefresh,
  ): Promise<IShoppingMallCustomer.IAuthorized> {
    try {
      return await postShoppingMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
