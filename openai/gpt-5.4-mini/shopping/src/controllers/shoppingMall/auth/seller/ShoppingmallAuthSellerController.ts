import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IShoppingMallSeller } from "../../../../api/structures/IShoppingMallSeller";
import { postShoppingMallAuthSellerJoin } from "../../../../providers/postShoppingMallAuthSellerJoin";
import { postShoppingMallAuthSellerLogin } from "../../../../providers/postShoppingMallAuthSellerLogin";
import { postShoppingMallAuthSellerRefresh } from "../../../../providers/postShoppingMallAuthSellerRefresh";

@Controller("/shoppingMall/auth/seller")
export class ShoppingmallAuthSellerController {
  /**
   * Create a new seller account for a merchant who wants to join the marketplace as a registered seller. This endpoint is the first authentication step for the seller actor and is used when a merchant submits email and password credentials to establish a seller identity in the system.
   *
   * The seller account model supports account credentials and lifecycle state, so this operation must create the account record and initialize it in a valid pre-selling state consistent with the seller approval workflow. The response returns authorization data so the seller can proceed with authenticated onboarding and account management after successful registration.
   *
   * This operation is only for seller account creation and must not be confused with profile editing, seller approval review, or account suspension management. Those are separate business operations and are not part of the authentication flow. The request must be validated carefully because seller registration is the entry point for the seller actor's authenticated session lifecycle.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials for creating a new seller account.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement a seller registration endpoint that creates a new seller account identity using the submitted email and password credentials, then returns authorized tokens after the account is successfully created. The service should validate the registration payload, ensure the email is unique among seller accounts, and persist the new seller record in the sellers actor table. If the platform requires seller approval before selling, the registration flow must still create the account but leave any approval-related state in the pending/default state defined by the seller account lifecycle. After persistence, issue access and refresh tokens tied to the newly created seller session record so the seller can continue to authenticated onboarding flows immediately.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.IJoin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing seller account using email and password credentials. This endpoint is the primary sign-in operation for merchants who already have a registered seller identity and need a valid session to access seller-specific features such as product management, inventory control, shipment handling, cancellation responses, and refund responses.
   *
   * The seller actor is a member-level account type, so login is required after registration to obtain a valid authenticated session. The seller account schema supports credential-based access and session tracking, which makes this endpoint the correct place to validate credentials and issue authorization tokens for subsequent requests.
   *
   * This endpoint must reject invalid credentials and any seller account state that prevents login according to the account security rules. It is separate from seller approval review and separate from profile or storefront management operations.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials used to authenticate an existing seller account.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement a seller login endpoint that verifies the submitted seller email and password against the stored seller credentials, then creates or renews a seller session and returns authorization tokens. The service should locate the seller account by email, confirm the password using the stored credential hash, and reject the request if the account is banned, otherwise unavailable, or fails any seller account security checks defined by the platform. On success, generate a fresh access token and refresh token pair and store the session tracking data in the seller sessions table so the authentication state can be managed consistently.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IShoppingMallSeller.ILogin,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an authenticated seller session by exchanging a valid refresh credential for a new authorization result. This endpoint exists so a seller can continue working without re-entering email and password while their current access token expires over time.
   *
   * The seller session model supports refresh tracking and revocation control, which makes this endpoint essential for maintaining secure long-lived seller authentication. The response provides fresh authorization data that can be used for continued access to seller-only functions such as product editing, inventory adjustments, shipment processing, and request handling.
   *
   * This endpoint is not a login endpoint and must not create a brand-new account. It only extends an already authenticated seller session and should fail if the refresh token or session state is invalid, revoked, or expired.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller refresh credentials used to renew an existing authenticated session.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement a seller token refresh endpoint that accepts the seller refresh payload, validates the current refresh token or session reference, and issues a new authorized token pair. The service should verify that the seller session exists, has not been revoked, and is still valid before rotating or reusing the refresh token according to the platform's session policy. If validation succeeds, return a new access token and refresh token pair and update the seller session tracking record to reflect the renewed authentication state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IShoppingMallSeller.IRefresh,
  ): Promise<IShoppingMallSeller.IAuthorized> {
    try {
      return await postShoppingMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
