import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallShipment } from "../../../../api/structures/IPageIShoppingMallShipment";
import { IShoppingMallShipment } from "../../../../api/structures/IShoppingMallShipment";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getShoppingMallSellerShipmentsShipmentId } from "../../../../providers/getShoppingMallSellerShipmentsShipmentId";
import { patchShoppingMallSellerShipments } from "../../../../providers/patchShoppingMallSellerShipments";

@Controller("/shoppingMall/seller/shipments")
export class ShoppingmallSellerShipmentsController {
  /**
   * Retrieve a paginated list of seller-specific shipment records for fulfillment tracking and operational review.
   *
   * A shipment represents the delivery grouping that collects one or more order items sent together from the same seller. This collection endpoint exposes the shipment records stored in `shopping_mall_shipments`, including the order linkage, seller linkage, carrier name, tracking number, current status, shipped timestamp, delivered timestamp, and record timestamps. It is intended for browsing and searching shipment history rather than loading a single shipment’s full delivery context.
   *
   * This operation is primarily used by sellers to monitor their outbound fulfillment work and by administrators to oversee shipment activity across the platform. The underlying table enforces a unique tracking number and maintains indexes by order, seller, status, and creation time, so the search criteria should align with those access patterns. Customers do not use this endpoint as a standalone shipment-management tool; customer-facing shipment visibility is normally consumed through order details, where shipment records are displayed together with the associated order items.
   *
   * The request supports filtering by order, seller, carrier, tracking number, shipment status, and timestamp ranges, along with pagination and sorting. The service should validate that any supplied identifiers exist, return only shipments visible to the caller’s role, and preserve the seller boundary of shipment records. If the query is too broad, the response must still remain paginated and stable for browsing. Detailed shipment contents are intentionally excluded from the list response because shipment-item grouping is presented in order detail views and shipment-specific detail operations.
   *
   * @param connection
   * @param body Shipment search criteria, pagination, and sorting options.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement a paginated shipment search service over shopping_mall_shipments.
   *
   * Apply filters against order id, seller id, status, carrier name, tracking number, and created_at / shipped_at / delivered_at date ranges. Use indexed fields where possible, especially status+created_at, seller+created_at, and order+created_at. Support deterministic sorting, defaulting to newest first. Return only summary data suitable for list browsing.
   *
   * Authorize sellers to see their own shipments, administrators to see all shipments, and customers only if business rules explicitly permit shipment browsing in the current session context; otherwise filter the result set to the caller's allowed scope. Validate UUID inputs, normalize text search for carrier and tracking number, and reject unsupported sort fields. Do not join shipment items here unless the summary contract requires them; shipment contents belong in detail views. Maintain pagination stability and avoid returning soft-deleted rows by default.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IShoppingMallShipment.IRequest,
  ): Promise<IPageIShoppingMallShipment.ISummary> {
    try {
      return await patchShoppingMallSellerShipments({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full detail view for a single shipment record.
   *
   * This endpoint returns one seller-specific fulfillment group that belongs to a single order and a single seller. The shipment record contains the carrier name, tracking number, current shipment state, and the timestamps that describe when the package was shipped and when delivery was confirmed. It is designed for order history pages, seller fulfillment screens, and administrative oversight views where a complete shipment record must be displayed for a single shipment identifier.
   *
   * Customers use this resource through order detail and order history flows to inspect how their order items were grouped into a shipment and to review the associated tracking information after fulfillment. Sellers use the same resource to review the shipment they created for their own order items, while administrators use it for platform oversight and dispute review. Because the shipment is tied to one order and one seller, the access rules must verify that the authenticated actor is allowed to view the shipment through the linked order or seller ownership boundary.
   *
   * The shipment is a historical fulfillment record and must remain available after the package has been completed. The response should therefore expose the shipment's persistent details rather than a mutable workflow object. If the shipment does not exist, or if the requester is not allowed to view it, the service should respond with the usual not-found or access-denied behavior used elsewhere in the platform.
   *
   * @param connection
   * @param shipmentId Shipment identifier.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Load the shipment by its UUID primary key from shopping_mall_shipments.
   * Join or fetch the related order and seller references as needed to enforce access control and to support response assembly.
   * Verify the authenticated actor:
   * - customer may read only when the shipment belongs to an order owned by that customer
   * - seller may read only when the shipment belongs to that seller
   * - administrator may read any shipment
   *
   * Do not accept any request body or additional filters. The endpoint is a direct single-record retrieval.
   *
   * Return the shipment detail DTO with the persisted fields from the shipment table, including IDs, carrier/tracking values, status, shipped_at, delivered_at, created_at, updated_at, and deleted_at if the platform exposes it in read models. Preserve timestamps as stored. If the shipment is not found, return the standard not-found response. If the actor is not authorized, return the standard access-denied response.
   *
   * Because shipment grouping must never cross seller boundaries, there is no need to resolve mixed-seller logic here; that validation belongs to shipment creation flows, not this read endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":shipmentId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallShipment> {
    try {
      return await getShoppingMallSellerShipmentsShipmentId({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
