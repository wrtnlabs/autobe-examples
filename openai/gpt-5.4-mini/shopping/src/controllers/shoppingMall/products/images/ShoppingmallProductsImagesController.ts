@Controller("/shoppingMall/products/:productId/images")
export class ShoppingmallProductsImagesController {
  /**
   * Update the ordered image set for a product listing.
   *
   * This operation lets the owning seller modify the gallery images attached to a marketplace product. Product images are part of the product's visual presentation, and their display order determines which image appears first as the main thumbnail in catalog listings and product detail views.
   *
   * The update applies to the product's current image collection as a single ordered set. Every submitted image must belong to the target product, and the platform must reject the request if it contains images from another product or images that are not currently attached to the product. This preserves the integrity of the product image set and prevents partial reordering when invalid membership is detected.
   *
   * Because product images are business data tied to the product's commercial identity, the platform must execute ownership validation before applying any change. Only the seller who owns the product may update its images. When the product is not eligible for editing, the image update must also be rejected so the image set cannot be changed independently of the product's edit lifecycle.
   *
   * The previous image state must be preserved as part of the product history. This operation therefore supports the broader product snapshot flow so that later reviews of the product's visual presentation can reconstruct the exact ordered image set that existed before the change. After a successful update, the response returns the product's current ordered image collection for immediate UI refresh.
   *
   * @param connection
   * @param productId Target product identifier.
   * @param body Ordered image update payload for the product.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Load the target product by productId and verify it exists and is active for editing. Resolve the authenticated seller and confirm they own the product. Reject the request if the caller is not the product owner.
   *
   * Treat the request as a collection-level replacement of the product's image ordering state. Validate that every referenced image belongs to shopping_mall_product_images for the same shopping_mall_product_id, and ensure no foreign image ids are included. If the request attempts to reorder using images not attached to this product, reject the entire operation without applying partial changes.
   *
   * Apply the update inside a transaction. Before modifying the current image set, capture the previous state for snapshot/history purposes according to the product snapshot workflow. Then update the display_order values and any allowed image metadata for the product's image set so that the smallest display_order remains the first thumbnail image.
   *
   * If the operation includes removing images, preserve the relative order of the remaining images and renumber them consistently so the surviving images stay in intended sequence. Do not allow duplicate display_order values for the same product; respect the unique constraint on (shopping_mall_product_id, display_order).
   *
   * Persist changes to the product image rows and update the product timestamp if the broader product edit flow requires it. Return the updated ordered images sorted by display_order. Handle not-found, ownership conflict, invalid membership, and edit-not-allowed cases with appropriate business errors.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async update(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallProductImage.IUpdate,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await patchShoppingMallProductsProductIdImages({
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single product image that belongs to a specific product.
   *
   * This operation returns one ordered image record from the product image set, including the public image URI, display order, optional alternative text, and lifecycle timestamps. Product images are part of the product’s visual presentation, and the first image in the ordered set serves as the main thumbnail used in listings and detail views.
   *
   * The requested image must belong to the product identified by `productId`. The server must verify that the image record is attached to that product through `shopping_mall_product_images.shopping_mall_product_id` before returning it. If the image does not belong to the specified product, the request must be rejected so that image membership remains consistent with the product image set.
   *
   * This endpoint is intended for seller product management and administrative inspection of image records. It supports workflows such as reviewing the current gallery order, checking the stored image URI, or confirming the image metadata used in product presentation. It does not modify the image set, and it does not return a collection; for the complete gallery, clients should use the product image list operation instead.
   *
   * @param connection
   * @param productId Identifier of the product that owns the image.
   * @param imageId Identifier of the image within the scoped product.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Load the product image by primary key `imageId` and verify that its `shopping_mall_product_id` matches the supplied `productId`.
   * If the record is not found, return not found. If the image belongs to another product, treat it as not found for the scoped resource.
   *
   * Use a read-only query against shopping_mall_product_images, selecting id, shopping_mall_product_id, image_uri, display_order, alt_text, created_at, updated_at, and deleted_at.
   * No transaction is required because this is a single-row read.
   *
   * Authorization should allow the owning seller of the parent product and administrators. If the caller is neither, return forbidden.
   * When the image is deleted, the record may still be stored, but the caller should only receive it if the endpoint policy allows viewing the current stored record; otherwise, treat inactive records according to the project’s visibility rules.
   *
   * Do not load product images from the product table itself, because the canonical image data is stored in shopping_mall_product_images. Do not infer thumbnail ordering in this endpoint; it should simply return the targeted image record.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":imageId")
  public async at(
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedParam("imageId")
    imageId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallProductImage> {
    try {
      return await getShoppingMallProductsProductIdImagesImageId({
        productId,
        imageId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
