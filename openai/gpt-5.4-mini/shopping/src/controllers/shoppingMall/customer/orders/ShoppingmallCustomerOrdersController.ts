import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IPageIShoppingMallOrder } from "../../../../api/structures/IPageIShoppingMallOrder";
import { IShoppingMallOrder } from "../../../../api/structures/IShoppingMallOrder";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderId } from "../../../../providers/getShoppingMallCustomerOrdersOrderId";
import { patchShoppingMallCustomerOrders } from "../../../../providers/patchShoppingMallCustomerOrders";

@Controller("/shoppingMall/customer/orders")
export class ShoppingmallCustomerOrdersController {
  /**
   * Retrieve the authenticated customer's order history as a paginated list of preserved order summaries.
   *
   * This endpoint returns the customer's committed purchase records from the shopping_mall_orders table, using the order number, placed timestamp, final total amount, and overall order status that are stored on each order header. The list is sorted with the newest orders first so the most recent purchases appear at the top of the history view.
   *
   * The response remains available even when the customer account itself has later been deleted, because order records are retained independently for legal, seller-record, and after-sales support purposes. The API therefore reads preserved order data from shopping_mall_orders rather than depending on mutable customer profile state. Consumers should use the order detail endpoint after this list endpoint when they need item-level lines, shipping information, or shipment tracking data.
   *
   * Access is limited to the authenticated customer actor. The service must scope the query to the current customer identity obtained from the authentication context and must not accept an arbitrary customer identifier in the request. Pagination, sorting, and any optional list filters are carried in the request body so the client can request consistent history windows without exposing additional path parameters.
   *
   * @param connection
   * @param body Pagination and list criteria for the authenticated customer's order history.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement a customer-scoped paginated query over shopping_mall_orders.
   *
   * Use the authenticated customer identity from the security context to filter shopping_mall_orders.shopping_mall_customer_id. Do not accept a customerId path parameter or request field. Exclude deleted-at orders only if the service's order retention policy explicitly requires hiding them from active history; otherwise preserve and return retained records because the business requirement states order history must remain available after customer deletion.
   *
   * Sort results by shopping_mall_orders.placed_at descending, with a stable secondary sort on created_at or id if needed for deterministic pagination. Return only summary fields required by the list UI: order_number, placed_at, total_amount, and status. If the summary DTO also includes identifier fields for navigation, map them directly from the order id.
   *
   * Implement pagination in the service layer with a consistent page size and total count. Use a single count query for the authenticated customer's scope and a paginated select query for the page data. Apply any optional search or status filters defined by the request DTO only if they are part of the generated schema. Reject attempts to query another customer's orders.
   *
   * No transaction is required because this is a read-only operation. If the authenticated principal is missing or not a customer, return an authorization failure. If there are no orders, return an empty page rather than an error. Preserve the historical order data exactly as stored so that deleted customer accounts do not affect order history visibility.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IShoppingMallOrder.IRequest,
  ): Promise<IPageIShoppingMallOrder.ISummary> {
    try {
      return await patchShoppingMallCustomerOrders({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the full detail of a single committed order, including its header information, preserved shipping destination context, order items, and shipment records.
   *
   * This endpoint returns the authoritative order history record stored in the shopping mall platform. The order header comes from the committed order table, which preserves the order number, owning customer reference, selected shipping address reference, monetary totals, overall lifecycle status, and the timestamps that describe when the checkout was completed and when payment was confirmed. It is designed for the customer order history page and for administrative oversight of platform-wide orders.
   *
   * The response remains available even when the customer account has later been deleted, because order history is preserved for legal and seller-record purposes. The endpoint must therefore read from the preserved order record itself rather than depending on the live customer account state. The related order items and shipment records are included so the consumer can present the full purchase breakdown, item-level status, and fulfillment tracking information in one detail view.
   *
   * Access to this endpoint should be limited to the owning customer and to administrators with platform oversight privileges. The implementation must verify that the requester is authorized to view the target order, except in administrative read contexts. If the order does not exist or is not visible to the requester, the service should return the standard not-found or forbidden response according to the platform's authorization policy.
   *
   * The endpoint depends on the order history listing operation for navigation: customers typically open the paginated order list first, then retrieve this detail view for a selected order number or order identifier. This detail endpoint is the source of truth for the committed purchase record and should not be reconstructed from cart, checkout, or live product state.
   *
   * @param connection
   * @param orderId The order's unique identifier.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load one order by its UUID primary key and include related detail data needed for a complete history view.
   *
   * Implementation should query shopping_mall_orders by id, eagerly loading the related customer reference, shipping address reference, order items, and shipments. The response should be assembled from the committed order record and its direct relations only; do not derive totals or status from live cart, product, or checkout state. Use the stored subtotal_amount, shipping_fee_amount, discount_amount, total_amount, placed_at, paid_at, and status fields as the authoritative values.
   *
   * For order items, join shopping_mall_order_items by shopping_mall_order_id and return each line item with its quantity, status, and relevant timestamps so the UI can show the item-level state. For shipments, join shopping_mall_shipments by shopping_mall_order_id and include carrier_name, tracking_number, status, shipped_at, and delivered_at so the customer can review fulfillment progress. For the shipping address, return the preserved address context if the relation exists; if the address was removed from the live account, the order record should still remain readable using the stored reference.
   *
   * Authorization must allow the owning customer to access their own order and administrators to access any order. If the caller is a customer, compare the authenticated customer id with shopping_mall_customer_id. If the order belongs to another customer, reject the request. If the record is missing, return not found. No mutation is involved, so no transaction is needed beyond a read-only query.
   *
   * Do not include checkout, payment retry, cancellation, or refund workflow logic here. Those are separate business operations and should not be triggered by this detail read. The endpoint is purely for retrieving the stored order record and its preserved related data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":orderId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrder> {
    try {
      return await getShoppingMallCustomerOrdersOrderId({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
