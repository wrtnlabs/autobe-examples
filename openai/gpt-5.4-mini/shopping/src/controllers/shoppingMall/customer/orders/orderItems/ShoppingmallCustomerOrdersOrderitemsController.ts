  /**
   * Retrieve the line items that belong to a specific order in a paginated, order-scoped collection view.
   *
   * This endpoint returns the purchased order items that were created when the order was successfully placed. Each item represents a specific purchased product variant and preserves the historical purchase state for the order, including the item status and the identity context that must remain stable for legal, seller-record, and customer support purposes. The parent order provides the ownership boundary, and the item list should always be interpreted within that order context.
   *
   * The response is intended for customers viewing their own order history, sellers reviewing the items they must fulfill for their own products, and administrators overseeing platform-wide order activity. Because the order history must remain available even after account deletion, this list must continue to read from the preserved order records rather than from mutable account-facing profile data.
   *
   * Use this endpoint together with the single-order detail endpoint when a client needs both the order header and the item breakdown. The list should support pagination and sorting so that larger orders can be rendered efficiently. Filtering by item status is appropriate when the caller needs to isolate paid, shipped, delivered, cancelled, or refunded items during fulfillment, support, or dispute workflows.
   *
   * The endpoint must not alter order contents. It is a read operation over the persisted order-item records that were created at checkout time and later updated only through the allowed order lifecycle actions such as shipping, delivery confirmation, cancellation, refund, or administrator enforcement.
   *
   * @param connection
   * @param orderId Target order ID.
   * @param body Search, filtering, sorting, and pagination criteria for the order's items.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query order items by orderId from shopping_mall_order_items with strict parent-order scoping.
   * Validate that the order exists and that the authenticated actor is allowed to view the order: the customer who owns the order, a seller responsible for at least one item in the order, or an administrator.
   *
   * Apply optional request-body filters for item status, keyword search over preserved item/product snapshot display fields, and pagination/sorting controls. Default sort should favor stable order-item listing behavior for the client; if the requirements for order detail views require a specific order, preserve creation/order-item sequence unless an explicit sort is requested.
   *
   * Return only items that belong to the requested orderId. Do not join mutable product or seller profile tables for display identity when historical values are required; instead, use the order item snapshot/history representation if available in the read model so that historical product name, variant values, and seller identity remain stable.
   *
   * The query should be read-only and non-mutating. If the order does not exist, or the caller cannot access it, return the standard not-found or forbidden response. If the order exists but has no items, return an empty page with pagination metadata.
   *
   * For each row, project summary fields suitable for list rendering: item identity, order linkage, purchased product/variant display, quantity, item status, and any preserved pricing or snapshot-derived display information needed by consumers.
   *
   * If the service layer uses a repository pattern, implement a single paginated query constrained by orderId and indexed filters to avoid loading the full order aggregate. Ensure total counts reflect only items in that order.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IShoppingMallOrderItem.IRequest,
  ): Promise<IPageIShoppingMallOrderItem.ISummary> {
    try {
      return await patchShoppingMallCustomerOrdersOrderIdOrderItems({
        customer,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the detailed record for one purchased order item that belongs to a specific order.
   *
   * This endpoint returns the live transactional state of a single line item within an order, including the purchased quantity, fulfillment status, and the timestamps that record when the item was shipped, delivered, cancelled, or refunded. The order-item table is the authoritative source for this current line-item state, while the parent order record preserves the checkout header and historical order context for customer history and seller/legal record keeping.
   *
   * Access is intended for the customer who owns the order, the seller responsible for the item’s product fulfillment context, and administrators performing platform oversight. The lookup must verify that the requested order item belongs to the specified order before returning data. If the item does not exist, is not part of the order, or is not visible to the caller’s role, the request must fail with a not-found or authorization error as appropriate.
   *
   * This endpoint is especially important for order history screens and dispute-resolution workflows. Even when a customer account has been deleted, the order history and item records remain available through preserved order data, so this detail view continues to function for retained purchase records. The response reflects the current item status only; preserved snapshots of the purchase state are stored separately and should be accessed through snapshot-oriented APIs when historical state comparisons are needed.
   *
   * @param connection
   * @param orderId Target order ID
   * @param orderItemId Target order item ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Load the parent order by orderId, then load the order item by orderItemId with a strict ownership check against the parent order. Use a single read query or a joined lookup that enforces both identifiers together so an item from a different order cannot be returned.
   *
   * Select the live columns from shopping_mall_order_items: id, shopping_mall_order_id, shopping_mall_product_variant_id, quantity, status, shipped_at, delivered_at, cancelled_at, refunded_at, created_at, updated_at, and deleted_at. The implementation should also verify the parent order exists in shopping_mall_orders and is consistent with the requested item scope.
   *
   * Apply authorization rules before returning the record: the owning customer may read their own order item, the responsible seller may read items associated with their products, and administrators may read any order item. If the caller lacks access, return a forbidden response. If the order or item cannot be found under the given parent relationship, return not found.
   *
   * No request body is required. No mutation logic, inventory adjustment, or snapshot creation belongs here. The endpoint is strictly read-only and must not expose unrelated collections or historical snapshots; those belong to separate APIs.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
