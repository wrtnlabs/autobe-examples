import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IShoppingMallOrderTrackingItem } from "../../../../../api/structures/IShoppingMallOrderTrackingItem";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getShoppingMallCustomerOrdersOrderIdTracking } from "../../../../../providers/getShoppingMallCustomerOrdersOrderIdTracking";

@Controller("/shoppingMall/customer/orders/:orderId/tracking")
export class ShoppingmallCustomerOrdersTrackingController {
  /**
   * Retrieve the shipment tracking information for a specific order.
   *
   * This endpoint provides the package-level delivery reference that belongs to the order’s shipment record. The shipment stores the carrier name and tracking number as the shared tracking context for all order items included in that shipment, so customers can follow delivery progress from the purchase history and order detail screens.
   *
   * The response is intended for the authenticated customer who owns the order, while sellers and administrators may access it when their permissions allow inspection of fulfillment records. Because the tracking information is part of the preserved purchase record, the API should return the current shipment tracking state even after later account or catalog changes.
   *
   * This operation does not expose editable shipment data and does not return order item mutation data. It is a read-only detail lookup that should resolve the order by its identifier, load the related shipment records, and present their carrier and tracking information together with shipment status and timestamps. If the order has multiple shipments, each shipment should be represented as a separate tracking entry because different sellers ship separately and each shipment carries one shared tracking context.
   *
   * @param connection
   * @param orderId Target order's ID.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement a read-only order tracking lookup that loads shipment records belonging to the given order ID. Resolve the order first, verify the requester is allowed to view the order, then query shopping_mall_shipments by shopping_mall_order_id ordered by created_at ascending or by fulfillment relevance if needed.
   *
   * Return carrier_name, tracking_number, status, shipped_at, and delivered_at for each shipment. If the order has no shipment records yet, return an empty tracking collection or a not-yet-shipped state representation, depending on the response schema design. Do not include order item mutation fields or shipment editing capabilities.
   *
   * Enforce ownership and access control: the order owner may view the data, and seller/admin roles may view it only when permitted by the platform authorization rules. If the order does not exist or the requester lacks access, return the standard not found or forbidden response from the application layer.
   *
   * Since tracking information is shared across all items in a shipment, do not attempt per-item tracking joins or item-level carrier overrides. Use the shipment as the single source of truth for tracking context.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallOrderTrackingItem> {
    try {
      return await getShoppingMallCustomerOrdersOrderIdTracking({
        customer,
        orderId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
