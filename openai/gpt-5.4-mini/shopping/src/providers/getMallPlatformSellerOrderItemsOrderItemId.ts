export async function getMallPlatformSellerOrderItemsOrderItemId(props: {
  seller: SellerPayload;
  orderItemId: string & tags.Format<"uuid">;
}): Promise<IMallPlatformOrderItem> {
  const record =
    await MyGlobal.prisma.mall_platform_order_items.findFirstOrThrow({
      where: {
        id: props.orderItemId,
        mall_platform_seller_id: props.seller.id,
      },
      ...MallPlatformOrderItemTransformer.select(),
    });
  return await MallPlatformOrderItemTransformer.transform(record);
}


