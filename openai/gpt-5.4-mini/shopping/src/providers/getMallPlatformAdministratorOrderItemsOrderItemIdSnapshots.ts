export async function getMallPlatformAdministratorOrderItemsOrderItemIdSnapshots(props: {
  administrator: AdministratorPayload;
  orderItemId: string & tags.Format<"uuid">;
}): Promise<IPageIMallPlatformOrderItemSnapshot.ISummary> {
  await MyGlobal.prisma.mall_platform_administrators.findUniqueOrThrow({
    where: { id: props.administrator.id },
    select: { id: true },
  });
  await MyGlobal.prisma.mall_platform_order_items.findUniqueOrThrow({
    where: { id: props.orderItemId },
    select: { id: true },
  });
  const page: number = 1;
  const limit: number = 100;
  const skip: number = (page - 1) * limit;
  const records =
    await MyGlobal.prisma.mall_platform_order_item_snapshots.findMany({
      where: { mall_platform_order_item_id: props.orderItemId },
      orderBy: [{ snapshot_at: "desc" }, { created_at: "desc" }],
      skip,
      take: limit,
      ...MallPlatformOrderItemSnapshotAtSummaryTransformer.select(),
    });
  const total = await MyGlobal.prisma.mall_platform_order_item_snapshots.count({
    where: { mall_platform_order_item_id: props.orderItemId },
  });
  return {
    pagination: {
      current: page,
      limit,
      records: total,
      pages: Math.ceil(total / limit),
    },
    data: await ArrayUtil.asyncMap(
      records,
      MallPlatformOrderItemSnapshotAtSummaryTransformer.transform,
    ),
  };
}


