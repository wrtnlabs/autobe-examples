/**
 * Restore a deleted todo from the authenticated member’s trash and return it to the active todo list.
 *
 * This operation is part of the private todo recovery workflow. A member can open a deleted todo from trash and restore it so the todo becomes visible again in the normal todo list. The restored todo keeps its original ownership, title, description, dates, completion state, and edit history; only its deleted state is cleared so it is no longer treated as trash content.
 *
 * This endpoint is available only to authenticated members because todo data is private and each todo belongs to exactly one member account. The server must verify that the target todo belongs to the current member and is currently deleted before performing the restore. If the todo is not deleted, the request must be rejected. If the todo does not belong to the current member, access must be denied.
 *
 * The restore action is commonly used together with the trash list endpoint that shows deleted todos in paginated form. A client should first retrieve trashed todos, then call this restore operation for the selected todo, and finally refresh the active todo list so the restored item appears again in normal browsing. The edit history associated with the todo remains available after restoration and does not need any separate recovery step.
 *
 * @param props.connection
 * @param props.todoId The identifier of the deleted todo to restore.
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Implement a member-scoped todo restoration command.
 *
 * 1. Authenticate the request and resolve the current member identity from the session or access token.
 * 2. Load the target todo by its path parameter `todoId`.
 * 3. Verify the todo exists and belongs to the authenticated member. If not, return a forbidden or not-found style error consistent with the application’s security rules.
 * 4. Verify the todo is currently marked as deleted and therefore eligible for restoration. If it is already active, reject the request as invalid state.
 * 5. Update only the deletion-related state so the todo is returned to the active set. Preserve all other fields, including title, description, start date, due date, completion status, ownership, and created timestamp.
 * 6. Do not alter or recreate edit-history rows. Existing TodoHistory entries remain linked to the restored todo.
 * 7. Execute the state change atomically in a transaction to prevent races with concurrent restore or permanent-delete actions.
 * 8. Return the restored todo payload after the update so the client can refresh its view.
 *
 * Edge cases:
 * - If the todo is missing, respond with the system’s standard not-found behavior.
 * - If the todo belongs to another member, deny access without exposing ownership details.
 * - If the todo is not deleted, reject the restore attempt because only trashed todos can be restored.
 * - If the todo was permanently deleted before this request, treat it as missing.
 *
 * This endpoint must not accept a request body because the action has no mutable input beyond the todo identifier.
 * @path /todoApp/member/todos/trash/:todoId/restore
 * @accessor api.functional.todoApp.member.todos.trash.restore.patchByTodoid
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function patchByTodoid(
  connection: IConnection,
  props: patchByTodoid.Props,
): Promise<patchByTodoid.Response> {
  return true === connection.simulate
    ? patchByTodoid.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...patchByTodoid.METADATA,
          path: patchByTodoid.path(props),
          status: null,
        },
      );
}
