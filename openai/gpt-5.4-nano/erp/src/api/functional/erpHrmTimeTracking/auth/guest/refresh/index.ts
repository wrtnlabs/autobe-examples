/**
 * This endpoint renews guest authentication tokens without requiring the guest to re-submit join credentials.
 *
 * It is explicitly limited to the guest actor by authorizationActor='guest' and uses the required DTO type IErpHrmTimeTrackingGuest.IRefresh for the request and IErpHrmTimeTrackingGuest.IAuthorized for the response.
 *
 * Implementation must validate the provided refresh token and map it to a persisted guest session record so that token renewal remains consistent with the server-side session artifacts (erp_hrm_time_tracking_guest_sessions) and the guest identity record (erp_hrm_time_tracking_guests).
 *
 * Security considerations: treat refresh tokens as secrets; never log raw refresh token values; on failure conditions (expired token, revoked session, signature mismatch), return 401/403 without revealing which validation step failed. If refresh-token rotation is implemented, ensure the old refresh token is invalidated so that replay attempts do not succeed.
 *
 * Related operations: clients should use the refresh token obtained from the successful response of POST /auth/guest/join and call this endpoint when access tokens expire.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest refresh payload containing the refresh token (and any required context) used for token renewal.
 * @x-autobe-authorization-type refresh
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implement POST /auth/guest/refresh as token renewal for guest actor. Parse JSON body according to IErpHrmTimeTrackingGuest.IRefresh. Validate the refresh token signature and expiry. Look up the guest session record in erp_hrm_time_tracking_guest_sessions and ensure it is associated with the correct guest identity in erp_hrm_time_tracking_guests. If schema supports rotation, revoke/replace the old refresh token mapping atomically in a transaction. Issue a new access token and (if required by DTO) a new refresh token, returning IErpHrmTimeTrackingGuest.IAuthorized.
 *
 * On invalid/expired refresh tokens, return 401 Unauthorized. On mismatched session/guest identity, return 403 Forbidden. Ensure idempotency where possible (e.g., if the same refresh token is submitted twice during rotation, second call should fail after revocation).
 *
 * Return 200 with IErpHrmTimeTrackingGuest.IAuthorized on success.
 * @path /erpHrmTimeTracking/auth/guest/refresh
 * @accessor api.functional.erpHrmTimeTracking.auth.guest.refresh.refreshGuest
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refreshGuest(
  connection: IConnection,
  props: refreshGuest.Props,
): Promise<refreshGuest.Response> {
  const output: refreshGuest.Response =
    true === connection.simulate
      ? refreshGuest.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...refreshGuest.METADATA,
            path: refreshGuest.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace refreshGuest {
  export type Props = {
    /**
     * Guest refresh payload containing the refresh token (and any required context) used for token renewal.
     */
    body: IErpHrmTimeTrackingGuest.IRefresh;
  };
  export type Body = IErpHrmTimeTrackingGuest.IRefresh;
  export type Response = IErpHrmTimeTrackingGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/erpHrmTimeTracking/auth/guest/refresh",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/erpHrmTimeTracking/auth/guest/refresh";
  export const random = (): IErpHrmTimeTrackingGuest.IAuthorized =>
    typia.random<IErpHrmTimeTrackingGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: refreshGuest.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refreshGuest.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
