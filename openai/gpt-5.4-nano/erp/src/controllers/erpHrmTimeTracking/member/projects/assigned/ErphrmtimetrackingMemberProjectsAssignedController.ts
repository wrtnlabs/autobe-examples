@Controller("/erpHrmTimeTracking/member/projects/assigned")
export class ErphrmtimetrackingMemberProjectsAssignedController {
  /**
   * Retrieve the list of projects assigned to the currently authenticated member within the selected organization context.
   *
   * This endpoint supports the “assigned projects” browsing flow. The server determines which projects are assigned by reading the member’s current ProjectMembership entries within the selected organization boundary. Since membership rows drive the employee’s eligible projects, removed memberships should no longer appear in the returned assigned list.
   *
   * Authorization is enforced so that the authenticated member can only view assignments that belong to the currently selected organization context. The returned list is intended for UI discovery and project selection.
   *
   * The request is a PATCH operation to allow request-body driven search/filtering and pagination. The server applies any search constraints over project fields that are included in the summary payload.
   *
   * Related operations: membership management (create/remove project memberships) must be reflected immediately in this assigned-projects view, ensuring consistency between membership changes and browsing results.
   *
   * @param connection
   * @param body Search, filtering, and pagination criteria for retrieving the requesting member’s assigned projects within the selected organization context.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1) Read organization context from the request context (selected organization) established by middleware.
   * 2) Identify the requesting member/employee identity.
   * 3) Query erp_hrm_time_tracking_project_memberships where:
   *    - employee_id = requesting employee id
   *    - deleted_at IS NULL
   *    - join to erp_hrm_time_tracking_projects to ensure erp_hrm_time_tracking_organization_id = selected organization id
   *    - projects.deleted_at IS NULL
   * 4) Join to erp_hrm_time_tracking_projects and select only the columns required by the assigned-project summary DTO.
   * 5) Apply requestBody filtering/sorting/pagination (as defined by IErpHrmTimeTrackingProject membership request DTO) after scoping to memberships/projects.
   * 6) Return a paginated payload of project summaries.
   *
   * Edge cases:
   * - If no memberships exist for the employee in the organization, return an empty paginated result.
   * - Ensure deterministic ordering (use project id as a tie-breaker).
   *
   * No writes are performed.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimeTrackingProjectMembership.IRequest,
  ): Promise<IPageIErpHrmTimeTrackingProject.ISummary> {
    try {
      return await patchErpHrmTimeTrackingMemberProjectsAssigned({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
