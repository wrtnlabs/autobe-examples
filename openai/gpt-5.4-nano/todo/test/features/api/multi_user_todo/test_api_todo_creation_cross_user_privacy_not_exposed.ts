export async function test_api_todo_creation_cross_user_privacy_not_exposed(
  connection: api.IConnection,
): Promise<void> {
  // 1) Member A joins
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuth = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.pick([true, false]),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(memberAAuth);
  // 2) Member B joins
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuth = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.pick([true, false]),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(memberBAuth);
  // 3) Member A creates a todo
  const created = await generate_random_multi_user_todo_member_todos_create(
    memberAConnection,
    {
      body: {
        title: `todo-${RandomGenerator.alphabets(10)}`,
        description: null,
        startDate: null,
        dueDate: null,
      } satisfies IMultiUserTodoEditHistoryEntry.ICreate,
    },
  );
  typia.assert(created);
  const todoId = created.id;
  // 4) Member B attempts to retrieve Member A's todo
  await TestValidator.error(
    "member B cannot access member A todo",
    async () => {
      await api.functional.multiUserTodo.member.todos.at(memberBConnection, {
        todoId,
      });
    },
  );
}
