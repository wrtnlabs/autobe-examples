export async function test_api_trash_todo_detail_not_in_trash_rejected(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_member_join(memberConnection, {
    body: typia.random<IMultiUserTodoMember.IJoin>(),
  });
  typia.assert(authorized);
  const todoId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "trash detail should reject when todo is not in trash",
    async () => {
      const result = await api.functional.multiUserTodo.member.trash.at(
        memberConnection,
        { todoId },
      );
      typia.assert(result);
    },
  );
}
