export async function test_api_user_profile_get_other_profile_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // Member A joins
  const memberAConnection: api.IConnection = { host: connection.host };
  const memberAAuth = await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.pick([true, false]),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(memberAAuth);
  // Member B joins
  const memberBConnection: api.IConnection = { host: connection.host };
  const memberBAuth = await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.pick([true, false]),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  typia.assert(memberBAuth);
  // Attempt to fetch Member B's profile using Member B's identifier.
  // The endpoint should enforce privacy and deny cross-member access.
  await TestValidator.error(
    "should deny access to other member profile",
    async () => {
      await api.functional.multiUserTodo.member.profiles.at(memberAConnection, {
        profileId: memberBAuth.id,
      });
    },
  );
}
