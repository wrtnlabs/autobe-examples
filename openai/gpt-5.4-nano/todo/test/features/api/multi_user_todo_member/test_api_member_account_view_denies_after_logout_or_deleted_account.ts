export async function test_api_member_account_view_denies_after_logout_or_deleted_account(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.pick([true, false]),
    } satisfies IMultiUserTodoMember.IJoin,
  });
  const profileBefore =
    await api.functional.multiUserTodo.member.account.at(memberConnection);
  typia.assert(profileBefore);
  const loggedOutConnection: api.IConnection = { host: connection.host };
  await TestValidator.error(
    "member account access denied after logout",
    async () => {
      await api.functional.multiUserTodo.member.account.at(loggedOutConnection);
    },
  );
}
