/**
 * Register/initialize a guest authentication context and issue tokens.
 *
 * This endpoint accepts an IMultiUserTodoGuest.IJoin request and returns IMultiUserTodoGuest.IAuthorized containing newly issued authentication tokens.
 *
 * Security behavior: only valid join inputs result in token issuance; invalid inputs must not create a token response.
 *
 * This operation is the entry point for guests to obtain credentials and later use the refresh flow.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest join payload used to initialize the guest authentication context and request token issuance.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implement guest join that validates the
 *   IMultiUserTodoGuest.IJoin payload, creates the guest authentication
 *   context/session as defined by the system, and issues JWT tokens returned in
 *   IMultiUserTodoGuest.IAuthorized. On validation or business-rule failure,
 *   respond with an appropriate 4xx error and do not issue tokens.
 * @path /multiUserTodo/auth/guest/join
 * @accessor api.functional.multiUserTodo.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
