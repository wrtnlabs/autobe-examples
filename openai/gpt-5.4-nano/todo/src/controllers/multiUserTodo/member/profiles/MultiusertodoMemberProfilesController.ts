import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoUserProfile } from "../../../../api/structures/IMultiUserTodoUserProfile";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getMultiUserTodoMemberProfilesProfileId } from "../../../../providers/getMultiUserTodoMemberProfilesProfileId";
import { patchMultiUserTodoMemberProfiles } from "../../../../providers/patchMultiUserTodoMemberProfiles";

@Controller("/multiUserTodo/member/profiles")
export class MultiusertodoMemberProfilesController {
  /**
   * Update the authenticated member’s profile display name for this private todo app.
   *
   * This endpoint allows a signed-in member to change only their own UserProfile display_name stored in multi_user_todo_user_profiles.
   *
   * Validation and privacy guarantees:
   * - The update must be scoped to the authenticated user’s own profile (multi_user_todo_user_id). The client must not be able to target another user’s profile.
   * - If the request would result in an empty display_name, the system rejects the update and keeps the existing value unchanged.
   * - If the authenticated user has no available (non-deleted) profile record, the update is rejected.
   *
   * After the update is accepted, subsequent reads of the profile must reflect the newly saved display_name.
   *
   * @param connection
   * @param body Profile update payload containing the new display_name for the authenticated user’s profile.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation guidance for Realize Agent:
   *
   * 1. Authentication/context
   * - Require authenticated member context.
   * - Derive authenticatedUserId from the request context; do not accept any user identifier from the client for this operation.
   *
   * 2. Load and validate target profile
   * - Query multi_user_todo_user_profiles by multi_user_todo_user_id = authenticatedUserId.
   * - If no record exists or the record has deleted_at set (soft-deleted), reject as not found/unavailable for update.
   *
   * 3. Validate input
   * - Read display_name from the request body.
   * - Trim leading/trailing whitespace.
   * - Reject if trimmed display_name is empty (empty display name edit must be rejected and existing data preserved).
   *
   * 4. Persist update
   * - Update multi_user_todo_user_profiles.display_name with the validated value.
   * - Update multi_user_todo_user_profiles.updated_at to the current server timestamp.
   *
   * 5. Return response
   * - Return the updated multi_user_todo_user_profiles row as JSON.
   *
   * 6. Error handling
   * - For any validation failure, do not modify the database.
   * - For missing/unavailable profile, return an error indicating the profile cannot be updated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateProfile(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoUserProfile.IUpdate,
  ): Promise<IMultiUserTodoUserProfile> {
    try {
      return await patchMultiUserTodoMemberProfiles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the authenticated member’s private user profile by profile identifier.
   *
   * This private todo app must ensure members cannot view any other user’s profile details. If a request targets a profile that does not belong to the authenticated user, the system must deny access without exposing other users’ profile data.
   *
   * The profile is only available when it is not soft-deleted (deleted_at is null).
   *
   * @param connection
   * @param profileId Profile identifier (UUID). The system must return the profile only if it belongs to the authenticated user (privacy boundary).
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1) Require an authenticated member context (authenticated account id).
   * 2) Validate profileId format (UUID) and return an error for invalid input.
   * 3) Query multi_user_todo_user_profiles by id = profileId and deleted_at IS NULL.
   * 4) If no row matches, return a not-found/unavailable response (treated as unavailable).
   * 5) Ownership enforcement: verify the row’s multi_user_todo_user_id equals the authenticated user id.
   *    - If it does not match, deny access (do not reveal whether the profile exists for another user).
   * 6) Map fields to response:
   *    - id
   *    - multi_user_todo_user_id (if present in the DTO; otherwise omit in mapping layer)
   *    - display_name
   *    - created_at
   *    - updated_at
   * 7) Do not join or return any todo or edit history data; profile operations are independent of todo ownership visibility.
   *
   * Error handling:
   * - Invalid UUID => 400-like validation error.
   * - Not found or soft-deleted => 404-like not found.
   * - Ownership mismatch => 403-like forbidden/access denied.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":profileId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("profileId")
    profileId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoUserProfile> {
    try {
      return await getMultiUserTodoMemberProfilesProfileId({
        member,
        profileId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
