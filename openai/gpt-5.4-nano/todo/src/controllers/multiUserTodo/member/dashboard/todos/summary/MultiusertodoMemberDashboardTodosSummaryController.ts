@Controller("/multiUserTodo/member/dashboard/todos/summary")
export class MultiusertodoMemberDashboardTodosSummaryController {
  /**
   * Return an authenticated member’s todo dashboard summary (normal vs trash).
   *
   * This endpoint provides a single aggregated overview so the client can render counts and quick status indicators without browsing full todo lists.
   *
   * Privacy and visibility are enforced:
   * - The system only considers todos owned by the authenticated member.
   * - Normal vs trash separation is respected using deleted_at-based visibility (normal excludes deleted todos; trash includes deleted-but-not-permanently-removed todos).
   * - The operation does not allow mixing normal and trashed results; it only returns the pre-separated aggregates.
   *
   * Error handling:
   * - If the authenticated user context is missing/invalid, access fails via the existing authentication layer.
   * - If no todos exist in a bucket, counts are returned as 0.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   * 1) Authenticate request as member; derive authenticatedMemberId from auth context.
   * 2) Query multi_user_todo_todos for records scoped to the authenticated owner.
   *    - Use multi_user_todos.deleted_at to separate buckets:
   *      - Normal bucket: deleted_at IS NULL.
   *      - Trash bucket: deleted_at IS NOT NULL.
   *    - Apply lifecycle_state constraints consistently if the service-layer defines additional trash/visibility semantics for lifecycle_state; otherwise keep visibility aligned with deleted_at rules.
   * 3) Compute aggregates for each bucket using only the fields available in the schema:
   *    - totalCount: COUNT(*).
   *    - completeCount: COUNT WHERE is_complete = true.
   *    - incompleteCount: COUNT WHERE is_complete = false.
   *    - startDateSetCount: COUNT WHERE start_date IS NOT NULL.
   *    - dueDateSetCount: COUNT WHERE due_date IS NOT NULL.
   *    - createdAtNewestAt/OldestAt (if supported by the DTO): derive from created_at.
   * 4) Never expose individual todo rows or any content beyond the summary DTO.
   * 5) Return a single JSON object matching IMultiUserTodoTodoSummary.
   *
   * Edge cases:
   * - No rows in a bucket: return counts as 0.
   * - Ensure privacy isolation: do not accept any client-provided owner identifiers; always use authenticatedMemberId for scoping.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IMultiUserTodoTodoEditHistoryEntry> {
    try {
      return await getMultiUserTodoMemberDashboardTodosSummary({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
