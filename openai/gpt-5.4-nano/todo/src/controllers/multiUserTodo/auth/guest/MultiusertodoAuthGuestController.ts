import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoUserProfile } from "../../../../api/structures/IMultiUserTodoUserProfile";
import { postMultiUserTodoAuthGuestJoin } from "../../../../providers/postMultiUserTodoAuthGuestJoin";
import { postMultiUserTodoAuthGuestRefresh } from "../../../../providers/postMultiUserTodoAuthGuestRefresh";

@Controller("/multiUserTodo/auth/guest")
export class MultiusertodoAuthGuestController {
  /**
   * Register/initialize a guest authentication context and issue tokens.
   *
   * This endpoint accepts an IMultiUserTodoGuest.IJoin request and returns IMultiUserTodoGuest.IAuthorized containing newly issued authentication tokens.
   *
   * Security behavior: only valid join inputs result in token issuance; invalid inputs must not create a token response.
   *
   * This operation is the entry point for guests to obtain credentials and later use the refresh flow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest join payload used to initialize the guest authentication context and request token issuance.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implement guest join that validates the
     *   IMultiUserTodoGuest.IJoin payload, creates the guest authentication
     *   context/session as defined by the system, and issues JWT tokens
     *   returned in IMultiUserTodoGuest.IAuthorized. On validation or
     *   business-rule failure, respond with an appropriate 4xx error and do not
     *   issue tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoUserProfile.IJoin,
  ): Promise<IMultiUserTodoUserProfile.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew guest authentication tokens.
   *
   * This endpoint accepts an IMultiUserTodoGuest.IRefresh request and returns IMultiUserTodoGuest.IAuthorized with renewed tokens.
   *
   * Security behavior: always verify refresh credential integrity and expiry before issuing new tokens; never issue tokens on validation failure.
   *
   * Integrates into the guest authentication workflow after join.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest refresh payload containing the credential needed to renew tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implement guest refresh that validates the
     *   provided refresh credential in IMultiUserTodoGuest.IRefresh, checks
     *   token integrity/expiry, and issues a new set of JWT tokens returned in
     *   IMultiUserTodoGuest.IAuthorized. If the refresh credential is
     *   invalid/expired, return a 4xx error and do not issue tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoUserProfile.IRefresh,
  ): Promise<IMultiUserTodoUserProfile.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
