import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { ITodoAppGuest } from "../../../../../api/structures/ITodoAppGuest";
import { postTodoAppAuthGuestJoin } from "../../../../../providers/postTodoAppAuthGuestJoin";

@Controller("/todoApp/auth/guest/join")
export class TodoappAuthGuestJoinController {
  /**
   * This operation creates the guest account identity and starts an authenticated guest session for subsequent token-based access.
   *
   * For guests, the system does not use email/password credentials. Instead, a stable guest identity is stored in `todo_app_guests`, where the critical field is `device_identifier` (unique). The guest lifecycle is tracked using `created_at`, `updated_at`, and `deleted_at`; if `deleted_at` is set, the identity is considered unusable for new sessions and a fresh identity should be created.
   *
   * After establishing (or finding) the guest identity, the operation records a concrete session context in `todo_app_guest_sessions`. That table stores `ip`, `href`, and `referrer` captured at the session start, and it defines when the session expires via `expired_at`. The row is also guarded by `deleted_at` for lifecycle cleanup.
   *
   * Security-wise, the issued JWT must be derived from the newly created session record: the server should include enough claims to map the token back to the specific guest identity (`todo_app_guest_id`) and the active session. Expiration enforcement must be consistent with `todo_app_guest_sessions.expired_at`; tokens tied to expired or deleted session rows must be rejected by the refresh workflow.
   *
   * Related authentication workflow: once this endpoint returns `ITodoAppGuest.IAuthorized`, the client can call `PATCH/POST /auth/guest/refresh` (depending on the generated method signature for guest refresh) to renew tokens when they approach expiration. No logout endpoint is provided; clients discard tokens when done.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration payload used to create (or reuse) a guest identity and establish the initial guest session context.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Implement POST /auth/guest/join as guest identity registration and session bootstrap. Steps: 1) Validate request payload fields required by ITodoAppGuest.IJoin. 2) Enforce uniqueness of device_identifier against todo_app_guests.device_identifier; if an existing guest identity exists with deleted_at != null, treat as non-existent (create new). 3) Create or reuse todo_app_guests row: if reuse, update updated_at; otherwise insert new with created_at/updated_at. 4) Create todo_app_guest_sessions row linked by todo_app_guest_id with ip/href/referrer and set expired_at according to configured guest session lifetime; created_at/updated_at now. 5) Generate JWT access token encoding guest identity (todo_app_guest_id) and session id (todo_app_guest_sessions.id) plus expiration derived from expired_at. 6) Return ITodoAppGuest.IAuthorized payload including issued tokens. Errors: duplicate device identifier conflicts resolved by reuse; if any DB insert fails, return 500. Validation errors: missing/invalid device identifier, ip, href, referrer formatting per DTO schema.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async joinGuest(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppGuest.IJoin,
  ): Promise<ITodoAppGuest.IAuthorized> {
    try {
      return await postTodoAppAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
