export async function test_api_shipment_admin_visibility_not_visible_error(
  connection: api.IConnection,
): Promise<void> {
  // 1) Admin authorization
  const adminConnection: api.IConnection = { host: connection.host };
  const adminJoin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IShoppingMallAdmin.IJoin,
  });
  typia.assert(adminJoin);
  // 2) Shipment identifier that should be treated as not visible.
  const shipmentId = typia.random<string & tags.Format<"uuid">>();
  // 3) Validate visibility boundary: not-visible shipment must not be readable.
  await TestValidator.httpError(
    "admin shipment visibility should fail for not-visible shipmentId",
    404,
    async () => {
      await api.functional.shoppingMall.admin.admin.shipments.at(
        adminConnection,
        {
          shipmentId,
        },
      );
    },
  );
}
