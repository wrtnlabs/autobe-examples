export async function test_api_product_variant_detail_member_inactive_hidden_not_viewable(
  connection: api.IConnection,
): Promise<void> {
  const memberConnection: api.IConnection = { host: connection.host };
  const memberAuth = await authorize_member_join(memberConnection, {});
  typia.assert(memberAuth);
  const productVariantId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "member cannot retrieve details for non-viewable product variant",
    [400, 401, 403, 404],
    async () => {
      await api.functional.shoppingMall.member.productVariants.at(
        memberConnection,
        {
          productVariantId,
        },
      );
    },
  );
}
