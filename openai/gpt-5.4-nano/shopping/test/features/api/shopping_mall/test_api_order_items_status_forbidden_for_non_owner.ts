export async function test_api_order_items_status_forbidden_for_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // Member A setup (separate actor connection)
  const memberAConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IShoppingMallMember.IJoin,
  });
  // Member A places an order
  const memberAOrder: IShoppingMallOrder =
    await generate_random_shopping_mall_member_orders_create(
      memberAConnection,
      {},
    );
  typia.assert(memberAOrder);
  const orderId: string & tags.Format<"uuid"> = memberAOrder.id;
  // Member B setup (separate actor connection)
  const memberBConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    } satisfies IShoppingMallMember.IJoin,
  });
  // Member B tries to read order item statuses of member A's order
  await TestValidator.httpError(
    "member cannot read order item statuses for a non-owned order",
    [403, 404],
    async () =>
      await api.functional.shoppingMall.member.orders.order_items.status.orderItemsStatus(
        memberBConnection,
        {
          orderId,
        },
      ),
  );
}
