  @TypedRoute.Get(":reviewId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("reviewId")
    reviewId: string & tags.Format<"uuid">,
  ): Promise<IShoppingMallReview> {
    try {
      return await getShoppingMallAdminReviewsReviewId({
        admin,
        reviewId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

