import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * This endpoint initiates the password reset workflow for users who forget
 * their credentials. Using the 'todo_list_users' schema, it verifies the
 * provided email against saved user records (field: 'email') before issuing a
 * secure, single-use, time-limited password reset token to the listed address.
 *
 * No password or security answer is required to request; confirmation occurs
 * via the reset link and subsequent operations. Underlying logic ensures tokens
 * are never issued for unregistered emails (avoiding information leakage), and
 * operations are auditable by email address and timestamp.
 *
 * The workflow sequence includes this request phase, user action via received
 * email, and a subsequent password reset phase (separate endpoint). This
 * operation is public; no authorization is enforced here except input
 * validation.
 *
 * Security relies on issuing cryptographically secure, time-bound tokens and
 * ensuring unregistered or deleted users do not leak system state information.
 * Errors only indicate request status (always noncommittal if email isn't
 * found).
 *
 * @param props.connection
 * @param props.body Registered email address of the user requesting password
 *   reset.
 * @path /auth/user/password/request-reset
 * @accessor api.functional.auth.user.password.request_reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Registered email address of the user requesting password reset. */
    body: ITodoListUser.IRequestPasswordReset;
  };
  export type Body = ITodoListUser.IRequestPasswordReset;
  export type Response = ITodoListUser.IPasswordResetStatus;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/request-reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/request-reset";
  export const random = (): ITodoListUser.IPasswordResetStatus =>
    typia.random<ITodoListUser.IPasswordResetStatus>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
