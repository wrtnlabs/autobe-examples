import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Sends account verification email to a newly registered user
 * (todo_list_users).
 *
 * This endpoint initiates an email verification workflow for new registrations
 * or when the user requires a new verification email (for example, expiry or
 * missed original message). Uses the 'email' field within the 'todo_list_users'
 * schema for user identification.
 *
 * No changes are made to database records other than audit; a secure token is
 * generated and used in a subsequent verification flow (external or future
 * operation).
 *
 * Input must be validated to prevent arbitrary email usage or information
 * disclosure; requesting verification for unregistered or deleted emails
 * returns a neutral status. Errors are silently handled, exposing no user state
 * details to requests.
 *
 * Links to registration/join, login (which is blocked if not verified), and
 * business process requirements regarding access and account setup.
 *
 * @param props.connection
 * @param props.body Registered email address for which to (re-)send
 *   verification link.
 * @path /auth/user/verification/request
 * @accessor api.functional.auth.user.verification.request.requestVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestVerification(
  connection: IConnection,
  props: requestVerification.Props,
): Promise<requestVerification.Response> {
  return true === connection.simulate
    ? requestVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestVerification.METADATA,
          path: requestVerification.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestVerification {
  export type Props = {
    /** Registered email address for which to (re-)send verification link. */
    body: ITodoListUser.IResendVerification;
  };
  export type Body = ITodoListUser.IResendVerification;
  export type Response = ITodoListUser.IVerificationStatus;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/verification/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/verification/request";
  export const random = (): ITodoListUser.IVerificationStatus =>
    typia.random<ITodoListUser.IVerificationStatus>();
  export const simulate = (
    connection: IConnection,
    props: requestVerification.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestVerification.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
