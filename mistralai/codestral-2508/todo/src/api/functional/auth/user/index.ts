/**
 * This endpoint facilitates secure new user registration by creating a new
 * entry in the 'todo_list_users' schema using the provided email and password
 * (hashed before storage). It enforces unique constraint on the 'email' column
 * and combines it with standard validation logic to prevent duplicate
 * accounts.
 *
 * All passwords are stored only as hashes in the 'password_hash' field,
 * protecting user credentials from disclosure. The registration payload
 * verifies business requirements for email validity and strength of new
 * passwords, also inheriting broader password policy requirements from the
 * authentication requirements analysis.
 *
 * No status- or soft-delete flags are present (see schema for
 * 'todo_list_users'); user accounts, once deleted, are permanently erased with
 * no recovery mechanism. The 'created_at' and 'updated_at' timestamps support
 * auditing of registration and any later change, as required by the
 * requirements analysis.
 *
 * Upon creation, a verification email must be triggered, referencing system
 * requirements that prohibit login unless the 'email' has been verified. Error
 * handling captures validation failures (e.g., format, uniqueness).
 *
 * Any user account created by this endpoint immediately receives a pending
 * verification status until the associated 'email' is confirmed. Related
 * workflows include subsequent login, email verification, and password reset,
 * as detailed in business process diagrams.
 *
 * @param props.connection
 * @param props.body Information required to register a new user: unique email
 *   and password. Email must be unique and business-validated; password is
 *   hashed and persisted.
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
