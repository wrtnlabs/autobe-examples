import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoListUser } from "../../../../../structures/ITodoListUser";

/**
 * Completes password reset for user (todo_list_users) after token validation.
 *
 * This endpoint finalizes the password reset process by accepting a new
 * password and associated token provided to the user's email. Validation logic
 * checks the token's validity, ensures it has not expired or been used, and
 * then updates the corresponding user's 'password_hash' in the
 * 'todo_list_users' schema.
 *
 * No direct user authentication is performed here; operation relies solely on
 * secure possession of the issued token. Passwords are stored as cryptographic
 * hashes, and the update is timestamped in the user's 'updated_at' as per
 * schema.
 *
 * Upon success, all previous sessions (in 'todo_list_user_sessions') may be
 * invalidated as a security enhancement, covered by the business requirement
 * for emergency password resets.
 *
 * Errors are triggered if tokens are used more than once, expired, or do not
 * map to an active user account (permanent deletion model).
 *
 * Operation relates to password reset request workflow, user login, and
 * security audit requirements.
 *
 * @param props.connection
 * @param props.body Valid reset token and new password for finalizing the
 *   reset.
 * @path /auth/user/password/reset
 * @accessor api.functional.auth.user.password.reset.resetPassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resetPassword(
  connection: IConnection,
  props: resetPassword.Props,
): Promise<resetPassword.Response> {
  return true === connection.simulate
    ? resetPassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resetPassword.METADATA,
          path: resetPassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resetPassword {
  export type Props = {
    /** Valid reset token and new password for finalizing the reset. */
    body: ITodoListUser.IResetPassword;
  };
  export type Body = ITodoListUser.IResetPassword;
  export type Response = ITodoListUser.IPasswordResetStatus;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset";
  export const random = (): ITodoListUser.IPasswordResetStatus =>
    typia.random<ITodoListUser.IPasswordResetStatus>();
  export const simulate = (
    connection: IConnection,
    props: resetPassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resetPassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
