/**
 * Search and retrieve paginated user sessions by userId from
 * todo_list_user_sessions.
 *
 * Obtain a filtered, paginated list of all sessions for a specific user
 * account, supporting search on session metadata such as IP and timing.
 * Intended for secure audit trails and compliance, the userId path parameter is
 * used to specify the target user.
 *
 * Returned data includes comprehensive session context for historical review.
 * Direct access control should be enforced via implementation since no explicit
 * API actor roles are permitted.
 *
 * See also the detail fetch endpoint for session metadata via GET
 * /users/{userId}/sessions/{sessionId}.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose sessions are being
 *   retrieved.
 * @param props.body Session search and filtering parameters; supports metadata
 *   filters, pagination, and optional sorting.
 * @path /todoList/users/:userId/sessions
 * @accessor api.functional.todoList.users.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the user whose sessions are being retrieved. */
    userId: string & tags.Format<"uuid">;

    /**
     * Session search and filtering parameters; supports metadata filters,
     * pagination, and optional sorting.
     */
    body: ITodoListUserSession.IRequest;
  };
  export type Body = ITodoListUserSession.IRequest;
  export type Response = IPageITodoListUserSession.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoList/users/:userId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoList/users/${encodeURIComponent(props.userId ?? "null")}/sessions`;
  export const random = (): IPageITodoListUserSession.ISummary =>
    typia.random<IPageITodoListUserSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

