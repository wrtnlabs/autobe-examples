import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently erase a user session from the Todo List application's audit
 * trail.
 *
 * This endpoint allows authenticated users to delete a specific session record,
 * such as to force logout a device or terminate old/compromised access. Each
 * session is uniquely identified by the owning user's ID and the session ID,
 * both of which must reference existing, related records as per the
 * 'todo_list_user_sessions' Prisma schema.
 *
 * Security: The session erase operation is protected so only the session owner
 * can perform this action. Cross-user access is strictly denied in alignment
 * with privacy and audit requirements. The business logic checks that both the
 * provided user and session IDs correspond to a valid user-session pair; any
 * invalid or unauthorized attempt results in appropriate authorization or
 * not-found errors.
 *
 * This operation triggers hard deletion; there is no recovery of erased
 * sessions. Typical use-cases include manual logouts from a user's devices or
 * revoking errant access. Related endpoints include searching the session list
 * (for listing all sessions), and user authentication flows that create these
 * session records.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user owning the session. Must
 *   match an existing user in the todo_list_users table.
 * @param props.sessionId Unique session identifier to be erased. Must reference
 *   a user session belonging to the given userId in the todo_list_user_sessions
 *   table.
 * @path /todoList/user/users/:userId/sessions/:sessionId
 * @accessor api.functional.todoList.user.users.sessions.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the user owning the session. Must match an
     * existing user in the todo_list_users table.
     */
    userId: string & tags.Format<"uuid">;

    /**
     * Unique session identifier to be erased. Must reference a user session
     * belonging to the given userId in the todo_list_user_sessions table.
     */
    sessionId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todoList/user/users/:userId/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/users/${encodeURIComponent(props.userId ?? "null")}/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
