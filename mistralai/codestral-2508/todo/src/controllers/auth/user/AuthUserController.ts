import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";

import { ITodoListUser } from "../../../api/structures/ITodoListUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * Registers a new user (todo_list_users) and issues a verification
   * initiation.
   *
   * This endpoint facilitates secure new user registration by creating a new
   * entry in the 'todo_list_users' schema using the provided email and password
   * (hashed before storage). It enforces unique constraint on the 'email'
   * column and combines it with standard validation logic to prevent duplicate
   * accounts.
   *
   * All passwords are stored only as hashes in the 'password_hash' field,
   * protecting user credentials from disclosure. The registration payload
   * verifies business requirements for email validity and strength of new
   * passwords, also inheriting broader password policy requirements from the
   * authentication requirements analysis.
   *
   * No status- or soft-delete flags are present (see schema for
   * 'todo_list_users'); user accounts, once deleted, are permanently erased
   * with no recovery mechanism. The 'created_at' and 'updated_at' timestamps
   * support auditing of registration and any later change, as required by the
   * requirements analysis.
   *
   * Upon creation, a verification email must be triggered, referencing system
   * requirements that prohibit login unless the 'email' has been verified.
   * Error handling captures validation failures (e.g., format, uniqueness).
   *
   * Any user account created by this endpoint immediately receives a pending
   * verification status until the associated 'email' is confirmed. Related
   * workflows include subsequent login, email verification, and password reset,
   * as detailed in business process diagrams.
   *
   * @param connection
   * @param body Information required to register a new user: unique email and
   *   password. Email must be unique and business-validated; password is hashed
   *   and persisted.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ICreate,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates users (todo_list_users) and initiates a new session with JWT
   * issuance.
   *
   * The login endpoint authenticates users by validating entered credentials
   * against the 'todo_list_users' schema (fields: 'email', 'password_hash'),
   * securely handling password comparison using cryptographic methods. If
   * validation succeeds, a row is created in 'todo_list_user_sessions' for
   * session tracking, including IP, origin, referrer, creation, and potential
   * session expiry, as per requirements analysis and schema.
   *
   * Login is strictly forbidden unless the user’s email is verified, ensuring
   * security. Multiple sessions per user are allowed per design, supporting
   * mobile and multi-device flows documented in requirements.
   *
   * Error scenarios include invalid login (credentials do not match any user),
   * unverified email (even if credentials are correct), and attempts to login
   * with deleted/nonexistent accounts (schema’s permanent deletion model). The
   * endpoint neither creates administrative roles nor escalates authority;
   * every session is fully auditable.
   *
   * Successful authentication issues standard JWTs, with payload containing
   * userId, role, and issuance timestamp, aligning with JWT issuance rules
   * described business requirements.
   *
   * Related endpoints: registration/join, email verification, session refresh,
   * logout, and password reset. Failing authentication returns a business error
   * response and does not create new session records.
   *
   * @param connection
   * @param body User credentials required for authentication: email and
   *   password.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoListUser.ILogin,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes user session tokens (todo_list_user_sessions) for ongoing
   * authenticated access.
   *
   * This endpoint allows users with a valid refresh token to obtain new JWTs,
   * prolonging their authenticated session without logging in again. It
   * cross-verifies session status using the 'todo_list_user_sessions' schema,
   * especially fields such as 'expired_at' and 'todo_list_user_id', as per
   * business requirement for concurrent session support.
   *
   * When a refresh is invoked, new tokens are emitted, and the used refresh
   * token is invalidated (unless business requirements allow concurrent
   * long-lived sessions). Expired or already-used refresh tokens are denied
   * renewal. Sessions terminated by explicit logout (setting 'expired_at')
   * cannot be refreshed.
   *
   * Security and audit compliance is ensured by tying each refresh operation to
   * both user and session records in the database for full traceability. The
   * JWT payload structure complies with requirements, embedding userId and
   * role.
   *
   * Related flows: login, registration/join, session expiration handling,
   * explicit logout, and security policies regarding token renewal and
   * revocation. All behavioral logic matches schema fields and the permission
   * matrix.
   *
   * @param connection
   * @param body Refresh token and session identifier, as required for session
   *   continuation.
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: ITodoListUser.IRefresh,
  ): Promise<ITodoListUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
