import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserVerificationRequest } from "../../../../../providers/postAuthUserVerificationRequest";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/verification/request")
export class AuthUserVerificationRequestController {
  /**
   * Sends account verification email to a newly registered user
   * (todo_list_users).
   *
   * This endpoint initiates an email verification workflow for new
   * registrations or when the user requires a new verification email (for
   * example, expiry or missed original message). Uses the 'email' field within
   * the 'todo_list_users' schema for user identification.
   *
   * No changes are made to database records other than audit; a secure token is
   * generated and used in a subsequent verification flow (external or future
   * operation).
   *
   * Input must be validated to prevent arbitrary email usage or information
   * disclosure; requesting verification for unregistered or deleted emails
   * returns a neutral status. Errors are silently handled, exposing no user
   * state details to requests.
   *
   * Links to registration/join, login (which is blocked if not verified), and
   * business process requirements regarding access and account setup.
   *
   * @param connection
   * @param body Registered email address for which to (re-)send verification
   *   link.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestVerification(
    @TypedBody()
    body: ITodoListUser.IResendVerification,
  ): Promise<ITodoListUser.IVerificationStatus> {
    try {
      return await postAuthUserVerificationRequest({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
