import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordReset } from "../../../../../providers/postAuthUserPasswordReset";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/reset")
export class AuthUserPasswordResetController {
  /**
   * This endpoint finalizes the password reset process by accepting a new
   * password and associated token provided to the user's email. Validation
   * logic checks the token's validity, ensures it has not expired or been used,
   * and then updates the corresponding user's 'password_hash' in the
   * 'todo_list_users' schema.
   *
   * No direct user authentication is performed here; operation relies solely on
   * secure possession of the issued token. Passwords are stored as
   * cryptographic hashes, and the update is timestamped in the user's
   * 'updated_at' as per schema.
   *
   * Upon success, all previous sessions (in 'todo_list_user_sessions') may be
   * invalidated as a security enhancement, covered by the business requirement
   * for emergency password resets.
   *
   * Errors are triggered if tokens are used more than once, expired, or do not
   * map to an active user account (permanent deletion model).
   *
   * Operation relates to password reset request workflow, user login, and
   * security audit requirements.
   *
   * @param connection
   * @param body Valid reset token and new password for finalizing the reset.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async resetPassword(
    @TypedBody()
    body: ITodoListUser.IResetPassword,
  ): Promise<ITodoListUser.IPasswordResetStatus> {
    try {
      return await postAuthUserPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
