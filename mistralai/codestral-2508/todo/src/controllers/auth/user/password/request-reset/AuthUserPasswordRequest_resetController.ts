import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordRequestReset } from "../../../../../providers/postAuthUserPasswordRequestReset";

import { ITodoListUser } from "../../../../../api/structures/ITodoListUser";

@Controller("/auth/user/password/request-reset")
export class AuthUserPasswordRequest_resetController {
  /**
   * Initiates password reset flow for a user (todo_list_users) via email.
   *
   * This endpoint initiates the password reset workflow for users who forget
   * their credentials. Using the 'todo_list_users' schema, it verifies the
   * provided email against saved user records (field: 'email') before issuing a
   * secure, single-use, time-limited password reset token to the listed
   * address.
   *
   * No password or security answer is required to request; confirmation occurs
   * via the reset link and subsequent operations. Underlying logic ensures
   * tokens are never issued for unregistered emails (avoiding information
   * leakage), and operations are auditable by email address and timestamp.
   *
   * The workflow sequence includes this request phase, user action via received
   * email, and a subsequent password reset phase (separate endpoint). This
   * operation is public; no authorization is enforced here except input
   * validation.
   *
   * Security relies on issuing cryptographically secure, time-bound tokens and
   * ensuring unregistered or deleted users do not leak system state
   * information. Errors only indicate request status (always noncommittal if
   * email isn't found).
   *
   * @param connection
   * @param body Registered email address of the user requesting password reset.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: ITodoListUser.IRequestPasswordReset,
  ): Promise<ITodoListUser.IPasswordResetStatus> {
    try {
      return await postAuthUserPasswordRequestReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
