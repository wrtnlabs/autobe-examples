import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUsersUserIdSessions } from "../../../../providers/patchTodoListUsersUserIdSessions";
import { getTodoListUsersUserIdSessionsSessionId } from "../../../../providers/getTodoListUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/users/:userId/sessions")
export class TodolistUsersSessionsController {
  /**
   * Obtain a filtered, paginated list of all sessions for a specific user
   * account, supporting search on session metadata such as IP and timing.
   * Intended for secure audit trails and compliance, the userId path parameter
   * is used to specify the target user.
   *
   * Returned data includes comprehensive session context for historical review.
   * Direct access control should be enforced via implementation since no
   * explicit API actor roles are permitted.
   *
   * See also the detail fetch endpoint for session metadata via GET
   * /users/{userId}/sessions/{sessionId}.
   *
   * @param connection
   * @param userId Unique identifier of the user whose sessions are being
   *   retrieved.
   * @param body Session search and filtering parameters; supports metadata
   *   filters, pagination, and optional sorting.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListUsersUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Fetch full session details by sessionId and parent userId, for audit or
   * security review. Returns all columns defined in the todo_list_user_sessions
   * schema plus the foreign key reference to user.
   *
   * API access is controlled by implementation, not by actor declaration in
   * this definition. Use the collection endpoint to list sessions (PATCH
   * /users/{userId}/sessions) before fetching detail.
   *
   * Direct user access or admin/outside access must be enforced at the provider
   * level, since actor assignment is not supported in this configuration.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session.
   * @param sessionId Unique identifier of the session to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListUsersUserIdSessionsSessionId({
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
