import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListUserUsers } from "../../../../providers/patchTodoListUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";
import { deleteTodoListUserUsersUserId } from "../../../../providers/deleteTodoListUserUsersUserId";

import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";
import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users")
export class TodolistUserUsersController {
  /**
   * Retrieve a paginated, filterable user list from the todo_list_users table.
   *
   * Retrieve a paginated list of users who are registered in the Todo List
   * application.
   *
   * This operation enables filtering, searching, and ordering user accounts.
   * Results are suitable for administrative views, support dashboards, or
   * analytics. Only fields permitted by business requirements—such as email,
   * display name, and timestamps—are returned, while credential fields
   * (password_hash) remain inaccessible for privacy and security.
   *
   * Security considerations require that this endpoint is protected and not
   * available to client users. Only properly authorized actors, such as system
   * administrators or support engineers, may execute this operation. The data
   * is drawn from the todo_list_users table, incorporating key account metadata
   * for auditing and analytics.
   *
   * @param connection
   * @param body User list search and filter parameters for pagination, sorting,
   *   and field-based filtering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve details for a specific user record from the todo_list_users table.
   *
   * Return the complete detail of a specific user account identified by userId
   * from the Todo List application.
   *
   * This operation is intended for administrative scenarios such as user
   * support, security audit, or compliance inspection. Only authorized actors
   * may retrieve full user details. The response contains all business-relevant
   * fields permitted to administrators—email, display name, timestamps, and
   * account metadata. Sensitive authentication data, such as the user's
   * password hash, is never returned or exposed in any part of the response.
   *
   * Strict access controls must be enforced to avoid information leakage or
   * unauthorized data access. This operation complements the user index/search
   * function and should be used when inspection of an individual user is needed
   * beyond general search results.
   *
   * @param connection
   * @param userId Unique identifier of the target user.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a registered Todo List user account in the todo_list_users table.
   *
   * Update details of an existing Todo List user account, identified by their
   * unique userId (UUID).
   *
   * Only authenticated users who own the account, or authorized administrators,
   * can update a user's email address, password (as a hashed value), or display
   * name. The operation enforces business validation as per the schema: new
   * email addresses must be globally unique and follow business email
   * validation rules; passwords are to be securely hashed before submission;
   * display name may be omitted or set to null to clear the field.
   *
   * Timestamps for last update are automatically persisted. There is no status
   * or soft-delete field; deleted users are physically removed using another
   * endpoint. Error handling addresses invalid IDs, duplicate email addresses,
   * and failed business validations. Related operations include user deletion
   * and session tracking for audit purposes.
   *
   * @param connection
   * @param userId Unique identifier of the user account to update, as a UUID.
   * @param body New values for the user profile fields to be updated; must
   *   comply with business validation rules for email, password_hash, and
   *   optional display_name.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a Todo List user account from the todo_list_users table
   * by UUID.
   *
   * Permanently remove a Todo List user account from the system, using the
   * unique userId as a hard delete.
   *
   * Only the owner of the account or an authorized administrator can delete a
   * user. Once deleted, all personal user data including email, password hash,
   * and display name are erased from the database. This action is
   * irreversible—no restoration or soft delete is supported. The operation is
   * strictly limited to one account at a time.
   *
   * Error handling includes checking for valid userId format, existence of the
   * user record, and proper permissions. Related session information (from
   * session table) is to be handled in backend business logic if user deletion
   * cascades are needed.
   *
   * @param connection
   * @param userId Unique identifier of the user account to delete, as a UUID.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
