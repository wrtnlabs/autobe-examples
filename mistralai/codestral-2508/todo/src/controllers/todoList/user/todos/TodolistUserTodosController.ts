import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoListUserTodos } from "../../../../providers/postTodoListUserTodos";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoListUserTodos } from "../../../../providers/patchTodoListUserTodos";
import { getTodoListUserTodosTodoId } from "../../../../providers/getTodoListUserTodosTodoId";
import { putTodoListUserTodosTodoId } from "../../../../providers/putTodoListUserTodosTodoId";
import { deleteTodoListUserTodosTodoId } from "../../../../providers/deleteTodoListUserTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";
import { IPageITodoListTodo } from "../../../../api/structures/IPageITodoListTodo";

@Controller("/todoList/user/todos")
export class TodolistUserTodosController {
  /**
   * Create a new Todo in the todo_list_todos table for the requesting user.
   *
   * Create a new Todo item for the currently authenticated user, storing it in
   * the todo_list_todos table.
   *
   * A valid request body must provide a non-blank title (max 100 chars), with
   * optional multi-line description (max 500 chars). Newly created Todos are
   * marked as incomplete and 'pending' by default; audit timestamps for
   * creation and update are set to the current time according to the backend
   * clock. Ownership is strictly bound to the creating user's account, as
   * derived from the session context. The operation enforces the business rule
   * that no user may have two active (incomplete) Todos with the same title.
   * All field length and nullability constraints are enforced server-side.
   *
   * If any constraint fails (e.g., duplicate pending title, too long/blank
   * title), an appropriate error is returned and no Todo is created. Successful
   * creation returns all Todo fields, including computed audit fields, the new
   * persistent UUID, and ownership assignment.
   *
   * @param connection
   * @param body Non-blank title (max 100 chars) and optional description (max
   *   500 chars) for the new Todo. The request DOES NOT include audit or
   *   ownership fields, which are server-generated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.ICreate,
  ): Promise<ITodoListTodo> {
    try {
      return await postTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and paginate the authenticated user's todo_list_todos records with
   * filtering.
   *
   * Retrieve and search the authenticated user's Todo tasks with optional
   * filters, search keywords, and pagination.
   *
   * This endpoint gives users robust, convenient access to their entire Todo
   * list. Only the authenticated user's own records are accessible—business
   * logic fully enforces per-user privacy and never exposes others' tasks.
   * Search parameters allow filtering by completion state (complete,
   * incomplete), substring match on title, and sort controls such as order by
   * creation or completion date.
   *
   * Security: Each request is executed strictly in the context of the user
   * session, exclusively returning Todos owned by the calling user. The
   * 'requestBody' allows specifying page number, page size, completion status
   * filter, partial title match, and order options. Invalid or out-of-range
   * values are handled gracefully, returning actionable validation errors per
   * requirements. Related operations include task creation, detail view,
   * update, complete, and erase APIs.
   *
   * @param connection
   * @param body Search criteria for the user's Todos, allowing pagination,
   *   completion filter, and substring match on title. All fields optional
   *   except for per-user context handled in authorization.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoListTodo.IRequest,
  ): Promise<IPageITodoListTodo.ISummary> {
    try {
      return await patchTodoListUserTodos({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single Todo by its UUID (from todo_list_todos table) for its
   * owner only.
   *
   * Retrieve a single Todo item owned by the authenticated user, based on the
   * provided Todo UUID.
   *
   * Only the owner of a Todo can access this resource. If a user tries to
   * access a Todo they did not create, a forbidden or not found error will be
   * returned. All information in the response—including title, description,
   * completion state, audit timestamps, and the owner's user ID—is drawn
   * directly from the authoritative schema in the database.
   *
   * This endpoint provides exhaustive detail about the Todo, which allows
   * integration with other endpoints such as task update or delete. The
   * endpoint does not support soft-deletion; permanently deleted Todos are
   * unrecoverable and will yield a 404. All field values in the response are up
   * to date as of the most recent edit, reflecting audit and privacy business
   * rules.
   *
   * @param connection
   * @param todoId Unique identifier (UUID) of the target Todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":todoId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update details of a specific todo task for the authenticated user
   * (todo_list_todos table).
   *
   * Update an existing todo task belonging to the authenticated user, replacing
   * its details with the specified data. Authenticated users may use this
   * endpoint to change the text, completion status, or other properties of a
   * personal todo. The todoId parameter precisely identifies the target record;
   * the operation performs full entity replacement with strict DTO validation.
   *
   * Only the owner of the todo may update their tasks—ownership is enforced in
   * business logic, and unauthorized requests result in an error. Data
   * validation and schema enforcement ensure all required and optional fields
   * are handled correctly, and that changes comply with input validation rules
   * set by the database model and ITodoListTodo.IUpdate DTO.
   *
   * Optimistic locking may be used if the schema provides versioning/timestamp
   * support, ensuring no conflicting task updates. The response provides the
   * updated task entity, which clients can use to synchronize state. Typical
   * error scenarios include attempts to update non-existent or unauthorized
   * todos, or requests with invalid or ill-formed payloads.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo task owned by the
   *   authenticated user
   * @param body Data representing the updated properties of the todo task,
   *   validated against the ITodoListTodo.IUpdate interface
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":todoId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListUserTodosTodoId({
        user,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Erase (hard delete) a todo task belonging to the authenticated user
   * (todo_list_todos table).
   *
   * Remove a specific todo task for the authenticated user by its unique
   * todoId. This operation allows users to permanently delete tasks from their
   * personal todo list, ensuring private, user-owned management and strict
   * access control. The endpoint enforces ownership: only tasks belonging to
   * the authenticated user can be erased; attempts to remove others’ tasks
   * result in error.
   *
   * The operation references the todo_list_todos schema definition, ensuring
   * validation of the unique identifier and appropriate business rule
   * application (such as preventing accidental deletion or confirming user
   * intent). No requestBody or responseBody is required. Typical errors include
   * attempts to delete non-existent or unauthorized tasks, or syntax/format
   * errors in the todoId parameter.
   *
   * Successful execution results in the requested todo task being fully removed
   * from the system. Clients are expected to refresh their view to exclude the
   * erased task and may display a confirmation message upon successful
   * deletion.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo task owned by the
   *   authenticated user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":todoId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("todoId")
    todoId: string,
  ): Promise<void> {
    try {
      return await deleteTodoListUserTodosTodoId({
        user,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
