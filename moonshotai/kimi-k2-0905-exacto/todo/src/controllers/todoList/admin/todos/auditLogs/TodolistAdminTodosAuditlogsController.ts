import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminTodosTodoIdAuditLogs } from "../../../../../providers/patchTodoListAdminTodosTodoIdAuditLogs";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminTodosTodoIdAuditLogsAuditLogId } from "../../../../../providers/getTodoListAdminTodosTodoIdAuditLogsAuditLogId";

import { IPageITodoListTodoAuditLog } from "../../../../../api/structures/IPageITodoListTodoAuditLog";
import { ITodoListTodoAuditLog } from "../../../../../api/structures/ITodoListTodoAuditLog";

@Controller("/todoList/admin/todos/:todoId/auditLogs")
export class TodolistAdminTodosAuditlogsController {
  /**
   * Search and retrieve paginated audit logs for a specific todo
   * (todo_list_todo_audit_logs).
   *
   * Retrieve a paginated, filterable list of audit trail records for a specific
   * todo item. This endpoint provides advanced search capabilities on audit
   * logs linked to the target todo, supporting filtering by actor (user/admin),
   * action, and time range.
   *
   * Audit logs track all privileged or destructive modifications—including CRUD
   * operations, status changes, admin interventions, and manual
   * deletions—across the todo's lifecycle. Each log entry provides full actor
   * context and an immutable record of who, what, and when, supporting
   * compliance with historical traceability requirements.
   *
   * Only admin users can access this endpoint, as regular users and even todo
   * creators may not review audit logs. The API response structure conforms to
   * `IPageITodoListTodoAuditLog.ISummary` for compatibility with compliance
   * dashboards, audit reviews, and operational forensics tools. Related
   * endpoints include detail retrieval for a single audit log entry.
   *
   * @param connection
   * @param todoId Unique identifier of the target todo item whose audit logs
   *   are to be queried.
   * @param body Query filter and pagination parameters for audit log search
   *   related to the specific todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodoAuditLog.IRequest,
  ): Promise<IPageITodoListTodoAuditLog.ISummary> {
    try {
      return await patchTodoListAdminTodosTodoIdAuditLogs({
        admin,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detail of a single audit log entry for a given todo
   * (todo_list_todo_audit_logs).
   *
   * Get detailed information for an individual audit log associated with a
   * given todo item. This endpoint returns all relevant data for a single
   * immutable audit event, including actor user/admin, action type, event
   * context, and exact timestamp.
   *
   * Audit logs are append-only and cannot be deleted or modified; this
   * guarantees historical accuracy in compliance and audit processes. Admins
   * use this operation to review critical or suspicious actions in-depth or to
   * support retrospective incident investigations.
   *
   * User access is strictly forbidden for audit details; only administrators
   * holding compliance or operational permissions can utilize this endpoint.
   * The response conforms to the `ITodoListTodoAuditLog` DTO structure and
   * supports integration with compliance tooling and audit dashboards. For list
   * queries, use the collection endpoint for audit logs of a todo.
   *
   * @param connection
   * @param todoId Unique identifier of the todo item related to the audit log.
   * @param auditLogId Unique identifier of the audit log entry to be retrieved.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":auditLogId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedParam("auditLogId")
    auditLogId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodoAuditLog> {
    try {
      return await getTodoListAdminTodosTodoIdAuditLogsAuditLogId({
        admin,
        todoId,
        auditLogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
