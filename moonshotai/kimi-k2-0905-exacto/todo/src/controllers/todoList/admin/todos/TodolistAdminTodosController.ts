import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListAdminTodosTodoId } from "../../../../providers/getTodoListAdminTodosTodoId";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { putTodoListAdminTodosTodoId } from "../../../../providers/putTodoListAdminTodosTodoId";
import { deleteTodoListAdminTodosTodoId } from "../../../../providers/deleteTodoListAdminTodosTodoId";

import { ITodoListTodo } from "../../../../api/structures/ITodoListTodo";

@Controller("/todoList/admin/todos/:todoId")
export class TodolistAdminTodosController {
  /**
   * Retrieve a specific todo item by id from todo_list_todos.
   *
   * Retrieve detailed information about a single todo item using its unique
   * identifier.
   *
   * Only the owning user or an administrator can access a particular todo. All
   * fields—including description, completed state, completed_at, created_at,
   * updated_at, and deleted_at—are returned, reflecting the most up-to-date
   * status of the todo. Access is strictly enforced: the todo can only be
   * retrieved if the requester is either the owner or is accessing it through
   * admin compliance functions.
   *
   * Requests for non-existent or inaccessible todos result in a suitable error
   * response, ensuring compliance with business rules on privacy and data
   * access. This operation fully aligns with the requirements of the
   * todo_list_todos table and its detailed comments on ownership and temporal
   * fields.
   *
   * @param connection
   * @param todoId Primary Key. Unique identifier for each todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await getTodoListAdminTodosTodoId({
        admin,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo item in the todo_list_todos table.
   *
   * Update the fields of an existing todo item such as its description or
   * completed state. Only the user who owns the todo may update it, enforcing
   * strict ownership policy mandated in the database schema and business
   * requirements.
   *
   * When successful, this operation ensures all content and validation rules
   * are met, including unique descriptions for the user (with regard to timing
   * of duplicate submissions) and conformity to length and content checks. If
   * the status is marked as complete, the completed_at field is set to the
   * current UTC timestamp; if reverted to incomplete, completed_at is cleared.
   * Record's updated_at is refreshed on any modification.
   *
   * Soft-deleted todos are locked from user updates but may be administered by
   * privileged roles for compliance actions. Unauthorized attempts yield
   * appropriate error messages including permission denied or not found. The
   * response returns the updated todo object for client synchronization. This
   * API endpoint requires the user be authenticated, and administrators have
   * elevated access for managing any user's todos as required by compliance
   * rules.
   *
   * @param connection
   * @param todoId Primary Key. Unique identifier for each todo item.
   * @param body Payload specifying updates to the todo, such as new description
   *   or completed status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListTodo.IUpdate,
  ): Promise<ITodoListTodo> {
    try {
      return await putTodoListAdminTodosTodoId({
        admin,
        todoId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently erase a todo item from the todo_list_todos table.
   *
   * Permanently remove a todo item from the database. This operation is
   * intended mainly for compliance or administrative enforcement, as regular
   * user removal typically employs soft-deletion with undo capability by
   * setting deleted_at and not erasing data immediately.
   *
   * Strict permission checks are applied: only the owning user and
   * administrators may invoke this hard delete. Once successful, the todo is
   * purged from all lists and cannot be recovered. Attempts to erase
   * already-removed or non-existent todos yield an appropriate error. The
   * erasure is fully audited for compliance.
   *
   * Field-level validation and referential integrity are enforced by business
   * rules in the system schema. This endpoint should be reserved for privileged
   * actors. Normal users should be encouraged to use soft-delete endpoints
   * unless compliance requires hard erasure.
   *
   * @param connection
   * @param todoId Primary Key. Unique identifier for each todo item.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("todoId")
    todoId: string & tags.Format<"uuid">,
  ): Promise<ITodoListTodo> {
    try {
      return await deleteTodoListAdminTodosTodoId({
        admin,
        todoId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
