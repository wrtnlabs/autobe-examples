import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsers } from "../../../../providers/patchTodoListAdminUsers";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { deleteTodoListAdminUsersUserId } from "../../../../providers/deleteTodoListAdminUsersUserId";

import { IPageITodoListUser } from "../../../../api/structures/IPageITodoListUser";
import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/admin/users")
export class TodolistAdminUsersController {
  /**
   * Paginate and search the list of registered users in todo_list_users for
   * admin dashboards.
   *
   * Search, filter, and paginate the entire list of registered end users of the
   * todo_list_users table for administrative backend use.
   *
   * This operation allows platform administrators to apply advanced query logic
   * to locate users based on email, lock status, creation date, or update date.
   * The request body supports flexible search and pagination features, enabling
   * result refinement for auditing or management purposes. Only platform admins
   * are authorized to use this endpoint, and the data returned should omit
   * confidential information such as password hashes.
   *
   * Search results are paginated and may be sorted by creation/update
   * timestamps or email address. To mitigate the risk of information leakage,
   * the endpoint supports result size limits and rate limiting enforcement.
   * Related operations may provide single-user detail or account status update
   * by id or email as needed by administration flows.
   *
   * @param connection
   * @param body Search conditions, filters, pagination, or sorting options for
   *   user records. Accept fields such as email substring, is_locked status,
   *   created_at/updated_at date ranges, and page/size controls.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListUser.IRequest,
  ): Promise<IPageITodoListUser.ISummary> {
    try {
      return await patchTodoListAdminUsers({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently erase a registered end user account from todo_list_users table.
   *
   * Permanently removes a specific end user registered in the Todo List system,
   * identified by their unique ID. This critical action is available
   * exclusively to administrators for security and compliance reasons.
   *
   * User accounts store private information, including a unique email for
   * communication and password authentication details. When this operation is
   * performed, all such sensitive user-specific information is deleted from the
   * todo_list_users table.
   *
   * Since users are not allowed to interact with the data of other users, this
   * operation is strictly administrative and cannot be performed by standard
   * users themselves. System-level clean-up of dependent sessions and related
   * audit logs is also triggered to ensure no orphaned data remains. An audit
   * log entry is created, and the outcome is available for future compliance
   * review.
   *
   * @param connection
   * @param userId Unique identifier of the target user account to be deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminUsersUserId({
        admin,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
