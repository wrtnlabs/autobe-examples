import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminUsersUserIdSessions } from "../../../../../providers/patchTodoListAdminUsersUserIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoListAdminUsersUserIdSessionsSessionId";
import { deleteTodoListAdminUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoListAdminUsersUserIdSessionsSessionId";

import { IPageITodoListUserSession } from "../../../../../api/structures/IPageITodoListUserSession";
import { ITodoListUserSession } from "../../../../../api/structures/ITodoListUserSession";

@Controller("/todoList/admin/users/:userId/sessions")
export class TodolistAdminUsersSessionsController {
  /**
   * Retrieve all authentication sessions for a specific todo_list_users
   * account.
   *
   * Retrieve the complete list of authentication sessions (current and
   * historical) for a designated user within the Todo List system.
   *
   * This operation is designed solely for privileged administrative usage, such
   * as security audits and abuse monitoring. Each session is individually
   * linked to the user by userId, and this API provides session details as
   * permitted by policy—typically key timestamps, last activity data, client
   * metadata, and status indicators, excluding confidential security tokens.
   *
   * Ordinary users cannot view session history for themselves or others to
   * ensure privacy. For audit or support scenarios, an administrator reviews
   * session data using this operation as part of compliance or incident
   * response.
   *
   * @param connection
   * @param userId Unique identifier of the target user account whose sessions
   *   are being queried.
   * @param body Query and pagination parameters for session list retrieval (if
   *   supported in DTO).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUserSession.IRequest,
  ): Promise<IPageITodoListUserSession.ISummary> {
    try {
      return await patchTodoListAdminUsersUserIdSessions({
        admin,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve one authentication session for a Todo List user from
   * todo_list_user_sessions.
   *
   * Retrieve detailed information for a single end user authentication session
   * in the Todo List system.
   *
   * This operation is intended for administrative oversight and security audit
   * use cases. It allows forensic analysts or privileged administrators to
   * examine the precise context of a user authentication event, including
   * origin IP, access URLs, and session lifecycle timestamps.
   *
   * To protect end-user privacy and comply with least-privilege principles,
   * this endpoint requires administrative privileges; ordinary users cannot
   * gain access via this interface. Only sessions that are parented by the
   * specified userId will be returned; attempts to access sessions outside that
   * context will result in a not-found error.
   *
   * Session data is returned as defined in the todo_list_user_sessions table,
   * referencing associated todo_list_users for ownership linkage. Security and
   * privacy logging is enforced at the application layer for all accesses to
   * this endpoint. Related operations include session deletion (DELETE) and
   * searching for user sessions by userId (PATCH /users/{userId}/sessions).
   *
   * @param connection
   * @param userId Unique identifier of the target user who owns the session
   *   (UUID, global scope).
   * @param sessionId Unique identifier for the session record (UUID, scoped to
   *   the selected user).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUserSession> {
    try {
      return await getTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a session for a Todo List user from todo_list_user_sessions
   * (administrative only).
   *
   * Permanently delete (revoke) an authentication session entry belonging to a
   * specific user in the Todo List system.
   *
   * This operation logs the session deletion and removes it from the
   * todo_list_user_sessions record set. Executed only by privileged
   * administrators for security reasons—regular users do not have access to
   * this functionality via the API. By design, this supports security
   * management, regulatory compliance, abuse response, and administrative
   * review workflows.
   *
   * When processed, the target session (identified by both userId and
   * sessionId) is removed from the active session register. This action is
   * irreversible and immediately revokes any authentication for the affected
   * session token. Related administrative operations include viewing session
   * details (GET /users/{userId}/sessions/{sessionId}) and auditing session
   * activity.
   *
   * @param connection
   * @param userId Unique identifier of the target user who owns the session
   *   (UUID, global scope).
   * @param sessionId Unique identifier for the session record (UUID, scoped to
   *   the selected user).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminUsersUserIdSessionsSessionId({
        admin,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
