import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAdmins } from "../../../../providers/patchTodoListAdminAdmins";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getTodoListAdminAdminsAdminId } from "../../../../providers/getTodoListAdminAdminsAdminId";
import { putTodoListAdminAdminsAdminId } from "../../../../providers/putTodoListAdminAdminsAdminId";
import { deleteTodoListAdminAdminsAdminId } from "../../../../providers/deleteTodoListAdminAdminsAdminId";

import { IPageITodoListAdmin } from "../../../../api/structures/IPageITodoListAdmin";
import { ITodoListAdmin } from "../../../../api/structures/ITodoListAdmin";

@Controller("/todoList/admin/admins")
export class TodolistAdminAdminsController {
  /**
   * Search and retrieve a filtered, paginated list of administrator accounts
   * (todo_list_admins table).
   *
   * Retrieve a filtered, paginated list of administrator accounts in the Todo
   * List service.
   *
   * This endpoint allows authorized actors to search and filter administrators
   * based on criteria such as email, lock status, and creation date. It returns
   * summarized admin records that include identification, contact, and status
   * information but never sensitive data such as password hashes. Each result
   * incorporates relevant audit and compliance information as required for
   * administrative review.
   *
   * Access is restricted exclusively to actors with the 'admin' role,
   * preventing exposure to unauthorized users. The operation references the
   * todo_list_admins table and honors its business logic, including unique
   * email constraints and proper handling of locked accounts. Rate limiting and
   * audit logging is recommended for this endpoint due to its privileged
   * nature.
   *
   * @param connection
   * @param body Administrator search/filter criteria and pagination/sort
   *   options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: ITodoListAdmin.IRequest,
  ): Promise<IPageITodoListAdmin.ISummary> {
    try {
      return await patchTodoListAdminAdmins({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator from
   * todo_list_admins by UUID id.
   *
   * Retrieve full details of a specific administrator account for management or
   * review purposes.
   *
   * This endpoint allows authorized admin actors to view comprehensive data
   * about a single administrator, identified by their unique UUID. The result
   * includes identification, contact, security status (such as lock status),
   * and relevant metadata for oversight and compliance. Sensitive data fields
   * such as password hashes are never exposed in the response body.
   *
   * Access is strictly limited to users with the 'admin' role. The operation
   * incorporates business logic and validation rules: verifies admin existence,
   * respects account lock status for special actions, and supports
   * traceability/audit. This operation is foundational for all admin account
   * management actions and works together with other privileged admin
   * operations in the service.
   *
   * @param connection
   * @param adminId UUID identifier of the target administrator account (primary
   *   key from todo_list_admins table).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdmin> {
    try {
      return await getTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update properties for a single administrator account in todo_list_admins.
   *
   * Update an administrator account's information in the Todo List platform.
   * This operation allows for modifying fields such as the admin’s email
   * address, password hash, and locked status (is_locked), as well as updating
   * the audit timestamps.
   *
   * Only privileged system processes or other admins with sufficient access
   * rights may perform this operation, ensuring that accidental or unauthorized
   * modifications are prevented. The update strictly checks business rules such
   * as unique email consistency, hashed password policy, and proper access
   * controls defined by the application RBAC model.
   *
   * The request body must include only allowed fields. All change events are
   * tracked for compliance, and related audit logs may be checked if necessary.
   * Errors will be returned if uniqueness, format, or access validation fails.
   * This operation does not permit reassigning admin role—creation and role
   * management are handled by separate operations.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account for
   *   update.
   * @param body New admin properties for update, including email, password
   *   hash, or lock flag.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":adminId")
  public async update(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdmin.IUpdate,
  ): Promise<ITodoListAdmin> {
    try {
      return await putTodoListAdminAdminsAdminId({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete (erase) a single administrator account from todo_list_admins.
   *
   * Delete a specified administrator account. This permanently removes the
   * account record from the underlying database table. Only privileged system
   * users, typically with admin or higher roles, are permitted to execute the
   * deletion; access is tightly controlled by the RBAC security layer to
   * prevent accidental or malicious erasure.
   *
   * All delete events are logged for audit and compliance, and any attempt to
   * delete a non-existent or protected admin will result in a clearly described
   * error response. Deletion is immediate and cannot be undone. This operation
   * does not affect related user accounts, sessions, or non-admin records, and
   * is isolated to the todo_list_admins table only.
   *
   * @param connection
   * @param adminId Unique identifier of the target administrator account to
   *   delete.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":adminId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsAdminId({
        admin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
