import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoListAdminAdminsAdminIdSessions } from "../../../../../providers/patchTodoListAdminAdminsAdminIdSessions";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getTodoListAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/getTodoListAdminAdminsAdminIdSessionsSessionId";
import { deleteTodoListAdminAdminsAdminIdSessionsSessionId } from "../../../../../providers/deleteTodoListAdminAdminsAdminIdSessionsSessionId";

import { IPageITodoListAdminSession } from "../../../../../api/structures/IPageITodoListAdminSession";
import { ITodoListAdminSession } from "../../../../../api/structures/ITodoListAdminSession";

@Controller("/todoList/admin/admins/:adminId/sessions")
export class TodolistAdminAdminsSessionsController {
  /**
   * Retrieve a paged, filterable list of admin session records for a specific
   * administrator from todo_list_admin_sessions.
   *
   * Retrieve a filtered, paginated list of authentication sessions for a
   * specific administrator. This operation provides system and security
   * administrators with comprehensive audit detail on administrator system
   * access events, including creation, expiration, and related networking
   * context.
   *
   * The query supports advanced filtering and pagination, allowing
   * administrators to review historical session data, analyze session lifespan
   * patterns, and investigate potential security incidents. Results include
   * relevant IP addresses and related URL metadata for each session, in
   * alignment with audit trace requirements defined in the Prisma schema.
   *
   * Access to this operation is strictly limited to authorized admin actors.
   * All returned session records are read-only, preserved for compliance, and
   * cannot be modified or deleted through this API. Session creation and
   * termination are managed solely by the authentication mechanism and are not
   * accessible from this endpoint. This endpoint depends on the unique adminId
   * to correctly scope sessions by owner.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) of the administrator whose
   *   authentication sessions are being queried.
   * @param body Search and pagination criteria for filtering admin session
   *   records. This DTO enables range filtering, session status, and sorting
   *   options.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListAdminSession.IRequest,
  ): Promise<IPageITodoListAdminSession.ISummary> {
    try {
      return await patchTodoListAdminAdminsAdminIdSessions({
        admin,
        adminId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve full audit record for a single admin session from
   * todo_list_admin_sessions.
   *
   * Fetch the complete context of a specific administrator's authentication
   * session. This allows authorized admin actors to review the
   * details—timestamp, IP, user agent context, origin URL, referrer, and
   * expiration—of a single privileged access record.
   *
   * This detailed session audit response is purpose-built for system compliance
   * reviews, security investigations, and administrative audits. Strict access
   * controls prevent non-admins from accessing this information.
   *
   * The composite of adminId and sessionId ensures session records are
   * unambiguously traced to their source admin in accordance with audit and
   * compliance best practices. All session data is immutable through this
   * endpoint; only administrative viewing is supported.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) of the administrator who owns the
   *   session being audited.
   * @param sessionId Unique identifier (UUID) of the administrative session
   *   record to retrieve.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoListAdminSession> {
    try {
      return await getTodoListAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete (erase) an admin authentication session
   * (todo_list_admin_sessions table).
   *
   * Permanently revoke and delete a specific administrator authentication
   * session from the system.
   *
   * This operation enforces immediate termination of all privileges and ongoing
   * authenticated access for the targeted admin session by deleting the session
   * record in todo_list_admin_sessions. It is used for security, incident
   * response, and compliance needs when an administrator's session must be
   * forcefully ended (such as due to detected suspicious activity or loss of
   * control over a device).
   *
   * Only users classified as administrators may execute this operation. The
   * endpoint validates the provided adminId and sessionId, ensuring both are
   * present and correspond to a valid relationship in the database. If the
   * session cannot be located or does not belong to the specified admin, an
   * error is returned. Upon successful erasure, there is no response body. This
   * operation upholds audit, security, and compliance standards by tightly
   * controlling privileged session lifecycles.
   *
   * Clients should ensure that any cached session credentials or tokens
   * associated with this session are also invalidated. This endpoint is
   * directly related to the PATCH /admins/{adminId}/sessions endpoint, which
   * lists sessions for administrative action and review.
   *
   * @param connection
   * @param adminId Unique identifier (UUID) of the administrator whose session
   *   is being revoked. This associates the operation with a specific admin
   *   user.
   * @param sessionId Unique identifier (UUID) of the specific authentication
   *   session to delete, as recorded in the todo_list_admin_sessions table.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("adminId")
    adminId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoListAdminAdminsAdminIdSessionsSessionId({
        admin,
        adminId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
