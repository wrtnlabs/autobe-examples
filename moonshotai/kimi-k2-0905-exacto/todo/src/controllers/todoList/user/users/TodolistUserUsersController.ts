import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoListUserUsersUserId } from "../../../../providers/getTodoListUserUsersUserId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { putTodoListUserUsersUserId } from "../../../../providers/putTodoListUserUsersUserId";

import { ITodoListUser } from "../../../../api/structures/ITodoListUser";

@Controller("/todoList/user/users/:userId")
export class TodolistUserUsersController {
  /**
   * Retrieve a todo list user account (todo_list_users) by ID with privacy
   * enforcement.
   *
   * Retrieve detailed information about a specific todo list user account using
   * the unique user ID (UUID). This endpoint allows an authenticated user to
   * access their own account details, including email and account status
   * fields. The path parameter userId must be the unique identifier for the
   * user in the database.
   *
   * Security and Privacy: This operation enforces strict user isolation and
   * privacy by allowing only the requested user to access their own account.
   * Requests for other users' accounts are strictly disallowed and will result
   * in an authorization error. The implementation must ensure that users cannot
   * enumerate or guess other valid user IDs.
   *
   * The response includes all primary data fields for the user entity, ensuring
   * clients can display and manage personal details in profile or settings
   * screens. Timestamps for account creation and last update are included for
   * informational and auditing purposes. System-managed authentication and
   * auditing details are never exposed here.
   *
   * This API operation directly references the todo_list_users Prisma table and
   * aligns with the schema's privacy requirements. Error handling includes not
   * found (invalid or non-existent userId), forbidden (attempt to access
   * another user's record), and possible locked status, where account
   * management is restricted.
   *
   * @param connection
   * @param userId UUID of the target user account. Must be the unique
   *   identifier assigned at account creation.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoListUser> {
    try {
      return await getTodoListUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update a todo list user account (todo_list_users) by ID, restricted to
   * self-update.
   *
   * Update the authenticated user's own todo list user account, as identified
   * by the path parameter userId. The request body contains the update
   * information using the ITodoListUser.IUpdate structure, which permits
   * modifications to allowed fields (email and/or password only).
   *
   * Access to this operation is strictly limited to the user whose account is
   * being updated. The implementation must prevent any possibility of privilege
   * escalation or modification of other users' accounts. Account locking,
   * unlocking, and privilege changes are not permitted for normal users via
   * this endpoint.
   *
   * If the update is successful, the full updated user account record is
   * returned. The updated_at timestamp is set to indicate the modification
   * time. Operations are audited for traceability and security. Error handling
   * includes forbidden (user mismatch), validation errors (invalid email or
   * password), and account-locked scenarios where updates are disallowed.
   *
   * @param connection
   * @param userId UUID of the user account to update. Must match the
   *   authenticated user's own ID.
   * @param body Update information for the todo list user. Includes fields
   *   allowable for user modifications (email or password).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoListUser.IUpdate,
  ): Promise<ITodoListUser> {
    try {
      return await putTodoListUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
