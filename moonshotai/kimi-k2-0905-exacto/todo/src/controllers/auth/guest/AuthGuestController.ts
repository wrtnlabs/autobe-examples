import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { GuestAuth } from "../../../decorators/GuestAuth";
import { GuestPayload } from "../../../decorators/payload/GuestPayload";
import { patchAuthGuestRefresh } from "../../../providers/patchAuthGuestRefresh";

import { ITodoGuest } from "../../../api/structures/ITodoGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Create temporary guest access token for preview functionality.
   *
   * Create temporary guest access for unauthenticated visitors to preview basic
   * functionality without requiring registration. This operation generates a
   * guest token that provides limited read-only access and demonstrates the
   * service's value proposition before account creation.
   *
   * The guest access enables potential customers to experience the minimal todo
   * functionality without friction, understanding how the service works through
   * actual interaction rather than descriptions. The temporary nature
   * encourages registration when users find value in the demonstration.
   *
   * This operation corresponds to the todo_guests table management where
   * temporary guest accounts are created and tracked. Related operations
   * include join (this operation) and refresh for maintaining temporary access
   * sessions as implemented by todo_guest_sessions table tracking.
   *
   * @param connection
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @GuestAuth()
    guest: GuestPayload,
  ): Promise<ITodoGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        guest,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest access token to extend preview session.
   *
   * Refresh temporary guest access tokens to extend session duration for
   * preview functionality. This operation enables guest users to continue
   * exploring the service without creating an account, maintaining their
   * demonstration session as long as needed.
   *
   * The refresh mechanism ensures guest users don't lose their preview session
   * before deciding whether to register for full functionality. It demonstrates
   * the service's reliability and user-friendly approach even for temporary
   * access. The operation validates current guest session validity before
   * issuing new tokens.
   *
   * This operation corresponds to session management in todo_guest_sessions
   * table, extending expired_at timestamps for continued temporary access. It
   * works in conjunction with the join operation to provide complete temporary
   * session lifecycle management for unauthenticated visitors.
   *
   * @param connection
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("refresh")
  public async refresh(
    @GuestAuth()
    guest: GuestPayload,
  ): Promise<ITodoGuest.IAuthorized> {
    try {
      return await patchAuthGuestRefresh({
        guest,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
