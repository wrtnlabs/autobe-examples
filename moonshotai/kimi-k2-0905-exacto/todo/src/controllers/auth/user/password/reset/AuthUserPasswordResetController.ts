import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordReset } from "../../../../../providers/postAuthUserPasswordReset";

import { ITodoUser } from "../../../../../api/structures/ITodoUser";

@Controller("/auth/user/password/reset")
export class AuthUserPasswordResetController {
  /**
   * Request password reset for users.
   *
   * Initiates password reset process for Todo application users. This endpoint
   * processes password reset requests by validating the user's email address
   * against the todo_users table, then generates a unique reset password token
   * and sets the reset_password_expires timestamp to 30 minutes in the future
   * as specified in the requirements. The operation updates the user's record
   * with the secure token that will be used for password recovery verification.
   * This is the first step in the password reset workflow, enabling users who
   * have forgotten their passwords to regain access to their accounts and todo
   * lists. The system implements proper security measures to prevent abuse
   * while ensuring legitimate users can recover access to their task management
   * functionality.
   *
   * @param connection
   * @param body Email address for password reset request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async requestPasswordReset(
    @TypedBody()
    body: ITodoUser.IPasswordResetRequest,
  ): Promise<ITodoUser.IPasswordResetResponse> {
    try {
      return await postAuthUserPasswordReset({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
