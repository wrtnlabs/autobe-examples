import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserPasswordResetConfirm } from "../../../../../../providers/postAuthUserPasswordResetConfirm";

import { ITodoUser } from "../../../../../../api/structures/ITodoUser";

@Controller("/auth/user/password/reset/confirm")
export class AuthUserPasswordResetConfirmController {
  /**
   * Complete password reset with new password.
   *
   * Completes password reset process for Todo application users. This endpoint
   * validates the provided reset password token against the stored
   * todo_users.reset_password_token and verifies that reset_password_expires
   * has not passed. Upon successful validation, the operation updates the
   * user's password_hash with the new securely hashed password and clears the
   * reset token fields to prevent reuse. This is the final step in password
   * recovery, allowing users to regain access to their accounts with a new
   * password. The implementation ensures that reset tokens can only be used
   * once and expire after 30 minutes as specified in the requirements,
   * maintaining account security for the task management system.
   *
   * @param connection
   * @param body New password with reset token confirmation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmPasswordReset(
    @TypedBody()
    body: ITodoUser.IPasswordResetConfirm,
  ): Promise<ITodoUser.IPasswordResetConfirmResponse> {
    try {
      return await postAuthUserPasswordResetConfirm({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
