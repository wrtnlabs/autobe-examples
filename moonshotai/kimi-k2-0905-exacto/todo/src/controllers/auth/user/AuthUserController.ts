import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";

import { ITodoAppUser } from "../../../api/structures/ITodoAppUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * This endpoint creates new user accounts for the Todo List Application. Upon
   * successful registration, the system creates a user record in the
   * todo_app_users table with the provided email address and hashed password.
   * The email field must be unique across all user accounts and follow valid
   * email format validation. The password is securely hashed using bcrypt
   * before storage in the password_hash field.
   *
   * The registration process automatically assigns a status of 'active' to new
   * accounts, allowing immediate access to todo functionality. Users can
   * optionally provide a display name for personalization, stored in the name
   * field. The system generates timestamps for both created_at and updated_at
   * fields, marking the initial account creation time.
   *
   * Security considerations include email uniqueness validation to prevent
   * duplicate accounts, password strength requirements following standard
   * security practices, and immediate issuance of JWT access and refresh tokens
   * upon successful registration. The system supports multi-device
   * authentication from creation, with session management enabling users to
   * access their accounts across multiple devices.
   *
   * The response returns authentication tokens and basic user information,
   * enabling immediate application use without additional verification steps.
   * This streamlined approach reduces barriers to adoption while maintaining
   * security standards through proper credential handling and session
   * management.
   *
   * @param connection
   * @param body User registration information including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ICreate,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint authenticates users with their email address and password
   * credentials. The login system validates credentials by comparing the
   * provided password against the stored password_hash in the todo_app_users
   * table using secure bcrypt comparison algorithms. Only accounts with
   * 'active' status are permitted to authenticate successfully.
   *
   * The authentication process supports multi-device access control, allowing
   * users to maintain concurrent sessions across up to 5 devices as specified
   * in the authentication requirements. Successful login generates fresh JWT
   * access and refresh tokens with appropriate expiration times. The access
   * token provides immediate API access, while the refresh token enables token
   * renewal without requiring re-authentication.
   *
   * Security measures include protection against brute force attacks through
   * rate limiting implementations, immediate token rotation upon successful
   * authentication to prevent replay attacks, and comprehensive logging of
   * authentication attempts for security monitoring. The system handles
   * authentication failures gracefully with generic error messages that don't
   * reveal whether email addresses exist in the system.
   *
   * The login response returns the authenticated user's basic information along
   * with the JWT token pair, enabling immediate API access for protected
   * endpoints. The refresh token supports session persistence for up to 7 days
   * of inactivity, balancing user convenience with security requirements. This
   * authentication approach provides enterprise-grade security while
   * maintaining the simple, streamlined user experience central to the todo
   * application.
   *
   * @param connection
   * @param body User login credentials with email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoAppUser.ILogin,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This endpoint refreshes JWT access tokens for users with valid refresh
   * tokens. The system validates the provided refresh token against stored
   * session data in related todo_app_sessions table, ensuring token
   * authenticity and checking for token revocation or expiration. Valid refresh
   * tokens enable issuance of new access tokens without requiring user
   * credential re-entry.
   *
   * The refresh process implements secure token rotation, invalidating the old
   * refresh token upon successful refresh and issuing a new refresh token pair.
   * This security measure prevents token replay attacks while maintaining
   * continuous authentication for active users. The operation supports the
   * specified 7-day refresh token expiration period, requiring
   * re-authentication only after extended inactivity periods.
   *
   * Token validation includes verification of token signature, expiration
   * checking against configured TTL values, and session status validation to
   * ensure the corresponding user account remains active. The system maintains
   * session consistency across multiple device access, ensuring token refresh
   * on one device doesn't invalidate legitimate sessions on other devices.
   *
   * The refresh response returns new JWT access and refresh tokens along with
   * user identification information, enabling seamless continuation of
   * protected API operations. This operation forms the backbone of the
   * application's session management strategy, providing secure, user-friendly
   * authentication that balances convenience with security best practices for
   * todo list management.
   *
   * @param connection
   * @param body Refresh token request containing the current refresh token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUser.IRefresh,
  ): Promise<ITodoAppUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
