import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthUserJoin } from "../../../providers/postAuthUserJoin";
import { postAuthUserLogin } from "../../../providers/postAuthUserLogin";
import { postAuthUserRefresh } from "../../../providers/postAuthUserRefresh";
import { UserAuth } from "../../../decorators/UserAuth";
import { UserPayload } from "../../../decorators/payload/UserPayload";

import { ITodoUser } from "../../../api/structures/ITodoUser";

@Controller("/auth/user")
export class AuthUserController {
  /**
   * User registration for new Todo application users.
   *
   * Registers a new user account in the Todo application. This endpoint creates
   * a new user record in the todo_users table with the provided email and
   * password, automatically hashing the password for security. The operation
   * validates that the email is unique and properly formatted, then creates the
   * user with default security settings including mfa_enabled=false,
   * failed_login_attempts=0, and generates timestamps for account creation.
   * This is the entry point for new users to access the task management system
   * and must be completed before any todo operations can be performed. The
   * system uses industry-standard password hashing algorithms and prepares the
   * account for future authentication operations including password reset and
   * multi-factor authentication setup.
   *
   * @param connection
   * @param body User registration credentials including email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.IJoin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * User login for existing Todo application users.
   *
   * Authenticates existing users in the Todo application. This endpoint
   * validates user credentials against the todo_users table, checking the email
   * and password hash for authentication. The operation implements security
   * measures including failed login attempt tracking, account lockout
   * protection after 5 consecutive failures, and lockout expiration handling.
   * Upon successful authentication, the system issues JWT access and refresh
   * tokens that enable users to access protected todo operations. The endpoint
   * also handles account security validation including checking for expired
   * reset tokens and MFA status. This is the primary authentication flow for
   * returning users to access their personal task lists and perform todo
   * operations.
   *
   * @param connection
   * @param body User login credentials with email and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: ITodoUser.ILogin,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens for authenticated users.
   *
   * Refreshes authentication tokens for authenticated users in the Todo
   * application. This endpoint validates the provided refresh token against the
   * user's session data and todo_user_sessions table, ensuring the token is
   * valid and not expired. The operation checks the user's account status
   * including whether the account is active (deleted_at is null) and implements
   * proper security validation. Upon successful validation, the system issues
   * new JWT access and refresh tokens, extending the user's authenticated
   * session. This allows users to maintain continuous access to their todo
   * operations without interruption due to token expiration. The refresh
   * mechanism is essential for maintaining long-running sessions while
   * implementing proper security boundaries for the task management system.
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRefresh,
  ): Promise<ITodoUser.IAuthorized> {
    try {
      return await postAuthUserRefresh({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
