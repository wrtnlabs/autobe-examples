import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoGuestGuestsGuestIdSessions } from "../../../../../providers/patchTodoGuestGuestsGuestIdSessions";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";

import { ITodoGuestSession } from "../../../../../api/structures/ITodoGuestSession";

@Controller("/todo/guest/guests/:guestId/sessions")
export class TodoGuestGuestsSessionsController {
  /**
   * Retrieve or refresh guest session information.
   *
   * Retrieve current active sessions for a guest user or refresh their
   * temporary access token. This operation allows unregistered users to
   * maintain their demonstration session and continue exploring the
   * application's core features without creating an account.
   *
   * The system tracks guest sessions through the todo_guest_sessions table,
   * maintaining connection metadata including IP address, creation timestamp,
   * and expiration. Each session provides temporary access to basic todo
   * functionality while preventing abuse through session expiration and
   * connection tracking.
   *
   * Guest users can only access demonstration features and should be redirected
   * to the registration flow when attempting to perform operations requiring
   * full user authentication. The session management ensures guest users have a
   * consistent experience during their temporary visit while encouraging
   * conversion to registered users for full functionality.
   *
   * Security considerations include automatic session expiration after
   * reasonable time periods, IP address tracking for accountability, and
   * restriction from user-specific operations. The operation should clearly
   * indicate session status and encourage account creation for persistent task
   * management.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user session
   * @param body Session refresh request with optional metadata updates
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoGuestSession.IRequest,
  ): Promise<ITodoGuestSession> {
    try {
      return await patchTodoGuestGuestsGuestIdSessions({
        guest,
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
