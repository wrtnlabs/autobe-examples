import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserUserTasks } from "../../../../providers/postTodoUserUserTasks";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoUserUserTasks } from "../../../../providers/patchTodoUserUserTasks";
import { getTodoUserUserTasksId } from "../../../../providers/getTodoUserUserTasksId";
import { putTodoUserUserTasksId } from "../../../../providers/putTodoUserUserTasksId";
import { deleteTodoUserUserTasksId } from "../../../../providers/deleteTodoUserUserTasksId";

import { ITodoTask } from "../../../../api/structures/ITodoTask";
import { IPageITodoTask } from "../../../../api/structures/IPageITodoTask";

@Controller("/todo/user/user-tasks")
export class TodoUserUser_tasksController {
  /**
   * Create a new task for the authenticated user.
   *
   * Creates a new task under the authenticated user's account. This operation
   * operates on the todo_tasks table from the Prisma schema and implements the
   * core task creation functionality.
   *
   * The task creation requires a description and automatically sets completion
   * status to false. The business workflow status defaults to 'pending' as
   * specified in the requirements, and creation and update timestamps are
   * automatically managed by the system. This ensures consistency across all
   * task creation operations.
   *
   * Input validation includes ensuring the task description is not empty and
   * does not exceed 500 characters, matching the functional requirement for
   * maximum task description length. The system also enforces the unique
   * constraint on task description per user to prevent duplicate tasks with the
   * same description for a single user.
   *
   * Access is restricted to authenticated users who have an active session. The
   * operation automatically associates the new task with the current user's
   * account, ensuring proper ownership and authorization through the session
   * management system.
   *
   * The operation provides immediate visual confirmation to users by returning
   * the created task object, allowing the client application to immediately
   * display the new task in their task list without requiring additional
   * queries or delays.
   *
   * @param connection
   * @param body New task information including the task description
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTask.ICreate,
  ): Promise<ITodoTask> {
    try {
      return await postTodoUserUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and filter todo tasks.
   *
   * This operation searches and retrieves todo tasks for the authenticated user
   * from the todo_tasks table. Users can filter by business_status (pending,
   * processing, completed), completion status (completed=true/false), and
   * perform text-based searches through task descriptions using PostgreSQL
   * gin_trgm_ops indexing for efficient partial text matching.
   *
   * The search capability supports multiple criteria including business
   * workflow status management as specified in the requirements. Users can
   * search for tasks containing specific text in the description field, filter
   * by completion status, and organize by business_status workflow stages. The
   * operation maintains pagination through the IPage response pattern to handle
   * potentially large numbers of tasks efficiently.
   *
   * The response format includes task details such as unique identifier,
   * description, completion status, business_status, and timing information
   * (created_at, updated_at, completed_at). The pagination metadata (total
   * count, current page, page size) enables clients to build consistent
   * navigation interfaces while maintaining performance across large task
   * collections.
   *
   * Security considerations ensure users can only search within their own task
   * collection, with the todo_user_id parameter automatically constrained to
   * the authenticated user's identifier. The operation enforces the relational
   * integrity between users and their associated tasks as defined in the Prisma
   * schema.
   *
   * @param connection
   * @param body Search criteria including filters for business_status,
   *   completion status, text search, and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoTask.IRequest,
  ): Promise<IPageITodoTask.ISummary> {
    try {
      return await patchTodoUserUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a specific task by ID.
   *
   * Retrieves detailed information for a specific task identified by its unique
   * ID. This operation operates on the todo_tasks table from the Prisma
   * schema.
   *
   * The task information includes the task description, current completion
   * status (boolean), business workflow status (pending/processing/completed),
   * creation timestamp, update timestamp, and completion timestamp if the task
   * has been completed. This allows users to view all relevant metadata about a
   * specific task.
   *
   * Access is restricted to the task owner only - users can only retrieve tasks
   * that belong to their account. This ensures data privacy and security by
   * preventing unauthorized access to other users' tasks. The operation
   * validates the task ID exists and belongs to the current user before
   * returning information.
   *
   * The immediate use case is displaying detailed task information to the user,
   * supporting scenarios where users need to review a specific task's details,
   * check its completion status, or monitor when it was last updated. This
   * supports the overall goal of providing clear visibility into task
   * management efforts.
   *
   * @param connection
   * @param id Unique identifier of the task to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":id")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<ITodoTask> {
    try {
      return await getTodoUserUserTasksId({
        user,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing todo task for the currently authenticated user. This
   * operation allows users to modify task descriptions up to 500 characters,
   * toggle completion status, and update the business workflow status.
   *
   * The system enforces several validation rules:
   *
   * - Task descriptions must not be empty and are trimmed of leading/trailing
   *   whitespace
   * - The description must be unique within the user's task list to prevent
   *   duplicate tasks
   * - Business status must be one of the allowed values: 'pending', 'processing',
   *   or 'completed'
   * - When marking a task as completed, the system automatically sets the
   *   completed_at timestamp
   *
   * Security considerations include proper authorization checks to ensure users
   * can only update their own tasks. The operation includes session validation
   * and provides immediate feedback on successful updates. Error handling
   * covers validation failures, duplicate task descriptions, and attempts to
   * access unauthorized tasks.
   *
   * @param connection
   * @param id Unique identifier of the task to update
   * @param body Updated task information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":id")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTask.IUpdate,
  ): Promise<ITodoTask> {
    try {
      return await putTodoUserUserTasksId({
        user,
        id,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a todo task permanently.
   *
   * Permanently delete a todo task from the authenticated user's task list.
   * This operation performs a hard delete, completely removing the task from
   * the database and making it unrecoverable.
   *
   * The system enforces strict authorization to ensure users can only delete
   * their own tasks. Before deletion, the system verifies that the task exists
   * and belongs to the authenticated user through the task_id and user_id
   * relationship. This prevents unauthorized deletion of tasks belonging to
   * other users.
   *
   * The operation provides immediate visual confirmation when a task is
   * successfully deleted. No undo mechanism is provided - once deleted, tasks
   * cannot be recovered. This design choice aligns with the application's
   * minimal approach, focusing on simple task management without complex
   * recovery mechanisms.
   *
   * Error handling covers scenarios where the task doesn't exist, the user
   * lacks authorization, or database operations fail. The system maintains data
   * integrity by using database transactions to ensure deletion operations
   * complete atomically.
   *
   * @param connection
   * @param id Unique identifier of the task to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":id")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("id")
    id: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserUserTasksId({
        user,
        id,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
