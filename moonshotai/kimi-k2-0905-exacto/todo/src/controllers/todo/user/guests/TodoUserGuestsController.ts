import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteTodoUserGuestsGuestId } from "../../../../providers/deleteTodoUserGuestsGuestId";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

@Controller("/todo/user/guests/:guestId")
export class TodoUserGuestsController {
  /**
   * Remove a temporary guest user account.
   *
   * Permanently remove a temporary guest user account and all associated
   * session data. This operation serves administrators by cleaning up temporary
   * access credentials after guests have previewed the application
   * functionality.
   *
   * When a guest user accesses the system temporarily, they create a session
   * that allows exploration of basic features without registration. Once the
   * guest session is no longer needed (either through expiration or active
   * cleanup), this operation properly removes the guest account from the
   * todo_guests table along with any associated session data in the
   * todo_guest_sessions table.
   *
   * The implementation ensures clean resource management by removing temporary
   * data that could accumulate over time. Since guest users don't have
   * persistent task data or personal information, the permanent deletion is
   * appropriate and necessary for data hygiene. The operation uses the hard
   * delete pattern since there are no soft delete fields in the guest tables.
   *
   * Access control ensures only authenticated users with appropriate privileges
   * can perform guest cleanup operations. The operation should verify the guest
   * account exists before attempting deletion and handle the cleanup of related
   * session data through proper database cascade operations.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user account to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserGuestsGuestId({
        user,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
