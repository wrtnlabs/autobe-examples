import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoUserUsersUserIdTasks } from "../../../../../providers/postTodoUserUsersUserIdTasks";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { patchTodoUserUsersUserIdTasks } from "../../../../../providers/patchTodoUserUsersUserIdTasks";
import { getTodoUserUsersUserIdTasksTaskId } from "../../../../../providers/getTodoUserUsersUserIdTasksTaskId";
import { putTodoUserUsersUserIdTasksTaskId } from "../../../../../providers/putTodoUserUsersUserIdTasksTaskId";
import { deleteTodoUserUsersUserIdTasksTaskId } from "../../../../../providers/deleteTodoUserUsersUserIdTasksTaskId";

import { ITodoTask } from "../../../../../api/structures/ITodoTask";
import { IPageITodoTask } from "../../../../../api/structures/IPageITodoTask";

@Controller("/todo/user/users/:userId/tasks")
export class TodoUserUsersTasksController {
  /**
   * Create a new todo task for a user.
   *
   * Create a new todo task for the authenticated user. This operation allows
   * users to quickly add new tasks without specifying complex parameters - only
   * the task description is required.
   *
   * The creation process automatically handles several system-managed fields
   * including the user association, creation timestamp, initial completion
   * status set to false, and business workflow status defaulting to 'pending'.
   * Duplicate prevention is enforced through the composite unique constraint on
   * description and user_id.
   *
   * The operation provides immediate feedback with the created task details
   * including all system-generated fields.
   *
   * @param connection
   * @param userId Unique identifier of the user who will own the newly created
   *   task
   * @param body Task creation information including description and optional
   *   business status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTask.ICreate,
  ): Promise<ITodoTask> {
    try {
      return await postTodoUserUsersUserIdTasks({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of todo tasks for a specific
   * user.
   *
   * Retrieve a filtered and paginated list of todo tasks for the authenticated
   * user. This operation provides advanced search capabilities for finding
   * tasks based on multiple criteria including completion status, business
   * workflow status, description text matching, and creation date ranges.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Users can filter tasks by completion status
   * (completed vs incomplete), business workflow status (pending, processing,
   * completed), and search task descriptions using fuzzy text matching.
   *
   * Security is enforced through user authentication - users can only access
   * their own tasks through the user-specific path parameter.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose tasks are being
   *   retrieved
   * @param body Search criteria and pagination parameters for task filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTask.IRequest,
  ): Promise<IPageITodoTask.ISummary> {
    try {
      return await patchTodoUserUsersUserIdTasks({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific todo task.
   *
   * Retrieve complete task information for a specific task owned by the
   * authenticated user. This operation provides full task details including the
   * task description up to 500 characters, completion status (true for
   * completed, false for incomplete), business workflow status (pending,
   * processing, completed), and all relevant timestamps for creation,
   * modification, and completion. The API ensures users can only access their
   * own tasks through user authentication verification. Task data is retrieved
   * using efficient database queries to maintain the application's performance
   * standards, completing operations within 300 milliseconds to provide instant
   * feedback that enhances user engagement. The response format includes all
   * task metadata needed for comprehensive task management and tracking,
   * supporting the application's goal of immediate utility without
   * configuration requirements.
   *
   * @param connection
   * @param userId Unique identifier of the task owner user
   * @param taskId Unique identifier of the specific task to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<ITodoTask> {
    try {
      return await getTodoUserUsersUserIdTasksTaskId({
        user,
        userId,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing todo task properties.
   *
   * Update an existing task belonging to the authenticated user. This operation
   * allows modification of task properties through a PUT endpoint that replaces
   * all task data with the provided update information. Users can modify the
   * task description (limited to 500 characters as per application
   * requirements), completion status to mark tasks as done or pending, and
   * business workflow status to track task progression through different
   * workflow states. The API ensures only task owners can update their tasks
   * through proper authorization checks. When a task transitions from
   * incomplete to completed state, the system automatically sets the
   * completed_at timestamp as specified in the functional requirements. The
   * update operation maintains the application's performance standards by
   * completing within 300 milliseconds while providing immediate visual
   * feedback to maintain user engagement. This supports the application's core
   * principle of delivering exactly what users need without complexity or
   * configuration overhead.
   *
   * @param connection
   * @param userId Unique identifier of the task owner user
   * @param taskId Unique identifier of the specific task to update
   * @param body Updated task properties including description, completion
   *   status, and business workflow status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoTask.IUpdate,
  ): Promise<ITodoTask> {
    try {
      return await putTodoUserUsersUserIdTasksTaskId({
        user,
        userId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific todo task owned by the user.
   *
   * Permanently delete a todo task from the user's personal task list. This
   * operation removes the task completely from the database without
   * implementing soft deletion, as the todo_tasks table lacks a deleted_at
   * field.
   *
   * The system enforces ownership validation to ensure users can only delete
   * their own tasks. The operation validates the composite unique constraint
   * matching both the userId and taskId parameters before deletion. Upon
   * successful deletion, the task is immediately removed from the user's task
   * list and cannot be recovered.
   *
   * This operation integrates with the todo_tasks table as defined in the
   * Prisma schema, respecting the relationship between users and their
   * associated tasks. The implementation ensures data consistency by only
   * allowing deletion of valid, existing tasks within the user's scope.
   *
   * @param connection
   * @param userId Unique identifier of the target user who owns the tasks (UUID
   *   format)
   * @param taskId Unique identifier of the task to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserUsersUserIdTasksTaskId({
        user,
        userId,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
