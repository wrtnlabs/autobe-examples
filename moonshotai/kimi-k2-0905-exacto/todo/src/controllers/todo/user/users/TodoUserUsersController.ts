import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsers } from "../../../../providers/patchTodoUserUsers";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserId } from "../../../../providers/getTodoUserUsersUserId";
import { putTodoUserUsersUserId } from "../../../../providers/putTodoUserUsersUserId";
import { deleteTodoUserUsersUserId } from "../../../../providers/deleteTodoUserUsersUserId";

import { IPageITodoUser } from "../../../../api/structures/IPageITodoUser";
import { ITodoUser } from "../../../../api/structures/ITodoUser";

@Controller("/todo/user/users")
export class TodoUserUsersController {
  /**
   * Retrieve a filtered and paginated list of todo users with support for
   * advanced search capabilities. This operation allows authenticated users to
   * search and filter users based on various criteria including email
   * addresses, account creation dates, login status, and authentication
   * details.
   *
   * The operation provides comprehensive filtering options for user account
   * management, including the ability to filter by user creation timestamps,
   * email patterns, multi-factor authentication status, account lockout status,
   * and failed login attempts. Results are returned in a paginated format with
   * configurable sorting options.
   *
   * Authenticated users can use this operation to monitor their own account
   * information, troubleshoot authentication issues, and view user lifecycle
   * states. The operation ensures that users can only access appropriate
   * account information while maintaining proper privacy controls.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering todo
   *   users
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoUser.IRequest,
  ): Promise<IPageITodoUser.ISummary> {
    try {
      return await patchTodoUserUsers({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific todo user.
   *
   * Retrieve comprehensive user profile information for a specific todo user
   * identified by their UUID. This operation provides access to user account
   * details including email address, account creation timestamp, multi-factor
   * authentication settings, account lockout status, and authentication failure
   * history.
   *
   * The operation allows authenticated users to view detailed user account
   * information while maintaining appropriate security controls. It provides
   * insights into user authentication patterns, security settings, and account
   * lifecycle status. User IDs are mapped via the UUID primary key in the
   * todo_users table.
   *
   * Authenticated users can use this operation to investigate their own account
   * status, verify authentication settings, and manage security-related
   * information. The operation ensures that user data is properly controlled
   * and only accessible with appropriate permissions.
   *
   * @param connection
   * @param userId Unique identifier of the target user
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":userId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoUser> {
    try {
      return await getTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update user account information including email and password.
   *
   * Update an existing user account with new information. This operation allows
   * users to modify their account details including email address and password.
   * The system validates that the email address is unique across all registered
   * users to prevent duplicate accounts. Password updates are handled securely
   * through proper hashing mechanisms.
   *
   * The operation ensures that users can only update their own accounts through
   * proper authorization checks. All changes are tracked with automatic
   * timestamping through the updated_at field in the todo_users table. The
   * system maintains data integrity by validating email format and ensuring
   * password complexity when password changes are requested.
   *
   * Security considerations include verifying the user's identity through
   * session validation before allowing updates. The operation respects the
   * user's privacy by only updating fields that are provided in the request.
   * The system maintains audit trails through the built-in timestamp fields in
   * the todo_users table.
   *
   * Error handling includes validation for invalid email formats, duplicate
   * email addresses, and user identification failures. The operation provides
   * clear feedback when updates fail or when authorization issues occur.
   *
   * @param connection
   * @param userId Unique identifier of the user account to update
   * @param body Updated user account information including email and optional
   *   password changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":userId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUser.IUpdate,
  ): Promise<ITodoUser> {
    try {
      return await putTodoUserUsersUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a user account and all associated data from the system.
   * This operation fully removes the user record from the todo_users table
   * along with all related data including tasks, sessions, and guest sessions
   * through cascade deletion. The operation performs hard deletion, removing
   * all traces of the user's existence in the system.
   *
   * The deletion affects multiple related tables through the defined foreign
   * key relationships. All tasks created by the user are removed, their user
   * sessions are terminated, and any guest sessions associated with their user
   * account are cleaned up. The irreversible nature of this operation requires
   * careful user confirmation before execution.
   *
   * Security requirements dictate that users can only delete their own accounts
   * to prevent unauthorized data loss. The system verifies session ownership
   * and validates that the requesting user has permission to delete the
   * specified account. Proper authorization is enforced through authentication
   * middleware that validates the user's identity and permissions.
   *
   * This operation supports the todo application's minimalist approach by
   * providing full data removal rather than soft deletion. Users who wish to
   * temporarily disable their accounts should contact support rather than using
   * this destructive operation. The system maintains data consistency by
   * removing all related data through proper cascade operations.
   *
   * @param connection
   * @param userId Unique identifier of the user account to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":userId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoUserUsersUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
