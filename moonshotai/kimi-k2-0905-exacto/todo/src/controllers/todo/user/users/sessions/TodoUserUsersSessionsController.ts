import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoUserUsersUserIdSessions } from "../../../../../providers/patchTodoUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoUserUsersUserIdSessionsSessionId";

import { IPageITodoUserSession } from "../../../../../api/structures/IPageITodoUserSession";
import { ITodoUserSession } from "../../../../../api/structures/ITodoUserSession";

@Controller("/todo/user/users/:userId/sessions")
export class TodoUserUsersSessionsController {
  /**
   * Search and retrieve a filtered, paginated list of user sessions.
   *
   * Retrieve a filtered and paginated list of user sessions from the system.
   * This operation provides advanced search capabilities for finding sessions
   * based on multiple criteria including IP address filtering, creation date
   * ranges, session status (active vs expired), and connection metadata.
   *
   * The operation supports comprehensive pagination with configurable page
   * sizes and sorting options. Sessions can be sorted by creation date, IP
   * address, or session status. The response includes session summary
   * information optimized for administrative displays, with options to include
   * additional details based on authorization level.
   *
   * Security considerations include proper authorization checks to ensure users
   * can only access their own session data unless they have administrative
   * privileges. The operation implements rate limiting for search operations
   * and appropriate filtering of sensitive connection information based on the
   * requesting user's authorization level.
   *
   * This operation integrates with the todo_user_sessions table as defined in
   * the Prisma schema, incorporating all available session fields and
   * relationships to the todo_users table. The response format includes session
   * metadata while protecting sensitive user information.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions are being
   *   queried
   * @param body Search criteria and pagination parameters for session filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoUserSession.IRequest,
  ): Promise<IPageITodoUserSession.ISummary> {
    try {
      return await patchTodoUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific user session including
   * connection metadata, creation timestamp, and session status. This operation
   * provides comprehensive session details for security auditing, session
   * verification, and user activity monitoring.
   *
   * The operation returns complete session information including the IP address
   * from which the session was created, the connection URL (href) and referrer
   * information, creation timestamp, and expiration status. This data is
   * essential for users to monitor their account activity and identify any
   * unauthorized access attempts.
   *
   * Security considerations include proper authorization to ensure users can
   * only access their own session data. The operation implements protection
   * against session enumeration attacks and ensures sensitive connection
   * information is handled appropriately. Users can use this endpoint to verify
   * their current session details and monitor for any suspicious activity.
   *
   * The response includes full session metadata while maintaining appropriate
   * privacy protections. Session data is linked to the user through the
   * todo_user_sessions table relationship with todo_users, ensuring data
   * integrity and proper access control throughout the system.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns this session
   * @param sessionId Unique identifier of the specific session to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoUserSession> {
    try {
      return await getTodoUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
