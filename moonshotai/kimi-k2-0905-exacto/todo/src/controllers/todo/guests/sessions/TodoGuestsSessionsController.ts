import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoGuestsGuestIdSessionsSessionId } from "../../../../providers/getTodoGuestsGuestIdSessionsSessionId";

import { ITodoGuestSession } from "../../../../api/structures/ITodoGuestSession";

@Controller("/todo/guests/:guestId/sessions/:sessionId")
export class TodoGuestsSessionsController {
  /**
   * Retrieve guest session details.
   *
   * Retrieve details about a specific guest session including connection
   * metadata and session status. This operation enables the system to track
   * temporary guest users who are accessing the application without full
   * registration. Guest sessions are created for demo purposes and allow users
   * to experience basic functionality before committing to registration.
   *
   * The system maintains connection information including IP address, original
   * URL, and referrer for auditing purposes. Sessions have expiration
   * timestamps to ensure temporary access doesn't persist indefinitely. This
   * endpoint is primarily used for session management and audit trails rather
   * than active functionality.
   *
   * Guest sessions provide temporary access to demonstrate the application's
   * value proposition while maintaining security isolation. The operation
   * supports session debugging and monitoring without exposing sensitive user
   * data since guests don't have access to persistent account features.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user
   * @param sessionId Unique identifier of the specific session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoGuestSession> {
    try {
      return await getTodoGuestsGuestIdSessionsSessionId({
        guestId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
