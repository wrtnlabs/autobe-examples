import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoGuests } from "../../../providers/postTodoGuests";
import { getTodoGuestsGuestId } from "../../../providers/getTodoGuestsGuestId";
import { putTodoGuestsGuestId } from "../../../providers/putTodoGuestsGuestId";

import { ITodoGuest } from "../../../api/structures/ITodoGuest";

@Controller("/todo/guests")
export class TodoGuestsController {
  /**
   * Create a new guest session for demo access.
   *
   * Creates a new guest authentication session that provides temporary access
   * to basic application features for demonstration purposes. The operation
   * generates a new guest record in the todo_guests table with automatic
   * timestamp tracking and unique session identification.
   *
   * Guest sessions enable potential users to explore the application's
   * functionality without registration friction. The system maintains security
   * boundaries by associating guest sessions with specific IP addresses and
   * connection metadata while limiting access to core features.
   *
   * This operation supports the user acquisition funnel by allowing interested
   * users to immediately experience the task management capabilities through a
   * guided demo or limited functionality mode. Guest sessions are automatically
   * managed with appropriate access controls and limitations to maintain system
   * security and performance.
   *
   * @param connection
   * @param body Guest session creation request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoGuest.ICreate,
  ): Promise<ITodoGuest> {
    try {
      return await postTodoGuests({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve guest visitor information.
   *
   * Retrieve detailed information about an anonymous guest session in the todo
   * application. This endpoint provides access control verification and session
   * validation for guest users who can preview basic application functionality
   * without registration.
   *
   * The operation returns guest identification data, session timestamps, and
   * access permissions. Guest access serves as a demonstration mechanism
   * allowing potential users to experience the core functionality before
   * creating an account.
   *
   * The response includes the guest's unique identifier, session creation time,
   * last update time, and deletion status. This information helps the
   * application manage temporary user access and provide appropriate
   * demonstrations based on guest session configurations.
   *
   * @param connection
   * @param guestId Unique identifier of the guest visitor session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<ITodoGuest> {
    try {
      return await getTodoGuestsGuestId({
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update guest visitor information.
   *
   * Update an existing guest session record to manage demonstration access and
   * temporary user permissions. This endpoint allows modification of guest
   * configuration settings and session metadata for unregistered preview
   * users.
   *
   * The operation supports extending guest session validity, updating
   * demonstration settings, and managing guest access restrictions. This
   * functionality enables dynamic control over guest demonstrations and ensures
   * appropriate resource allocation for preview users.
   *
   * The request includes updated session configuration data, demonstration
   * preferences, and any modifications to guest access permissions. The
   * response confirms successful updates and reflects current guest session
   * status and available demonstration features.
   *
   * @param connection
   * @param guestId Unique identifier of the guest visitor session to update
   * @param body Updated guest session configuration including demonstration
   *   settings and access permissions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":guestId")
  public async update(
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoGuest.IUpdate,
  ): Promise<ITodoGuest> {
    try {
      return await putTodoGuestsGuestId({
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
