import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppAuthUsersUserIdSessions } from "../../../../../providers/postTodoAppAuthUsersUserIdSessions";
import { patchTodoAppAuthUsersUserIdSessions } from "../../../../../providers/patchTodoAppAuthUsersUserIdSessions";

import { ITodoAppUserSession } from "../../../../../api/structures/ITodoAppUserSession";
import { IPageITodoAppUserSession } from "../../../../../api/structures/IPageITodoAppUserSession";

@Controller("/todoApp/auth/users/:userId/sessions")
export class TodoappAuthUsersSessionsController {
  /**
   * Create authenticated user session for administrative support or testing.
   *
   * Administrators can create authenticated sessions for user accounts to
   * provide support, troubleshoot issues, or handle emergency access scenarios.
   * This operation enables legitimate administrative oversight while
   * maintaining comprehensive audit trails of all session creation activities.
   *
   * Session creation includes capturing connection metadata such as IP address,
   * access URL, and referrer information for security tracking. All
   * administrator-initiated sessions are clearly marked in audit logs with the
   * creating administrator's identity and business justification. Sessions
   * follow standard expiration policies and can be manually revoked by
   * administrators when no longer needed.
   *
   * The operation enforces strict authorization controls, requiring
   * administrative privileges and providing detailed session information back
   * to the administrator. Created sessions enable administrators to experience
   * the application from the user's perspective for effective troubleshooting
   * and support.
   *
   * @param connection
   * @param userId Unique identifier of the user account to create session for
   * @param body Session creation parameters including connection metadata and
   *   business justification
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserSession.ICreate,
  ): Promise<ITodoAppUserSession> {
    try {
      return await postTodoAppAuthUsersUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve user authentication sessions for administrative
   * monitoring.
   *
   * Administrators can search and retrieve user session data to monitor
   * authentication activity and account security. This operation provides
   * comprehensive session tracking including IP addresses, access times,
   * session durations, and browser information for security auditing and user
   * support.
   *
   * The operation supports filtering by session status (active/expired), date
   * ranges, and can search by IP address or referrer URL. Results are paginated
   * for performance when dealing with users who have extensive login history.
   * Session data helps administrators identify suspicious activity,
   * troubleshoot login issues, and maintain security compliance.
   *
   * Security considerations include restricted access to administrative users
   * only, with all session data remaining confidential and used solely for
   * security monitoring and user support purposes. The operation respects user
   * privacy while providing necessary oversight capabilities.
   *
   * @param connection
   * @param userId Unique identifier of the user account to retrieve sessions
   *   for
   * @param body Search criteria and pagination parameters for filtering user
   *   sessions
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession> {
    try {
      return await patchTodoAppAuthUsersUserIdSessions({
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
