import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppUserStatisticsCompletionRate } from "../../../../../providers/getTodoAppUserStatisticsCompletionRate";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTaskCompletionRateStatistics } from "../../../../../api/structures/ITodoAppTaskCompletionRateStatistics";

@Controller("/todoApp/user/statistics/completion-rate")
export class TodoappUserStatisticsCompletion_rateController {
  /**
   * Calculate personal task completion rate percentage for authenticated user.
   *
   * Retrieve task completion rate statistics for the currently authenticated
   * user, calculated as the percentage of completed tasks relative to total
   * tasks created. This operation aggregates data across the user's task
   * history to provide insights into personal productivity and task management
   * effectiveness.
   *
   * The completion rate is computed using the formula: (Completed Tasks ÷ Total
   * Tasks) × 100. Completed tasks include those marked as complete through the
   * system's completion workflow, while total tasks encompass all tasks created
   * by the user including those pending completion.
   *
   * The statistic provides valuable insights into user productivity patterns,
   * helping identify periods of high completion rates versus those requiring
   * improved task management strategies. The operation supports historical
   * comparison and goal-setting for personal productivity improvement.
   *
   * This endpoint integrates with task management workflows and completion
   * history tracking. Users can leverage completion rate data to identify
   * trends, set improvement targets, and monitor progress toward achieving
   * better task completion consistency. The calculation accounts for task
   * reactivation scenarios where completed tasks are later reopened for
   * additional work.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppTaskCompletionRateStatistics> {
    try {
      return await getTodoAppUserStatisticsCompletionRate({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
