import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserUserQuotasUserUserId } from "../../../../../providers/getTodoAppUserUserQuotasUserUserId";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppUserQuota } from "../../../../../api/structures/ITodoAppUserQuota";

@Controller("/todoApp/user/userQuotas/user/:userId")
export class TodoappUserUserquotasUserController {
  /**
   * Retrieve detailed quota usage for a specific user.
   *
   * Get comprehensive quota information for a specific user including current
   * usage against limits for tasks, categories, and daily task creation rates.
   * This operation enables monitoring individual user consumption patterns and
   * ensuring fair resource distribution.
   *
   * The response includes both hard limits that prevent further usage when
   * reached, and current status indicators showing how much of each quota has
   * been consumed. Premium user status is also reflected with appropriately
   * adjusted limits based on their subscription tier.
   *
   * This data is crucial for support investigations, usage trend analysis, and
   * ensuring system stability by preventing any single user from consuming
   * excessive resources. The detailed quota view helps identify users who might
   * benefit from premium upgrades or need quota adjustments.
   *
   * Regular users can access their own quota information to understand their
   * current usage and remaining capacity. Administrators can view any user's
   * quota details for monitoring and support purposes.
   *
   * @param connection
   * @param userId Unique identifier of the user whose quota information is
   *   being retrieved
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserQuota> {
    try {
      return await getTodoAppUserUserQuotasUserUserId({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
