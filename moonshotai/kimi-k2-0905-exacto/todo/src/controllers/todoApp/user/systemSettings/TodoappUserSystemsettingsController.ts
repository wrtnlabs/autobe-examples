import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoAppUserSystemSettings } from "../../../../providers/patchTodoAppUserSystemSettings";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";

import { IPageITodoAppSystemSettings } from "../../../../api/structures/IPageITodoAppSystemSettings";
import { ITodoAppSystemSettings } from "../../../../api/structures/ITodoAppSystemSettings";

@Controller("/todoApp/user/systemSettings")
export class TodoappUserSystemsettingsController {
  /**
   * Retrieve paginated system configuration settings with filtering options.
   *
   * Retrieve paginated system configuration settings with filtering
   * capabilities. This operation allows authenticated users to view and filter
   * system-wide settings including default user quotas, feature toggles, rate
   * limiting configuration, email settings, privacy controls, and other
   * operational parameters.
   *
   * These settings define the baseline behavior for all users and affect system
   * performance, security, and user experience. System administrators can
   * monitor and adjust these configurations to optimize application performance
   * and ensure appropriate resource allocation.
   *
   * The operation supports advanced filtering to help locate specific
   * configuration items efficiently. The response includes detailed information
   * about each setting's configuration, current values, and contextual
   * descriptions to assist with system management and troubleshooting.
   *
   * @param connection
   * @param body Search and pagination parameters for filtering system settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppSystemSettings.IRequest,
  ): Promise<IPageITodoAppSystemSettings.ISummary> {
    try {
      return await patchTodoAppUserSystemSettings({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
