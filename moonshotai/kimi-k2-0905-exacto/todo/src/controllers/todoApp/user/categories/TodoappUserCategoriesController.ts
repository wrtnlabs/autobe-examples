import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserCategories } from "../../../../providers/postTodoAppUserCategories";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { patchTodoAppUserCategories } from "../../../../providers/patchTodoAppUserCategories";
import { getTodoAppUserCategoriesCategoryId } from "../../../../providers/getTodoAppUserCategoriesCategoryId";
import { putTodoAppUserCategoriesCategoryId } from "../../../../providers/putTodoAppUserCategoriesCategoryId";
import { deleteTodoAppUserCategoriesCategoryId } from "../../../../providers/deleteTodoAppUserCategoriesCategoryId";

import { ITodoAppCategory } from "../../../../api/structures/ITodoAppCategory";
import { IPageITodoAppCategory } from "../../../../api/structures/IPageITodoAppCategory";

@Controller("/todoApp/user/categories")
export class TodoappUserCategoriesController {
  /**
   * Create a new task category for authenticated users to organize their todo
   * items effectively. Categories provide the primary organizational mechanism
   * within the todo application, enabling users to group related tasks by
   * project, context, or personal classification preferences.
   *
   * The operation enforces business rules that ensure category names remain
   * unique within each user account while accepting descriptive names that
   * follow character restriction guidelines. Category names must contain 2-50
   * characters and can only use letters, numbers, spaces, and hyphens to
   * maintain system compatibility and export functionality requirements.
   *
   * Categories support flexible organization patterns including work/personal
   * divisions, project-based groupings, or contextual organization schemes.
   * Users can filter tasks by category and perform bulk operations on all tasks
   * within a category, making category selection an important organizational
   * decision that impacts daily workflow efficiency.
   *
   * Category creation becomes immediately available for task assignment, and
   * the system maintains category history to support organization evolution as
   * user needs change. The operation supports rapid category creation while
   * providing optional description fields for additional context that helps
   * users maintain clear organizational structure over time.
   *
   * @param connection
   * @param body Category creation data including name and optional description
   *   for task organization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppCategory.ICreate,
  ): Promise<ITodoAppCategory> {
    try {
      return await postTodoAppUserCategories({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve filtered, paginated list of user categories.
   *
   * Retrieve a filtered and paginated list of todo app categories belonging to
   * the authenticated user. This operation provides advanced search
   * capabilities for finding categories based on text search in name and
   * description fields, filtering by creation date ranges, and sorting by
   * various criteria including name, creation date, or update date.
   *
   * The system enforces user isolation - users can only view their own
   * categories due to the foreign key relationship to todo_app_users. Each
   * category must have a unique name within the user's account as enforced by
   * the unique constraint on [todo_app_user_id, name].
   *
   * Categories support the organizational hierarchy described in the Prisma
   * schema, allowing users to group related tasks. The operation respects the
   * 50 category limit per user and provides mechanisms for managing category
   * collections efficiently. Text search uses GIN indexes on the name field for
   * optimal performance.
   *
   * This operation integrates with task management workflows, as categories are
   * referenced by todo_app_tasks through the todo_app_category_id foreign key.
   * Users can filter categories based on usage patterns and manage their
   * organizational structure effectively.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppCategory.IRequest,
  ): Promise<IPageITodoAppCategory.ISummary> {
    try {
      return await patchTodoAppUserCategories({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific category.
   *
   * Retrieve detailed information about a specific todo app category by its
   * unique identifier. This operation provides complete category data including
   * name, description, creation and update timestamps, and relationship to the
   * category owner.
   *
   * Security is enforced through user ownership verification - the operation
   * only returns categories where the todo_app_user_id matches the
   * authenticated user's ID. This prevents users from accessing other users'
   * categories while maintaining data privacy and isolation.
   *
   * The operation supports the category management workflow by providing
   * detailed category information needed for editing, organization planning,
   * and task assignment decisions. Users can view category descriptions to
   * understand organizational context and make informed decisions about task
   * placement.
   *
   * Category data retrieved by this operation can be used for various purposes
   * including displaying category details in management interfaces, validating
   * category existence before task creation, and providing context for bulk
   * operations on tasks within the category.
   *
   * @param connection
   * @param categoryId Unique identifier of the target todo app category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppCategory> {
    try {
      return await getTodoAppUserCategoriesCategoryId({
        user,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing task category for authenticated users.
   *
   * Update an existing task category with modified information while preserving
   * all existing task relationships and organizational structure. The operation
   * enables users to refine their organizational scheme as needs evolve without
   * disrupting existing task assignments.
   *
   * The update process maintains the same validation requirements used during
   * category creation, ensuring category names remain unique within user
   * accounts while following character restriction guidelines. Users can modify
   * category descriptions to provide additional context about category purpose
   * or usage patterns.
   *
   * Category updates preserve all associated task relationships automatically,
   * meaning tasks assigned to the category will continue referencing the
   * updated category without requiring manual reassignment. This ensures
   * organizational continuity while supporting evolution of categorization
   * approaches based on changing user needs or workflow preferences.
   *
   * The operation supports comprehensive category modification while
   * maintaining data integrity across the todo system. Users receive immediate
   * visual feedback about successful updates while the system maintains
   * complete audit trails for accountability and recovery purposes.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to update
   * @param body Updated category information including modified name or
   *   description
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryId")
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppCategory.IUpdate,
  ): Promise<ITodoAppCategory> {
    try {
      return await putTodoAppUserCategoriesCategoryId({
        user,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a specific category and all associated tasks.
   *
   * Permanently removes a specific category and all associated tasks from the
   * authenticated user's todo application. This operation performs a hard
   * delete operation that completely eliminates the category and its related
   * tasks from the database without any recovery mechanism.
   *
   * The deletion process includes all tasks that are currently assigned to this
   * category, ensuring that no orphaned task records remain in the system.
   * Users should be aware that this is an irreversible operation that will
   * remove all organizational structure associated with the selected category.
   *
   * Security considerations include validation that the category being deleted
   * belongs to the currently authenticated user, preventing unauthorized
   * deletion of other users' categories. The operation logs the deletion event
   * for audit trail purposes and maintains system integrity through proper
   * foreign key constraint handling.
   *
   * This operation should be used cautiously as it permanently removes
   * organizational data that may have taken significant time to establish.
   * Users should consider reassigning tasks to different categories before
   * deletion if they wish to preserve the task information while removing only
   * the categorization structure.
   *
   * @param connection
   * @param categoryId Unique identifier of the category to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppCategory> {
    try {
      return await deleteTodoAppUserCategoriesCategoryId({
        user,
        categoryId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
