import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserCategoriesCategoryIdTasks } from "../../../../../providers/patchTodoAppUserCategoriesCategoryIdTasks";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { IPageITodoAppTask } from "../../../../../api/structures/IPageITodoAppTask";
import { ITodoAppTask } from "../../../../../api/structures/ITodoAppTask";

@Controller("/todoApp/user/categories/:categoryId/tasks")
export class TodoappUserCategoriesTasksController {
  /**
   * Search and retrieve tasks within a specific category.
   *
   * Searches and retrieves all tasks associated with a specific category for
   * the authenticated user. This operation provides category-scoped task
   * listing with advanced filtering, sorting, and pagination capabilities
   * specifically designed for organizational task management.
   *
   * Users can filter tasks by multiple criteria including status (pending,
   * in-progress, completed), priority level (Low, Medium, High), due date
   * ranges, and completion status within the specific category context. The
   * operation supports sorting by creation date, priority, due date, completion
   * order, and title to accommodate different organizational preferences.
   *
   * The search functionality includes text search across task titles and
   * descriptions within the category scope, supporting partial word matching
   * and result highlighting. Users can combine multiple filter criteria to
   * create highly specific task views within their organized category
   * structure.
   *
   * Results are returned in paginated format with configurable page sizes and
   * support for continuation tokens where needed. The response includes
   * category information to maintain context and provide complete
   * organizational structure for the returned task collection.
   *
   * This operation is essential for users who organize their work through the
   * category system and need to focus on specific project groups or
   * organizational structures. It provides the detailed task view capabilities
   * needed for effective category-based productivity management.
   *
   * @param connection
   * @param categoryId Unique identifier of the category containing tasks to
   *   retrieve
   * @param body Search criteria and pagination parameters for filtering tasks
   *   within the specified category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("categoryId")
    categoryId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTask.IRequest,
  ): Promise<IPageITodoAppTask.ISummary> {
    try {
      return await patchTodoAppUserCategoriesCategoryIdTasks({
        user,
        categoryId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
