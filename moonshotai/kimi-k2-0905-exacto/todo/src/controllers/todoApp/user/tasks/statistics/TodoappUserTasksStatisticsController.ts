import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppUserTasksStatistics } from "../../../../../providers/getTodoAppUserTasksStatistics";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTaskStatistics } from "../../../../../api/structures/ITodoAppTaskStatistics";

@Controller("/todoApp/user/tasks/statistics")
export class TodoappUserTasksStatisticsController {
  /**
   * Retrieve task statistics and analytics.
   *
   * Retrieve comprehensive task statistics and analytics for the authenticated
   * user's todo list. This operation provides detailed insights into task
   * management patterns including overall task counts, completion rates,
   * priority distributions, and due date analysis.
   *
   * The statistics include total task count breakdown by status (pending vs
   * completed), priority level distribution across all priority categories
   * (none, low, medium, high), completion rate percentages and trends, overdue
   * task counts and percentages, and task creation/activity patterns over time.
   * Additional metrics include average task completion time, most active task
   * creation periods, and productivity trend analysis.
   *
   * These analytics help users understand their task management habits,
   * identify productivity patterns, and make informed decisions about task
   * prioritization and time management. The data is computed in real-time from
   * the user's current task dataset and provides actionable insights for
   * improving personal productivity and task organization effectiveness.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppTaskStatistics> {
    try {
      return await getTodoAppUserTasksStatistics({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
