import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoAppUserTasksBulkDelete } from "../../../../../providers/patchTodoAppUserTasksBulkDelete";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTaskDeletion } from "../../../../../api/structures/ITodoAppTaskDeletion";

@Controller("/todoApp/user/tasks/bulk-delete")
export class TodoappUserTasksBulk_deleteController {
  /**
   * Delete multiple tasks simultaneously.
   *
   * This operation enables authenticated users to permanently remove multiple
   * tasks from their todo list in a single API call. Users can select tasks
   * that are no longer relevant, completed and archived, or outdated and remove
   * them simultaneously instead of processing individual deletion operations
   * which would require significant user interaction overhead.
   *
   * The operation performs soft deletion of tasks in the todo_app_tasks table
   * by removing them from active user views rather than permanently deleting
   * records from the database. This approach enables task recovery if users
   * accidentally delete important items while maintaining organizational
   * cleanliness for active task management workflows. Individual task responses
   * can be fully deleted whereas bulk operations provide atomic processing for
   * efficiency without disrupting normal user workflows.
   *
   * Bulk deletion through this operation differs from individual task deletion
   * in processing approach and user experience patterns. Users experience
   * atomic processing where all deletions succeed or fail together rather
   * having individual confirmation dialogs for each task deletion request. This
   * operation is designed for efficiency while maintaining data safety and
   * audit trail requirements.
   *
   * The bulk deletion operation supports user organizational patterns including
   * periodic task list cleanup, outdated item removal, and comprehensive
   * project completion where all related tasks should be eliminated
   * simultaneously rather than requiring individual confirmation cycles that
   * would discourage effective organization and cleanup behaviors.
   *
   * @param connection
   * @param body Array of task IDs to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async bulkDelete(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTaskDeletion.ICreate,
  ): Promise<ITodoAppTaskDeletion.ISummary> {
    try {
      return await patchTodoAppUserTasksBulkDelete({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
