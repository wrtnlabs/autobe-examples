import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postTodoAppUserTasks } from "../../../../providers/postTodoAppUserTasks";
import { patchTodoAppUserTasks } from "../../../../providers/patchTodoAppUserTasks";
import { UserAuth } from "../../../../decorators/UserAuth";
import { UserPayload } from "../../../../decorators/payload/UserPayload";
import { getTodoAppUserTasksTaskId } from "../../../../providers/getTodoAppUserTasksTaskId";
import { putTodoAppUserTasksTaskId } from "../../../../providers/putTodoAppUserTasksTaskId";
import { deleteTodoAppUserTasksTaskId } from "../../../../providers/deleteTodoAppUserTasksTaskId";

import { ITodoAppTask } from "../../../../api/structures/ITodoAppTask";
import { IPageITodoAppTask } from "../../../../api/structures/IPageITodoAppTask";

@Controller("/todoApp/user/tasks")
export class TodoappUserTasksController {
  /**
   * Create a new personal todo task with essential productivity features
   * including title, description, priority levels, and optional due date
   * management. This operation enables users to organize their daily activities
   * through an intuitive interface that emphasizes ease of use over
   * complexity.
   *
   * The task creation process automatically assigns the task to the
   * authenticated user and initializes appropriate metadata including creation
   * timestamp and default status. Users can specify task priorities (none, low,
   * medium, high) to help focus on urgent items, with medium as the default for
   * balanced organization.
   *
   * Task titles are limited to 200 characters to ensure clarity and
   * readability, while descriptions support up to 1000 characters for
   * comprehensive task information. Due dates can be set up to 5 years in the
   * future for realistic planning horizons. The system maintains data isolation
   * ensuring each user has exclusive access to their own tasks.
   *
   * @param connection
   * @param body Task creation data including title, description, priority, and
   *   optional due date
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @TypedBody()
    body: ITodoAppTask.ICreate,
  ): Promise<ITodoAppTask> {
    try {
      return await postTodoAppUserTasks({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve a filtered, paginated list of todo tasks belonging to
   * the authenticated user. This operation provides comprehensive filtering
   * capabilities allowing users to find tasks based on multiple criteria
   * including title/description text search, status filtering
   * (pending/completed), priority levels, due date ranges, and completion
   * timestamps.
   *
   * The search functionality supports full-text search across task titles and
   * descriptions, enabling users to quickly locate specific tasks using natural
   * language queries. Advanced filtering options include date range filtering
   * for creation, update, and completion timestamps, priority-based filtering
   * from none to high priority, and status-based filtering to focus on pending
   * or completed tasks.
   *
   * Pagination is fully configurable with adjustable page sizes and
   * cursor-based navigation for large datasets. Results can be sorted by
   * various fields including creation date, due date, priority level,
   * completion status, and last update timestamp in both ascending and
   * descending order. The response includes task summaries optimized for list
   * displays while maintaining essential task information for effective task
   * management.
   *
   * @param connection
   * @param body Search criteria, filtering parameters, pagination settings, and
   *   sorting options for task retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTask.IRequest,
  ): Promise<IPageITodoAppTask.ISummary> {
    try {
      return await patchTodoAppUserTasks({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get complete details for a specific todo task identified by its unique
   * UUID. This operation returns the task's title, description, status,
   * priority level, due date, creation date, completion date, and all
   * associated metadata for authenticated users.
   *
   * The endpoint enforces strict user ownership by filtering tasks based on the
   * authenticated user's identity, ensuring data privacy and security. Only
   * tasks belonging to the authenticated user will be returned, preventing
   * unauthorized access to other users' task data.
   *
   * This operation serves the core task retrieval requirement, enabling users
   * to view detailed information about any individual task in their todo list.
   * The complete task information supports editing features and allows users to
   * review all task properties including status history and modification
   * timestamps.
   *
   * @param connection
   * @param taskId Unique UUID identifier of the task to retrieve from the
   *   todo_app_tasks table
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":taskId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTask> {
    try {
      return await getTodoAppUserTasksTaskId({
        user,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing personal todo task with modified information including
   * title, description, status, priority levels, and due date. This operation
   * enables users to keep their task information current and accurate while
   * maintaining complete lifecycle tracking.
   *
   * The update process automatically records modification timestamps and
   * handles status transitions appropriately. When a task is marked as
   * completed, the system records the completion timestamp for productivity
   * analytics and user reference. Users can update any task field while the
   * system maintains data integrity and ownership verification.
   *
   * Task ownership is strictly enforced - users can only update tasks they own.
   * The operation supports all task modifications including priority
   * adjustments, due date changes, and status updates while preserving the
   * task's creation history and user assignment.
   *
   * @param connection
   * @param taskId Unique identifier of the task to update
   * @param body Task update data with optional fields for title, description,
   *   status, priority, and due date
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":taskId")
  public async update(
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppTask.IUpdate,
  ): Promise<ITodoAppTask> {
    try {
      return await putTodoAppUserTasksTaskId({
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete a task from the user's todo list by removing the task
   * record completely from the database. This operation performs a hard delete,
   * permanently eliminating the task data without the possibility of recovery.
   *
   * The hard delete approach ensures that users can clean up their task lists
   * completely when tasks are no longer needed. Deleted tasks are physically
   * removed from the database, freeing up storage space and maintaining clean
   * task management workflows.
   *
   * Users should exercise caution when deleting tasks, as this operation cannot
   * be undone. Once a task is deleted, it cannot be recovered through normal
   * application functionality. The system does not maintain backups of
   * individual deleted tasks.
   *
   * Security considerations ensure that users can only delete tasks they own.
   * The system validates that the requesting user has ownership rights to the
   * specified task before allowing deletion. This prevents unauthorized access
   * to other users' task data while maintaining proper isolation between user
   * accounts.
   *
   * The operation integrates with the todo_app_tasks table as defined in the
   * Prisma schema. Upon successful deletion, the task is completely removed
   * from all user-facing task lists and the database, providing a clean slate
   * for task management.
   *
   * @param connection
   * @param taskId Unique identifier of the task to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":taskId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("taskId")
    taskId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppTask> {
    try {
      return await deleteTodoAppUserTasksTaskId({
        user,
        taskId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
