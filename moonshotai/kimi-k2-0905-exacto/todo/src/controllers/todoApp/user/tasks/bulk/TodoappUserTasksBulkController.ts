import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { putTodoAppUserTasksBulk } from "../../../../../providers/putTodoAppUserTasksBulk";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { patchTodoAppUserTasksBulk } from "../../../../../providers/patchTodoAppUserTasksBulk";

import { ITodoAppTask } from "../../../../../api/structures/ITodoAppTask";

@Controller("/todoApp/user/tasks/bulk")
export class TodoappUserTasksBulkController {
  /**
   * Perform bulk updates on multiple todo tasks, applying changes to status,
   * priority, due dates, completion state, or task content across multiple
   * tasks simultaneously. This operation supports scenarios where users need to
   * update multiple tasks at once, such as marking tasks as complete, changing
   * priorities, updating due dates, or reorganizing task categories.
   *
   * The operation accepts an array of task update operations in the request
   * body, where each operation includes the task identifier and the specific
   * fields to be updated. All updates are applied transactionally - either all
   * updates succeed or all updates fail to maintain data consistency.
   *
   * Error handling provides detailed validation feedback for each individual
   * task update, allowing partial success scenarios where valid updates are
   * applied even if some individual updates fail. The response includes
   * information about which tasks were successfully updated and which failed
   * with specific error details for debugging purposes.
   *
   * @param connection
   * @param body Array of task update operations with individual task
   *   identifiers and update parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTask.IBulkUpdate,
  ): Promise<ITodoAppTask.IBulkUpdateResult> {
    try {
      return await putTodoAppUserTasksBulk({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Execute bulk operations on multiple tasks in a single API call for improved
   * efficiency and user experience. This operation enables users to perform
   * common batch actions such as marking several tasks as completed, updating
   * priorities across multiple items, or adjusting due dates for task groups.
   *
   * The bulk operation design prioritizes performance and atomic consistency,
   * ensuring that either all requested changes succeed or none are applied.
   * This prevents partial updates that could leave task data in inconsistent
   * states while maintaining the integrity of user task management workflows.
   *
   * Common use cases include marking multiple tasks as completed when finishing
   * a project phase, updating priority levels for related tasks during planning
   * sessions, or adjusting due dates when project timelines change. The
   * operation supports flexible action types to accommodate diverse user
   * workflows and task management patterns.
   *
   * The system validates that users have ownership rights for all specified
   * tasks before applying bulk changes. This prevents unauthorized
   * modifications to other users' task data while maintaining proper data
   * isolation between user accounts. The operation integrates with the
   * todo_app_tasks table and respects all business rules and constraints
   * defined in the Prisma schema.
   *
   * @param connection
   * @param body Bulk operation request containing task IDs and the action to
   *   perform
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async bulkUpdate(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTask.IBulkRequest,
  ): Promise<ITodoAppTask.IBulkResponse> {
    try {
      return await patchTodoAppUserTasksBulk({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
