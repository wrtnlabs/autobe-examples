import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchTodoAppUserTasksBulkComplete } from "../../../../../providers/patchTodoAppUserTasksBulkComplete";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTaskCompletion } from "../../../../../api/structures/ITodoAppTaskCompletion";

@Controller("/todoApp/user/tasks/bulk-complete")
export class TodoappUserTasksBulk_completeController {
  /**
   * Complete multiple tasks simultaneously.
   *
   * This operation enables authenticated users to mark multiple tasks as
   * completed in a single API call, providing an efficient workflow for bulk
   * task management. Users can select tasks from their current todo list and
   * complete them simultaneously, which is particularly useful when finishing
   * related work items or during end-of-day task organization.
   *
   * The operation updates task status in the todo_app_tasks table for all valid
   * tasks while creating completion records in todo_app_task_completions table
   * for each task completion event. This maintains a complete audit trail of
   * task completion history, supports productivity tracking, and enables users
   * to view their completion statistics over time.
   *
   * Task completion using this bulk operation differs from individual
   * completion in that it provides atomic processing for multiple tasks and
   * potentially different feedback mechanisms compared to single-task
   * completion operations. Users may experience different visual feedback or
   * confirmation patterns when completing tasks in bulk versus one-by-one
   * completion operations.
   *
   * The bulk completion operation supports user productivity patterns including
   * end-of-day task reviews, project completion workflows, and organizational
   * task management where multiple items can be addressed simultaneously rather
   * than requiring individual completion operations.
   *
   * @param connection
   * @param body Array of task IDs to be completed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async bulkComplete(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppTaskCompletion.ICreate,
  ): Promise<ITodoAppTaskCompletion.ISummary> {
    try {
      return await patchTodoAppUserTasksBulkComplete({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
