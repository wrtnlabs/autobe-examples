import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getTodoAppUserDashboardUserProgress } from "../../../../../providers/getTodoAppUserDashboardUserProgress";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { ITodoAppTaskCountStatistics } from "../../../../../api/structures/ITodoAppTaskCountStatistics";

@Controller("/todoApp/user/dashboard/user-progress")
export class TodoappUserDashboardUser_progressController {
  /**
   * Get basic dashboard metrics for the authenticated user including simple
   * counts of completed tasks versus total tasks. The operation filters tasks
   * by the current user ID and provides basic statistics that can be computed
   * through straightforward database queries on the todo_app_tasks table.
   *
   * The response includes task completion counts, pending task counts, and
   * total task count derived from existing data in the todo_app_tasks table.
   * These basic metrics support user productivity tracking through simple
   * counting operations that map directly to the available Prisma schema
   * fields.
   *
   * This endpoint provides essential visibility into user task engagement
   * through measurable statistics that align with the current database schema
   * capabilities, focusing on aggregation that requires only basic database
   * filtering and counting operations.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async userProgress(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppTaskCountStatistics> {
    try {
      return await getTodoAppUserDashboardUserProgress({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
