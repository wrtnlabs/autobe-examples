import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUserLimitsUserUserId } from "../../../../../providers/patchTodoAppUserUserLimitsUserUserId";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";

import { IPageITodoAppUserLimit } from "../../../../../api/structures/IPageITodoAppUserLimit";
import { ITodoAppUserLimit } from "../../../../../api/structures/ITodoAppUserLimit";

@Controller("/todoApp/user/userLimits/user/:userId")
export class TodoappUserUserlimitsUserController {
  /**
   * Search and retrieve user-specific limits and quotas with advanced
   * filtering.
   *
   * Retrieve a filtered and paginated list of user-specific limits and quotas
   * for a particular user in the todo application. This operation enables
   * administrators and users to view resource constraints, operational limits,
   * and quota definitions that govern access to system resources.
   *
   * The operation supports sophisticated querying including filtering by limit
   * type (task_count, category_count, bulk_operation_size, api_rate), period
   * type (lifetime, daily, weekly, monthly), and activation status. Results can
   * be sorted by creation date, limit type, or period type and paginated for
   * large result sets.
   *
   * Security considerations ensure that users can only view their own limits
   * while administrators can view limits for any user. The response includes
   * comprehensive limit information including current values, descriptions, and
   * activation status to facilitate account management and resource planning.
   *
   * This operation integrates with the todo_app_user_limits table as defined in
   * the Prisma schema, incorporating all available limit fields and
   * relationships to user accounts and validation rules. The results are
   * optimized for administrative interfaces and user dashboard displays.
   *
   * @param connection
   * @param userId Unique identifier of the user whose limits are being queried
   * @param body Search criteria and pagination parameters for filtering user
   *   limits
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserLimit.IRequest,
  ): Promise<IPageITodoAppUserLimit.ISummary> {
    try {
      return await patchTodoAppUserUserLimitsUserUserId({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
