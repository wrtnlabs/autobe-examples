import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserUsersUserIdSessions } from "../../../../../providers/patchTodoAppUserUsersUserIdSessions";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { getTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/getTodoAppUserUsersUserIdSessionsSessionId";
import { deleteTodoAppUserUsersUserIdSessionsSessionId } from "../../../../../providers/deleteTodoAppUserUsersUserIdSessionsSessionId";

import { IPageITodoAppSession } from "../../../../../api/structures/IPageITodoAppSession";
import { ITodoAppSession } from "../../../../../api/structures/ITodoAppSession";

@Controller("/todoApp/user/users/:userId/sessions")
export class TodoappUserUsersSessionsController {
  /**
   * Retrieve a filtered and paginated list of user sessions with comprehensive
   * search capabilities designed for personal session management and security
   * awareness. This operation enables users to query their own sessions across
   * multiple criteria including device characteristics, authentication context,
   * and temporal ranges.
   *
   * The system supports session management for up to 5 concurrent sessions per
   * user account with detailed tracking including IP geolocation, device
   * fingerprinting, and authentication type differentiation. Sessions
   * automatically expire after 30 days with configurable invalidation support
   * for enhanced security.
   *
   * Users can filter their sessions by device type (web, mobile, tablet, api),
   * session validity status, IP address patterns, and date ranges spanning
   * session creation and expiration times. The system maintains device
   * identification for cross-device management and personal security
   * monitoring.
   *
   * Security considerations include allowing users to review their active
   * sessions for unauthorized access detection, manage device-specific
   * settings, and maintain awareness of their authentication footprint across
   * different platforms and devices. The operation respects user privacy while
   * enabling comprehensive session oversight.
   *
   * @param connection
   * @param userId Unique identifier of the target user whose sessions are being
   *   queried
   * @param body Advanced search criteria for filtering user sessions including
   *   device type, validity status, IP address patterns, and temporal ranges
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppSession.IRequest,
  ): Promise<IPageITodoAppSession.ISummary> {
    try {
      return await patchTodoAppUserUsersUserIdSessions({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Obtain comprehensive session details for personal security management and
   * device oversight. This operation provides detailed access to individual
   * session records within the user's own context for device management and
   * security awareness.
   *
   * The returned session data includes complete device identification
   * information including device type classification, user-friendly device
   * names, and device fingerprinting capabilities. Authentication context
   * covers session type differentiation (standard, mfa, oauth) with
   * corresponding security policy enforcement details for the user's personal
   * session management.
   *
   * Security tracking information includes IP address geolocation data for
   * geographic analysis of login locations, referrer URL tracking for
   * navigation audit trails, and session validity status for access control
   * verification. The system maintains detailed device metadata for
   * cross-device management and personal security monitoring.
   *
   * Users receive complete session context needed for effective device
   * management, including session establishment timestamps, expected expiration
   * times, and device-specific metadata for multi-device management scenarios.
   * The operation ensures proper authorization through personal access controls
   * while maintaining user privacy through appropriate data isolation
   * mechanisms.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns this session
   * @param sessionId Unique identifier of the specific session being retrieved
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppSession> {
    try {
      return await getTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authenticated users to terminate a specific
   * authentication session by permanently deleting the session record from the
   * system. Users can end sessions for devices they no longer use or as part of
   * security best practices to prevent unauthorized access.
   *
   * The operation performs ownership validation to ensure users can only delete
   * their own sessions, preventing session hijacking or unauthorized
   * termination of other users' sessions. Session deletion is permanent and
   * cannot be reversed - once deleted, the session token becomes invalid
   * immediately.
   *
   * Security considerations include rate limiting for session management
   * operations and comprehensive logging of session termination events for
   * audit trails. This operation is essential for multi-device account
   * management and security hygiene.
   *
   * Related operations: Login creates sessions (handled by authentication
   * service), List Sessions shows active sessions, Refresh Token maintains
   * session validity.
   *
   * @param connection
   * @param userId Unique identifier of the user who owns the session being
   *   terminated
   * @param sessionId Unique identifier of the session to be permanently deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":sessionId")
  public async erase(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteTodoAppUserUsersUserIdSessionsSessionId({
        user,
        userId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
