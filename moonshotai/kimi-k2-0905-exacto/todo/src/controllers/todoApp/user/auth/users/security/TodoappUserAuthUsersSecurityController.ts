import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserAuthUsersUserIdSecurity } from "../../../../../../providers/getTodoAppUserAuthUsersUserIdSecurity";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { putTodoAppUserAuthUsersUserIdSecurity } from "../../../../../../providers/putTodoAppUserAuthUsersUserIdSecurity";

import { IPageITodoAppUserSession } from "../../../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUser } from "../../../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/auth/users/:userId/security")
export class TodoappUserAuthUsersSecurityController {
  /**
   * Retrieve user session security information.
   *
   * Retrieve security information for a specific user's session. This operation
   * provides detailed session security data including IP address tracking,
   * connection URL information, referrer data, and session expiration
   * timestamps.
   *
   * The security information is primarily used for administrative oversight,
   * audit trails, and security monitoring. It allows authorized administrators
   * to review session details for security analysis, detect suspicious
   * activity, and maintain audit compliance.
   *
   * Session security data includes connection metadata that can help identify
   * potential security risks such as unusual login patterns, geographic
   * anomalies, or suspicious referrer URLs. The operation respects privacy
   * regulations by ensuring only authorized personnel can access this sensitive
   * session information.
   *
   * This operation queries the todo_app_user_sessions table to provide
   * comprehensive security session details while maintaining appropriate access
   * controls and audit logging for security-sensitive operations.
   *
   * @param connection
   * @param userId Unique identifier of the user whose session security
   *   information is being accessed
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await getTodoAppUserAuthUsersUserIdSecurity({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update user security settings and password.
   *
   * Update security settings for an authenticated user's account. This
   * operation allows users to modify their password and other security-related
   * configurations while ensuring they can only update their own account
   * settings.
   *
   * The operation validates that the requesting user matches the target userId
   * to prevent unauthorized account modifications. Users must be authenticated
   * to access this endpoint, and they can only update security settings for
   * their own account.
   *
   * Security considerations include password strength validation, secure
   * password hashing, and audit logging of security changes. The operation
   * maintains account integrity by preventing cross-user security
   * modifications.
   *
   * This operation integrates with the todo_app_users table as defined in the
   * Prisma schema, updating the password_hash field and potentially other
   * security-related configurations. The response includes confirmation of
   * successful security setting updates.
   *
   * @param connection
   * @param userId Unique identifier of the user whose security settings are
   *   being updated (must match authenticated user)
   * @param body Security update request containing new password and optional
   *   security configurations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updateSecurity(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<void> {
    try {
      return await putTodoAppUserAuthUsersUserIdSecurity({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
