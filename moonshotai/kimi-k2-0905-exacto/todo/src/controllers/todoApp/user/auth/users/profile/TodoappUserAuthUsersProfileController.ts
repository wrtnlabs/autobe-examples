import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getTodoAppUserAuthUsersUserIdProfile } from "../../../../../../providers/getTodoAppUserAuthUsersUserIdProfile";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";
import { putTodoAppUserAuthUsersUserIdProfile } from "../../../../../../providers/putTodoAppUserAuthUsersUserIdProfile";

import { ITodoAppUserProfile } from "../../../../../../api/structures/ITodoAppUserProfile";
import { ITodoAppUser } from "../../../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/auth/users/:userId/profile")
export class TodoappUserAuthUsersProfileController {
  /**
   * Retrieve user profile information for account management.
   *
   * Retrieves comprehensive user profile information for display in account
   * management interfaces. The profile includes essential account details such
   * as email address, account creation date, and last update timestamp from the
   * todo_app_users table. This operation provides users with visibility into
   * their account status and basic account information needed for profile
   * management.
   *
   * The profile data excludes sensitive authentication information like
   * password hashes or session tokens. It focuses on user-managed content and
   * account metadata that users commonly need to view for account verification
   * or management purposes. The operation maintains privacy by only returning
   * profile data for the authenticated user's own account.
   *
   * Response includes the user ID, email address (used for login and
   * notifications), creation timestamp for account age calculation, and last
   * modification timestamp to indicate recent account activity. This
   * information enables users to verify their account details and understand
   * account status without exposing private authentication data.
   *
   * The operation supports user self-service account management by providing
   * necessary information for profile updates, account maintenance, and
   * personal account overview. It serves as the foundation for account settings
   * interfaces and user dashboard functionality.
   *
   * @param connection
   * @param userId Unique identifier of the user whose profile is being
   *   retrieved
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
  ): Promise<ITodoAppUserProfile> {
    try {
      return await getTodoAppUserAuthUsersUserIdProfile({
        user,
        userId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update user profile information for the specified user account. This
   * operation allows users to modify their personal profile data including
   * display name, contact information, and other profile-related fields stored
   * in the user account.
   *
   * The PUT method is used for complete profile replacement, meaning all
   * profile fields should be provided in the request body. Individual field
   * updates can be handled through PATCH operations if supported by the backend
   * implementation.
   *
   * Security considerations include validating that the requesting user has
   * permission to update the target profile. Users can only update their own
   * profiles unless they have administrative privileges. The operation should
   * validate email format, ensure unique email addresses, and apply appropriate
   * business rules for profile data.
   *
   * This operation integrates with the todo_app_users table as defined in the
   * Prisma schema, updating the user's profile information while maintaining
   * data integrity and audit trails through the updated_at timestamp field.
   *
   * @param connection
   * @param userId Unique identifier of the user whose profile is being updated
   * @param body Profile update data including personal information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserAuthUsersUserIdProfile({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
