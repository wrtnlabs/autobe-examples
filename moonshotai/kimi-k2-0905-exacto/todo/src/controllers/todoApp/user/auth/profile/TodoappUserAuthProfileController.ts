import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getTodoAppUserAuthProfile } from "../../../../../providers/getTodoAppUserAuthProfile";
import { UserAuth } from "../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../decorators/payload/UserPayload";
import { putTodoAppUserAuthProfile } from "../../../../../providers/putTodoAppUserAuthProfile";

import { ITodoAppUser } from "../../../../../api/structures/ITodoAppUser";

@Controller("/todoApp/user/auth/profile")
export class TodoappUserAuthProfileController {
  /**
   * Retrieve authenticated user's profile information.
   *
   * Retrieve comprehensive user account information for personal account
   * viewing and management purposes. This operation returns the complete user
   * profile including authentication details, account timestamps, and system
   * metadata for the currently authenticated user.
   *
   * The operation enforces strict authorization to ensure users can only access
   * their own account information. Only the authenticated user can retrieve
   * their account details, implementing a self-service account management model
   * that maintains privacy and security standards.
   *
   * User data includes email address for identification, and account
   * creation/modification timestamps for tracking purposes. The response
   * provides all essential user account properties needed for personal account
   * oversight and profile management scenarios.
   *
   * Security considerations include proper authorization checks through JWT
   * token validation, data sanitization to ensure sensitive information is
   * appropriately handled, and session validation to confirm the requesting
   * user identity. The operation integrates with the JWT authentication system
   * to validate user sessions and access rights.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @UserAuth()
    user: UserPayload,
  ): Promise<ITodoAppUser> {
    try {
      return await getTodoAppUserAuthProfile({
        user,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update authenticated user's profile information.
   *
   * Update user account information with validated input data. This operation
   * enables modification of user profile properties while preserving account
   * security and data integrity through comprehensive validation and
   * authorization checks.
   *
   * The update process supports partial modification, allowing specific fields
   * to be changed without requiring complete profile resubmission. All updates
   * undergo validation to ensure data quality and prevent malformed input from
   * corrupting user accounts. The operation automatically manages update
   * timestamps to track modification history.
   *
   * Authorization verification ensures users can only modify their own account
   * information. Users must be authenticated and the operation validates the
   * JWT token to confirm ownership. This self-service update model maintains
   * privacy by preventing users from modifying other accounts while enabling
   * convenient account management.
   *
   * Data validation includes email format verification, and input sanitization
   * to prevent injection attacks. The operation maintains referential integrity
   * with related entities and ensures cascading updates are handled
   * appropriately.
   *
   * Security measures include audit logging of all account modifications,
   * session validation to prevent unauthorized changes, and data sanitization
   * to protect against malicious input. The operation integrates with the
   * authentication system to handle profile updates appropriately while
   * maintaining account security standards.
   *
   * @param connection
   * @param body Updated user account information with validated fields
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @UserAuth()
    user: UserPayload,
    @TypedBody()
    body: ITodoAppUser.IUpdate,
  ): Promise<ITodoAppUser> {
    try {
      return await putTodoAppUserAuthProfile({
        user,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
