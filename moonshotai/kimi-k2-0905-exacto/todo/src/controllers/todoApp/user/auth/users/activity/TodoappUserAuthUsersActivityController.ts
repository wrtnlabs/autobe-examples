import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchTodoAppUserAuthUsersUserIdActivity } from "../../../../../../providers/patchTodoAppUserAuthUsersUserIdActivity";
import { UserAuth } from "../../../../../../decorators/UserAuth";
import { UserPayload } from "../../../../../../decorators/payload/UserPayload";

import { IPageITodoAppUserSession } from "../../../../../../api/structures/IPageITodoAppUserSession";
import { ITodoAppUserSession } from "../../../../../../api/structures/ITodoAppUserSession";

@Controller("/todoApp/user/auth/users/:userId/activity")
export class TodoappUserAuthUsersActivityController {
  /**
   * Search user activity history and session logs.
   *
   * Search and retrieve user activity history with pagination and filtering
   * capabilities. This operation enables authenticated users to review their
   * login sessions, access patterns, and account activity for security
   * monitoring and audit purposes.
   *
   * The operation provides comprehensive activity tracking including session
   * creation timestamps, IP addresses, referrer information, and session
   * expiration details. Users can filter results by date ranges, session
   * status, and other criteria to focus on specific time periods or activity
   * patterns.
   *
   * Security considerations ensure users can only access their own activity
   * data, preventing unauthorized viewing of other users' session information.
   * The operation maintains privacy by restricting access to the authenticated
   * user's own activity records.
   *
   * This operation integrates with the todo_app_user_sessions table as defined
   * in the Prisma schema, providing historical session data with detailed
   * access information. The response includes paginated session summaries
   * optimized for user review and security analysis.
   *
   * @param connection
   * @param userId Unique identifier of the user whose activity is being
   *   retrieved (must match authenticated user)
   * @param body Activity search criteria including date ranges, session
   *   filters, and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @UserAuth()
    user: UserPayload,
    @TypedParam("userId")
    userId: string & tags.Format<"uuid">,
    @TypedBody()
    body: ITodoAppUserSession.IRequest,
  ): Promise<IPageITodoAppUserSession.ISummary> {
    try {
      return await patchTodoAppUserAuthUsersUserIdActivity({
        user,
        userId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
