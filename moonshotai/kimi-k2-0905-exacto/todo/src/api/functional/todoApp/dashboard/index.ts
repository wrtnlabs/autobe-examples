export async function overview(
  connection: IConnection,
): Promise<overview.Response> {
  return true === connection.simulate
    ? overview.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...overview.METADATA,
          path: overview.path(),
          status: null,
        },
      );
}
export namespace overview {
  export type Response = ITodoAppDashboard.IOverview;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/dashboard/overview",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/dashboard/overview";
  export const random = (): ITodoAppDashboard.IOverview =>
    typia.random<ITodoAppDashboard.IOverview>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
