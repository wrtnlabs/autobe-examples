import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTask } from "../../../../structures/ITodoAppTask";
import { IPageITodoAppTask } from "../../../../structures/IPageITodoAppTask";

/**
 * Search and filter user tasks with comprehensive query capabilities.
 *
 * Perform comprehensive task search and filtering operations across the user's
 * personal task collection. This search operation supports multiple filtering
 * criteria enabling users to locate specific tasks efficiently within their
 * task management workflows.
 *
 * The search system provides powerful filtering capabilities including
 * text-based search across task titles and descriptions, category-based
 * filtering to focus on specific project areas, priority level filtering for
 * urgent task identification, and due date range filtering for deadline
 * management. Users can combine multiple filters simultaneously to create
 * highly specific task searches.
 *
 * Text search functionality supports natural language queries with partial word
 * matching, enabling discovery based on incomplete search terms common in
 * productivity applications. The system highlights matching terms within search
 * results for immediate relevance recognition while maintaining search
 * performance even for users with extensive task collections.
 *
 * The operation provides flexible sorting options including chronological
 * organization by creation date, due date proximity for deadline-focused work,
 * manual ordering for personal preference organization, and priority-based
 * organization for urgency-driven workflows. Sort order preferences are
 * preserved across search sessions and can be adjusted with minimal interaction
 * requirements.
 *
 * Search results are delivered through pagination to maintain performance for
 * large task collections while providing comprehensive result metadata
 * including total result counts, active filter status, and sorting criteria.
 * The system maintains search state across paginated results enabling efficient
 * navigation through filtered task collections.
 *
 * Security considerations include rate limiting for search operations to
 * prevent system abuse while maintaining reasonable access for legitimate
 * productivity workflows. The search functionality respects user data isolation
 * ensuring users can only access their own tasks and related information
 * throughout the search process.
 *
 * @param props.connection
 * @param props.body Search criteria including text queries, filters, sorting
 *   preferences, and pagination parameters
 * @path /todoApp/search/tasks
 * @accessor api.functional.todoApp.search.tasks.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search criteria including text queries, filters, sorting preferences,
     * and pagination parameters
     */
    body: ITodoAppTask.IRequest;
  };
  export type Body = ITodoAppTask.IRequest;
  export type Response = IPageITodoAppTask.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/search/tasks",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/search/tasks";
  export const random = (): IPageITodoAppTask.ISummary =>
    typia.random<IPageITodoAppTask.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
