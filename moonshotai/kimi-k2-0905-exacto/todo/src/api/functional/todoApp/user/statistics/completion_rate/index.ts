export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoAppTaskCompletionRateStatistics;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/statistics/completion-rate",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/statistics/completion-rate";
  export const random = (): ITodoAppTaskCompletionRateStatistics =>
    typia.random<ITodoAppTaskCompletionRateStatistics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
