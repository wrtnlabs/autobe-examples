import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoAppTaskStatistics } from "../../../../../structures/ITodoAppTaskStatistics";

/**
 * Retrieve comprehensive task statistics and analytics for the authenticated
 * user's todo list. This operation provides detailed insights into task
 * management patterns including overall task counts, completion rates, priority
 * distributions, and due date analysis.
 *
 * The statistics include total task count breakdown by status (pending vs
 * completed), priority level distribution across all priority categories (none,
 * low, medium, high), completion rate percentages and trends, overdue task
 * counts and percentages, and task creation/activity patterns over time.
 * Additional metrics include average task completion time, most active task
 * creation periods, and productivity trend analysis.
 *
 * These analytics help users understand their task management habits, identify
 * productivity patterns, and make informed decisions about task prioritization
 * and time management. The data is computed in real-time from the user's
 * current task dataset and provides actionable insights for improving personal
 * productivity and task organization effectiveness.
 *
 * @param props.connection
 * @path /todoApp/user/tasks/statistics
 * @accessor api.functional.todoApp.user.tasks.statistics.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = ITodoAppTaskStatistics;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/tasks/statistics",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/tasks/statistics";
  export const random = (): ITodoAppTaskStatistics =>
    typia.random<ITodoAppTaskStatistics>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
