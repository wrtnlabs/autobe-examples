/**
 * Retrieve user session security information.
 *
 * Retrieve security information for a specific user's session. This operation
 * provides detailed session security data including IP address tracking,
 * connection URL information, referrer data, and session expiration
 * timestamps.
 *
 * The security information is primarily used for administrative oversight,
 * audit trails, and security monitoring. It allows authorized administrators to
 * review session details for security analysis, detect suspicious activity, and
 * maintain audit compliance.
 *
 * Session security data includes connection metadata that can help identify
 * potential security risks such as unusual login patterns, geographic
 * anomalies, or suspicious referrer URLs. The operation respects privacy
 * regulations by ensuring only authorized personnel can access this sensitive
 * session information.
 *
 * This operation queries the todo_app_user_sessions table to provide
 * comprehensive security session details while maintaining appropriate access
 * controls and audit logging for security-sensitive operations.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose session security
 *   information is being accessed
 * @path /todoApp/user/auth/users/:userId/security
 * @accessor api.functional.todoApp.user.auth.users.security.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the user whose session security information is
     * being accessed
     */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = IPageITodoAppUserSession.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/auth/users/:userId/security",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/auth/users/${encodeURIComponent(props.userId ?? "null")}/security`;
  export const random = (): IPageITodoAppUserSession.ISummary =>
    typia.random<IPageITodoAppUserSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

