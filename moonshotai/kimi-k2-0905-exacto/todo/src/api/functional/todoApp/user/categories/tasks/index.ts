/**
 * Search and retrieve tasks within a specific category.
 *
 * Searches and retrieves all tasks associated with a specific category for the
 * authenticated user. This operation provides category-scoped task listing with
 * advanced filtering, sorting, and pagination capabilities specifically
 * designed for organizational task management.
 *
 * Users can filter tasks by multiple criteria including status (pending,
 * in-progress, completed), priority level (Low, Medium, High), due date ranges,
 * and completion status within the specific category context. The operation
 * supports sorting by creation date, priority, due date, completion order, and
 * title to accommodate different organizational preferences.
 *
 * The search functionality includes text search across task titles and
 * descriptions within the category scope, supporting partial word matching and
 * result highlighting. Users can combine multiple filter criteria to create
 * highly specific task views within their organized category structure.
 *
 * Results are returned in paginated format with configurable page sizes and
 * support for continuation tokens where needed. The response includes category
 * information to maintain context and provide complete organizational structure
 * for the returned task collection.
 *
 * This operation is essential for users who organize their work through the
 * category system and need to focus on specific project groups or
 * organizational structures. It provides the detailed task view capabilities
 * needed for effective category-based productivity management.
 *
 * @param props.connection
 * @param props.categoryId Unique identifier of the category containing tasks to
 *   retrieve
 * @param props.body Search criteria and pagination parameters for filtering
 *   tasks within the specified category
 * @path /todoApp/user/categories/:categoryId/tasks
 * @accessor api.functional.todoApp.user.categories.tasks.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the category containing tasks to retrieve */
    categoryId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering tasks within
     * the specified category
     */
    body: ITodoAppTask.IRequest;
  };
  export type Body = ITodoAppTask.IRequest;
  export type Response = IPageITodoAppTask.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/categories/:categoryId/tasks",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/categories/${encodeURIComponent(props.categoryId ?? "null")}/tasks`;
  export const random = (): IPageITodoAppTask.ISummary =>
    typia.random<IPageITodoAppTask.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryId")(() => typia.assert(props.categoryId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
