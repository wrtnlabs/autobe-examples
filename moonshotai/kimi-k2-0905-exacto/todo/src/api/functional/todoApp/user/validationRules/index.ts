/**
 * Search and retrieve validation rules with administrative filtering.
 *
 * Retrieve a filtered and paginated list of validation rules and business
 * constraints governing the todo application. This operation provides
 * administrators with comprehensive access to validation criteria that enforce
 * data quality, format requirements, and business logic constraints throughout
 * the system.
 *
 * The operation supports advanced filtering including searching by rule key,
 * validation type (length, format, range, custom), field target patterns, and
 * activation status. Results can be sorted by priority, creation date, or field
 * target and paginated for administrative interfaces. Administrators can audit
 * validation rules, understand constraint definitions, and manage rule
 * priorities for optimal user experience.
 *
 * Validation rules include format validation for emails and data types, range
 * constraints for numeric fields, length limits for text inputs, and custom
 * business logic validations. The flexible rule system allows for easy updates
 * and additions as business requirements evolve while maintaining consistent
 * error messaging and user feedback.
 *
 * This operation integrates with the todo_app_validation_rules table as defined
 * in the Prisma schema, incorporating all validation rule definitions,
 * constraint specifications, and error message templates. The response is
 * optimized for administrative validation management interfaces and system
 * configuration dashboards.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering
 *   validation rules
 * @path /todoApp/user/validationRules
 * @accessor api.functional.todoApp.user.validationRules.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
