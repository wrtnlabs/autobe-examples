import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUserSession } from "../../../../../../structures/ITodoAppUserSession";
import { IPageITodoAppUserSession } from "../../../../../../structures/IPageITodoAppUserSession";

/**
 * Search user activity history and session logs.
 *
 * Search and retrieve user activity history with pagination and filtering
 * capabilities. This operation enables authenticated users to review their
 * login sessions, access patterns, and account activity for security monitoring
 * and audit purposes.
 *
 * The operation provides comprehensive activity tracking including session
 * creation timestamps, IP addresses, referrer information, and session
 * expiration details. Users can filter results by date ranges, session status,
 * and other criteria to focus on specific time periods or activity patterns.
 *
 * Security considerations ensure users can only access their own activity data,
 * preventing unauthorized viewing of other users' session information. The
 * operation maintains privacy by restricting access to the authenticated user's
 * own activity records.
 *
 * This operation integrates with the todo_app_user_sessions table as defined in
 * the Prisma schema, providing historical session data with detailed access
 * information. The response includes paginated session summaries optimized for
 * user review and security analysis.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose activity is being
 *   retrieved (must match authenticated user)
 * @param props.body Activity search criteria including date ranges, session
 *   filters, and pagination parameters
 * @path /todoApp/user/auth/users/:userId/activity
 * @accessor api.functional.todoApp.user.auth.users.activity.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the user whose activity is being retrieved (must
     * match authenticated user)
     */
    userId: string & tags.Format<"uuid">;

    /**
     * Activity search criteria including date ranges, session filters, and
     * pagination parameters
     */
    body: ITodoAppUserSession.IRequest;
  };
  export type Body = ITodoAppUserSession.IRequest;
  export type Response = IPageITodoAppUserSession.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/auth/users/:userId/activity",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/auth/users/${encodeURIComponent(props.userId ?? "null")}/activity`;
  export const random = (): IPageITodoAppUserSession.ISummary =>
    typia.random<IPageITodoAppUserSession.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
