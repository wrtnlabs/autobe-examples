import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTaskCompletion } from "../../../../../structures/ITodoAppTaskCompletion";

/**
 * Complete multiple tasks simultaneously.
 *
 * This operation enables authenticated users to mark multiple tasks as
 * completed in a single API call, providing an efficient workflow for bulk task
 * management. Users can select tasks from their current todo list and complete
 * them simultaneously, which is particularly useful when finishing related work
 * items or during end-of-day task organization.
 *
 * The operation updates task status in the todo_app_tasks table for all valid
 * tasks while creating completion records in todo_app_task_completions table
 * for each task completion event. This maintains a complete audit trail of task
 * completion history, supports productivity tracking, and enables users to view
 * their completion statistics over time.
 *
 * Task completion using this bulk operation differs from individual completion
 * in that it provides atomic processing for multiple tasks and potentially
 * different feedback mechanisms compared to single-task completion operations.
 * Users may experience different visual feedback or confirmation patterns when
 * completing tasks in bulk versus one-by-one completion operations.
 *
 * The bulk completion operation supports user productivity patterns including
 * end-of-day task reviews, project completion workflows, and organizational
 * task management where multiple items can be addressed simultaneously rather
 * than requiring individual completion operations.
 *
 * @param props.connection
 * @param props.body Array of task IDs to be completed
 * @path /todoApp/user/tasks/bulk-complete
 * @accessor api.functional.todoApp.user.tasks.bulk_complete.bulkComplete
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkComplete(
  connection: IConnection,
  props: bulkComplete.Props,
): Promise<bulkComplete.Response> {
  return true === connection.simulate
    ? bulkComplete.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkComplete.METADATA,
          path: bulkComplete.path(),
          status: null,
        },
        props.body,
      );
}
export namespace bulkComplete {
  export type Props = {
    /** Array of task IDs to be completed */
    body: ITodoAppTaskCompletion.ICreate;
  };
  export type Body = ITodoAppTaskCompletion.ICreate;
  export type Response = ITodoAppTaskCompletion.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/tasks/bulk-complete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/tasks/bulk-complete";
  export const random = (): ITodoAppTaskCompletion.ISummary =>
    typia.random<ITodoAppTaskCompletion.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: bulkComplete.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: bulkComplete.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
