import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppTaskDeletion } from "../../../../../structures/ITodoAppTaskDeletion";

/**
 * Delete multiple tasks simultaneously.
 *
 * This operation enables authenticated users to permanently remove multiple
 * tasks from their todo list in a single API call. Users can select tasks that
 * are no longer relevant, completed and archived, or outdated and remove them
 * simultaneously instead of processing individual deletion operations which
 * would require significant user interaction overhead.
 *
 * The operation performs soft deletion of tasks in the todo_app_tasks table by
 * removing them from active user views rather than permanently deleting records
 * from the database. This approach enables task recovery if users accidentally
 * delete important items while maintaining organizational cleanliness for
 * active task management workflows. Individual task responses can be fully
 * deleted whereas bulk operations provide atomic processing for efficiency
 * without disrupting normal user workflows.
 *
 * Bulk deletion through this operation differs from individual task deletion in
 * processing approach and user experience patterns. Users experience atomic
 * processing where all deletions succeed or fail together rather having
 * individual confirmation dialogs for each task deletion request. This
 * operation is designed for efficiency while maintaining data safety and audit
 * trail requirements.
 *
 * The bulk deletion operation supports user organizational patterns including
 * periodic task list cleanup, outdated item removal, and comprehensive project
 * completion where all related tasks should be eliminated simultaneously rather
 * than requiring individual confirmation cycles that would discourage effective
 * organization and cleanup behaviors.
 *
 * @param props.connection
 * @param props.body Array of task IDs to be deleted
 * @path /todoApp/user/tasks/bulk-delete
 * @accessor api.functional.todoApp.user.tasks.bulk_delete.bulkDelete
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function bulkDelete(
  connection: IConnection,
  props: bulkDelete.Props,
): Promise<bulkDelete.Response> {
  return true === connection.simulate
    ? bulkDelete.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...bulkDelete.METADATA,
          path: bulkDelete.path(),
          status: null,
        },
        props.body,
      );
}
export namespace bulkDelete {
  export type Props = {
    /** Array of task IDs to be deleted */
    body: ITodoAppTaskDeletion.ICreate;
  };
  export type Body = ITodoAppTaskDeletion.ICreate;
  export type Response = ITodoAppTaskDeletion.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/tasks/bulk-delete",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/user/tasks/bulk-delete";
  export const random = (): ITodoAppTaskDeletion.ISummary =>
    typia.random<ITodoAppTaskDeletion.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: bulkDelete.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: bulkDelete.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
