import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppConfiguration } from "../../../../structures/ITodoAppConfiguration";

/**
 * Update a system configuration setting.
 *
 * Update an existing system configuration setting with new values and
 * properties. This operation allows authorized administrators to modify
 * application-wide settings that control system behavior, features, and
 * operational parameters.
 *
 * Configuration updates affect all users across the application and should be
 * performed carefully. The system maintains audit trails through updated_at
 * timestamps and soft deletion capabilities. Only enabled configurations are
 * actively used by the system.
 *
 * The operation validates that the configuration ID exists and that any key
 * changes maintain uniqueness constraints. Updated configurations take effect
 * immediately across all user sessions and system operations.
 *
 * Security considerations require proper authorization to prevent unauthorized
 * system modifications. The operation should be used sparingly as configuration
 * changes can impact overall application behavior and user experience.
 *
 * @param props.connection
 * @param props.configurationId Unique identifier of the configuration setting
 *   to update
 * @param props.body Updated configuration data including new values and
 *   properties
 * @path /todoApp/user/configurations/:configurationId
 * @accessor api.functional.todoApp.user.configurations.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the configuration setting to update */
    configurationId: string & tags.Format<"uuid">;

    /** Updated configuration data including new values and properties */
    body: ITodoAppConfiguration.IUpdate;
  };
  export type Body = ITodoAppConfiguration.IUpdate;
  export type Response = ITodoAppConfiguration;

  export const METADATA = {
    method: "PUT",
    path: "/todoApp/user/configurations/:configurationId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/configurations/${encodeURIComponent(props.configurationId ?? "null")}`;
  export const random = (): ITodoAppConfiguration =>
    typia.random<ITodoAppConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("configurationId")(() =>
        typia.assert(props.configurationId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

