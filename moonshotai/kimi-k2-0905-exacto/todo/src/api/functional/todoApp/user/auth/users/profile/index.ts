/**
 * Retrieve user profile information for account management.
 *
 * Retrieves comprehensive user profile information for display in account
 * management interfaces. The profile includes essential account details such as
 * email address, account creation date, and last update timestamp from the
 * todo_app_users table. This operation provides users with visibility into
 * their account status and basic account information needed for profile
 * management.
 *
 * The profile data excludes sensitive authentication information like password
 * hashes or session tokens. It focuses on user-managed content and account
 * metadata that users commonly need to view for account verification or
 * management purposes. The operation maintains privacy by only returning
 * profile data for the authenticated user's own account.
 *
 * Response includes the user ID, email address (used for login and
 * notifications), creation timestamp for account age calculation, and last
 * modification timestamp to indicate recent account activity. This information
 * enables users to verify their account details and understand account status
 * without exposing private authentication data.
 *
 * The operation supports user self-service account management by providing
 * necessary information for profile updates, account maintenance, and personal
 * account overview. It serves as the foundation for account settings interfaces
 * and user dashboard functionality.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose profile is being
 *   retrieved
 * @path /todoApp/user/auth/users/:userId/profile
 * @accessor api.functional.todoApp.user.auth.users.profile.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the user whose profile is being retrieved */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppUserProfile;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/auth/users/:userId/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/auth/users/${encodeURIComponent(props.userId ?? "null")}/profile`;
  export const random = (): ITodoAppUserProfile =>
    typia.random<ITodoAppUserProfile>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

