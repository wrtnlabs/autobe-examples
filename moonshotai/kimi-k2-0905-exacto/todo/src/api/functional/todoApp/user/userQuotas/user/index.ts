import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoAppUserQuota } from "../../../../../structures/ITodoAppUserQuota";

/**
 * Retrieve detailed quota usage for a specific user.
 *
 * Get comprehensive quota information for a specific user including current
 * usage against limits for tasks, categories, and daily task creation rates.
 * This operation enables monitoring individual user consumption patterns and
 * ensuring fair resource distribution.
 *
 * The response includes both hard limits that prevent further usage when
 * reached, and current status indicators showing how much of each quota has
 * been consumed. Premium user status is also reflected with appropriately
 * adjusted limits based on their subscription tier.
 *
 * This data is crucial for support investigations, usage trend analysis, and
 * ensuring system stability by preventing any single user from consuming
 * excessive resources. The detailed quota view helps identify users who might
 * benefit from premium upgrades or need quota adjustments.
 *
 * Regular users can access their own quota information to understand their
 * current usage and remaining capacity. Administrators can view any user's
 * quota details for monitoring and support purposes.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose quota information is
 *   being retrieved
 * @path /todoApp/user/userQuotas/user/:userId
 * @accessor api.functional.todoApp.user.userQuotas.user.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier of the user whose quota information is being
     * retrieved
     */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoAppUserQuota;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/user/userQuotas/user/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoApp/user/userQuotas/user/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoAppUserQuota =>
    typia.random<ITodoAppUserQuota>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
