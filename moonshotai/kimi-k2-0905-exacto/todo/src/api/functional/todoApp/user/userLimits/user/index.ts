/**
 * Search and retrieve user-specific limits and quotas with advanced filtering.
 *
 * Retrieve a filtered and paginated list of user-specific limits and quotas for
 * a particular user in the todo application. This operation enables
 * administrators and users to view resource constraints, operational limits,
 * and quota definitions that govern access to system resources.
 *
 * The operation supports sophisticated querying including filtering by limit
 * type (task_count, category_count, bulk_operation_size, api_rate), period type
 * (lifetime, daily, weekly, monthly), and activation status. Results can be
 * sorted by creation date, limit type, or period type and paginated for large
 * result sets.
 *
 * Security considerations ensure that users can only view their own limits
 * while administrators can view limits for any user. The response includes
 * comprehensive limit information including current values, descriptions, and
 * activation status to facilitate account management and resource planning.
 *
 * This operation integrates with the todo_app_user_limits table as defined in
 * the Prisma schema, incorporating all available limit fields and relationships
 * to user accounts and validation rules. The results are optimized for
 * administrative interfaces and user dashboard displays.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose limits are being
 *   queried
 * @param props.body Search criteria and pagination parameters for filtering
 *   user limits
 * @path /todoApp/user/userLimits/user/:userId
 * @accessor api.functional.todoApp.user.userLimits.user.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the user whose limits are being queried */
    userId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for filtering user limits */
    body: ITodoAppUserLimit.IRequest;
  };
  export type Body = ITodoAppUserLimit.IRequest;
  export type Response = IPageITodoAppUserLimit.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/todoApp/user/userLimits/user/:userId",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todoApp/user/userLimits/user/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): IPageITodoAppUserLimit.ISummary =>
    typia.random<IPageITodoAppUserLimit.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
