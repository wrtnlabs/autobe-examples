import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoTask } from "../../../structures/ITodoTask";
import { IPageITodoTask } from "../../../structures/IPageITodoTask";

/**
 * Search and filter todo tasks for authenticated user.
 *
 * This operation searches and retrieves todo tasks for the authenticated user
 * from the todo_tasks table. Users can filter by business_status (pending,
 * processing, completed), completion status (completed=true/false), and perform
 * text-based searches through task descriptions using PostgreSQL gin_trgm_ops
 * indexing for efficient partial text matching.
 *
 * The search capability supports multiple criteria including business workflow
 * status management as specified in the requirements. Users can search for
 * tasks containing specific text in the description field, filter by completion
 * status, and organize by business_status workflow stages. The operation
 * maintains pagination through the IPage response pattern to handle potentially
 * large numbers of tasks efficiently.
 *
 * @param props.connection
 * @param props.userId Unique identifier of the user whose tasks to search
 * @param props.body Search criteria including filters for business_status,
 *   completion status, text search, and pagination parameters
 * @path /users/:userId/tasks
 * @accessor api.functional.users.tasks.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the user whose tasks to search */
    userId: string & tags.Format<"uuid">;

    /**
     * Search criteria including filters for business_status, completion
     * status, text search, and pagination parameters
     */
    body: ITodoTask.IRequest;
  };
  export type Body = ITodoTask.IRequest;
  export type Response = IPageITodoTask.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/users/:userId/tasks",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/users/${encodeURIComponent(props.userId ?? "null")}/tasks`;
  export const random = (): IPageITodoTask.ISummary =>
    typia.random<IPageITodoTask.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
