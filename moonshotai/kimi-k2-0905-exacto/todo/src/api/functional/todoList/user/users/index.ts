/**
 * Retrieve a todo list user account (todo_list_users) by ID with privacy
 * enforcement.
 *
 * Retrieve detailed information about a specific todo list user account using
 * the unique user ID (UUID). This endpoint allows an authenticated user to
 * access their own account details, including email and account status fields.
 * The path parameter userId must be the unique identifier for the user in the
 * database.
 *
 * Security and Privacy: This operation enforces strict user isolation and
 * privacy by allowing only the requested user to access their own account.
 * Requests for other users' accounts are strictly disallowed and will result in
 * an authorization error. The implementation must ensure that users cannot
 * enumerate or guess other valid user IDs.
 *
 * The response includes all primary data fields for the user entity, ensuring
 * clients can display and manage personal details in profile or settings
 * screens. Timestamps for account creation and last update are included for
 * informational and auditing purposes. System-managed authentication and
 * auditing details are never exposed here.
 *
 * This API operation directly references the todo_list_users Prisma table and
 * aligns with the schema's privacy requirements. Error handling includes not
 * found (invalid or non-existent userId), forbidden (attempt to access another
 * user's record), and possible locked status, where account management is
 * restricted.
 *
 * @param props.connection
 * @param props.userId UUID of the target user account. Must be the unique
 *   identifier assigned at account creation.
 * @path /todoList/user/users/:userId
 * @accessor api.functional.todoList.user.users.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * UUID of the target user account. Must be the unique identifier
     * assigned at account creation.
     */
    userId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoListUser;

  export const METADATA = {
    method: "GET",
    path: "/todoList/user/users/:userId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todoList/user/users/${encodeURIComponent(props.userId ?? "null")}`;
  export const random = (): ITodoListUser => typia.random<ITodoListUser>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("userId")(() => typia.assert(props.userId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

