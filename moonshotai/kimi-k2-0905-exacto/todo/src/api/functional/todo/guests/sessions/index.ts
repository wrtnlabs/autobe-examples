import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoGuestSession } from "../../../../structures/ITodoGuestSession";

/**
 * Retrieve guest session details.
 *
 * Retrieve details about a specific guest session including connection metadata
 * and session status. This operation enables the system to track temporary
 * guest users who are accessing the application without full registration.
 * Guest sessions are created for demo purposes and allow users to experience
 * basic functionality before committing to registration.
 *
 * The system maintains connection information including IP address, original
 * URL, and referrer for auditing purposes. Sessions have expiration timestamps
 * to ensure temporary access doesn't persist indefinitely. This endpoint is
 * primarily used for session management and audit trails rather than active
 * functionality.
 *
 * Guest sessions provide temporary access to demonstrate the application's
 * value proposition while maintaining security isolation. The operation
 * supports session debugging and monitoring without exposing sensitive user
 * data since guests don't have access to persistent account features.
 *
 * @param props.connection
 * @param props.guestId Unique identifier of the guest user
 * @param props.sessionId Unique identifier of the specific session
 * @path /todo/guests/:guestId/sessions/:sessionId
 * @accessor api.functional.todo.guests.sessions.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the guest user */
    guestId: string & tags.Format<"uuid">;

    /** Unique identifier of the specific session */
    sessionId: string & tags.Format<"uuid">;
  };
  export type Response = ITodoGuestSession;

  export const METADATA = {
    method: "GET",
    path: "/todo/guests/:guestId/sessions/:sessionId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todo/guests/${encodeURIComponent(props.guestId ?? "null")}/sessions/${encodeURIComponent(props.sessionId ?? "null")}`;
  export const random = (): ITodoGuestSession =>
    typia.random<ITodoGuestSession>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("guestId")(() => typia.assert(props.guestId));
      assert.param("sessionId")(() => typia.assert(props.sessionId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
