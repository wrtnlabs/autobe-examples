/**
 * Create a new guest session for demo access.
 *
 * Creates a new guest authentication session that provides temporary access to
 * basic application features for demonstration purposes. The operation
 * generates a new guest record in the todo_guests table with automatic
 * timestamp tracking and unique session identification.
 *
 * Guest sessions enable potential users to explore the application's
 * functionality without registration friction. The system maintains security
 * boundaries by associating guest sessions with specific IP addresses and
 * connection metadata while limiting access to core features.
 *
 * This operation supports the user acquisition funnel by allowing interested
 * users to immediately experience the task management capabilities through a
 * guided demo or limited functionality mode. Guest sessions are automatically
 * managed with appropriate access controls and limitations to maintain system
 * security and performance.
 *
 * @param props.connection
 * @param props.body Guest session creation request
 * @path /todo/guests
 * @accessor api.functional.todo.guests.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Guest session creation request */
    body: ITodoGuest.ICreate;
  };
  export type Body = ITodoGuest.ICreate;
  export type Response = ITodoGuest;

  export const METADATA = {
    method: "POST",
    path: "/todo/guests",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todo/guests";
  export const random = (): ITodoGuest => typia.random<ITodoGuest>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

