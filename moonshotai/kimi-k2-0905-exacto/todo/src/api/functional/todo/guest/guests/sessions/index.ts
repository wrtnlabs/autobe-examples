import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoGuestSession } from "../../../../../structures/ITodoGuestSession";

/**
 * Retrieve or refresh guest session information.
 *
 * Retrieve current active sessions for a guest user or refresh their temporary
 * access token. This operation allows unregistered users to maintain their
 * demonstration session and continue exploring the application's core features
 * without creating an account.
 *
 * The system tracks guest sessions through the todo_guest_sessions table,
 * maintaining connection metadata including IP address, creation timestamp, and
 * expiration. Each session provides temporary access to basic todo
 * functionality while preventing abuse through session expiration and
 * connection tracking.
 *
 * Guest users can only access demonstration features and should be redirected
 * to the registration flow when attempting to perform operations requiring full
 * user authentication. The session management ensures guest users have a
 * consistent experience during their temporary visit while encouraging
 * conversion to registered users for full functionality.
 *
 * Security considerations include automatic session expiration after reasonable
 * time periods, IP address tracking for accountability, and restriction from
 * user-specific operations. The operation should clearly indicate session
 * status and encourage account creation for persistent task management.
 *
 * @param props.connection
 * @param props.guestId Unique identifier of the guest user session
 * @param props.body Session refresh request with optional metadata updates
 * @path /todo/guest/guests/:guestId/sessions
 * @accessor api.functional.todo.guest.guests.sessions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the guest user session */
    guestId: string & tags.Format<"uuid">;

    /** Session refresh request with optional metadata updates */
    body: ITodoGuestSession.IRequest;
  };
  export type Body = ITodoGuestSession.IRequest;
  export type Response = ITodoGuestSession;

  export const METADATA = {
    method: "PATCH",
    path: "/todo/guest/guests/:guestId/sessions",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/todo/guest/guests/${encodeURIComponent(props.guestId ?? "null")}/sessions`;
  export const random = (): ITodoGuestSession =>
    typia.random<ITodoGuestSession>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("guestId")(() => typia.assert(props.guestId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
