/**
 * Create a new configuration setting for the todo application. This endpoint
 * enables administrators to add system-wide configuration parameters that
 * control various aspects of the application behavior.
 *
 * The system supports different configuration types including string, number,
 * boolean, and JSON values, allowing for flexible configuration management.
 * Each configuration entry requires a unique key identifier and can optionally
 * include a description for documentation purposes.
 *
 * Configuration settings marked as system-level cannot be modified by regular
 * users and require elevated permissions. This ensures critical system
 * parameters remain protected from unauthorized changes. The created_at and
 * updated_at timestamps are automatically managed by the system to track
 * configuration changes over time.
 *
 * @param props.connection
 * @param props.body Configuration creation data including key, value, type, and
 *   system flag
 * @path /todo/configurations
 * @accessor api.functional.todo.configurations.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Configuration creation data including key, value, type, and system
     * flag
     */
    body: ITodoConfiguration.ICreate;
  };
  export type Body = ITodoConfiguration.ICreate;
  export type Response = ITodoConfiguration;

  export const METADATA = {
    method: "POST",
    path: "/todo/configurations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todo/configurations";
  export const random = (): ITodoConfiguration =>
    typia.random<ITodoConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

