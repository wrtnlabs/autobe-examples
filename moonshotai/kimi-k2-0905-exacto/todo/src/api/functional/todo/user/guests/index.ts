import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Remove a temporary guest user account.
 *
 * Permanently remove a temporary guest user account and all associated session
 * data. This operation serves administrators by cleaning up temporary access
 * credentials after guests have previewed the application functionality.
 *
 * When a guest user accesses the system temporarily, they create a session that
 * allows exploration of basic features without registration. Once the guest
 * session is no longer needed (either through expiration or active cleanup),
 * this operation properly removes the guest account from the todo_guests table
 * along with any associated session data in the todo_guest_sessions table.
 *
 * The implementation ensures clean resource management by removing temporary
 * data that could accumulate over time. Since guest users don't have persistent
 * task data or personal information, the permanent deletion is appropriate and
 * necessary for data hygiene. The operation uses the hard delete pattern since
 * there are no soft delete fields in the guest tables.
 *
 * Access control ensures only authenticated users with appropriate privileges
 * can perform guest cleanup operations. The operation should verify the guest
 * account exists before attempting deletion and handle the cleanup of related
 * session data through proper database cascade operations.
 *
 * @param props.connection
 * @param props.guestId Unique identifier of the guest user account to be
 *   deleted
 * @path /todo/user/guests/:guestId
 * @accessor api.functional.todo.user.guests.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the guest user account to be deleted */
    guestId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/todo/user/guests/:guestId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todo/user/guests/${encodeURIComponent(props.guestId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("guestId")(() => typia.assert(props.guestId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
