import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoConfiguration } from "../../../../structures/ITodoConfiguration";
import { IPageITodoConfiguration } from "../../../../structures/IPageITodoConfiguration";

/**
 * Retrieve paginated system configuration settings with search and filtering.
 *
 * Search and retrieve paginated list of system configuration settings. This
 * operation enables administrators to query configuration settings with
 * advanced filtering capabilities including configuration type filtering,
 * system-only flag filtering, and text-based search on configuration keys and
 * descriptions.
 *
 * The operation supports comprehensive pagination with configurable page sizes
 * and sorting options, primarily sorted by creation timestamp to show most
 * recent configurations first. Results include both system-generated and
 * user-managed configuration entries.
 *
 * This search operation is designed for administrative oversight of application
 * configuration, allowing technical staff to review configuration settings,
 * identify potential configuration-related issues, and maintain system-wide
 * configuration consistency across the application infrastructure.
 *
 * @param props.connection
 * @param props.body Search criteria including filters for configuration type,
 *   system flag, and pagination parameters
 * @path /todo/user/configuration
 * @accessor api.functional.todo.user.configuration.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria including filters for configuration type, system
     * flag, and pagination parameters
     */
    body: ITodoConfiguration.IRequest;
  };
  export type Body = ITodoConfiguration.IRequest;
  export type Response = IPageITodoConfiguration;

  export const METADATA = {
    method: "PATCH",
    path: "/todo/user/configuration",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todo/user/configuration";
  export const random = (): IPageITodoConfiguration =>
    typia.random<IPageITodoConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve specific configuration setting by ID.
 *
 * Retrieve a specific configuration setting by its unique identifier. This
 * operation provides complete access to individual configuration entries
 * including all associated metadata such as configuration type, whether it's a
 * system-level setting, creation and update timestamps, and any associated
 * description.
 *
 * The operation supports both administrative review of configuration settings
 * and programmatic access for applications that need to inspect specific
 * configuration values. Access is restricted based on whether the configuration
 * is system-level or user-managed, with system configurations requiring
 * appropriate administrative permissions for viewing.
 *
 * Configuration data is essential for application behavior control, allowing
 * dynamic adjustment of system settings without requiring code changes or
 * deployments. Each configuration entry contains the configuration key as a
 * unique identifier, the configuration value, and metadata about the
 * configuration type and scope.
 *
 * @param props.connection
 * @param props.id Unique identifier of the target configuration setting
 * @path /todo/user/configuration/:id
 * @accessor api.functional.todo.user.configuration.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the target configuration setting */
    id: string & tags.Format<"uuid">;
  };
  export type Response = ITodoConfiguration;

  export const METADATA = {
    method: "GET",
    path: "/todo/user/configuration/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todo/user/configuration/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): ITodoConfiguration =>
    typia.random<ITodoConfiguration>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
