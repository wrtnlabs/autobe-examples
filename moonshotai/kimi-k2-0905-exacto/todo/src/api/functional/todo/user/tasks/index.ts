import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoTask } from "../../../../structures/ITodoTask";

/**
 * Get detailed information for a specific task by ID.
 *
 * Retrieves detailed information for a specific task identified by its unique
 * ID. This operation operates on the todo_tasks table from the Prisma schema.
 *
 * The task information includes the task description, current completion status
 * (boolean), business workflow status (pending/processing/completed), creation
 * timestamp, update timestamp, and completion timestamp if the task has been
 * completed. This allows users to view all relevant metadata about a specific
 * task.
 *
 * Access is restricted to the task owner only - users can only retrieve tasks
 * that belong to their account. This ensures data privacy and security by
 * preventing unauthorized access to other users' tasks. The operation validates
 * the task ID exists and belongs to the current user before returning
 * information.
 *
 * The immediate use case is displaying detailed task information to the user,
 * supporting scenarios where users need to review a specific task's details,
 * check its completion status, or monitor when it was last updated. This
 * supports the overall goal of providing clear visibility into task management
 * efforts.
 *
 * @param props.connection
 * @param props.id Unique identifier of the task to retrieve in UUID format
 * @path /todo/user/tasks/:id
 * @accessor api.functional.todo.user.tasks.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the task to retrieve in UUID format */
    id: string & tags.Format<"uuid">;
  };
  export type Response = ITodoTask;

  export const METADATA = {
    method: "GET",
    path: "/todo/user/tasks/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/todo/user/tasks/${encodeURIComponent(props.id ?? "null")}`;
  export const random = (): ITodoTask => typia.random<ITodoTask>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("id")(() => typia.assert(props.id));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

