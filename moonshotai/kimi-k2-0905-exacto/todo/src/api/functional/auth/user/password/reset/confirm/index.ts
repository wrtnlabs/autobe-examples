import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoUser } from "../../../../../../structures/ITodoUser";

/**
 * Complete password reset with new password.
 *
 * Completes password reset process for Todo application users. This endpoint
 * validates the provided reset password token against the stored
 * todo_users.reset_password_token and verifies that reset_password_expires has
 * not passed. Upon successful validation, the operation updates the user's
 * password_hash with the new securely hashed password and clears the reset
 * token fields to prevent reuse. This is the final step in password recovery,
 * allowing users to regain access to their accounts with a new password. The
 * implementation ensures that reset tokens can only be used once and expire
 * after 30 minutes as specified in the requirements, maintaining account
 * security for the task management system.
 *
 * @param props.connection
 * @param props.body New password with reset token confirmation
 * @path /auth/user/password/reset/confirm
 * @accessor api.functional.auth.user.password.reset.confirm.confirmPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function confirmPasswordReset(
  connection: IConnection,
  props: confirmPasswordReset.Props,
): Promise<confirmPasswordReset.Response> {
  return true === connection.simulate
    ? confirmPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...confirmPasswordReset.METADATA,
          path: confirmPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace confirmPasswordReset {
  export type Props = {
    /** New password with reset token confirmation */
    body: ITodoUser.IPasswordResetConfirm;
  };
  export type Body = ITodoUser.IPasswordResetConfirm;
  export type Response = ITodoUser.IPasswordResetConfirmResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset/confirm",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset/confirm";
  export const random = (): ITodoUser.IPasswordResetConfirmResponse =>
    typia.random<ITodoUser.IPasswordResetConfirmResponse>();
  export const simulate = (
    connection: IConnection,
    props: confirmPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: confirmPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
