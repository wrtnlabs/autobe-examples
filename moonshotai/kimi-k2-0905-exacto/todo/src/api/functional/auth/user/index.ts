/**
 * This endpoint creates new user accounts for the Todo List Application. Upon
 * successful registration, the system creates a user record in the
 * todo_app_users table with the provided email address and hashed password. The
 * email field must be unique across all user accounts and follow valid email
 * format validation. The password is securely hashed using bcrypt before
 * storage in the password_hash field.
 *
 * The registration process automatically assigns a status of 'active' to new
 * accounts, allowing immediate access to todo functionality. Users can
 * optionally provide a display name for personalization, stored in the name
 * field. The system generates timestamps for both created_at and updated_at
 * fields, marking the initial account creation time.
 *
 * Security considerations include email uniqueness validation to prevent
 * duplicate accounts, password strength requirements following standard
 * security practices, and immediate issuance of JWT access and refresh tokens
 * upon successful registration. The system supports multi-device authentication
 * from creation, with session management enabling users to access their
 * accounts across multiple devices.
 *
 * The response returns authentication tokens and basic user information,
 * enabling immediate application use without additional verification steps.
 * This streamlined approach reduces barriers to adoption while maintaining
 * security standards through proper credential handling and session
 * management.
 *
 * @param props.connection
 * @param props.body User registration information including email and password
 * @setHeader token.access Authorization
 *
 * @path /auth/user/join
 * @accessor api.functional.auth.user.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** User registration information including email and password */
    body: ITodoAppUser.ICreate;
  };
  export type Body = ITodoAppUser.ICreate;
  export type Response = ITodoAppUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/join";
  export const random = (): ITodoAppUser.IAuthorized =>
    typia.random<ITodoAppUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

