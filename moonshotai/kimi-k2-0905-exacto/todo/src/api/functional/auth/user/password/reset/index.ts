import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { ITodoUser } from "../../../../../structures/ITodoUser";
export * as confirm from "./confirm/index";

/**
 * Request password reset for users.
 *
 * Initiates password reset process for Todo application users. This endpoint
 * processes password reset requests by validating the user's email address
 * against the todo_users table, then generates a unique reset password token
 * and sets the reset_password_expires timestamp to 30 minutes in the future as
 * specified in the requirements. The operation updates the user's record with
 * the secure token that will be used for password recovery verification. This
 * is the first step in the password reset workflow, enabling users who have
 * forgotten their passwords to regain access to their accounts and todo lists.
 * The system implements proper security measures to prevent abuse while
 * ensuring legitimate users can recover access to their task management
 * functionality.
 *
 * @param props.connection
 * @param props.body Email address for password reset request
 * @path /auth/user/password/reset
 * @accessor api.functional.auth.user.password.reset.requestPasswordReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestPasswordReset(
  connection: IConnection,
  props: requestPasswordReset.Props,
): Promise<requestPasswordReset.Response> {
  return true === connection.simulate
    ? requestPasswordReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPasswordReset.METADATA,
          path: requestPasswordReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestPasswordReset {
  export type Props = {
    /** Email address for password reset request */
    body: ITodoUser.IPasswordResetRequest;
  };
  export type Body = ITodoUser.IPasswordResetRequest;
  export type Response = ITodoUser.IPasswordResetResponse;

  export const METADATA = {
    method: "POST",
    path: "/auth/user/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/user/password/reset";
  export const random = (): ITodoUser.IPasswordResetResponse =>
    typia.random<ITodoUser.IPasswordResetResponse>();
  export const simulate = (
    connection: IConnection,
    props: requestPasswordReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestPasswordReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
