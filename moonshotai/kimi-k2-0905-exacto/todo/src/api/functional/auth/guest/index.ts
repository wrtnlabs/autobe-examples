import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { ITodoGuest } from "../../../structures/ITodoGuest";

/**
 * Create temporary guest access token for preview functionality.
 *
 * Create temporary guest access for unauthenticated visitors to preview basic
 * functionality without requiring registration. This operation generates a
 * guest token that provides limited read-only access and demonstrates the
 * service's value proposition before account creation.
 *
 * The guest access enables potential customers to experience the minimal todo
 * functionality without friction, understanding how the service works through
 * actual interaction rather than descriptions. The temporary nature encourages
 * registration when users find value in the demonstration.
 *
 * This operation corresponds to the todo_guests table management where
 * temporary guest accounts are created and tracked. Related operations include
 * join (this operation) and refresh for maintaining temporary access sessions
 * as implemented by todo_guest_sessions table tracking.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(connection: IConnection): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Response = ITodoGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): ITodoGuest.IAuthorized =>
    typia.random<ITodoGuest.IAuthorized>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Refresh guest access token to extend preview session.
 *
 * Refresh temporary guest access tokens to extend session duration for preview
 * functionality. This operation enables guest users to continue exploring the
 * service without creating an account, maintaining their demonstration session
 * as long as needed.
 *
 * The refresh mechanism ensures guest users don't lose their preview session
 * before deciding whether to register for full functionality. It demonstrates
 * the service's reliability and user-friendly approach even for temporary
 * access. The operation validates current guest session validity before issuing
 * new tokens.
 *
 * This operation corresponds to session management in todo_guest_sessions
 * table, extending expired_at timestamps for continued temporary access. It
 * works in conjunction with the join operation to provide complete temporary
 * session lifecycle management for unauthenticated visitors.
 *
 * @param props.connection
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/refresh
 * @accessor api.functional.auth.guest.refresh
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
