import { ITodoAppGuest } from "../../../structures/ITodoAppGuest";

/**
 * Guest registration for todo application with temporary session creation.
 *
 * Guest registration creates temporary guest accounts that enable prospective
 * users to experience core functionality through demonstration content and
 * basic feature exploration while maintaining clear differentiation from full
 * registered user experiences. This operation generates unique session
 * identifiers for guest session tracking and upgrade tracking when guests
 * transition to registered users.
 *
 * The guest account creation process uses session management patterns that
 * support seamless upgrade pathways when guests decide to register,
 * facilitating data preservation and account conversion workflows. Guest
 * sessions have controlled expiration to prevent indefinite usage and maintain
 * resource management.
 *
 * The implementation validates session identifier uniqueness and creates
 * appropriate database records in todo_app_guests with proper timestamp
 * management for creation and expiration tracking. This operation is essential
 * for providing immediate application access to visitors while maintaining
 * security through temporary session management.
 *
 * Guest registration provides a frictionless entry point for users to explore
 * todo application capabilities before committing to full account creation. The
 * system tracks guest engagement through session identifiers and maintains
 * audit trails for potential conversion tracking while providing adequate
 * functionality demonstration.
 *
 * @param props.connection
 * @param props.body Guest registration request containing basic session
 *   information for temporary account creation
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Guest registration request containing basic session information for
     * temporary account creation
     */
    body: ITodoAppGuest.ICreate;
  };
  export type Body = ITodoAppGuest.ICreate;
  export type Response = ITodoAppGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): ITodoAppGuest.IAuthorized =>
    typia.random<ITodoAppGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

