export type ITodoAppUser = {
  /**
   * Primary key in UUID format serving as the unique identifier for user
   * accounts across the todo application.
   *
   * This identifier is used across all user-related operations,
   * authentication flows, task associations, category organization, and
   * system-wide references to maintain data integrity and enable efficient
   * cross-table relationships within the database schema.
   */
  id: string & tags.Format<"uuid">;

  /**
   * User email address used for account authentication and communication.
   * Must be unique across all registered users and follow standard email
   * format validation.
   *
   * Serves as the primary login credential alongside the password hash,
   * enables notification delivery, password reset workflows, and provides
   * user identity verification through email validation processes.
   */
  email: string & tags.Format<"email">;

  /**
   * Timestamp when user account was created, recorded automatically during
   * registration process for audit trail and account management purposes.
   */
  created_at: string & tags.Format<"date-time">;

  /**
   * Timestamp of last user account modification, updated automatically when
   * profile information changes for change tracking and audit purposes.
   */
  updated_at?: (string & tags.Format<"date-time">) | undefined;

  /**
   * Soft delete timestamp for account deactivation. When set, indicates
   * account is inactive and user cannot authenticate, but data is preserved
   * for recovery or compliance purposes.
   *
   * This field supports the soft delete pattern where account data is
   * preserved for audit trails, recovery scenarios, and compliance
   * requirements while maintaining data integrity and system performance
   * optimization.
   */
  deleted_at?: (string & tags.Format<"date-time">) | undefined;
};
