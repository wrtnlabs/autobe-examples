import { tags } from "typia";

import { IEconomicDiscussionMember } from "./IEconomicDiscussionMember";
import { IEconomicDiscussionSearchQuery } from "./IEconomicDiscussionSearchQuery";

/**
 * Personal search history entry for logged-in members tracking individual
 * search queries.
 *
 * Represents a single search performed by a community member, storing the
 * actual query text and execution timestamp for personalized history retention.
 * This enables users to review their previous searches and quickly return to
 * previously accessed content.
 *
 * Each history entry maintains associations with the member who performed the
 * search and the master search query for analytics tracking. The system
 * automatically creates these entries when members perform searches through the
 * platform's interface.
 *
 * Links to member via economic_discussion_member_id foreign key. Links to
 * master search query via economic_discussion_search_query_id foreign key.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IEconomicDiscussionSearchHistory = {
  /** Primary key for this search history entry. */
  id: string & tags.Format<"uuid">;

  /**
   * Foreign key reference to the member who performed this search. Links to
   * economic_discussion_members.id
   */
  economic_discussion_member_id: string & tags.Format<"uuid">;

  /**
   * Foreign key reference to the master search query. Links to
   * economic_discussion_search_queries.id for analytics tracking
   */
  economic_discussion_search_query_id: string & tags.Format<"uuid">;

  /** Actual search query text entered by the user. */
  query_text: string &
    tags.JsonSchemaPlugin<{
      "x-autobe-prisma-field": "query_text";
    }>;

  /** When this search was performed. */
  created_at: string &
    tags.Format<"date-time"> &
    tags.JsonSchemaPlugin<{
      "x-autobe-prisma-field": "created_at";
    }>;

  /**
   * Associated community member who performed this search query. Provides
   * complete member information including username, email verification
   * status, and reputation score for full user context.
   */
  member?: IEconomicDiscussionMember.ISummary | undefined;

  /**
   * Reference to the master search query entity for analytics and
   * optimization. Provides comprehensive query analytics including frequency
   * tracking, result counts, and click-through performance metrics.
   */
  searchQuery?: IEconomicDiscussionSearchQuery.ISummary | undefined;
};
