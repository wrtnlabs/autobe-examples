import { tags } from "typia";

import { IPoliticsBbsArticle } from "./IPoliticsBbsArticle";
import { IPoliticsBbsMember } from "./IPoliticsBbsMember";
import { IPoliticsBbsImageAttachment } from "./IPoliticsBbsImageAttachment";
import { IPoliticsBbsAttachmentOfVisitor } from "./IPoliticsBbsAttachmentOfVisitor";
import { IPoliticsBbsAttachmentOfMember } from "./IPoliticsBbsAttachmentOfMember";
