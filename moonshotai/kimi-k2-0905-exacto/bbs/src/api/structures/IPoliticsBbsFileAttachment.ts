/**
 * Document file attachments for articles supporting up to 10MB per file and 5
 * files per article. Manages document uploads with format validation for PDF,
 * DOC, DOCX, and TXT formats. The schema enforces that all file attachments
 * must have a member creator, but this creates an inconsistency with the
 * polymorphic attachment ownership pattern that also supports visitor and
 * moderator uploads through separate association tables.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type IPoliticsBbsFileAttachment = {
  /** Primary key. Unique identifier for the file attachment. */
  id: string & tags.Format<"uuid">;

  /** Attached article's ID referencing the politics_bbs_articles table. */
  politics_bbs_article_id: string & tags.Format<"uuid">;

  /**
   * Uploading member's ID referencing the politics_bbs_members table. This
   * field is required as per the database schema but represents a design flaw
   * since visitors can also upload files through the polymorphic attachment
   * system. The schema should support nullable member_id to accommodate
   * visitor uploads, or use a different ownership pattern.
   */
  politics_bbs_member_id: string & tags.Format<"uuid">;

  /** Original filename of the uploaded document. */
  filename: string;

  /** Size of the document file in bytes. Maximum 10MB allowed. */
  file_size: number & tags.Type<"int32">;

  /**
   * MIME type of the document (application/pdf, application/msword,
   * application/vnd.openxmlformats-officedocument.wordprocessingml.document,
   * text/plain).
   */
  mime_type: string;

  /** Storage path or URL reference to the document file. */
  file_path: string;

  /** Timestamp when the file was uploaded. */
  created_at: string & tags.Format<"date-time">;

  /** Relationship to the article this file attachment belongs to. */
  article?: IPoliticsBbsArticle | undefined;

  /** Relationship to the member who uploaded this file. */
  member?: IPoliticsBbsMember | undefined;

  /**
   * Image attachments that are part of this file attachment (for composite
   * uploads).
   */
  image_attachments?: IPoliticsBbsImageAttachment[] | undefined;

  /**
   * Visitor-specific attachment relationship if this file was uploaded by a
   * visitor.
   */
  visitor_attachment?: IPoliticsBbsAttachmentOfVisitor | undefined;

  /**
   * Member-specific attachment relationship if this file was uploaded by a
   * member.
   */
  member_attachment?: IPoliticsBbsAttachmentOfMember | undefined;

  /**
   * Moderator-specific attachment relationship if this file was uploaded by a
   * moderator.
   */
  moderator_attachment?: IPoliticsBbsAttachmentOfModerator | undefined;
};
