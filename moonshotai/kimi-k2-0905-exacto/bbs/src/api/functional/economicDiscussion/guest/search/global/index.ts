import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionSearch } from "../../../../../structures/IEconomicDiscussionSearch";
import { IPageIEconomicDiscussionSearchQuery } from "../../../../../structures/IPageIEconomicDiscussionSearchQuery";

/**
 * Perform global search across all content types.
 *
 * Search across all economic and political discussion content including
 * articles, categories, and related metadata. This operation provides a unified
 * search experience that helps users discover relevant discussions and topics
 * across the entire platform.
 *
 * The search functionality uses intelligent matching algorithms to find
 * relevant content based on query terms. It searches through article titles,
 * categories, and descriptions, with results ranked by relevance. The system
 * supports complex queries and provides comprehensive result sets with proper
 * pagination.
 *
 * This is a powerful discovery tool that helps users navigate the extensive
 * content library. It integrates with the search history tracking system to
 * provide personalized search experiences and maintain search context.
 *
 * Advanced features include relevance-based ranking, partial text matching, and
 * efficient pagination. The operation returns a comprehensive set of search
 * results with metadata for easy content discovery.
 *
 * @param props.connection
 * @param props.body Search query parameters including search terms, filters,
 *   and pagination settings
 * @path /economicDiscussion/guest/search/global
 * @accessor api.functional.economicDiscussion.guest.search.global.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search query parameters including search terms, filters, and
     * pagination settings
     */
    body: IEconomicDiscussionSearch.IRequest;
  };
  export type Body = IEconomicDiscussionSearch.IRequest;
  export type Response = IPageIEconomicDiscussionSearchQuery.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/guest/search/global",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/guest/search/global";
  export const random = (): IPageIEconomicDiscussionSearchQuery.ISummary =>
    typia.random<IPageIEconomicDiscussionSearchQuery.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
