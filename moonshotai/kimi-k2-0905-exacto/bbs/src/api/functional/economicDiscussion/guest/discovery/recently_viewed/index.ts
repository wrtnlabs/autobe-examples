/**
 * This operation returns articles that the current user has recently viewed on
 * the economic discussion board platform. It provides personalized content
 * discovery based on the user's recent browsing activity, helping them quickly
 * return to previously viewed economic and political discussion articles.
 *
 * The operation supports pagination to handle long viewing histories and uses
 * PATCH method to allow for complex query parameters including filtering by
 * date ranges, limiting results, and sorting preferences. Recent articles are
 * sorted by viewing timestamp in descending order, with most recently viewed
 * articles appearing first.
 *
 * For authenticated members, the system tracks viewing history across sessions
 * for persistent recommendations. For guest users, recently viewed articles are
 * limited to the current guest session and expire when the session ends.
 *
 * The operation filters out articles that have been deleted or are no longer
 * accessible due to moderation. It also considers privacy settings and content
 * visibility rules to ensure appropriate content is returned based on the
 * user's authorization level and community guidelines.
 *
 * @param props.connection
 * @param props.body Query parameters for filtering recently viewed articles
 *   including date ranges, limits, and sorting preferences
 * @path /economicDiscussion/guest/discovery/recently-viewed
 * @accessor api.functional.economicDiscussion.guest.discovery.recently_viewed.recentlyViewed
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function recentlyViewed(
  connection: IConnection,
  props: recentlyViewed.Props,
): Promise<recentlyViewed.Response> {
  return true === connection.simulate
    ? recentlyViewed.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...recentlyViewed.METADATA,
          path: recentlyViewed.path(),
          status: null,
        },
        props.body,
      );
}
export namespace recentlyViewed {
  export type Props = {
    /**
     * Query parameters for filtering recently viewed articles including
     * date ranges, limits, and sorting preferences
     */
    body: IEconomicDiscussionRecentlyViewed.IRequest;
  };
  export type Body = IEconomicDiscussionRecentlyViewed.IRequest;
  export type Response = IPageIEconomicDiscussionArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/guest/discovery/recently-viewed",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/economicDiscussion/guest/discovery/recently-viewed";
  export const random = (): IPageIEconomicDiscussionArticle.ISummary =>
    typia.random<IPageIEconomicDiscussionArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: recentlyViewed.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: recentlyViewed.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
