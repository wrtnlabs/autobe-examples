import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconomicDiscussionTrendingList } from "../../../structures/IEconomicDiscussionTrendingList";
export * as popular_tags from "./popular_tags/index";
export * as recently_viewed from "./recently_viewed/index";

/**
 * Retrieve trending economic and political discussions.
 *
 * Retrieves a list of trending articles based on recent community activity and
 * engagement metrics. The trending discovery endpoint analyzes articles from
 * the past 24 hours to identify the most actively discussed economic and
 * political topics.
 *
 * The system evaluates multiple engagement factors including view counts,
 * comment activity, and interaction patterns to rank articles by trending
 * status. This provides users with a dynamic way to discover the most relevant
 * and active discussions in the community.
 *
 * Results are refreshed automatically every 2 hours to ensure content remains
 * current and reflective of recent community interests. The trending list
 * typically features a mix of breaking economic news, policy developments, and
 * political analysis that are generating significant community participation.
 *
 * @param props.connection
 * @path /economicDiscussion/discovery/trending
 * @accessor api.functional.economicDiscussion.discovery.trending
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function trending(
  connection: IConnection,
): Promise<trending.Response> {
  return true === connection.simulate
    ? trending.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...trending.METADATA,
          path: trending.path(),
          status: null,
        },
      );
}
export namespace trending {
  export type Response = IEconomicDiscussionTrendingList;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/discovery/trending",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/discovery/trending";
  export const random = (): IEconomicDiscussionTrendingList =>
    typia.random<IEconomicDiscussionTrendingList>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
