import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconomicDiscussionPopularTags } from "../../../../structures/IEconomicDiscussionPopularTags";

/**
 * This operation returns a collection of the most popular tags used in economic
 * and political discussion articles. Popular tags are determined by frequency
 * of usage across published articles, providing users with insights into
 * trending economic topics and political discourse themes.
 *
 * The tag popularity calculation considers the total number of articles
 * associated with each tag, excluding articles that are pending approval or
 * have been soft-deleted. Tags are ranked by usage count and returned in
 * descending order of popularity.
 *
 * This operation supports content discovery by helping users identify which
 * economic and political topics are currently most discussed in the community.
 * Popular tags can be used for navigation, filtering, and discovering related
 * content on the platform.
 *
 * The response includes tag identifiers, names, and usage statistics to provide
 * context about each tag's popularity within the discussion board community.
 *
 * @param props.connection
 * @path /economicDiscussion/discovery/popular-tags
 * @accessor api.functional.economicDiscussion.discovery.popular_tags.popularTags
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function popularTags(
  connection: IConnection,
): Promise<popularTags.Response> {
  return true === connection.simulate
    ? popularTags.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...popularTags.METADATA,
          path: popularTags.path(),
          status: null,
        },
      );
}
export namespace popularTags {
  export type Response = IEconomicDiscussionPopularTags;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/discovery/popular-tags",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/discovery/popular-tags";
  export const random = (): IEconomicDiscussionPopularTags =>
    typia.random<IEconomicDiscussionPopularTags>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
