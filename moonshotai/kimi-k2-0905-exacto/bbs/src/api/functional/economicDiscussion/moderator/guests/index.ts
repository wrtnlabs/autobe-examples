import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionGuest } from "../../../../structures/IEconomicDiscussionGuest";
export * as sessions from "./sessions/index";

/**
 * Retrieve detailed information about a specific guest user session in the
 * Economic Discussion Board platform. This operation provides comprehensive
 * access to guest user data stored in the economic_discussion_guests table,
 * including session identifiers, browsing history, download activities, and
 * activity timestamps.
 *
 * Guest users represent anonymous visitors to the discussion board who can
 * browse and read content without registration. Their access is tracked through
 * session management, allowing administrators to monitor platform usage,
 * understand visitor engagement patterns, and ensure appropriate resource
 * allocation for unregistered users.
 *
 * The data returned includes the guest's temporary username assignment, IP
 * address for session identification, browser user agent string when available,
 * creation and last activity timestamps, and usage counters for articles viewed
 * and downloads performed during the session lifetime. This information enables
 * administrators to analyze visitor behavior, identify potential issues with
 * guest access, and optimize the platform experience for all users.
 *
 * Security considerations include authorization verification to ensure only
 * legitimate moderators can access guest user information, appropriate handling
 * of sensitive data such as IP addresses in compliance with privacy
 * regulations, and consideration of whether this operation should be exposed
 * through public APIs or reserved for internal administrative systems.
 *
 * @param props.connection
 * @param props.guestId Unique identifier of the guest user session
 * @path /economicDiscussion/moderator/guests/:guestId
 * @accessor api.functional.economicDiscussion.moderator.guests.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the guest user session */
    guestId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicDiscussionGuest;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/moderator/guests/:guestId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicDiscussion/moderator/guests/${encodeURIComponent(props.guestId ?? "null")}`;
  export const random = (): IEconomicDiscussionGuest =>
    typia.random<IEconomicDiscussionGuest>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("guestId")(() => typia.assert(props.guestId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
