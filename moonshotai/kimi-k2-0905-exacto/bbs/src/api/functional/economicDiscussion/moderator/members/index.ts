/**
 * Search and retrieve filtered lists of Economic Discussion community members
 * with support for complex search criteria, sorting, and pagination. This
 * operation enables administrators and moderators to discover members based on
 * various criteria including registration date ranges, email verification
 * status, usernames, reputation scores, and activity patterns.
 *
 * The operation provides comprehensive member discovery capabilities essential
 * for community management tasks such as identifying active contributors,
 * finding members for moderation review, analyzing registration trends, and
 * managing user support workflows. Results are optimized for administrative
 * interfaces with member summaries rather than detailed profiles.
 *
 * Advanced filtering includes exact username matching, email domain filtering,
 * reputation score ranges, and activity-based searches. The paginated response
 * format supports efficient browsing of large member bases with customizable
 * page sizes and sorting preferences.
 *
 * @param props.connection
 * @param props.body Member search criteria including filters, sorting
 *   preferences, and pagination parameters
 * @path /economicDiscussion/moderator/members
 * @accessor api.functional.economicDiscussion.moderator.members.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Member search criteria including filters, sorting preferences, and
     * pagination parameters
     */
    body: IEconomicDiscussionMember.IRequest;
  };
  export type Body = IEconomicDiscussionMember.IRequest;
  export type Response = IPageIEconomicDiscussionMember.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/moderator/members",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/moderator/members";
  export const random = (): IPageIEconomicDiscussionMember.ISummary =>
    typia.random<IPageIEconomicDiscussionMember.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

