import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionComment } from "../../../../../structures/IEconomicDiscussionComment";

/**
 * Delete a comment from an economic discussion article.
 *
 * This operation enables deletion of comments from economic and political
 * discussion articles on the platform. Members can delete their own comments to
 * remove content they no longer wish to share, while moderators have broader
 * permissions to remove any content that violates community guidelines.
 *
 * The system implements soft deletion to maintain referential integrity and
 * preserve the discussion thread structure. Deleted comments remain in the
 * database with a deleted flag but are hidden from user views. This approach
 * preserves the conversation flow and prevents broken references in nested
 * comment discussions.
 *
 * The operation requires both article ID and comment ID parameters to ensure
 * the comment being removed belongs to the specified article. Authentication is
 * required to verify comment ownership for regular members and moderator
 * privileges for administrative actions.
 *
 * Content moderation benefits from this traceable deletion system, allowing
 * moderators to review deletion patterns and maintain discussion quality. The
 * soft-delete approach also enables potential restoration of inappropriately
 * removed content.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the economic discussion article
 *   containing the comment to delete
 * @param props.commentId Unique identifier of the specific comment to be
 *   deleted
 * @path /economicDiscussion/moderator/articles/:articleId/comments/:commentId
 * @accessor api.functional.economicDiscussion.moderator.articles.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique identifier of the economic discussion article containing the
     * comment to delete
     */
    articleId: string & tags.Format<"uuid">;

    /** Unique identifier of the specific comment to be deleted */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicDiscussionComment;

  export const METADATA = {
    method: "DELETE",
    path: "/economicDiscussion/moderator/articles/:articleId/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicDiscussion/moderator/articles/${encodeURIComponent(props.articleId ?? "null")}/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IEconomicDiscussionComment =>
    typia.random<IEconomicDiscussionComment>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
