/**
 * Search and retrieve filtered, paginated list of economic discussion articles.
 *
 * Retrieve a filtered and paginated list of economic discussion articles with
 * advanced search capabilities. This operation enables comprehensive filtering
 * across article titles, content, author information, categories, publication
 * status, and engagement metrics like view counts.
 *
 * The search functionality supports full-text search across article titles and
 * content using PostgreSQL's GIN indexes for optimal performance. Users can
 * combine multiple filter criteria including category selection, status
 * filtering, date range queries, and author-based filtering to find relevant
 * economic and political discussions.
 *
 * The operation provides comprehensive pagination with configurable page sizes
 * and sorting options. Articles can be sorted by creation date, view count,
 * title, or other relevant fields in ascending or descending order. The
 * response includes complete article information with author details,
 * attachment counts, and category assignments optimized for list displays.
 *
 * Security considerations include appropriate filtering of content based on
 * publication status and user permissions. Public users can only search
 * approved articles, while authenticated users may have access to additional
 * content based on their roles. The system implements rate limiting for search
 * operations to prevent abuse and maintain performance during high-traffic
 * periods.
 *
 * This search operation integrates with the economic_discussion_articles table
 * and related entities including categories, attachments, and user accounts.
 * The results are formatted for optimal display in article listing interfaces
 * with essential metadata for quick scanning and selection.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering parameters, and pagination
 *   options for article discovery
 * @path /economicDiscussion/search/articles
 * @accessor api.functional.economicDiscussion.search.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering parameters, and pagination options for
     * article discovery
     */
    body: IEconomicDiscussionArticle.IRequest;
  };
  export type Body = IEconomicDiscussionArticle.IRequest;
  export type Response = IPageIEconomicDiscussionArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/search/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/search/articles";
  export const random = (): IPageIEconomicDiscussionArticle.ISummary =>
    typia.random<IPageIEconomicDiscussionArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
