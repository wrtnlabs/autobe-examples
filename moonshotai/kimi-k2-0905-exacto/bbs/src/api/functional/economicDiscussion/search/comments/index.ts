import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionComment } from "../../../../structures/IEconomicDiscussionComment";
import { IPageIEconomicDiscussionComment } from "../../../../structures/IPageIEconomicDiscussionComment";

/**
 * Retrieve a filtered and paginated list of comments posted on economic
 * discussion articles. This operation enables comprehensive filtering across
 * comment content, associated articles, comment authors, moderation status, and
 * temporal ranges for both community members and content moderators.
 *
 * The search functionality supports full-text search across comment content
 * using PostgreSQL's text indexing capabilities. Users can filter comments by
 * specific articles, authors, moderation status (pending, approved, rejected),
 * and time periods. Advanced filtering includes nested comment relationships,
 * allowing search within specific discussion threads.
 *
 * The operation provides comprehensive pagination with configurable page sizes
 * suitable for content moderation workflows. Comments can be sorted by creation
 * date, relevance to search terms, or moderation status based on the user's
 * purpose. The response includes complete comment information with author
 * details, thread context, and moderation information.
 *
 * For moderators, this search interface supports content moderation workflows
 * by allowing filtering of pending comments, identifying potentially
 * problematic content, and reviewing flagged discussions. The system provides
 * efficient processing of large comment volumes while maintaining performance
 * standards.
 *
 * Security considerations include appropriate access control based on user
 * roles and moderation privileges. Public users can search approved comments,
 * while authenticated users may access additional content based on their
 * permissions. The system implements protections against automated searching
 * while enabling legitimate community management activities.
 *
 * This search operation integrates with the economic_discussion_comments table
 * and related entities including articles, members, and moderation workflows.
 * The results are formatted to support both community browsing and
 * administrative oversight functions.
 *
 * @param props.connection
 * @param props.body Search criteria, filtering parameters, and pagination
 *   options for comment discovery
 * @path /economicDiscussion/search/comments
 * @accessor api.functional.economicDiscussion.search.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria, filtering parameters, and pagination options for
     * comment discovery
     */
    body: IEconomicDiscussionComment.IRequest;
  };
  export type Body = IEconomicDiscussionComment.IRequest;
  export type Response = IPageIEconomicDiscussionComment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/search/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/search/comments";
  export const random = (): IPageIEconomicDiscussionComment.ISummary =>
    typia.random<IPageIEconomicDiscussionComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
