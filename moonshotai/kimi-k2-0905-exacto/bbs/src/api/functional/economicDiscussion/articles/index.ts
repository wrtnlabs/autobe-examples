/**
 * Search and retrieve economic discussion articles with advanced filtering and
 * pagination capabilities. This operation enables users to discover relevant
 * economic and political discussion content through comprehensive search
 * mechanisms.
 *
 * The search functionality supports content filtering by status, categories,
 * authors, and date ranges. Users can filter by multiple categories
 * simultaneously and search within specific author scopes. Status filtering
 * enables finding articles in different workflow states including pending,
 * approved, and rejected content.
 *
 * Pagination is implemented with configurable page sizes and offset-based
 * navigation. Results can be sorted by creation date, view count, title, and
 * other relevant criteria. Each article summary includes essential information
 * for content discovery including title, author details, category assignments,
 * view statistics, and current status.
 *
 * This operation serves as the primary content discovery mechanism for the
 * economic discussion platform, supporting both casual browsing and targeted
 * research for economic analysis.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for article
 *   discovery
 * @path /economicDiscussion/articles
 * @accessor api.functional.economicDiscussion.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for article discovery */
    body: IEconomicDiscussionArticle.IRequest;
  };
  export type Body = IEconomicDiscussionArticle.IRequest;
  export type Response = IPageIEconomicDiscussionArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/articles";
  export const random = (): IPageIEconomicDiscussionArticle.ISummary =>
    typia.random<IPageIEconomicDiscussionArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Retrieve complete information for a specific economic discussion article by
 * its unique identifier. This operation provides the full article content along
 * with all associated metadata including author details, categorization, file
 * attachments, and engagement metrics like view counts.
 *
 * The response includes the article's current status (pending, approved, or
 * rejected) which determines visibility permissions. Only approved articles are
 * publicly accessible by default, while pending or rejected articles require
 * appropriate authorization levels.
 *
 * File attachments are included with their metadata (filename, file type, size)
 * and security scanning status. The system automatically filters out
 * attachments that haven't completed security scanning or have been flagged as
 * potentially unsafe.
 *
 * This operation increments the article's view count to track engagement and
 * popularity. View counts are updated in real-time and help surface popular
 * content in recommendation algorithms.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the economic discussion article
 *   to retrieve
 * @path /economicDiscussion/articles/:articleId
 * @accessor api.functional.economicDiscussion.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the economic discussion article to retrieve */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicDiscussionArticle;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/articles/:articleId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicDiscussion/articles/${encodeURIComponent(props.articleId ?? "null")}`;
  export const random = (): IEconomicDiscussionArticle =>
    typia.random<IEconomicDiscussionArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
