/**
 * Get a comprehensive list of all comments posted on a specific economic and
 * political discussion article. This operation provides read-only access to the
 * article's discussion thread, returning comment content, author information,
 * and discussion timestamps.
 *
 * The operation returns comment data in a format optimized for article display,
 * including threaded discussion structure when applicable. Each comment
 * contains the full text content, author's display name, creation timestamp,
 * and any relevant metadata that helps readers follow the conversation flow.
 *
 * The GET method makes this endpoint easily cacheable and suitable for public
 * access, supporting efficient article page loading with integrated comment
 * display. The response format is designed for direct integration into article
 * view interfaces.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target economic discussion
 *   article
 * @path /economicDiscussion/articles/:articleId/comments
 * @accessor api.functional.economicDiscussion.articles.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target economic discussion article */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIEconomicDiscussionComment.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/articles/:articleId/comments",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicDiscussion/articles/${encodeURIComponent(props.articleId ?? "null")}/comments`;
  export const random = (): IPageIEconomicDiscussionComment.ISummary =>
    typia.random<IPageIEconomicDiscussionComment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

