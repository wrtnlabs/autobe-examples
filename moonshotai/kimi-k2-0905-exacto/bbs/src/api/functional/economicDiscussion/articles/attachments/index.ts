import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionAttachment } from "../../../../structures/IEconomicDiscussionAttachment";
import { IPageIEconomicDiscussionAttachment } from "../../../../structures/IPageIEconomicDiscussionAttachment";

/**
 * Retrieve paginated list of file attachments for an article.
 *
 * This operation retrieves all file attachments associated with a specific
 * economic discussion article. It returns a paginated list of attachment
 * metadata including filename, file size, MIME type, upload timestamp, and
 * security scan status.
 *
 * The operation supports filtering by file type categories (image, document,
 * spreadsheet) to help users find specific attachment types. All attachments
 * inherit the same visibility permissions as their parent article - if the
 * article is publicly accessible, attachments are visible to all users; if the
 * article requires member access, only authenticated members can view
 * attachments.
 *
 * Security scanning status is included to indicate whether files have completed
 * the mandatory virus scanning process required by the platform. Attachments
 * are automatically removed when their associated article is deleted,
 * maintaining data consistency and preventing orphaned attachment records.
 *
 * The response includes essential metadata for file attachment UI display and
 * download preparation, excluding the actual file content which is delivered
 * through separate download endpoints.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the economic discussion article
 * @param props.body Search and filtering parameters for attachment listing
 * @path /economicDiscussion/articles/:articleId/attachments
 * @accessor api.functional.economicDiscussion.articles.attachments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the economic discussion article */
    articleId: string & tags.Format<"uuid">;

    /** Search and filtering parameters for attachment listing */
    body: IEconomicDiscussionAttachment.IRequest;
  };
  export type Body = IEconomicDiscussionAttachment.IRequest;
  export type Response = IPageIEconomicDiscussionAttachment.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/articles/:articleId/attachments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/economicDiscussion/articles/${encodeURIComponent(props.articleId ?? "null")}/attachments`;
  export const random = (): IPageIEconomicDiscussionAttachment.ISummary =>
    typia.random<IPageIEconomicDiscussionAttachment.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
