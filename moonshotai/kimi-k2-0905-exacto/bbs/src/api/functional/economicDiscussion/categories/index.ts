/**
 * Search and retrieve paginated list of discussion categories.
 *
 * Retrieve a filtered and paginated list of discussion board categories with
 * support for advanced search criteria. This operation enables users to
 * discover relevant discussion topics by filtering based on category names,
 * descriptions, creation dates, and activity levels.
 *
 * The operation supports full-text search within category titles and
 * descriptions, allowing users to find categories matching their interests.
 * Pagination controls including page size, sort order, and continuation tokens
 * provide efficient browsing through large category sets.
 *
 * Security measures include rate limiting for search frequency and appropriate
 * visibility controls based on user authorization level. Public guests can view
 * active categories while authenticated members may access additional metadata
 * about category activity and popularity.
 *
 * This operation integrates with the economic_discussion_categories table from
 * the Prisma schema while incorporating related metadata from article-category
 * associations for usage statistics.
 *
 * @param props.connection
 * @param props.body Search parameters for filtering and paginating discussion
 *   categories
 * @path /economicDiscussion/categories
 * @accessor api.functional.economicDiscussion.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search parameters for filtering and paginating discussion categories */
    body: IEconomicDiscussionCategory.IRequest;
  };
  export type Body = IEconomicDiscussionCategory.IRequest;
  export type Response = IPageIEconomicDiscussionCategory.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/categories",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/categories";
  export const random = (): IPageIEconomicDiscussionCategory.ISummary =>
    typia.random<IPageIEconomicDiscussionCategory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

