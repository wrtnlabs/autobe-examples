/**
 * Create a new economic discussion article with comprehensive content and
 * metadata. This operation allows authenticated users to publish economic
 * insights, political analysis, and policy discussions on the platform.
 *
 * Article creation requires a valid title and content body with minimum length
 * requirements. The title should clearly indicate the discussion topic or
 * question being addressed. Content must meet platform guidelines and will
 * undergo moderation review before public visibility.
 *
 * The operation automatically sets the initial article version to 1.0 and
 * assigns a pending status for moderation review. View count is initialized to
 * zero and will increment as users access the article after approval.
 *
 * File attachments can be associated with the article through separate API
 * calls after creation. The article can be categorized immediately upon
 * creation or categories can be added later through the article-category
 * relationship endpoints.
 *
 * @param props.connection
 * @param props.body Article creation data including title, content, and initial
 *   categorization
 * @path /economicDiscussion/member/articles
 * @accessor api.functional.economicDiscussion.member.articles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Article creation data including title, content, and initial
     * categorization
     */
    body: IEconomicDiscussionArticle.ICreate;
  };
  export type Body = IEconomicDiscussionArticle.ICreate;
  export type Response = IEconomicDiscussionArticle;

  export const METADATA = {
    method: "POST",
    path: "/economicDiscussion/member/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/member/articles";
  export const random = (): IEconomicDiscussionArticle =>
    typia.random<IEconomicDiscussionArticle>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

