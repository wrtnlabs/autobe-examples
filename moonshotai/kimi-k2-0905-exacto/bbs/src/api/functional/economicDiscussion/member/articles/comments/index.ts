/**
 * Add a new comment to an existing discussion article in the economic and
 * political discussion platform. This operation allows authenticated members to
 * provide textual feedback, opinions, and responses to published articles,
 * enabling community discussion and interaction.
 *
 * The operation validates that the target article exists and is accessible,
 * then creates a new comment that becomes immediately visible as part of the
 * article's discussion thread. Comments are automatically associated with the
 * authenticated member making the request, enabling proper attribution and
 * allowing for ownership tracking.
 *
 * This operation serves as the primary way for community members to participate
 * in discussions, providing a mechanism for expressing viewpoints, asking
 * questions, and engaging with article content. The comment system supports
 * direct engagement between members while maintaining a threaded discussion
 * format.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target discussion article
 *   where the comment will be added
 * @param props.body Comment content and metadata for creation
 * @path /economicDiscussion/member/articles/:articleId/comments
 * @accessor api.functional.economicDiscussion.member.articles.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
