import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionRecommendationsRequest } from "../../../../../structures/IEconomicDiscussionRecommendationsRequest";
import { IEconomicDiscussionRecommendationsList } from "../../../../../structures/IEconomicDiscussionRecommendationsList";

/**
 * Provides personalized article recommendations based on user browsing history
 * and interaction patterns. The recommendation engine analyzes user activity
 * including search queries, viewed articles, comment participation, and
 * engagement patterns to suggest relevant economic and political content.
 *
 * The algorithm considers factors such as frequently viewed categories, search
 * keywords, user interaction patterns with different article types, and time
 * spent on various topics to generate personalized content suggestions. This
 * personalization helps users discover new discussions that align with their
 * economic and political interests.
 *
 * For authenticated users, recommendations are based on individual user
 * profiles and activity history tracked through member sessions and interaction
 * logs. For guest users, recommendations may be based on current session
 * behavior or default to trending/popular content patterns that reflect overall
 * community interests.
 *
 * @param props.connection
 * @param props.body Recommendation preferences including user interests,
 *   category preferences, and interaction history parameters
 * @path /economicDiscussion/member/discovery/recommendations
 * @accessor api.functional.economicDiscussion.member.discovery.recommendations.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Recommendation preferences including user interests, category
     * preferences, and interaction history parameters
     */
    body: IEconomicDiscussionRecommendationsRequest;
  };
  export type Body = IEconomicDiscussionRecommendationsRequest;
  export type Response = IEconomicDiscussionRecommendationsList;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/member/discovery/recommendations",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/economicDiscussion/member/discovery/recommendations";
  export const random = (): IEconomicDiscussionRecommendationsList =>
    typia.random<IEconomicDiscussionRecommendationsList>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
