/**
 * Retrieve comprehensive member profile information including username, email
 * verification status, account creation date, reputation score, and member
 * account status. This operation provides essential member data for profile
 * display, community interaction, and administrative oversight.
 *
 * The response includes member's community participation metrics such as total
 * article count, comment count, and reputation score calculated based on
 * activity within the economic discussion community. The reputation score
 * reflects the member's engagement level and contributes to their ranking and
 * feature access within the platform.
 *
 * This operation serves as the primary mechanism for profile retrieval,
 * enabling both members to view their own accounts and moderators to access
 * member information for community management purposes. The detailed profile
 * data supports user experience personalization and community feature
 * implementations.
 *
 * @param props.connection
 * @param props.memberId Unique identifier pointing to the specific economic
 *   discussion member
 * @path /economicDiscussion/member/members/:memberId
 * @accessor api.functional.economicDiscussion.member.members.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier pointing to the specific economic discussion member */
    memberId: string & tags.Format<"uuid">;
  };
  export type Response = IEconomicDiscussionMember;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/member/members/:memberId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/economicDiscussion/member/members/${encodeURIComponent(props.memberId ?? "null")}`;
  export const random = (): IEconomicDiscussionMember =>
    typia.random<IEconomicDiscussionMember>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("memberId")(() => typia.assert(props.memberId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

