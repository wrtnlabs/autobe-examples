/**
 * Retrieve paginated version history for an article.
 *
 * Get a paginated list of article version snapshots for a specific article,
 * providing complete edit history tracking. This operation retrieves all
 * historical versions of an article, showing how content has evolved over
 * time.
 *
 * Each version captures the complete article state including title, content,
 * and metadata at that specific moment. The versions are ordered
 * chronologically, allowing users to browse through the edit history and see
 * detailed changes over time.
 *
 * This feature supports content transparency requirements where users can view
 * who made changes and when. It also enables potential rollback capabilities by
 * providing access to previous article states. The pagination system ensures
 * efficient loading even for articles with extensive edit histories.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article
 * @param props.body Pagination and sorting parameters for version history
 *   retrieval
 * @path /economicDiscussion/member/articles/:articleId/versions
 * @accessor api.functional.economicDiscussion.member.articles.versions.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
