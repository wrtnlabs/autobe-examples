/**
 * Retrieves the authenticated member's personal search history from the
 * Economic Discussion Board platform. This operation returns a chronologically
 * ordered list of all searches performed by the currently logged-in member,
 * including the search query text, execution timestamp, and related search
 * analytics data.
 *
 * The search history enables members to quickly access and re-execute previous
 * searches, track their research patterns, and discover content they've
 * previously explored. Each search history entry includes the actual query text
 * entered by the user and links to the related search query metadata in the
 * master search queries table.
 *
 * Permission validation ensures only the authenticated member can access their
 * own search history, with proper session verification and ownership
 * validation. The operation leverages the foreign key relationships to
 * economic_discussion_members (member_id), economic_discussion_search_queries
 * (query_id), and includes access to frequency data, result counts, and average
 * click positions from the master query table for enhanced user experience.
 *
 * @param props.connection
 * @path /economicDiscussion/member/search/history
 * @accessor api.functional.economicDiscussion.member.search.history.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPageIEconomicDiscussionSearchHistory;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/member/search/history",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/member/search/history";
  export const random = (): IPageIEconomicDiscussionSearchHistory =>
    typia.random<IPageIEconomicDiscussionSearchHistory>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

