import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionAttachment } from "../../../../../structures/IEconomicDiscussionAttachment";

/**
 * Create a new file attachment for a specific economic discussion article. This
 * operation allows authenticated users to upload and attach files (images,
 * documents, spreadsheets) to their own articles.
 *
 * The system validates attachment limits (maximum 5 files per article) and
 * total combined file size constraints. Security scanning is initiated
 * automatically upon upload completion. Supported file types include images
 * (JPEG, PNG, GIF), documents (PDF, DOC, DOCX), and spreadsheets (XLS, XLSX)
 * with different size limits for each category.
 *
 * Authentication is required to verify the user owns the target article.
 * Authorization checks ensure only moderators can add attachments to any
 * article, while regular members can only attach files to their own article.
 * The uploaded file is immediately available for download and preview within
 * the article context.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target article to attach the
 *   file to
 * @param props.body File upload request containing the attachment file and
 *   metadata
 * @path /economicDiscussion/member/articles/:articleId/attachmentFiles
 * @accessor api.functional.economicDiscussion.member.articles.attachmentFiles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Unique identifier of the target article to attach the file to */
    articleId: string & tags.Format<"uuid">;

    /** File upload request containing the attachment file and metadata */
    body: IEconomicDiscussionAttachment.ICreate;
  };
  export type Body = IEconomicDiscussionAttachment.ICreate;
  export type Response = IEconomicDiscussionAttachment;

  export const METADATA = {
    method: "POST",
    path: "/economicDiscussion/member/articles/:articleId/attachmentFiles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/economicDiscussion/member/articles/${encodeURIComponent(props.articleId ?? "null")}/attachmentFiles`;
  export const random = (): IEconomicDiscussionAttachment =>
    typia.random<IEconomicDiscussionAttachment>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

