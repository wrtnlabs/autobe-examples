import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionArticle } from "../../../../../structures/IEconomicDiscussionArticle";
import { IPageIEconomicDiscussionArticle } from "../../../../../structures/IPageIEconomicDiscussionArticle";

/**
 * Search and filter articles within a specific discussion category.
 *
 * Perform advanced search queries across economic and political discussion
 * articles filtered by category code. This operation enables users to find
 * relevant content within specific topic areas using text-based searches across
 * article titles and content.
 *
 * The search functionality leverages database indexing for optimal performance,
 * supporting partial text matching starting from 2 characters. Users can
 * combine search terms with additional filters like article status, creation
 * date ranges, and sorting preferences. The system automatically applies
 * permission-based filtering to show only approved articles to general users
 * and all statuses to moderators.
 *
 * Pagination is supported with configurable page sizes and sorting options.
 * Results include article summaries optimized for list display, showing curated
 * excerpts that highlight relevant search terms. Engagement metrics like view
 * counts and comment numbers help users identify popular and active
 * discussions.
 *
 * Search queries are automatically tracked in the search history tables for
 * logged-in users and aggregated in the search queries table for platform-wide
 * analytics.
 *
 * @param props.connection
 * @param props.categoryCode Unique category code identifier for filtering
 *   articles within a specific discussion category. Must correspond to an
 *   active category from economic_discussion_categories.code.
 * @param props.body Search criteria and pagination parameters for
 *   category-specific article filtering
 * @path /economicDiscussion/member/search/categories/:categoryCode
 * @accessor api.functional.economicDiscussion.member.search.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique category code identifier for filtering articles within a
     * specific discussion category. Must correspond to an active category
     * from economic_discussion_categories.code.
     */
    categoryCode: string;

    /**
     * Search criteria and pagination parameters for category-specific
     * article filtering
     */
    body: IEconomicDiscussionArticle.IRequest;
  };
  export type Body = IEconomicDiscussionArticle.IRequest;
  export type Response = IPageIEconomicDiscussionArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/economicDiscussion/member/search/categories/:categoryCode",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/economicDiscussion/member/search/categories/${encodeURIComponent(props.categoryCode ?? "null")}`;
  export const random = (): IPageIEconomicDiscussionArticle.ISummary =>
    typia.random<IPageIEconomicDiscussionArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryCode")(() => typia.assert(props.categoryCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
