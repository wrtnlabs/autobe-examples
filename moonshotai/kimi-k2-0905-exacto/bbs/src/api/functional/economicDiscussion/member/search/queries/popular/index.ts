import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IEconomicDiscussionArticle } from "../../../../../../structures/IEconomicDiscussionArticle";

/**
 * Retrieve popular search queries from the platform.
 *
 * Access platform-wide search analytics to discover trending topics and popular
 * content areas in economic and political discussions. This operation surfaces
 * queries that demonstrate high community engagement, useful result quality,
 * and strong search performance metrics.
 *
 * The algorithm prioritizes queries with high total frequency counts,
 * indicating broad community interest in specific topics. Only queries with
 * recent activity (within 30 days) are included to ensure relevance. Additional
 * weight is given to queries with quality metrics such as average click
 * positions below 5 (indicating users found relevant results in the top
 * positions) and result counts above 3 (ensuring meaningful content
 * discovery).
 *
 * Results are ordered by frequency and filtered to exclude test queries, spam,
 * or low-engagement searches. The ranking considers both absolute popularity
 * and recent momentum, helping identify emerging discussion topics alongside
 * established subject matter.
 *
 * This information aids content creators in identifying community interests and
 * users in discovering popular discussion areas. The data excludes sensitive
 * queries and personal searches to maintain privacy while providing valuable
 * community insights.
 *
 * @param props.connection
 * @path /economicDiscussion/member/search/queries/popular
 * @accessor api.functional.economicDiscussion.member.search.queries.popular.popularQueries
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function popularQueries(
  connection: IConnection,
): Promise<popularQueries.Response> {
  return true === connection.simulate
    ? popularQueries.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...popularQueries.METADATA,
          path: popularQueries.path(),
          status: null,
        },
      );
}
export namespace popularQueries {
  export type Response = IEconomicDiscussionArticle.ISummary;

  export const METADATA = {
    method: "GET",
    path: "/economicDiscussion/member/search/queries/popular",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/economicDiscussion/member/search/queries/popular";
  export const random = (): IEconomicDiscussionArticle.ISummary =>
    typia.random<IEconomicDiscussionArticle.ISummary>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
