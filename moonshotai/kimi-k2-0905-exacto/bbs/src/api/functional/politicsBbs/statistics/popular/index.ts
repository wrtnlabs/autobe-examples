import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPoliticsBbsPopularArticles } from "../../../../structures/IPoliticsBbsPopularArticles";

/**
 * Retrieve popular articles based on view counts and recent engagement.
 *
 * This operation retrieves a curated list of the most popular articles from the
 * politicsBBS discussion board based on a combination of view counts, recent
 * engagement metrics, and publication recency. The system analyzes article
 * statistics to surface trending content that is currently generating
 * significant user interest and participation.
 *
 * The popularity algorithm considers multiple factors including total view
 * counts, recent view activity within the last 24-48 hours, and the recency of
 * publication to ensure both established discussions and new content with
 * emerging interest are featured. Only articles with approved status (state:
 * approved) are included to ensure quality and relevant content.
 *
 * The result set is optimized for quick discovery of high-engagement content,
 * providing users with an immediate overview of active discussions on economic
 * and political topics. This aids in community building by surfacing
 * discussions that are likely to generate further dialogue and participation.
 *
 * @param props.connection
 * @path /politicsBbs/statistics/popular
 * @accessor api.functional.politicsBbs.statistics.popular.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(connection: IConnection): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
      );
}
export namespace index {
  export type Response = IPoliticsBbsPopularArticles;

  export const METADATA = {
    method: "GET",
    path: "/politicsBbs/statistics/popular",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/statistics/popular";
  export const random = (): IPoliticsBbsPopularArticles =>
    typia.random<IPoliticsBbsPopularArticles>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
