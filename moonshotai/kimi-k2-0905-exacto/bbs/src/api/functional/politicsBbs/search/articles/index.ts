import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsArticle } from "../../../../structures/IPoliticsBbsArticle";
import { IPageIPoliticsBbsArticle } from "../../../../structures/IPageIPoliticsBbsArticle";

/**
 * Search and filter articles with advanced query parameters and sorting.
 *
 * This operation enables advanced search and filtering across the politicsBBS
 * article content, providing users with comprehensive discovery capabilities
 * beyond simple category browsing. The system accepts complex search parameters
 * including keyword queries, category filters, date ranges, and sorting
 * preferences to deliver highly targeted article results.
 *
 * The search implementation supports both title-only queries and full-content
 * searches using PostgreSQL's text search capabilities with trigram indexing.
 * Users can filter results by specific categories (Economic Policy, Political
 * Analysis, International Relations, etc.) to focus on topics of interest. Date
 * filtering allows discovery of recent content or historical perspectives
 * within specified timeframes.
 *
 * The operation supports multiple sorting options including chronological order
 * (newest first), relevance ranking for keyword searches, and popularity
 * ordering based on view counts. Pagination delivers results in manageable
 * chunks while maintaining search context and filter state across page
 * requests.
 *
 * Advanced search parameters accommodate power users who need sophisticated
 * filtering options such as minimum view counts, specific author filtering, or
 * exact phrase matching. The system maintains search history for authenticated
 * members and allows saved searches for frequently used queries.
 *
 * The search results include rich metadata for each article including creation
 * timestamps, view counts, comment counts, category assignments, and author
 * information to aid in content evaluation without requiring additional data
 * requests.
 *
 * @param props.connection
 * @param props.body Search criteria including keywords, category filters, date
 *   range, sorting options, and pagination parameters for advanced article
 *   discovery
 * @path /politicsBbs/search/articles
 * @accessor api.functional.politicsBbs.search.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria including keywords, category filters, date range,
     * sorting options, and pagination parameters for advanced article
     * discovery
     */
    body: IPoliticsBbsArticle.IRequest;
  };
  export type Body = IPoliticsBbsArticle.IRequest;
  export type Response = IPageIPoliticsBbsArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/politicsBbs/search/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/search/articles";
  export const random = (): IPageIPoliticsBbsArticle.ISummary =>
    typia.random<IPageIPoliticsBbsArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
