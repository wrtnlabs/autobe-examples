import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsSearch } from "../../../../structures/IPoliticsBbsSearch";
import { IPageIPoliticsBbsSearchResult } from "../../../../structures/IPageIPoliticsBbsSearchResult";

/**
 * Perform unified search across all discussion board content.
 *
 * Execute a comprehensive search across all content types in the politicsBBS
 * discussion board including articles, comments, and user-generated content.
 * The search system utilizes PostgreSQL's full-text search capabilities with
 * trigram similarity matching to provide relevant results across economic and
 * political discussions.
 *
 * The operation supports advanced filtering options including content type
 * filtering (articles only, comments only, or all content), date range
 * filtering for temporal searches, category filtering to focus on specific
 * political or economic topics, and user role filtering to search within
 * specific user groups. Search results are ranked by relevance using a
 * combination of text similarity scores and recency weighting.
 *
 * This unified search endpoint serves as the primary discovery mechanism for
 * users to find relevant discussions, policy analyses, and economic discourse
 * across the entire platform. The search algorithm prioritizes recent content
 * while maintaining relevance to the search query, ensuring users can easily
 * locate both current and historical discussions on political and economic
 * topics.
 *
 * @param props.connection
 * @param props.body Search criteria including query terms, filters, and
 *   pagination parameters
 * @path /politicsBbs/search/unified
 * @accessor api.functional.politicsBbs.search.unified.search
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function search(
  connection: IConnection,
  props: search.Props,
): Promise<search.Response> {
  return true === connection.simulate
    ? search.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...search.METADATA,
          path: search.path(),
          status: null,
        },
        props.body,
      );
}
export namespace search {
  export type Props = {
    /**
     * Search criteria including query terms, filters, and pagination
     * parameters
     */
    body: IPoliticsBbsSearch.IRequest;
  };
  export type Body = IPoliticsBbsSearch.IRequest;
  export type Response = IPageIPoliticsBbsSearchResult;

  export const METADATA = {
    method: "PATCH",
    path: "/politicsBbs/search/unified",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/search/unified";
  export const random = (): IPageIPoliticsBbsSearchResult =>
    typia.random<IPageIPoliticsBbsSearchResult>();
  export const simulate = (
    connection: IConnection,
    props: search.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: search.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
