import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsComment } from "../../../structures/IPoliticsBbsComment";

/**
 * Get detailed information about a specific comment.
 *
 * Retrieve detailed information about a specific comment by its unique
 * identifier. This operation provides complete comment metadata including the
 * comment content, moderation status, creation timestamp, nesting level within
 * the comment thread, and actor type information indicating whether the comment
 * was posted by a visitor, member, or moderator.
 *
 * The operation supports anonymous access and returns comment information based
 * on database query results. If the comment does not exist or has been deleted,
 * appropriate error responses ensure user feedback. Special handling exists for
 * comments with different moderation statuses, providing appropriate viewing
 * permissions based on content review states.
 *
 * Comments follow a threaded structure with nesting levels 0-2, supporting up
 * to 3 levels of discussion depth. The comment system maintains polymorphic
 * ownership through subtype entities that link to the specific user type who
 * created the comment, enabling proper attribution and permission management
 * within the discussion framework.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the comment to retrieve
 * @path /politicsBbs/comments/:commentId
 * @accessor api.functional.politicsBbs.comments.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the comment to retrieve */
    commentId: string & tags.Format<"uuid">;
  };
  export type Response = IPoliticsBbsComment;

  export const METADATA = {
    method: "GET",
    path: "/politicsBbs/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicsBbs/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): IPoliticsBbsComment =>
    typia.random<IPoliticsBbsComment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
