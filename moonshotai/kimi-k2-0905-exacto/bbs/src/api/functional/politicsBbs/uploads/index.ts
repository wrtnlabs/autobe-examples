import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsFileAttachment } from "../../../structures/IPoliticsBbsFileAttachment";

/**
 * Get uploaded file information and metadata.
 *
 * Retrieve detailed information about a specific uploaded file or image
 * attachment including metadata such as filename, file size, MIME type, upload
 * timestamp, and for images - dimensions and processing information. This
 * operation supports transparency in file handling and enables users to
 * understand what attachments are available alongside article content. The
 * response provides essential metadata without returning the actual file
 * content, which is served separately through file download endpoints.
 *
 * @param props.connection
 * @param props.uploadId Unique identifier of the uploaded attachment
 * @path /politicsBbs/uploads/:uploadId
 * @accessor api.functional.politicsBbs.uploads.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the uploaded attachment */
    uploadId: string & tags.Format<"uuid">;
  };
  export type Response = IPoliticsBbsFileAttachment;

  export const METADATA = {
    method: "GET",
    path: "/politicsBbs/uploads/:uploadId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicsBbs/uploads/${encodeURIComponent(props.uploadId ?? "null")}`;
  export const random = (): IPoliticsBbsFileAttachment =>
    typia.random<IPoliticsBbsFileAttachment>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("uploadId")(() => typia.assert(props.uploadId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
