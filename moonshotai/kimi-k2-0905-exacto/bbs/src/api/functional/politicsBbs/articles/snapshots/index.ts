import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPageIPoliticsBbsArticleSnapshot } from "../../../../structures/IPageIPoliticsBbsArticleSnapshot";

/**
 * Retrieve historical snapshots of a politics discussion article.
 *
 * This operation retrieves all historical snapshots associated with a specific
 * politics discussion board article. Snapshots capture the complete state of an
 * article at crucial transition points, including title, content, lifecycle
 * state information, and view count data when state changes occurred.
 *
 * The snapshots serve as a critical audit trail for tracking political
 * discourse evolution, enabling users to review the progression of economic
 * discussions and policy debates over time. This functionality supports content
 * integrity protection by maintaining immutable historical records of article
 * modifications throughout the discussion lifecycle.
 *
 * By providing chronological access to article state changes, the system
 * enables content moderation teams to understand discussion development
 * patterns, review major content modifications, and maintain accountability for
 * political discourse standards. The historical tracking is essential for
 * measuring content quality evolution and maintaining credibility of economic
 * and political policy discussions on the platform.
 *
 * This operation maintains transparency by allowing public inspection of
 * article modification history while preserving the original discussion context
 * that shaped political and economic policy debates on the platform.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the target politics discussion
 *   article
 * @path /politicsBbs/articles/:articleId/snapshots
 * @accessor api.functional.politicsBbs.articles.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target politics discussion article */
    articleId: string & tags.Format<"uuid">;
  };
  export type Response = IPageIPoliticsBbsArticleSnapshot;

  export const METADATA = {
    method: "GET",
    path: "/politicsBbs/articles/:articleId/snapshots",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicsBbs/articles/${encodeURIComponent(props.articleId ?? "null")}/snapshots`;
  export const random = (): IPageIPoliticsBbsArticleSnapshot =>
    typia.random<IPageIPoliticsBbsArticleSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
