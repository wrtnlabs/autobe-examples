import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsContentApproval } from "../../../../../../structures/IPoliticsBbsContentApproval";

/**
 * Approve content for public visibility.
 *
 * Approve specific content item by transitioning it from pending review to
 * approved public status. This operation enables content to become visible to
 * all users once approved by a moderator.
 *
 * Upon approval, articles transition from 'pending' to 'approved' state and
 * become publicly visible in their assigned categories. Comments marked as
 * approved become visible in the discussion threads they belong to. The
 * approval process is designed to ensure quality content reaches the community
 * while inappropriate content remains in review until properly vetted.
 *
 * @param props.connection
 * @param props.contentId Unique identifier of the content item to approve
 * @param props.body Approval confirmation and moderation notes
 * @path /politicsBbs/moderator/moderator/content/:contentId/approve
 * @accessor api.functional.politicsBbs.moderator.moderator.content.approve.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Unique identifier of the content item to approve */
    contentId: string & tags.Format<"uuid">;

    /** Approval confirmation and moderation notes */
    body: IPoliticsBbsContentApproval.ICreate;
  };
  export type Body = IPoliticsBbsContentApproval.ICreate;
  export type Response = IPoliticsBbsContentApproval;

  export const METADATA = {
    method: "PUT",
    path: "/politicsBbs/moderator/moderator/content/:contentId/approve",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/politicsBbs/moderator/moderator/content/${encodeURIComponent(props.contentId ?? "null")}/approve`;
  export const random = (): IPoliticsBbsContentApproval =>
    typia.random<IPoliticsBbsContentApproval>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("contentId")(() => typia.assert(props.contentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
