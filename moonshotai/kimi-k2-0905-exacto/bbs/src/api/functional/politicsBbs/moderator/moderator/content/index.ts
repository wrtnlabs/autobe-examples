/**
 * Reject inappropriate content with moderation reasoning.
 *
 * Reject content that violates community guidelines or platform policies. This
 * operation enables moderators to maintain content quality by rejecting
 * articles or comments that contain inappropriate material, misinformation, or
 * violate the platform's focus on economic and political discourse.
 *
 * The rejection process updates the content status to 'rejected' and triggers
 * notification to the content creator with the rejection reason. Moderators
 * must provide a clear explanation for the rejection to help users understand
 * policy violations and encourage better content creation in the future.
 *
 * This operation maintains comprehensive audit logs of all moderation actions,
 * ensuring transparency in content management decisions. The rejected content
 * becomes invisible to regular users while remaining accessible to moderators
 * for reference and potential appeals processing.
 *
 * The moderation system supports graduated responses, allowing moderators to
 * provide educational feedback rather than immediate account penalties for
 * minor violations. This approach helps build a healthier community while
 * maintaining platform standards for substantive economic and political
 * discussions.
 *
 * @param props.connection
 * @param props.contentId Unique identifier of the content (article or comment)
 *   to be rejected
 * @param props.body Rejection details including the reason for content
 *   rejection
 * @path /politicsBbs/moderator/moderator/content/:contentId/reject
 * @accessor api.functional.politicsBbs.moderator.moderator.content.reject
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function reject(
  connection: IConnection,
  props: reject.Props,
): Promise<reject.Response> {
  return true === connection.simulate
    ? reject.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...reject.METADATA,
          path: reject.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace reject {
  export type Props = {
    /** Unique identifier of the content (article or comment) to be rejected */
    contentId: string & tags.Format<"uuid">;

    /** Rejection details including the reason for content rejection */
    body: IPoliticsBbsContent.IReject;
  };
  export type Body = IPoliticsBbsContent.IReject;
  export type Response = IPoliticsBbsContent.IRejectResponse;

  export const METADATA = {
    method: "PUT",
    path: "/politicsBbs/moderator/moderator/content/:contentId/reject",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/politicsBbs/moderator/moderator/content/${encodeURIComponent(props.contentId ?? "null")}/reject`;
  export const random = (): IPoliticsBbsContent.IRejectResponse =>
    typia.random<IPoliticsBbsContent.IRejectResponse>();
  export const simulate = (
    connection: IConnection,
    props: reject.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: reject.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("contentId")(() => typia.assert(props.contentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
