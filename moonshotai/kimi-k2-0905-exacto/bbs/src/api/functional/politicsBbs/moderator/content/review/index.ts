import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsContentReview } from "../../../../../structures/IPoliticsBbsContentReview";
import { IPageIPoliticsBbsContentReview } from "../../../../../structures/IPageIPoliticsBbsContentReview";

/**
 * Get list of content pending moderator review.
 *
 * Retrieve a paginated list of content items pending moderator review,
 * including articles and comments that need approval or moderation actions.
 * This operation supports the editorial workflow by allowing moderators to
 * efficiently review content submissions and maintain community standards.
 *
 * The operation filters content based on moderation status, showing only items
 * that require review. Articles in 'pending' state appear in the review queue,
 * while comments with 'flagged' or 'pending' status require moderator
 * attention. This ensures inappropriate content is caught while legitimate
 * discussions are approved quickly.
 *
 * @param props.connection
 * @param props.body Search and filtering parameters for content review queue
 * @path /politicsBbs/moderator/content/review
 * @accessor api.functional.politicsBbs.moderator.content.review.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search and filtering parameters for content review queue */
    body: IPoliticsBbsContentReview.IRequest;
  };
  export type Body = IPoliticsBbsContentReview.IRequest;
  export type Response = IPageIPoliticsBbsContentReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/politicsBbs/moderator/content/review",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/moderator/content/review";
  export const random = (): IPageIPoliticsBbsContentReview.ISummary =>
    typia.random<IPageIPoliticsBbsContentReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
