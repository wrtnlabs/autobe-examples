/**
 * Search and retrieve filtered politics discussion categories.
 *
 * Retrieve a filtered list of political discussion categories with support for
 * complex search queries, sorting by sequence or name, and filtering by primary
 * categories. Categories are predefined by moderators and include economic
 * policy, political analysis, international relations, domestic politics,
 * fiscal policy, and other economic/political discussion topics.
 *
 * The system enforces that economic and political discussions remain focused on
 * substantive topics, avoiding personal attacks while encouraging
 * evidence-based arguments. Categories provide the primary organizational
 * structure for content discovery and navigation within the discussion board
 * platform.
 *
 * This operation supports pagination with configurable page sizes and multiple
 * sorting options including alphabetical, creation date, and display sequence.
 * Users can filter by primary categories for featured content or view secondary
 * categories for expanded discussion topics. The response includes category
 * metadata such as color codes, icons, and multiplicative settings for proper
 * category assignment.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for category
 *   filtering
 * @path /politicsBbs/categories
 * @accessor api.functional.politicsBbs.categories.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Search criteria and pagination parameters for category filtering */
    body: IPoliticsBbsCategory.IRequest;
  };
  export type Body = IPoliticsBbsCategory.IRequest;
  export type Response = IPageIPoliticsBbsCategory.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/politicsBbs/categories",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/categories";
  export const random = (): IPageIPoliticsBbsCategory.ISummary =>
    typia.random<IPageIPoliticsBbsCategory.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

