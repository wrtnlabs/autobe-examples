import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsUpload } from "../../../../structures/IPoliticsBbsUpload";

/**
 * Upload image or document attachments for articles.
 *
 * Handle file uploads for the politicsBBS discussion board supporting both
 * image and document attachments. The upload process includes comprehensive
 * validation to ensure file safety and compliance with platform requirements.
 *
 * For image uploads, the system accepts JPEG, PNG, and GIF formats with a
 * maximum file size of 5MB per image. Images are automatically processed to
 * generate thumbnails and optimized versions for web display. The system allows
 * up to 10 images per article and maintains proper aspect ratios while creating
 * responsive versions for mobile devices.
 *
 * Document uploads support PDF, DOC, DOCX, and TXT formats with a maximum size
 * of 10MB per file. Users can attach up to 5 documents per article. All
 * uploaded files undergo malware scanning and content validation before being
 * accepted. The system generates preview thumbnails for supported document
 * types and stores files with secure access controls.
 *
 * File uploads are associated with the authenticated user's account and
 * maintain proper audit trails. The operation returns file metadata including
 * unique identifiers, file paths, and processing status that can be used when
 * creating or editing articles to attach the uploaded files.
 *
 * @param props.connection
 * @param props.body File upload data including the file content and metadata
 * @path /politicsBbs/member/uploads
 * @accessor api.functional.politicsBbs.member.uploads.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** File upload data including the file content and metadata */
    body: IPoliticsBbsUpload.ICreate;
  };
  export type Body = IPoliticsBbsUpload.ICreate;
  export type Response = IPoliticsBbsUpload;

  export const METADATA = {
    method: "POST",
    path: "/politicsBbs/member/uploads",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/member/uploads";
  export const random = (): IPoliticsBbsUpload =>
    typia.random<IPoliticsBbsUpload>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
