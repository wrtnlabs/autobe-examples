import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsComment } from "../../../../../structures/IPoliticsBbsComment";

/**
 * Create a new comment on an article.
 *
 * Create a new comment on a politicsBBS article with support for threaded
 * discussions and user authentication. This operation validates comment content
 * (minimum 20 characters, maximum 1000 characters), determines the appropriate
 * nesting level for replies, and associates the comment with the authenticated
 * user making the request.
 *
 * The comment system supports threading with up to 3 levels of nesting depth.
 * When creating a reply to an existing comment, the system calculates the
 * appropriate depth level and validates against the maximum nesting constraint.
 * Comments maintain polymorphic ownership patterns where different user types
 * (visitors, members, moderators) create comments through dedicated subtype
 * relationships.
 *
 * Content validation ensures comments provide meaningful dialogue while
 * preventing spam and inappropriate content. The operation creates the base
 * comment entity and associated subtype entity based on the user's role type,
 * maintaining proper referential integrity. On successful creation, the system
 * returns the complete comment information including generated IDs and
 * timestamps.
 *
 * Comments are initially created with 'pending' status by default, which
 * moderators can then approve for publication, ensuring quality control over
 * the discussion content while maintaining quick user feedback during the
 * posting process.
 *
 * @param props.connection
 * @param props.articleId Unique identifier of the article where the comment
 *   should be created
 * @param props.body Comment creation parameters including content and optional
 *   parent comment for threading
 * @path /politicsBbs/member/articles/:articleId/comments
 * @accessor api.functional.politicsBbs.member.articles.comments.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /** Unique identifier of the article where the comment should be created */
    articleId: string & tags.Format<"uuid">;

    /**
     * Comment creation parameters including content and optional parent
     * comment for threading
     */
    body: IPoliticsBbsComment.ICreate;
  };
  export type Body = IPoliticsBbsComment.ICreate;
  export type Response = IPoliticsBbsComment;

  export const METADATA = {
    method: "POST",
    path: "/politicsBbs/member/articles/:articleId/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/politicsBbs/member/articles/${encodeURIComponent(props.articleId ?? "null")}/comments`;
  export const random = (): IPoliticsBbsComment =>
    typia.random<IPoliticsBbsComment>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleId")(() => typia.assert(props.articleId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
