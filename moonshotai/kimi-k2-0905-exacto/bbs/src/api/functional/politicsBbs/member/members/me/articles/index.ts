import { IConnection } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";

import { IPoliticsBbsArticle } from "../../../../../../structures/IPoliticsBbsArticle";

/**
 * Get current member's created articles with statistics.
 *
 * Retrieve a comprehensive list of articles created by the currently
 * authenticated member. This operation provides members with visibility into
 * their content creation history, including all articles they've published on
 * the politics discussion board platform.
 *
 * The response includes detailed information about each article such as title,
 * creation date, current status (draft, pending, approved, rejected), view
 * count statistics, and associated category information. Members can use this
 * data to track their engagement levels and understand which topics generate
 * the most discussion within the community.
 *
 * This operation supports the member dashboard functionality, enabling users to
 * manage their content portfolio and identify their most successful
 * contributions to economic and political discourse. The information helps
 * members understand their impact on community discussions and identify
 * opportunities for more engaging content creation.
 *
 * The system maintains privacy by ensuring members can only access their own
 * article data, preventing unauthorized viewing of other users' content
 * creation patterns. This self-service approach reduces support overhead while
 * empowering members with comprehensive analytics about their platform
 * contributions.
 *
 * @param props.connection
 * @path /politicsBbs/member/members/me/articles
 * @accessor api.functional.politicsBbs.member.members.me.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IPoliticsBbsArticle.ISummaryList;

  export const METADATA = {
    method: "GET",
    path: "/politicsBbs/member/members/me/articles",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/member/members/me/articles";
  export const random = (): IPoliticsBbsArticle.ISummaryList =>
    typia.random<IPoliticsBbsArticle.ISummaryList>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
