/**
 * Create a new article with attachments.
 *
 * Submit a new article to the politics discussion board with support for images
 * and file attachments. This endpoint handles the complete article creation
 * workflow including title validation (5-150 characters), content validation
 * (minimum 50 characters), category assignment, and file upload processing
 * within size limits.
 *
 * The operation enforces business rules including a 5MB maximum for image files
 * and 10MB maximum for document files, with automatic scanning for prohibited
 * content types. Articles are created in 'pending' state by default and require
 * moderator approval before public visibility, maintaining content quality
 * standards for the economic and political discussion platform.
 *
 * Members can create content immediately upon successful authentication, with
 * the system tracking the creator relationship for 24-hour editing permission
 * and ownership rights. The response returns the created article details
 * including assigned unique identifier and preliminary attachment information
 * while files process asynchronously in the background.
 *
 * @param props.connection
 * @param props.body Article creation data including title, content, category
 *   selection, and optional attachments
 * @path /politicsBbs/member/articles
 * @accessor api.functional.politicsBbs.member.articles.create
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function create(
  connection: IConnection,
  props: create.Props,
): Promise<create.Response> {
  return true === connection.simulate
    ? create.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...create.METADATA,
          path: create.path(),
          status: null,
        },
        props.body,
      );
}
export namespace create {
  export type Props = {
    /**
     * Article creation data including title, content, category selection,
     * and optional attachments
     */
    body: IPoliticsBbsArticle.ICreate;
  };
  export type Body = IPoliticsBbsArticle.ICreate;
  export type Response = IPoliticsBbsArticle;

  export const METADATA = {
    method: "POST",
    path: "/politicsBbs/member/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/politicsBbs/member/articles";
  export const random = (): IPoliticsBbsArticle =>
    typia.random<IPoliticsBbsArticle>();
  export const simulate = (
    connection: IConnection,
    props: create.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: create.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

