import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Soft delete a member's own comment.
 *
 * Marks a comment as deleted by setting the deleted_at timestamp while
 * preserving its content and related data. This operation can only be performed
 * on comments where the authenticated member is the original author through the
 * member-specific comment subtype relationship. The comment remains in the
 * system with soft deletion status for audit purposes.
 *
 * The operation validates comment ownership through the polymorphic comment
 * system, ensuring members can only delete their own contributions and not
 * comments from visitors or other actors. It handles cleanup of presentation
 * flags while preserving audit trail information including creation timestamp,
 * content, and moderation history.
 *
 * This soft-delete approach maintains conversation integrity among threaded
 * discussions while allowing content removal for the original author. The
 * operation integrates with the member-specific comment management system
 * through proper subtype relationships.
 *
 * @param props.connection
 * @param props.commentId Unique identifier of the member's comment to be soft
 *   deleted
 * @path /politicsBbs/member/comments/:commentId
 * @accessor api.functional.politicsBbs.member.comments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the member's comment to be soft deleted */
    commentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/politicsBbs/member/comments/:commentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/politicsBbs/member/comments/${encodeURIComponent(props.commentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("commentId")(() => typia.assert(props.commentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
