import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsModerator } from "../../../../structures/IPoliticsBbsModerator";

/**
 * Change current moderator password.
 *
 * Change authenticated moderator password with validation.
 *
 * This endpoint enables moderators to securely update their account password.
 * The change process requires current password verification to prevent
 * unauthorized access attempts. New passwords must meet security requirements
 * including minimum 8 characters, mixed case letters, and numeric inclusion.
 *
 * Password validation includes comprehensive strength checking to ensure
 * compliance with security standards. The system implements secure password
 * hashing with appropriate salting techniques for all password storage.
 * Password changes are recorded for audit purposes while maintaining historical
 * security for account protection.
 *
 * @param props.connection
 * @param props.body Password change request with current and new passwords
 * @path /auth/moderator/password
 * @accessor api.functional.auth.moderator.password.updatePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function updatePassword(
  connection: IConnection,
  props: updatePassword.Props,
): Promise<updatePassword.Response> {
  return true === connection.simulate
    ? updatePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...updatePassword.METADATA,
          path: updatePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace updatePassword {
  export type Props = {
    /** Password change request with current and new passwords */
    body: IPoliticsBbsModerator.IPassword;
  };
  export type Body = IPoliticsBbsModerator.IPassword;
  export type Response = IPoliticsBbsModerator.IAuthorized;

  export const METADATA = {
    method: "PUT",
    path: "/auth/moderator/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/password";
  export const random = (): IPoliticsBbsModerator.IAuthorized =>
    typia.random<IPoliticsBbsModerator.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: updatePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: updatePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
