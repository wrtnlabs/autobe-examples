import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IPoliticsBbsModerator } from "../../../../structures/IPoliticsBbsModerator";

/**
 * Get current authenticated moderator profile information.
 *
 * Retrieve current authenticated moderator profile information.
 *
 * This endpoint returns comprehensive profile details for the currently
 * authenticated moderator. The information includes all relevant fields from
 * the politics_bbs_moderators table including username, email, creation
 * timestamp, and last update information.
 *
 * The profile data provides moderators with insights into their account status,
 * enabling review of account details, tracking of profile changes through
 * update timestamps, and verification of account creation history. This
 * supports moderator account management and audit requirements for
 * administrative role verification.
 *
 * @param props.connection
 * @path /auth/moderator/me
 * @accessor api.functional.auth.moderator.me.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(connection: IConnection): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(),
          status: null,
        },
      );
}
export namespace at {
  export type Response = IPoliticsBbsModerator;

  export const METADATA = {
    method: "GET",
    path: "/auth/moderator/me",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/me";
  export const random = (): IPoliticsBbsModerator =>
    typia.random<IPoliticsBbsModerator>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}

/**
 * Update current authenticated moderator profile information.
 *
 * This endpoint enables moderators to modify their profile details while
 * maintaining system integrity through comprehensive validation. The update
 * process supports username changes, email modifications, and maintains audit
 * trails for profile modifications.
 *
 * Username validation ensures unique usernames across the system with proper
 * character and length restrictions. Email modification requires verification
 * through system processes to ensure continued account access. Profile updates
 * are recorded with comprehensive audit information including the update
 * timestamp and modification tracking for administrative oversight.
 *
 * @param props.connection
 * @param props.body Moderator profile update information
 * @path /auth/moderator/me
 * @accessor api.functional.auth.moderator.me.update
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function update(
  connection: IConnection,
  props: update.Props,
): Promise<update.Response> {
  return true === connection.simulate
    ? update.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...update.METADATA,
          path: update.path(),
          status: null,
        },
        props.body,
      );
}
export namespace update {
  export type Props = {
    /** Moderator profile update information */
    body: IPoliticsBbsModerator.IUpdate;
  };
  export type Body = IPoliticsBbsModerator.IUpdate;
  export type Response = IPoliticsBbsModerator;

  export const METADATA = {
    method: "PUT",
    path: "/auth/moderator/me",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/moderator/me";
  export const random = (): IPoliticsBbsModerator =>
    typia.random<IPoliticsBbsModerator>();
  export const simulate = (
    connection: IConnection,
    props: update.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: update.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
