/**
 * Create new member account with JWT token issuance.
 *
 * Member registration endpoint for creating new member accounts. Members can
 * create articles, post comments, and upload attachments to the politics
 * discussion board.
 *
 * WHEN a new user registers, THE system SHALL validate the email format and
 * ensure uniqueness across the politics_bbs_members table. THE system SHALL
 * enforce password complexity requirements and store the password hash securely
 * using appropriate hashing algorithms.
 *
 * THE system SHALL create a new entry in the politics_bbs_members table with
 * generated UUID, unique username, email, password_hash, and current timestamps
 * for created_at and updated_at fields. THE deleted_at field SHALL remain null
 * for active accounts.
 *
 * Upon successful registration, THE system SHALL return JWT access and refresh
 * tokens to enable immediate authentication for the newly created member
 * account.
 *
 * Related operations include member login for authentication and token refresh
 * for session management. This operation is the entry point for new users to
 * join the discussion platform.
 *
 * @param props.connection
 * @param props.body Member registration credentials including username, email,
 *   and password
 * @setHeader token.access Authorization
 *
 * @path /auth/members/join
 * @accessor api.functional.auth.members.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Member registration credentials including username, email, and
     * password
     */
    body: IPoliticsBbsMember.IJoin;
  };
  export type Body = IPoliticsBbsMember.IJoin;
  export type Response = IPoliticsBbsMember.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/members/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/members/join";
  export const random = (): IPoliticsBbsMember.IAuthorized =>
    typia.random<IPoliticsBbsMember.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

