/**
 * Register new member account with email verification for economic discussion
 * board community.
 *
 * Member registration enables new users to join the economic and political
 * discussion board community. The system validates incoming registration data
 * against database constraints, checking that usernames contain only valid
 * characters (letters, numbers, hyphens, underscores) and are unique within the
 * 3-30 character range. Email addresses must follow standard format validation
 * and cannot already exist in the economic_discussion_members table.
 *
 * The registration process automatically initializes member properties with
 * sensible defaults. Email verification is mandatory for account activation, so
 * the email_verified field defaults to false until verification is completed.
 * The reputation_score starts at 0 and increases through community
 * participation such as creating articles and receiving comments. Timestamps
 * are automatically recorded for audit purposes with created_at and updated_at
 * fields.
 *
 * Password security is handled through robust hashing algorithms that transform
 * plaintext passwords into non-reversible hashes. The system supports
 * industry-standard cryptographic methods using bcrypt or similar secure
 * algorithms that prevent password disclosure even if database access is
 * compromised. Password requirements align with modern security standards and
 * community guidelines.
 *
 * From the database perspective, this operation directly corresponds to the
 * economic_discussion_members table structure. The username field maps to the
 * unique member display name, email stores the authentication address,
 * password_hash contains the encrypted credential, and supporting fields track
 * verification status plus temporal information. The reputation_score enables
 * community participation rewards and quality filtering.
 *
 * Successful registration creates a new member record accessible to the broader
 * community system. The new account can immediately receive verification
 * emails, though content creation privileges await email confirmation. This
 * operation integrates with the session management system for creating initial
 * authentication tokens used in subsequent login flows.
 *
 * @param props.connection
 * @param props.body Member registration request containing username, email, and
 *   password for new account creation
 * @setHeader token.access Authorization
 *
 * @path /auth/member/join
 * @accessor api.functional.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
