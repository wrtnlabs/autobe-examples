/**
 * Register temporary visitor account.
 *
 * Creates visitor accounts for the politicsBbs discussion board system. This
 * endpoint generates temporary guest accounts that provide session management
 * for unauthenticated users, allowing the system to track visitor activity,
 * recommend content based on browsing history, and maintain basic
 * personalization features. Visitor accounts receive limited JWT tokens that
 * expire after the browsing session ends, maintaining security for guest users
 * while providing essential session functionality. The registration process
 * requires minimal information - only username and password hash - reflecting
 * the temporary nature of visitor accounts. Upon successful registration, the
 * system creates a new visitor record with auto-generated UUID, timestamps for
 * account creation and last activity, and returns authorization tokens for
 * session management. This enables the discussion board to distinguish between
 * different guest visitors while maintaining the anonymity and limited
 * privileges appropriate for unauthenticated users.
 *
 * @param props.connection
 * @param props.body Visitor registration credentials
 * @setHeader token.access Authorization
 *
 * @path /auth/visitor/join
 * @accessor api.functional.auth.visitor.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Visitor registration credentials */
    body: IPoliticsBbsVisitorUser.IJoin;
  };
  export type Body = IPoliticsBbsVisitorUser.IJoin;
  export type Response = IPoliticsBbsVisitorUser.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/visitor/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/visitor/join";
  export const random = (): IPoliticsBbsVisitorUser.IAuthorized =>
    typia.random<IPoliticsBbsVisitorUser.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

