import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IEconomicDiscussionGuest } from "../../../structures/IEconomicDiscussionGuest";

/**
 * Creates a new guest user account for browsing the Economic Discussion Board
 * system. Guest users have read-only access to articles, comments, and file
 * attachments but cannot create content or post comments.
 *
 * The operation validates the guest's IP address and creates a tracking session
 * for activity monitoring and download limit enforcement. Guest accounts are
 * linked by IP address and user agent string to prevent abuse while maintaining
 * anonymous browsing capabilities.
 *
 * The system enforces download limits of 10 files per session per IP address
 * and tracks articles viewed for analytics purposes. Guest sessions expire
 * after periods of inactivity to maintain system performance.
 *
 * This endpoint requires no authentication and creates temporary guest sessions
 * that last for the duration of the browsing session. Guest users can upgrade
 * to member accounts through the standard registration process.
 *
 * @param props.connection
 * @param props.body Guest user creation information
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Guest user creation information */
    body: IEconomicDiscussionGuest.ICreate;
  };
  export type Body = IEconomicDiscussionGuest.ICreate;
  export type Response = IEconomicDiscussionGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): IEconomicDiscussionGuest.IAuthorized =>
    typia.random<IEconomicDiscussionGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

