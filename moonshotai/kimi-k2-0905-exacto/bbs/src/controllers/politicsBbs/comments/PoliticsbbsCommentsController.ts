import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getPoliticsBbsCommentsCommentId } from "../../../providers/getPoliticsBbsCommentsCommentId";

import { IPoliticsBbsComment } from "../../../api/structures/IPoliticsBbsComment";

@Controller("/politicsBbs/comments/:commentId")
export class PoliticsbbsCommentsController {
  /**
   * Get detailed information about a specific comment.
   *
   * Retrieve detailed information about a specific comment by its unique
   * identifier. This operation provides complete comment metadata including the
   * comment content, moderation status, creation timestamp, nesting level
   * within the comment thread, and actor type information indicating whether
   * the comment was posted by a visitor, member, or moderator.
   *
   * The operation supports anonymous access and returns comment information
   * based on database query results. If the comment does not exist or has been
   * deleted, appropriate error responses ensure user feedback. Special handling
   * exists for comments with different moderation statuses, providing
   * appropriate viewing permissions based on content review states.
   *
   * Comments follow a threaded structure with nesting levels 0-2, supporting up
   * to 3 levels of discussion depth. The comment system maintains polymorphic
   * ownership through subtype entities that link to the specific user type who
   * created the comment, enabling proper attribution and permission management
   * within the discussion framework.
   *
   * @param connection
   * @param commentId Unique identifier of the comment to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IPoliticsBbsComment> {
    try {
      return await getPoliticsBbsCommentsCommentId({
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
