import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postPoliticsBbsModeratorCategories } from "../../../../providers/postPoliticsBbsModeratorCategories";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putPoliticsBbsModeratorCategoriesCategoryCode } from "../../../../providers/putPoliticsBbsModeratorCategoriesCategoryCode";
import { deletePoliticsBbsModeratorCategoriesCategoryCode } from "../../../../providers/deletePoliticsBbsModeratorCategoriesCategoryCode";

import { IPoliticsBbsCategory } from "../../../../api/structures/IPoliticsBbsCategory";

@Controller("/politicsBbs/moderator/categories")
export class PoliticsbbsModeratorCategoriesController {
  /**
   * Create new discussion category.
   *
   * Creates a new discussion category with unique code and display name.
   * Categories facilitate content discoverability by organizing discussions
   * into topics like Economic Policy, International Relations, and Domestic
   * Politics.
   *
   * The category creation process validates that the code is unique across the
   * system and maps to valid category data. Only admins or moderators can
   * create new categories to maintain organizational consistency.
   *
   * This operation supports the platform's focus on economic and political
   * discourse by allowing structured categorization that helps users find
   * relevant discussions. Categories are required when creating articles,
   * ensuring that all content is properly organized and easily discoverable.
   *
   * @param connection
   * @param body Category creation information including unique code, display
   *   name, description, color, icon, sequence, and configuration flags
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticsBbsCategory.ICreate,
  ): Promise<IPoliticsBbsCategory> {
    try {
      return await postPoliticsBbsModeratorCategories({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update existing discussion category.
   *
   * Updates an existing category's properties including name, description,
   * color, icon, sequence, and configuration flags. The category is identified
   * by its unique code rather than internal ID, making URLs more readable and
   * user-friendly.
   *
   * The update process maintains referential integrity with related articles,
   * ensuring that category changes don't break existing content relationships.
   * All changes are tracked with updated_at timestamps for audit purposes.
   *
   * This operation is central to managing the discussion board's organizational
   * structure. Categories help users filter and discover relevant discussions,
   * making quality category management essential for a focused economic and
   * political discourse platform.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target category
   *   (global scope)
   * @param body Category update information including fields to modify
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryCode")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IPoliticsBbsCategory.IUpdate,
  ): Promise<IPoliticsBbsCategory> {
    try {
      return await putPoliticsBbsModeratorCategoriesCategoryCode({
        moderator,
        categoryCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a discussion category from the system.
   *
   * Remove a discussion category from the politicsBbs platform. This operation
   * permanently deletes category records that are no longer needed for
   * organizing content.
   *
   * The system validates that the requesting user has moderator privileges
   * before allowing category deletion. When a category is deleted, the system
   * handles existing articles that were assigned to this category by removing
   * the category association but preserving the articles themselves.
   *
   * Deletion is a hard delete operation that permanently removes the category
   * record from the database. There is no soft delete functionality for
   * categories in the current schema design. The operation includes proper
   * error handling for cases where the category code does not exist or when the
   * requesting user lacks appropriate permissions.
   *
   * @param connection
   * @param categoryCode Unique code identifier of the category to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryCode")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<void> {
    try {
      return await deletePoliticsBbsModeratorCategoriesCategoryCode({
        moderator,
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
