import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putPoliticsBbsModeratorModeratorContentContentIdReject } from "../../../../../../providers/putPoliticsBbsModeratorModeratorContentContentIdReject";
import { ModeratorAuth } from "../../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../../decorators/payload/ModeratorPayload";

import { IPoliticsBbsContent } from "../../../../../../api/structures/IPoliticsBbsContent";

@Controller("/politicsBbs/moderator/moderator/content/:contentId/reject")
export class PoliticsbbsModeratorModeratorContentController {
  /**
   * Reject inappropriate content with moderation reasoning.
   *
   * Reject content that violates community guidelines or platform policies.
   * This operation enables moderators to maintain content quality by rejecting
   * articles or comments that contain inappropriate material, misinformation,
   * or violate the platform's focus on economic and political discourse.
   *
   * The rejection process updates the content status to 'rejected' and triggers
   * notification to the content creator with the rejection reason. Moderators
   * must provide a clear explanation for the rejection to help users understand
   * policy violations and encourage better content creation in the future.
   *
   * This operation maintains comprehensive audit logs of all moderation
   * actions, ensuring transparency in content management decisions. The
   * rejected content becomes invisible to regular users while remaining
   * accessible to moderators for reference and potential appeals processing.
   *
   * The moderation system supports graduated responses, allowing moderators to
   * provide educational feedback rather than immediate account penalties for
   * minor violations. This approach helps build a healthier community while
   * maintaining platform standards for substantive economic and political
   * discussions.
   *
   * @param connection
   * @param contentId Unique identifier of the content (article or comment) to
   *   be rejected
   * @param body Rejection details including the reason for content rejection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async reject(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("contentId")
    contentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticsBbsContent.IReject,
  ): Promise<IPoliticsBbsContent.IRejectResponse> {
    try {
      return await putPoliticsBbsModeratorModeratorContentContentIdReject({
        moderator,
        contentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
