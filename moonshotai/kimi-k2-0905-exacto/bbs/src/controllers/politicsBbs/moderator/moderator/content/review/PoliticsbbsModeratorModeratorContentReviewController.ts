import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchPoliticsBbsModeratorModeratorContentReview } from "../../../../../../providers/patchPoliticsBbsModeratorModeratorContentReview";
import { ModeratorAuth } from "../../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../../decorators/payload/ModeratorPayload";

import { IPageIPoliticsBbsModerationReview } from "../../../../../../api/structures/IPageIPoliticsBbsModerationReview";
import { IPoliticsBbsModerationReview } from "../../../../../../api/structures/IPoliticsBbsModerationReview";

@Controller("/politicsBbs/moderator/moderator/content/review")
export class PoliticsbbsModeratorModeratorContentReviewController {
  /**
   * Get list of content pending moderator review.
   *
   * Retrieve a paginated list of content items pending moderator review,
   * including articles and comments that need approval or moderation actions.
   * This operation supports the editorial workflow by allowing moderators to
   * efficiently review content submissions and maintain community standards.
   *
   * The operation filters content based on moderation status, showing only
   * items that require review. Articles in 'pending' state appear in the review
   * queue, while comments with 'flagged' or 'pending' status require moderator
   * attention. This ensures inappropriate content is caught while legitimate
   * discussions are approved quickly.
   *
   * @param connection
   * @param body Search and filtering parameters for content review queue
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticsBbsModerationReview.IRequest,
  ): Promise<IPageIPoliticsBbsModerationReview.ISummary> {
    try {
      return await patchPoliticsBbsModeratorModeratorContentReview({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
