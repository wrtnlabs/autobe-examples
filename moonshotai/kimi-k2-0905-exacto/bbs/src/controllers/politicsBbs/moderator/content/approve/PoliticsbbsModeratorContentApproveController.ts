import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { putPoliticsBbsModeratorContentContentIdApprove } from "../../../../../providers/putPoliticsBbsModeratorContentContentIdApprove";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IPoliticsBbsContentApproval } from "../../../../../api/structures/IPoliticsBbsContentApproval";

@Controller("/politicsBbs/moderator/content/:contentId/approve")
export class PoliticsbbsModeratorContentApproveController {
  /**
   * Approve content for public visibility.
   *
   * Approve specific content item by transitioning it from pending review to
   * approved public status. This operation enables content to become visible to
   * all users once approved by a moderator.
   *
   * Upon approval, articles transition from 'pending' to 'approved' state and
   * become publicly visible in their assigned categories. Comments marked as
   * approved become visible in the discussion threads they belong to. The
   * approval process is designed to ensure quality content reaches the
   * community while inappropriate content remains in review until properly
   * vetted.
   *
   * @param connection
   * @param contentId Unique identifier of the content item to approve
   * @param body Approval confirmation and moderation notes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("contentId")
    contentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticsBbsContentApproval.ICreate,
  ): Promise<IPoliticsBbsContentApproval> {
    try {
      return await putPoliticsBbsModeratorContentContentIdApprove({
        moderator,
        contentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
