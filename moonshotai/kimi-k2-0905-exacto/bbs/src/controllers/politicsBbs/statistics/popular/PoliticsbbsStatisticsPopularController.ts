import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getPoliticsBbsStatisticsPopular } from "../../../../providers/getPoliticsBbsStatisticsPopular";

import { IPoliticsBbsPopularArticles } from "../../../../api/structures/IPoliticsBbsPopularArticles";

@Controller("/politicsBbs/statistics/popular")
export class PoliticsbbsStatisticsPopularController {
  /**
   * Retrieve popular articles based on view counts and recent engagement.
   *
   * This operation retrieves a curated list of the most popular articles from
   * the politicsBBS discussion board based on a combination of view counts,
   * recent engagement metrics, and publication recency. The system analyzes
   * article statistics to surface trending content that is currently generating
   * significant user interest and participation.
   *
   * The popularity algorithm considers multiple factors including total view
   * counts, recent view activity within the last 24-48 hours, and the recency
   * of publication to ensure both established discussions and new content with
   * emerging interest are featured. Only articles with approved status (state:
   * approved) are included to ensure quality and relevant content.
   *
   * The result set is optimized for quick discovery of high-engagement content,
   * providing users with an immediate overview of active discussions on
   * economic and political topics. This aids in community building by surfacing
   * discussions that are likely to generate further dialogue and
   * participation.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(): Promise<IPoliticsBbsPopularArticles> {
    try {
      return await getPoliticsBbsStatisticsPopular();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
