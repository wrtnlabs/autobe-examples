import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getPoliticsBbsUploadsUploadId } from "../../../providers/getPoliticsBbsUploadsUploadId";

import { IPoliticsBbsFileAttachment } from "../../../api/structures/IPoliticsBbsFileAttachment";

@Controller("/politicsBbs/uploads/:uploadId")
export class PoliticsbbsUploadsController {
  /**
   * Get uploaded file information and metadata.
   *
   * Retrieve detailed information about a specific uploaded file or image
   * attachment including metadata such as filename, file size, MIME type,
   * upload timestamp, and for images - dimensions and processing information.
   * This operation supports transparency in file handling and enables users to
   * understand what attachments are available alongside article content. The
   * response provides essential metadata without returning the actual file
   * content, which is served separately through file download endpoints.
   *
   * @param connection
   * @param uploadId Unique identifier of the uploaded attachment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @TypedParam("uploadId")
    uploadId: string & tags.Format<"uuid">,
  ): Promise<IPoliticsBbsFileAttachment> {
    try {
      return await getPoliticsBbsUploadsUploadId({
        uploadId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
