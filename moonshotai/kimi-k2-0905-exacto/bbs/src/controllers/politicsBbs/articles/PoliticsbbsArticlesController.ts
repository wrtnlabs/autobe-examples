import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchPoliticsBbsArticles } from "../../../providers/patchPoliticsBbsArticles";
import { getPoliticsBbsArticlesArticleId } from "../../../providers/getPoliticsBbsArticlesArticleId";

import { IPageIPoliticsBbsArticle } from "../../../api/structures/IPageIPoliticsBbsArticle";
import { IPoliticsBbsArticle } from "../../../api/structures/IPoliticsBbsArticle";

@Controller("/politicsBbs/articles")
export class PoliticsbbsArticlesController {
  /**
   * Search and filter articles with advanced query capabilities.
   *
   * Search and filter politicsBbs articles with advanced query capabilities.
   * This operation supports comprehensive filtering options including full-text
   * search across article titles and content, category-based filtering, date
   * range queries, and sorting options.
   *
   * The search functionality is optimized for the politicsBbs use case of
   * discussing economic and political topics. Users can filter by specific
   * categories like Economic Policy or International Relations, search within
   * article content using full-text matching, and sort results by relevance,
   * recency, or popularity based on view counts.
   *
   * The operation supports pagination to handle large result sets efficiently.
   * Results are returned as paginated summary information that includes
   * essential article metadata without full content, enabling responsive user
   * interfaces. The search engine leverages PostgreSQL's full-text search
   * capabilities with proper indexing on title and content fields for optimal
   * performance.
   *
   * @param connection
   * @param body Search and filtering parameters for article queries
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IPoliticsBbsArticle.IRequest,
  ): Promise<IPageIPoliticsBbsArticle.ISummary> {
    try {
      return await patchPoliticsBbsArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get article details with all attachments and comments.
   *
   * Retrieve complete article information including title, content, author
   * details, associated category, and related file attachments. This endpoint
   * returns the full content of an approved article with view tracking enabled.
   * The response includes nested comment threads up to 3 levels deep, providing
   * a complete discussion context for economic and political discourse on the
   * platform.
   *
   * Users can access this endpoint without authentication for public content,
   * making it the primary entry point for article consumption. The response is
   * optimized for single-article viewing with lazy-loaded attachment galleries
   * and threaded comment displays that support the evidence-based discussion
   * format required by the politics board.
   *
   * Articles that have been rejected or are in pending moderation status will
   * only be accessible to the content creator and moderators, ensuring proper
   * content quality control while maintaining transparency for valid
   * contributors.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IPoliticsBbsArticle> {
    try {
      return await getPoliticsBbsArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
