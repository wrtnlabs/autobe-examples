import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getPoliticsBbsArticlesArticleIdSnapshots } from "../../../../providers/getPoliticsBbsArticlesArticleIdSnapshots";

import { IPageIPoliticsBbsArticleSnapshot } from "../../../../api/structures/IPageIPoliticsBbsArticleSnapshot";

@Controller("/politicsBbs/articles/:articleId/snapshots")
export class PoliticsbbsArticlesSnapshotsController {
  /**
   * Retrieve historical snapshots of a politics discussion article.
   *
   * This operation retrieves all historical snapshots associated with a
   * specific politics discussion board article. Snapshots capture the complete
   * state of an article at crucial transition points, including title, content,
   * lifecycle state information, and view count data when state changes
   * occurred.
   *
   * The snapshots serve as a critical audit trail for tracking political
   * discourse evolution, enabling users to review the progression of economic
   * discussions and policy debates over time. This functionality supports
   * content integrity protection by maintaining immutable historical records of
   * article modifications throughout the discussion lifecycle.
   *
   * By providing chronological access to article state changes, the system
   * enables content moderation teams to understand discussion development
   * patterns, review major content modifications, and maintain accountability
   * for political discourse standards. The historical tracking is essential for
   * measuring content quality evolution and maintaining credibility of economic
   * and political policy discussions on the platform.
   *
   * This operation maintains transparency by allowing public inspection of
   * article modification history while preserving the original discussion
   * context that shaped political and economic policy debates on the platform.
   *
   * @param connection
   * @param articleId Unique identifier of the target politics discussion
   *   article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IPageIPoliticsBbsArticleSnapshot> {
    try {
      return await getPoliticsBbsArticlesArticleIdSnapshots({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
