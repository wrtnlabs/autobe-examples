import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deletePoliticsBbsMemberCommentsCommentId } from "../../../../providers/deletePoliticsBbsMemberCommentsCommentId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

@Controller("/politicsBbs/member/comments/:commentId")
export class PoliticsbbsMemberCommentsController {
  /**
   * Soft delete a member's own comment.
   *
   * Marks a comment as deleted by setting the deleted_at timestamp while
   * preserving its content and related data. This operation can only be
   * performed on comments where the authenticated member is the original author
   * through the member-specific comment subtype relationship. The comment
   * remains in the system with soft deletion status for audit purposes.
   *
   * The operation validates comment ownership through the polymorphic comment
   * system, ensuring members can only delete their own contributions and not
   * comments from visitors or other actors. It handles cleanup of presentation
   * flags while preserving audit trail information including creation
   * timestamp, content, and moderation history.
   *
   * This soft-delete approach maintains conversation integrity among threaded
   * discussions while allowing content removal for the original author. The
   * operation integrates with the member-specific comment management system
   * through proper subtype relationships.
   *
   * @param connection
   * @param commentId Unique identifier of the member's comment to be soft
   *   deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deletePoliticsBbsMemberCommentsCommentId({
        member,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
