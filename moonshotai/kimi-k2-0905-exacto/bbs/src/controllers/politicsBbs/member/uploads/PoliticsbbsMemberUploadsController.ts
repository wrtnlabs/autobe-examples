import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postPoliticsBbsMemberUploads } from "../../../../providers/postPoliticsBbsMemberUploads";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

import { IPoliticsBbsUpload } from "../../../../api/structures/IPoliticsBbsUpload";

@Controller("/politicsBbs/member/uploads")
export class PoliticsbbsMemberUploadsController {
  /**
   * Upload image or document attachments for articles.
   *
   * Handle file uploads for the politicsBBS discussion board supporting both
   * image and document attachments. The upload process includes comprehensive
   * validation to ensure file safety and compliance with platform
   * requirements.
   *
   * For image uploads, the system accepts JPEG, PNG, and GIF formats with a
   * maximum file size of 5MB per image. Images are automatically processed to
   * generate thumbnails and optimized versions for web display. The system
   * allows up to 10 images per article and maintains proper aspect ratios while
   * creating responsive versions for mobile devices.
   *
   * Document uploads support PDF, DOC, DOCX, and TXT formats with a maximum
   * size of 10MB per file. Users can attach up to 5 documents per article. All
   * uploaded files undergo malware scanning and content validation before being
   * accepted. The system generates preview thumbnails for supported document
   * types and stores files with secure access controls.
   *
   * File uploads are associated with the authenticated user's account and
   * maintain proper audit trails. The operation returns file metadata including
   * unique identifiers, file paths, and processing status that can be used when
   * creating or editing articles to attach the uploaded files.
   *
   * @param connection
   * @param body File upload data including the file content and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IPoliticsBbsUpload.ICreate,
  ): Promise<IPoliticsBbsUpload> {
    try {
      return await postPoliticsBbsMemberUploads({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
