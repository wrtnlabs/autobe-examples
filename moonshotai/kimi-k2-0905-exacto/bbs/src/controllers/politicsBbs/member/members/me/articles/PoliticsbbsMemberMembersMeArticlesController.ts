import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getPoliticsBbsMemberMembersMeArticles } from "../../../../../../providers/getPoliticsBbsMemberMembersMeArticles";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";

import { IPoliticsBbsArticle } from "../../../../../../api/structures/IPoliticsBbsArticle";

@Controller("/politicsBbs/member/members/me/articles")
export class PoliticsbbsMemberMembersMeArticlesController {
  /**
   * Get current member's created articles with statistics.
   *
   * Retrieve a comprehensive list of articles created by the currently
   * authenticated member. This operation provides members with visibility into
   * their content creation history, including all articles they've published on
   * the politics discussion board platform.
   *
   * The response includes detailed information about each article such as
   * title, creation date, current status (draft, pending, approved, rejected),
   * view count statistics, and associated category information. Members can use
   * this data to track their engagement levels and understand which topics
   * generate the most discussion within the community.
   *
   * This operation supports the member dashboard functionality, enabling users
   * to manage their content portfolio and identify their most successful
   * contributions to economic and political discourse. The information helps
   * members understand their impact on community discussions and identify
   * opportunities for more engaging content creation.
   *
   * The system maintains privacy by ensuring members can only access their own
   * article data, preventing unauthorized viewing of other users' content
   * creation patterns. This self-service approach reduces support overhead
   * while empowering members with comprehensive analytics about their platform
   * contributions.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPoliticsBbsArticle.ISummaryList> {
    try {
      return await getPoliticsBbsMemberMembersMeArticles({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
