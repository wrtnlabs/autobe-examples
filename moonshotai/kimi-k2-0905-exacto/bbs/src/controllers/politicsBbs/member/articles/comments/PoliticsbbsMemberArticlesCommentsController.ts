import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postPoliticsBbsMemberArticlesArticleIdComments } from "../../../../../providers/postPoliticsBbsMemberArticlesArticleIdComments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IPoliticsBbsComment } from "../../../../../api/structures/IPoliticsBbsComment";

@Controller("/politicsBbs/member/articles/:articleId/comments")
export class PoliticsbbsMemberArticlesCommentsController {
  /**
   * Create a new comment on an article.
   *
   * Create a new comment on a politicsBBS article with support for threaded
   * discussions and user authentication. This operation validates comment
   * content (minimum 20 characters, maximum 1000 characters), determines the
   * appropriate nesting level for replies, and associates the comment with the
   * authenticated user making the request.
   *
   * The comment system supports threading with up to 3 levels of nesting depth.
   * When creating a reply to an existing comment, the system calculates the
   * appropriate depth level and validates against the maximum nesting
   * constraint. Comments maintain polymorphic ownership patterns where
   * different user types (visitors, members, moderators) create comments
   * through dedicated subtype relationships.
   *
   * Content validation ensures comments provide meaningful dialogue while
   * preventing spam and inappropriate content. The operation creates the base
   * comment entity and associated subtype entity based on the user's role type,
   * maintaining proper referential integrity. On successful creation, the
   * system returns the complete comment information including generated IDs and
   * timestamps.
   *
   * Comments are initially created with 'pending' status by default, which
   * moderators can then approve for publication, ensuring quality control over
   * the discussion content while maintaining quick user feedback during the
   * posting process.
   *
   * @param connection
   * @param articleId Unique identifier of the article where the comment should
   *   be created
   * @param body Comment creation parameters including content and optional
   *   parent comment for threading
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticsBbsComment.ICreate,
  ): Promise<IPoliticsBbsComment> {
    try {
      return await postPoliticsBbsMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
