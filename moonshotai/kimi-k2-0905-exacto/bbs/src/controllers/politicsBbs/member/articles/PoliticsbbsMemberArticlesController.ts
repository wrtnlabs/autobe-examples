import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postPoliticsBbsMemberArticles } from "../../../../providers/postPoliticsBbsMemberArticles";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putPoliticsBbsMemberArticlesArticleId } from "../../../../providers/putPoliticsBbsMemberArticlesArticleId";
import { deletePoliticsBbsMemberArticlesArticleId } from "../../../../providers/deletePoliticsBbsMemberArticlesArticleId";

import { IPoliticsBbsArticle } from "../../../../api/structures/IPoliticsBbsArticle";

@Controller("/politicsBbs/member/articles")
export class PoliticsbbsMemberArticlesController {
  /**
   * Create a new article with attachments.
   *
   * Submit a new article to the politics discussion board with support for
   * images and file attachments. This endpoint handles the complete article
   * creation workflow including title validation (5-150 characters), content
   * validation (minimum 50 characters), category assignment, and file upload
   * processing within size limits.
   *
   * The operation enforces business rules including a 5MB maximum for image
   * files and 10MB maximum for document files, with automatic scanning for
   * prohibited content types. Articles are created in 'pending' state by
   * default and require moderator approval before public visibility,
   * maintaining content quality standards for the economic and political
   * discussion platform.
   *
   * Members can create content immediately upon successful authentication, with
   * the system tracking the creator relationship for 24-hour editing permission
   * and ownership rights. The response returns the created article details
   * including assigned unique identifier and preliminary attachment information
   * while files process asynchronously in the background.
   *
   * @param connection
   * @param body Article creation data including title, content, category
   *   selection, and optional attachments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IPoliticsBbsArticle.ICreate,
  ): Promise<IPoliticsBbsArticle> {
    try {
      return await postPoliticsBbsMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing article with new content.
   *
   * This operation allows authenticated members to update articles they have
   * previously created. Users can modify the article title, content text, and
   * category assignment. The system enforces a 24-hour editing window from the
   * original creation time to maintain content integrity and prevent abuse.
   * Upon successful update, the system creates an article snapshot to preserve
   * the previous version for audit purposes and updates the modification
   * timestamp. The operation validates that the requesting user matches the
   * original article creator and maintains all business rules including minimum
   * content length requirements and category validity. This ensures that users
   * can correct errors or improve their content while maintaining historical
   * records for accountability and potential moderation needs.
   *
   * @param connection
   * @param articleId Unique identifier of the article to be updated
   * @param body Updated article information including title, content, and
   *   category ID
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IPoliticsBbsArticle.IUpdate,
  ): Promise<IPoliticsBbsArticle> {
    try {
      return await putPoliticsBbsMemberArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently delete an existing article.
   *
   * This operation removes an article from the public discussion board while
   * preserving it for audit trail purposes through the soft delete mechanism.
   * When an article is deleted, the system removes all associated content
   * including comments (which are cascade deleted through parent-child
   * relationships), file attachments, and image attachments. The operation
   * validates that the requesting user is the original creator of the article
   * or has moderator privileges to delete articles for policy violations. The
   * deleted_at timestamp is set to mark the record as deleted while maintaining
   * all historical data for potential recovery or investigation purposes. This
   * approach ensures data integrity and provides a safety net for accidental
   * deletions while maintaining the clean separation between active and removed
   * content.
   *
   * @param connection
   * @param articleId Unique identifier of the article to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deletePoliticsBbsMemberArticlesArticleId({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
