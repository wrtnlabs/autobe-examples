import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchPoliticsBbsCategories } from "../../../providers/patchPoliticsBbsCategories";
import { getPoliticsBbsCategoriesCategoryCode } from "../../../providers/getPoliticsBbsCategoriesCategoryCode";

import { IPageIPoliticsBbsCategory } from "../../../api/structures/IPageIPoliticsBbsCategory";
import { IPoliticsBbsCategory } from "../../../api/structures/IPoliticsBbsCategory";

@Controller("/politicsBbs/categories")
export class PoliticsbbsCategoriesController {
  /**
   * Search and retrieve filtered politics discussion categories.
   *
   * Retrieve a filtered list of political discussion categories with support
   * for complex search queries, sorting by sequence or name, and filtering by
   * primary categories. Categories are predefined by moderators and include
   * economic policy, political analysis, international relations, domestic
   * politics, fiscal policy, and other economic/political discussion topics.
   *
   * The system enforces that economic and political discussions remain focused
   * on substantive topics, avoiding personal attacks while encouraging
   * evidence-based arguments. Categories provide the primary organizational
   * structure for content discovery and navigation within the discussion board
   * platform.
   *
   * This operation supports pagination with configurable page sizes and
   * multiple sorting options including alphabetical, creation date, and display
   * sequence. Users can filter by primary categories for featured content or
   * view secondary categories for expanded discussion topics. The response
   * includes category metadata such as color codes, icons, and multiplicative
   * settings for proper category assignment.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for category
   *   filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IPoliticsBbsCategory.IRequest,
  ): Promise<IPageIPoliticsBbsCategory.ISummary> {
    try {
      return await patchPoliticsBbsCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information about a specific politics discussion category.
   *
   * Retrieve detailed information about a specific political discussion
   * category using its unique code identifier. Categories are identified by
   * custom-defined codes that serve as the primary reference in URLs and user
   * interfaces.
   *
   * Categories organize discussions into logical groups including Economic
   * Policy, Political Analysis, International Relations, Local Policy Debate,
   * Domestic Politics, and other economic/political topics. Each category
   * contains metadata about display order, visual styling (colors and icons),
   * and assignment rules (single vs. multiple category selection).
   *
   * The category system supports both primary featured categories highlighted
   * for prominence and secondary categories for broader content organization.
   * Users can browse by category to find relevant discussions, and category
   * pages provide filtering capabilities for content discovery within specific
   * political or economic focus areas.
   *
   * @param connection
   * @param categoryCode Unique code identifier of the politics discussion
   *   category
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryCode")
  public async at(
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IPoliticsBbsCategory> {
    try {
      return await getPoliticsBbsCategoriesCategoryCode({
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
