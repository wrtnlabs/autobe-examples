import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchPoliticsBbsSearchArticles } from "../../../../providers/patchPoliticsBbsSearchArticles";

import { IPageIPoliticsBbsArticle } from "../../../../api/structures/IPageIPoliticsBbsArticle";
import { IPoliticsBbsArticle } from "../../../../api/structures/IPoliticsBbsArticle";

@Controller("/politicsBbs/search/articles")
export class PoliticsbbsSearchArticlesController {
  /**
   * Search and filter articles with advanced query parameters and sorting.
   *
   * This operation enables advanced search and filtering across the politicsBBS
   * article content, providing users with comprehensive discovery capabilities
   * beyond simple category browsing. The system accepts complex search
   * parameters including keyword queries, category filters, date ranges, and
   * sorting preferences to deliver highly targeted article results.
   *
   * The search implementation supports both title-only queries and full-content
   * searches using PostgreSQL's text search capabilities with trigram indexing.
   * Users can filter results by specific categories (Economic Policy, Political
   * Analysis, International Relations, etc.) to focus on topics of interest.
   * Date filtering allows discovery of recent content or historical
   * perspectives within specified timeframes.
   *
   * The operation supports multiple sorting options including chronological
   * order (newest first), relevance ranking for keyword searches, and
   * popularity ordering based on view counts. Pagination delivers results in
   * manageable chunks while maintaining search context and filter state across
   * page requests.
   *
   * Advanced search parameters accommodate power users who need sophisticated
   * filtering options such as minimum view counts, specific author filtering,
   * or exact phrase matching. The system maintains search history for
   * authenticated members and allows saved searches for frequently used
   * queries.
   *
   * The search results include rich metadata for each article including
   * creation timestamps, view counts, comment counts, category assignments, and
   * author information to aid in content evaluation without requiring
   * additional data requests.
   *
   * @param connection
   * @param body Search criteria including keywords, category filters, date
   *   range, sorting options, and pagination parameters for advanced article
   *   discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IPoliticsBbsArticle.IRequest,
  ): Promise<IPageIPoliticsBbsArticle.ISummary> {
    try {
      return await patchPoliticsBbsSearchArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
