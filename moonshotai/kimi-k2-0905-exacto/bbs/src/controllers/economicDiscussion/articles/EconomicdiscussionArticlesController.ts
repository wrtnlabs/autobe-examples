import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconomicDiscussionArticles } from "../../../providers/patchEconomicDiscussionArticles";
import { getEconomicDiscussionArticlesArticleId } from "../../../providers/getEconomicDiscussionArticlesArticleId";

import { IPageIEconomicDiscussionArticle } from "../../../api/structures/IPageIEconomicDiscussionArticle";
import { IEconomicDiscussionArticle } from "../../../api/structures/IEconomicDiscussionArticle";

@Controller("/economicDiscussion/articles")
export class EconomicdiscussionArticlesController {
  /**
   * Search and retrieve filtered, paginated list of economic discussion
   * articles.
   *
   * Search and retrieve economic discussion articles with advanced filtering
   * and pagination capabilities. This operation enables users to discover
   * relevant economic and political discussion content through comprehensive
   * search mechanisms.
   *
   * The search functionality supports content filtering by status, categories,
   * authors, and date ranges. Users can filter by multiple categories
   * simultaneously and search within specific author scopes. Status filtering
   * enables finding articles in different workflow states including pending,
   * approved, and rejected content.
   *
   * Pagination is implemented with configurable page sizes and offset-based
   * navigation. Results can be sorted by creation date, view count, title, and
   * other relevant criteria. Each article summary includes essential
   * information for content discovery including title, author details, category
   * assignments, view statistics, and current status.
   *
   * This operation serves as the primary content discovery mechanism for the
   * economic discussion platform, supporting both casual browsing and targeted
   * research for economic analysis.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for article discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicDiscussionArticle.IRequest,
  ): Promise<IPageIEconomicDiscussionArticle.ISummary> {
    try {
      return await patchEconomicDiscussionArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information for a single economic discussion article.
   *
   * Retrieve complete information for a specific economic discussion article by
   * its unique identifier. This operation provides the full article content
   * along with all associated metadata including author details,
   * categorization, file attachments, and engagement metrics like view counts.
   *
   * The response includes the article's current status (pending, approved, or
   * rejected) which determines visibility permissions. Only approved articles
   * are publicly accessible by default, while pending or rejected articles
   * require appropriate authorization levels.
   *
   * File attachments are included with their metadata (filename, file type,
   * size) and security scanning status. The system automatically filters out
   * attachments that haven't completed security scanning or have been flagged
   * as potentially unsafe.
   *
   * This operation increments the article's view count to track engagement and
   * popularity. View counts are updated in real-time and help surface popular
   * content in recommendation algorithms.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article to
   *   retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":articleId")
  public async at(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionArticle> {
    try {
      return await getEconomicDiscussionArticlesArticleId({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
