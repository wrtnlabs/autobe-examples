import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconomicDiscussionArticlesArticleIdComments } from "../../../../providers/getEconomicDiscussionArticlesArticleIdComments";
import { patchEconomicDiscussionArticlesArticleIdComments } from "../../../../providers/patchEconomicDiscussionArticlesArticleIdComments";
import { putEconomicDiscussionArticlesArticleIdCommentsCommentId } from "../../../../providers/putEconomicDiscussionArticlesArticleIdCommentsCommentId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteEconomicDiscussionArticlesArticleIdCommentsCommentId } from "../../../../providers/deleteEconomicDiscussionArticlesArticleIdCommentsCommentId";

import { IPageIEconomicDiscussionComment } from "../../../../api/structures/IPageIEconomicDiscussionComment";
import { IEconomicDiscussionComment } from "../../../../api/structures/IEconomicDiscussionComment";

@Controller("/economicDiscussion/articles/:articleId/comments")
export class EconomicdiscussionArticlesCommentsController {
  /**
   * Get all comments for a specific economic discussion article.
   *
   * Get a comprehensive list of all comments posted on a specific economic and
   * political discussion article. This operation provides read-only access to
   * the article's discussion thread, returning comment content, author
   * information, and discussion timestamps.
   *
   * The operation returns comment data in a format optimized for article
   * display, including threaded discussion structure when applicable. Each
   * comment contains the full text content, author's display name, creation
   * timestamp, and any relevant metadata that helps readers follow the
   * conversation flow.
   *
   * The GET method makes this endpoint easily cacheable and suitable for public
   * access, supporting efficient article page loading with integrated comment
   * display. The response format is designed for direct integration into
   * article view interfaces.
   *
   * @param connection
   * @param articleId Unique identifier of the target economic discussion
   *   article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IPageIEconomicDiscussionComment.ISummary> {
    try {
      return await getEconomicDiscussionArticlesArticleIdComments({
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Search and retrieve paginated comments for a specific economic discussion
   * article.
   *
   * Retrieve all comments associated with a specific economic and political
   * discussion article. This operation returns a paginated list of comments
   * with essential information including comment content, author details,
   * creation timestamp, and comment hierarchy for threaded discussions.
   *
   * The operation supports standard pagination parameters to efficiently load
   * comment data. Each comment includes the author's username and basic profile
   * information, allowing readers to understand the discussion context and
   * participant identities.
   *
   * Results are ordered by creation date (newest first) to show the most recent
   * discussion activity. The pagination system helps manage large comment
   * threads efficiently, preventing performance issues with articles that have
   * extensive discussion history.
   *
   * @param connection
   * @param articleId Unique identifier of the target economic discussion
   *   article
   * @param body Pagination and filtering parameters for retrieving article
   *   comments
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionComment.IRequest,
  ): Promise<IPageIEconomicDiscussionComment.ISummary> {
    try {
      return await patchEconomicDiscussionArticlesArticleIdComments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing comment on an economic discussion article.
   *
   * This operation allows authenticated economic discussion members to edit
   * their own comments on articles within the political discussion platform.
   * The update process maintains content integrity while providing users the
   * ability to correct errors, clarify statements, or extend their thoughts.
   *
   * The operation validates that the requesting member is the original author
   * of the comment to prevent unauthorized modifications. Upon successful
   * update, it creates a new entry in the comment versions table to preserve
   * the edit history. The article ID in the path ensures the comment belongs to
   * the specified discussion article.
   *
   * Security considerations include rate limiting to prevent abuse and content
   * validation based on business rules defined in the platform. The edit
   * history is preserved for transparency and potential moderation purposes.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   *   containing the comment
   * @param commentId Unique identifier of the specific comment to be updated
   * @param body Updated comment content and metadata for the economic
   *   discussion article comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionComment.IUpdate,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await putEconomicDiscussionArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft delete comment from economic discussion article.
   *
   * This operation enables deletion of comments from economic and political
   * discussion articles on the platform. Members can delete their own comments
   * to remove content they no longer wish to share, while moderators have
   * broader permissions to remove any content that violates community
   * guidelines.
   *
   * The system implements soft deletion using the deleted_at field in the
   * database schema. Deleted comments remain in the database with a deleted_at
   * timestamp but are hidden from user views. This approach preserves the
   * conversation flow and prevents broken references in nested comment
   * discussions. The deleted_at field in the schema controls this soft delete
   * behavior.
   *
   * The operation requires both article ID and comment ID parameters to ensure
   * the comment being removed belongs to the specified article. Authentication
   * is required to verify comment ownership for regular members and moderator
   * privileges for administrative actions.
   *
   * Content moderation benefits from this traceable deletion system, allowing
   * moderators to review deletion patterns and maintain discussion quality. The
   * soft-delete approach enables potential restoration of inappropriately
   * removed content.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   *   containing the comment to delete
   * @param commentId Unique identifier of the specific comment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await deleteEconomicDiscussionArticlesArticleIdCommentsCommentId({
        member,
        articleId,
        commentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
