import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconomicDiscussionArticlesArticleIdAttachments } from "../../../../providers/patchEconomicDiscussionArticlesArticleIdAttachments";

import { IPageIEconomicDiscussionAttachment } from "../../../../api/structures/IPageIEconomicDiscussionAttachment";
import { IEconomicDiscussionAttachment } from "../../../../api/structures/IEconomicDiscussionAttachment";

@Controller("/economicDiscussion/articles/:articleId/attachments")
export class EconomicdiscussionArticlesAttachmentsController {
  /**
   * This operation retrieves all file attachments associated with a specific
   * economic discussion article. It returns a paginated list of attachment
   * metadata including filename, file size, MIME type, upload timestamp, and
   * security scan status.
   *
   * The operation supports filtering by file type categories (image, document,
   * spreadsheet) to help users find specific attachment types. All attachments
   * inherit the same visibility permissions as their parent article - if the
   * article is publicly accessible, attachments are visible to all users; if
   * the article requires member access, only authenticated members can view
   * attachments.
   *
   * Security scanning status is included to indicate whether files have
   * completed the mandatory virus scanning process required by the platform.
   * Attachments are automatically removed when their associated article is
   * deleted, maintaining data consistency and preventing orphaned attachment
   * records.
   *
   * The response includes essential metadata for file attachment UI display and
   * download preparation, excluding the actual file content which is delivered
   * through separate download endpoints.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   * @param body Search and filtering parameters for attachment listing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionAttachment.IRequest,
  ): Promise<IPageIEconomicDiscussionAttachment.ISummary> {
    try {
      return await patchEconomicDiscussionArticlesArticleIdAttachments({
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
