import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconomicDiscussionMemberMembersMemberId } from "../../../../providers/getEconomicDiscussionMemberMembersMemberId";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putEconomicDiscussionMemberMembersMemberId } from "../../../../providers/putEconomicDiscussionMemberMembersMemberId";

import { IEconomicDiscussionMember } from "../../../../api/structures/IEconomicDiscussionMember";

@Controller("/economicDiscussion/member/members/:memberId")
export class EconomicdiscussionMemberMembersController {
  /**
   * Retrieve comprehensive member profile information including username, email
   * verification status, account creation date, reputation score, and member
   * account status. This operation provides essential member data for profile
   * display, community interaction, and administrative oversight.
   *
   * The response includes member's community participation metrics such as
   * total article count, comment count, and reputation score calculated based
   * on activity within the economic discussion community. The reputation score
   * reflects the member's engagement level and contributes to their ranking and
   * feature access within the platform.
   *
   * This operation serves as the primary mechanism for profile retrieval,
   * enabling both members to view their own accounts and moderators to access
   * member information for community management purposes. The detailed profile
   * data supports user experience personalization and community feature
   * implementations.
   *
   * @param connection
   * @param memberId Unique identifier pointing to the specific economic
   *   discussion member
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionMember> {
    try {
      return await getEconomicDiscussionMemberMembersMemberId({
        member,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Allow authenticated members to update their profile information including
   * username, email preferences, and other account details within the defined
   * editing windows and permission constraints specified for the economic
   * discussion platform.
   *
   * The update process validates that the requesting member has appropriate
   * permissions to modify the target profile. Members can only edit their own
   * profiles to maintain account security while moderators may have elevated
   * permissions for community management purposes. The operation enforces the
   * content editing time constraints where profile updates are permitted within
   * the community governance framework.
   *
   * Profile updates are processed with field-level validation including
   * username uniqueness checks, email format validation, and adherence to
   * community policies for the economic and political discussion environment.
   * The operation maintains audit trails of profile changes for transparency
   * and moderation oversight within the platform.
   *
   * @param connection
   * @param memberId Unique identifier pointing to the specific economic
   *   discussion member to update
   * @param body Updated member profile data with username and email changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionMember.IUpdate,
  ): Promise<IEconomicDiscussionMember> {
    try {
      return await putEconomicDiscussionMemberMembersMemberId({
        member,
        memberId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
