import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionMemberSearchCategoriesCategoryCode } from "../../../../../providers/patchEconomicDiscussionMemberSearchCategoriesCategoryCode";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";

import { IPageIEconomicDiscussionArticle } from "../../../../../api/structures/IPageIEconomicDiscussionArticle";
import { IEconomicDiscussionArticle } from "../../../../../api/structures/IEconomicDiscussionArticle";

@Controller("/economicDiscussion/member/search/categories/:categoryCode")
export class EconomicdiscussionMemberSearchCategoriesController {
  /**
   * Search and filter articles within a specific discussion category.
   *
   * Perform advanced search queries across economic and political discussion
   * articles filtered by category code. This operation enables users to find
   * relevant content within specific topic areas using text-based searches
   * across article titles and content.
   *
   * The search functionality leverages database indexing for optimal
   * performance, supporting partial text matching starting from 2 characters.
   * Users can combine search terms with additional filters like article status,
   * creation date ranges, and sorting preferences. The system automatically
   * applies permission-based filtering to show only approved articles to
   * general users and all statuses to moderators.
   *
   * Pagination is supported with configurable page sizes and sorting options.
   * Results include article summaries optimized for list display, showing
   * curated excerpts that highlight relevant search terms. Engagement metrics
   * like view counts and comment numbers help users identify popular and active
   * discussions.
   *
   * Search queries are automatically tracked in the search history tables for
   * logged-in users and aggregated in the search queries table for
   * platform-wide analytics.
   *
   * @param connection
   * @param categoryCode Unique category code identifier for filtering articles
   *   within a specific discussion category. Must correspond to an active
   *   category from economic_discussion_categories.code.
   * @param body Search criteria and pagination parameters for category-specific
   *   article filtering
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IEconomicDiscussionArticle.IRequest,
  ): Promise<IPageIEconomicDiscussionArticle.ISummary> {
    try {
      return await patchEconomicDiscussionMemberSearchCategoriesCategoryCode({
        member,
        categoryCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
