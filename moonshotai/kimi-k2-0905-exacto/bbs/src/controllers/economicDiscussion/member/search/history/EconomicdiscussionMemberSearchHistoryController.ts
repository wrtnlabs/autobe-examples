import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getEconomicDiscussionMemberSearchHistory } from "../../../../../providers/getEconomicDiscussionMemberSearchHistory";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteEconomicDiscussionMemberSearchHistory } from "../../../../../providers/deleteEconomicDiscussionMemberSearchHistory";

import { IPageIEconomicDiscussionSearchHistory } from "../../../../../api/structures/IPageIEconomicDiscussionSearchHistory";

@Controller("/economicDiscussion/member/search/history")
export class EconomicdiscussionMemberSearchHistoryController {
  /**
   * Retrieves the authenticated member's personal search history from the
   * Economic Discussion Board platform. This operation returns a
   * chronologically ordered list of all searches performed by the currently
   * logged-in member, including the search query text, execution timestamp, and
   * related search analytics data.
   *
   * The search history enables members to quickly access and re-execute
   * previous searches, track their research patterns, and discover content
   * they've previously explored. Each search history entry includes the actual
   * query text entered by the user and links to the related search query
   * metadata in the master search queries table.
   *
   * Permission validation ensures only the authenticated member can access
   * their own search history, with proper session verification and ownership
   * validation. The operation leverages the foreign key relationships to
   * economic_discussion_members (member_id), economic_discussion_search_queries
   * (query_id), and includes access to frequency data, result counts, and
   * average click positions from the master query table for enhanced user
   * experience.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async index(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IPageIEconomicDiscussionSearchHistory> {
    try {
      return await getEconomicDiscussionMemberSearchHistory({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes search history entries for authenticated members of the
   * Economic Discussion Board platform. Members can delete individual search
   * entries or clear their entire search history to maintain privacy control
   * and manage their research patterns.
   *
   * The operation provides flexible deletion options allowing members to remove
   * sensitive searches, clear outdated queries, or reset their complete search
   * history. This supports user privacy requirements and enables members to
   * manage their digital footprint within the discussion board platform.
   *
   * Permission validation ensures only the authenticated member can delete
   * their own search history entries, with proper session verification and
   * ownership verification. The operation references the member authentication
   * from JWT tokens and validates that the search history being deleted belongs
   * to the current member.
   *
   * This feature supports the member user workflow requirements for content
   * management and privacy control, allowing users to maintain control over
   * their search patterns and historical data within the economic discussion
   * community platform.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<void> {
    try {
      return await deleteEconomicDiscussionMemberSearchHistory({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
