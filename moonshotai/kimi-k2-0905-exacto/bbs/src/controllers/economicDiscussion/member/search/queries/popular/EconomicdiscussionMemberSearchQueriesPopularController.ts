import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getEconomicDiscussionMemberSearchQueriesPopular } from "../../../../../../providers/getEconomicDiscussionMemberSearchQueriesPopular";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";

import { IEconomicDiscussionArticle } from "../../../../../../api/structures/IEconomicDiscussionArticle";

@Controller("/economicDiscussion/member/search/queries/popular")
export class EconomicdiscussionMemberSearchQueriesPopularController {
  /**
   * Retrieve popular search queries from the platform.
   *
   * Access platform-wide search analytics to discover trending topics and
   * popular content areas in economic and political discussions. This operation
   * surfaces queries that demonstrate high community engagement, useful result
   * quality, and strong search performance metrics.
   *
   * The algorithm prioritizes queries with high total frequency counts,
   * indicating broad community interest in specific topics. Only queries with
   * recent activity (within 30 days) are included to ensure relevance.
   * Additional weight is given to queries with quality metrics such as average
   * click positions below 5 (indicating users found relevant results in the top
   * positions) and result counts above 3 (ensuring meaningful content
   * discovery).
   *
   * Results are ordered by frequency and filtered to exclude test queries,
   * spam, or low-engagement searches. The ranking considers both absolute
   * popularity and recent momentum, helping identify emerging discussion topics
   * alongside established subject matter.
   *
   * This information aids content creators in identifying community interests
   * and users in discovering popular discussion areas. The data excludes
   * sensitive queries and personal searches to maintain privacy while providing
   * valuable community insights.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async popularQueries(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IEconomicDiscussionArticle.ISummary> {
    try {
      return await getEconomicDiscussionMemberSearchQueriesPopular({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
