import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicDiscussionMemberArticles } from "../../../../providers/postEconomicDiscussionMemberArticles";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putEconomicDiscussionMemberArticlesArticleId } from "../../../../providers/putEconomicDiscussionMemberArticlesArticleId";
import { deleteEconomicDiscussionMemberArticlesArticleId } from "../../../../providers/deleteEconomicDiscussionMemberArticlesArticleId";

import { IEconomicDiscussionArticle } from "../../../../api/structures/IEconomicDiscussionArticle";

@Controller("/economicDiscussion/member/articles")
export class EconomicdiscussionMemberArticlesController {
  /**
   * Create a new economic discussion article with comprehensive content and
   * metadata. This operation allows authenticated users to publish economic
   * insights, political analysis, and policy discussions on the platform.
   *
   * Article creation requires a valid title and content body with minimum
   * length requirements. The title should clearly indicate the discussion topic
   * or question being addressed. Content must meet platform guidelines and will
   * undergo moderation review before public visibility.
   *
   * The operation automatically sets the initial article version to 1.0 and
   * assigns a pending status for moderation review. View count is initialized
   * to zero and will increment as users access the article after approval.
   *
   * File attachments can be associated with the article through separate API
   * calls after creation. The article can be categorized immediately upon
   * creation or categories can be added later through the article-category
   * relationship endpoints.
   *
   * @param connection
   * @param body Article creation data including title, content, and initial
   *   categorization
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconomicDiscussionArticle.ICreate,
  ): Promise<IEconomicDiscussionArticle> {
    try {
      return await postEconomicDiscussionMemberArticles({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing economic/political discussion article.
   *
   * Update an economic or political discussion article with new title and
   * content. This operation allows article authors to refine their analysis,
   * correct factual information, or improve discussion quality while
   * maintaining version history for transparency.
   *
   * The update functionality includes automatic version number incrementing (by
   * 0.1) to track edit history. Content undergoes the same moderation screening
   * as new articles to maintain community standards. If updated content
   * contains policy-violating material, the article status may change to
   * pending for moderator review.
   *
   * Authors receive immediate feedback on their changes, with update
   * confirmation and any status changes displayed promptly. The system
   * validates content length requirements similar to article creation. After
   * the initial edit window expires, only moderators can modify articles
   * through administrative functions.
   *
   * Related operations include article creation (POST /articles) and detailed
   * article retrieval (GET /articles/{articleId}).
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article to
   *   update
   * @param body Updated article information including new title, content, and
   *   version tracking
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":articleId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionArticle.IUpdate,
  ): Promise<IEconomicDiscussionArticle> {
    try {
      return await putEconomicDiscussionMemberArticlesArticleId({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an economic/political discussion article.
   *
   * Remove an economic or political discussion article from the system. Article
   * authors can delete their own content within the designated editing window,
   * or moderators can remove content that violates community guidelines. The
   * operation handles associated data cleanup according to system
   * configuration.
   *
   * Deletion rights are restricted to prevent abuse: article authors can delete
   * their own content within the designated editing window, while moderators
   * have authority to remove any content for community management purposes.
   *
   * This operation provides confirmation of successful removal and updates
   * related entities to reflect the change
   *
   * Related operations include article creation (POST /articles) and list
   * retrieval (PATCH /articles).
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article to
   *   delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":articleId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionArticle> {
    try {
      return await deleteEconomicDiscussionMemberArticlesArticleId({
        member,
        articleId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
