import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconomicDiscussionMemberArticlesArticleIdVersions } from "../../../../../providers/patchEconomicDiscussionMemberArticlesArticleIdVersions";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getEconomicDiscussionMemberArticlesArticleIdVersionsVersionId } from "../../../../../providers/getEconomicDiscussionMemberArticlesArticleIdVersionsVersionId";

import { IPageIEconomicDiscussionArticleVersion } from "../../../../../api/structures/IPageIEconomicDiscussionArticleVersion";
import { IEconomicDiscussionArticleVersion } from "../../../../../api/structures/IEconomicDiscussionArticleVersion";

@Controller("/economicDiscussion/member/articles/:articleId/versions")
export class EconomicdiscussionMemberArticlesVersionsController {
  /**
   * Get a paginated list of article version snapshots for a specific article,
   * providing complete edit history tracking. This operation retrieves all
   * historical versions of an article, showing how content has evolved over
   * time.
   *
   * Each version captures the complete article state including title, content,
   * and metadata at that specific moment. The versions are ordered
   * chronologically, allowing users to browse through the edit history and see
   * detailed changes over time.
   *
   * This feature supports content transparency requirements where users can
   * view who made changes and when. It also enables potential rollback
   * capabilities by providing access to previous article states. The pagination
   * system ensures efficient loading even for articles with extensive edit
   * histories.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param body Pagination and sorting parameters for version history retrieval
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionArticleVersion.IRequest,
  ): Promise<IPageIEconomicDiscussionArticleVersion.ISummary> {
    try {
      return await patchEconomicDiscussionMemberArticlesArticleIdVersions({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information about a specific version of an article, including
   * the complete content snapshot as it existed at that specific version
   * timestamp. This operation provides access to historical article data,
   * allowing users to view content at any point in its evolution history.
   *
   * Each version snapshot includes the title, content, and version number as
   * they existed when that version was created, along with creation timestamp.
   * This provides complete transparency into the article's content history and
   * enables various use cases such as content comparison, audit trails,
   * understanding edit motivations, and potential rollback to previous
   * well-functioning content.
   *
   * The article context is maintained through the path parameter to ensure the
   * version belongs to the specified article, preventing unauthorized access to
   * historical content belonging to other articles.
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param versionId Unique identifier of the specific version snapshot to
   *   retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":versionId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("versionId")
    versionId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionArticleVersion> {
    try {
      return await getEconomicDiscussionMemberArticlesArticleIdVersionsVersionId(
        {
          member,
          articleId,
          versionId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
