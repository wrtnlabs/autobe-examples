import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicDiscussionMemberArticlesArticleIdComments } from "../../../../../providers/postEconomicDiscussionMemberArticlesArticleIdComments";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { getEconomicDiscussionMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/getEconomicDiscussionMemberArticlesArticleIdCommentsCommentId";
import { putEconomicDiscussionMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/putEconomicDiscussionMemberArticlesArticleIdCommentsCommentId";
import { deleteEconomicDiscussionMemberArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteEconomicDiscussionMemberArticlesArticleIdCommentsCommentId";

import { IEconomicDiscussionComment } from "../../../../../api/structures/IEconomicDiscussionComment";

@Controller("/economicDiscussion/member/articles/:articleId/comments")
export class EconomicdiscussionMemberArticlesCommentsController {
  /**
   * Add a new comment to an existing discussion article in the economic and
   * political discussion platform. This operation allows authenticated members
   * to provide textual feedback, opinions, and responses to published articles,
   * enabling community discussion and interaction.
   *
   * The operation validates that the target article exists and is accessible,
   * then creates a new comment that becomes immediately visible as part of the
   * article's discussion thread. Comments are automatically associated with the
   * authenticated member making the request, enabling proper attribution and
   * allowing for ownership tracking.
   *
   * This operation serves as the primary way for community members to
   * participate in discussions, providing a mechanism for expressing
   * viewpoints, asking questions, and engaging with article content. The
   * comment system supports direct engagement between members while maintaining
   * a threaded discussion format.
   *
   * @param connection
   * @param articleId Unique identifier of the target discussion article where
   *   the comment will be added
   * @param body Comment content and metadata for creation
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionComment.ICreate,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await postEconomicDiscussionMemberArticlesArticleIdComments({
        member,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific comment on the economic and
   * political discussion platform. This operation provides comprehensive access
   * to individual comment data, including the complete comment text, author
   * details, creation timestamps, and the associated article context.
   *
   * The operation validates access permissions and returns the comment with all
   * relevant metadata for detailed viewing or processing. It supports use cases
   * where specific comment content needs to be examined, referenced, or
   * displayed in isolation from the main article discussion thread.
   *
   * This endpoint enables precise retrieval of individual discussion
   * contributions, supporting moderation workflows, detailed content
   * management, and providing granular access to specific community feedback.
   * It returns complete comment context including the full content and author
   * attribution.
   *
   * @param connection
   * @param articleId Unique identifier of the discussion article containing the
   *   target comment
   * @param commentId Unique identifier of the specific comment to retrieve
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":commentId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await getEconomicDiscussionMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation allows authenticated economic discussion members to edit
   * their own comments on articles within the political discussion platform.
   * The update process maintains content integrity while providing users the
   * ability to correct errors, clarify statements, or extend their thoughts.
   *
   * The operation validates that the requesting member is the original author
   * of the comment to prevent unauthorized modifications. Upon successful
   * update, it creates a new entry in the comment versions table to preserve
   * the edit history. The article ID in the path ensures the comment belongs to
   * the specified discussion article.
   *
   * Security considerations include rate limiting to prevent abuse and content
   * validation based on business rules defined in the platform. The edit
   * history is preserved for transparency and potential moderation purposes.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   *   containing the comment
   * @param commentId Unique identifier of the specific comment to be updated
   * @param body Updated comment content and metadata for the economic
   *   discussion article comment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":commentId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionComment.IUpdate,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await putEconomicDiscussionMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation enables deletion of comments from economic and political
   * discussion articles on the platform. Members can delete their own comments
   * to remove content they no longer wish to share, while moderators have
   * broader permissions to remove any content that violates community
   * guidelines.
   *
   * The system implements soft deletion to maintain referential integrity and
   * preserve the discussion thread structure. Deleted comments remain in the
   * database with a deleted flag but are hidden from user views. This approach
   * preserves the conversation flow and prevents broken references in nested
   * comment discussions.
   *
   * The operation requires both article ID and comment ID parameters to ensure
   * the comment being removed belongs to the specified article. Authentication
   * is required to verify comment ownership for regular members and moderator
   * privileges for administrative actions.
   *
   * Content moderation benefits from this traceable deletion system, allowing
   * moderators to review deletion patterns and maintain discussion quality. The
   * soft-delete approach also enables potential restoration of inappropriately
   * removed content.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   *   containing the comment to delete
   * @param commentId Unique identifier of the specific comment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":commentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await deleteEconomicDiscussionMemberArticlesArticleIdCommentsCommentId(
        {
          member,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
