import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicDiscussionMemberArticlesArticleIdAttachmentFiles } from "../../../../../providers/postEconomicDiscussionMemberArticlesArticleIdAttachmentFiles";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteEconomicDiscussionMemberArticlesArticleIdAttachmentFilesAttachmentId } from "../../../../../providers/deleteEconomicDiscussionMemberArticlesArticleIdAttachmentFilesAttachmentId";

import { IEconomicDiscussionAttachment } from "../../../../../api/structures/IEconomicDiscussionAttachment";

@Controller("/economicDiscussion/member/articles/:articleId/attachmentFiles")
export class EconomicdiscussionMemberArticlesAttachmentfilesController {
  /**
   * Create a new file attachment for an article.
   *
   * Create a new file attachment for a specific economic discussion article.
   * This operation allows authenticated users to upload and attach files
   * (images, documents, spreadsheets) to their own articles.
   *
   * The system validates attachment limits (maximum 5 files per article) and
   * total combined file size constraints. Security scanning is initiated
   * automatically upon upload completion. Supported file types include images
   * (JPEG, PNG, GIF), documents (PDF, DOC, DOCX), and spreadsheets (XLS, XLSX)
   * with different size limits for each category.
   *
   * Authentication is required to verify the user owns the target article.
   * Authorization checks ensure only moderators can add attachments to any
   * article, while regular members can only attach files to their own article.
   * The uploaded file is immediately available for download and preview within
   * the article context.
   *
   * @param connection
   * @param articleId Unique identifier of the target article to attach the file
   *   to
   * @param body File upload request containing the attachment file and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionAttachment.ICreate,
  ): Promise<IEconomicDiscussionAttachment> {
    try {
      return await postEconomicDiscussionMemberArticlesArticleIdAttachmentFiles(
        {
          member,
          articleId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete a file attachment from an article.
   *
   * Permanently remove a file attachment from a specific economic discussion
   * article. This operation allows users to delete their own attachments while
   * moderators can remove any attachment for content moderation purposes.
   *
   * The deletion permanently removes the attachment record and all associated
   * file references from the database. This ensures complete cleanup of file
   * metadata and protects user privacy by ensuring deleted files cannot be
   * recovered or referenced later.
   *
   * Ownership verification is mandatory - regular members can only delete
   * attachments from their own articles, while moderators have authority to
   * remove attachments from any article for policy violations or content
   * moderation. The operation ensures proper access control before permitting
   * deletion.
   *
   * @param connection
   * @param articleId Unique identifier of the article containing the attachment
   * @param attachmentId Unique identifier of the file attachment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionAttachment> {
    try {
      return await deleteEconomicDiscussionMemberArticlesArticleIdAttachmentFilesAttachmentId(
        {
          member,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
