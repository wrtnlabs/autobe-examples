import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionCategories } from "../../../providers/patchEconomicDiscussionCategories";
import { getEconomicDiscussionCategoriesCategoryCode } from "../../../providers/getEconomicDiscussionCategoriesCategoryCode";

import { IPageIEconomicDiscussionCategory } from "../../../api/structures/IPageIEconomicDiscussionCategory";
import { IEconomicDiscussionCategory } from "../../../api/structures/IEconomicDiscussionCategory";

@Controller("/economicDiscussion/categories")
export class EconomicdiscussionCategoriesController {
  /**
   * Search and retrieve paginated list of discussion categories.
   *
   * Retrieve a filtered and paginated list of discussion board categories with
   * support for advanced search criteria. This operation enables users to
   * discover relevant discussion topics by filtering based on category names,
   * descriptions, creation dates, and activity levels.
   *
   * The operation supports full-text search within category titles and
   * descriptions, allowing users to find categories matching their interests.
   * Pagination controls including page size, sort order, and continuation
   * tokens provide efficient browsing through large category sets.
   *
   * Security measures include rate limiting for search frequency and
   * appropriate visibility controls based on user authorization level. Public
   * guests can view active categories while authenticated members may access
   * additional metadata about category activity and popularity.
   *
   * This operation integrates with the economic_discussion_categories table
   * from the Prisma schema while incorporating related metadata from
   * article-category associations for usage statistics.
   *
   * @param connection
   * @param body Search parameters for filtering and paginating discussion
   *   categories
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicDiscussionCategory.IRequest,
  ): Promise<IPageIEconomicDiscussionCategory.ISummary> {
    try {
      return await patchEconomicDiscussionCategories({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Get detailed information about a discussion category.
   *
   * Retrieve comprehensive details for a specific discussion board category
   * identified by its unique code. This operation provides complete category
   * information including title, description, creation timestamp, last
   * activity, and engagement statistics derived from associated content.
   *
   * The response includes computed metrics such as total article count, recent
   * activity trends, and category popularity indicators. These statistics help
   * users understand the category's relevance and activity level before
   * participating in discussions.
   *
   * The system validates that the requested category exists and is visible to
   * the requesting user based on their authorization level. Moderators may
   * access additional administrative metadata for category management
   * purposes.
   *
   * This operation serves the user interface category detail pages while
   * providing related data for category management functionality in the
   * administrative interface. It integrates seamlessly with the
   * economic_discussion_categories table while aggregating real-time statistics
   * from related entities for comprehensive category intelligence.
   *
   * @param connection
   * @param categoryCode Unique business identifier code of the target
   *   discussion category (global scope)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":categoryCode")
  public async at(
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IEconomicDiscussionCategory> {
    try {
      return await getEconomicDiscussionCategoriesCategoryCode({
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
