import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getEconomicDiscussionDiscoveryPopularTags } from "../../../../providers/getEconomicDiscussionDiscoveryPopularTags";

import { IEconomicDiscussionPopularTags } from "../../../../api/structures/IEconomicDiscussionPopularTags";

@Controller("/economicDiscussion/discovery/popular-tags")
export class EconomicdiscussionDiscoveryPopular_tagsController {
  /**
   * Retrieve popular tags from economic discussion articles for topic
   * discovery.
   *
   * This operation returns a collection of the most popular tags used in
   * economic and political discussion articles. Popular tags are determined by
   * frequency of usage across published articles, providing users with insights
   * into trending economic topics and political discourse themes.
   *
   * The tag popularity calculation considers the total number of articles
   * associated with each tag, excluding articles that are pending approval or
   * have been soft-deleted. Tags are ranked by usage count and returned in
   * descending order of popularity.
   *
   * This operation supports content discovery by helping users identify which
   * economic and political topics are currently most discussed in the
   * community. Popular tags can be used for navigation, filtering, and
   * discovering related content on the platform.
   *
   * The response includes tag identifiers, names, and usage statistics to
   * provide context about each tag's popularity within the discussion board
   * community.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async popularTags(): Promise<IEconomicDiscussionPopularTags> {
    try {
      return await getEconomicDiscussionDiscoveryPopularTags();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
