import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionDiscoveryRecentlyViewed } from "../../../../providers/patchEconomicDiscussionDiscoveryRecentlyViewed";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";

import { IPageIEconomicDiscussionArticle } from "../../../../api/structures/IPageIEconomicDiscussionArticle";
import { IEconomicDiscussionRecentlyViewed } from "../../../../api/structures/IEconomicDiscussionRecentlyViewed";

@Controller("/economicDiscussion/discovery/recently-viewed")
export class EconomicdiscussionDiscoveryRecently_viewedController {
  /**
   * This operation returns articles that the current user has recently viewed
   * on the economic discussion board platform. It provides personalized content
   * discovery based on the user's recent browsing activity, helping them
   * quickly return to previously viewed economic and political discussion
   * articles.
   *
   * The operation supports pagination to handle long viewing histories and uses
   * PATCH method to allow for complex query parameters including filtering by
   * date ranges, limiting results, and sorting preferences. Recent articles are
   * sorted by viewing timestamp in descending order, with most recently viewed
   * articles appearing first.
   *
   * For authenticated members, the system tracks viewing history across
   * sessions for persistent recommendations. For guest users, recently viewed
   * articles are limited to the current guest session and expire when the
   * session ends.
   *
   * The operation filters out articles that have been deleted or are no longer
   * accessible due to moderation. It also considers privacy settings and
   * content visibility rules to ensure appropriate content is returned based on
   * the user's authorization level and community guidelines.
   *
   * @param connection
   * @param body Query parameters for filtering recently viewed articles
   *   including date ranges, limits, and sorting preferences
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async recentlyViewed(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IEconomicDiscussionRecentlyViewed.IRequest,
  ): Promise<IPageIEconomicDiscussionArticle.ISummary> {
    try {
      return await patchEconomicDiscussionDiscoveryRecentlyViewed({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
