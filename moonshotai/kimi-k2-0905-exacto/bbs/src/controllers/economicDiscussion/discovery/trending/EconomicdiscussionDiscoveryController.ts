import { Controller } from "@nestjs/common";
import { TypedRoute } from "@nestia/core";
import typia from "typia";
import { getEconomicDiscussionDiscoveryTrending } from "../../../../providers/getEconomicDiscussionDiscoveryTrending";

import { IEconomicDiscussionTrendingList } from "../../../../api/structures/IEconomicDiscussionTrendingList";

@Controller("/economicDiscussion/discovery/trending")
export class EconomicdiscussionDiscoveryController {
  /**
   * Retrieve trending economic and political discussions.
   *
   * Retrieves a list of trending articles based on recent community activity
   * and engagement metrics. The trending discovery endpoint analyzes articles
   * from the past 24 hours to identify the most actively discussed economic and
   * political topics.
   *
   * The system evaluates multiple engagement factors including view counts,
   * comment activity, and interaction patterns to rank articles by trending
   * status. This provides users with a dynamic way to discover the most
   * relevant and active discussions in the community.
   *
   * Results are refreshed automatically every 2 hours to ensure content remains
   * current and reflective of recent community interests. The trending list
   * typically features a mix of breaking economic news, policy developments,
   * and political analysis that are generating significant community
   * participation.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async trending(): Promise<IEconomicDiscussionTrendingList> {
    try {
      return await getEconomicDiscussionDiscoveryTrending();
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
