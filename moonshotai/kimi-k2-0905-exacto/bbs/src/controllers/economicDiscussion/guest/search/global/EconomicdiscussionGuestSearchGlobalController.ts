import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionGuestSearchGlobal } from "../../../../../providers/patchEconomicDiscussionGuestSearchGlobal";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";

import { IPageIEconomicDiscussionSearchQuery } from "../../../../../api/structures/IPageIEconomicDiscussionSearchQuery";
import { IEconomicDiscussionSearch } from "../../../../../api/structures/IEconomicDiscussionSearch";

@Controller("/economicDiscussion/guest/search/global")
export class EconomicdiscussionGuestSearchGlobalController {
  /**
   * Search across all economic and political discussion content including
   * articles, categories, and related metadata. This operation provides a
   * unified search experience that helps users discover relevant discussions
   * and topics across the entire platform.
   *
   * The search functionality uses intelligent matching algorithms to find
   * relevant content based on query terms. It searches through article titles,
   * categories, and descriptions, with results ranked by relevance. The system
   * supports complex queries and provides comprehensive result sets with proper
   * pagination.
   *
   * This is a powerful discovery tool that helps users navigate the extensive
   * content library. It integrates with the search history tracking system to
   * provide personalized search experiences and maintain search context.
   *
   * Advanced features include relevance-based ranking, partial text matching,
   * and efficient pagination. The operation returns a comprehensive set of
   * search results with metadata for easy content discovery.
   *
   * @param connection
   * @param body Search query parameters including search terms, filters, and
   *   pagination settings
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async search(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IEconomicDiscussionSearch.IRequest,
  ): Promise<IPageIEconomicDiscussionSearchQuery.ISummary> {
    try {
      return await patchEconomicDiscussionGuestSearchGlobal({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
