import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getEconomicDiscussionModeratorSearchAnalyticsTrends } from "../../../../../providers/getEconomicDiscussionModeratorSearchAnalyticsTrends";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { patchEconomicDiscussionModeratorSearchAnalyticsPerformance } from "../../../../../providers/patchEconomicDiscussionModeratorSearchAnalyticsPerformance";

import { IEconomicDiscussionSearchAnalyticsTrends } from "../../../../../api/structures/IEconomicDiscussionSearchAnalyticsTrends";
import { IPageIEconomicDiscussionSearchAnalyticsPerformance } from "../../../../../api/structures/IPageIEconomicDiscussionSearchAnalyticsPerformance";
import { IEconomicDiscussionSearchAnalytics } from "../../../../../api/structures/IEconomicDiscussionSearchAnalytics";

@Controller("/economicDiscussion/moderator/search/analytics")
export class EconomicdiscussionModeratorSearchAnalyticsController {
  /**
   * Retrieve comprehensive search analytics trends for the economic discussion
   * board platform. This operation analyzes search query patterns from the
   * economic_discussion_search_queries table to identify trending topics,
   * popular search terms, and user engagement patterns within economic and
   * political discussions.
   *
   * The operation aggregates search data across multiple dimensions including
   * time periods, query frequency, and user interaction metrics. It helps
   * platform administrators understand community interests, identify emerging
   * economic discussion topics, and monitor search behavior patterns over
   * time.
   *
   * Security: Search analytics are typically considered sensitive operational
   * data. Access should be restricted to moderators who need to monitor
   * platform usage patterns for business intelligence purposes.
   *
   * Related operations: Search performance analytics (PATCH
   * /search/analytics/performance) provides complementary data on search
   * accuracy and user satisfaction.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("trends")
  public async trends(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IEconomicDiscussionSearchAnalyticsTrends> {
    try {
      return await getEconomicDiscussionModeratorSearchAnalyticsTrends({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve comprehensive performance analytics for the economic discussion
   * board's search functionality. This operation analyzes search performance
   * metrics from the economic_discussion_search_queries table and related data
   * to measure search effectiveness, accuracy, and user satisfaction.
   *
   * The operation evaluates multiple performance dimensions including query
   * response times, result relevance, click-through rates, successful search
   * completion rates, and user feedback metrics. It helps platform moderators
   * identify search optimization opportunities, diagnose performance issues,
   * and improve the overall search experience for users.
   *
   * This query-based operation supports complex filtering options for analyzing
   * performance by time periods, query types, user segments, and specific
   * search features. Moderators can drill down into performance metrics to
   * identify improvement areas and monitor system health.
   *
   * Security: Performance analytics are sensitive operational data that should
   * be restricted to authorized personnel responsible for platform
   * optimization.
   *
   * Related operations: Search analytics trends (GET /search/analytics/trends)
   * provides complementary data on search query patterns and trending topics.
   *
   * @param connection
   * @param body Performance analytics query parameters including filtering by
   *   time period, search criteria, and analysis depth
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("performance")
  public async performance(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IEconomicDiscussionSearchAnalytics.IRequest,
  ): Promise<IPageIEconomicDiscussionSearchAnalyticsPerformance> {
    try {
      return await patchEconomicDiscussionModeratorSearchAnalyticsPerformance({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
