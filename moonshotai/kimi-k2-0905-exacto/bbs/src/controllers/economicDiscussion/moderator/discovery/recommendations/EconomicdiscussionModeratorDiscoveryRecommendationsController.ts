import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionModeratorDiscoveryRecommendations } from "../../../../../providers/patchEconomicDiscussionModeratorDiscoveryRecommendations";

import { IEconomicDiscussionRecommendationsList } from "../../../../../api/structures/IEconomicDiscussionRecommendationsList";
import { IEconomicDiscussionRecommendationsRequest } from "../../../../../api/structures/IEconomicDiscussionRecommendationsRequest";

@Controller("/economicDiscussion/moderator/discovery/recommendations")
export class EconomicdiscussionModeratorDiscoveryRecommendationsController {
  /**
   * Provides personalized article recommendations based on browsing history and
   * interaction patterns. The recommendation engine analyzes user activity
   * including search queries, viewed articles, comment participation, and
   * engagement patterns to suggest relevant economic and political content.
   *
   * The algorithm considers factors such as frequently viewed categories,
   * search keywords, user interaction patterns with different article types,
   * and time spent on various topics to generate personalized content
   * suggestions. This personalization helps users discover new discussions that
   * align with their economic and political interests.
   *
   * For authenticated users, recommendations are based on individual user
   * profiles and activity history tracked through member sessions and
   * interaction logs. For authenticated users, recommendations may be based on
   * current session behavior or default to trending/popular content patterns
   * that reflect overall community interests.
   *
   * @param connection
   * @param body Recommendation preferences including user interests, category
   *   preferences, and interaction history parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicDiscussionRecommendationsRequest,
  ): Promise<IEconomicDiscussionRecommendationsList> {
    try {
      return await patchEconomicDiscussionModeratorDiscoveryRecommendations({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
