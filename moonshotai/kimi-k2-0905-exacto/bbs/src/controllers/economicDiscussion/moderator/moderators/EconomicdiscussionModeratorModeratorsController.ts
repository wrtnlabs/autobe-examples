  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("moderatorId")
    moderatorId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionModerator.IUpdate,
  ): Promise<IEconomicDiscussionModerator> {
    try {
      return await putEconomicDiscussionModeratorModeratorsModeratorId({
        moderator,
        moderatorId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

