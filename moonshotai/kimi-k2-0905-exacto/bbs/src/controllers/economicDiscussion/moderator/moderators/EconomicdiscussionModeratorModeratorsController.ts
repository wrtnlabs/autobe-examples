import { deleteEconomicDiscussionModeratorModeratorsModeratorId } from "../../../../providers/deleteEconomicDiscussionModeratorModeratorsModeratorId";

import { IPageIEconomicDiscussionModerator } from "../../../../api/structures/IPageIEconomicDiscussionModerator";
