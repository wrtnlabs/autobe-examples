import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { getEconomicDiscussionModeratorGuestsGuestId } from "../../../../providers/getEconomicDiscussionModeratorGuestsGuestId";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

import { IEconomicDiscussionGuest } from "../../../../api/structures/IEconomicDiscussionGuest";

@Controller("/economicDiscussion/moderator/guests/:guestId")
export class EconomicdiscussionModeratorGuestsController {
  /**
   * Retrieve detailed information about a specific guest user session in the
   * Economic Discussion Board platform. This operation provides comprehensive
   * access to guest user data stored in the economic_discussion_guests table,
   * including session identifiers, browsing history, download activities, and
   * activity timestamps.
   *
   * Guest users represent anonymous visitors to the discussion board who can
   * browse and read content without registration. Their access is tracked
   * through session management, allowing administrators to monitor platform
   * usage, understand visitor engagement patterns, and ensure appropriate
   * resource allocation for unregistered users.
   *
   * The data returned includes the guest's temporary username assignment, IP
   * address for session identification, browser user agent string when
   * available, creation and last activity timestamps, and usage counters for
   * articles viewed and downloads performed during the session lifetime. This
   * information enables administrators to analyze visitor behavior, identify
   * potential issues with guest access, and optimize the platform experience
   * for all users.
   *
   * Security considerations include authorization verification to ensure only
   * legitimate moderators can access guest user information, appropriate
   * handling of sensitive data such as IP addresses in compliance with privacy
   * regulations, and consideration of whether this operation should be exposed
   * through public APIs or reserved for internal administrative systems.
   *
   * @param connection
   * @param guestId Unique identifier of the guest user session
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionGuest> {
    try {
      return await getEconomicDiscussionModeratorGuestsGuestId({
        moderator,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
