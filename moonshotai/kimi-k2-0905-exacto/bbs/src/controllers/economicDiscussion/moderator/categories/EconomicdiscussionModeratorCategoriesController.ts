import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia from "typia";
import { postEconomicDiscussionModeratorCategories } from "../../../../providers/postEconomicDiscussionModeratorCategories";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putEconomicDiscussionModeratorCategoriesCategoryCode } from "../../../../providers/putEconomicDiscussionModeratorCategoriesCategoryCode";
import { deleteEconomicDiscussionModeratorCategoriesCategoryCode } from "../../../../providers/deleteEconomicDiscussionModeratorCategoriesCategoryCode";

import { IEconomicDiscussionCategory } from "../../../../api/structures/IEconomicDiscussionCategory";

@Controller("/economicDiscussion/moderator/categories")
export class EconomicdiscussionModeratorCategoriesController {
  /**
   * Creates a new category for organizing discussion articles within the
   * economic and political discourse platform. This operation enables
   * administrators to expand the taxonomy system by adding new topical areas
   * for content organization.
   *
   * Categories function as the primary filtering mechanism for users to
   * discover relevant discussions. Each category includes a unique code for URL
   * generation, display properties for user interfaces, and status controls for
   * availability. The system maintains article counts and ordering for optimal
   * user experience.
   *
   * Security considerations include admin-only access for category creation to
   * maintain consistent platform organization. The operation validates category
   * codes for uniqueness and ensures proper display ordering. Categories can be
   * deactivated rather than deleted to preserve historical content
   * organization.
   *
   * @param connection
   * @param body Category creation data including code, name, description, and
   *   display configuration
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IEconomicDiscussionCategory.ICreate,
  ): Promise<IEconomicDiscussionCategory> {
    try {
      return await postEconomicDiscussionModeratorCategories({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates the properties of an existing discussion category within the
   * economic and political discourse platform. This operation enables
   * administrators to modify category metadata while maintaining the integrity
   * of associated articles and content organization.
   *
   * Category updates support name changes for clarity, description
   * modifications for better user guidance, display order adjustments for
   * navigation optimization, and status changes for availability management.
   * The system preserves all article relationships during updates to maintain
   * content integrity.
   *
   * The operation includes validation for unique category codes and ensures
   * display ordering consistency. Historical data and article counts remain
   * intact during property updates. Category deactivation is preferred over
   * deletion to preserve content organization and historical references.
   *
   * @param connection
   * @param categoryCode Unique category code identifier for the category to be
   *   updated
   * @param body Updated category properties including name, description,
   *   display order, and active status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":categoryCode")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
    @TypedBody()
    body: IEconomicDiscussionCategory.IUpdate,
  ): Promise<IEconomicDiscussionCategory> {
    try {
      return await putEconomicDiscussionModeratorCategoriesCategoryCode({
        moderator,
        categoryCode,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently deactivate a discussion category by marking it as deleted. This
   * operation logically removes categories from active use while preserving all
   * historical data and relationships.
   *
   * Category deletion is a moderation action that affects content organization.
   * When a category is deleted, it becomes unavailable for new article
   * assignment while maintaining all existing associations. Articles in deleted
   * categories remain accessible but cannot tag new articles with these
   * categories.
   *
   * The operation uses soft deletion to preserve data integrity and maintain
   * audit trails. The category's unique code is maintained in the system,
   * preventing reuse of the same code for new categories while allowing
   * recovery if needed. This approach ensures smooth operation continuity and
   * maintains referential integrity with historical records.
   *
   * @param connection
   * @param categoryCode Unique code identifier of the category to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryCode")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<IEconomicDiscussionCategory> {
    try {
      return await deleteEconomicDiscussionModeratorCategoriesCategoryCode({
        moderator,
        categoryCode,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
