import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { deleteEconomicDiscussionModeratorArticlesArticleIdCommentsCommentId } from "../../../../../providers/deleteEconomicDiscussionModeratorArticlesArticleIdCommentsCommentId";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";

import { IEconomicDiscussionComment } from "../../../../../api/structures/IEconomicDiscussionComment";

@Controller(
  "/economicDiscussion/moderator/articles/:articleId/comments/:commentId",
)
export class EconomicdiscussionModeratorArticlesCommentsController {
  /**
   * Delete a comment from an economic discussion article.
   *
   * This operation enables deletion of comments from economic and political
   * discussion articles on the platform. Members can delete their own comments
   * to remove content they no longer wish to share, while moderators have
   * broader permissions to remove any content that violates community
   * guidelines.
   *
   * The system implements soft deletion to maintain referential integrity and
   * preserve the discussion thread structure. Deleted comments remain in the
   * database with a deleted flag but are hidden from user views. This approach
   * preserves the conversation flow and prevents broken references in nested
   * comment discussions.
   *
   * The operation requires both article ID and comment ID parameters to ensure
   * the comment being removed belongs to the specified article. Authentication
   * is required to verify comment ownership for regular members and moderator
   * privileges for administrative actions.
   *
   * Content moderation benefits from this traceable deletion system, allowing
   * moderators to review deletion patterns and maintain discussion quality. The
   * soft-delete approach also enables potential restoration of inappropriately
   * removed content.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   *   containing the comment to delete
   * @param commentId Unique identifier of the specific comment to be deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("commentId")
    commentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionComment> {
    try {
      return await deleteEconomicDiscussionModeratorArticlesArticleIdCommentsCommentId(
        {
          moderator,
          articleId,
          commentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
