import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconomicDiscussionModeratorArticlesArticleIdCategories } from "../../../../../providers/patchEconomicDiscussionModeratorArticlesArticleIdCategories";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { postEconomicDiscussionModeratorArticlesArticleIdCategoriesCategoryCode } from "../../../../../providers/postEconomicDiscussionModeratorArticlesArticleIdCategoriesCategoryCode";
import { deleteEconomicDiscussionModeratorArticlesArticleIdCategoriesCategoryCode } from "../../../../../providers/deleteEconomicDiscussionModeratorArticlesArticleIdCategoriesCategoryCode";

import { IEconomicDiscussionArticle } from "../../../../../api/structures/IEconomicDiscussionArticle";

@Controller("/economicDiscussion/moderator/articles/:articleId/categories")
export class EconomicdiscussionModeratorArticlesCategoriesController {
  /**
   * Update the category assignments for a specific discussion article. This
   * operation enables dynamic content organization by allowing articles to be
   * tagged with multiple relevant categories.
   *
   * The system maintains a many-to-many relationship between articles and
   * categories through the economic_discussion_article_categories junction
   * table. When updating categories, the operation clears existing associations
   * and assigns the complete new set, ensuring accurate categorization without
   * duplicates.
   *
   * Category assignment affects content discoverability through filtering and
   * browsing. Proper categorization helps users find relevant discussions
   * within their areas of interest while supporting the platform's organization
   * system. Categories must be active categories from the
   * economic_discussion_categories table with valid category codes.
   *
   * The operation includes validation to ensure all provided category codes
   * reference existing, active categories. It handles the complexity of
   * relationship management while maintaining referential integrity between
   * articles, categories, and their junction records.
   *
   * @param connection
   * @param articleId Unique identifier of the article whose categories are
   *   being updated
   * @param body List of category codes to assign to the article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async updateCategories(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionArticle.ICategoriesUpdate,
  ): Promise<IEconomicDiscussionArticle.ISummary> {
    try {
      return await patchEconomicDiscussionModeratorArticlesArticleIdCategories({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Associate an economic and political discussion article with a specific
   * category to improve content organization and discoverability. This
   * operation creates a many-to-many relationship between articles and
   * categories, allowing articles to be tagged with multiple relevant topic
   * areas.
   *
   * The system validates that both the target article and category exist before
   * creating the association. Each article-category combination must be unique,
   * preventing duplicate taggings. Categories represent specific fields of
   * economic or political discourse such as macroeconomics, monetary policy,
   * fiscal policy, international trade, or political theory.
   *
   * This assignment enables users to filter and browse discussions by category,
   * making it easier to find content within their areas of interest. The
   * operation maintains referential integrity while supporting flexible content
   * organization strategies.
   *
   * @param connection
   * @param articleId Unique identifier of the target economic discussion
   *   article
   * @param categoryCode Code identifier of the category to associate with the
   *   article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":categoryCode")
  public async attachCategory(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<void> {
    try {
      return await postEconomicDiscussionModeratorArticlesArticleIdCategoriesCategoryCode(
        {
          moderator,
          articleId,
          categoryCode,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Disassociate an economic and political discussion article from a specific
   * category to update its classification and organization within the platform.
   * This operation removes a tagging relationship while ensuring the article
   * maintains appropriate categorization for optimal discoverability.
   *
   * The system validates that both the target article and category exist, and
   * that the requested association currently exists before removal. This
   * prevents accidental detachment of non-existent associations and maintains
   * data integrity throughout the categorization system.
   *
   * After removal, users will no longer find this article when filtering by the
   * detached category, though the article may retain other category
   * associations. The operation supports flexible content organization
   * strategies while maintaining referential integrity and preventing orphaned
   * category relationships.
   *
   * @param connection
   * @param articleId Unique identifier of the target economic discussion
   *   article
   * @param categoryCode Code identifier of the category to remove from the
   *   article
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":categoryCode")
  public async detachCategory(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("categoryCode")
    categoryCode: string,
  ): Promise<void> {
    try {
      return await deleteEconomicDiscussionModeratorArticlesArticleIdCategoriesCategoryCode(
        {
          moderator,
          articleId,
          categoryCode,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
