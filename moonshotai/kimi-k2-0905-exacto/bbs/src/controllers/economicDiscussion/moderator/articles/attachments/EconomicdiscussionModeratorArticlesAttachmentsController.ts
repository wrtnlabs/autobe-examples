import { Controller } from "@nestjs/common";
import { TypedRoute, TypedParam, TypedBody } from "@nestia/core";
import typia, { tags } from "typia";
import { postEconomicDiscussionModeratorArticlesArticleIdAttachments } from "../../../../../providers/postEconomicDiscussionModeratorArticlesArticleIdAttachments";
import { ModeratorAuth } from "../../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../../decorators/payload/ModeratorPayload";
import { getEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/getEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId";
import { putEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/putEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId";
import { deleteEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId } from "../../../../../providers/deleteEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId";

import { IEconomicDiscussionAttachment } from "../../../../../api/structures/IEconomicDiscussionAttachment";

@Controller("/economicDiscussion/moderator/articles/:articleId/attachments")
export class EconomicdiscussionModeratorArticlesAttachmentsController {
  /**
   * This operation enables members and moderators to upload file attachments to
   * economic discussion articles. The system enforces strict file type and size
   * restrictions while providing immediate upload confirmation.
   *
   * Each article can have up to 5 attachments total, with individual file size
   * limits (5MB for images, 20MB for documents) to maintain storage efficiency
   * and ensure reasonable download times. The upload process automatically
   * categorizes files into image, document, or spreadsheet types based on file
   * extension and MIME type detection.
   *
   * Security is prioritized through automatic virus scanning initiation upon
   * upload completion. Files remain in a pending state until security
   * verification completes successfully. The system generates secure download
   * URLs and maintains content integrity through file hash verification.
   *
   * File visibility follows the same permission model as the parent article,
   * inheriting access restrictions automatically. When the associated article
   * is deleted, all attachments are automatically removed to maintain data
   * consistency. The operation returns comprehensive metadata including file
   * path, size, type categorization, and security scanning status for
   * client-side display and download preparation.
   *
   * The upload process is optimized for user experience with progress tracking
   * and immediate metadata return while background security processes complete
   * asynchronously.
   *
   * @param connection
   * @param articleId Unique identifier of the article to attach files to
   * @param body File upload information including file details and metadata
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionAttachment.ICreate,
  ): Promise<IEconomicDiscussionAttachment> {
    try {
      return await postEconomicDiscussionModeratorArticlesArticleIdAttachments({
        moderator,
        articleId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed metadata for a specific file attachment associated with
   * an economic discussion article. This operation provides access to
   * attachment information including filename, file size, MIME type, upload
   * timestamp, and security scanning status without exposing the actual file
   * content.
   *
   * The operation enforces article-level access controls - users can only view
   * attachment metadata if they have access to the parent article. For members
   * and moderators, this means attachments on their own articles, while
   * administrators can view attachment metadata for any article.
   *
   * Attachment metadata is useful for multiple scenarios:
   *
   * - Previewing attachment details before deciding to download files
   * - Managing attachments as part of article editing workflows
   * - Verifying file properties like size and format before download
   * - Checking security scanning completion status
   * - Displaying attachment lists in user interfaces
   *
   * The response excludes sensitive storage path information and focuses on
   * user-relevant metadata. File paths are system-level details that should
   * remain hidden from users for security reasons.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   * @param attachmentId Unique identifier of the file attachment
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":attachmentId")
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
  ): Promise<IEconomicDiscussionAttachment> {
    try {
      return await getEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId(
        {
          moderator,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update metadata for an existing file attachment associated with an economic
   * discussion article. This operation allows authorized users to modify
   * attachment properties while preserving the original file content.\n\nThe
   * primary use case for this operation is renaming attachments to improve
   * clarity or correct descriptive information. Users often realize their
   * attached files need clearer names after uploading, and this endpoint
   * enables that correction without requiring re-upload.\n\nPermission
   * requirements follow standard ownership patterns:\n- Members can update
   * attachments on their own articles\n- Moderators can update attachments on
   * their own articles\n- Administrators are represented by moderator level in
   * this system\n\nThe operation performs comprehensive validation:\n- Verifies
   * the attachment exists and is associated with the specified article\n-
   * Checks user permissions based on article ownership or moderator status\n-
   * Ensures filename changes don't conflict with existing attachments on the
   * same article\n- Preserves system-controlled fields like file_path,
   * created_at, and scan_status\n\nUpdates are limited to user-modifiable
   * metadata. System-controlled fields (storage paths, upload timestamps,
   * security status) cannot be modified through this endpoint to maintain
   * system integrity and audit trail consistency.
   *
   * @param connection
   * @param articleId Unique identifier of the economic discussion article
   * @param attachmentId Unique identifier of the file attachment
   * @param body Updated attachment metadata including filename changes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":attachmentId")
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string & tags.Format<"uuid">,
    @TypedParam("attachmentId")
    attachmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEconomicDiscussionAttachment.IUpdate,
  ): Promise<IEconomicDiscussionAttachment> {
    try {
      return await putEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId(
        {
          moderator,
          articleId,
          attachmentId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Remove a file attachment from an economic/political discussion article.
   * This operation allows article owners to delete their own attachments, or
   * moderators to remove inappropriate content.
   *
   * The operation validates that the requesting user has permission to delete
   * the attachment - either as the article owner or as a community moderator.
   * Upon successful deletion, the system removes the database record and the
   * associated physical file from storage.
   *
   * This operation helps maintain clean and relevant content by allowing users
   * to manage their attachments. It integrates with the attachment management
   * system and ensures proper cleanup of both database records and file
   * storage.
   *
   * Related operations include uploading attachments (POST) and listing article
   * attachments (GET).
   *
   * @param connection
   * @param articleId Unique identifier of the target article
   * @param attachmentId Unique identifier of the attachment to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":attachmentId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("articleId")
    articleId: string,
    @TypedParam("attachmentId")
    attachmentId: string,
  ): Promise<void> {
    try {
      return await deleteEconomicDiscussionModeratorArticlesArticleIdAttachmentsAttachmentId(
        {
          moderator,
          articleId,
          attachmentId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
