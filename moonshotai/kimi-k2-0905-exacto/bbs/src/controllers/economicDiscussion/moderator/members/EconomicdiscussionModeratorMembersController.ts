import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody, TypedParam } from "@nestia/core";
import typia, { tags } from "typia";
import { patchEconomicDiscussionModeratorMembers } from "../../../../providers/patchEconomicDiscussionModeratorMembers";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { deleteEconomicDiscussionModeratorMembersMemberId } from "../../../../providers/deleteEconomicDiscussionModeratorMembersMemberId";

import { IPageIEconomicDiscussionMember } from "../../../../api/structures/IPageIEconomicDiscussionMember";
import { IEconomicDiscussionMember } from "../../../../api/structures/IEconomicDiscussionMember";

@Controller("/economicDiscussion/moderator/members")
export class EconomicdiscussionModeratorMembersController {
  /**
   * Search and retrieve filtered lists of Economic Discussion community members
   * with support for complex search criteria, sorting, and pagination. This
   * operation enables administrators and moderators to discover members based
   * on various criteria including registration date ranges, email verification
   * status, usernames, reputation scores, and activity patterns.
   *
   * The operation provides comprehensive member discovery capabilities
   * essential for community management tasks such as identifying active
   * contributors, finding members for moderation review, analyzing registration
   * trends, and managing user support workflows. Results are optimized for
   * administrative interfaces with member summaries rather than detailed
   * profiles.
   *
   * Advanced filtering includes exact username matching, email domain
   * filtering, reputation score ranges, and activity-based searches. The
   * paginated response format supports efficient browsing of large member bases
   * with customizable page sizes and sorting preferences.
   *
   * @param connection
   * @param body Member search criteria including filters, sorting preferences,
   *   and pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IEconomicDiscussionMember.IRequest,
  ): Promise<IPageIEconomicDiscussionMember.ISummary> {
    try {
      return await patchEconomicDiscussionModeratorMembers({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * This operation permanently removes a member account from the economic
   * discussion board system. It completely deletes the member's profile,
   * authentication credentials, and associated session data from the database.
   *
   * The operation targets the economic_discussion_members table where member
   * accounts are stored with their username, email, password hash, and profile
   * information. Upon deletion, all corresponding records in the
   * economic_discussion_member_sessions table are also removed to maintain
   * referential integrity.
   *
   * Security considerations include requiring appropriate authorization to
   * prevent unauthorized account deletion. Only system administrators or
   * designated moderators with elevated permissions should be able to execute
   * this operation to ensure community safety and proper account management
   * procedures.
   *
   * Related operations: Member management operations for account updates and
   * session management.
   *
   * @param connection
   * @param memberId Unique identifier of the member account to delete
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":memberId")
  public async erase(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedParam("memberId")
    memberId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteEconomicDiscussionModeratorMembersMemberId({
        moderator,
        memberId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
