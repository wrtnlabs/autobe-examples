import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionSearchArticles } from "../../../../providers/patchEconomicDiscussionSearchArticles";

import { IPageIEconomicDiscussionArticle } from "../../../../api/structures/IPageIEconomicDiscussionArticle";
import { IEconomicDiscussionArticle } from "../../../../api/structures/IEconomicDiscussionArticle";

@Controller("/economicDiscussion/search/articles")
export class EconomicdiscussionSearchArticlesController {
  /**
   * Search and retrieve filtered, paginated list of economic discussion
   * articles.
   *
   * Retrieve a filtered and paginated list of economic discussion articles with
   * advanced search capabilities. This operation enables comprehensive
   * filtering across article titles, content, author information, categories,
   * publication status, and engagement metrics like view counts.
   *
   * The search functionality supports full-text search across article titles
   * and content using PostgreSQL's GIN indexes for optimal performance. Users
   * can combine multiple filter criteria including category selection, status
   * filtering, date range queries, and author-based filtering to find relevant
   * economic and political discussions.
   *
   * The operation provides comprehensive pagination with configurable page
   * sizes and sorting options. Articles can be sorted by creation date, view
   * count, title, or other relevant fields in ascending or descending order.
   * The response includes complete article information with author details,
   * attachment counts, and category assignments optimized for list displays.
   *
   * Security considerations include appropriate filtering of content based on
   * publication status and user permissions. Public users can only search
   * approved articles, while authenticated users may have access to additional
   * content based on their roles. The system implements rate limiting for
   * search operations to prevent abuse and maintain performance during
   * high-traffic periods.
   *
   * This search operation integrates with the economic_discussion_articles
   * table and related entities including categories, attachments, and user
   * accounts. The results are formatted for optimal display in article listing
   * interfaces with essential metadata for quick scanning and selection.
   *
   * @param connection
   * @param body Search criteria, filtering parameters, and pagination options
   *   for article discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicDiscussionArticle.IRequest,
  ): Promise<IPageIEconomicDiscussionArticle.ISummary> {
    try {
      return await patchEconomicDiscussionSearchArticles({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
