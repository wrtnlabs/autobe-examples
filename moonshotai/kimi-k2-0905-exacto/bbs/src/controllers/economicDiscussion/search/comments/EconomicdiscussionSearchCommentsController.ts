import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { patchEconomicDiscussionSearchComments } from "../../../../providers/patchEconomicDiscussionSearchComments";

import { IPageIEconomicDiscussionComment } from "../../../../api/structures/IPageIEconomicDiscussionComment";
import { IEconomicDiscussionComment } from "../../../../api/structures/IEconomicDiscussionComment";

@Controller("/economicDiscussion/search/comments")
export class EconomicdiscussionSearchCommentsController {
  /**
   * Retrieve a filtered and paginated list of comments posted on economic
   * discussion articles. This operation enables comprehensive filtering across
   * comment content, associated articles, comment authors, moderation status,
   * and temporal ranges for both community members and content moderators.
   *
   * The search functionality supports full-text search across comment content
   * using PostgreSQL's text indexing capabilities. Users can filter comments by
   * specific articles, authors, moderation status (pending, approved,
   * rejected), and time periods. Advanced filtering includes nested comment
   * relationships, allowing search within specific discussion threads.
   *
   * The operation provides comprehensive pagination with configurable page
   * sizes suitable for content moderation workflows. Comments can be sorted by
   * creation date, relevance to search terms, or moderation status based on the
   * user's purpose. The response includes complete comment information with
   * author details, thread context, and moderation information.
   *
   * For moderators, this search interface supports content moderation workflows
   * by allowing filtering of pending comments, identifying potentially
   * problematic content, and reviewing flagged discussions. The system provides
   * efficient processing of large comment volumes while maintaining performance
   * standards.
   *
   * Security considerations include appropriate access control based on user
   * roles and moderation privileges. Public users can search approved comments,
   * while authenticated users may access additional content based on their
   * permissions. The system implements protections against automated searching
   * while enabling legitimate community management activities.
   *
   * This search operation integrates with the economic_discussion_comments
   * table and related entities including articles, members, and moderation
   * workflows. The results are formatted to support both community browsing and
   * administrative oversight functions.
   *
   * @param connection
   * @param body Search criteria, filtering parameters, and pagination options
   *   for comment discovery
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEconomicDiscussionComment.IRequest,
  ): Promise<IPageIEconomicDiscussionComment.ISummary> {
    try {
      return await patchEconomicDiscussionSearchComments({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
