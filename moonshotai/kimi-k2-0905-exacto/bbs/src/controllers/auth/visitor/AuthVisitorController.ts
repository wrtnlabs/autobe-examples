import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthVisitorJoin } from "../../../providers/postAuthVisitorJoin";
import { VisitorAuth } from "../../../decorators/VisitorAuth";
import { VisitorPayload } from "../../../decorators/payload/VisitorPayload";
import { patchAuthVisitorRefresh } from "../../../providers/patchAuthVisitorRefresh";

import { IPoliticsBbsVisitorUser } from "../../../api/structures/IPoliticsBbsVisitorUser";
import { IPoliticsBbsUser } from "../../../api/structures/IPoliticsBbsUser";

@Controller("/auth/visitor")
export class AuthVisitorController {
  /**
   * Register temporary visitor account.
   *
   * Creates visitor accounts for the politicsBbs discussion board system. This
   * endpoint generates temporary guest accounts that provide session management
   * for unauthenticated users, allowing the system to track visitor activity,
   * recommend content based on browsing history, and maintain basic
   * personalization features. Visitor accounts receive limited JWT tokens that
   * expire after the browsing session ends, maintaining security for guest
   * users while providing essential session functionality. The registration
   * process requires minimal information - only username and password hash -
   * reflecting the temporary nature of visitor accounts. Upon successful
   * registration, the system creates a new visitor record with auto-generated
   * UUID, timestamps for account creation and last activity, and returns
   * authorization tokens for session management. This enables the discussion
   * board to distinguish between different guest visitors while maintaining the
   * anonymity and limited privileges appropriate for unauthenticated users.
   *
   * @param connection
   * @param body Visitor registration credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @VisitorAuth()
    visitor: VisitorPayload,
    @TypedBody()
    body: IPoliticsBbsVisitorUser.IJoin,
  ): Promise<IPoliticsBbsVisitorUser.IAuthorized> {
    try {
      return await postAuthVisitorJoin({
        visitor,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh visitor session tokens.
   *
   * Refreshes visitor session tokens for the politicsBbs discussion board
   * system. This endpoint validates existing refresh tokens and issues new
   * access tokens for visitor sessions, enabling temporary guest accounts to
   * maintain browsing sessions without re-authentication. The refresh process
   * checks token validity, extracts visitor identity, and generates new tokens
   * with appropriate expiration times. Visitor sessions receive shorter token
   * lifetimes reflecting their temporary nature while providing sufficient
   * session continuity for a typical browsing session. This enables the system
   * to maintain visitor-specific features like viewing history and basic
   * preferences while preserving the security appropriate for unauthenticated
   * guest users. The endpoint handles token rotation to maintain security
   * hygiene even for visitor accounts.
   *
   * @param connection
   * @param body Token refresh request with valid refresh token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch("refresh")
  public async refresh(
    @VisitorAuth()
    visitor: VisitorPayload,
    @TypedBody()
    body: IPoliticsBbsUser.IRefresh,
  ): Promise<IPoliticsBbsVisitorUser.IAuthorized> {
    try {
      return await patchAuthVisitorRefresh({
        visitor,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
