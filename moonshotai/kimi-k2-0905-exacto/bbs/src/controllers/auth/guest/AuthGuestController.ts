import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthGuestJoin } from "../../../providers/postAuthGuestJoin";
import { postAuthGuestRefresh } from "../../../providers/postAuthGuestRefresh";

import { IEconomicDiscussionGuest } from "../../../api/structures/IEconomicDiscussionGuest";

@Controller("/auth/guest")
export class AuthGuestController {
  /**
   * Create guest user account for anonymous browsing.
   *
   * Creates a new guest user account for browsing the Economic Discussion Board
   * system. Guest users have read-only access to articles, comments, and file
   * attachments but cannot create content or post comments.
   *
   * The operation validates the guest's IP address and creates a tracking
   * session for activity monitoring and download limit enforcement. Guest
   * accounts are linked by IP address and user agent string to prevent abuse
   * while maintaining anonymous browsing capabilities.
   *
   * The system enforces download limits of 10 files per session per IP address
   * and tracks articles viewed for analytics purposes. Guest sessions expire
   * after periods of inactivity to maintain system performance.
   *
   * This endpoint requires no authentication and creates temporary guest
   * sessions that last for the duration of the browsing session. Guest users
   * can upgrade to member accounts through the standard registration process.
   *
   * @param connection
   * @param body Guest user creation information
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEconomicDiscussionGuest.ICreate,
  ): Promise<IEconomicDiscussionGuest.IAuthorized> {
    try {
      return await postAuthGuestJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh guest user access token.
   *
   * Refreshes the guest user access token for continued browsing access to the
   * Economic Discussion Board system. This operation maintains the guest user's
   * temporary session without requiring re-authentication or registration.
   *
   * The system validates the existing guest session using the current refresh
   * token and creates a new access token pair if the session is still valid.
   * Guest sessions are tracked by IP address and expire after periods of
   * inactivity to prevent abuse.
   *
   * The operation ensures uninterrupted browsing access for guest users while
   * maintaining security through session expiration and limit enforcement.
   * Guest users retain their download limits and viewing history throughout the
   * refresh process.
   *
   * This operation is essential for maintaining user experience by preventing
   * session timeouts during extended browsing sessions or article reading
   * activities.
   *
   * @param connection
   * @param body Guest refresh token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEconomicDiscussionGuest.IRefresh,
  ): Promise<IEconomicDiscussionGuest.IAuthorized> {
    try {
      return await postAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
