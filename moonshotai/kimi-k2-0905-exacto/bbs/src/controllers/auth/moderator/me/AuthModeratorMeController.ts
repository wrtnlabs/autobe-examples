import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { getAuthModeratorMe } from "../../../../providers/getAuthModeratorMe";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";
import { putAuthModeratorMe } from "../../../../providers/putAuthModeratorMe";

import { IPoliticsBbsModerator } from "../../../../api/structures/IPoliticsBbsModerator";

@Controller("/auth/moderator/me")
export class AuthModeratorMeController {
  /**
   * Get current authenticated moderator profile information.
   *
   * Retrieve current authenticated moderator profile information.
   *
   * This endpoint returns comprehensive profile details for the currently
   * authenticated moderator. The information includes all relevant fields from
   * the politics_bbs_moderators table including username, email, creation
   * timestamp, and last update information.
   *
   * The profile data provides moderators with insights into their account
   * status, enabling review of account details, tracking of profile changes
   * through update timestamps, and verification of account creation history.
   * This supports moderator account management and audit requirements for
   * administrative role verification.
   *
   * @param connection
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @ModeratorAuth()
    moderator: ModeratorPayload,
  ): Promise<IPoliticsBbsModerator> {
    try {
      return await getAuthModeratorMe({
        moderator,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update current authenticated moderator profile information.
   *
   * This endpoint enables moderators to modify their profile details while
   * maintaining system integrity through comprehensive validation. The update
   * process supports username changes, email modifications, and maintains audit
   * trails for profile modifications.
   *
   * Username validation ensures unique usernames across the system with proper
   * character and length restrictions. Email modification requires verification
   * through system processes to ensure continued account access. Profile
   * updates are recorded with comprehensive audit information including the
   * update timestamp and modification tracking for administrative oversight.
   *
   * @param connection
   * @param body Moderator profile update information
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticsBbsModerator.IUpdate,
  ): Promise<IPoliticsBbsModerator> {
    try {
      return await putAuthModeratorMe({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
