import { Controller } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { putAuthModeratorPassword } from "../../../../providers/putAuthModeratorPassword";
import { ModeratorAuth } from "../../../../decorators/ModeratorAuth";
import { ModeratorPayload } from "../../../../decorators/payload/ModeratorPayload";

import { IPoliticsBbsModerator } from "../../../../api/structures/IPoliticsBbsModerator";

@Controller("/auth/moderator/password")
export class AuthModeratorPasswordController {
  /**
   * Change current moderator password.
   *
   * Change authenticated moderator password with validation.
   *
   * This endpoint enables moderators to securely update their account password.
   * The change process requires current password verification to prevent
   * unauthorized access attempts. New passwords must meet security requirements
   * including minimum 8 characters, mixed case letters, and numeric inclusion.
   *
   * Password validation includes comprehensive strength checking to ensure
   * compliance with security standards. The system implements secure password
   * hashing with appropriate salting techniques for all password storage.
   * Password changes are recorded for audit purposes while maintaining
   * historical security for account protection.
   *
   * @param connection
   * @param body Password change request with current and new passwords
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updatePassword(
    @ModeratorAuth()
    moderator: ModeratorPayload,
    @TypedBody()
    body: IPoliticsBbsModerator.IPassword,
  ): Promise<IPoliticsBbsModerator.IAuthorized> {
    try {
      return await putAuthModeratorPassword({
        moderator,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
