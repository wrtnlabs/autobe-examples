import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthModeratorJoin } from "../../../providers/postAuthModeratorJoin";
import { postAuthModeratorLogin } from "../../../providers/postAuthModeratorLogin";
import { postAuthModeratorRefresh } from "../../../providers/postAuthModeratorRefresh";

import { IPoliticsBbsModerator } from "../../../api/structures/IPoliticsBbsModerator";

@Controller("/auth/moderator")
export class AuthModeratorController {
  /**
   * Register new moderator account and issue JWT tokens.
   *
   * Create new moderator account with authentication token issuance.
   *
   * This endpoint enables new moderators to register for the politicsBBS
   * discussion board system. The registration process includes comprehensive
   * validation to ensure security and uniqueness within the system.
   *
   * The registration flow validates that usernames contain only letters,
   * numbers, and hyphens with a length between 3-20 characters, following the
   * requirements defined in the politics_bbs_moderators schema. Email addresses
   * must be unique across the system, with proper format validation according
   * to standard email specifications. Passwords must meet security requirements
   * including minimum 8 characters with at least one uppercase letter, one
   * lowercase letter, and one number.
   *
   * Upon successful validation, the system creates a new moderator record in
   * the politics_bbs_moderators table with a unique identifier and securely
   * hashed password using appropriate salting algorithms. The system generates
   * both access token (15-minute expiration) and refresh token (30-day
   * expiration) following JWT standards for immediate authentication.
   *
   * The response includes complete moderator profile information,
   * authentication tokens with proper expiration settings, and role-specific
   * permissions for content moderation activities. This enables new moderators
   * to immediately begin accessing moderation functionality after successful
   * registration.
   *
   * Error handling covers duplicate username scenarios, duplicate email
   * addresses, password format violations, and external registration
   * restrictions. All responses follow standard HTTP status codes with detailed
   * error messages that help users understand validation failures and take
   * corrective actions.
   *
   * @param connection
   * @param body Moderator registration information including username, email,
   *   and password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IPoliticsBbsModerator.ICreate,
  ): Promise<IPoliticsBbsModerator.IAuthorized> {
    try {
      return await postAuthModeratorJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Login moderator with JWT token generation.
   *
   * Authenticate moderator credentials and issue access tokens.
   *
   * This endpoint handles moderator authentication by validating username/email
   * and password credentials against the politics_bbs_moderators table. The
   * login process implements comprehensive security measures to protect against
   * unauthorized access while providing reliable authentication for legitimate
   * moderator users.
   *
   * The system accepts either username or email as the primary credential,
   * providing flexibility for moderator login preferences. Password validation
   * uses the securely stored password_hash from the moderator record,
   * implementing proper cryptographic verification with timing attack
   * resistance. Failed login attempts are tracked for security monitoring.
   *
   * Upon successful credential validation, the system generates a new session
   * record in the politics_bbs_moderator_sessions table with IP address
   * tracking, referrer information, and comprehensive audit details. This
   * supports security monitoring and administrative oversight of moderator
   * account access patterns.
   *
   * JWT token generation produces access tokens with 15-minute expiration for
   * API access and refresh tokens with 30-day expiration for session
   * management. Tokens include moderator identifier, username, role
   * confirmation, and comprehensive permission set for content moderation
   * activities including article review, comment moderation, and user
   * management capabilities.
   *
   * The response provides complete profile information including moderator ID,
   * username, email address, creation timestamp, and account status. Token
   * information includes both access and refresh tokens with proper expiration
   * times, enabling immediate access to moderator-specific functionality across
   * the discussion board platform.
   *
   * @param connection
   * @param body Moderator login credentials including username/email and
   *   password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IPoliticsBbsModerator.ILogin,
  ): Promise<IPoliticsBbsModerator.IAuthorized> {
    try {
      return await postAuthModeratorLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh moderator access tokens using refresh tokens.
   *
   * Refresh moderator access tokens using valid refresh tokens.
   *
   * This endpoint extends moderator authentication sessions by validating
   * existing refresh tokens and issuing new access tokens without requiring
   * users to re-enter their credentials. The refresh process implements token
   * rotation security measures while maintaining continuous access to
   * moderation functionality.
   *
   * The refresh token validation occurs against active session records in the
   * politics_bbs_moderator_sessions table, ensuring the token corresponds to a
   * valid, non-expired session. Invalid or expired refresh tokens result in
   * authentication failure, directing users to re-authenticate through the
   * login process.
   *
   * Upon successful validation, the system generates a fresh access token with
   * 15-minute expiration for immediate API access while maintaining the
   * existing refresh token validity. This approach balances security with
   * convenience, preventing token reuse while extending session duration for
   * ongoing moderator activities.
   *
   * Token generation creates access tokens containing moderator identifier,
   * username confirmation, role verification, and comprehensive permission set
   * including article approval workflows, comment moderation, content review,
   * user warning systems, and community management tools. Token metadata
   * includes creation timestamp, expiration time, and session identification
   * for audit tracking.
   *
   * The response maintains compatibility with the original login response
   * format, providing updated access tokens, refreshed expiration times,
   * moderated profile information, and complete permission sets for seamless
   * continuation of content management activities across the politicsBBS
   * platform.
   *
   * @param connection
   * @param body Token refresh request containing valid refresh token
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IPoliticsBbsModerator.IRefresh,
  ): Promise<IPoliticsBbsModerator.IAuthorized> {
    try {
      return await postAuthModeratorRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
