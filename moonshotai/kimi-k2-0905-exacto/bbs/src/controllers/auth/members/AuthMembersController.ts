import { Controller, Ip } from "@nestjs/common";
import { TypedRoute, TypedBody } from "@nestia/core";
import typia from "typia";
import { postAuthMembersJoin } from "../../../providers/postAuthMembersJoin";
import { postAuthMembersLogin } from "../../../providers/postAuthMembersLogin";
import { postAuthMembersRefresh } from "../../../providers/postAuthMembersRefresh";

import { IPoliticsBbsMember } from "../../../api/structures/IPoliticsBbsMember";

@Controller("/auth/members")
export class AuthMembersController {
  /**
   * Create new member account with JWT token issuance.
   *
   * Member registration endpoint for creating new member accounts. Members can
   * create articles, post comments, and upload attachments to the politics
   * discussion board.
   *
   * WHEN a new user registers, THE system SHALL validate the email format and
   * ensure uniqueness across the politics_bbs_members table. THE system SHALL
   * enforce password complexity requirements and store the password hash
   * securely using appropriate hashing algorithms.
   *
   * THE system SHALL create a new entry in the politics_bbs_members table with
   * generated UUID, unique username, email, password_hash, and current
   * timestamps for created_at and updated_at fields. THE deleted_at field SHALL
   * remain null for active accounts.
   *
   * Upon successful registration, THE system SHALL return JWT access and
   * refresh tokens to enable immediate authentication for the newly created
   * member account.
   *
   * Related operations include member login for authentication and token
   * refresh for session management. This operation is the entry point for new
   * users to join the discussion platform.
   *
   * @param connection
   * @param body Member registration credentials including username, email, and
   *   password
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IPoliticsBbsMember.IJoin,
  ): Promise<IPoliticsBbsMember.IAuthorized> {
    try {
      return await postAuthMembersJoin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate member with username and password.
   *
   * Member login endpoint for authenticating existing member accounts. Members
   * use their username and password to obtain JWT tokens for accessing
   * protected features of the politics discussion board.
   *
   * WHEN a member attempts to log in, THE system SHALL validate credentials by
   * checking the provided password against the stored password_hash in the
   * politics_bbs_members table. THE system SHALL verify the member account
   * exists and has not been soft-deleted by checking that the deleted_at field
   * is null.
   *
   * THE login process validates the member's username and matches against
   * existing records in the politics_bbs_members table. THE system SHALL handle
   * authentication failures gracefully and provide appropriate security
   * feedback without revealing specific account status.
   *
   * Upon successful authentication, THE system SHALL issue JWT access and
   * refresh tokens with appropriate expiration policies. THE access token SHALL
   * contain member identification information while maintaining security
   * standards.
   *
   * This operation enables members to access features like creating
   * political/economic discussion articles, posting comments, and uploading
   * attachments with appropriate restrictions.
   *
   * @param connection
   * @param body Member login credentials
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IPoliticsBbsMember.ILogin,
  ): Promise<IPoliticsBbsMember.IAuthorized> {
    try {
      return await postAuthMembersLogin({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh member authentication tokens.
   *
   * Member token refresh endpoint for maintaining active sessions. Members can
   * exchange valid refresh tokens for new access tokens without requiring full
   * re-authentication.
   *
   * THE system SHALL validate the provided refresh token and issue a new access
   * token if the refresh token is valid and not expired. This operation
   * maintains the member's authenticated session state.
   *
   * THE refresh token mechanism enables members to maintain their session while
   * accessing member-only features like creating political/economic articles,
   * uploading attachments, and participating in threaded discussions.
   *
   * THE system SHALL ensure that refresh tokens are securely handled and have
   * appropriate expiration policies to maintain security standards for the
   * political discussion platform.
   *
   * @param connection
   * @param body Valid refresh token for token renewal
   * @setHeader token.access Authorization
   *
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IPoliticsBbsMember.IRefresh,
  ): Promise<IPoliticsBbsMember.IAuthorized> {
    try {
      return await postAuthMembersRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
