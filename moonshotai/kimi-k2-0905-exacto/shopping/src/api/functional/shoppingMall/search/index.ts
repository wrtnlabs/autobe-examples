/**
 * Execute comprehensive global search across all platform content and entities
 * including products, articles, FAQ entries, and help documentation to provide
 * unified discovery capabilities for marketplace users. This operation
 * implements sophisticated cross-domain search functionality accessing multiple
 * Prisma tables including shopping_mall_products, shopping_mall_articles,
 * shopping_mall_faq_articles, and related content entities through complex
 * query composition and relevance ranking algorithms.
 *
 * The search operation supports multiple content types with intelligent ranking
 * based on user behavior patterns, content freshness, and relevance scoring.
 * Users can discover products through text matching against product names,
 * descriptions, and specifications, access help documentation and FAQ answers,
 * find platform articles and announcements, and locate relevant educational
 * content. The search incorporates advanced filtering capabilities including
 * category restrictions, date ranges, content type preferences, and result
 * quantity controls.
 *
 * Performance optimization includes GIN index utilization for text search
 * acceleration, result caching mechanisms for popular queries, and intelligent
 * autocomplete integration to improve user experience. The operation serves
 * both authenticated customers seeking products and guest visitors exploring
 * platform resources, with personalized result ordering for recognized users
 * based on browsing history and preferences.
 *
 * @param props.connection
 * @param props.body Global search request parameters including query terms,
 *   content type filters, pagination settings, and result preferences
 * @path /shoppingMall/search/global
 * @accessor api.functional.shoppingMall.search.global
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function global(
  connection: IConnection,
  props: global.Props,
): Promise<global.Response> {
  return true === connection.simulate
    ? global.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...global.METADATA,
          path: global.path(),
          status: null,
        },
        props.body,
      );
}
export namespace global {
  export type Props = {
    /**
     * Global search request parameters including query terms, content type
     * filters, pagination settings, and result preferences
     */
    body: IShoppingMallGlobalSearch.IRequest;
  };
  export type Body = IShoppingMallGlobalSearch.IRequest;
  export type Response = IPageIShoppingMallGlobalSearchResult;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/search/global",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/search/global";
  export const random = (): IPageIShoppingMallGlobalSearchResult =>
    typia.random<IPageIShoppingMallGlobalSearchResult>();
  export const simulate = (
    connection: IConnection,
    props: global.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: global.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
