import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallCart } from "../../../structures/IShoppingMallCart";

/**
 * Retrieve detailed information about a specific shopping cart including all
 * cart items, product details, pricing calculations, and current status. This
 * operation provides comprehensive cart data for customers to review their
 * selections before proceeding to checkout.
 *
 * The operation returns the complete cart object with associated cart items,
 * each containing detailed product information including variants, pricing, and
 * inventory status. Cart totals are calculated including item subtotals, tax
 * estimates, and shipping costs where applicable. The response includes cart
 * lifecycle information such as expiration dates and conversion status.
 *
 * Security considerations ensure that customers can only access their own
 * carts, with appropriate validation to prevent unauthorized access to shopping
 * session data. The operation supports both authenticated customers and guest
 * shopping sessions with proper session management.
 *
 * Implementation note: Cart access should be validated against current session
 * context to ensure customers can only view their own cart data.
 *
 * @param props.connection
 * @param props.cartId Unique identifier of the shopping cart to retrieve
 * @path /shoppingMall/carts/:cartId
 * @accessor api.functional.shoppingMall.carts.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique identifier of the shopping cart to retrieve */
    cartId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallCart;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/carts/:cartId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/carts/${encodeURIComponent(props.cartId ?? "null")}`;
  export const random = (): IShoppingMallCart =>
    typia.random<IShoppingMallCart>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cartId")(() => typia.assert(props.cartId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

