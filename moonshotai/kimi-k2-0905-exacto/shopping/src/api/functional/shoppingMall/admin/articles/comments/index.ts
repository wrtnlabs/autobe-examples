import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallArticleComment } from "../../../../../structures/IShoppingMallArticleComment";
import { IPageIShoppingMallArticleComment } from "../../../../../structures/IPageIShoppingMallArticleComment";

/**
 * Retrieve a filtered and paginated list of article comments from the shopping
 * mall platform. This operation operates on the shopping_mall_article_comments
 * table and provides comprehensive search capabilities for finding comments
 * based on multiple criteria including content, author information, rating
 * levels, and engagement metrics.
 *
 * The article comment system enables community engagement around platform
 * content, supporting threaded discussions, rating mechanisms, and moderation
 * capabilities. Comments can be authored by customers, sellers, or
 * administrators, with each comment maintaining relationships to the parent
 * article and optional parent comment for nested threading.
 *
 * Comments support rich text formatting for expressive discussion, multiple
 * author types (customer, seller, admin), and comprehensive engagement tracking
 * including like counts, ratings, and moderation status. The system
 * automatically calculates helpfulness scores and provides filtering options
 * based on rating levels, creation dates, and author types.
 *
 * Security considerations include content moderation for inappropriate
 * material, spam detection algorithms, and appropriate filtering based on
 * comment visibility status. Only users with appropriate permissions can access
 * detailed comment analytics and moderation tools through this endpoint.
 *
 * @param props.connection
 * @param props.articleCode Unique business identifier code of the target
 *   article (global scope)
 * @param props.body Search parameters for filtering article comments by
 *   content, author type, rating levels, and engagement metrics
 * @path /shoppingMall/admin/articles/:articleCode/comments
 * @accessor api.functional.shoppingMall.admin.articles.comments.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique business identifier code of the target article (global scope) */
    articleCode: string;

    /**
     * Search parameters for filtering article comments by content, author
     * type, rating levels, and engagement metrics
     */
    body: IShoppingMallArticleComment.IRequest;
  };
  export type Body = IShoppingMallArticleComment.IRequest;
  export type Response = IPageIShoppingMallArticleComment;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/articles/:articleCode/comments",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/articles/${encodeURIComponent(props.articleCode ?? "null")}/comments`;
  export const random = (): IPageIShoppingMallArticleComment =>
    typia.random<IPageIShoppingMallArticleComment>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleCode")(() => typia.assert(props.articleCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
