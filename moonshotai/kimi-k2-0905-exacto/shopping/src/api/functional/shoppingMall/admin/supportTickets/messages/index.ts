import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallTicketMessage } from "../../../../../structures/IShoppingMallTicketMessage";
import { IPageIShoppingMallTicketMessage } from "../../../../../structures/IPageIShoppingMallTicketMessage";

/**
 * Retrieve paginated message history for a specific support ticket with
 * advanced filtering and search capabilities. This operation enables
 * comprehensive conversation thread analysis with message content search,
 * sender identification, and temporal filtering to support ticket investigation
 * and quality assurance processes.
 *
 * The message retrieval system provides flexible query parameters for locating
 * specific communications, analyzing conversation patterns, and reviewing agent
 * response quality across different support scenarios. Search capabilities
 * include message content matching, sender-based filtering, and date range
 * limitations to enable targeted investigation of ticket resolution processes.
 *
 * Results are returned in chronological order with comprehensive metadata
 * including sender attribution, message types, attachment information, and read
 * status indicators to provide complete conversation context for support
 * quality analysis and customer service improvement initiatives.
 *
 * @param props.connection
 * @param props.ticketId Unique identifier of the support ticket whose message
 *   history is being retrieved
 * @param props.body Search criteria and pagination parameters for ticket
 *   message filtering including content search, sender filtering, and temporal
 *   range limitations
 * @path /shoppingMall/admin/supportTickets/:ticketId/messages
 * @accessor api.functional.shoppingMall.admin.supportTickets.messages.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the support ticket whose message history is
     * being retrieved
     */
    ticketId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for ticket message
     * filtering including content search, sender filtering, and temporal
     * range limitations
     */
    body: IShoppingMallTicketMessage.IRequest;
  };
  export type Body = IShoppingMallTicketMessage.IRequest;
  export type Response = IPageIShoppingMallTicketMessage.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/supportTickets/:ticketId/messages",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/supportTickets/${encodeURIComponent(props.ticketId ?? "null")}/messages`;
  export const random = (): IPageIShoppingMallTicketMessage.ISummary =>
    typia.random<IPageIShoppingMallTicketMessage.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("ticketId")(() => typia.assert(props.ticketId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
