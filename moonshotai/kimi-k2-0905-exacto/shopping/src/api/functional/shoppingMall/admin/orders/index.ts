/**
 * Retrieve a filtered and paginated list of orders from the shopping mall
 * platform. This operation provides comprehensive order search capabilities
 * across the order lifecycle, supporting complex queries for customers,
 * sellers, and administrators to track orders through various statuses
 * including pending, confirmed, processing, shipped, delivered, cancelled, and
 * refunded states.
 *
 * The operation enables detailed filtering by customer identity, seller
 * attribution, order status, date ranges, payment confirmation status,
 * multi-seller coordination flags, and other order-specific criteria. Results
 * include order summaries optimized for list displays while maintaining access
 * to detailed financial information, shipping details, and customer
 * communication history.
 *
 * Security considerations include role-based data visibility where customers
 * access only their own orders, sellers view orders containing their products,
 * and administrators access platform-wide order data. The operation supports
 * real-time inventory verification, payment status validation, and automated
 * alerts for orders requiring immediate attention or intervention.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for order
 *   filtering including customer, seller, status, date range, and payment
 *   filters
 * @path /shoppingMall/admin/orders
 * @accessor api.functional.shoppingMall.admin.orders.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
