/**
 * Retrieve a filtered and paginated list of refund records associated with a
 * specific order in the shopping mall platform. This operation searches through
 * the shopping_mall_order_refunds table to find all financial compensation
 * records linked to the specified order, including full order refunds, partial
 * item refunds, and dispute resolution transactions.
 *
 * The operation supports comprehensive filtering capabilities including refund
 * reason categories, fault determination (seller, customer, or platform issue),
 * refund status (pending, approved, rejected), administrative approval status,
 * and completion status. Results can be sorted by request date, decision date,
 * or refund amount, providing flexible access to refund history for order
 * management and financial reconciliation.
 *
 * This endpoint is essential for customer service representatives handling
 * order inquiries, financial teams performing refund reconciliation, and
 * administrators monitoring refund patterns across the marketplace. The
 * paginated response includes detailed refund information with associated
 * payment transaction details, seller information, and resolution timelines.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the order whose refund records are
 *   being retrieved
 * @param props.body Search criteria and pagination parameters for filtering
 *   refund records associated with the specified order
 * @path /shoppingMall/admin/orders/:orderId/refunds
 * @accessor api.functional.shoppingMall.admin.orders.refunds.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique identifier of the order whose refund records are being
     * retrieved
     */
    orderId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering refund
     * records associated with the specified order
     */
    body: IShoppingMallOrderRefund.IRequest;
  };
  export type Body = IShoppingMallOrderRefund.IRequest;
  export type Response = IPageIShoppingMallOrderRefund;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/admin/orders/:orderId/refunds",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/admin/orders/${encodeURIComponent(props.orderId ?? "null")}/refunds`;
  export const random = (): IPageIShoppingMallOrderRefund =>
    typia.random<IPageIShoppingMallOrderRefund>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
