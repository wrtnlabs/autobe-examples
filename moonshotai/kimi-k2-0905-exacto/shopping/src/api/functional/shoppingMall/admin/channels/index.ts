import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallChannel } from "../../../../structures/IShoppingMallChannel";
export * as categories from "./categories/index";
export * as sections from "./sections/index";

/**
 * Permanently remove a shopping mall channel from the platform database. This
 * operation deletes the channel record along with all associated
 * configurations, policies, and relationships.
 *
 * Channel deletion is a destructive action that cannot be undone and will
 * affect all sellers and products associated with this channel. The operation
 * requires administrative privileges due to its impact on marketplace
 * operations and seller businesses.
 *
 * Before deletion, the system validates that no active sellers, products, or
 * ongoing transactions are associated with the channel. If dependencies exist,
 * the deletion will be prevented to maintain data integrity.
 *
 * This operation permanently removes the channel from the
 * shopping_mall_channels table and cascades to related records in
 * shopping_mall_channel_categories and other channel-specific configurations.
 * All historical data, settings, and associations will be permanently deleted
 * from the database.
 *
 * @param props.connection
 * @param props.channelCode Unique business identifier code of the target
 *   shopping mall channel (global scope)
 * @path /shoppingMall/admin/channels/:channelCode
 * @accessor api.functional.shoppingMall.admin.channels.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /**
     * Unique business identifier code of the target shopping mall channel
     * (global scope)
     */
    channelCode: string;
  };
  export type Response = IShoppingMallChannel;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/channels/:channelCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/channels/${encodeURIComponent(props.channelCode ?? "null")}`;
  export const random = (): IShoppingMallChannel =>
    typia.random<IShoppingMallChannel>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("channelCode")(() => typia.assert(props.channelCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
