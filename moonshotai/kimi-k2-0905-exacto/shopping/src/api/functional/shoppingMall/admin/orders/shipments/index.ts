import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

/**
 * Permanently remove a shipment record from the shopping mall order fulfillment
 * system. This operation deletes the physical delivery tracking information
 * associated with a specific order shipment, including carrier details,
 * tracking numbers, shipping costs, and delivery status information from the
 * shopping_mall_order_shipments table.
 *
 * The deletion affects all shipment-related data including tracking
 * information, carrier service details, estimated delivery dates, and any
 * delivery confirmation records. Once deleted, this shipping information cannot
 * be recovered and customers will lose access to tracking capabilities for this
 * shipment.
 *
 * This operation should be used cautiously as it permanently removes logistics
 * documentation that may be required for customer service, dispute resolution,
 * or regulatory compliance. Consider archiving shipment data instead of
 * complete deletion for businesses requiring shipping record retention.
 *
 * @param props.connection
 * @param props.shipmentId Unique identifier of the shipment record to be
 *   permanently deleted
 * @path /shoppingMall/admin/orders/shipments/:shipmentId
 * @accessor api.functional.shoppingMall.admin.orders.shipments.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<void> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique identifier of the shipment record to be permanently deleted */
    shipmentId: string & tags.Format<"uuid">;
  };

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/orders/shipments/:shipmentId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/orders/shipments/${encodeURIComponent(props.shipmentId ?? "null")}`;
  export const random = (): void => typia.random<void>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): void => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
