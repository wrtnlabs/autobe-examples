import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProduct } from "../../../../structures/IShoppingMallProduct";

/**
 * Permanently remove a product from the marketplace catalog. This operation
 * deletes the product record from the shopping_mall_products table and cascades
 * to remove all associated variants, inventory records, and related data. The
 * operation ensures complete data removal while maintaining referential
 * integrity across the platform.
 *
 * This is a hard delete operation that completely removes the product and all
 * its dependencies from the database. Once executed, the product cannot be
 * recovered and all associated data including variants, inventory levels, and
 * historical records will be permanently deleted. The operation validates that
 * the product exists and that the requesting user has appropriate permissions
 * before proceeding with deletion.
 *
 * Security considerations include verifying seller ownership for
 * seller-initiated deletions and ensuring that products with active orders or
 * pending transactions cannot be deleted. Administrative users may override
 * certain restrictions for platform management purposes. The operation logs all
 * deletion activities for audit trails and maintains system integrity through
 * proper cascading deletes.
 *
 * @param props.connection
 * @param props.productCode Unique SKU code identifying the product to be
 *   deleted (global scope)
 * @path /shoppingMall/admin/products/:productCode
 * @accessor api.functional.shoppingMall.admin.products.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function erase(
  connection: IConnection,
  props: erase.Props,
): Promise<erase.Response> {
  return true === connection.simulate
    ? erase.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...erase.METADATA,
          path: erase.path(props),
          status: null,
        },
      );
}
export namespace erase {
  export type Props = {
    /** Unique SKU code identifying the product to be deleted (global scope) */
    productCode: string;
  };
  export type Response = IShoppingMallProduct;

  export const METADATA = {
    method: "DELETE",
    path: "/shoppingMall/admin/products/:productCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/admin/products/${encodeURIComponent(props.productCode ?? "null")}`;
  export const random = (): IShoppingMallProduct =>
    typia.random<IShoppingMallProduct>();
  export const simulate = (
    connection: IConnection,
    props: erase.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: erase.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
