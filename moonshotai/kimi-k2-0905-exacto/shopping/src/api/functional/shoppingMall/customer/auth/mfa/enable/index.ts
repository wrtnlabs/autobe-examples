import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallAuthentication } from "../../../../../../structures/IShoppingMallAuthentication";

/**
 * Enable two-factor authentication for the currently authenticated customer in
 * the shopping mall platform. This operation operates on the customer
 * authentication system and creates a new multi-factor authentication
 * configuration linked to the authenticated customer account.
 *
 * @param props.connection
 * @param props.body MFA enablement request containing authentication
 *   preferences
 * @path /shoppingMall/customer/auth/mfa/enable
 * @accessor api.functional.shoppingMall.customer.auth.mfa.enable.enableMfa
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function enableMfa(
  connection: IConnection,
  props: enableMfa.Props,
): Promise<enableMfa.Response> {
  return true === connection.simulate
    ? enableMfa.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...enableMfa.METADATA,
          path: enableMfa.path(),
          status: null,
        },
        props.body,
      );
}
export namespace enableMfa {
  export type Props = {
    /** MFA enablement request containing authentication preferences */
    body: IShoppingMallAuthentication.IEnableMfa;
  };
  export type Body = IShoppingMallAuthentication.IEnableMfa;
  export type Response = IShoppingMallAuthentication.IMfaSetupResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/customer/auth/mfa/enable",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/customer/auth/mfa/enable";
  export const random = (): IShoppingMallAuthentication.IMfaSetupResponse =>
    typia.random<IShoppingMallAuthentication.IMfaSetupResponse>();
  export const simulate = (
    connection: IConnection,
    props: enableMfa.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: enableMfa.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
