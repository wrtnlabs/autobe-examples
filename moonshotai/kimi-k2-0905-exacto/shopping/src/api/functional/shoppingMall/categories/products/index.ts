import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProduct } from "../../../../structures/IShoppingMallProduct";
import { IPageIShoppingMallProduct } from "../../../../structures/IPageIShoppingMallProduct";

/**
 * Retrieve a filtered and paginated list of products within a specific product
 * category from the shopping mall catalog. This operation enables
 * category-based product discovery and browsing, supporting advanced filtering
 * by price range, product condition, availability status, and seller attributes
 * while maintaining comprehensive search capabilities for enhanced customer
 * experience.
 *
 * The operation leverages the hierarchical product categorization system to
 * provide targeted product listings within specific category branches.
 * Customers can filter products by various criteria including price ranges,
 * product condition (new/used/refurbished), seller reputation, availability
 * status, and featured product highlights. The system supports dynamic sorting
 * options including price (low-to-high, high-to-low), popularity, newest
 * arrivals, and customer ratings to optimize product discovery workflows.
 *
 * Security considerations include respecting product visibility rules based on
 * seller status, product approval workflows, and customer authorization levels.
 * Products with status 'active' and published_at timestamps are included in
 * results, while draft, archived, or deleted products are filtered out. The
 * operation integrates with inventory management to show real-time availability
 * and prevents displaying out-of-stock items unless backordering is explicitly
 * allowed.
 *
 * This operation serves as the primary mechanism for category-based product
 * browsing in the marketplace interface. It supports SEO-optimized category
 * pages, merchandising strategies, and personalized product recommendations
 * while maintaining performance through efficient database queries and result
 * caching mechanisms.
 *
 * @param props.connection
 * @param props.categoryCode Unique category code identifier for browsing
 *   products within this specific category and its subcategories
 * @param props.body Search criteria and filtering parameters for product
 *   discovery within the specified category
 * @path /shoppingMall/categories/:categoryCode/products
 * @accessor api.functional.shoppingMall.categories.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Unique category code identifier for browsing products within this
     * specific category and its subcategories
     */
    categoryCode: string;

    /**
     * Search criteria and filtering parameters for product discovery within
     * the specified category
     */
    body: IShoppingMallProduct.IRequest;
  };
  export type Body = IShoppingMallProduct.IRequest;
  export type Response = IPageIShoppingMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/categories/:categoryCode/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/categories/${encodeURIComponent(props.categoryCode ?? "null")}/products`;
  export const random = (): IPageIShoppingMallProduct.ISummary =>
    typia.random<IPageIShoppingMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("categoryCode")(() => typia.assert(props.categoryCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
