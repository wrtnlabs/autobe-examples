import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallArticle } from "../../../structures/IShoppingMallArticle";

/**
 * Retrieve detailed information about a specific article using its business
 * identifier code. This operation accesses the shopping_mall_articles table and
 * returns complete article details including content, metadata, SEO
 * information, and publishing status.
 *
 * The article lookup uses the unique code field which serves as the business
 * identifier for external references and URL building. This operation supports
 * content management workflows, article viewing, and editorial preview
 * functionality. The returned data includes full article body content,
 * associated metadata, publication timestamps, and relationship information to
 * channels, sections, and categories.
 *
 * Security considerations include article visibility based on publication
 * status, channel accessibility, and user authorization. Only published
 * articles are accessible to public users, while draft and archived articles
 * require appropriate editorial permissions. The operation validates article
 * existence and accessibility before returning data.
 *
 * @param props.connection
 * @param props.articleCode Unique business identifier code of the target
 *   article (global scope)
 * @path /shoppingMall/articles/:articleCode
 * @accessor api.functional.shoppingMall.articles.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /** Unique business identifier code of the target article (global scope) */
    articleCode: string;
  };
  export type Response = IShoppingMallArticle;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/articles/:articleCode",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/articles/${encodeURIComponent(props.articleCode ?? "null")}`;
  export const random = (): IShoppingMallArticle =>
    typia.random<IShoppingMallArticle>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("articleCode")(() => typia.assert(props.articleCode));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
