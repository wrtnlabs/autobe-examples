import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductReview } from "../../../../structures/IShoppingMallProductReview";
import { IPageIShoppingMallProductReview } from "../../../../structures/IPageIShoppingMallProductReview";

/**
 * Retrieve product reviews and ratings for customer evaluation and purchase
 * decision support. This customer-facing operation searches reviews within a
 * specific product catalog entry, providing filtered review discovery
 * capabilities including rating-based sorting, most helpful prioritization, and
 * keyword search for relevant customer feedback.
 *
 * The operation enables customers to evaluate product quality through
 * community-generated reviews, verified purchase validation, and helpfulness
 * scoring. Review content includes comprehensive ratings analysis, detailed
 * customer experiences, and photo/video evidence demonstrating real-world
 * product usage and satisfaction levels.
 *
 * Search capabilities support practical customer needs including finding
 * reviews by rating ranges (1-5 stars), filtering verified purchases for
 * authenticity assurance, parsing review content for specific feature mentions,
 * and sorting by community helpfulness to surface the most valuable purchasing
 * insights.
 *
 * Customer access requires authenticated session for review visibility while
 * maintaining appropriate privacy boundaries. The system integrates with
 * customer accounts to provide personalized review helpfulness voting and
 * supports community-driven quality assessment through collective review
 * evaluation.
 *
 * @param props.connection
 * @param props.productCode Unique product SKU identifier for review lookup
 *   (global scope)
 * @param props.body Review search criteria with customer-oriented filtering
 *   options for rating ranges, verification status, and helpfulness
 *   prioritization
 * @path /shoppingMall/products/:productCode/reviews
 * @accessor api.functional.shoppingMall.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique product SKU identifier for review lookup (global scope) */
    productCode: string;

    /**
     * Review search criteria with customer-oriented filtering options for
     * rating ranges, verification status, and helpfulness prioritization
     */
    body: IShoppingMallProductReview.IRequest;
  };
  export type Body = IShoppingMallProductReview.IRequest;
  export type Response = IPageIShoppingMallProductReview;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/products/:productCode/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/products/${encodeURIComponent(props.productCode ?? "null")}/reviews`;
  export const random = (): IPageIShoppingMallProductReview =>
    typia.random<IPageIShoppingMallProductReview>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
