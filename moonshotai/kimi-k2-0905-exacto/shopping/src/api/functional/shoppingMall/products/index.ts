/**
 * Retrieve a filtered and paginated list of products from the shopping mall
 * catalog. This operation queries the shopping_mall_products table and provides
 * comprehensive search capabilities including text-based search, category
 * filtering, price range filtering, and advanced sorting options.
 *
 * The operation supports complex filtering criteria including product
 * name/description search, category hierarchy traversal, price range
 * specifications, availability status, and seller-based filtering. Results can
 * be sorted by various fields including popularity, price, creation date, and
 * customer ratings with both ascending and descending order support.
 *
 * The response includes product summary information optimized for list
 * displays, containing essential product details, pricing information,
 * thumbnail images, and key attributes without loading full product details or
 * variant information. The pagination system supports configurable page sizes
 * and provides total count information for UI rendering.
 *
 * Security considerations include appropriate data visibility based on product
 * status (active/inactive) and seller account status. Only products that are
 * publicly visible and associated with active sellers are returned in the
 * results.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for product
 *   filtering including text search, category filters, price ranges, and
 *   sorting preferences
 * @path /shoppingMall/products
 * @accessor api.functional.shoppingMall.products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
