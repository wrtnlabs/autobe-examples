import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPasswordChange } from "../../../../../structures/IShoppingMallPasswordChange";
import { IShoppingMallPasswordConfirm } from "../../../../../structures/IShoppingMallPasswordConfirm";

/**
 * Complete the password reset process by setting a new password using a valid
 * reset token. This operation validates the reset token and updates the user's
 * password in a single transaction.
 *
 * The system first verifies that the provided reset token is valid, unexpired,
 * and corresponds to an existing user account. The new password must meet
 * security requirements (minimum length, complexity requirements). Upon
 * successful validation, the password is updated and the reset token is
 * immediately invalidated to prevent reuse.
 *
 * Security considerations include token validation with time expiration
 * checking, password strength requirements enforcement, immediate token
 * invalidation after use, and comprehensive audit logging of the password
 * change event. The operation also triggers any related security measures like
 * sending confirmation emails.
 *
 * This operation requires the reset token to be included in the request body
 * along with the new password. The token is typically obtained from the
 * password reset email sent by the reset request operation.
 *
 * Related operations: Password reset request (POST /auth/password/reset), User
 * profile update (PUT /auth/profile).
 *
 * @param props.connection
 * @param props.body Password change request containing the new password and
 *   reset token
 * @path /shoppingMall/auth/password/change
 * @accessor api.functional.shoppingMall.auth.password.change.changePassword
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function changePassword(
  connection: IConnection,
  props: changePassword.Props,
): Promise<changePassword.Response> {
  return true === connection.simulate
    ? changePassword.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...changePassword.METADATA,
          path: changePassword.path(),
          status: null,
        },
        props.body,
      );
}
export namespace changePassword {
  export type Props = {
    /** Password change request containing the new password and reset token */
    body: IShoppingMallPasswordChange.IUpdate;
  };
  export type Body = IShoppingMallPasswordChange.IUpdate;
  export type Response = IShoppingMallPasswordConfirm;

  export const METADATA = {
    method: "PUT",
    path: "/shoppingMall/auth/password/change",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/password/change";
  export const random = (): IShoppingMallPasswordConfirm =>
    typia.random<IShoppingMallPasswordConfirm>();
  export const simulate = (
    connection: IConnection,
    props: changePassword.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: changePassword.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
