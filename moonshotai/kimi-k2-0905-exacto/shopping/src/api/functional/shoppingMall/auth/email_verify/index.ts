import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallEmailVerify } from "../../../../structures/IShoppingMallEmailVerify";
import { IShoppingMallEmailVerifyResponse } from "../../../../structures/IShoppingMallEmailVerifyResponse";

/**
 * Verify customer email addresses during registration through email
 * verification link confirmation. This operation validates email verification
 * tokens sent to users completing the email verification step in the customer
 * onboarding workflow. The process confirms email address authenticity and
 * activates customer accounts with basic permissions after successful
 * verification.
 *
 * Email verification is a mandatory step following customer registration that
 * ensures valid email addresses and prevents fraudulent account creation. The
 * operation validates verification tokens with automatic expiration handling
 * and provides clear feedback for successful completion or failure conditions
 * including expired tokens, previously verified addresses, or invalid
 * characters in verification strings.
 *
 * The verification process integrates with the shopping_mall_customer and
 * related session management systems to upgrade account status from pending to
 * active while creating comprehensive audit trails for security tracking.
 * Account activation includes basic customer permissions and access to platform
 * features while maintaining security boundaries appropriate for new accounts.
 *
 * @param props.connection
 * @param props.body Email verification details including confirmation code and
 *   email address
 * @path /shoppingMall/auth/email-verify
 * @accessor api.functional.shoppingMall.auth.email_verify.verifyEmail
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyEmail(
  connection: IConnection,
  props: verifyEmail.Props,
): Promise<verifyEmail.Response> {
  return true === connection.simulate
    ? verifyEmail.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyEmail.METADATA,
          path: verifyEmail.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyEmail {
  export type Props = {
    /**
     * Email verification details including confirmation code and email
     * address
     */
    body: IShoppingMallEmailVerify;
  };
  export type Body = IShoppingMallEmailVerify;
  export type Response = IShoppingMallEmailVerifyResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/email-verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/email-verify";
  export const random = (): IShoppingMallEmailVerifyResponse =>
    typia.random<IShoppingMallEmailVerifyResponse>();
  export const simulate = (
    connection: IConnection,
    props: verifyEmail.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyEmail.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
