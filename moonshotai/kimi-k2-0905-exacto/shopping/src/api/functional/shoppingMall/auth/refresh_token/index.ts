import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallTokenRefresh } from "../../../../structures/IShoppingMallTokenRefresh";
import { IShoppingMallAuthentication } from "../../../../structures/IShoppingMallAuthentication";

/**
 * Refresh expired or near-expiry JWT access tokens using valid refresh tokens
 * to maintain user sessions without requiring re-authentication. This operation
 * implements secure token rotation mechanisms that enhance security while
 * providing seamless user experience across extended platform usage periods.
 *
 * The refresh process validates the presented refresh token against stored
 * session data, implements token rotation with automated refresh token
 * replacement, and generates new access tokens with updated expiration
 * timestamps. Security features include refresh token usage tracking to detect
 * potential token theft, automatic session validation against device
 * fingerprints and IP address changes, and comprehensive audit logging for
 * security analysis and compliance reporting.
 *
 * This operation supports multi-device session management by maintaining
 * separate refresh tokens for each authenticated device while enabling
 * coordinated session revocation when security incidents are detected. The
 * implementation handles edge cases including expired refresh tokens, revoked
 * sessions, device changes requiring additional verification, and concurrent
 * refresh attempts that could indicate security compromise.
 *
 * The token refresh mechanism integrates with the
 * shopping_mall_customer_sessions, shopping_mall_seller_sessions, and
 * shopping_mall_admin_sessions tables to maintain persistent authentication
 * state across user activities. It implements intelligent token rotation
 * policies that balance security enhancement with user convenience, supports
 * configurable access token lifetimes based on user roles and security
 * policies, and provides detailed refresh analytics for platform security
 * monitoring and incident response coordination.
 *
 * @param props.connection
 * @param props.body Token refresh request containing the current refresh token
 *   and optional device identification information for secure token renewal
 * @path /shoppingMall/auth/refresh-token
 * @accessor api.functional.shoppingMall.auth.refresh_token.refreshToken
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function refreshToken(
  connection: IConnection,
  props: refreshToken.Props,
): Promise<refreshToken.Response> {
  return true === connection.simulate
    ? refreshToken.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...refreshToken.METADATA,
          path: refreshToken.path(),
          status: null,
        },
        props.body,
      );
}
export namespace refreshToken {
  export type Props = {
    /**
     * Token refresh request containing the current refresh token and
     * optional device identification information for secure token renewal
     */
    body: IShoppingMallTokenRefresh.ICreate;
  };
  export type Body = IShoppingMallTokenRefresh.ICreate;
  export type Response = IShoppingMallAuthentication.ITokenResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/refresh-token",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/refresh-token";
  export const random = (): IShoppingMallAuthentication.ITokenResponse =>
    typia.random<IShoppingMallAuthentication.ITokenResponse>();
  export const simulate = (
    connection: IConnection,
    props: refreshToken.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: refreshToken.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
