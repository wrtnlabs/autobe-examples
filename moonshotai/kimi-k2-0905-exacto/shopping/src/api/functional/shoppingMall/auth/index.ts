/**
 * Terminate the current user session across all active contexts in the shopping
 * mall platform. This endpoint operates on the session management system to
 * invalidate JWT tokens and perform session cleanup for customers, sellers, and
 * administrators. The operation ensures complete session termination by
 * removing session records from the appropriate session tables within the
 * database and marking tokens as invalidated.
 *
 * The logout process handles multi-faceted session cleanup including token
 * invalidation, session record deletion from the relevant user type session
 * table, and cleanup of any temporary data associated with the active session.
 * It supports cross-device logout scenarios and ensures that all session
 * contexts are properly terminated to prevent unauthorized access. The
 * operation also handles special cases such as guest session cleanup, partial
 * session termination for multi-session users, and integration with SSO or
 * federated authentication systems.
 *
 * Security features include token blacklisting to prevent token reuse, session
 * termination across all active sessions for the user, and comprehensive audit
 * logging of logout events for security monitoring. The endpoint supports both
 * single-session termination and comprehensive session cleanup for users with
 * multiple active sessions across different devices or contexts.
 *
 * The logout operation is designed to be atomic and comprehensive, ensuring
 * that no session artifacts remain that could be exploited for unauthorized
 * access while maintaining audit trails for security and compliance purposes.
 *
 * @param props.connection
 * @param props.body Logout request containing the JWT access token to be
 *   invalidated and optional session cleanup preferences
 * @path /shoppingMall/auth/logout
 * @accessor api.functional.shoppingMall.auth.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
  props: logout.Props,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
        props.body,
      );
}
export namespace logout {
  export type Props = {
    /**
     * Logout request containing the JWT access token to be invalidated and
     * optional session cleanup preferences
     */
    body: IShoppingMallLogoutRequest;
  };
  export type Body = IShoppingMallLogoutRequest;
  export type Response = IShoppingMallLogoutConfirmation;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/logout",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/logout";
  export const random = (): IShoppingMallLogoutConfirmation =>
    typia.random<IShoppingMallLogoutConfirmation>();
  export const simulate = (
    connection: IConnection,
    props: logout.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: logout.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
