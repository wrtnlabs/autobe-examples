import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallAccessToken } from "../../../../structures/IShoppingMallAccessToken";
import { IShoppingMallSessionValidation } from "../../../../structures/IShoppingMallSessionValidation";

/**
 * Validate the current user session and return extended session information
 * including user profile, permissions, and active roles across the shopping
 * mall platform. This endpoint operates on the session management system
 * defined in the Prisma schema, specifically referencing the various session
 * tables (shopping_mall_customer_sessions, shopping_mall_seller_sessions,
 * shopping_mall_admin_sessions) to determine the active session state and
 * associated user context.
 *
 * The operation performs comprehensive session validation by checking JWT token
 * integrity, expiration status, and cross-referencing with the appropriate
 * session table based on user type (customer, seller, or admin). It returns
 * enriched session data that includes not just basic authentication status but
 * also user profile information, role permissions, and platform-specific
 * context needed for frontend applications to render appropriate user
 * interfaces.
 *
 * Security considerations include rate limiting to prevent session validation
 * abuse, token fingerprint validation to detect unauthorized session sharing,
 * and automatic session extension for active users. The endpoint also handles
 * edge cases such as expired sessions, invalidated tokens, and cross-device
 * session management scenarios.
 *
 * @param props.connection
 * @param props.body Session validation request containing the JWT access token
 *   for authentication verification
 * @path /shoppingMall/auth/validate-session
 * @accessor api.functional.shoppingMall.auth.validate_session.validateSession
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function validateSession(
  connection: IConnection,
  props: validateSession.Props,
): Promise<validateSession.Response> {
  return true === connection.simulate
    ? validateSession.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...validateSession.METADATA,
          path: validateSession.path(),
          status: null,
        },
        props.body,
      );
}
export namespace validateSession {
  export type Props = {
    /**
     * Session validation request containing the JWT access token for
     * authentication verification
     */
    body: IShoppingMallAccessToken;
  };
  export type Body = IShoppingMallAccessToken;
  export type Response = IShoppingMallSessionValidation;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/validate-session",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/validate-session";
  export const random = (): IShoppingMallSessionValidation =>
    typia.random<IShoppingMallSessionValidation>();
  export const simulate = (
    connection: IConnection,
    props: validateSession.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: validateSession.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
