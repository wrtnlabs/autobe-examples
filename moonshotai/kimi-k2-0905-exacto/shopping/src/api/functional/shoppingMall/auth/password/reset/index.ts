import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallPasswordReset } from "../../../../../structures/IShoppingMallPasswordReset";

/**
 * Initiate a password reset process for users who have forgotten their
 * passwords. This operation sends a secure password reset link or token to the
 * user's registered email address.
 *
 * The system validates that the provided email address exists in the database
 * and corresponds to an active user account. If valid, it generates a
 * time-limited, cryptographically secure reset token and sends it via email.
 * The token is designed to expire after a configurable time period (typically
 * 1-4 hours) to maintain security.
 *
 * Security measures include rate limiting to prevent abuse, email validation,
 * token generation with sufficient entropy, and logging of reset attempts for
 * audit purposes. The operation does not reveal whether the email exists to
 * prevent user enumeration attacks.
 *
 * Related operations: Password change (PUT /auth/password/change), User login
 * (POST /auth/login).
 *
 * @param props.connection
 * @param props.body Password reset request containing the user's email address
 * @path /shoppingMall/auth/password/reset
 * @accessor api.functional.shoppingMall.auth.password.reset.requestReset
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function requestReset(
  connection: IConnection,
  props: requestReset.Props,
): Promise<requestReset.Response> {
  return true === connection.simulate
    ? requestReset.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestReset.METADATA,
          path: requestReset.path(),
          status: null,
        },
        props.body,
      );
}
export namespace requestReset {
  export type Props = {
    /** Password reset request containing the user's email address */
    body: IShoppingMallPasswordReset.ICreate;
  };
  export type Body = IShoppingMallPasswordReset.ICreate;
  export type Response = IShoppingMallPasswordReset;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/password/reset",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/password/reset";
  export const random = (): IShoppingMallPasswordReset =>
    typia.random<IShoppingMallPasswordReset>();
  export const simulate = (
    connection: IConnection,
    props: requestReset.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: requestReset.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
