import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallResendVerification } from "../../../../../structures/IShoppingMallResendVerification";
import { IShoppingMallResendVerificationResponse } from "../../../../../structures/IShoppingMallResendVerificationResponse";

/**
 * Resend email verification messages to customers who need to complete email
 * address verification during registration. This operation provides fallback
 * verification for users who didn't receive original verification emails or
 * need to re-send due to expired tokens or email delivery failures.
 *
 * Email re-sending is available during the registration process when accounts
 * remain in unverified status, typically within the first 24-48 hours after
 * account creation. The system generates fresh verification tokens with updated
 * expiration times while implementing rate limiting to prevent abuse or
 * excessive email volume to single addresses.
 *
 * The operation maintains verification request history for security monitoring
 * and provides technical details about delivery status through email service
 * provider integration. Users can request re-verification multiple times within
 * specified intervals while the account remains unverified, helping ensure
 * legitimate users complete registration successfully.
 *
 * @param props.connection
 * @param props.body Email resend verification request with customer identifier
 * @path /shoppingMall/auth/verification/resend
 * @accessor api.functional.shoppingMall.auth.verification.resend.resendVerification
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function resendVerification(
  connection: IConnection,
  props: resendVerification.Props,
): Promise<resendVerification.Response> {
  return true === connection.simulate
    ? resendVerification.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...resendVerification.METADATA,
          path: resendVerification.path(),
          status: null,
        },
        props.body,
      );
}
export namespace resendVerification {
  export type Props = {
    /** Email resend verification request with customer identifier */
    body: IShoppingMallResendVerification;
  };
  export type Body = IShoppingMallResendVerification;
  export type Response = IShoppingMallResendVerificationResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/verification/resend",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/verification/resend";
  export const random = (): IShoppingMallResendVerificationResponse =>
    typia.random<IShoppingMallResendVerificationResponse>();
  export const simulate = (
    connection: IConnection,
    props: resendVerification.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: resendVerification.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
