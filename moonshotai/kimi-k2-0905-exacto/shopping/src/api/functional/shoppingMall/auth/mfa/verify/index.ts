import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallMfaVerify } from "../../../../../structures/IShoppingMallMfaVerify";
import { IShoppingMallAuthentication } from "../../../../../structures/IShoppingMallAuthentication";

/**
 * Verify multi-factor authentication code during the login process for enhanced
 * account security. This operation validates time-based one-time passwords
 * (TOTP) or SMS verification codes submitted by users as the second
 * authentication factor after successful password verification.
 *
 * The operation processes MFA verification attempts by validating the provided
 * code against the stored secret or generated token, implementing appropriate
 * time windows for code validity, and handling multiple verification method
 * types including authenticator applications and SMS-based codes. Security
 * measures include rate limiting to prevent brute force attacks, automatic
 * session creation upon successful verification, and comprehensive audit
 * logging for security monitoring.
 *
 * This operation serves as the final step in the two-factor authentication
 * flow, creating authenticated sessions with appropriate JWT tokens that grant
 * platform access based on user role permissions. The implementation supports
 * both customer and seller accounts with role-specific session management,
 * device recognition for enhanced security, and automatic backup code
 * validation when primary methods are unavailable.
 *
 * The verification process integrates with the shopping_mall_customer_sessions,
 * shopping_mall_seller_sessions, and shopping_mall_admin_sessions tables to
 * establish authenticated sessions with comprehensive security tracking
 * including IP address logging, device fingerprinting, and session expiration
 * management for multi-device access control.
 *
 * @param props.connection
 * @param props.body Multi-factor authentication verification request containing
 *   the verification code and optional backup code information for account
 *   access confirmation
 * @path /shoppingMall/auth/mfa/verify
 * @accessor api.functional.shoppingMall.auth.mfa.verify.verifyMfa
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verifyMfa(
  connection: IConnection,
  props: verifyMfa.Props,
): Promise<verifyMfa.Response> {
  return true === connection.simulate
    ? verifyMfa.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verifyMfa.METADATA,
          path: verifyMfa.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verifyMfa {
  export type Props = {
    /**
     * Multi-factor authentication verification request containing the
     * verification code and optional backup code information for account
     * access confirmation
     */
    body: IShoppingMallMfaVerify.ICreate;
  };
  export type Body = IShoppingMallMfaVerify.ICreate;
  export type Response = IShoppingMallAuthentication.ITokenResponse;

  export const METADATA = {
    method: "POST",
    path: "/shoppingMall/auth/mfa/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/auth/mfa/verify";
  export const random = (): IShoppingMallAuthentication.ITokenResponse =>
    typia.random<IShoppingMallAuthentication.ITokenResponse>();
  export const simulate = (
    connection: IConnection,
    props: verifyMfa.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verifyMfa.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
