import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallSeller } from "../../../structures/IShoppingMallSeller";

/**
 * Retrieve detailed seller information from the shopping mall seller database
 * table. This operation returns comprehensive seller profile data including
 * business information, verification status, contact details, and operational
 * metrics.
 *
 * The operation accesses the shopping_mall_seller table which contains primary
 * seller account information including business name, registration details,
 * verification status, and commission rates. The response includes all
 * essential seller profile fields needed for seller dashboard display,
 * administrator management, and customer-facing seller information.
 *
 * Security considerations include ensuring only authorized users can access
 * seller profile information. Public seller information may be accessible while
 * sensitive business details require appropriate permissions. The operation
 * supports marketplace transparency by providing seller verification status and
 * business information visible to potential customers.
 *
 * This operation serves multiple stakeholder needs including seller account
 * verification, customer decision-making support, platform administration for
 * seller management, and analytics for seller relationship management.
 *
 * @param props.connection
 * @param props.sellerId Unique identifier (UUID) of the target seller for
 *   retrieving detailed profile information
 * @path /shoppingMall/sellers/:sellerId
 * @accessor api.functional.shoppingMall.sellers.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Unique identifier (UUID) of the target seller for retrieving detailed
     * profile information
     */
    sellerId: string & tags.Format<"uuid">;
  };
  export type Response = IShoppingMallSeller;

  export const METADATA = {
    method: "GET",
    path: "/shoppingMall/sellers/:sellerId",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/shoppingMall/sellers/${encodeURIComponent(props.sellerId ?? "null")}`;
  export const random = (): IShoppingMallSeller =>
    typia.random<IShoppingMallSeller>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("sellerId")(() => typia.assert(props.sellerId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
