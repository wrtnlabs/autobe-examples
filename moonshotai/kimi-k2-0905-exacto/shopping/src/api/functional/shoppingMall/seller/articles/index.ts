/**
 * Retrieves a filtered and paginated list of platform articles with advanced
 * search capabilities. This operation operates on the shopping_mall_articles
 * table and provides sophisticated content filtering for editorial management,
 * content discovery, and administrative oversight across the marketplace
 * platform.
 *
 * The search system supports multiple filtering criteria including publication
 * status (draft, published, archived), content categorization, creation date
 * ranges, author attribution, and SEO optimization scoring. Articles can be
 * filtered by channel association, section assignment, and featured content
 * priority enabling targeted content management workflows for different
 * marketplace environments.
 *
 * Performance optimization includes intelligent indexing on article titles,
 * content text, and metadata fields while maintaining comprehensive full-text
 * search capabilities across article body content. The system automatically
 * calculates content engagement metrics, keyword relevance scoring, and SEO
 * effectiveness indicators to support editorial decision-making and content
 * optimization strategies.
 *
 * Administrative features include bulk content management capabilities,
 * publication workflow state filtering, and cross-channel content analysis for
 * marketplace operators managing multiple selling environments. The operation
 * respects content permissions ensuring users only access articles from their
 * authorized channels and sections while maintaining comprehensive audit trails
 * for content access and modification activities.
 *
 * @param props.connection
 * @param props.body Advanced search criteria and pagination parameters for
 *   article filtering including publication status, categorization filters,
 *   date ranges, content type specifications, and sorting preferences.
 * @path /shoppingMall/seller/articles
 * @accessor api.functional.shoppingMall.seller.articles.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Advanced search criteria and pagination parameters for article
     * filtering including publication status, categorization filters, date
     * ranges, content type specifications, and sorting preferences.
     */
    body: IShoppingMallArticle.IRequest;
  };
  export type Body = IShoppingMallArticle.IRequest;
  export type Response = IPageIShoppingMallArticle.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/seller/articles",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/shoppingMall/seller/articles";
  export const random = (): IPageIShoppingMallArticle.ISummary =>
    typia.random<IPageIShoppingMallArticle.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
