import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia, { tags } from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallOrderItem } from "../../../../../structures/IShoppingMallOrderItem";
import { IPageIShoppingMallOrderItem } from "../../../../../structures/IPageIShoppingMallOrderItem";

/**
 * Retrieve a filtered and paginated list of order items for a specific order in
 * the shopping mall platform. This operation queries the
 * shopping_mall_order_items table to return individual line items within an
 * order, supporting complex search criteria including fulfillment status
 * filtering, seller-based filtering, price range queries, and date range
 * searches for items added within specific time periods.
 *
 * The operation enables comprehensive order item analysis for various
 * stakeholders including customers reviewing their purchases, sellers managing
 * their portions of multi-seller orders, and administrators monitoring order
 * fulfillment across the marketplace. It supports filtering by
 * fulfillment_status to track items through the delivery process,
 * shopping_mall_seller_id to isolate specific seller contributions, and
 * price-based queries for financial reconciliation.
 *
 * Advanced features include sorting by various item attributes (price,
 * quantity, fulfillment status, seller information), paginated results for
 * large orders, and the ability to search by product name snapshots for
 * historical accuracy. The response includes complete item details with product
 * information, pricing snapshots, shipping costs, and fulfillment tracking data
 * necessary for comprehensive order management and customer service
 * operations.
 *
 * @param props.connection
 * @param props.orderId Unique identifier of the target order whose items are
 *   being retrieved
 * @param props.body Search criteria and pagination parameters for filtering
 *   order items
 * @path /shoppingMall/seller/orders/:orderId/items
 * @accessor api.functional.shoppingMall.seller.orders.items.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique identifier of the target order whose items are being retrieved */
    orderId: string & tags.Format<"uuid">;

    /** Search criteria and pagination parameters for filtering order items */
    body: IShoppingMallOrderItem.IRequest;
  };
  export type Body = IShoppingMallOrderItem.IRequest;
  export type Response = IPageIShoppingMallOrderItem;

  export const METADATA = {
    method: "PATCH",
    path: "/shoppingMall/seller/orders/:orderId/items",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/shoppingMall/seller/orders/${encodeURIComponent(props.orderId ?? "null")}/items`;
  export const random = (): IPageIShoppingMallOrderItem =>
    typia.random<IPageIShoppingMallOrderItem>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("orderId")(() => typia.assert(props.orderId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
