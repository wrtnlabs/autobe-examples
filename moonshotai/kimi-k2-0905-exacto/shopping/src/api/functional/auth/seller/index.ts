/**
 * Seller registration endpoint for creating new merchant accounts. This
 * endpoint handles business verification requirements including tax
 * identification, business registration numbers, and official documentation.
 * Sellers must provide comprehensive business information including business
 * name, email, password, business registration details, tax ID, phone contact,
 * and business type classification. The system validates business registration
 * numbers against official databases, verifies tax ID formats, and initiates
 * manual verification workflows for compliance requirements within 2 business
 * days. Email verification is mandatory before sellers can access dashboard
 * functionality or list products for sale. Enhanced security protocols include
 * mandatory two-factor authentication setup, IP verification for initial login,
 * and comprehensive audit trail logging for all registration activities. The
 * registration process creates secure password hashes using industry-standard
 * algorithms and establishes seller-specific commission rates based on business
 * type and product categories. During verification pending status, sellers can
 * set up store profiles but cannot process orders or list products for sale
 * until manual verification is completed.
 *
 * @param props.connection
 * @param props.body Seller registration request with comprehensive business
 *   information including contact details, business verification documents, and
 *   payment setup requirements.
 * @setHeader token.access Authorization
 *
 * @path /auth/seller/join
 * @accessor api.functional.auth.seller.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
