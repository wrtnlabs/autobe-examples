import { IShoppingMallGuest } from "../../../structures/IShoppingMallGuest";

/**
 * Guest registration operation for creating anonymous guest sessions in the
 * shopping mall platform. This endpoint enables unauthenticated visitors to
 * establish temporary guest accounts that provide basic browsing capabilities
 * and session management without requiring personal information submission or
 * permanent account creation. The operation creates a new guest entry with
 * anonymous session tracking, IP address logging for security purposes, user
 * agent detection for device compatibility, and initial activity timestamp
 * recording. Guest accounts are designed for temporary access and facilitate
 * basic shopping cart functionality, product browsing history, and session
 * continuity across page visits while maintaining user anonymity and privacy.
 * The system automatically manages guest session expiration and cleanup
 * processes to maintain platform performance and data hygiene. This
 * registration process establishes the foundation for potential future customer
 * conversion while providing immediate marketplace access for anonymous
 * browsing and product discovery activities.
 *
 * @param props.connection
 * @param props.body Guest registration request containing anonymous session
 *   information for temporary account creation
 * @setHeader token.access Authorization
 *
 * @path /auth/guest/join
 * @accessor api.functional.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /**
     * Guest registration request containing anonymous session information
     * for temporary account creation
     */
    body: IShoppingMallGuest.ICreate;
  };
  export type Body = IShoppingMallGuest.ICreate;
  export type Response = IShoppingMallGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/auth/guest/join";
  export const random = (): IShoppingMallGuest.IAuthorized =>
    typia.random<IShoppingMallGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

