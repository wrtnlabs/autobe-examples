import { IConnection, HttpError } from "@nestia/fetcher";
import { PlainFetcher } from "@nestia/fetcher/lib/PlainFetcher";
import typia from "typia";
import { NestiaSimulator } from "@nestia/fetcher/lib/NestiaSimulator";

import { IShoppingMallProductSnapshot } from "../../../../structures/IShoppingMallProductSnapshot";
import { IPageIShoppingMallProductSnapshot } from "../../../../structures/IPageIShoppingMallProductSnapshot";

/**
 * Administrative access to product catalog version history and change tracking
 * archives for platform oversight and audit compliance. This operation provides
 * comprehensive product evolution tracking including complete pricing
 * histories, description modifications, category movements, and systematic
 * change attribution across managed marketplace products.
 *
 * The administrative interface enables revenue tracking analysis by monitoring
 * pricing modifications, capacity performance assessment across product
 * versions, compliance monitoring for content standard adherence, and seller
 * accountability verification for catalog accuracy and policy compliance.
 * Historical data supports comprehensive product performance evaluation
 * including pricing strategy effectiveness, content optimization impact
 * assessments, and long-term inventory trend analysis.
 *
 * Administrative oversight capabilities include multi-dimensional filtering by
 * temporal ranges, specific change attribution to seller management teams,
 * category-standard compliance tracking for marketplace quality maintenance,
 * and revenue impact analysis through historical pricing comparison across
 * product lifecycle phases.
 *
 * Access requires platform administrator authorization to maintain sensitive
 * audit data confidentiality while providing marketplace oversight
 * capabilities. The system supports duty differentiation across monitoring,
 * compliance, and analytical administrative functions.
 *
 * @param props.connection
 * @param props.productCode Unique product SKU identifier for administrative
 *   snapshot retrieval
 * @param props.body Administrative audit trail request with comprehensive
 *   filtering for version analysis, change attribution, and oversight
 *   monitoring
 * @path /admin/products/:productCode/snapshots
 * @accessor api.functional.admin.products.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /** Unique product SKU identifier for administrative snapshot retrieval */
    productCode: string;

    /**
     * Administrative audit trail request with comprehensive filtering for
     * version analysis, change attribution, and oversight monitoring
     */
    body: IShoppingMallProductSnapshot.IRequest;
  };
  export type Body = IShoppingMallProductSnapshot.IRequest;
  export type Response = IPageIShoppingMallProductSnapshot;

  export const METADATA = {
    method: "PATCH",
    path: "/admin/products/:productCode/snapshots",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/admin/products/${encodeURIComponent(props.productCode ?? "null")}/snapshots`;
  export const random = (): IPageIShoppingMallProductSnapshot =>
    typia.random<IPageIShoppingMallProductSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productCode")(() => typia.assert(props.productCode));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
