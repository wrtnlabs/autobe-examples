import { tags } from "typia";

export namespace IShoppingMallMfaVerify {
  /**
   * Multi-factor authentication verification request containing security
   * verification information for account access confirmation within the
   * shopping mall marketplace platform.
   *
   * This request structure captures all necessary authentication credentials
   * and security context for comprehensive multi-factor verification
   * processing. The implementation supports both primary authentication
   * methods (TOTP codes) and fallback mechanisms (backup codes) while
   * maintaining detailed audit trails for security monitoring and compliance
   * requirements.
   *
   * Mandatory session context fields including href and referrer are required
   * for proper self-authentication operations, ensuring comprehensive audit
   * trail establishment and security monitoring across the marketplace
   * platform ecosystem.
   */
  export type ICreate = {
    /**
     * Six-digit TOTP (Time-based One-Time Password) authentication code
     * generated by an authenticator application or received via SMS for the
     * current login attempt. Must be exactly six numeric characters and
     * valid for the current 30-second time window.
     */
    code: string;

    /**
     * Emergency backup authentication code for account recovery when
     * primary MFA methods are unavailable. Optional alternative
     * verification method typically consisting of eight alphanumeric
     * characters provided during initial MFA setup.
     */
    backup_code?: string | null | undefined;

    /**
     * Unique identifier linking this verification attempt to the
     * established authentication session context for security correlation
     * and audit trail consistency across the shopping mall platform.
     */
    session_id?: string | null | undefined;

    /**
     * Client IP address for geographical verification and security
     * monitoring. Used for anomaly detection and access restriction
     * enforcement to prevent unauthorized access attempts from suspicious
     * locations.
     */
    ip_address?: (string & tags.Format<"ipv4">) | null | undefined;

    /**
     * Device fingerprint information including user agent and basic device
     * characteristics for security tracking and fraud detection. Captures
     * browser information, operating system details, and device
     * identifiers.
     */
    device_info?: string | null | undefined;

    /**
     * Verification attempt timestamp for time-sensitive code validation and
     * replay attack prevention. Must be in ISO 8601 format with timezone
     * information for accurate time window validation.
     */
    timestamp?: (string & tags.Format<"date-time">) | null | undefined;

    /**
     * Connection URL (current page URL) - MANDATORY session context field
     * for self-authentication operations to establish proper audit trail
     * and maintain security correlation across verification flows.
     */
    href: string;

    /**
     * Referrer URL (previous page URL) - MANDATORY session context field
     * for self-authentication operations to establish proper audit trail
     * and enable comprehensive security analysis of user navigation
     * patterns.
     */
    referrer: string;
  };
}
