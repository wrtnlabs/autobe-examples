import { tags } from "typia";

/**
 * Security context validation including session information and device
 * fingerprinting.
 *
 * Contains validation data to ensure the MFA setup request originates from a
 * legitimate authenticated session and trusted device context.
 *
 * This structure provides comprehensive security validation for multi-factor
 * authentication operations, including session verification and device
 * identification. The session ID validates the current authenticated state,
 * device fingerprinting helps detect unusual access patterns, and IP address
 * logging supports audit trail requirements.
 *
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export type ISecurityContext = {
  /**
   * Current authenticated session identifier for validation during MFA setup
   * process
   */
  session_id?: (string & tags.Format<"uuid">) | undefined;

  /**
   * Client IP address for security logging and session validation. Provides
   * IP tracking for security audit trails and geographic analysis during MFA
   * operations.
   */
  ip_address: (string & tags.Format<"ipv4">) | null;

  /** Device fingerprint identifier for security validation during MFA setup */
  device_fingerprint?: (string & tags.MaxLength<255>) | undefined;

  /**
   * Connection URL (current page URL) for session tracking and security
   * context during MFA setup operations. Provides context about the
   * environment where MFA setup was initiated for audit and support
   * purposes.
   */
  href: string & tags.Format<"uri">;

  /**
   * Referrer URL (previous page URL) for session tracking and security
   * context validation during MFA setup. Helps identify the navigation path
   * that led to MFA setup initiation for security monitoring and user
   * experience optimization.
   */
  referrer: string & tags.Format<"uri">;
};
