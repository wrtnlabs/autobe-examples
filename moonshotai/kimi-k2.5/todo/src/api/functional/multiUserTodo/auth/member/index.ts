/**
 * Register a new member account with email and password credentials.
 *
 * This operation creates a new member record in the multi_user_todo_members table with the provided email and hashed password. The member's id is generated as a UUID v7. Upon successful creation, a new session is established with both access and refresh tokens.
 *
 * The email must be unique across all members. Password requirements include minimum 8 characters. The password is hashed using bcrypt before storage - plain text passwords are never persisted.
 *
 * On success, returns an IAuthorized response containing both access_token (short-lived, 15 minutes) and refresh_token (long-lived, 7 days). The access_token should be used for subsequent authenticated requests, while the refresh_token enables obtaining new access tokens when the current one expires.
 *
 * Related operations: After joining, members can use the access_token for authenticated operations, or call login if they need to re-authenticate later.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Member registration credentials with email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Implementation: Validate email uniqueness against
 *   multi_user_todo_members table. Hash password using bcrypt (cost factor 10).
 *   Create member record with UUID v7 for id. Create session record with
 *   access_token (15 min expiry) and refresh_token (7 days expiry). Return
 *   tokens in IAuthorized response.
 *
 * Transaction: Member + Session creation in same transaction.
 *
 * Validation: Email must be unique, password minimum 8 characters.
 *
 * Error cases: 409 Conflict if email exists, 400 for weak password.
 * @path /multiUserTodo/auth/member/join
 * @accessor api.functional.multiUserTodo.auth.member.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
