/**
 * Verify a password reset token to confirm its validity before allowing
 * password reset.
 *
 * This operation validates the password reset token that was sent to the
 * member's email address. When a member clicks the password reset link in their
 * email, the application extracts the token and sends it to this endpoint for
 * verification. The endpoint checks the todo_app_password_reset_tokens table to
 * ensure the token exists and has not expired.
 *
 * Upon successful verification, the endpoint returns minimal member information
 * including the member's ID and email address. This information is required for
 * the subsequent password reset operation where the new password will be set.
 * The member identification ensures that the password change is applied to the
 * correct account.
 *
 * Security considerations include automatic cleanup of expired tokens during
 * the validation process. Invalid or expired tokens result in appropriate error
 * responses (401 for invalid tokens, 410 for expired tokens) to prevent brute
 * force attempts. The endpoint does not reveal whether an email exists in the
 * system for security reasons.
 *
 * This verification step is a prerequisite for the actual password reset
 * operation (typically PUT /auth/members/password/reset). The returned member
 * information should be used to construct the subsequent reset request.
 *
 * @param props.connection
 * @param props.body Password reset token to verify
 * @x-autobe-specification Validate the provided password reset token against the todo_app_password_reset_tokens table. Check that the token exists and has not expired (expires_at > NOW()). If valid, retrieve the associated member from todo_app_members table and return minimal member information (id and email). If token is invalid or expired, return 401 Unauthorized or 410 Gone respectively. Clean up expired tokens during validation as a maintenance operation.
 * @path /todoApp/member/auth/members/password/reset/verify
 * @accessor api.functional.todoApp.member.auth.members.password.reset.verify
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function verify(
  connection: IConnection,
  props: verify.Props,
): Promise<verify.Response> {
  return true === connection.simulate
    ? verify.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...verify.METADATA,
          path: verify.path(),
          status: null,
        },
        props.body,
      );
}
export namespace verify {
  export type Props = {
    /** Password reset token to verify */
    body: ITodoAppPasswordResetToken.IVerify;
  };
  export type Body = ITodoAppPasswordResetToken.IVerify;
  export type Response = ITodoAppMember.ISummary;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/member/auth/members/password/reset/verify",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () =>
    "/todoApp/member/auth/members/password/reset/verify";
  export const random = (): ITodoAppMember.ISummary =>
    typia.random<ITodoAppMember.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: verify.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: verify.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
