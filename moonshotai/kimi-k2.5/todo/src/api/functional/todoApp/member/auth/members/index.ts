/**
 * Log out an authenticated member and invalidate their session tokens.
 *
 * This operation allows authenticated members to logout from the Todo
 * application, providing control over session invalidation. Members can choose
 * to logout from just the current session (single device) or from all active
 * sessions across all devices. The operation validates the JWT access token
 * from the Authorization header, identifies the authenticated user, and
 * performs the appropriate token revocation based on the requested scope.
 *
 * When logging out from the current session only, the system revokes the
 * specific refresh token associated with the current session while preserving
 * other active sessions. When logging out from all sessions, the system revokes
 * all refresh tokens for the user, forcing re-authentication on all devices. In
 * both cases, the current access token is added to a short-term blacklist to
 * prevent its reuse until natural expiration.
 *
 * Security considerations include proper token validation, comprehensive audit
 * logging of logout events, and consistent error handling. The operation
 * returns a generic success response regardless of the actual logout scope to
 * prevent information leakage. Related operations include the login endpoint
 * (POST /auth/members/login) which creates sessions, and the token refresh
 * endpoint for obtaining new access tokens.
 *
 * @param props.connection
 * @param props.body Logout scope specification determining whether to logout
 *   from current session only or all active sessions
 * @x-autobe-specification Extract the Bearer access token from the Authorization header. Validate the JWT token signature, expiration, and blacklist status. Extract the user ID from the token subject claim. Parse the request body to determine logout scope ('current' or 'all'). If scope is 'current': find and revoke the refresh token associated with the current session in todo_app_member_sessions table. If scope is 'all': revoke ALL refresh tokens for the user. Add the access token to the blacklist with its expiration timestamp. Log the logout event to todo_app_audit_logs with user ID, IP address, user agent, and scope. Return success response with logout confirmation details.
 * @path /todoApp/member/auth/members/logout
 * @accessor api.functional.todoApp.member.auth.members.logout
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function logout(
  connection: IConnection,
  props: logout.Props,
): Promise<logout.Response> {
  return true === connection.simulate
    ? logout.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...logout.METADATA,
          path: logout.path(),
          status: null,
        },
        props.body,
      );
}
