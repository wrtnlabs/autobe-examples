export async function healthCheck(
  connection: IConnection,
): Promise<healthCheck.Response> {
  return true === connection.simulate
    ? healthCheck.simulate(connection)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...healthCheck.METADATA,
          path: healthCheck.path(),
          status: null,
        },
      );
}
export namespace healthCheck {
  export type Response = ITodoAppHealth;

  export const METADATA = {
    method: "GET",
    path: "/todoApp/health",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/health";
  export const random = (): ITodoAppHealth => typia.random<ITodoAppHealth>();
  export const simulate = (_connection: IConnection): Response => {
    return random();
  };
}
