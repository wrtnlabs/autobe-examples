import { ITodoAppGuest } from "../../../../structures/ITodoAppGuest";

/**
 * Creates a new temporary guest session for unauthenticated visitors.
 *
 * Generates a unique guest identifier and session record. Issues JWT access and
 * refresh tokens granting temporary access privileges.
 *
 * This endpoint is publicly accessible, serving as the entry point for guest
 * users. Guest sessions provide limited functionality for application
 * exploration before registration.
 *
 * Access tokens expire after 15 minutes, refresh tokens valid for 7 days.
 * Sessions can be used across page refreshes.
 *
 * Guests can later convert to full member accounts through member registration.
 *
 * @param props.connection
 * @param props.body Guest session creation request.
 * @setHeader token.access Authorization
 *
 * @x-autobe-specification Generate UUID for guest, create record in todo_app_guests, generate secure refresh token, hash and store in todo_app_guest_sessions, generate JWT access token with 15-min expiration, return both tokens.
 * @path /todoApp/auth/guest/join
 * @accessor api.functional.todoApp.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
export namespace join {
  export type Props = {
    /** Guest session creation request. */
    body: ITodoAppGuest.IJoin;
  };
  export type Body = ITodoAppGuest.IJoin;
  export type Response = ITodoAppGuest.IAuthorized;

  export const METADATA = {
    method: "POST",
    path: "/todoApp/auth/guest/join",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/todoApp/auth/guest/join";
  export const random = (): ITodoAppGuest.IAuthorized =>
    typia.random<ITodoAppGuest.IAuthorized>();
  export const simulate = (
    connection: IConnection,
    props: join.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: join.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

