import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoGuest } from "../../../../api/structures/IMultiUserTodoGuest";
import { postMultiUserTodoAuthGuestJoin } from "../../../../providers/postMultiUserTodoAuthGuestJoin";
import { postMultiUserTodoAuthGuestRefresh } from "../../../../providers/postMultiUserTodoAuthGuestRefresh";

@Controller("/multiUserTodo/auth/guest")
export class MultiusertodoAuthGuestController {
  /**
   * Creates a new temporary guest identity for unauthenticated visitors.
   *
   * This endpoint allows unauthenticated visitors to obtain a temporary identity without providing credentials. The guest identity enables immediate access to the application without requiring email or password registration. Upon successful creation, authentication tokens are returned that establish a session for the guest.
   *
   * **Implementation Details:**
   * - Generates a unique device identifier for guest recognition
   * - Creates a new guest record in the multi_user_todo_guests table
   * - Establishes a session record in multi_user_todo_guest_sessions with IP, href, and referrer tracking
   * - Issues JWT access and refresh tokens valid for the guest identity
   * - Session expiration is enforced via the expired_at field in the session record
   *
   * **Related Operations:**
   * - Use POST /auth/guest/refresh to renew an expiring access token using the refresh token
   * - Guest identities can be converted to member accounts through the member registration flow
   *
   * **Security Considerations:**
   * - Device identifiers should be unique and persistent across sessions
   * - Session metadata (IP, referrer) is captured for audit purposes
   * - Tokens have limited lifetime and must be refreshed periodically
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest registration request containing optional device information.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Creates a new guest identity for unauthenticated visitors. The service generates a unique device identifier if not provided, creates a guest record in multi_user_todo_guests, and establishes a new session in multi_user_todo_guest_sessions. Returns authentication tokens (access token and refresh token) that grant temporary access to the system. The implementation should validate device_id format if provided, generate UUIDv4 for guest ID and device_id when missing, set session expiration based on configuration, and return tokens that include the guest identity claims.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoGuest.IJoin,
  ): Promise<IMultiUserTodoGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renews the access token for an authenticated guest session.
   *
   * This endpoint allows guest sessions to maintain access by refreshing their authentication tokens before expiration. The refresh token, obtained during initial guest creation, must be provided to exchange for a new access token.
   *
   * **Implementation Details:**
   * - Validates the provided refresh token signature and claims
   * - Extracts the guest ID from the token and verifies the session exists in multi_user_todo_guest_sessions
   * - Checks the session has not exceeded its expiration time (expired_at field)
   * - Issues a new access token with updated expiration claims while maintaining the same guest identity
   * - The refresh token remains valid for subsequent refresh operations until its own expiration
   *
   * **Related Operations:**
   * - Call POST /auth/guest/join first to obtain initial tokens
   * - Use the new access token returned by this endpoint for subsequent API calls
   *
   * **Security Considerations:**
   * - Refresh tokens have a longer lifetime than access tokens but still expire
   * - Sessions are invalidated when expired_at is reached
   * - Failed refresh attempts indicate the session has ended and a new join is required
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the refresh token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Renews an expiring access token for a guest using a valid refresh token. The service validates the refresh token against the guest session in multi_user_todo_guest_sessions, verifies the session has not expired (expired_at > current time), and issues a new access token. The implementation should extract the guest ID from the refresh token claims, lookup the session to confirm validity, check that expired_at has not passed, generate a new access token with the same guest identity, and return the new token without changing the refresh token.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoGuest.IRefresh,
  ): Promise<IMultiUserTodoGuest.IAuthorized> {
    try {
      return await postMultiUserTodoAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
