import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { postMultiUserTodoAuthMemberJoin } from "../../../../providers/postMultiUserTodoAuthMemberJoin";
import { postMultiUserTodoAuthMemberLogin } from "../../../../providers/postMultiUserTodoAuthMemberLogin";
import { postMultiUserTodoAuthMemberRefresh } from "../../../../providers/postMultiUserTodoAuthMemberRefresh";

@Controller("/multiUserTodo/auth/member")
export class MultiusertodoAuthMemberController {
  /**
   * Register a new member account with email and password credentials.
   *
   * This operation creates a new member record in the multi_user_todo_members table with the provided email and hashed password. The member's id is generated as a UUID v7. Upon successful creation, a new session is established with both access and refresh tokens.
   *
   * The email must be unique across all members. Password requirements include minimum 8 characters. The password is hashed using bcrypt before storage - plain text passwords are never persisted.
   *
   * On success, returns an IAuthorized response containing both access_token (short-lived, 15 minutes) and refresh_token (long-lived, 7 days). The access_token should be used for subsequent authenticated requests, while the refresh_token enables obtaining new access tokens when the current one expires.
   *
   * Related operations: After joining, members can use the access_token for authenticated operations, or call login if they need to re-authenticate later.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration credentials with email and password
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation: Validate email uniqueness against
     *   multi_user_todo_members table. Hash password using bcrypt (cost factor
     *   10). Create member record with UUID v7 for id. Create session record
     *   with access_token (15 min expiry) and refresh_token (7 days expiry).
     *   Return tokens in IAuthorized response.
   *
   * Transaction: Member + Session creation in same transaction.
   *
   * Validation: Email must be unique, password minimum 8 characters.
   *
   * Error cases: 409 Conflict if email exists, 400 for weak password.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.IJoin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing member with email and password credentials.
   *
   * This operation validates the provided email and password against records in the multi_user_todo_members table. The email lookup uses the unique index on the email column. Password verification uses bcrypt to compare the provided plain text password with the stored password_hash.
   *
   * Soft-deleted members (where deleted_at is not null) cannot authenticate and will receive a 403 Forbidden response. This ensures account deletion is respected even if credentials are known.
   *
   * Upon successful authentication, a new session is created in the multi_user_todo_member_sessions table with a fresh access_token and refresh_token pair. The session tracks the member's id, IP address, referrer, and browser metadata for security auditing.
   *
   * Session tokens have different lifespans: access_token expires after 15 minutes for security, while refresh_token is valid for 7 days to enable seamless token renewal. Members should call the refresh endpoint when access_token expires.
   *
   * Related operations: Use the returned access_token for all authenticated API calls. Call refresh when access_token nears expiration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login credentials with email and password
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation: Query multi_user_todo_members by
     *   email. Verify password hash matches using bcrypt.compare(). Check if
     *   member deleted_at is null (soft deleted members cannot login). Generate
     *   new access_token (15 min) and refresh_token (7 days). Create session
     *   record in multi_user_todo_member_sessions. Return IAuthorized response.
   *
   * Security: Rate limit 5 attempts per IP per minute.
   *
   * Validation: Email format validation, password presence check.
   *
   * Error cases: 401 Unauthorized for invalid credentials, 403 Forbidden for deleted accounts.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IMultiUserTodoMember.ILogin,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh access token using a valid refresh token.
   *
   * This operation enables members to obtain new access tokens without re-entering credentials. The refresh_token provided in the request body is validated against the multi_user_todo_member_sessions table, checking both that the session exists and has not expired (expired_at > now()).
   *
   * For security, the refresh endpoint implements token rotation: the old refresh_token is immediately invalidated and replaced with a new one in the same response. This prevents replay attacks where a stolen refresh_token could be used repeatedly.
   *
   * The operation also verifies that the associated member account is still active (deleted_at is null). If the member account has been soft-deleted since the session was created, the refresh is denied with a 403 Forbidden response.
   *
   * Both new tokens have fresh expiration times: access_token for 15 minutes, refresh_token for 7 days from the time of refresh. The session metadata in multi_user_todo_member_sessions is updated with these new values.
   *
   * Related operations: Call this endpoint when access_token expires (typically 401 response from other endpoints). The new access_token can immediately be used for subsequent authenticated requests.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token to obtain new access token
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation: Extract refresh_token from
     *   request body. Query multi_user_todo_member_sessions by refresh_token.
     *   Verify session exists and expired_at > now(). Check that associated
     *   member exists and deleted_at is null. Generate new access_token and new
     *   refresh_token with fresh expiry times. Update session record in
     *   database. Return IAuthorized with new tokens.
   *
   * Security: Old refresh_token is invalidated immediately (replaced with new one). This prevents token replay attacks.
   *
   * Validation: Refresh token format validation (JWT structure).
   *
   * Error cases: 401 Unauthorized for invalid token, 401 for expired session, 403 if member account deleted.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IMultiUserTodoMember.IRefresh,
  ): Promise<IMultiUserTodoMember.IAuthorized> {
    try {
      return await postMultiUserTodoAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
