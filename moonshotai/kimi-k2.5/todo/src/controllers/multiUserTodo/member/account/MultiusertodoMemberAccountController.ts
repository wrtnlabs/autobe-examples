import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteMultiUserTodoMemberAccount } from "../../../../providers/deleteMultiUserTodoMemberAccount";

@Controller("/multiUserTodo/member/account")
export class MultiusertodoMemberAccountController {
  /**
   * Permanently delete the authenticated member's account and all associated data.
   *
   * This operation permanently removes the member account, including all todos, edit histories, and trash items owned by the member. This action is irreversible and cannot be undone.
   *
   * Upon successful deletion:
   * - All active todos belonging to the member are permanently removed
   * - All todos currently in trash are permanently removed
   * - All edit history entries for the member's todos are permanently removed
   * - The member's session is terminated
   * - The email address becomes available for new account registration
   *
   * This endpoint requires authentication as a member. Unauthenticated requests will be rejected. After successful deletion, the client should clear any stored session credentials.
   *
   * The operation performs a hard delete on the multi_user_todo_members record and cascades to related entities including multi_user_todo_todos, multi_user_todo_histories, and multi_user_todo_todos_in_trash.
   *
   * This is a destructive operation that removes all data without recovery options. Members should be warned about the permanent nature of this action before confirmation.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Authenticate the requesting member using session/token middleware. Extract member ID from authentication context.
   *
   * Validate the member exists in multi_user_todo_members table by id. If not found, return 404 error.
   *
   * Execute cascading permanent deletion in a database transaction:
   * 1. Delete all edit history entries where todo_id IN (SELECT id FROM multi_user_todo_todos WHERE member_id = current_member_id)
   * 2. Delete all records from multi_user_todo_todos_in_trash where member_id = current_member_id
   * 3. Delete all todos from multi_user_todo_todos where member_id = current_member_id
   * 4. Delete the member record from multi_user_todo_members where id = current_member_id
   * 5. Delete any associated password reset tokens from multi_user_todo_member_password_resets for this member
   *
   * Terminate the member's active sessions by deleting records from multi_user_todo_member_sessions where member_id = current_member_id.
   *
   * Commit transaction. If any step fails, rollback and return 500 error.
   *
   * Clear any cached session data. Return 200 OK with empty body.
   *
   * Edge cases:
   * - If member is already being deleted (concurrent request), handle gracefully
   * - Ensure email uniqueness constraint allows re-registration after deletion
   * - Transaction must succeed completely or fail completely to avoid partial data
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<void> {
    try {
      return await deleteMultiUserTodoMemberAccount({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
