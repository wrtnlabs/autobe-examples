import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IMultiUserTodoMember } from "../../../../api/structures/IMultiUserTodoMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putMultiUserTodoMemberPassword } from "../../../../providers/putMultiUserTodoMemberPassword";

@Controller("/multiUserTodo/member/password")
export class MultiusertodoMemberPasswordController {
  /**
   * Change the authenticated member's password.
   *
   * This operation allows authenticated members to update their account password. The member must provide their current password for verification purposes before the new password can be set. This security measure ensures that only the legitimate account owner can modify the authentication credentials.
   *
   * The current password is validated against the stored password_hash in the multi_user_todo_members table. If the current password does not match, the request is rejected with an authentication error. Upon successful validation, the password_hash is updated with a hash of the new password.
   *
   * The password change takes effect immediately. All future authentication attempts must use the new password. Existing sessions remain valid and are not invalidated by this operation.
   *
   * This operation is only accessible to authenticated members. Guests cannot change passwords as they do not have established credentials in the system.
   *
   * @param connection
   * @param body Current password for verification and the new password to set
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification 1. Extract the authenticated member ID from the
     *   request context (session/token). 2. Verify the current_password
     *   provided in the request body matches the stored password_hash for the
     *   member: - Retrieve the member record from multi_user_todo_members using
     *   the authenticated member ID - Compare the provided current_password
     *   with the stored password_hash using appropriate password hashing
     *   comparison - If passwords do not match, return authentication error
     *   (401 or 403) 3. Validate the new_password meets password strength
     *   requirements (if any business rules apply). 4. Hash the new_password
     *   using the same hashing algorithm used for initial registration. 5.
     *   Update the password_hash field in multi_user_todo_members table for the
     *   member. 6. Update the updated_at timestamp to reflect the password
     *   change. 7. Return the updated member record.
   *
   * Edge cases:
   * - Current password mismatch: Reject with authentication error
   * - New password same as current: Accept but may want to warn (implementer's choice)
   * - Missing required fields: Validation error (400)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async updatePassword(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IMultiUserTodoMember.IUpdatePassword,
  ): Promise<IMultiUserTodoMember> {
    try {
      return await putMultiUserTodoMemberPassword({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
