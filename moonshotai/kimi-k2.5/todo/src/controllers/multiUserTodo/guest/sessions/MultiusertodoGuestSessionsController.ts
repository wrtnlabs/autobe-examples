import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IMultiUserTodoMemberSession } from "../../../../api/structures/IMultiUserTodoMemberSession";
import { IPageIMultiUserTodoMemberSession } from "../../../../api/structures/IPageIMultiUserTodoMemberSession";
import { GuestAuth } from "../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../decorators/payload/GuestPayload";
import { getMultiUserTodoGuestSessionsSessionId } from "../../../../providers/getMultiUserTodoGuestSessionsSessionId";
import { patchMultiUserTodoGuestSessions } from "../../../../providers/patchMultiUserTodoGuestSessions";

@Controller("/multiUserTodo/guest/sessions")
export class MultiusertodoGuestSessionsController {
  /**
   * Query and filter active member sessions.
   *
   * This operation allows an authenticated member to view a filtered and paginated list of their active sessions (device, location, browser information) for transparency and security monitoring.
   *
   * The request body supports filtering by IP address, href/referrer patterns, creation date ranges, and session expiration status. Results are paginated and sorted by creation time (most recent first by default).
   *
   * Access is restricted to the authenticated member's own sessions only - cross-user session access is prohibited and returns an empty result set or unauthorized error.
   *
   * @param connection
   * @param body Search criteria and pagination for sessions
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query multi_user_todo_member_sessions table with filters for authenticated member.
   * - Filter by multi_user_todo_member_id from session context (authenticated user's ID)
   * - Support filtering by: ip (substring match), href (prefix/suffix), referrer (substring), created_at range, expired_at range
   * - Default sort: created_at DESC (newest sessions first)
   * - Apply pagination with cursor or offset/limit
   * - Return session summaries with access_token prefix (masked), created_at, expired_at, ip, href for security audit
   * - Do NOT return full access_token or refresh_token values
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @GuestAuth()
    guest: GuestPayload,
    @TypedBody()
    body: IMultiUserTodoMemberSession.IRequest,
  ): Promise<IPageIMultiUserTodoMemberSession.ISummary> {
    try {
      return await patchMultiUserTodoGuestSessions({
        guest,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific member session by its unique identifier.
   *
   * This operation returns comprehensive session data including the JWT access token, refresh token, connection metadata (IP address, referrer, href), and expiration timestamps. The session must belong to the currently authenticated member.
   *
   * Security Note: This endpoint requires authentication and only returns sessions belonging to the requesting member. Attempting to access another member's session will result in an access denied error.
   *
   * Related Operations:
   * - Session creation is handled during login operations
   * - Session termination uses DELETE /sessions/{sessionId}
   *
   * @param connection
   * @param sessionId The unique identifier of the member session to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the multi_user_todo_member_sessions table by the provided sessionId UUID. Verify that the session exists and belongs to the currently authenticated member (identified via access token in request headers). If the session does not exist, return 404 NOT FOUND. If the session exists but belongs to a different member, return 403 FORBIDDEN. Return all session fields including id, memberId, accessToken, refreshToken, ip, href, referrer, createdAt, and expiredAt.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IMultiUserTodoMemberSession> {
    try {
      return await getMultiUserTodoGuestSessionsSessionId({
        guest,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
