export namespace EcommerceMallProductVariantSnapshotAtInvertTransformer {
  export type Payload =
    Prisma.ecommerce_mall_product_variant_snapshotsGetPayload<
      ReturnType<typeof select>
    >;
  export function select() {
    return {
      select: {
        id: true,
        sku_code: true,
        price: true,
        created_at: true,
        optionValues:
          EcommerceMallProductVariantSnapshotOptionValueTransformer.select(),
      },
    } satisfies Prisma.ecommerce_mall_product_variant_snapshotsFindManyArgs;
  }
  export async function transform(
    input: Payload,
  ): Promise<IEcommerceMallProductVariantSnapshot.IInvert> {
    return {
      id: input.id,
      skuCode: input.sku_code,
      price: input.price,
      createdAt: input.created_at.toISOString(),
      optionValues: await ArrayUtil.asyncMap(
        input.optionValues,
        EcommerceMallProductVariantSnapshotOptionValueTransformer.transform,
      ),
      orderItem: {} as IEcommerceMallOrderItem.ISummary,
    };
  }
}
