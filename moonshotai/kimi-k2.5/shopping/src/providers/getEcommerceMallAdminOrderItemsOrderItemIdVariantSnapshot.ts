export async function getEcommerceMallAdminOrderItemsOrderItemIdVariantSnapshot(props: {
  admin: AdminPayload;
  orderItemId: string;
}): Promise<IEcommerceMallProductVariantSnapshot> {
  const orderItem =
    await MyGlobal.prisma.ecommerce_mall_order_items.findUniqueOrThrow({
      where: { id: props.orderItemId },
      select: {
        id: true,
        variantSnapshot:
          EcommerceMallProductVariantSnapshotTransformer.select(),
      },
    });
  if (orderItem.variantSnapshot === null) {
    throw new HttpException(
      "Variant snapshot not found for this order item",
      404,
    );
  }
  return await EcommerceMallProductVariantSnapshotTransformer.transform(
    orderItem.variantSnapshot,
  );
}
