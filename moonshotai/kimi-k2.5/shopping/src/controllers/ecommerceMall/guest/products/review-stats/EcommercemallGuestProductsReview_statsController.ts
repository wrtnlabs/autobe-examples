import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductReviewStat } from "../../../../../api/structures/IEcommerceMallProductReviewStat";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { getEcommerceMallGuestProductsProductIdReviewStats } from "../../../../../providers/getEcommerceMallGuestProductsProductIdReviewStats";

@Controller("/ecommerceMall/guest/products/:productId/review-stats")
export class EcommercemallGuestProductsReview_statsController {
  /**
   * Retrieve review statistics for a specific product, including average rating, total review count, and rating distribution breakdown.
   *
   * This endpoint provides aggregated review data suitable for product listing pages and statistics displays. The average rating is calculated from all non-deleted reviews for the product, expressed as a numeric value from 1.0 to 5.0 with one decimal precision.
   *
   * The key statistics returned include:
   * - Average rating: The arithmetic mean of all non-deleted review ratings
   * - Total review count: The number of reviews (non-deleted) contributing to the average
   * - Rating distribution: A breakdown showing how many reviews fall into each star rating (1-5 stars)
   *
   * This data is used to display star ratings, review counts, and distribution charts on product detail pages. Snapshots of deleted reviews are excluded from the calculation as they are preserved for audit purposes but not considered in the average rating.
   *
   * Related operations:
   * - GET /products/{productId}/reviews - Retrieve the actual review content and details
   * - GET /products/{productId} - Product detail which may include basic rating summary
   *
   * @param connection
   * @param productId The unique identifier of the product to get review statistics for
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the ecommerce_mall_reviews table filtered by product_id and where deleted_at is null. Calculate the average rating and count. Also query the distribution of ratings grouped by rating value (1-5).
   *
   * Return an object containing:
   * - averageRating: float rounded to 1 decimal place (calculated from non-deleted reviews)
   * - totalCount: integer count of non-deleted reviews for this product
   * - distribution: object with keys '1', '2', '3', '4', '5' representing count of reviews for each star rating
   *
   * The endpoint is read-only and must support efficient caching since product statistics are frequently accessed. Consider implementing materialized view or caching strategy for common products. If the product has no reviews, return averageRating of 0 and totalCount of 0 with all distribution counts at 0.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async reviewStats(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallProductReviewStat> {
    try {
      return await getEcommerceMallGuestProductsProductIdReviewStats({
        guest,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
