import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSeller } from "../../../../../api/structures/IEcommerceMallSeller";
import { GuestAuth } from "../../../../../decorators/GuestAuth";
import { GuestPayload } from "../../../../../decorators/payload/GuestPayload";
import { getEcommerceMallGuestSellersSellerIdProfile } from "../../../../../providers/getEcommerceMallGuestSellersSellerIdProfile";

@Controller("/ecommerceMall/guest/sellers/:sellerId/profile")
export class EcommercemallGuestSellersProfileController {
  /**
   * Retrieve the public profile of a seller by their unique identifier.
   *
   * This endpoint returns the complete shop profile information for a seller, including the shop name, description, and logo image. Seller profiles are publicly accessible and serve as the brand identity representing the seller's business to customers browsing the platform.
   *
   * When customers browse product listings or visit a seller's dedicated shop page, they can view this profile information to learn more about who they are purchasing from. The shop profile is established automatically when a seller account receives administrator approval.
   *
   * If the seller does not exist or does not have an approved profile, this endpoint will return a not found error.
   *
   * @param connection
   * @param sellerId The unique identifier (UUID) of the seller whose profile is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Query the ecommerce_mall_seller_profiles table by seller_id to retrieve the seller's profile record. The query should join with the ecommerce_mall_sellers table to verify the seller exists and their account status.
   *
   * Return the profile fields: shop name, shop description, and logo image URL. If the seller account is suspended, the profile should still be returned but with an indicator of the suspension status.
   *
   * Handle the case where the seller exists but has no profile (e.g., if registration is still pending) by returning a 404 error with an appropriate message.
   *
   * Caching: Consider short-term caching of seller profiles to improve performance for frequently viewed profiles.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @GuestAuth()
    guest: GuestPayload,
    @TypedParam("sellerId")
    sellerId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallSeller> {
    try {
      return await getEcommerceMallGuestSellersSellerIdProfile({
        guest,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
