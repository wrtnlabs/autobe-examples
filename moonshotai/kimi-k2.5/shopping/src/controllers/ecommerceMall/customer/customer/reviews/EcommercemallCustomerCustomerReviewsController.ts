import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallReview } from "../../../../../api/structures/IEcommerceMallReview";
import { IPageIEcommerceMallReview } from "../../../../../api/structures/IPageIEcommerceMallReview";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceMallCustomerCustomerReviews } from "../../../../../providers/patchEcommerceMallCustomerCustomerReviews";

@Controller("/ecommerceMall/customer/customer/reviews")
export class EcommercemallCustomerCustomerReviewsController {
  /**
   * Retrieve a paginated list of reviews written by the authenticated customer.
   *
   * This operation allows customers to view their complete review history, including ratings, text content, creation dates, and the products they reviewed. Reviews are sorted by newest first, showing the most recent feedback prominently.
   *
   * Each review entry includes the product information and purchase context, enabling customers to track their feedback across different orders. Deleted reviews are excluded from the results as they are no longer publicly visible.
   *
   * The operation supports filtering by date ranges and pagination parameters to efficiently browse large review histories.
   *
   * @param connection
   * @param body Pagination and filtering parameters for review list
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query ecommerce_mall_reviews table filtering by authenticated customer_id.
   * Apply pagination (limit/offset or cursor-based) from request body.
   * Filter out soft-deleted reviews (deleted_at IS NULL).
   * Sort by created_at DESC (newest first).
   * Join with ecommerce_mall_products to include product information.
   * Join with ecommerce_mall_orders to include order context.
   * Return paginated results with review summaries including rating, content, dates, and product details.
   * Validate that the requesting user is authenticated as a customer.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallReview.IRequest,
  ): Promise<IPageIEcommerceMallReview.ISummary> {
    try {
      return await patchEcommerceMallCustomerCustomerReviews({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
