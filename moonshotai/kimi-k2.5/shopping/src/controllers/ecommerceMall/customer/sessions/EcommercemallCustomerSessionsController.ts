import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerSession } from "../../../../api/structures/IEcommerceMallCustomerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerSessionsSessionId } from "../../../../providers/getEcommerceMallCustomerSessionsSessionId";
import { patchEcommerceMallCustomerSessions } from "../../../../providers/patchEcommerceMallCustomerSessions";

@Controller("/ecommerceMall/customer/sessions")
export class EcommercemallCustomerSessionsController {
  /**
   * Retrieve a paginated and filtered list of JWT authentication sessions across all actor types.
   *
   * This operation enables administrators to audit authentication activity by querying sessions from customers, sellers, administrators, and super administrators. Sessions are append-only security audit records that track successful login events with connection context metadata.
   *
   * **Security and Access Control:**
   * - Only administrators (admin and superAdmin actors) can access this endpoint
   * - Sessions are filtered by actor type, user ID, connection metadata, and temporal bounds
   * - Access to session data follows the Snapshot principle where authentication events are immutable audit trail records
   * - Session queries respect actor boundaries - administrators can view sessions across all user types
   *
   * **Search Capabilities:**
   * - Filter by actor type (customer, seller, admin, superAdmin)
   * - Filter by user ID to view sessions for a specific account
   * - Filter by connection metadata (IP address, referrer patterns)
   * - Filter by temporal range (creation time, expiration status)
   * - Filter by session status (active, expired, all)
   *
   * **Response Data:**
   * - Returns session summary information optimized for list display
   * - Each session includes connection metadata, temporal boundaries, and ownership
   * - Pagination supports cursor-based navigation for large result sets
   * - Sessions are ordered by creation time descending (newest first)
   *
   * **Related Operations:**
   * - Session data is automatically created during login operations (POST /customers/login, POST /sellers/login, etc.)
   * - Sessions expire based on security policies defined in temporal fields
   * - Session invalidation occurs on password change (section 288), account deletion, or logout
   *
   * @param connection
   * @param body Search criteria and pagination parameters for session queries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement unified session query across four session tables: ecommerce_mall_customer_sessions, ecommerce_mall_seller_sessions, ecommerce_mall_admin_sessions, ecommerce_mall_super_admin_sessions.
   *
   * **Query Logic:**
   * - Union query across all session tables with actor type discriminator
   * - Filter by request parameters: actorType (enum: customer, seller, admin, superAdmin), userId (UUID), ip (string pattern), referrer (string pattern), createdAt range, expiredAt range, isActive (boolean computed as expiredAt > now())
   *
   * **Database Query:**
   * ```sql
   * -- Conceptual union across session tables
   * SELECT 'customer' as actor_type, id, ip, href, referrer, created_at, expired_at, ecommerce_mall_customer_id as user_id
   * FROM ecommerce_mall_customer_sessions
   * UNION ALL
   * SELECT 'seller' as actor_type, id, ip, href, referrer, created_at, expired_at, ecommerce_mall_seller_id as user_id
   * FROM ecommerce_mall_seller_sessions
   * UNION ALL
   * ...
   * ORDER BY created_at DESC
   * ```
   *
   * **Index Utilization:**
   * - Use composite indexes on (user_id, created_at) and (created_at) for pagination
   * - Text search on ip/referrer using LIKE patterns
   * - Temporal filtering on created_at/expired_at columns
   *
   * **Pagination:**
   * - Cursor-based pagination using created_at timestamp
   * - Support page size configuration (default 20, max 100)
   * - Return total count and hasMore flag
   *
   * **Authorization:**
   * - Verify caller has admin or superAdmin actor type
   * - Reject with 403 if non-admin attempts access
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallCustomerSessions({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific session by its unique identifier.
   *
   * This endpoint returns the complete session record including the JWT access token, refresh token, actor identity, and session metadata. Sessions represent authenticated states established after successful login and bind users to their actor types (customer, seller, administrator, or super administrator).
   *
   * Administrators can use this endpoint to verify active sessions, monitor authentication status, and troubleshoot session-related issues. The response includes essential session information optimized for audit and monitoring purposes while excluding sensitive token details where appropriate.
   *
   * Session validation occurs on each request to ensure the user is properly authenticated. If a session is invalid, terminated, or expired, appropriate error responses are returned directing to re-authenticate.
   *
   * @param connection
   * @param sessionId Target session's unique identifier (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_customer_sessions, ecommerce_mall_seller_sessions, ecommerce_mall_admin_sessions, ecommerce_mall_super_admin_sessions, or ecommerce_mall_guest_sessions table based on the session actor type to retrieve the session record matching the provided sessionId UUID.
   *
   * Validate that the sessionId exists and corresponds to a valid session. If the session is not found, return a 404 error indicating the session does not exist.
   *
   * Return session details including: session ID, actor type (customer, seller, admin, superAdmin, guest), associated user ID, access token status, refresh token status, expiration timestamps, and creation timestamp.
   *
   * Administrators should have permission to view any session. Regular users should only be able to view their own active session. If an unauthorized user attempts to access another user's session, return a 403 Forbidden error.
   *
   * The operation follows standard session retrieval patterns used for authentication monitoring and security auditing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IEcommerceMallCustomerSession> {
    try {
      return await getEcommerceMallCustomerSessionsSessionId({
        customer,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
