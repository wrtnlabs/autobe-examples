import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProduct } from "../../../../../api/structures/IEcommerceMallProduct";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProductsProductIdDetail } from "../../../../../providers/getEcommerceMallCustomerProductsProductIdDetail";

@Controller("/ecommerceMall/customer/products/:productId/detail")
export class EcommercemallCustomerProductsDetailController {
  /**
   * Retrieve complete product details for a single product.
   *
   * This operation returns comprehensive product information including all images, category details, seller shop information, available variants with prices and stock status, and customer reviews. The first image in the sequence serves as the main thumbnail.
   *
   * Products without any variants are displayed but marked as unavailable for purchase. Out-of-stock variants are visually distinguished from available variants. The response includes the average customer rating and total review count calculated from all non-deleted reviews.
   *
   * If the product has been deleted (soft-deleted), it will not be returned. This endpoint is accessible to authenticated customers.
   *
   * @param connection
   * @param productId Product unique identifier (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Query the ecommerce_mall_products table by id
     *   where deleted_at is null.
   *
   * Fetch the following related data:
   * 1. Product images from ecommerce_mall_product_images ordered by display_order ascending
   * 2. Category details from ecommerce_mall_categories (name, description)
   * 3. Seller information from ecommerce_mall_sellers joined with ecommerce_mall_seller_profiles (shop_name, logo_image_url, shop_description)
   * 4. All product variants from ecommerce_mall_product_variants where deleted_at is null
   * 5. For each variant, calculate current stock by summing quantities from ecommerce_mall_inventory_records
   * 6. All reviews from ecommerce_mall_reviews where deleted_at is null, ordered by created_at descending
   * 7. Calculate average rating and review count from non-deleted reviews
   *
   * Return a 404 error if the product does not exist or is deleted.
   * Return all data in a single response with nested relations.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await getEcommerceMallCustomerProductsProductIdDetail({
        customer,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
