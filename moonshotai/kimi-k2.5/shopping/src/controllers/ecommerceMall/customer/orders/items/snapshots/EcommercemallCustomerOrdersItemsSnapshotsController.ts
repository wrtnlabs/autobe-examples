import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItemSnapshot } from "../../../../../../api/structures/IEcommerceMallOrderItemSnapshot";
import { IPageIEcommerceMallOrderItemSnapshot } from "../../../../../../api/structures/IPageIEcommerceMallOrderItemSnapshot";
import { CustomerAuth } from "../../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId } from "../../../../../../providers/getEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId";
import { patchEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshots } from "../../../../../../providers/patchEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshots";

@Controller("/ecommerceMall/customer/orders/:orderId/items/:itemId/snapshots")
export class EcommercemallCustomerOrdersItemsSnapshotsController {
  /**
   * Retrieve a paginated list of order item snapshots for a specific order item.
   *
   * Order item snapshots preserve the complete state of products, variants, and seller profiles at the exact moment of purchase. These snapshots are immutable records created automatically when an order is placed, ensuring accurate historical data for dispute resolution and legal compliance.
   *
   * The snapshot junction table links an order item to three separate snapshot entities:
   * - Product snapshot: Preserves product name, description, category, and base price
   * - Variant snapshot: Preserves SKU code, option values, and variant price
   * - Seller snapshot: Preserves shop name and logo at time of purchase
   *
   * Access is restricted based on actor roles:
   * - Customers can view snapshots for their own orders only
   * - Sellers can view snapshots for orders containing their products
   * - Administrators can view all snapshots for oversight and dispute resolution
   *
   * Snapshots are permanent records that cannot be modified or deleted, even after the original product, variant, or seller account has been removed from the platform.
   *
   * @param connection
   * @param orderId Order ID (UUID format)
   * @param itemId Order item ID (UUID format) - identifies the specific order item within the order
   * @param body Search criteria for filtering snapshots including snapshot type and date range
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Query the ecommerce_mall_order_item_snapshots junction table joining with its related snapshot tables (product_snapshot, variant_snapshot, seller_snapshot).
   *
   * Implementation steps:
   * 1. Validate that the order item exists and belongs to the specified order
   * 2. Join ecommerce_mall_order_item_snapshots with:
   *    - ecommerce_mall_order_item_product_snapshots (for product data)
   *    - ecommerce_mall_order_item_variant_snapshots (for variant data)
   *    - ecommerce_mall_order_item_seller_snapshots (for seller data)
   * 3. Apply access control:
   *    - Customer: validate order.customer_id matches authenticated customer
   *    - Seller: validate order item seller_id matches authenticated seller
   *    - Admin: allow access to all snapshots
   * 4. Support filtering by:
   *    - snapshot_type (product, variant, seller)
   *    - created_at date range (snapshot creation timestamp)
   * 5. Return paginated results with snapshot details and creation timestamps
   * 6. Handle edge case: return empty page if order item has no snapshots (should not occur in normal operation as snapshots are created at order placement)
   *
   * The response includes complete snapshot data for dispute investigation and historical reference.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("itemId")
    itemId: string,
    @TypedBody()
    body: IEcommerceMallOrderItemSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallOrderItemSnapshot> {
    try {
      return await patchEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshots({
        customer,
        orderId,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific snapshot of an order item by its unique identifier.
   *
   * This operation returns the complete snapshot record for an order item, capturing the immutable state of the product, variant, and seller profile at a specific point in time. Snapshots serve as critical audit trail records for dispute resolution and historical reference in the e-commerce platform.
   *
   * The snapshot includes the order item reference, product snapshot reference, variant snapshot reference, seller snapshot reference, and the timestamp when the snapshot was created. These immutable records preserve the exact product state at the time of purchase, including product name, description, images, variant options, pricing, and seller shop identity.
   *
   * Snapshots cannot be modified or deleted after creation. They are automatically created when order items are created (purchase-time snapshots), preserving all relevant entity states for legal and compliance purposes. This operation is primarily used by customers to view historical order states, by sellers to verify past transactions, and by administrators for dispute investigation.
   *
   * Related operations: PATCH /orders/{orderId}/items/{orderItemId}/snapshots to list all snapshots for an order item, GET /orders/{orderId} to view order details, GET /orders/{orderId}/items/{orderItemId} to view the order item.
   *
   * @param connection
   * @param orderId Target order's unique identifier
   * @param itemId Target order item's unique identifier
   * @param snapshotId Target snapshot identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve a specific order item snapshot by its ID from the ecommerce_mall_order_item_snapshots table. The operation should validate that:
   * 1. The order exists (ecommerce_mall_orders table)
   * 2. The order item belongs to the specified order
   * 3. The snapshot belongs to the specified order item
   * 4. The current user has permission to view this snapshot (customer who placed order, seller who fulfilled the item, or administrator)
   *
   * Join with ecommerce_mall_order_item_product_snapshots, ecommerce_mall_order_item_variant_snapshots, and ecommerce_mall_order_item_seller_snapshots to populate the full snapshot details.
   *
   * The query should return 404 if any of the resources don't exist or don't belong to the specified hierarchy. Access control should enforce that only authorized users can view snapshots:
   * - Customer who placed the order: can view
   * - Seller who fulfilled the order item: can view
   * - Administrator: can view
   * - Other users: denied access
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("itemId")
    itemId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallOrderItemSnapshot> {
    try {
      return await getEcommerceMallCustomerOrdersOrderIdItemsItemIdSnapshotsSnapshotId(
        {
          customer,
          orderId,
          itemId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
