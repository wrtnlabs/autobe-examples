  /**
   * Removes a cart item from the customer's shopping cart.
   *
   * This operation marks the cart item as deleted by setting the soft delete timestamp. The cart item is removed from the customer's active cart and will no longer appear in cart listings.
   *
   * Security: Customers can only delete cart items belonging to their own account. Attempts to delete another customer's cart items will be rejected with a 403 Forbidden error.
   *
   * The cart item reference is validated before deletion to ensure it exists and belongs to the authenticated customer.
   *
   * @param connection
   * @param cartItemId The unique identifier of the cart item to delete (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Soft delete the cart item by setting the deleted_at timestamp to current time.
   *
   * Validation steps:
   * 1. Verify the cart item exists by id (cartItemId parameter)
   * 2. Verify the cart item's customer_id matches the authenticated customer's id
   * 3. If either check fails, reject with appropriate error (404 for not found, 403 for ownership violation)
   *
   * Database operation:
   * - Update ecommerce_mall_cart_items table
   * - Set deleted_at = NOW()
   * - WHERE id = cartItemId AND customer_id = currentUserId AND deleted_at IS NULL
   *
   * Edge cases:
   * - Cart item already deleted: return 404 (item not found in active cart)
   * - Cart item belongs to different customer: return 403 (access denied)
   * - Invalid UUID format: return 400 (bad request)
   *
   * The soft delete pattern preserves the record for potential audit or recovery purposes while removing it from active listings.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":cartItemId")
  public async erase(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("cartItemId")
    cartItemId: string,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallCustomerCartItemsCartItemId({
        customer,
        cartItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
