  /**
   * Retrieves the details of a specific shopping cart item by its ID.
   *
   * This endpoint returns complete information about a single cart item including the product details, selected variant options, quantity, and pricing. The cart item represents a customer's selection of a specific product variant with the intent to purchase.
   *
   * **Authorization Required**: Customer must be authenticated and can only access cart items belonging to their own account. Attempts to access another customer's cart items will be rejected per access boundary enforcement rules.
   *
   * **Related Operations**:
   * - `PATCH /cart-items` - List/search cart items
   * - `POST /cart-items` - Add item to cart
   * - `PUT /cart-items/{cartItemId}` - Update cart item quantity
   * - `DELETE /cart-items/{cartItemId}` - Remove item from cart
   *
   * @param connection
   * @param cartItemId The unique identifier of the cart item to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement cart item retrieval by ID with strict ownership verification:
   *
   * 1. **Authentication Check**: Verify the requesting customer is authenticated via JWT session.
   *
   * 2. **Ownership Verification**:
   *    - Query the cart_items table for the record matching the provided cartItemId
   *    - Verify the cart item's customer_id matches the authenticated customer's ID
   *    - If ownership mismatch → return 403 Forbidden (per section [367] Cart Access Boundary Enforcement)
   *
   * 3. **Data Retrieval**:
   *    - Join with ecommerce_mall_product_variants to get variant details (SKU code, option values, price)
   *    - Join with ecommerce_mall_products to get product details (name, description, images)
   *    - Join with ecommerce_mall_sellers and ecommerce_mall_seller_profiles to get shop name
   *    - Calculate subtotal as quantity × variant price
   *
   * 4. **Response Construction**:
   *    - Return full cart item details including:
   *      - Cart item ID, customer ID, variant ID
   *      - Product name and main image
   *      - Variant option values (color, size, etc.)
   *      - Individual variant price
   *      - Quantity in cart
   *      - Subtotal calculation
   *      - Stock availability status (compare quantity against current inventory)
   *
   * 5. **Error Handling**:
   *    - 404 Not Found: Cart item with given ID does not exist
   *    - 403 Forbidden: Cart item exists but belongs to different customer (security boundary)
   *    - 401 Unauthorized: Missing or invalid authentication token
   *
   * 6. **Performance Considerations**:
   *    - Use indexed lookup on cart_items.id (primary key)
   *    - Eager load related entities to minimize database round-trips
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
