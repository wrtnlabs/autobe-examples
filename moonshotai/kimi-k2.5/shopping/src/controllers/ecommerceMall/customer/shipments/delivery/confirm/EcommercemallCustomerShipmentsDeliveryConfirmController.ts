@Controller("/ecommerceMall/customer/shipments/:shipmentId/delivery/confirm")
export class EcommercemallCustomerShipmentsDeliveryConfirmController {
  /**
   * Confirm delivery of a shipment by the customer.
   *
   * This operation allows customers to manually confirm receipt of a shipped package. When a customer confirms delivery for a shipment, all order items contained within that shipment are simultaneously updated from 'shipped' status to 'delivered' status as an atomic operation. This reflects the physical reality that items shipped together in one package arrive together.
   *
   * The operation creates a delivery confirmation record in the ecommerce_mall_shipment_deliveries table, capturing the delivered_at timestamp and marking the confirmation as customer-initiated (not auto-delivered). If the customer does not manually confirm delivery within 14 days of the shipment being created, the system automatically marks all items as delivered.
   *
   * After delivery confirmation, the items in the shipment become eligible for refund requests according to the platform's refund policy time window. The overall order status is also updated to reflect the delivery progress.
   *
   * This operation requires customer authentication and the authenticated customer must be the owner of the order containing this shipment.
   *
   * @param connection
   * @param shipmentId Target shipment's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement delivery confirmation for a shipment with the following logic:
   *
   * 1. Validate that the authenticated customer exists and is active.
   *
   * 2. Validate the shipment exists and is not soft-deleted (deleted_at is null).
   *
   * 3. Verify the shipment belongs to an order where the authenticated customer is the order owner (ecommerce_mall_orders.customer_id matches the authenticated customer).
   *
   * 4. Verify the shipment has not already been delivered by checking if a corresponding ecommerce_mall_shipment_deliveries record exists for this shipment_id.
   *
   * 5. In a transaction:
   *    a. Create a delivery record in ecommerce_mall_shipment_deliveries with:
   *       - shipment_id: the shipment ID from path parameter
   *       - customer_id: the authenticated customer's ID
   *       - delivered_at: current timestamp (NOW())
   *       - is_auto_delivered: false
   *       - created_at/updated_at: current timestamp
   *
   *    b. Update all order items linked to this shipment via ecommerce_mall_shipment_items:
   *       - Find all order_item_ids where shipment_id matches
   *       - Update status from 'shipped' to 'delivered' for each order item
   *       - Set updated_at to current timestamp
   *
   *    c. The database triggers or stored procedures should automatically update the overall order status based on item status aggregation.
   *
   * 6. Return the created IEcommerceMallShipmentDelivery record with the delivery information.
   *
   * Error handling:
   * - Return 404 if shipment not found or soft-deleted
   * - Return 403 if customer does not own the order containing this shipment
   * - Return 409 if delivery already confirmed for this shipment
   * - Return 400 if any included items are not in 'shipped' status
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IEcommerceMallShipmentDelivery> {
    try {
      return await postEcommerceMallCustomerShipmentsShipmentIdDeliveryConfirm({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
