import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { IEcommerceMallShipmentDelivery } from "../../../../../api/structures/IEcommerceMallShipmentDelivery";
import { CustomerAuth } from "../../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../../decorators/payload/CustomerPayload";
import { patchEcommerceMallCustomerShipmentsShipmentIdDeliveries } from "../../../../../providers/patchEcommerceMallCustomerShipmentsShipmentIdDeliveries";
import { postEcommerceMallCustomerShipmentsShipmentIdDeliveries } from "../../../../../providers/postEcommerceMallCustomerShipmentsShipmentIdDeliveries";

@Controller("/ecommerceMall/customer/shipments/:shipmentId/deliveries")
export class EcommercemallCustomerShipmentsDeliveriesController {
  /**
   * Confirm delivery for a shipment and update all associated order items.
   *
   * This endpoint allows customers to confirm that they have received a shipment, marking all order items within that shipment as delivered simultaneously. Delivery confirmation occurs at the shipment level rather than individual item level, reflecting the physical reality that items shipped together in one package arrive together.
   *
   * When a customer confirms delivery:
   * 1. A delivery confirmation record is created with the customer's confirmation timestamp
   * 2. The shipment status changes from "In Transit" to "Delivered"
   * 3. All order items within the shipment are atomically updated to "delivered" status
   * 4. The refund request window opens, allowing the customer to request refunds within 7 days
   *
   * This endpoint can only be called by the customer who placed the order. The shipment must be in "In Transit" status to be confirmable. Once confirmed, the status cannot be reverted.
   *
   * **Authorization Required**: Customer only. The authenticated customer must be the recipient of the order containing this shipment.
   *
   * **Related Operations**:
   * - `GET /shipments/{shipmentId}` - Retrieve shipment details with tracking information before confirming delivery
   * - `GET /orders/{orderId}` - View order status after delivery confirmation
   * - `POST /refundRequests` - Request refund for delivered items (available for 7 days after delivery)
   *
   * @param connection
   * @param shipmentId UUID of the shipment being confirmed as delivered
   * @param body Optional delivery confirmation details (empty body accepted, as confirmation is implicit from the authenticated customer context)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implementation details for delivery confirmation:
   *
   * **Authorization Check**:
   * 1. Verify the authenticated user's customer ID
   * 2. Query the shipment by shipmentId to get associated orderId
   * 3. Verify the order belongs to the authenticated customer
   * 4. Reject with 403 Forbidden if unauthorized
   *
   * **State Validation**:
   * 1. Check shipment current status is "In Transit" (awaiting delivery)
   * 2. If status is already "Delivered", return 409 Conflict with appropriate error
   * 3. If shipment doesn't exist, return 404 Not Found
   *
   * **Database Transaction**:
   * 1. Create delivery confirmation record in shipment_deliveries table:
   *    - shipment_id: the provided shipmentId
   *    - confirmed_by_customer_id: authenticated customer's ID
   *    - confirmed_at: current timestamp
   * 2. Update shipment status to "Delivered" in shipments table
   * 3. Update all order items associated with this shipment:
   *    - Set status from "shipped" to "delivered"
   *    - Set delivered_at timestamp
   * 4. Commit transaction atomically
   *
   * **Side Effects**:
   * - Order items become eligible for refund requests (7-day window starts)
   * - Order status updates (if all items delivered, order becomes "delivered" or "partially_completed")
   * - Inventory records are not affected (stock was already deducted at order)
   *
   * **Response Construction**:
   * - Return the created delivery confirmation record
   * - Include the updated shipment with its status
   * - Include all order items that were updated (with their new "delivered" status)
   *
   * **Edge Cases**:
   * - If customer already confirmed delivery (idempotent request), return existing delivery record with 200 OK
   * - Automatic conversion after 14 days is handled separately by a background job, not this endpoint
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallShipmentDelivery.ICreate,
  ): Promise<IEcommerceMallShipmentDelivery> {
    try {
      return await postEcommerceMallCustomerShipmentsShipmentIdDeliveries({
        customer,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Confirm delivery of a shipment and update all contained order items to delivered status.
   *
   * This operation allows customers to mark a shipment as delivered, confirming receipt of all items within that shipment. All order items within the shipment are automatically updated to delivered status simultaneously, reflecting the physical reality that items shipped together arrive together.
   *
   * **Authorization**: Customer actor only. The customer must be the owner of the order containing this shipment.
   *
   * **Business Rules**:
   * - Only shipments with "In Transit" status can be confirmed as delivered
   * - All order items within the shipment are updated to delivered status together
   * - The delivery timestamp is recorded at the shipment level
   * - Once confirmed, items become eligible for refund requests within the 7-day return window (counting from delivery date)
   *
   * **Edge Cases**:
   * - If the customer confirms delivery manually, the automatic 14-day conversion is cancelled
   * - If the shipment is already delivered, the operation may return the existing delivered state
   *
   * @param connection
   * @param shipmentId Target shipment ID (scoped to customer orders)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate that the authenticated customer is the owner of the order associated with this shipment (via orderId in shipments table joined with orders table's customerId). Check that the shipment status is "In Transit" - reject if already delivered or in invalid state. Update the shipment status to "Delivered" and record the delivery timestamp. Use a database transaction to atomically update all order items within this shipment to status "Delivered". The shipment_items table links order items to shipments; find all orderItemId values associated with this shipmentId and update the corresponding order_items records. Return the updated shipment information including the new delivered status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async confirmDelivery(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallCustomerShipmentsShipmentIdDeliveries({
        customer,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
