import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { CustomerAuth } from "../../../../decorators/CustomerAuth";
import { CustomerPayload } from "../../../../decorators/payload/CustomerPayload";
import { getEcommerceMallCustomerProfile } from "../../../../providers/getEcommerceMallCustomerProfile";
import { putEcommerceMallCustomerProfile } from "../../../../providers/putEcommerceMallCustomerProfile";

@Controller("/ecommerceMall/customer/profile")
export class EcommercemallCustomerProfileController {
  /**
   * Retrieve the authenticated customer's profile information.
   *
   * Returns the current display name and phone number stored in the customer's profile. Either or both fields may be empty if the customer has not yet provided this information.
   *
   * The profile serves as the canonical source for the customer's public-facing identity and contact information across the platform, including communications with sellers and delivery coordination.
   *
   * This operation is only accessible to authenticated customers and returns only their own profile data.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Retrieve the customer profile associated with the authenticated user's session.
   *
   * 1. Extract customer ID from authentication context (JWT/session)
   * 2. Query the ecommerce_mall_customer_profiles table where customer_id matches the authenticated customer
   * 3. Return the profile record containing display_name and phone_number fields
   * 4. If profile exists, return it (fields may be null/empty if not populated)
   * 5. If no profile found (edge case), return appropriate error
   *
   * Security: Verify customer is authenticated. Profile ownership is implicitly enforced by using the authenticated customer's ID in the query - customers can only ever access their own profile.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @CustomerAuth()
    customer: CustomerPayload,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await getEcommerceMallCustomerProfile({
        customer,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the authenticated customer's profile information.
   *
   * This operation allows customers to modify their public-facing profile data including display name and phone number. Both fields are editable throughout the account lifetime and changes take effect immediately upon saving.
   *
   * The system verifies that the authenticated customer is modifying their own profile. Profile edits do not create snapshots as profile information is not subject to the snapshot principle that applies to transactional data.
   *
   * If the submitted data fails validation (e.g., invalid phone number format), the request is rejected with specific validation error details.
   *
   * @param connection
   * @param body Profile update data containing fields to modify (display name and/or phone number)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Validate the authenticated customer's identity from the session. Verify the customer has a profile (created automatically during registration). Validate the request body fields: display name (string, optional for update), phone number (string, must be valid format). Update the profile record in ecommerce_mall_customers table. Return the updated profile with current values. Handle validation errors by returning 400 with specific field errors. Handle authentication errors by returning 401 if no valid session exists.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @CustomerAuth()
    customer: CustomerPayload,
    @TypedBody()
    body: IEcommerceMallCustomer.IUpdate,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await putEcommerceMallCustomerProfile({
        customer,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
