import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerLogin } from "../../../../providers/postEcommerceMallAuthSellerLogin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Register a new seller account on the platform. Sellers must provide a unique email address and password to create an account. Upon successful registration, the seller account is created with pending approval status and requires administrator review before products can be listed. The operation creates a seller registration application that tracks the approval workflow.
   *
   * The registration process validates email uniqueness, enforces password strength requirements, and securely hashes the password using bcrypt. A JWT access token and refresh token are issued upon successful registration, allowing immediate authentication while awaiting approval.
   *
   * Seller accounts with pending status can log in but cannot create products or list items for sale until an administrator approves the registration.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration credentials containing email and password for account creation
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement seller registration (join) operation.
     *   Verify email uniqueness against ecommerce_mall_sellers table. Hash
     *   password using bcrypt. Create seller record with
     *   approval_status='pending'. Create initial seller registration record in
     *   ecommerce_mall_seller_registrations with status='pending'. Generate JWT
     *   access and refresh tokens. Create session record in
     *   ecommerce_mall_seller_sessions capturing IP, href, referrer from
     *   request headers. Return tokens and seller info. Error scenarios:
     *   duplicate email (409), invalid email format (400), password too weak
     *   (400).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing seller using email and password credentials. This operation validates the provided credentials against the stored password hash and establishes a new JWT authentication session.
   *
   * Upon successful authentication, the system issues fresh access and refresh tokens and records the session with connection metadata (IP address, origin URL, referrer) for security auditing. The response includes the seller's current approval status, which determines whether they can list products or must wait for administrator approval.
   *
   * Soft-deleted accounts cannot log in. The operation supports the complete authentication flow for approved, pending, and rejected sellers to check their account status.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials containing email and password for authentication
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement seller login operation. Look up seller
     *   by email in ecommerce_mall_sellers table. Verify password against
     *   password_hash using bcrypt. Check that account is not soft-deleted
     *   (deleted_at is null). Generate new JWT access and refresh tokens.
     *   Create session record in ecommerce_mall_seller_sessions with connection
     *   metadata (IP, href, referrer). Return tokens and seller info including
     *   approval_status. Error scenarios: invalid credentials (401), account
     *   not found (401), account deleted (401).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.ILogin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Renew an expired or nearly-expired JWT access token using a valid refresh token. This operation extends the seller's authenticated session without requiring re-entry of credentials.
   *
   * The refresh token is validated against the active sessions stored in the ecommerce_mall_seller_sessions table. Upon successful validation, a new access token is issued with a fresh expiration timestamp. The session record is updated to reflect the continued activity.
   *
   * This operation is essential for maintaining long-lived sessions while adhering to JWT security best practices through short-lived access tokens and periodic refresh.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the refresh token to exchange for new access credentials
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement token refresh operation. Validate the
     *   provided refresh token. Look up existing session in
     *   ecommerce_mall_seller_sessions table. Verify session belongs to the
     *   authenticated seller and has not expired. Generate new JWT access token
     *   with updated expiration. Optionally rotate refresh token for security.
     *   Update session record with new token information and extended
     *   expiration. Return new tokens and seller info. Error scenarios: invalid
     *   refresh token (401), expired session (401), seller not found (401).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
