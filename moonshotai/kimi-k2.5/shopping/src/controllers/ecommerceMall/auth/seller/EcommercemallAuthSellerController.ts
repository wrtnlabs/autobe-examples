import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../api/structures/IEcommerceMallSeller";
import { postEcommerceMallAuthSellerJoin } from "../../../../providers/postEcommerceMallAuthSellerJoin";
import { postEcommerceMallAuthSellerLogin } from "../../../../providers/postEcommerceMallAuthSellerLogin";
import { postEcommerceMallAuthSellerRefresh } from "../../../../providers/postEcommerceMallAuthSellerRefresh";

@Controller("/ecommerceMall/auth/seller")
export class EcommercemallAuthSellerController {
  /**
   * Seller registration operation. Creates a new seller account with email and password credentials.
   *
   * This endpoint handles the initial seller onboarding process. Sellers must provide a unique email address and a secure password. The email is validated for format correctness and uniqueness across both the customer and seller user bases to prevent duplicate registrations. Upon successful registration, the seller account is created in the database and a new JWT session is established with access and refresh tokens.
   *
   * The newly registered seller will initially have a pending approval status and must wait for administrator approval before they can list products and sell on the platform. During the pending period, the seller can log in and view their account status but cannot perform selling operations.
   *
   * The response includes authentication tokens that can be used for subsequent API calls, along with the seller's unique identifier and session expiration information.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller registration information containing email and password for account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Join operation creates new seller accounts in the ecommerce_mall_sellers table. Upon successful creation, generate JWT access and refresh tokens stored in ecommerce_mall_seller_sessions. Validate email uniqueness against both customers and existing sellers. Password must be hashed using bcrypt with salt rounds. Return IEcommerceMallSeller.IAuthorized containing tokens and seller identification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.IJoin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Seller login operation. Authenticates an existing seller using their registered email address and password.
   *
   * This endpoint validates the provided credentials against the stored seller account information. Password comparison uses secure bcrypt hashing to protect against credential exposure. Before successful authentication, the system verifies that the seller account is not suspended or banned by administrators.
   *
   * Upon successful authentication, a new JWT session is created with fresh access and refresh tokens. The tokens are stored in the session table for tracking and potential revocation purposes. The access token has a limited lifetime and must be renewed using the refresh token endpoint before expiration.
   *
   * The response includes the authentication tokens along with the seller's account information including their current approval status (pending, approved, or rejected). Sellers with rejected status are informed that they need to submit a new registration application.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Seller login credentials containing email and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Login operation validates seller credentials against ecommerce_mall_sellers table using bcrypt password comparison. Check for account suspension or ban status before allowing authentication. On success, create or update session record in ecommerce_mall_seller_sessions with new tokens. Return IEcommerceMallSeller.IAuthorized with tokens and seller details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSeller.ILogin,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh operation. Generates new authentication tokens using a valid refresh token.
   *
   * This endpoint allows sellers to obtain new access tokens without re-entering their credentials. The refresh token from the request is validated against the stored session records to ensure it is active and not expired. Refresh tokens have a longer lifetime than access tokens but also expire eventually for security reasons.
   *
   * Upon successful validation, the system generates new access and refresh tokens, updates the session record with the new token values and extended expiration times, and returns them to the client. The old refresh token is invalidated and cannot be used again, preventing replay attacks.
   *
   * This operation is essential for maintaining long-lived authenticated sessions while following security best practices for token rotation. Sellers should call this endpoint when their access token approaches expiration to seamlessly continue their authenticated session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for obtaining new authentication tokens.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Refresh operation validates the refresh token from ecommerce_mall_seller_sessions table. Check token expiration and mark expired tokens appropriately. Generate new access and refresh tokens, update session record. Return IEcommerceMallSeller.IAuthorized with new tokens. Reject request if refresh token is expired, revoked, or doesn't exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSeller.IRefresh,
  ): Promise<IEcommerceMallSeller.IAuthorized> {
    try {
      return await postEcommerceMallAuthSellerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
