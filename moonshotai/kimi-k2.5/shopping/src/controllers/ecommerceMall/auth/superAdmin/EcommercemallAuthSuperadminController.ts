import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSuperAdmin } from "../../../../api/structures/IEcommerceMallSuperAdmin";
import { postEcommerceMallAuthSuperAdminJoin } from "../../../../providers/postEcommerceMallAuthSuperAdminJoin";
import { postEcommerceMallAuthSuperAdminLogin } from "../../../../providers/postEcommerceMallAuthSuperAdminLogin";
import { postEcommerceMallAuthSuperAdminRefresh } from "../../../../providers/postEcommerceMallAuthSuperAdminRefresh";

@Controller("/ecommerceMall/auth/superAdmin")
export class EcommercemallAuthSuperadminController {
  /**
   * Register a new super administrator account.
   *
   * Creates a new super administrator account with email-based authentication. The super administrator represents the highest privilege level in the platform hierarchy with abilities to approve admin promotion requests, promote/demote administrators, and manage the admin hierarchy.
   *
   * Email must be unique across all super admin accounts. Password is securely hashed before storage. Upon successful registration, a JWT session is established with both access and refresh tokens returned. The session metadata including IP address and request context is recorded for audit purposes.
   *
   * This operation is available publicly for initial super admin creation and requires no authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super administrator registration credentials containing email and password for new account creation.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Super administrator registration operation. Creates a new super admin account with email and password. Implementation steps: 1) Validate request body contains email and password meeting business rules (email format, password complexity). 2) Check email uniqueness against ecommerce_mall_super_admins table - reject if exists. 3) Hash password using secure algorithm (bcrypt/Argon2). 4) Generate UUID for new record. 5) Insert into ecommerce_mall_super_admins with grade='super_admin', created_at/updated_at current timestamp. 6) Generate JWT access and refresh tokens. 7) Create session record in ecommerce_mall_super_admin_sessions with token metadata (IP, href, referrer from request context, created_at, expired_at). 8) Return IEcommerceMallSuperAdmin.IAuthorized containing tokens and super admin identity.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IJoin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a super administrator with email and password credentials.
   *
   * Validates the provided email and password against the stored credentials in the ecommerce_mall_super_admins table. Only active accounts (not soft deleted) can authenticate. The email field is unique per account and serves as the login identifier.
   *
   * Upon successful credential validation, a new JWT session is established. Both access and refresh tokens are generated and returned. The session is recorded in the ecommerce_mall_super_admin_sessions table with metadata including client IP address, page URL, and referrer for security monitoring. Previous sessions remain valid until they expire.
   *
   * This operation is publicly accessible and requires no prior authentication.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Super administrator login credentials containing email and password for authentication.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Super administrator login operation. Validates credentials and establishes session. Implementation steps: 1) Validate request body contains email and password. 2) Query ecommerce_mall_super_admins by email, ensuring account is not soft deleted (deleted_at is null). 3) Verify password_hash matches provided password using secure comparison. 4) Reject if credentials invalid or account deleted. 5) Generate new JWT access and refresh tokens. 6) Create session record in ecommerce_mall_super_admin_sessions capturing connection context (IP, href, referrer). 7) Return IEcommerceMallSuperAdmin.IAuthorized with tokens and super admin details.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallSuperAdmin.ILogin,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh the access token for an authenticated super administrator session.
   *
   * Accepts a valid refresh token and issues a new access token, allowing the super administrator to maintain their session without re-authenticating with credentials. The refresh token is validated for authenticity and expiration.
   *
   * The operation verifies the associated session exists in ecommerce_mall_super_admin_sessions and that the super administrator account remains active (not soft deleted). This enables continuous access management while maintaining security through token rotation.
   *
   * This operation is publicly accessible and requires no prior authentication header - the refresh token itself serves as the authentication credential in the request body.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the refresh token used to obtain a new access token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Super administrator token refresh operation. Issues new access token using valid refresh token. Implementation steps: 1) Extract and validate the refresh token from the IEcommerceMallSuperAdmin.IRefresh request body. 2) Verify token signature and expiration. 3) Look up associated session in ecommerce_mall_super_admin_sessions to ensure session is still valid/active. 4) Query super admin account from ecommerce_mall_super_admins to verify account still exists and is not deleted. 5) Generate new access token (and optionally new refresh token based on security policy). 6) Update session expiration if using sliding expiration. 7) Return IEcommerceMallSuperAdmin.IAuthorized with new tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallSuperAdmin.IRefresh,
  ): Promise<IEcommerceMallSuperAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthSuperAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
