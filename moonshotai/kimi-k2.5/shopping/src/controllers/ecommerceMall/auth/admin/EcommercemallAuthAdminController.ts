import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { postEcommerceMallAuthAdminJoin } from "../../../../providers/postEcommerceMallAuthAdminJoin";
import { postEcommerceMallAuthAdminLogin } from "../../../../providers/postEcommerceMallAuthAdminLogin";
import { postEcommerceMallAuthAdminRefresh } from "../../../../providers/postEcommerceMallAuthAdminRefresh";

@Controller("/ecommerceMall/auth/admin")
export class EcommercemallAuthAdminController {
  /**
   * Administrator join operation. Administrators are created through the promotion request flow (AdminPromotionRequest) approved by super administrators, not through public registration. This operation authenticates an existing admin account using email and password credentials.
   *
   * Validates the email exists in ecommerce_mall_admins, verifies the BCrypt password_hash matches the provided password, and confirms the account status is 'active' (suspended or banned accounts cannot authenticate). Administrators have two privilege grades: 'regular' (standard admin permissions) and 'super_admin' (can promote/demote other admins).
   *
   * Upon successful authentication, creates a new session record in ecommerce_mall_admin_sessions with JWT tokens (access and refresh), captures connection metadata (IP address, page URL, referrer) for security audit trails, and returns the authorization tokens with admin profile information.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator join credentials including email and password for authentication.
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Join operation for administrator accounts. This is typically used when a user (customer or seller) has been approved as an administrator through the AdminPromotionRequest flow. The operation validates the email and password match an existing admin record with 'active' status. Upon successful validation, creates a new session in ecommerce_mall_admin_sessions with JWT access token and refresh token. Capture client metadata (ip, href, referrer) for security auditing. Hash the provided password using BCrypt and compare against password_hash. Set token expiration based on configuration (e.g., access token 15 minutes, refresh token 30 days). Return both tokens in IEcommerceMallAdmin.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.IJoin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Administrator login operation. Authenticates administrators using email and password credentials stored in the ecommerce_mall_admins table.
   *
   * The operation performs multiple validations: verifies the email exists, checks the account status is 'active' (suspended or banned administrators cannot log in), and validates the password against the BCrypt password_hash. Administrators have two grades: 'regular' (standard admin with seller approval, category management, and oversight permissions) and 'super_admin' (additional privileges to promote/demote administrators and approve admin promotion requests).
   *
   * Upon successful authentication, creates a session record in ecommerce_mall_admin_sessions with JWT access and refresh tokens. Captures security metadata including IP address, referring URL (href), and HTTP referrer for audit trail purposes. Returns the authorization tokens along with the administrator's profile information.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Administrator login credentials with email and password.
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Login operation for administrators. Validates email and password against ecommerce_mall_admins table. Check that status is 'active' (reject suspended or banned accounts). Verify BCrypt password_hash. On success, create a session in ecommerce_mall_admin_sessions with JWT tokens including: access token (short-lived, e.g., 15 min) and refresh token (long-lived, e.g., 30 days). Capture IP, href, referrer from request headers for security audit. Set expired_at based on refresh token lifetime. Return IEcommerceMallAdmin.IAuthorized containing tokens and admin profile (id, email, grade, status, nickname).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallAdmin.ILogin,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Token refresh operation for administrator authentication. Allows administrators to obtain a new access token without re-entering credentials by presenting a valid refresh token.
   *
   * The operation validates the provided refresh token against the ecommerce_mall_admin_sessions table, checking that the session exists and has not expired (expired_at timestamp is in the future). The refresh token is linked to the administrator via the admin_id foreign key relationship.
   *
   * Upon successful validation, generates a new JWT access token with fresh expiration time. Implementing token rotation (issuing a new refresh token and invalidating the old one) is recommended for enhanced security but optional. Returns IEcommerceMallAdmin.IAuthorized containing the new access token, the refresh token (new or existing), and the administrator's profile information.
   *
   * If the session has expired or the token is invalid/not found, returns 401 Unauthorized error requiring the administrator to log in again.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token request containing the refresh token to exchange for a new access token.
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Refresh operation for administrator sessions. Accepts a refresh token in the request body and validates it against the ecommerce_mall_admin_sessions table. Look up the session by matching the token and ensure it has not expired (expired_at > now()). On valid token, issue a new access token with updated expiration time. The refresh token itself may be rotated (optional security practice) or kept the same. Update the session record if token rotation is implemented. Return IEcommerceMallAdmin.IAuthorized with the new access token. If the session has expired or the token is invalid, return 401 Unauthorized.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallAdmin.IRefresh,
  ): Promise<IEcommerceMallAdmin.IAuthorized> {
    try {
      return await postEcommerceMallAuthAdminRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
