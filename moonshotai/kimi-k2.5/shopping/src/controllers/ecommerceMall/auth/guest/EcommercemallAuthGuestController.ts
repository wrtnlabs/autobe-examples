import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { postEcommerceMallAuthGuestJoin } from "../../../../providers/postEcommerceMallAuthGuestJoin";
import { postEcommerceMallAuthGuestRefresh } from "../../../../providers/postEcommerceMallAuthGuestRefresh";

@Controller("/ecommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Creates a new guest session for unauthenticated visitors.
   *
   * This endpoint allows unauthenticated visitors to obtain a temporary JWT session before accessing registration or login endpoints. The platform requires authentication for all features, so guests must first establish a session token to proceed with account creation.
   *
   * The operation generates fresh access and refresh tokens, stores the session record in the database with expiration timestamps, and returns the tokens to the client. The returned access token should be included in the Authorization header for subsequent API calls.
   *
   * This is typically the first API call made by a visitor to the platform. Once a guest has tokens, they can use them to access the customer or seller registration endpoints.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Optional metadata for the guest session creation. No credentials are required for guest sessions.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implementation: Generate a new JWT access token
     *   and refresh token pair for an unauthenticated visitor. Create a guest
     *   session record in the database with the refresh token hash, expiration
     *   timestamps, and client metadata. Return both tokens in the response. No
     *   input credentials required since this creates a temporary anonymous
     *   session. The access token should have a short expiration (e.g., 15
     *   minutes) and the refresh token longer (e.g., 7 days) to allow session
     *   persistence.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallGuest.IJoin,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an existing guest session with new access and refresh tokens.
   *
   * This endpoint allows guest clients to extend their session validity when the access token expires. The client must provide a valid refresh token obtained from the initial join response or previous refresh response.
   *
   * The operation validates the refresh token against the stored session record, generates new token pairs, updates the session record with new expiration timestamps, and returns fresh tokens. Token rotation may be implemented for enhanced security.
   *
   * If the refresh token is invalid, expired, or revoked, the operation returns a 401 error and the client must call join again to establish a new guest session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body The refresh token from the existing guest session to exchange for new tokens.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor guest
     * @x-autobe-specification Implementation: Validate the provided refresh
     *   token against the guest_sessions table. Check that the token is not
     *   expired and matches a valid session record. Generate a new access token
     *   and optionally rotate the refresh token for security. Update the
     *   session record with new token hashes and expiration timestamps. Return
     *   the new token pair. If the refresh token is invalid or expired, return
     *   a 401 error requiring the client to call join again.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
