import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { postEcommerceMallAuthGuestJoin } from "../../../../providers/postEcommerceMallAuthGuestJoin";
import { postEcommerceMallAuthGuestRefresh } from "../../../../providers/postEcommerceMallAuthGuestRefresh";

@Controller("/ecommerceMall/auth/guest")
export class EcommercemallAuthGuestController {
  /**
   * Creates a new guest session and generates JWT tokens for temporary access.
   *
   * This endpoint serves unauthenticated visitors who need temporary access to the platform. Unlike member/login actors, guests cannot log in with credentials because they have no registered account. Instead, this join operation both creates a new guest entity and establishes an authenticated session.
   *
   * The implementation must:
   * 1. Generate cryptographically secure tokens (access_token, refresh_token)
   * 2. Create guest record in ecommerce_mall_guests table
   * 3. Create session in ecommerce_mall_guest_sessions table with token expiry
   * 4. Return tokens to the client for subsequent authenticated requests
   *
   * This operation is public and requires no authentication. The returned tokens enable the guest to call refresh endpoints to maintain session validity.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest session creation input (empty for guests, no credentials needed)
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification POST /auth/guest/join
   *
   * Creates a new guest session with JWT tokens. Since guests are unauthenticated visitors with no credentials, this operation functions as both session creation and initial authentication. The server generates fresh access_token and refresh_token pairs stored in the ecommerce_mall_guest_sessions table. The operation inserts a new guest record into ecommerce_mall_guests and creates the corresponding session. Returns authenticated state with tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallGuest.IJoin,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an expired guest session with a new JWT token pair.
   *
   * This endpoint allows guests to maintain their session without re-creating a guest identity. When the access_token expires, clients call this endpoint with their refresh_token to obtain fresh credentials.
   *
   * The implementation must:
   * 1. Validate the refresh_token exists in ecommerce_mall_guest_sessions table
   * 2. Check token hasn't expired
   * 3. Generate new access_token and refresh_token pair
   * 4. Update the session record with new tokens and expiry
   * 5. Return the new tokens to the client
   *
   * If the refresh_token is invalid, expired, or has been revoked, the operation returns an authentication error requiring the client to call join again to create a new guest session.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for renewing the guest session
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification POST /auth/guest/refresh
   *
   * Refreshes an expired guest session token. Requires a valid refresh_token from the request body. Verifies the token exists in ecommerce_mall_guest_sessions table and hasn't expired. Generates new token pair, updates the session record, returns fresh tokens. If the refresh_token is invalid or expired, returns authentication error.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuest.IAuthorized> {
    try {
      return await postEcommerceMallAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
