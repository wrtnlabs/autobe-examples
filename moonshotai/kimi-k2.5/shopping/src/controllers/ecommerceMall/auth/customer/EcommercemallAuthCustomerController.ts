import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerLogin } from "../../../../providers/postEcommerceMallAuthCustomerLogin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Register a new customer account with email and password.
   *
   * Creates a new customer record in the ecommerce_mall_customers table with the provided email address and hashed password. Validates that the email address is unique across all customer accounts. Upon successful registration, establishes a new authenticated session and returns JWT access and refresh tokens.
   *
   * The session is recorded in ecommerce_mall_customer_sessions with connection context including IP address, referring page, and timestamps for security auditing. Customers can immediately use their credentials to access protected endpoints after registration.
   *
   * This endpoint establishes the customer's identity in the system and issues authentication credentials for subsequent API access.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials containing email address and password for the new account.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implementation notes: Validate email uniqueness
     *   against ecommerce_mall_customers table. Hash password using
     *   bcrypt/argon2. Create customer record with email and password_hash.
     *   Generate JWT access and refresh tokens. Create session record in
     *   ecommerce_mall_customer_sessions with ip, href, referrer, and
     *   expiration timestamp. Return tokens in
     *   IEcommerceMallCustomer.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate an existing customer with email and password credentials.
   *
   * Validates the provided email address and password against the ecommerce_mall_customers table. Uses secure password hashing comparison to verify credentials. Rejects authentication if the email is not found, password does not match, or the account has been soft deleted.
   *
   * Upon successful authentication, generates new JWT access and refresh tokens and creates a session record in ecommerce_mall_customer_sessions capturing the connection context (IP address, referring URL, timestamps) for security monitoring.
   *
   * The returned access token must be included in subsequent API requests via the Authorization header. The refresh token can be used to obtain new access tokens when the current one expires.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials containing email address and password for authentication.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implementation notes: Look up customer by email
     *   in ecommerce_mall_customers table. Verify password_hash matches
     *   provided password using secure comparison. Check account is not soft
     *   deleted (deleted_at is null). Reject if credentials invalid. Generate
     *   JWT access and refresh tokens. Create session record in
     *   ecommerce_mall_customer_sessions tracking connection context. Return
     *   tokens in IEcommerceMallCustomer.IAuthorized response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.ILogin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh an expired or soon-to-expire access token using a valid refresh token.
   *
   * Accepts a refresh token previously issued during login or registration and returns a new access token without requiring the customer to re-enter credentials. Validates the refresh token against the session records and verifies the associated customer account remains active.
   *
   * For enhanced security, this operation may also issue a new refresh token (token rotation) and invalidate the previous one to prevent replay attacks. The refresh token itself is stored in the ecommerce_mall_customer_sessions table with expiration tracking.
   *
   * Use this endpoint when the access token expires (typically returns 401 Unauthorized) to maintain the customer's session without interrupting their workflow.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Token refresh request containing the refresh token obtained from previous login or registration.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor customer
     * @x-autobe-specification Implementation notes: Validate the provided
     *   refresh token against ecommerce_mall_customer_sessions. Check token is
     *   not expired. Look up associated customer from ecommerce_mall_customers
     *   table. Verify customer account is active (not deleted). Generate new
     *   JWT access token with fresh expiration. Optionally rotate refresh token
     *   for security. Return new tokens in IEcommerceMallCustomer.IAuthorized
     *   response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
