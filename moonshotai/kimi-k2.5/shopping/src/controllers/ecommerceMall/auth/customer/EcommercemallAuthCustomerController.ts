import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../../api/structures/IEcommerceMallCustomer";
import { postEcommerceMallAuthCustomerJoin } from "../../../../providers/postEcommerceMallAuthCustomerJoin";
import { postEcommerceMallAuthCustomerLogin } from "../../../../providers/postEcommerceMallAuthCustomerLogin";
import { postEcommerceMallAuthCustomerRefresh } from "../../../../providers/postEcommerceMallAuthCustomerRefresh";

@Controller("/ecommerceMall/auth/customer")
export class EcommercemallAuthCustomerController {
  /**
   * Register a new customer account with email and password.
   *
   * This endpoint creates a new customer account in the ecommerce_mall_customers table. The email must be unique across all customers and is used for login. Password is securely hashed before storage.
   *
   * Validation rules:
   * - Email must be unique (ecommerce_mall_customers.email @@unique constraint)
   * - Email format must be valid RFC 5322
   * - Password strength requirements apply (minimum length, complexity)
   *
   * On success, creates a customer record and establishes a JWT session in ecommerce_mall_customer_sessions, returning access and refresh tokens for immediate authentication.
   *
   * Related operations:
   * - POST /auth/customer/login for existing account authentication
   * - POST /auth/customer/refresh for token renewal
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer registration credentials with email and password
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer registration with email uniqueness check and password hashing.
   *
   * 1. Validate email format using RFC 5322 regex
   * 2. Check email uniqueness - if exists and not deleted, return 409 conflict
   * 3. Hash password using bcrypt with 10 rounds
   * 4. Create customer record with email, password_hash, created_at, updated_at
   * 5. Create session in ecommerce_mall_customer_sessions with JWT tokens
   * 6. Return authorized response with access_token and refresh_token
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.IJoin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticate a customer with email and password credentials.
   *
   * This endpoint validates customer credentials against the ecommerce_mall_customers table and creates a JWT session in ecommerce_mall_customer_sessions. Returns access and refresh tokens upon successful authentication.
   *
   * The session records connection metadata including IP address, href, and referrer for security auditing. Sessions have expiration timestamps managed in the expired_at field.
   *
   * Validation rules:
   * - Email must exist and account must be active (deleted_at is null)
   * - Password must match the stored hash
   *
   * Error handling:
   * - 401 Unauthorized for invalid credentials or inactive accounts
   * - Prevent account enumeration through consistent error messages
   *
   * Related operations:
   * - POST /auth/customer/join for account creation
   * - POST /auth/customer/refresh for token renewal
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Customer login credentials with email and password
   * @x-autobe-authorization-type login
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement customer login with email/password verification.
   *
   * 1. Find customer by email in ecommerce_mall_customers
   * 2. If not found or soft-deleted (deleted_at), return 401 unauthorized
   * 3. Verify password using bcrypt.compare
   * 4. If password invalid, return 401 unauthorized
   * 5. Create new session in ecommerce_mall_customer_sessions
   * 6. Record connection context: ip, href, referrer
   * 7. Return authorized response with tokens
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IEcommerceMallCustomer.ILogin,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refresh authentication tokens using a valid refresh token.
   *
   * This endpoint exchanges a valid refresh token for a new access token (and optionally a new refresh token). The refresh token must correspond to an active session in ecommerce_mall_customer_sessions that has not expired.
   *
   * The operation validates:
   * - Refresh token signature and expiration
   * - Session exists and is not expired (expired_at check)
   * - Customer account is active (deleted_at is null)
   *
   * Token renewal extends the authentication session without requiring re-login. Refresh tokens have longer expiration periods than access tokens per security policy.
   *
   * Security considerations:
   * - Revoked or expired refresh tokens are rejected
   * - Account deletion invalidates all associated sessions
   * - Consider implementing refresh token rotation for enhanced security
   *
   * Related operations:
   * - POST /auth/customer/login for initial authentication
   * - POST /auth/customer/join for account creation
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token for token renewal
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor customer
   * @x-autobe-specification Implement token refresh using valid refresh token.
   *
   * 1. Extract refresh token from request body
   * 2. Validate refresh token signature and expiration
   * 3. Find session in ecommerce_mall_customer_sessions
   * 4. Check session exists and is not expired (expired_at)
   * 5. Check customer account is active (deleted_at is null)
   * 6. Generate new access token with extended expiration
   * 7. Optionally rotate refresh token for security
   * 8. Return authorized response with new tokens
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IEcommerceMallCustomer.IRefresh,
  ): Promise<IEcommerceMallCustomer.IAuthorized> {
    try {
      return await postEcommerceMallAuthCustomerRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
