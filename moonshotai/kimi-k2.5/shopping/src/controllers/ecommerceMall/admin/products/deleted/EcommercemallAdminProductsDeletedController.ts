import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProduct } from "../../../../../api/structures/IEcommerceMallProduct";
import { IPageIEcommerceMallProduct } from "../../../../../api/structures/IPageIEcommerceMallProduct";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { patchEcommerceMallAdminProductsDeleted } from "../../../../../providers/patchEcommerceMallAdminProductsDeleted";

@Controller("/ecommerceMall/admin/products/deleted")
export class EcommercemallAdminProductsDeletedController {
  /**
   * Retrieve a paginated list of deleted products.
   *
   * This operation returns products that have been soft-deleted (where deleted_at is not null). Administrators can retrieve all deleted products across the platform, while sellers can only retrieve their own deleted products for archive/history purposes.
   *
   * The operation supports filtering by seller ID (administrators only), date range when the product was deleted, and text search on product name. Results are paginated with configurable page sizes and sorting options.
   *
   * Deleted products are excluded from normal search and category browsing but remain accessible through this dedicated endpoint for audit and record-keeping purposes. The response includes product summary information suitable for list displays.
   *
   * Snapshots of deleted products remain available through separate snapshot APIs for viewing complete historical state.
   *
   * @param connection
   * @param body Search criteria for deleted products including filters, pagination, and sorting
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_products table filtering where deleted_at IS NOT NULL.
   *
   * For admin actors: Can view all deleted products. Apply requested filters including seller_id if specified.
   * For seller actors: Must filter by current seller's id automatically. Ignore any seller_id filter in request.
   *
   * Query joins with ecommerce_mall_categories for category name and ecommerce_mall_sellers for seller shop name.
   * GIN indexes on name field support partial text matching.
   *
   * Pagination: Use cursor-based or offset pagination based on created_at ordering.
   * Sorting: Support by deleted_at (newest first default), name (alphabetical).
   *
   * Response includes: product id, name, base_price, seller shop name, category name, deleted_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallProduct.IRequest,
  ): Promise<IPageIEcommerceMallProduct.ISummary> {
    try {
      return await patchEcommerceMallAdminProductsDeleted({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
