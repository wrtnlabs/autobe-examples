import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallRefundRequest } from "../../../../api/structures/IEcommerceMallRefundRequest";
import { IPageIEcommerceMallRefundRequest } from "../../../../api/structures/IPageIEcommerceMallRefundRequest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminRefundRequestsRefundRequestId } from "../../../../providers/getEcommerceMallAdminRefundRequestsRefundRequestId";
import { patchEcommerceMallAdminRefundRequests } from "../../../../providers/patchEcommerceMallAdminRefundRequests";

@Controller("/ecommerceMall/admin/refundRequests")
export class EcommercemallAdminRefundrequestsController {
  /**
   * Retrieve a filtered and paginated list of refund requests for platform administrative oversight.
   *
   * This operation allows administrators (admin and superAdmin) to browse all refund requests across the platform with comprehensive search capabilities. It provides visibility into the refund request workflow for monitoring seller-customer dispute resolution.
   *
   * Administrators can filter refund requests by status (pending, approved, rejected), date ranges, associated order items, customers, and sellers. This enables effective oversight of refund activities and identification of patterns requiring attention.
   *
   * The response includes summary information for each refund request: ID, status, submission timestamp, associated order item details, customer information, seller information, and seller response information if available.
   *
   * Pagination is cursor-based with configurable page sizes. Results are sorted by submission time in descending order (newest first) by default, ensuring administrators see the most recent refund activity first.
   *
   * Related operations include refund request detail retrieval and seller response actions.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for refund request listing. Supports filtering by status, date ranges, customer, seller, and order item.
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the refund_requests table with the following filtering logic:
   *
   * 1. **Authorization Filter**: Based on the authenticated actor:
   *    - Customer: Filter where request belongs to their order items
   *    - Seller: Filter where orderItem.sellerId matches seller's ID
   *    - Admin/SuperAdmin: No filtering (view all)
   *
   * 2. **Searchable Fields**:
   *    - status: Filter by request status (PENDING, APPROVED, REJECTED)
   *    - orderItemId: Filter by specific order item
   *    - submittedAfter/Before: Date range for submission time
   *    - respondedAfter/Before: Date range for response time
   *    - customerId: Filter by requesting customer (admin only)
   *    - sellerId: Filter by seller (admin only)
   *
   * 3. **Joins Required**:
   *    - Join with order_items to get seller/product info
   *    - Join with customers to get requester info
   *    - Join with sellers to get seller info
   *    - Join with refund_request_snapshots for latest snapshot if needed
   *
   * 4. **Sorting**:
   *    - Default: submittedAt DESC (newest first)
   *    - Options: submittedAt ASC/DESC, respondedAt ASC/DESC
   *
   * 5. **Pagination**:
   *    - Cursor-based pagination for performance
   *    - Include total count for UI pagination controls
   *
   * 6. **Response Format**:
   *    - Return paginated summary with list of IRefundRequestSummary
   *    - Each summary includes: id, status, submittedAt, respondedAt, orderItemId, productName (from snapshot), sellerShopName, customerDisplayName, hasResponse
   *
   * Security: Verify actor can view each request before including in results.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallRefundRequest.IRequest,
  ): Promise<IPageIEcommerceMallRefundRequest.ISummary> {
    try {
      return await patchEcommerceMallAdminRefundRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific refund request.
   *
   * This endpoint returns complete details for a single refund request identified by its UUID. A refund request represents a customer's formal petition to return a delivered order item and receive a refund.
   *
   * The refund request entity contains information about the associated order item, the reason provided by the customer for the refund request, the current status of the request (pending, approved, or rejected), and timestamps tracking when the request was submitted and when it was resolved.
   *
   * When a seller responds to a refund request (either approving or rejecting it), a snapshot of the request state is automatically created. This immutable snapshot preserves the decision, timestamp, and request state at the time of response for audit and dispute resolution purposes.
   *
   * This operation is used by customers to track the status of their refund requests, by sellers to review refund requests for items they sold, and by administrators for platform oversight and dispute resolution.
   *
   * @param connection
   * @param refundRequestId Target refund request's UUID identifier
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_refund_requests table joined with related tables to retrieve complete refund request information.
   *
   * Database Query Logic:
   * 1. Select refund request by primary key (id = refundRequestId)
   * 2. Join with ecommerce_mall_order_items to get associated order item details
   * 3. Join with ecommerce_mall_products to get product information
   * 4. Join with ecommerce_mall_product_variants to get variant details
   * 5. Join with ecommerce_mall_customers to get requester information
   * 6. Include related refund request snapshots (ecommerce_mall_refund_request_snapshots) showing response history
   *
   * Authorization Logic:
   * - Customers: Can view their own refund requests only (check customer_id via order_item → order → customer relationship)
   * - Sellers: Can view refund requests for items they sold only (check seller_id via order_item)
   * - Admins/SuperAdmins: Can view any refund request
   *
   * The query should include:
   * - Refund request ID, status, reason, created_at, response_at
   * - Associated order item details with product and variant snapshots
   * - Customer information (for sellers/admins)
   * - Any existing snapshots showing response history
   * - Seller information (for customers)
   *
   * Return 404 if refund request not found. Return 403 if user lacks permission to view this specific request.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await getEcommerceMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
