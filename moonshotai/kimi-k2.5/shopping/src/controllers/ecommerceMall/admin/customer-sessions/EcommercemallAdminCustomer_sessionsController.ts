import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerSession } from "../../../../api/structures/IEcommerceMallCustomerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminCustomerSessionsSessionId } from "../../../../providers/getEcommerceMallAdminCustomerSessionsSessionId";
import { patchEcommerceMallAdminCustomerSessions } from "../../../../providers/patchEcommerceMallAdminCustomerSessions";

@Controller("/ecommerceMall/admin/customer-sessions")
export class EcommercemallAdminCustomer_sessionsController {
  /**
   * Retrieve a filtered and paginated list of customer authentication sessions.
   *
   * This operation provides session history retrieval with advanced filtering capabilities including creation date ranges, expiration status, and connection context filters. Customers can view their own active and expired sessions to monitor account access and security.
   *
   * Sessions include connection metadata such as IP address, referrer URL, and creation timestamp. Expired sessions are retained for security auditing purposes. Results are paginated with cursor-based navigation for efficient browsing of large session histories.
   *
   * Requires authentication. Customers can only access their own sessions. Administrators may have broader access depending on implementation policies.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering customer sessions
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_mall_customer_sessions table with
     *   pagination and filtering.
   *
   * Authorization: Verify authenticated customer can only access sessions where ecommerce_mall_customer_id matches their own customer ID. Administrators may bypass this restriction based on role.
   *
   * Filtering support:
   * - created_at date range (from/to)
   * - expired_at date range for expired sessions
   * - expiration status filter (active only, expired only, or all)
   * - ip address partial matching for security analysis
   *
   * Pagination: Use cursor-based pagination with created_at as the cursor field for consistent ordering. Support configurable page sizes (default 20, max 100).
   *
   * Sorting: Primary sort by created_at DESC (newest first), secondary sort by id for stability.
   *
   * Response fields include: id, ip, href, referrer, created_at, expired_at, and a flag indicating if the session is currently active (expired_at > now).
   *
   * Do not include sensitive token data in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallAdminCustomerSessions({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieves detailed information about a specific customer session by its unique identifier.
   *
   * This operation allows authenticated customers to view their own session details for security auditing and account management purposes. The session information includes connection metadata such as IP address, page URL where the session was initiated, and HTTP referrer header value. Temporal fields indicate when the session was created and when it expires.
   *
   * Session data is sensitive and access is strictly limited to the customer who owns the session. The system validates ownership before returning any session information. If the requested session does not belong to the authenticated customer, the system returns a not-found response to prevent session ID enumeration attacks.
   *
   * Active sessions can be monitored by customers to detect unauthorized access or unusual login patterns from unexpected IP addresses or referrers.
   *
   * @param connection
   * @param sessionId Unique identifier of the customer session to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_customer_sessions table
     *   by primary key id matching the provided sessionId path parameter.
   *
   * Validate that the session's ecommerce_mall_customer_id matches the authenticated customer's ID. If ownership verification fails, return 404 Not Found (do not reveal the session belongs to another user).
   *
   * Return the complete session record including: id, ecommerce_mall_customer_id, ip, href, referrer, created_at, expired_at.
   *
   * Edge case handling:
   * - If sessionId is not a valid UUID format, return 400 Bad Request
   * - If session does not exist, return 404 Not Found
   * - If session exists but belongs to different customer, return 404 Not Found (security through obscurity)
   * - If session has expired, still return it if owned by requesting customer (customer can see their expired sessions)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IEcommerceMallCustomerSession> {
    try {
      return await getEcommerceMallAdminCustomerSessionsSessionId({
        admin,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
