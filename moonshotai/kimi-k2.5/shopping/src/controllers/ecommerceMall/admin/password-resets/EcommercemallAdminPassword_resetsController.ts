import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallCustomerPasswordReset } from "../../../../api/structures/IEcommerceMallCustomerPasswordReset";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminPasswordResetsResetId } from "../../../../providers/getEcommerceMallAdminPasswordResetsResetId";
import { patchEcommerceMallAdminPasswordResets } from "../../../../providers/patchEcommerceMallAdminPasswordResets";

@Controller("/ecommerceMall/admin/password-resets")
export class EcommercemallAdminPassword_resetsController {
  /**
   * Reset a user account password using a valid password reset token.
   *
   * This operation allows customers, sellers, and administrators to complete the password reset process by providing their unique reset token and new password. The system validates the token against all three user type tables (customers, sellers, administrators), verifies the token has not expired, and updates the user's password hash.
   *
   * Upon successful password reset, the token is permanently deleted to prevent reuse, and all existing sessions for that user are invalidated for security. The user must log in again with their new password.
   *
   * The new password must meet platform security requirements including minimum length and complexity. If the token is invalid, expired, or the new password fails validation, the operation is rejected with an appropriate error.
   *
   * @param connection
   * @param body Password reset token and new password credentials
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Implement password reset using token validation:
   *
   * 1. Search for the provided token in all three password reset tables:
   *    - ecommerce_mall_customer_password_resets (token unique constraint)
   *    - ecommerce_mall_seller_password_resets (token unique constraint)
   *    - ecommerce_mall_admin_password_resets (token unique constraint)
   *
   * 2. Verify the token exists and has not expired (compare expires_at/created_at with current time).
   *
   * 3. Retrieve the associated user from the corresponding actor table:
   *    - customers table for customer tokens
   *    - sellers table for seller tokens
   *    - admins table for admin tokens
   *
   * 4. Validate the new password meets platform security requirements (minimum length, complexity rules).
   *
   * 5. Hash the new password using the platform's password hashing algorithm.
   *
   * 6. Update the user's password hash in their respective table within a transaction.
   *
   * 7. Delete the used password reset token record to prevent replay attacks.
   *
   * 8. Invalidate all existing sessions for this user by deleting session records from:
   *    - ecommerce_mall_customer_sessions
   *    - ecommerce_mall_seller_sessions
   *    - ecommerce_mall_admin_sessions
   *
   * 9. Handle edge cases:
   *    - Return 404 error if token not found in any table
   *    - Return 410 error if token has expired
   *    - Return 422 error if new password fails validation
   *    - Use database transactions to ensure atomicity between password update and token deletion
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async resetPassword(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCustomerPasswordReset.IUpdate,
  ): Promise<void> {
    try {
      return await patchEcommerceMallAdminPasswordResets({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a password reset record by its unique identifier.
   *
   * This endpoint is used to validate a password reset token during the password recovery workflow. When a user requests a password reset, a token is generated and sent to their email. This endpoint allows the system to verify that the token exists and has not expired before allowing the user to set a new password.
   *
   * The response includes the token details including creation and expiration timestamps. If the token has expired, the client should reject the password reset attempt and prompt the user to request a new reset.
   *
   * This operation supports all user actor types in the platform - customers, sellers, administrators, and super administrators - each having their own password reset record type.
   *
   * @param connection
   * @param resetId Unique identifier of the password reset record (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the password reset table by the provided
     *   resetId UUID.
   *
   * For customer tokens: query ecommerce_mall_customer_password_resets
   * For seller tokens: query ecommerce_mall_seller_password_resets
   * For admin tokens: query ecommerce_mall_admin_password_resets
   * For super admin tokens: query ecommerce_mall_super_admin_password_resets
   *
   * Check if the record exists and compare expires_at/expired_at against current timestamp.
   * Return 404 if the reset record does not exist.
   * Return the full record including token, created_at, and expiration timestamps.
   * Do not include the foreign key (customer_id, seller_id, etc.) in the response for security.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":resetId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("resetId")
    resetId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallCustomerPasswordReset> {
    try {
      return await getEcommerceMallAdminPasswordResetsResetId({
        admin,
        resetId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
