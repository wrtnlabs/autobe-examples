@Controller("/ecommerceMall/admin/orderItems/:orderItemId/variantSnapshot")
export class EcommercemallAdminOrderitemsVariantsnapshotController {
  /**
   * Retrieve the product variant snapshot associated with a specific order item.
   *
   * This endpoint returns the immutable variant snapshot that was captured when the order was placed. The snapshot preserves the exact state of the product variant at the time of purchase, including the SKU code, option values (such as color and size), and the variant-specific price.
   *
   * Variant snapshots are created automatically during order creation and remain unchanged throughout the order's lifecycle. They serve as the authoritative record for displaying order details and resolving any disputes about what the customer actually purchased. The snapshot ensures that even if the seller later modifies or deletes the product variant, the customer's order history still accurately reflects the item they bought.
   *
   * This endpoint is typically used when displaying order details to customers, sellers, or administrators who need to see the exact product configuration that was ordered.
   *
   * @param connection
   * @param orderItemId Unique identifier of the order item whose variant snapshot is being retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_order_items table to find the variant snapshot associated with the provided orderItemId.
   *
   * Join with ecommerce_mall_product_variant_snapshots to retrieve the full snapshot data. The snapshot contains: SKU code, option values (color, size, etc.), and the variant-specific price at purchase time.
   *
   * The variant snapshot is immutable and cannot be modified after order creation. Acccess to the snapshot is restricted to: the customer who placed the order, the seller who owns the product, and administrators.
   *
   * Return the complete variant snapshot record with all preserved fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IEcommerceMallProductVariantSnapshot> {
    try {
      return await getEcommerceMallAdminOrderItemsOrderItemIdVariantSnapshot({
        admin,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
