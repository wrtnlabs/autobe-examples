import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItemProductSnapshot } from "../../../../../../api/structures/IEcommerceMallOrderItemProductSnapshot";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdProductSnapshot } from "../../../../../../providers/getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdProductSnapshot";

@Controller(
  "/ecommerceMall/admin/orders/:orderId/items/:orderItemId/productSnapshot",
)
export class EcommercemallAdminOrdersItemsProductsnapshotController {
  /**
   * Retrieves the product snapshot associated with a specific order item, capturing the exact product state at the time of purchase.
   *
   * This endpoint returns immutable product data including name, description, category details, base price, and all images as they appeared when the order was placed. Product snapshots are automatically created during successful checkout and preserved for dispute resolution and historical accuracy.
   *
   * The snapshot includes all product images in their original display order, with the first image serving as the thumbnail/main image. Related variant and seller snapshots can be retrieved through separate endpoints.
   *
   * Access is restricted based on user role: customers can view snapshots for their own orders, sellers can view snapshots for items sold by them, and administrators can view any snapshot for oversight purposes.
   *
   * @param connection
   * @param orderId UUID of the order containing the order item
   * @param orderItemId UUID of the order item whose product snapshot should be retrieved
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate the order exists by orderId (UUID)
   * 2. Validate the order item exists by orderItemId and belongs to the specified order
   * 3. Retrieve the product snapshot where order_item_id matches the orderItemId (1:1 relationship per schema @@unique([order_item_id]))
   * 4. Eager load associated images ordered by display_order ASC
   * 5. Verify authorization:
   *    - Customer role: verify order.customer_id matches authenticated customer
   *    - Seller role: verify order_item.seller_id matches authenticated seller
   *    - Admin role: unrestricted access
   * 6. Return the product snapshot with nested images array
   *
   * Error scenarios:
   * - 404 if order not found
   * - 404 if order item not found or doesn't belong to order
   * - 404 if product snapshot not found (should not occur if order creation was successful)
   * - 403 if user lacks permission to view this order
   *
   * Database query:
   * ```sql
   * SELECT ps.*, psi.*
   * FROM ecommerce_mall_order_item_product_snapshots ps
   * LEFT JOIN ecommerce_mall_order_item_product_snapshot_images psi ON ps.id = psi.order_item_product_snapshot_id
   * WHERE ps.order_item_id = :orderItemId
   * ORDER BY psi.display_order ASC
   * ```
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IEcommerceMallOrderItemProductSnapshot> {
    try {
      return await getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdProductSnapshot(
        {
          admin,
          orderId,
          orderItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
