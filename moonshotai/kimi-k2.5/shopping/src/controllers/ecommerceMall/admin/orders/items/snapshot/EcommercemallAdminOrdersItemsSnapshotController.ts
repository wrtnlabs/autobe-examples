import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItemSnapshot } from "../../../../../../api/structures/IEcommerceMallOrderItemSnapshot";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdSnapshot } from "../../../../../../providers/getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdSnapshot";

@Controller("/ecommerceMall/admin/orders/:orderId/items/:orderItemId/snapshot")
export class EcommercemallAdminOrdersItemsSnapshotController {
  /**
   * Retrieves the immutable snapshot data for a specific order item.
   *
   * This endpoint returns the complete purchase-time state captured when the order was placed, including:
   * - The product snapshot with name, description, category, base price, and images as they appeared at purchase time
   * - The variant snapshot with SKU code, option values, and price at the time of purchase
   * - The seller profile snapshot with shop name and logo as they were displayed to the customer
   *
   * Snapshots are created automatically by the system during order creation and serve as the authoritative historical record for dispute resolution and legal compliance. They remain unchanged even if the original product, variant, or seller profile is later modified or deleted, per the snapshot immutability requirements.
   *
   * The snapshot data is used when displaying historical order information to ensure accurate historical records, regardless of subsequent changes to the seller's catalog or profile.
   *
   * Authorization: Administrators have access to view snapshots of any order item for platform oversight and dispute resolution purposes per section 586 (data access control). Customer and seller snapshots are accessible through their respective endpoints.
   *
   * @param connection
   * @param orderId The unique identifier of the order
   * @param orderItemId The unique identifier of the order item within the order
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Validate that the orderItemId belongs to the specified orderId to prevent unauthorized access to other orders' items.
   *
   * Query the ecommerce_mall_order_item_snapshots junction table by order_item_id to retrieve the snapshot relationship record.
   *
   * Perform the following joins to assemble the complete snapshot:
   * - Join with ecommerce_mall_order_item_product_snapshots to get product data (name, description, category_name, base_price, created_at)
   * - Join with ecommerce_mall_order_item_variant_snapshots to get variant data (sku_code, price, created_at)
   * - Join with ecommerce_mall_order_item_seller_snapshots to get seller data (shop_name, logo_url, created_at)
   * - For product images, join with ecommerce_mall_order_item_product_snapshot_images
   * - For variant option values, join with ecommerce_mall_order_item_variant_snapshot_attributes
   *
   * Return all snapshot data in a unified structure. If the snapshot doesn't exist (should not happen for valid order items), return 404.
   *
   * Authorization: The requesting customer must be the owner of the order. Sellers can view snapshots for their own order items. Administrators can view any snapshot.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IEcommerceMallOrderItemSnapshot> {
    try {
      return await getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdSnapshot({
        admin,
        orderId,
        orderItemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
