import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItemSellerSnapshot } from "../../../../../../api/structures/IEcommerceMallOrderItemSellerSnapshot";
import { AdminAuth } from "../../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdSellerSnapshot } from "../../../../../../providers/getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdSellerSnapshot";

@Controller(
  "/ecommerceMall/admin/orders/:orderId/items/:orderItemId/sellerSnapshot",
)
export class EcommercemallAdminOrdersItemsSellersnapshotController {
  /**
   * Retrieve the seller profile snapshot associated with a specific order item.
   *
   * This operation returns the immutable snapshot of the seller's shop profile that was captured at the moment of purchase. The snapshot preserves the seller's shop name, description, and logo image as they appeared when the order was placed. This preserved state is used for order context, dispute resolution, and maintaining historical accuracy even if the seller later changes their profile or deletes their account.
   *
   * Only customers who own the order, the seller whose profile is captured, or administrators can access this snapshot. The snapshot is read-only and cannot be modified.
   *
   * @param connection
   * @param orderId Unique identifier of the order containing the order item (global scope)
   * @param orderItemId Unique identifier of the order item whose seller snapshot to retrieve (scoped to order)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Retrieve the seller profile snapshot from ecommerce_mall_order_item_seller_snapshots table.
   *
   * Query by orderItemId to find the associated seller snapshot record.
   * Validate that the requesting user has permission to view this order item:
   * - Customer must be the order owner
   * - OR Seller must be the snapshot owner
   * - OR User is an administrator
   *
   * Return the snapshot containing:
   * - shopName: the seller's shop name at time of purchase
   * - shopDescription: the shop description at time of purchase
   * - logoImage: the logo image URL/path at time of purchase
   * - createdAt: timestamp when the snapshot was created
   *
   * This is a read-only operation that returns historical data preserved for order context and dispute resolution.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("orderItemId")
    orderItemId: string,
  ): Promise<IEcommerceMallOrderItemSellerSnapshot> {
    try {
      return await getEcommerceMallAdminOrdersOrderIdItemsOrderItemIdSellerSnapshot(
        {
          admin,
          orderId,
          orderItemId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
