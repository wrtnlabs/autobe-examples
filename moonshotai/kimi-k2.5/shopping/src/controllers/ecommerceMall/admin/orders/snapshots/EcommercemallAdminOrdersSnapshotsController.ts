import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderSnapshot } from "../../../../../api/structures/IEcommerceMallOrderSnapshot";
import { IPageIEcommerceMallOrderSnapshot } from "../../../../../api/structures/IPageIEcommerceMallOrderSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminOrdersOrderIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallAdminOrdersOrderIdSnapshotsSnapshotId";
import { patchEcommerceMallAdminOrdersOrderIdSnapshots } from "../../../../../providers/patchEcommerceMallAdminOrdersOrderIdSnapshots";

@Controller("/ecommerceMall/admin/orders/:orderId/snapshots")
export class EcommercemallAdminOrdersSnapshotsController {
  /**
   * Retrieve a paginated list of order snapshots for a specific order.
   *
   * Order snapshots are immutable point-in-time records that capture the complete state of an order at specific moments. They are created automatically when orders undergo significant status changes or when audit records are required for compliance and legal purposes.
   *
   * This operation allows authorized users to view the history of order states, enabling them to track how an order evolved over time. Customers can view snapshots of their own orders for personal reference, while administrators can view snapshots of any order for dispute resolution and auditing purposes.
   *
   * Snapshots include the timestamp when they were created and maintain a reference to the order state at that moment. They are stored chronologically and can be filtered by creation date ranges for historical analysis.
   *
   * The response includes essential snapshot information suitable for list displays, with full snapshot details available through related operations.
   *
   * @param connection
   * @param orderId Order ID (UUID format)
   * @param body Filter criteria and pagination parameters for snapshot listing
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_order_snapshots table filtering by the order_id path parameter.
   *
   * Validate that the requesting actor has permission to view this order's snapshots:
   * - Customers can only view snapshots of their own orders
   * - Administrators can view snapshots of any order
   * - Sellers can view snapshots for orders containing their items
   *
   * Apply filters from the request body:
   * - Filter by created_at date range (createdAfter, createdBefore)
   * - Apply pagination parameters (page, limit)
   * - Sort by created_at in descending order (newest first)
   *
   * Return paginated results with snapshot summary including id, orderId, and createdAt. Handle edge cases where the order has no snapshots by returning empty data array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IEcommerceMallOrderSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallOrderSnapshot.ISummary> {
    try {
      return await patchEcommerceMallAdminOrdersOrderIdSnapshots({
        admin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific order snapshot by ID for administrator oversight and dispute resolution.
   *
   * This endpoint returns the complete details of an order snapshot, which captures the state of an order at a specific point in time. Order snapshots are immutable records created automatically when orders undergo significant state changes or when audit records are required for compliance and legal purposes.
   *
   * Each snapshot preserves the order state including the reference to the order, the timestamp when the snapshot was created, and any related data captured at that moment. Snapshots serve as authoritative historical records for dispute resolution, accounting audits, and legal compliance.
   *
   * This is an administrator-only endpoint intended for:
   * - Investigation of order-related disputes
   * - Audit trail review for compliance purposes
   * - Legal proceedings requiring historical order evidence
   *
   * Snapshots are permanent records that remain accessible even if the original order is deleted, ensuring complete audit trails for financial transactions.
   *
   * @param connection
   * @param orderId Target order's ID (UUID)
   * @param snapshotId Target snapshot's ID (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement by querying the ecommerce_mall_order_snapshots table using the provided snapshotId parameter. Validate that the snapshot exists and belongs to the specified orderId. Join with the ecommerce_mall_orders table to verify authorization:
   *
   * 1. For customers: Verify the order belongs to the authenticated customer by checking customer_id
   * 2. For sellers: Verify the order contains order items belonging to the authenticated seller via ecommerce_mall_order_items table
   * 3. For administrators: Allow access to any snapshot
   *
   * Return the snapshot record with fields: id, order_id, created_at. If the snapshot includes additional captured state data (such as order details at the time of snapshot), include those fields in the response.
   *
   * Edge cases to handle:
   * - Return 404 error if snapshotId does not exist
   * - Return 404 error if snapshot exists but does not belong to the specified orderId
   * - Return 403 error if the authenticated user is not authorized to view this snapshot
   *
   * The snapshot data is immutable - never return modified or partial snapshot data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallOrderSnapshot> {
    try {
      return await getEcommerceMallAdminOrdersOrderIdSnapshotsSnapshotId({
        admin,
        orderId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
