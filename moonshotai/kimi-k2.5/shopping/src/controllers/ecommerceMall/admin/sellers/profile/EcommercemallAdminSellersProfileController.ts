import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSeller } from "../../../../../api/structures/IEcommerceMallSeller";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminSellersSellerIdProfile } from "../../../../../providers/getEcommerceMallAdminSellersSellerIdProfile";

@Controller("/ecommerceMall/admin/sellers/:sellerId/profile")
export class EcommercemallAdminSellersProfileController {
  /**
   * Retrieve a seller's shop profile information.
   *
   * This operation returns the current profile details for a specific seller, including the shop name, description, and logo image URL. Seller profiles are publicly visible and do not require authentication to access.
   *
   * The profile data is returned from the seller's current active profile state. This endpoint is commonly used when customers browse products and want to learn more about the shop they're purchasing from, or when navigating to a seller's dedicated shop page.
   *
   * The response includes the complete profile information: shop name for identification, shop description for business context, and logo image URL for visual branding. If the seller has not yet set up their profile or certain fields, those fields may be null.
   *
   * @param connection
   * @param sellerId Target seller's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the current profile state for the specified seller.
   *
   * Implementation steps:
   * 1. Extract sellerId from path parameter
   * 2. Verify seller exists by querying ecommerce_mall_sellers table by id
   * 3. If seller not found or deleted (deleted_at is not null), return 404
   * 4. Retrieve the current profile data (shop_name, shop_description, logo_image_url)
   * 5. Return the profile data in IEcommerceMallSellerProfile format
   *
   * Authorization: Public endpoint - no authentication required per requirements section 66 (Public Visibility and Customer Access).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
  ): Promise<IEcommerceMallSeller> {
    try {
      return await getEcommerceMallAdminSellersSellerIdProfile({
        admin,
        sellerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
