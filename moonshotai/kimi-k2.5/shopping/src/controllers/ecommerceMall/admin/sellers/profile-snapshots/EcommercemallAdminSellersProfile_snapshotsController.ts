import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerProfileSnapshot } from "../../../../../api/structures/IEcommerceMallSellerProfileSnapshot";
import { IPageIEcommerceMallSellerProfileSnapshot } from "../../../../../api/structures/IPageIEcommerceMallSellerProfileSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminSellersSellerIdProfileSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallAdminSellersSellerIdProfileSnapshotsSnapshotId";
import { patchEcommerceMallAdminSellersSellerIdProfileSnapshots } from "../../../../../providers/patchEcommerceMallAdminSellersSellerIdProfileSnapshots";

@Controller("/ecommerceMall/admin/sellers/:sellerId/profile-snapshots")
export class EcommercemallAdminSellersProfile_snapshotsController {
  /**
   * Retrieve a paginated list of profile snapshots for a specific seller.
   *
   * Seller profile snapshots are immutable point-in-time records that capture the complete state of a seller's shop profile (shop name, description, and logo image) before each edit operation. These snapshots serve as an audit trail for dispute resolution and historical verification.
   *
   * Snapshots are created automatically whenever a seller modifies their profile through the profile update operation. Each snapshot preserves the exact values that were in effect at the moment of the change, along with the precise timestamp when the modification occurred.
   *
   * Results are ordered chronologically by creation time (newest first by default). The response includes summary information optimized for list display while maintaining the complete field values for each snapshot.
   *
   * This operation supports both sellers viewing their own profile history and administrators reviewing any seller's profile changes for oversight and dispute investigation purposes.
   *
   * @param connection
   * @param sellerId Unique identifier of the seller whose profile snapshots are being retrieved (UUID format)
   * @param body Search criteria and pagination parameters for filtering profile snapshots
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_seller_profile_snapshots
     *   table filtered by the provided sellerId path parameter.
   *
   * Implement pagination using cursor-based or offset-based pagination depending on the request parameters. Support search criteria in the request body including:
   * - Date range filtering (createdAfter, createdBefore)
   * - Pagination parameters (limit, cursor/page)
   *
   * Return snapshot summaries containing: id, shop_name, shop_description, logo_image_url, and created_at.
   *
   * Order results by created_at in descending order (newest snapshots first) by default, with option to sort ascending.
   *
   * Authorization checks:
   * - Allow sellers to view their own profile snapshots
   * - Allow administrators to view any seller's profile snapshots
   * - Reject access with 403 for non-owners who are not administrators
   *
   * Performance optimization: Utilize the composite index on (seller_id, created_at) for efficient filtering and ordering.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedBody()
    body: IEcommerceMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallSellerProfileSnapshot.ISummary> {
    try {
      return await patchEcommerceMallAdminSellersSellerIdProfileSnapshots({
        admin,
        sellerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve the complete details of a specific seller profile snapshot.
   *
   * Seller profile snapshots are immutable records that capture the complete state of a seller's shop profile at a specific point in time. Each snapshot preserves the shop name, description, and logo image URL as they existed when the snapshot was created.
   *
   * These snapshots serve as an immutable audit trail for dispute resolution, enabling administrators and the platform to review historical states of seller profiles even after subsequent edits or account deletions. Snapshots are created whenever a seller edits their profile content and are referenced by order items to preserve the seller's shop identity at the time of purchase.
   *
   * Both the seller themselves and administrators can view snapshots. Sellers can view their own profile snapshots to understand how their shop information has evolved over time. Administrators can view any seller's snapshots for dispute investigation and resolution purposes.
   *
   * @param connection
   * @param sellerId The unique identifier of the seller (UUID format)
   * @param snapshotId The unique identifier of the specific profile snapshot to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_seller_profile_snapshots
     *   table for the snapshot matching both sellerId and snapshotId.
   *
   * Join with ecommerce_mall_sellers to ensure the snapshot belongs to the specified seller.
   *
   * Return the full snapshot data including: id, seller_id, shop_name, shop_description, logo_image_url, and created_at.
   *
   * Authorization: Sellers can only view their own snapshots. Administrators can view any seller's snapshots.
   *
   * Error handling: Return 404 if the snapshot is not found or does not belong to the specified seller. Return 403 if the requesting user is not authorized to view the snapshot.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("sellerId")
    sellerId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallSellerProfileSnapshot> {
    try {
      return await getEcommerceMallAdminSellersSellerIdProfileSnapshotsSnapshotId(
        {
          admin,
          sellerId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
