import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallGuest } from "../../../../../api/structures/IEcommerceMallGuest";
import { IEcommerceMallGuestSession } from "../../../../../api/structures/IEcommerceMallGuestSession";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminGuestsGuestIdSessionsSessionId } from "../../../../../providers/getEcommerceMallAdminGuestsGuestIdSessionsSessionId";
import { patchEcommerceMallAdminGuestsGuestIdSessions } from "../../../../../providers/patchEcommerceMallAdminGuestsGuestIdSessions";

@Controller("/ecommerceMall/admin/guests/:guestId/sessions")
export class EcommercemallAdminGuestsSessionsController {
  /**
   * Refresh a guest session to obtain new authentication tokens.
   *
   * This operation allows guests to extend their session validity by exchanging a valid refresh token for new access and refresh tokens. This supports long-running guest sessions for users who browse the platform without logging in while maintaining security through token rotation.
   *
   * The request must include a valid refresh token that was previously issued to the guest session. The system validates the refresh token against the stored session records and, if valid, generates new access and refresh tokens with extended expiry times.
   *
   * Security Considerations:
   * - Refresh tokens have a longer lifecycle than access tokens
   * - Each refresh operation invalidates the previous refresh token
   * - Token rotation prevents replay attacks
   * - Expired refresh tokens cannot be used
   *
   * The operation updates the session record with new token values and refreshed_at timestamp. The old refresh token is immediately invalidated upon successful completion.
   *
   * Response includes the complete session details with new token credentials and updated expiry timestamps.
   *
   * @param connection
   * @param guestId Guest session identifier (UUID format)
   * @param body Refresh token to exchange for new session credentials
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Implement token refresh logic for guest sessions:
   *
   * 1. Validate the guestId parameter format (UUID)
   *
   * 2. Extract and validate the refreshToken from request body
   *    - Must be non-empty string
   *    - Must match the refresh_token stored for the guest session
   *
   * 3. Query the guest_sessions table:
   *    - Find record where guest_id = guestId AND refresh_token = refreshToken
   *    - Check if expires_at > current time (token not expired)
   *
   * 4. If refresh token is expired or doesn't match:
   *    - Return 401 Unauthorized with error "Refresh token expired or invalid"
   *
   * 5. Generate new tokens:
   *    - Generate new JWT access token (short duration, e.g., 15 minutes)
   *    - Generate new random refresh token (longer duration, e.g., 7 days)
   *    - Calculate new expires_at timestamp
   *
   * 6. Update guest_sessions record atomically:
   *    - Set access_token = newAccessToken
   *    - Set refresh_token = newRefreshToken
   *    - Set refreshed_at = current timestamp
   *    - Set expires_at = calculated expiry
   *    - Set updated_at = current timestamp
   *
   * 7. Return the updated session details with new tokens
   *
   * Edge Cases:
   * - Concurrent refresh requests: Use database locking to prevent race conditions
   * - If refresh token was already used (replay attack): Invalidate session entirely and require re-authentication
   * - Handle missing guest session gracefully with 404
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async refresh(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string,
    @TypedBody()
    body: IEcommerceMallGuest.IRefresh,
  ): Promise<IEcommerceMallGuestSession> {
    try {
      return await patchEcommerceMallAdminGuestsGuestIdSessions({
        admin,
        guestId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific guest session by its ID.
   *
   * This operation returns detailed information about a guest's authentication session, including session metadata such as IP address, referrer URL, and lifecycle timestamps. The session must belong to the specified guest.
   *
   * This endpoint is typically used to validate session state or retrieve session information for authentication purposes.
   *
   * @param connection
   * @param guestId Target guest's ID (global scope)
   * @param sessionId Target session's ID (scoped to guest)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_guest_sessions table filtering by the session ID and guest ID.
   *
   * 1. Validate that guestId and sessionId are valid UUID strings
   * 2. Query the session record where id = sessionId AND ecommerce_mall_guest_id = guestId
   * 3. If no record found, return 404 Not Found
   * 4. Return the session entity with all fields
   *
   * The composite key (guestId + sessionId) ensures proper authorization - users can only access sessions belonging to the specified guest.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string & tags.Format<"uuid">,
    @TypedParam("sessionId")
    sessionId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallGuestSession> {
    try {
      return await getEcommerceMallAdminGuestsGuestIdSessionsSessionId({
        admin,
        guestId,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
