import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { IPageIEcommerceMallGuest } from "../../../../api/structures/IPageIEcommerceMallGuest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminGuestsGuestId } from "../../../../providers/getEcommerceMallAdminGuestsGuestId";
import { patchEcommerceMallAdminGuests } from "../../../../providers/patchEcommerceMallAdminGuests";

@Controller("/ecommerceMall/admin/guests")
export class EcommercemallAdminGuestsController {
  /**
   * Retrieve a filtered and paginated list of temporary guest accounts created by unauthenticated visitors.
   *
   * This operation enables administrators to monitor guest activity across the platform, including guest creation patterns, session activity, and time-based analytics. Guest accounts are temporary entities that exist before users register as customers or sellers. Only administrators can access this endpoint as part of security and analytics oversight.
   *
   * Guests represent unauthenticated visitors with no persistent identity beyond their current browsing session. The system tracks guest sessions in ecommerce_mall_guest_sessions which belong to guest accounts. Guest accounts are automatically cleaned up after expiration and do not persist between visits.
   *
   * Filtering supports date range queries on created_at field to identify guest creation patterns. Response includes summary guest information optimized for list displays with pagination for large result sets.
   *
   * Requires administrator authentication. Related operations: Guest session logs require accessing the guest_sessions relation separately.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering guest accounts
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query ecommerce_mall_guests table with cursor-based pagination and filtering.
   * Apply date range filters on created_at column for guest creation analytics.
   * Support soft delete filtering via deleted_at (exclude deleted by default, include with flag).
   * Join with ecommerce_mall_guest_sessions to compute session_count if requested.
   * Order by created_at DESC for newest guests first.
   * Return paginated results with IEcommerceMallGuest.ISummary structure.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallGuest.IRequest,
  ): Promise<IPageIEcommerceMallGuest.ISummary> {
    try {
      return await patchEcommerceMallAdminGuests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific guest account by its unique identifier.
   *
   * This operation returns detailed information about a temporary guest account, including its creation timestamp, last update time, and associated session tokens. Guest accounts are temporary browser sessions that allow unauthenticated visitors to access login and registration endpoints before completing registration.
   *
   * The response includes all session tokens associated with this guest, which track JWT authentication sessions and connection metadata (IP address, referrer URL). Each session has its own lifecycle with creation and expiration timestamps.
   *
   * Note that guest accounts have soft deletion capability - if deleted_at is present, the guest account has been removed but may still be referenced in historical records.
   *
   * @param connection
   * @param guestId Target guest's unique identifier (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor admin
   * @x-autobe-specification Query the ecommerce_mall_guests table by the provided guestId parameter.
   *
   * Retrieve the guest record with columns: id, created_at, updated_at, deleted_at.
   *
   * Join with ecommerce_mall_guest_sessions to include all associated sessions where ecommerce_mall_guest_id matches the guest id.
   *
   * For each session, include: id, ecommerce_mall_guest_id, ip, href, referrer, created_at, expired_at.
   *
   * Return 404 error if no guest exists with the provided guestId.
   *
   * Return 400 error if guestId is not a valid UUID format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("guestId")
    guestId: string,
  ): Promise<IEcommerceMallGuest> {
    try {
      return await getEcommerceMallAdminGuestsGuestId({
        admin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
