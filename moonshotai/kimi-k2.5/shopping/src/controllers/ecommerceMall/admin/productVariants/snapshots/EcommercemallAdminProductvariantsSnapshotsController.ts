import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProductVariantSnapshot } from "../../../../../api/structures/IEcommerceMallProductVariantSnapshot";
import { AdminAuth } from "../../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminProductVariantsVariantIdSnapshotsCompare } from "../../../../../providers/getEcommerceMallAdminProductVariantsVariantIdSnapshotsCompare";
import { getEcommerceMallAdminProductVariantsVariantIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallAdminProductVariantsVariantIdSnapshotsSnapshotId";

@Controller("/ecommerceMall/admin/productVariants/:variantId/snapshots")
export class EcommercemallAdminProductvariantsSnapshotsController {
  /**
   * Retrieve a specific product variant snapshot by its unique identifier.
   *
   * Product variant snapshots are immutable point-in-time records that preserve the complete state of a variant at the moment of modification. Each snapshot captures the SKU code, price, and all option values that existed before a change was made.
   *
   * Snapshots serve as the authoritative audit trail for dispute resolution and historical reference. They cannot be modified or deleted after creation and remain preserved even if the parent variant is later deleted.
   *
   * Authorization rules:
   * - Sellers can view snapshots of their own product variants
   * - Administrators can view snapshots of any product variant on the platform
   *
   * This operation returns the complete snapshot record including the captured SKU code, price at the time of snapshot, creation timestamp, and associated option value records stored in the normalized child table.
   *
   * @param connection
   * @param variantId UUID of the product variant (scoped context)
   * @param snapshotId UUID of the snapshot to retrieve
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Implement authorization checking based on user
     *   role:
   *
   * 1. For seller role: Verify the product variant identified by variantId belongs to the authenticated seller by joining with ecommerce_mall_product_variants -> ecommerce_mall_products -> seller_id
   * 2. For admin/superAdmin roles: Allow access to any snapshot
   *
   * Query the ecommerce_mall_product_variant_snapshots table by snapshotId primary key.
   * Include related option values from ecommerce_mall_product_variant_snapshot_option_values child table joined by snapshot_id.
   *
   * Handle error cases:
   * - If snapshot not found: return 404 error
   * - If variantId in path does not match the snapshot's product_variant_id: return 404 (prevent information leakage about snapshot existence under wrong variant)
   * - If seller attempts to access another seller's snapshot: return 403 Forbidden
   *
   * Return the full snapshot entity with all fields: id, product_variant_id, sku_code, price, created_at, and nested array of option values.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("variantId")
    variantId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallProductVariantSnapshot> {
    try {
      return await getEcommerceMallAdminProductVariantsVariantIdSnapshotsSnapshotId(
        {
          admin,
          variantId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Compare two snapshots of a product variant to identify differences.
   *
   * This operation retrieves two specific snapshots of a product variant and returns a detailed comparison showing what changed between them. The comparison includes differences in SKU code, price, and option values.
   *
   * Sellers can compare snapshots of their own product variants to track changes over time. Administrators can compare snapshots of any variant on the platform. This supports audit trails and dispute resolution by enabling users to see exactly what changed between any two points in time.
   *
   * Snapshots are immutable records (Section 281) that preserve the complete state of a variant at a specific moment. Every edit to a variant (Section 212, 493) creates a snapshot recording the previous state including SKU code, option values, and price.
   *
   * @param connection
   * @param variantId Unique identifier of the product variant (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Validate that the variant exists and is
     *   accessible to the requesting user (sellers can only access their own
     *   variants, administrators can access any).
   *
   * Validate that both snapshot IDs reference snapshots belonging to the specified variant.
   *
   * Retrieve both snapshots from ecommerce_mall_product_variant_snapshots with their related optionValues from ecommerce_mall_product_variant_snapshot_option_values.
   *
   * Calculate the differences between the two snapshots:
   * - Compare sku_code field
   * - Compare price field
   * - Compare optionValues (key-value pairs) - identify added, removed, or changed options
   *
   * Return the comparison result including both snapshot timestamps and the detected differences. The comparison should show before/after values for each changed field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("compare")
  public async compare(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("variantId")
    variantId: string,
  ): Promise<IEcommerceMallProductVariantSnapshot.ICompare> {
    try {
      return await getEcommerceMallAdminProductVariantsVariantIdSnapshotsCompare(
        {
          admin,
          variantId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
