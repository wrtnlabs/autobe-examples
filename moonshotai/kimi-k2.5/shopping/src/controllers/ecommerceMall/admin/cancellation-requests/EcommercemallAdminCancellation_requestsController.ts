import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCancellationRequest } from "../../../../api/structures/IEcommerceMallCancellationRequest";
import { IPageIEcommerceMallCancellationRequest } from "../../../../api/structures/IPageIEcommerceMallCancellationRequest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminCancellationRequestsCancellationRequestId } from "../../../../providers/getEcommerceMallAdminCancellationRequestsCancellationRequestId";
import { patchEcommerceMallAdminCancellationRequests } from "../../../../providers/patchEcommerceMallAdminCancellationRequests";

@Controller("/ecommerceMall/admin/cancellation-requests")
export class EcommercemallAdminCancellation_requestsController {
  /**
   * Retrieve a filtered and paginated list of cancellation requests.
   *
   * This operation provides search capabilities for cancellation requests submitted by customers or reviewed by sellers. Customers can view their own cancellation requests to track status changes from 'pending' to 'approved' or 'rejected'. Sellers can view cancellation requests for order items they need to review and respond to.
   *
   * Supports comprehensive filtering including status ('pending', 'approved', 'rejected'), date range for request creation, and associated order items. Results are paginated with cursor-based navigation and support sorting by newest first or by status.
   *
   * Cancellation requests preserve the state through snapshots when sellers respond, ensuring audit trail integrity for dispute resolution.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering cancellation requests
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_mall_cancellation_requests table
     *   with pagination and filtering.
   *
   * Authorization and Access Control:
   * - Customers: Only see cancellation requests where customerId matches their authenticated customer ID
   * - Sellers: Only see cancellation requests where sellerId matches their authenticated seller ID
   * - Admins/SuperAdmins: Can view all cancellation requests with optional customerId or sellerId filters
   *
   * Query Parameters (in request body):
   * - status: Filter by cancellation request status ('pending', 'approved', 'rejected')
   * - orderItemId: Filter by specific order item
   * - customerId: For sellers/admins - filter by requesting customer (ignored for regular customers)
   * - sellerId: For admins - filter by responding seller
   * - createdAtFrom: Filter requests created after this timestamp
   * - createdAtTo: Filter requests created before this timestamp
   * - sortBy: 'createdAt' | 'updatedAt' | 'status'
   * - sortOrder: 'asc' | 'desc'
   * - pagination: cursor or offset-based pagination parameters
   *
   * Database Query Strategy:
   * 1. Apply WHERE clauses for all provided filters
   * 2. Add authorization filter based on actor type (customer_id = currentCustomerId OR seller_id = currentSellerId)
   * 3. Join with ecommerce_mall_order_items to get item details
   * 4. Join with ecommerce_mall_customers for customer display name
   * 5. Join with ecommerce_mall_sellers for seller shop name
   * 6. Order by requested sort field
   * 7. Apply pagination limit and offset
   *
   * Response includes:
   * - Cancellation request ID, status, reason, response reason
   * - Related order item summary
   * - Customer and seller information
   * - Timestamps (created_at, responded_at)
   * - Pagination metadata with next cursor
   *
   * Error Handling:
   * - Return empty page if no matching records found (not an error)
   * - Reject if date range is invalid (from after to)
   * - Reject if status filter contains invalid values
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallCancellationRequest.IRequest,
  ): Promise<IPageIEcommerceMallCancellationRequest.ISummary> {
    try {
      return await patchEcommerceMallAdminCancellationRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single cancellation request by its unique identifier.
   *
   * This operation returns the complete details of a cancellation request, including the customer's reason, current status (pending, approved, or rejected), the seller's response and note if available, and associated order item information. Each cancellation request includes creation timestamps and maintains a complete snapshot history for audit purposes.
   *
   * The response contains the full IEcommerceMallCancellationRequest entity with nested order item details, customer information, seller information (if reviewed), and the snapshot array showing all state changes and decisions made on this request.
   *
   * @param connection
   * @param cancellationRequestId Unique identifier of the cancellation request (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_cancellation_requests
     *   table by the provided cancellationRequestId UUID.
   *
   * Join with ecommerce_mall_order_items to include order item details (product name, variant options, quantity).
   * Join with ecommerce_mall_customers to include customer information.
   * Left join with ecommerce_mall_sellers to include seller reviewer information (nullable, only populated after seller responds).
   * Join with ecommerce_mall_cancellation_request_snapshots to include the complete history of state changes.
   *
   * Verify the requesting user (customer or seller or admin) has permission to view this specific cancellation request.
   * Return 404 if the cancellation request does not exist or has been soft-deleted.
   * Return 403 if the requesting user is not authorized to view this request (not the requester customer, not the seller associated with the order item, and not an admin).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":cancellationRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("cancellationRequestId")
    cancellationRequestId: string,
  ): Promise<IEcommerceMallCancellationRequest> {
    try {
      return await getEcommerceMallAdminCancellationRequestsCancellationRequestId(
        {
          admin,
          cancellationRequestId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
