import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallRefundRequest } from "../../../../api/structures/IEcommerceMallRefundRequest";
import { IPageIEcommerceMallRefundRequest } from "../../../../api/structures/IPageIEcommerceMallRefundRequest";
import { AdminAuth } from "../../../../decorators/AdminAuth";
import { AdminPayload } from "../../../../decorators/payload/AdminPayload";
import { getEcommerceMallAdminRefundRequestsRefundRequestId } from "../../../../providers/getEcommerceMallAdminRefundRequestsRefundRequestId";
import { patchEcommerceMallAdminRefundRequests } from "../../../../providers/patchEcommerceMallAdminRefundRequests";

@Controller("/ecommerceMall/admin/refund-requests")
export class EcommercemallAdminRefund_requestsController {
  /**
   * Retrieve a filtered and paginated list of refund requests.
   *
   * This operation provides comprehensive search capabilities for refund requests across different user perspectives. Customers can view refund requests they have submitted for their delivered order items. Sellers can view refund requests targeting their products. Administrators have access to all refund requests on the platform.
   *
   * Refund requests represent formal customer petitions to return delivered order items and receive refunds within the 7-day return window. Each request is associated with a specific order item and contains the customer's reason for the return. Customers may cancel pending refund requests, which results in soft deletion of the request record.
   *
   * The search supports filtering by request status (pending, approved, rejected), submission date ranges, and related order information. Only active (non-cancelled) refund requests are returned. Results include summary data optimized for list displays, showing key information such as request status, submission date, and associated order details.
   *
   * Supports comprehensive pagination with configurable page sizes and sorting options. Response includes metadata for navigating through large result sets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for refund requests
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query ecommerce_mall_refund_requests table with
     *   join to ecommerce_mall_order_items for order context.
   *
   * **Authentication & Authorization:**
   * - Customer: Filter by customer's order items via order_items → orders relationship
   * - Seller: Filter by seller's order items via order_items.sellerId
   * - Admin/SuperAdmin: No additional filtering (view all)
   *
   * **Search Filters:**
   * - status: Filter by refund request status (pending, approved, rejected)
   * - orderItemId: Filter by specific order item
   * - createdAt range: Filter by request submission date range
   * - Include related order item details with product and variant snapshots
   *
   * **Pagination:**
   * - Cursor-based pagination for large result sets
   * - Default page size: 20
   * - Max page size: 100
   * - Sort by createdAt descending (newest first) by default
   * - Optional sort by status or orderId
   *
   * **Related Data:**
   * - Join with order_items to get purchase context
   * - Include product snapshot data (name, image)
   * - Include variant snapshot data (SKU, options)
   * - Include seller profile snapshot for seller context
   *
   * **Performance:**
   * - Index on status, order_item_id, created_at columns
   * - Use covering indexes for summary fields
   * - Optimize joins with order_items table
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @AdminAuth()
    admin: AdminPayload,
    @TypedBody()
    body: IEcommerceMallRefundRequest.IRequest,
  ): Promise<IPageIEcommerceMallRefundRequest.ISummary> {
    try {
      return await patchEcommerceMallAdminRefundRequests({
        admin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single refund request by its unique identifier.
   *
   * This operation returns the complete details of a refund request including the associated order item, requesting customer, seller responsible for review, refund reason, current status, and relevant timestamps.
   *
   * Refund requests represent customer petitions to return delivered items within the 7-day return window. The request status indicates whether it is pending seller review, approved, or rejected. If the seller has responded, the responded_at timestamp will be populated.
   *
   * This endpoint is used by customers to check the status of their refund requests and by sellers to review request details before responding. Access is restricted to the requesting customer and the responsible seller.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request (global scope, UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor admin
     * @x-autobe-specification Query the ecommerce_mall_refund_requests table by
     *   primary key (id).
   *
   * Use parameterized query to fetch the refund request record matching the provided refundRequestId.
   *
   * The query should join with related entities to provide complete context:
   * - Join with ecommerce_mall_order_items to get order item details
   * - Join with ecommerce_mall_customers to get customer information
   * - Join with ecommerce_mall_sellers to get seller information
   *
   * Validate that the authenticated user has permission to view this refund request:
   * - For customers: the customer_id must match the requesting customer
   * - For sellers: the seller_id must match the authenticated seller
   * - For admins/superAdmins: allow access regardless of ownership
   *
   * Return a 404 error if the refund request does not exist.
   * Return a 403 error if the user attempts to access a refund request they do not have permission to view.
   *
   * Apply soft-delete check: do not return refund requests where deleted_at is not null (customers can cancel pending requests by soft-deleting).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":refundRequestId")
  public async at(
    @AdminAuth()
    admin: AdminPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await getEcommerceMallAdminRefundRequestsRefundRequestId({
        admin,
        refundRequestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
