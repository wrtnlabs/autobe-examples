import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallSellerRegistration } from "../../../../../../api/structures/IEcommerceMallSellerRegistration";
import { SuperadminAuth } from "../../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../../decorators/payload/SuperadminPayload";
import { postEcommerceMallSuperAdminSellersRegistrationsRegistrationIdReview } from "../../../../../../providers/postEcommerceMallSuperAdminSellersRegistrationsRegistrationIdReview";

@Controller(
  "/ecommerceMall/superAdmin/sellers/registrations/:registrationId/review",
)
export class EcommercemallSuperadminSellersRegistrationsController {
  /**
   * Approve or reject a seller registration application.
   *
   * This endpoint allows administrators to review pending seller registrations and make approval decisions. When a seller submits a registration, it enters a pending status and requires administrator review before the seller can list products on the platform.
   *
   * Administrators can either approve the registration, which immediately grants the seller selling privileges, or reject the registration with a specific reason. When rejecting, administrators must provide clear reasoning that will be visible to the applicant, allowing them to address concerns and potentially resubmit.
   *
   * The review action updates the registration status to either 'approved' or 'rejected', records the reviewing administrator's ID, captures the review timestamp, and stores any rejection reason provided. Once reviewed, the registration status is final and the seller's account status is updated accordingly.
   *
   * For approved registrations, the seller gains immediate ability to create products and conduct sales. For rejected registrations, the seller remains in rejected status until they submit a new registration request addressing the cited issues.
   *
   * A snapshot of the registration state is automatically created before the review is processed, preserving the audit trail for dispute resolution and compliance tracking.
   *
   * @param connection
   * @param registrationId The unique identifier of the seller registration to review
   * @param body Review decision containing approval status and optional rejection reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate the registration exists and is in pending status. Verify the requesting actor is an administrator (admin or superAdmin role). Begin transaction: create a snapshot of the current registration state using ecommerce_mall_seller_registration_snapshots table to preserve pre-review state. Update the registration: set status to the provided value (approved or rejected), set reviewer_id to the current admin's ID, set reviewed_at to current timestamp. If status is rejected and rejection_reason is provided, store it in the rejection_reason field. If approving, update the associated seller's status to active. If rejecting, ensure rejection_reason is provided (business validation). Update the updated_at timestamp. Commit transaction and return the updated registration entity with seller and reviewer relations populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async review(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("registrationId")
    registrationId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallSellerRegistration.IReview,
  ): Promise<IEcommerceMallSellerRegistration> {
    try {
      return await postEcommerceMallSuperAdminSellersRegistrationsRegistrationIdReview(
        {
          superAdmin,
          registrationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
