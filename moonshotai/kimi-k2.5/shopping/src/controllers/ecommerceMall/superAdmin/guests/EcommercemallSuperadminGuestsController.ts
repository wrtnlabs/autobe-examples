import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallGuest } from "../../../../api/structures/IEcommerceMallGuest";
import { IPageIEcommerceMallGuest } from "../../../../api/structures/IPageIEcommerceMallGuest";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminGuestsGuestId } from "../../../../providers/getEcommerceMallSuperAdminGuestsGuestId";
import { patchEcommerceMallSuperAdminGuests } from "../../../../providers/patchEcommerceMallSuperAdminGuests";

@Controller("/ecommerceMall/superAdmin/guests")
export class EcommercemallSuperadminGuestsController {
  /**
   * Retrieve a filtered and paginated list of guest sessions.
   *
   * Guests are unauthenticated temporary visitors who have not registered or logged into the platform. This operation provides visibility into guest session activity for security monitoring and usage analytics.
   *
   * Per the platform's registration-required policy, guests can only access login and registration endpoints. All other platform functionality is blocked until authentication is completed. Guest sessions exist only until registration, login, or session termination.
   *
   * Administrators can search guest sessions by time ranges and filter by activity patterns. Results are paginated for efficient browsing of potentially large session volumes.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for guest session queries
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query ecommerce_mall_guests and ecommerce_mall_guest_sessions tables with pagination and filtering.
   *
   * Filter by: createdAt time range (start/end), lastActivityAt time range, IP address patterns, user agent patterns.
   *
   * Join with guest_sessions to retrieve session metadata including token expiration timestamps.
   *
   * Authorization: Restricted to admin and superAdmin actors only.
   *
   * Return cursor-based pagination with configurable page sizes. Include session validity status (active/expired).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IEcommerceMallGuest.IRequest,
  ): Promise<IPageIEcommerceMallGuest.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminGuests({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single guest account by its unique identifier.
   *
   * This operation fetches the complete guest entity including its creation and update timestamps. Guest accounts are temporary browser sessions created for unauthenticated visitors before registration.
   *
   * The returned guest information can be used to validate session existence and track guest activity timelines. The deleted_at field indicates if the guest account has been soft-deleted.
   *
   * @param connection
   * @param guestId Unique identifier of the guest account (UUID)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query ecommerce_mall_guests table by the provided guestId UUID parameter. Return the matching guest record with all fields: id, created_at, updated_at, deleted_at.
   *
   * Implementation details:
   * - Use exact UUID match on the id column
   * - Return 404 Not Found if no guest exists with the provided ID
   * - Include soft-deleted records if deleted_at is populated
   * - No authorization required - guest data is accessible in All namespace
   * - Response should contain complete entity for session validation purposes
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":guestId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("guestId")
    guestId: string,
  ): Promise<IEcommerceMallGuest> {
    try {
      return await getEcommerceMallSuperAdminGuestsGuestId({
        superAdmin,
        guestId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
