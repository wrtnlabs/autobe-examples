import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderSnapshot } from "../../../../../api/structures/IEcommerceMallOrderSnapshot";
import { IPageIEcommerceMallOrderSnapshot } from "../../../../../api/structures/IPageIEcommerceMallOrderSnapshot";
import { SuperadminAuth } from "../../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminOrdersOrderIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSuperAdminOrdersOrderIdSnapshotsSnapshotId";
import { patchEcommerceMallSuperAdminOrdersOrderIdSnapshots } from "../../../../../providers/patchEcommerceMallSuperAdminOrdersOrderIdSnapshots";

@Controller("/ecommerceMall/superAdmin/orders/:orderId/snapshots")
export class EcommercemallSuperadminOrdersSnapshotsController {
  /**
   * Retrieve a paginated list of order snapshots for a specific order.
   *
   * This operation provides access to historical snapshots of an order's state at various points in time. Order snapshots are automatically created during significant status changes and serve as immutable audit records for dispute resolution and order history tracking.
   *
   * Customers can view snapshots of their own orders to track order progression. Sellers can view snapshots of orders containing their items. Administrators can view snapshots of any order on the platform for investigation purposes.
   *
   * Snapshots include the complete order state at the time of capture, preserving all order item information, status, and related metadata. The response is paginated and supports filtering by snapshot creation time range.
   *
   * @param connection
   * @param orderId Unique identifier of the order whose snapshots are being retrieved
   * @param body Search criteria and pagination parameters for filtering order snapshots
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Query order snapshots filtered by the given
     *   orderId. Join with order_snapshots table where order_id matches the
     *   path parameter.
   *
   * Apply optional filters from request body:
   * - createdAtFrom: filter snapshots created after this timestamp
   * - createdAtTo: filter snapshots created before this timestamp
   *
   * Sort by created_at in descending order (newest first) by default.
   * Implement cursor-based or offset pagination based on request parameters.
   *
   * Access control:
   * - Customers: can only view snapshots for their own orders
   * - Sellers: can only view snapshots for orders containing their items
   * - Administrators: can view snapshots for any order
   *
   * Return paginated list of order snapshot summaries including snapshot ID, creation timestamp, and a summary of the order state at that point in time.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedBody()
    body: IEcommerceMallOrderSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallOrderSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminOrdersOrderIdSnapshots({
        superAdmin,
        orderId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single order snapshot by its ID.
   *
   * Order snapshots are immutable records that capture the complete state of an order at a specific point in time. They are created automatically during significant order state changes or when audit records are required for compliance and legal purposes.
   *
   * Snapshots preserve historical order data and cannot be modified or deleted. This endpoint allows authorized users to view the exact state of an order as it existed when the snapshot was created, including all associated metadata and timestamps.
   *
   * @param connection
   * @param orderId The unique identifier of the order (UUID format)
   * @param snapshotId The unique identifier of the order snapshot (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor superAdmin
     * @x-autobe-specification Query the ecommerce_mall_order_snapshots table
     *   filtering by both snapshot_id and order_id to ensure the snapshot
     *   belongs to the specified order.
   *
   * Return the complete snapshot record including: id, order_id, created_at, and any embedded order state data captured at snapshot time.
   *
   * Authorization: Order owners (customers), order item sellers, and administrators can view snapshots. Verify the requesting actor has permission to access the parent order before returning snapshot data.
   *
   * Edge cases: Return 404 if snapshot does not exist or does not belong to the specified order. Snapshots are immutable - no update or delete operations are supported.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("orderId")
    orderId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallOrderSnapshot> {
    try {
      return await getEcommerceMallSuperAdminOrdersOrderIdSnapshotsSnapshotId({
        superAdmin,
        orderId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
