import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallAdmin } from "../../../../api/structures/IEcommerceMallAdmin";
import { IPageIEcommerceMallAdmin } from "../../../../api/structures/IPageIEcommerceMallAdmin";
import { SuperadminAuth } from "../../../../decorators/SuperadminAuth";
import { SuperadminPayload } from "../../../../decorators/payload/SuperadminPayload";
import { getEcommerceMallSuperAdminAdminsAdminId } from "../../../../providers/getEcommerceMallSuperAdminAdminsAdminId";
import { patchEcommerceMallSuperAdminAdmins } from "../../../../providers/patchEcommerceMallSuperAdminAdmins";

@Controller("/ecommerceMall/superAdmin/admins")
export class EcommercemallSuperadminAdminsController {
  /**
   * Search and filter administrator accounts with pagination.
   *
   * This operation provides a paginated list of administrator accounts with filtering capabilities. Administrators can be filtered by their privilege grade (regular or super_admin), account status (active, suspended, or banned), and by name or email search terms.
   *
   * Results are returned in a paginated format for efficient browsing of administrator lists. Sorting is available by creation time and other relevant fields.
   *
   * Only super administrators have access to view all administrator accounts.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering administrators
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query ecommerce_mall_admins table with the following filter conditions:
   * 1. grade filter: 'regular' or 'super_admin' if specified in request
   * 2. status filter: 'active', 'suspended', or 'banned' if specified in request
   * 3. nickname search: partial match using trigram index (Gin)
   * 4. email search: partial match if specified
   * 5. created_at range: filter by min/max timestamps if provided
   *
   * Apply soft delete handling:
   * - By default, exclude records where deleted_at is not null
   * - Include soft-deleted admins only if includeDeleted flag is explicitly set in request
   *
   * Sorting options:
   * - created_at (asc/desc) - default desc
   * - grade, status
   *
   * Pagination:
   * - Use cursor-based pagination for efficient large dataset handling
   * - Support page-based fallback for simpler clients
   *
   * Return summary fields only: id, email, grade, status, nickname, created_at.
   * Exclude password_hash from all responses.
   *
   * Enforce authorization at service layer - validate caller has permission to list administrators.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedBody()
    body: IEcommerceMallAdmin.IRequest,
  ): Promise<IPageIEcommerceMallAdmin.ISummary> {
    try {
      return await patchEcommerceMallSuperAdminAdmins({
        superAdmin,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific administrator account.
   *
   * This operation returns complete administrator profile data including their privilege grade (regular or super administrator), account status (active, suspended, or banned), and metadata such as creation and update timestamps. The response includes the administrator's email address, display nickname, and role information necessary for audit and administrative oversight.
   *
   * Only super administrators and regular administrators with appropriate permissions can access administrator account details. This endpoint is primarily used for administrator management, audit trails, and governance workflows where understanding an administrator's grade and status is essential for platform oversight.
   *
   * The response excludes sensitive authentication data such as password hashes, which are never exposed through API interfaces. Administrator accounts represent the governance layer of the platform, responsible for seller approvals, category management, product oversight, and enforcing marketplace policies.
   *
   * @param connection
   * @param adminId The unique identifier of the administrator account to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Query the ecommerce_mall_admins table by the provided adminId UUID parameter.
   *
   * Select all columns except password_hash: id, email, grade, status, nickname, created_at, updated_at, deleted_at.
   *
   * The operation must verify that the requesting user has administrator privileges (either regular or super admin) before returning the data. Non-administrators should receive an authorization error.
   *
   * If no administrator with the given adminId exists, or if the administrator's deleted_at timestamp is set (soft deleted), return a not found error (404) with a consistent message to prevent enumeration attacks.
   *
   * Handle the case where adminId is not a valid UUID format with appropriate validation error (400).
   *
   * Return the full IEcommerceMallAdmin entity in the response body. The soft deletion status can be inferred from the presence of the deleted_at field.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":adminId")
  public async at(
    @SuperadminAuth()
    superAdmin: SuperadminPayload,
    @TypedParam("adminId")
    adminId: string,
  ): Promise<IEcommerceMallAdmin> {
    try {
      return await getEcommerceMallSuperAdminAdminsAdminId({
        superAdmin,
        adminId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
