  /**
   * Approve or reject an administrator promotion request.
   *
   * This operation allows super administrators to review pending promotion requests submitted by customers or sellers seeking administrative privileges. The super administrator can either approve the request, granting the requester regular administrator status, or reject the request with a reason.
   *
   * When approved, the requester's status changes to approved and they gain administrator privileges. When rejected, the rejection_reason field captures the explanation for the denial, allowing the requester to understand why their request was not accepted and potentially submit a new request in the future.
   *
   * The operation automatically sets the reviewer to the current authenticated super administrator and updates the review timestamp. A snapshot of the request state is created for audit trail purposes. Only requests with pending status can be reviewed; attempts to update already approved or rejected requests will fail.
   *
   * @param connection
   * @param requestId The unique identifier of the administrator promotion request to review
   * @param body Review decision and optional rejection reason for the promotion request
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor superAdmin
   * @x-autobe-specification Validate that the requesting user is a super administrator. Verify the promotion request exists and has pending status - reject if already approved or rejected.
   *
   * If status is being changed to 'approved':
   * - Validate no rejection_reason is provided (cannot reject and approve simultaneously)
   * - Set reviewer_id to current super admin's ID
   * - Create corresponding Administrator record for the requester with grade 'regular'
   * - Create AdminPromotionRequestSnapshot for audit trail
   *
   * If status is being changed to 'rejected':
   * - Validate rejection_reason is provided and non-empty
   * - Set reviewer_id to current super admin's ID
   * - Create AdminPromotionRequestSnapshot for audit trail
   *
   * Update the updated_at timestamp. Return the full promotion request entity including the reviewer relationship.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
