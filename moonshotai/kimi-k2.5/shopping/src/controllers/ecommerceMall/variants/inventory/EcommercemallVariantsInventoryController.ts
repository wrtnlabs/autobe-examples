import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallInventoryRecord } from "../../../../api/structures/IEcommerceMallInventoryRecord";
import { IPageIEcommerceMallInventoryRecord } from "../../../../api/structures/IPageIEcommerceMallInventoryRecord";
import { getEcommerceMallVariantsVariantIdInventoryRecordId } from "../../../../providers/getEcommerceMallVariantsVariantIdInventoryRecordId";
import { patchEcommerceMallVariantsVariantIdInventory } from "../../../../providers/patchEcommerceMallVariantsVariantIdInventory";

@Controller("/ecommerceMall/variants/:variantId/inventory")
export class EcommercemallVariantsInventoryController {
  /**
   * Retrieve paginated inventory records for a specific product variant.
   *
   * This operation returns the complete inventory history for a product variant, including all stock movements such as restocking (positive quantity changes), order deductions, cancellations, refunds, and manual adjustments. Each record shows the quantity change amount, reason for the change, and timestamp.
   *
   * Inventory records are immutable and serve as an audit trail for inventory management and dispute resolution. The current stock level is calculated by summing all quantity changes associated with the variant.
   *
   * This endpoint requires seller authentication. Sellers can only view inventory records for variants belonging to their own products. Access is verified by checking that the variant's product belongs to the authenticated seller.
   *
   * Returns paginated results with filtering capabilities. Supports filtering by date range to view inventory movements within specific periods. Results are sorted by creation time in descending order (newest first).
   *
   * @param connection
   * @param variantId Target product variant's ID
   * @param body Search criteria including pagination and date range filtering
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Validate seller authentication and ownership of the variant before returning records.
   *
   * Query Implementation:
   * 1. Find variant by variantId - reject if soft-deleted or not found
   * 2. Join with products table to verify seller ownership (product.seller_id must match authenticated seller)
   * 3. Query inventory_records table filtered by product_variant_id
   * 4. Apply request filters: date range (created_at between startDate and endDate), reason type filtering
   * 5. Sort by created_at DESC (newest inventory movements first)
   * 6. Apply cursor-based pagination using request pagination parameters
   *
   * Response Construction:
   * - Return IPageIEcommerceMallInventoryRecord.ISummary with pagination info
   * - Each record includes: id, quantityChange, reason, createdAt
   * - Calculate currentStock by summing all quantity_changes for the variant (can be cached or calculated on demand)
   *
   * Security Checks:
   * - Verify authenticated user is a seller
   * - Verify variant exists and belongs to seller's product
   * - Return 403 Forbidden if seller doesn't own the product
   * - Return 404 if variant doesn't exist or is deleted
   *
   * Business Logic:
   * - quantityChange > 0 indicates stock increase (restocking, cancellations, refunds)
   * - quantityChange < 0 indicates stock decrease (orders, adjustments)
   * - Records are immutable - never updated or deleted
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedParam("variantId")
    variantId: string,
    @TypedBody()
    body: IEcommerceMallInventoryRecord.IRequest,
  ): Promise<IPageIEcommerceMallInventoryRecord.ISummary> {
    try {
      return await patchEcommerceMallVariantsVariantIdInventory({
        variantId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific inventory record by its unique identifier.
   *
   * This operation returns the complete details of a single inventory record, providing visibility into a specific stock movement event. The response includes the quantity change, reason for the change, and timestamp when the record was created.
   *
   * Inventory records are immutable and serve as an audit trail for inventory management.
   *
   * @param connection
   * @param variantId Target product variant ID
   * @param recordId Target inventory record ID
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor null
   * @x-autobe-specification Query ecommerce_mall_inventory_records table by recordId. Verify the record belongs to the specified variantId. Authorization ensures sellers can only view records for their own product variants.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":recordId")
  public async at(
    @TypedParam("variantId")
    variantId: string,
    @TypedParam("recordId")
    recordId: string,
  ): Promise<IEcommerceMallInventoryRecord> {
    try {
      return await getEcommerceMallVariantsVariantIdInventoryRecordId({
        variantId,
        recordId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
