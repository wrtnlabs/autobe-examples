import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomer } from "../../../api/structures/IEcommerceMallCustomer";
import { IPageIEcommerceMallCustomer } from "../../../api/structures/IPageIEcommerceMallCustomer";
import { getEcommerceMallCustomersCustomerId } from "../../../providers/getEcommerceMallCustomersCustomerId";
import { patchEcommerceMallCustomers } from "../../../providers/patchEcommerceMallCustomers";

@Controller("/ecommerceMall/customers")
export class EcommercemallCustomersController {
  /**
   * Retrieve a filtered and paginated list of all customer accounts for administrative oversight.
   *
   * This operation provides administrators with comprehensive search capabilities to browse the complete customer base. It supports filtering by partial email matching, account status (active or banned), and registration date ranges. The response includes customer summary information optimized for list displays, showing essential identification and status information without exposing sensitive details.
   *
   * Results are paginated with configurable page sizes and support cursor-based navigation for efficient browsing of large customer databases. Sorting options include newest first, email alphabetical order, and account status grouping.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering customer accounts
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_mall_customers table with
     *   pagination and filtering support.
   *
   * Apply search filters:
   * - email: Partial string match (LIKE query with wildcards)
   * - accountStatus: Exact match filtering for 'active' or 'banned' status
   * - registrationDateRange: Date range filter on created_at field
   * - displayName: Partial match on related CustomerProfile.display_name
   *
   * Validate that the requesting actor has admin role before executing query.
   *
   * Use cursor-based pagination (limit/after) for efficient large dataset navigation.
   *
   * Join with ecommerce_mall_customer_profiles to include display name in results.
   * Exclude soft-deleted accounts from results unless explicitly requested.
   *
   * Return IPageIEcommerceMallCustomer.ISummary with:
   * - customer id and email
   * - profile display name
   * - account status
   * - registration timestamp
   * - total order count (aggregated from related orders)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @TypedBody()
    body: IEcommerceMallCustomer.IRequest,
  ): Promise<IPageIEcommerceMallCustomer.ISummary> {
    try {
      return await patchEcommerceMallCustomers({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific customer account.
   *
   * This operation returns the complete customer record identified by the provided customerId UUID. The response includes the customer's email address, account creation timestamp, and last update timestamp.
   *
   * For security reasons, sensitive fields such as password hash are not included in the response. The deleted_at field indicates whether the customer account has been soft-deleted.
   *
   * This endpoint is typically used by customers viewing their own account details or by administrators performing account oversight. Access control ensures customers can only view their own data unless they have administrative privileges.
   *
   * @param connection
   * @param customerId Unique identifier of the customer account (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor null
     * @x-autobe-specification Query the ecommerce_mall_customers table by
     *   primary key id matching the customerId path parameter.
   *
   * Return fields: id, email, created_at, updated_at, deleted_at.
   *
   * Security consideration: Exclude password_hash from the response to prevent credential exposure.
   *
   * Error handling:
   * - Return 404 Not Found if no customer exists with the given customerId
   * - Return 403 Forbidden if the requesting customer attempts to access another customer's data without admin privileges
   *
   * The deleted_at field being non-null indicates a soft-deleted account where orders and reviews are preserved per business requirements.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":customerId")
  public async at(
    @TypedParam("customerId")
    customerId: string,
  ): Promise<IEcommerceMallCustomer> {
    try {
      return await getEcommerceMallCustomersCustomerId({
        customerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
