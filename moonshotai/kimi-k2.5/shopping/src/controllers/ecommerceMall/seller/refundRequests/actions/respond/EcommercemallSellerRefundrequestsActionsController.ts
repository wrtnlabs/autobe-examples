import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallRefundRequest } from "../../../../../../api/structures/IEcommerceMallRefundRequest";
import { SellerAuth } from "../../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerRefundRequestsRefundRequestIdActionsRespond } from "../../../../../../providers/patchEcommerceMallSellerRefundRequestsRefundRequestIdActionsRespond";

@Controller(
  "/ecommerceMall/seller/refundRequests/:refundRequestId/actions/respond",
)
export class EcommercemallSellerRefundrequestsActionsController {
  /**
   * Seller response endpoint for refund request review.
   *
   * This operation allows the seller who sold the corresponding order item to respond to a customer's refund request by either approving or rejecting it. The response includes the seller's decision (approved or rejected) and an optional explanation for their decision.
   *
   * **Security Considerations**
   * Only the seller who originally sold the order item can respond to the refund request. Cross-seller responses are blocked and will result in an authorization error (per section 397 and 549).
   *
   * **Database Relationships**
   * The operation updates the ecommerce_mall_refund_requests table, changing the status from 'pending' to either 'approved' or 'rejected', and recording the responded_at timestamp. Upon successful response, the system automatically creates a snapshot in ecommerce_mall_refund_request_snapshots preserving the complete state at the time of response for audit purposes.
   *
   * **Business Rules**
   * - The order item must have status 'delivered' to allow refund responses
   * - The refund request must be in status 'pending' to be responded to
   * - The seller must be the owner of the order item being refunded
   * - If approved, the order item status changes to 'refunded' and stock is restored via inventory records
   *
   * **Related Operations**
   * - GET /shoppings/customers/orders/{orderId} - Used to view order details including refund request status
   * - PATCH /cancellations/{cancellationId}/actions/respond - Similar endpoint for cancellation requests
   *
   * @param connection
   * @param refundRequestId Target refund request ID to respond to
   * @param body Seller's response to the refund request including the decision status and optional response reason
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Implement this operation to allow sellers to respond to refund requests:
   *
   * 1. **Authorization Check**: Verify the authenticated user is the seller who owns the order item associated with this refund request. Query ecommerce_mall_refund_requests joined with ecommerce_mall_order_items to verify seller ownership. Reject with 403 Forbidden if unauthorized.
   *
   * 2. **Status Validation**: Check the refund request status is 'pending'. Reject with 409 Conflict if already approved or rejected.
   *
   * 3. **Order Item Status Check**: Verify the order item has status 'delivered' (refund requests are only valid for delivered items per section 549).
   *
   * 4. **Transaction Processing**:
   *    - Update ecommerce_mall_refund_requests: set status to approved or rejected based on request body, set responded_at to current timestamp
   *    - Create snapshot in ecommerce_mall_refund_request_snapshots with the complete state before and after response
   *
   * 5. **Approval Flow** (if status is 'approved'):
   *    - Update order item status in ecommerce_mall_order_items to 'refunded'
   *    - Create inventory record in ecommerce_mall_inventory_records with positive quantity to restore stock
   *    - Update product variant stock quantity
   *
   * 6. **Rejection Flow** (if status is 'rejected'):
   *    - Order item status remains 'delivered'
   *    - Refund request is marked rejected, customer may submit new request within 7-day window
   *
   * 7. **Snapshot Creation**:
   *    - Insert record into ecommerce_mall_refund_request_snapshots with: refund_request_id, reason (original), status (new status), response_reason (from request)
   *
   * Return the updated IEcommerceMallRefundRequest entity with all fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async respond(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string,
    @TypedBody()
    body: IEcommerceMallRefundRequest.IRespond,
  ): Promise<IEcommerceMallRefundRequest> {
    try {
      return await patchEcommerceMallSellerRefundRequestsRefundRequestIdActionsRespond(
        {
          seller,
          refundRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
