import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallCustomerSession } from "../../../../api/structures/IEcommerceMallCustomerSession";
import { IEcommerceMallSellerSession } from "../../../../api/structures/IEcommerceMallSellerSession";
import { IPageIEcommerceMallCustomerSession } from "../../../../api/structures/IPageIEcommerceMallCustomerSession";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerSessionsSessionId } from "../../../../providers/getEcommerceMallSellerSessionsSessionId";
import { patchEcommerceMallSellerSessions } from "../../../../providers/patchEcommerceMallSellerSessions";

@Controller("/ecommerceMall/seller/sessions")
export class EcommercemallSellerSessionsController {
  /**
   * Retrieve a filtered, paginated list of authentication sessions.
   *
   * This operation provides session audit trail access for security monitoring and compliance tracking. Sessions are append-only records that track authentication events with JWT tokens, connection metadata (IP address, page URL, referrer), and temporal boundaries.
   *
   * Different session types exist for each actor: guest sessions, customer sessions, seller sessions, administrator sessions, and super administrator sessions. Each session represents a logged-in user with an access token that expires for security purposes.
   *
   * When sessions become invalid or are terminated (logout, expiration, account deletion), the records are preserved for security analysis. This endpoint enables administrators to monitor active sessions, review historical login events, and audit authentication patterns.
   *
   * Results can be filtered by actor type, session status (active/expired), creation date range, and other criteria. Active sessions are those where expired_at is in the future.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering sessions
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query session records from all session tables
     *   (guest, customer, seller, admin, super_admin) with JOINs to respective
     *   user tables for identity information.
   *
   * Apply filters from request body: actorType to filter by user type, status (active/expired) to filter by expired_at comparison with current time, createdAt range for date filtering, and userId for specific user sessions.
   *
   * Support pagination with limit/offset or cursor-based pagination. Sort by created_at descending (newest first) by default.
   *
   * Include related user information (email, name) from parent tables for summary display. Exclude sensitive token values from response - only return metadata.
   *
   * Return paginated result with session summaries containing: session id, actor type, user identifier, IP address, connection context, creation time, expiration time, and status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallCustomerSession.IRequest,
  ): Promise<IPageIEcommerceMallCustomerSession.ISummary> {
    try {
      return await patchEcommerceMallSellerSessions({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a single seller session record by its unique identifier.
   *
   * This operation returns the complete details of a specific seller authentication session, including session metadata (IP address, origin URL, referrer), creation timestamp, and expiration time.
   *
   * Seller session records are append-only and serve as an audit trail for authentication events. They cannot be modified or deleted through this endpoint. The operation is used for session verification, security auditing, and debugging purposes.
   *
   * Access is restricted: sellers can retrieve their own sessions, while administrators and super administrators may retrieve any seller session for security oversight.
   *
   * @param connection
   * @param sessionId Unique identifier of the session to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the session table matching the sessionId
     *   parameter against the id column. Return the session record if found and
     *   the requester has authorization to view it.
   *
   * Authorization rules:
   * - Customers can retrieve their own customer sessions
   * - Sellers can retrieve their own seller sessions
   * - Administrators can retrieve admin sessions and may have broader access for security auditing
   * - Super administrators can retrieve any session type
   *
   * The session record includes: id, user identifier (varies by session type), connection metadata (ip, href, referrer), creation timestamp, and expiration timestamp.
   *
   * If the session ID does not exist, return 404 Not Found.
   * If the requester lacks authorization to view the session, return 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":sessionId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("sessionId")
    sessionId: string,
  ): Promise<IEcommerceMallSellerSession> {
    try {
      return await getEcommerceMallSellerSessionsSessionId({
        seller,
        sessionId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
