import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItem } from "../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerOrderItems } from "../../../../providers/patchEcommerceMallSellerOrderItems";

@Controller("/ecommerceMall/seller/order-items")
export class EcommercemallSellerOrder_itemsController {
  /**
   * Search and list order item records with pagination and filtering capabilities.
   *
   * This endpoint allows authorized users (sellers viewing their order items, customers viewing their purchased items, administrators viewing all) to retrieve a paginated list of order items. Order items represent individual purchased product variants within an order.
   *
   * Supports filtering by:
   * - Order status (Paid, Shipped, Delivered, Cancelled, Refunded)
   * - Order ID
   * - Product ID
   * - Seller ID
   * - Customer ID
   * - Date ranges
   *
   * The response includes summary information suitable for list displays, showing product names, quantities, prices, and current status. Pagination uses offset/limit pattern for flexible navigation through large result sets.
   *
   * Related operations:
   * - Individual order item retrieval: GET /order-items/{orderItemId}
   * - Order creation: POST /orders
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering order items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_order_items table with pagination and filtering support.
   *
   * **Implementation Steps:**
   * 1. Validate user permissions based on actor type:
   *    - Customers: filter by their own customerId only
   *    - Sellers: filter by their own sellerId only
   *    - Admins/SuperAdmins: can filter by any criteria
   *
   * 2. Apply filters from request body:
   *    - orderId: filter items belonging to specific order
   *    - productId: filter items for specific product
   *    - sellerId: filter items for specific seller (admin only)
   *    - status: filter by item status (PAID, SHIPPED, DELIVERED, CANCELLED, REFUNDED)
   *    - orderDateFrom/To: date range filtering
   *
   * 3. Join with related tables for display data:
   *    - ecommerce_mall_products: get product name
   *    - ecommerce_mall_product_variants: get variant info
   *    - ecommerce_mall_orders: get order date and customer info
   *
   * 4. Return paginated results with:
   *    - Total count for pagination
   *    - Order item summaries with product/variant names
   *    - Current status and timestamps
   *    - Price and quantity information
   *
   * **Edge Cases:**
   * - Empty result set when no items match filters
   * - Respect data isolation: customers cannot see other customers' order items
   * - Respect data isolation: sellers cannot see other sellers' order items
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerOrderItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
