import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerProfileSnapshot } from "../../../../../api/structures/IEcommerceMallSellerProfileSnapshot";
import { IPageIEcommerceMallSellerProfileSnapshot } from "../../../../../api/structures/IPageIEcommerceMallSellerProfileSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerProfileSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSellerProfileSnapshotsSnapshotId";
import { getEcommerceMallSellerProfileSnapshotsSnapshotIdCompareOtherSnapshotId } from "../../../../../providers/getEcommerceMallSellerProfileSnapshotsSnapshotIdCompareOtherSnapshotId";
import { patchEcommerceMallSellerProfileSnapshots } from "../../../../../providers/patchEcommerceMallSellerProfileSnapshots";

@Controller("/ecommerceMall/seller/profile/snapshots")
export class EcommercemallSellerProfileSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of seller profile snapshots.
   *
   * This operation provides access to immutable snapshots of seller profile states that are automatically created whenever a seller modifies their shop name, description, or logo. Each snapshot captures the complete state of the seller's profile at a specific point in time, including the shop name, description, logo image URL, and the timestamp when the snapshot was created. These snapshots serve as an audit trail for dispute resolution and preserve historical states even after profile edits or account deletions.
   *
   * Access control depends on the actor:
   * - Sellers can retrieve snapshots of their own profile only
   * - Administrators and super administrators can retrieve snapshots of any seller's profile
   * - The request body supports filtering by seller_id (primarily for admin use), pagination parameters, and sorting options
   *
   * Snapshots cannot be modified or deleted. They are automatically created by the system as part of the profile update workflow and are retained indefinitely for accountability and compliance purposes.
   *
   * @param connection
   * @param body Search criteria, pagination, and sorting parameters for retrieving seller profile snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_seller_profile_snapshots table with optional filtering by seller_id.
   *
   * For sellers: Automatically filter by the authenticated seller's ID.
   * For admins: Accept seller_id filter from request body to view any seller's snapshots.
   *
   * Support pagination with cursor or offset-based approach.
   * Support sorting by created_at (ascending/descending).
   *
   * Return snapshot summaries containing: id, shop_name, shop_description, logo_image_url, created_at.
   *
   * Validate that requesting seller can only access their own snapshots unless admin.
   * Query optimization: index on seller_id + created_at for efficient listing.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallSellerProfileSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallSellerProfileSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSellerProfileSnapshots({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller profile snapshot by its unique identifier.
   *
   * This operation returns a single immutable snapshot that captures the complete state of a seller's profile at a specific point in time. Each snapshot preserves the shop name, shop description, and logo image URL as they existed when the snapshot was created.
   *
   * Snapshots are created automatically whenever a seller edits their profile content. These snapshots serve as an audit trail for dispute resolution and historical reference. Even after subsequent profile edits or account deletion, snapshots remain preserved and accessible.
   *
   * Authorization Rules:
   * - Sellers can retrieve snapshots of their own profile only
   * - Administrators can retrieve snapshots of any seller's profile
   * - Customers cannot access profile snapshots
   *
   * The snapshot data is immutable and cannot be modified or deleted, ensuring a reliable historical record.
   *
   * @param connection
   * @param snapshotId Unique identifier of the seller profile snapshot to retrieve (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_profile_snapshots table by the provided snapshotId.
   *
   * Authorization Check:
   * 1. If the caller is a seller, verify that the snapshot's seller_id matches the authenticated seller's ID
   * 2. If the caller is an administrator or super administrator, allow access to any snapshot
   * 3. If the caller is a customer or lacks appropriate permissions, reject with 403 Forbidden
   *
   * Query Logic:
   * - Select from ecommerce_mall_seller_profile_snapshots where id = snapshotId
   * - Include the related seller information (seller_id, but not full seller details)
   *
   * Error Handling:
   * - If snapshotId does not exist, return 404 Not Found
   * - If user lacks permission to view the snapshot, return 403 Forbidden
   *
   * Return the complete snapshot record including: id, sellerId, shopName, shopDescription, logoImageUrl, and createdAt timestamp. The response preserves the exact state as it was captured when the snapshot was created.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallSellerProfileSnapshot> {
    try {
      return await getEcommerceMallSellerProfileSnapshotsSnapshotId({
        seller,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Compare two seller profile snapshots to analyze differences between profile states.
   *
   * This operation retrieves two seller profile snapshots by their IDs and returns them together for side-by-side comparison. Each snapshot captures the complete state of a seller's shop profile at a specific point in time, including the shop name, description, and logo image URL.
   *
   * Sellers can use this endpoint to view how their shop profile has evolved over time, comparing different versions to track changes in branding or representation. Administrators use this comparison capability during dispute resolution to verify what shop information was displayed to customers during specific transactions.
   *
   * The snapshots returned are immutable records preserved from the ecommerce_mall_seller_profile_snapshots table. The comparison includes both timestamps so users can understand the chronological relationship between the two states. This operation is read-only and does not create or modify any data.
   *
   * Both snapshots must exist and be accessible to the requesting user based on viewing permissions outlined in the snapshot access rules.
   *
   * @param connection
   * @param snapshotId ID of the reference snapshot to compare (the base version)
   * @param otherSnapshotId ID of the comparison snapshot to compare against (the other version)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_profile_snapshots table for both snapshot records by their primary key IDs.
   *
   * Validation steps:
   * 1. Verify both snapshotId and otherSnapshotId exist in the database
   * 2. Check user authorization: sellers can only access their own snapshots, administrators can access any
   * 3. Return both complete snapshot records with all fields
   *
   * Edge cases:
   * - If either snapshot ID does not exist, return 404 Not Found
   * - If user lacks authorization to view one or both snapshots, return 403 Forbidden
   * - Snapshots may be from different sellers - admin access required in such cases
   *
   * Join with ecommerce_mall_sellers table if additional seller context is needed for authorization checks. The seller_id field in each snapshot identifies the owner for permission verification.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId/compare/:otherSnapshotId")
  public async compare(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("snapshotId")
    snapshotId: string,
    @TypedParam("otherSnapshotId")
    otherSnapshotId: string,
  ): Promise<IEcommerceMallSellerProfileSnapshot.IComparison> {
    try {
      return await getEcommerceMallSellerProfileSnapshotsSnapshotIdCompareOtherSnapshotId(
        {
          seller,
          snapshotId,
          otherSnapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
