import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallOrderItem } from "../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerItemsItemId } from "../../../../providers/getEcommerceMallSellerItemsItemId";
import { patchEcommerceMallSellerItems } from "../../../../providers/patchEcommerceMallSellerItems";
import { patchEcommerceMallSellerItemsItemId } from "../../../../providers/patchEcommerceMallSellerItemsItemId";

@Controller("/ecommerceMall/seller/items")
export class EcommercemallSellerItemsController {
  /**
   * Retrieve a single order item by its unique identifier.
   *
   * This endpoint returns the complete details of a specific order item, which represents a purchased product variant within a customer's order. The order item includes information about the product, variant, quantity, price at time of purchase, and current fulfillment status.
   *
   * **Authorization**: Access is restricted based on the caller's role:
   * - Customers: Can only view order items belonging to their own orders
   * - Sellers: Can only view order items containing products they own
   * - Administrators: Can view any order item on the platform
   *
   * **Related Operations**: Use the index endpoint to list order items with filtering. Use shipment endpoints to track delivery status. Use cancellation or refund request endpoints to initiate returns.
   *
   * @param connection
   * @param itemId Unique identifier of the order item to retrieve (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the ecommerce_mall_order_items table by
     *   primary key (id).
   *
   * 1. Validate that the itemId parameter is a valid UUID format
   * 2. Retrieve the order item record from the database
   * 3. If not found, return 404 Not Found
   * 4. Verify authorization based on actor type:
   *    - For customers: Check that order_item.order.customer_id matches the authenticated customer
   *    - For sellers: Check that order_item.seller_id matches the authenticated seller
   *    - For admins/superAdmins: Allow access to any order item
   * 5. If unauthorized, return 403 Forbidden
   * 6. Join with related tables to provide complete information:
   *    - Product details from ecommerce_mall_products
   *    - Variant details from ecommerce_mall_product_variants
   *    - Seller information from ecommerce_mall_sellers
   *    - Order snapshot data preserved at purchase time
   * 7. Return the full order item entity
   *
   * Edge cases to handle:
   * - Soft-deleted order items should still be accessible to sellers and admins for historical records, but customers may receive a filtered view
   * - Include related shipment information if the item has been shipped
   * - Include cancellation/refund request status if applicable
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":itemId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("itemId")
    itemId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await getEcommerceMallSellerItemsItemId({
        seller,
        itemId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Partially update an order item's fields, primarily used for administrative status changes such as force-cancel or force-refund operations.
   *
   * This operation allows authorized users (typically administrators) to modify specific fields of an order item. The primary use case is for administrative overrides where items need to be cancelled or refunded outside the normal request workflow.
   *
   * When the status is changed to 'cancelled' or 'refunded', the system automatically restores stock quantities to the product variant through inventory records. Status changes trigger snapshot creation to preserve the state transition history.
   *
   * Updates are processed atomically with validation to ensure status transitions follow allowed paths (e.g., only 'paid' items can be cancelled, only 'delivered' items can be refunded). Concurrent modifications are handled through optimistic locking via the updated_at timestamp.
   *
   * @param connection
   * @param itemId Unique identifier of the order item to update (UUID format)
   * @param body Fields to update on the order item, including status for administrative actions
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate the order item exists and belongs to the
     *   requesting user/admin based on authorization rules.
   *
   * If status is being updated, validate the transition is valid:
   * - To 'cancelled': current status must be 'paid', decrement stock quantity for the variant
   * - To 'refunded': current status must be 'delivered', decrement stock quantity for the variant
   * - Other status transitions through this endpoint should be rejected (use dedicated shipment/cancellation workflows)
   *
   * If status changes to 'cancelled' or 'refunded', execute atomically:
   * 1. Update the order item status
   * 2. Create inventory record with positive quantity adjustment for stock restoration
   * 3. Update the order's derived status based on item states
   * 4. Create appropriate snapshot record for audit trail
   *
   * Return the full updated order item entity including related order and variant information for the client to refresh its state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch(":itemId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("itemId")
    itemId: string,
    @TypedBody()
    body: IEcommerceMallOrderItem.IUpdate,
  ): Promise<IEcommerceMallOrderItem> {
    try {
      return await patchEcommerceMallSellerItemsItemId({
        seller,
        itemId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of order items.
   *
   * This endpoint allows sellers and administrators to search and browse order items with advanced filtering capabilities. Sellers can view items for their products, filter by status (paid, shipped, delivered, cancelled, refunded), and manage their fulfillment workflow. Administrators can view all order items across the platform for oversight purposes.
   *
   * The endpoint supports filtering by: item status, date ranges (created_at), and seller association. Results are returned as paginated summaries optimized for list displays, showing essential information like product name, variant details, quantity, price, and current status.
   *
   * Response includes complete pagination metadata for navigation through large result sets.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering order items
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_order_items table with
     *   pagination and filtering support.
   *
   * Join with related tables to provide complete information:
   * - Join ecommerce_mall_products to get product names
   * - Join ecommerce_mall_product_variants to get variant details (SKU, options)
   * - Join ecommerce_mall_sellers to get seller information
   * - Join ecommerce_mall_orders to get order context
   *
   * Filtering capabilities:
   * - Filter by status (paid, shipped, delivered, cancelled, refunded)
   * - Filter by created_at date range
   * - For sellers: automatically scope to their seller_id
   * - For admins: can filter by specific seller_id
   *
   * Sorting options:
   * - Default: created_at DESC (newest first)
   * - Optional: status, price_at_purchase
   *
   * Pagination:
   * - Cursor-based pagination for efficient large dataset handling
   * - Configurable page size
   *
   * Authorization:
   * - Sellers: can only see items where seller_id matches their account
   * - Admins: can see all items, optionally filtered by seller
   *
   * Soft deleted items (deleted_at is not null) should be excluded from default results unless explicitly requested (admin only).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerItems({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
