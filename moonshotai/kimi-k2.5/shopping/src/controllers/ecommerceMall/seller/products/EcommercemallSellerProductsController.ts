import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProduct } from "../../../../api/structures/IEcommerceMallProduct";
import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteEcommerceMallSellerProductsProductId } from "../../../../providers/deleteEcommerceMallSellerProductsProductId";
import { postEcommerceMallSellerProducts } from "../../../../providers/postEcommerceMallSellerProducts";
import { putEcommerceMallSellerProductsProductId } from "../../../../providers/putEcommerceMallSellerProductsProductId";

@Controller("/ecommerceMall/seller/products")
export class EcommercemallSellerProductsController {
  /**
   * Create a new product listing on the platform.
   *
   * This endpoint allows sellers to register new products for customer purchase. A product requires a name, description, category selection, and base price. The product is exclusively associated with the authenticated seller who creates it.
   *
   * Only sellers with approved registration status can create products. Pending or rejected sellers are blocked from this operation until their registration is approved.
   *
   * Upon successful creation, the product enters an active state. The product becomes visible in search results and category listings once it has at least one variant added. Every product edit (including creation) creates a snapshot preserving the product state.
   *
   * @param connection
   * @param body Product creation data including name, description, category ID, and base price
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Validate that the authenticated user is a
     *   seller with approved registration status. If status is pending or
     *   rejected, return 403 Forbidden.
   *
   * 2. Validate request body fields:
   *    - name: required, non-empty string, max length per business rules
   *    - description: required, non-empty string
   *    - categoryId: required, valid UUID referencing existing category
   *    - basePrice: required, positive number
   *
   * 3. Verify the category exists in the database. If not found, return 404 Not Found.
   *
   * 4. Create the product record with:
   *    - Generated UUID as primary key
   *    - name, description, basePrice from request
   *    - categoryId referencing the selected category
   *    - sellerId set to the authenticated seller's ID
   *    - createdAt timestamp set to current time
   *
   * 5. Return the created product entity with all fields populated.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @SellerAuth()
    seller: SellerPayload,
    @TypedBody()
    body: IEcommerceMallProduct.ICreate,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await postEcommerceMallSellerProducts({
        seller,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Updates an existing product's details.
   *
   * This operation allows sellers to modify their product information including name, description, category assignment, and base price. Only the product owner (the seller who created it) can perform updates.
   *
   * Per the Snapshot Principle, every successful update automatically creates a product snapshot that preserves the previous state of the product and all its variants. This snapshot includes all product fields (name, description, category, base price, images) and variant states at that moment, enabling dispute resolution and audit trails.
   *
   * The operation validates seller ownership before allowing any modifications. Attempts to update a product owned by another seller will be rejected. Soft-deleted products cannot be updated until restored.
   *
   * Related operations: GET /products/{productId} to retrieve current state, POST /products to create new products.
   *
   * @param connection
   * @param productId The unique identifier of the product to update
   * @param body Product update fields
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Implement the following:
   *
   * 1. **Authentication & Authorization**: Verify the requesting user is an authenticated seller. Check that the product belongs to the requesting seller by comparing seller_id. Return 403 Forbidden if ownership mismatch.
   *
   * 2. **Existence Check**: Verify the product exists and is not soft-deleted (deleted_at is null). Return 404 Not Found if product doesn't exist or is deleted.
   *
   * 3. **Snapshot Creation**: Before applying updates, create a product snapshot record capturing the current state:
   *    - Copy all current product fields (name, description, category_id, base_price)
   *    - Create product snapshot image records for all current images
   *    - Create product variant snapshots for all variants of this product
   *    - Link the snapshot to the product for audit trail
   *
   * 4. **Field Updates**: Apply the provided fields from the request body:
   *    - name: Product display name (required in request)
   *    - description: Detailed product description (required in request)
   *    - categoryId: Category assignment (required, must reference existing category)
   *    - basePrice: Base price value (required, must be positive number)
   *
   * 5. **Validation**: Validate all fields per business rules:
   *    - Name and description must be non-empty strings
   *    - Category must exist and not be soft-deleted
   *    - Base price must be a positive number
   *
   * 6. **Update Execution**: Update the product record in ecommerce_mall_products table, set updated_at to current timestamp.
   *
   * 7. **Response**: Return the full updated product entity including all fields (id, sellerId, categoryId, name, description, basePrice, createdAt, updatedAt).
   *
   * Edge Cases:
   * - If seller registration is pending/rejected, block the operation (per Pre-Approval Operation Blocking rule)
   * - If category is changed, the product moves to the new category automatically
   * - Concurrent modifications: Use optimistic locking via updated_at timestamp to detect conflicts
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":productId")
  public async update(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallProduct.IUpdate,
  ): Promise<IEcommerceMallProduct> {
    try {
      return await putEcommerceMallSellerProductsProductId({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Soft-deletes a product and removes it from active listings.
   *
   * This operation allows sellers to delete their own products when they are no longer needed or available. The product is soft-deleted by setting the deleted_at timestamp, which removes it from search results and category listings while preserving the record for historical order reference and dispute resolution.
   *
   * Before deletion, the system validates that there are no pending order items with 'paid' or 'shipped' status for any variant of the product, and no pending cancellation or refund requests.
   *
   * Upon successful deletion:
   * - The product is soft-deleted and no longer appears in search results or category listings
   * - All product variants are cascade deleted
   * - All inventory records for those variants are removed
   * - All product images are removed from active listings
   * - Product snapshots are preserved for purchase history and dispute resolution
   *
   * The operation returns the deleted product details for client state management.
   *
   * @param connection
   * @param productId Unique identifier of the product to delete (global scope, UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification 1. Authorization: Verify the authenticated user
     *   is a seller who owns the product (seller_id matches authenticated
     *   seller).
   *
   * 2. Blocker Validation: Query order_items table joined with product_variants to check for any order items with status 'paid' OR 'shipped' belonging to any variant of the product. If any found, return 409 Conflict with error message indicating pending orders exist.
   *
   * 3. Service Request Validation: Query cancellation_requests and refund_requests tables joined with order_items and product_variants to check for any pending (unresponded) requests. If found, return 409 Conflict.
   *
   * 4. Soft Delete Execution: Set deleted_at timestamp to current time on ecommerce_mall_products record with productId. The schema defines onDelete: Cascade for related records, which will handle variants, images, and inventory records.
   *
   * 5. Return the deleted product entity including its soft-deleted state.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":productId")
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallSellerProductsProductId({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
