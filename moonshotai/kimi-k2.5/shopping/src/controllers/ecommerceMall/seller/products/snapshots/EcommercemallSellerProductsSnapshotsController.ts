import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallProductSnapshot } from "../../../../../api/structures/IEcommerceMallProductSnapshot";
import { IEcommerceMallProductSnapshotComparison } from "../../../../../api/structures/IEcommerceMallProductSnapshotComparison";
import { IPageIEcommerceMallProductSnapshot } from "../../../../../api/structures/IPageIEcommerceMallProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerProductsProductIdSnapshotsCompare } from "../../../../../providers/getEcommerceMallSellerProductsProductIdSnapshotsCompare";
import { getEcommerceMallSellerProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSellerProductsProductIdSnapshotsSnapshotId";
import { patchEcommerceMallSellerProductsProductIdSnapshots } from "../../../../../providers/patchEcommerceMallSellerProductsProductIdSnapshots";

@Controller("/ecommerceMall/seller/products/:productId/snapshots")
export class EcommercemallSellerProductsSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of product snapshots for a specific product.
   *
   * Snapshots are immutable point-in-time records that capture the complete state of a product whenever editable fields (name, description, category, base price, images) are modified. Each snapshot preserves the exact product configuration including all variant states at that moment.
   *
   * This operation supports date range filtering to find snapshots created within specific time periods, enabling historical analysis and dispute investigation. Results are sorted by creation time (newest first by default) and support cursor-based pagination for efficient browsing of large snapshot histories.
   *
   * Access control: Product owners (sellers) can view snapshots of their own products. Administrators can view snapshots of any product on the platform.
   *
   * @param connection
   * @param productId The unique identifier of the product (UUID format)
   * @param body Search criteria and pagination parameters for filtering product snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_snapshots table filtered by product_id.
   *
   * Support search criteria:
   * - createdAtFrom: Filter snapshots created on or after this timestamp
   * - createdAtTo: Filter snapshots created on or before this timestamp
   * - Pagination with cursor-based navigation (limit, cursor)
   *
   * Sorting: Default sort by created_at DESC (newest first). Support optional sort by created_at ASC.
   *
   * Join with ecommerce_mall_product_snapshot_images to include snapshot image URLs in response.
   * Join with ecommerce_mall_categories to include category name at snapshot time.
   *
   * Authorization check:
   * - Verify caller is the product owner (seller) OR caller has admin role
   * - Return 403 Forbidden if unauthorized
   *
   * Return paginated snapshot summaries containing: id, createdAt, name, basePrice, and associated image thumbnails.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedBody()
    body: IEcommerceMallProductSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallProductSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSellerProductsProductIdSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product snapshot by ID.
   *
   * This operation returns the complete state of a product at a specific point in time. The snapshot includes all product fields (name, description, category reference, base price), associated images with their display order, and snapshots of all product variants existing at that moment.
   *
   * Product snapshots are immutable records created automatically whenever a product is modified. They serve as historical evidence for audit trails and dispute resolution.
   *
   * Access control: Sellers can retrieve snapshots only for products they own. Administrators can retrieve snapshots for any product on the platform. Snapshots remain accessible even after product deletion.
   *
   * Related operations: List all snapshots for a product via the product snapshots index endpoint.
   *
   * @param connection
   * @param productId UUID of the product (global scope)
   * @param snapshotId UUID of the snapshot to retrieve (scoped to product)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_product_snapshots table by snapshot_id and product_id.
   *
   * Authorization checks:
   * 1. Verify the requesting user is authenticated as either a seller or administrator
   * 2. If seller: verify the product's seller_id matches the requesting seller's ID
   * 3. If administrator: allow access to any product snapshot
   *
   * Database query:
   * - Join with ecommerce_mall_product_snapshot_images to retrieve all associated images ordered by display_order
   * - Join with ecommerce_mall_product_variant_snapshots to retrieve all variant snapshots that existed at the time
   *
   * Return the complete snapshot object including:
   * - Snapshot metadata (id, product_id, created_at)
   * - Product fields at snapshot time (category_id, name, description, base_price)
   * - Nested array of snapshot images (url, display_order)
   * - Nested array of variant snapshots (sku_code, price, option values)
   *
   * Edge cases:
   * - Return 404 if snapshot doesn't exist or doesn't belong to the specified product
   * - Return 403 if seller attempts to access another seller's product snapshot
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallProductSnapshot> {
    try {
      return await getEcommerceMallSellerProductsProductIdSnapshotsSnapshotId({
        seller,
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Compare two snapshots of a product to identify differences between versions.
   *
   * This operation enables detailed comparison of product states at different points in time, showing exactly what fields were modified, added, or removed.
   *
   * The comparison includes:
   * - Product-level fields: name, description, category assignment, base price
   * - Product images: additions, removals, reordering
   * - Product variants: SKU code changes, option value modifications, price adjustments
   *
   * Access control:
   * - Sellers can compare snapshots of their own products
   * - Administrators can compare snapshots of any product on the platform
   *
   * The response highlights differences with before/after values for each changed field. This supports dispute resolution by providing clear evidence of what product information was displayed at specific times.
   *
   * @param connection
   * @param productId The unique identifier of the product whose snapshots are being compared (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Retrieve the two specified product snapshots from ecommerce_mall_product_snapshots table by productId and snapshotId parameters.
   *
   * If sourceSnapshotId is provided but targetSnapshotId is null, compare the source snapshot with the current product state from ecommerce_mall_products table.
   *
   * If both snapshot IDs are provided, load both snapshots from the snapshot table and compare them.
   *
   * Perform deep comparison on:
   * - Product fields: name, description, category_id, base_price
   * - Images: compare arrays for additions, deletions, order changes
   * - Variants: compare SKU codes, option_values, and prices
   *
   * Return a structured diff object showing field-level changes with old_value and new_value for each modification.
   *
   * Authorization check: Verify requester owns the product (seller) or has administrator privileges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get("compare")
  public async compare(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
  ): Promise<IEcommerceMallProductSnapshotComparison> {
    try {
      return await getEcommerceMallSellerProductsProductIdSnapshotsCompare({
        seller,
        productId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
