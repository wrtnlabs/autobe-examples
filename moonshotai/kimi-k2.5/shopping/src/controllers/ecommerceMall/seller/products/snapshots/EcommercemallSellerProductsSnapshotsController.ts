import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallProductSnapshot } from "../../../../../api/structures/IEcommerceMallProductSnapshot";
import { IPageIEcommerceMallProductSnapshot } from "../../../../../api/structures/IPageIEcommerceMallProductSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerProductsProductIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSellerProductsProductIdSnapshotsSnapshotId";
import { getEcommerceMallSellerProductsProductIdSnapshotsSnapshotIdCompareOtherSnapshotId } from "../../../../../providers/getEcommerceMallSellerProductsProductIdSnapshotsSnapshotIdCompareOtherSnapshotId";
import { patchEcommerceMallSellerProductsProductIdSnapshots } from "../../../../../providers/patchEcommerceMallSellerProductsProductIdSnapshots";

@Controller("/ecommerceMall/seller/products/:productId/snapshots")
export class EcommercemallSellerProductsSnapshotsController {
  /**
   * Retrieve a paginated list of product snapshots for a specific product.
   *
   * This endpoint provides access to the complete edit history of a product through its immutable snapshots. Each snapshot captures the state of the product at a specific point in time, including the product name, description, category assignment, base price, and associated images. Snapshots are created automatically whenever editable product fields are modified.
   *
   * Sellers can view snapshots of their own products for auditing and dispute resolution purposes. Administrators can view snapshots of any product on the platform, providing oversight and investigation capabilities. Snapshots preserve historical data even after a product is deleted from active listings.
   *
   * The endpoint supports pagination with configurable page sizes and supports filtering by date ranges to examine changes within specific time periods. Results are ordered by creation timestamp in descending order (newest first).
   *
   * Snapshots are append-only and cannot be modified or deleted after creation. Each snapshot includes complete state capture of the product and all its variants at that moment in time. Related images are stored as separate records linked to each snapshot.
   *
   * @param connection
   * @param productId The unique identifier of the product whose snapshots to retrieve
   * @param body Search criteria for filtering product snapshots by date range and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query ecommerce_mall_product_snapshots table filtered by product_id matching the path parameter. Apply additional filter criteria from request body: created_at date range filters (created_at_from, created_at_to). Join with ecommerce_mall_product_snapshot_images to include associated image records for each snapshot. Order by created_at DESC to show newest snapshots first. Implement cursor-based pagination for efficient handling of large snapshot histories. Return snapshot summary data including id, created_at, name, description, base_price, and nested image summaries. Authorization: verify requesting actor is either the product owner (seller) or has administrator privileges.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IEcommerceMallProductSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallProductSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSellerProductsProductIdSnapshots({
        seller,
        productId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific product snapshot by its ID. This endpoint returns the complete historical state of a product at a specific point in time, including the product name, description, category, base price, and all associated images as they existed when the snapshot was created.
   *
   * Access to snapshots is restricted based on user role. Sellers can only view snapshots of products they own, while administrators can view snapshots of any product for oversight and dispute resolution purposes. The system validates that the requesting user has appropriate permissions before returning the snapshot data.
   *
   * Snapshots are immutable records that capture the exact state of a product at a specific moment. They serve as historical records for audit trails, dispute resolution, and verifying product information. Snapshots are permanently retained and cannot be deleted by any user - they remain accessible even after the associated product is deleted from the platform.
   *
   * Related operations include listing all snapshots for a product and viewing product details. This operation is typically used when investigating historical product data or resolving disputes about product information.
   *
   * @param connection
   * @param productId Target product's ID that the snapshot belongs to
   * @param snapshotId Target snapshot's ID to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_product_snapshots table by the snapshotId parameter. Join with ecommerce_mall_product_snapshot_images to retrieve all images associated with the snapshot, ordered by display_order ascending. Validate that the requesting user is either the seller who owns the referenced product (check via product_id relation) or has administrator privileges. Return 404 if the snapshot is not found or does not belong to the specified product. Return the snapshot with all fields: id, product_id, category_id, name, description, base_price, created_at, and the nested images array.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallProductSnapshot> {
    try {
      return await getEcommerceMallSellerProductsProductIdSnapshotsSnapshotId({
        seller,
        productId,
        snapshotId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Compare two product snapshots to see what fields changed between two points in time.
   *
   * This endpoint allows authorized users to view the differences between two snapshots of the same product. The comparison highlights field-level changes including product name, description, base price, category assignment, and associated variant snapshots.
   *
   * Access is restricted to product owners (sellers) and administrators. Sellers can only compare snapshots of their own products, while administrators can compare snapshots of any product on the platform. This access control supports both business transparency for sellers and dispute resolution oversight for administrators.
   *
   * The response includes the before and after values for each changed field, along with timestamps and a summary of the differences. If the snapshots are identical in all fields, an empty diff is returned. The comparison is read-only and does not modify any snapshot data, preserving the immutability guarantee.
   *
   * Related operations:
   * - GET /products/{productId}/snapshots to list all snapshots for a product
   * - GET /products/{productId}/snapshots/{snapshotId} to view a single snapshot
   *
   * @param connection
   * @param productId ID of the parent product (UUID v4)
   * @param snapshotId ID of the base snapshot to compare from (UUID v4)
   * @param otherSnapshotId ID of the target snapshot to compare to (UUID v4)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Fetch both snapshots by the provided IDs, verifying:
   * 1. Both snapshots belong to the specified product_id
   * 2. The requesting user has authorization (is product owner seller or administrator)
   * 3. Both snapshots exist and are not deleted
   *
   * Compare the following fields from ecommerce_mall_product_snapshots:
   * - name (string comparison)
   * - description (string comparison)
   * - base_price (numeric comparison)
   * - category_id (UUID comparison)
   * - images (compare ordered list of image URLs via ecommerce_mall_product_snapshot_images)
   * - variants (compare variant snapshots via related tables: sku_code, option_values, price)
   *
   * Return a structured diff showing:
   * - Added fields (values present only in newer snapshot)
   * - Modified fields (values changed between snapshots)
   * - Unchanged fields (identical values)
   * - Nested comparisons for variants and images
   *
   * Authorization: Check if current user is the seller owner of the product, or is an administrator. If neither, return 403 Forbidden.
   *
   * Edge cases:
   * - If either snapshot_id doesn't exist for the product, return 404 Not Found
   * - If snapshots are identical, return empty diff with identical flag set
   * - Deleted products may still have accessible snapshots for historical viewing
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId/compare/:otherSnapshotId")
  public async compare(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("productId")
    productId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
    @TypedParam("otherSnapshotId")
    otherSnapshotId: string,
  ): Promise<IEcommerceMallProductSnapshot.IComparison> {
    try {
      return await getEcommerceMallSellerProductsProductIdSnapshotsSnapshotIdCompareOtherSnapshotId(
        {
          seller,
          productId,
          snapshotId,
          otherSnapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
