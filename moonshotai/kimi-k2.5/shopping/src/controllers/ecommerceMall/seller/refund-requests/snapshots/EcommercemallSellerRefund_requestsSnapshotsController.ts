import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallRefundRequestSnapshot } from "../../../../../api/structures/IEcommerceMallRefundRequestSnapshot";
import { IPageIEcommerceMallRefundRequestSnapshot } from "../../../../../api/structures/IPageIEcommerceMallRefundRequestSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerRefundRequestsRefundRequestIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSellerRefundRequestsRefundRequestIdSnapshotsSnapshotId";
import { patchEcommerceMallSellerRefundRequestsRefundRequestIdSnapshots } from "../../../../../providers/patchEcommerceMallSellerRefundRequestsRefundRequestIdSnapshots";

@Controller("/ecommerceMall/seller/refund-requests/:refundRequestId/snapshots")
export class EcommercemallSellerRefund_requestsSnapshotsController {
  /**
   * Retrieve a filtered and paginated list of refund request snapshots.
   *
   * Refund request snapshots are immutable point-in-time records automatically created whenever a seller responds to a refund request (approving or rejecting). Each snapshot captures the complete state of the request including the customer's original reason, seller's response status, and explanation provided at the moment of response.
   *
   * These snapshots serve as critical audit trail evidence for dispute resolution between customers and sellers. They are immutable and permanent - once created, snapshots cannot be modified or deleted under any circumstances. Snapshots remain accessible even if the refund request itself is resolved or archived.
   *
   * This operation supports filtering by creation date range to locate specific response events, and results are paginated with cursor-based navigation for efficient browsing of large snapshot histories.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the refund request (UUID format)
   * @param body Search criteria and pagination parameters for filtering refund request snapshots
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query ecommerce_mall_refund_request_snapshots
     *   table filtering by refund_request_id parameter.
   *
   * Apply filters for created_at date range to narrow down specific response events.
   * Sort results by created_at in descending order (newest snapshots first) to present the most recent response state.
   * Join with ecommerce_mall_refund_requests to verify request exists and return 404 if not found.
   * Verify actor has permission to view the refund request before returning snapshots (customer views their own, seller views items for their products, admin views all).
   * Implement cursor-based pagination using created_at + id composite for efficient navigation through snapshot history.
   * Return full snapshot records including reason, status, response_reason, and created_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string,
    @TypedBody()
    body: IEcommerceMallRefundRequestSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallRefundRequestSnapshot> {
    try {
      return await patchEcommerceMallSellerRefundRequestsRefundRequestIdSnapshots(
        {
          seller,
          refundRequestId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific refund request snapshot by its ID.
   *
   * Refund request snapshots are immutable records that capture the complete state of a refund request at the moment a seller responds. They preserve the customer's original reason for requesting a refund, the status after seller response (approved or rejected), the seller's response reason, and the exact timestamp of the response.
   *
   * Snapshots serve as permanent audit trail records for dispute resolution between customers and sellers. They cannot be modified or deleted by any actor, including super administrators. When a refund request is responded to, the system automatically creates a snapshot as part of the same transaction.
   *
   * This endpoint allows authorized parties (the seller who received the request, the customer who made the request, or administrators) to view historical snapshot data for verification and dispute resolution purposes.
   *
   * @param connection
   * @param refundRequestId Unique identifier of the parent refund request (scoped to refund request)
   * @param snapshotId Unique identifier of the snapshot to retrieve (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Validate that the refundRequestId path parameter
     *   is a valid UUID format. Validate that the snapshotId path parameter is
     *   a valid UUID format. Query the ecommerce_mall_refund_request_snapshots
     *   table by snapshotId. Verify that the retrieved snapshot belongs to the
     *   specified refundRequestId (return 404 if mismatch). Return the full
     *   snapshot record with all fields: id, refund_request_id, reason, status,
     *   response_reason, created_at. Authorization: Only the customer who made
     *   the refund request, the seller who received it, or administrators can
     *   view the snapshot.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("refundRequestId")
    refundRequestId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallRefundRequestSnapshot> {
    try {
      return await getEcommerceMallSellerRefundRequestsRefundRequestIdSnapshotsSnapshotId(
        {
          seller,
          refundRequestId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
