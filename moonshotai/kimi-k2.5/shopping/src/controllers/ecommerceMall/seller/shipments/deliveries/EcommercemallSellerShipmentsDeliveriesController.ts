import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallShipment } from "../../../../../api/structures/IEcommerceMallShipment";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerShipmentsShipmentIdDeliveries } from "../../../../../providers/patchEcommerceMallSellerShipmentsShipmentIdDeliveries";

@Controller("/ecommerceMall/seller/shipments/:shipmentId/deliveries")
export class EcommercemallSellerShipmentsDeliveriesController {
  /**
   * Confirm delivery of a shipment and update all contained order items to delivered status.
   *
   * This operation allows customers to mark a shipment as delivered, confirming receipt of all items within that shipment. All order items within the shipment are automatically updated to delivered status simultaneously, reflecting the physical reality that items shipped together arrive together.
   *
   * **Authorization**: Customer actor only. The customer must be the owner of the order containing this shipment.
   *
   * **Business Rules**:
   * - Only shipments with "In Transit" status can be confirmed as delivered
   * - All order items within the shipment are updated to delivered status together
   * - The delivery timestamp is recorded at the shipment level
   * - Once confirmed, items become eligible for refund requests within the 7-day return window (counting from delivery date)
   *
   * **Edge Cases**:
   * - If the customer confirms delivery manually, the automatic 14-day conversion is cancelled
   * - If the shipment is already delivered, the operation may return the existing delivered state
   *
   * @param connection
   * @param shipmentId Target shipment ID (scoped to customer orders)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Validate that the authenticated customer is the owner of the order associated with this shipment (via orderId in shipments table joined with orders table's customerId). Check that the shipment status is "In Transit" - reject if already delivered or in invalid state. Update the shipment status to "Delivered" and record the delivery timestamp. Use a database transaction to atomically update all order items within this shipment to status "Delivered". The shipment_items table links order items to shipments; find all orderItemId values associated with this shipmentId and update the corresponding order_items records. Return the updated shipment information including the new delivered status.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async confirmDelivery(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
  ): Promise<IEcommerceMallShipment.ISummary> {
    try {
      return await patchEcommerceMallSellerShipmentsShipmentIdDeliveries({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
