import { TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IEcommerceMallShipmentDelivery } from "../../../../../api/structures/IEcommerceMallShipmentDelivery";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerShipmentsShipmentIdDelivery } from "../../../../../providers/getEcommerceMallSellerShipmentsShipmentIdDelivery";

@Controller("/ecommerceMall/seller/shipments/:shipmentId/delivery")
export class EcommercemallSellerShipmentsDeliveryController {
  /**
   * Retrieve the delivery confirmation details for a specific shipment.
   *
   * This operation returns information about when and how a shipment was marked as delivered. Delivery can occur either through manual confirmation by the customer or automatic confirmation after the 14-day delivery window expires.
   *
   * The response includes the delivery timestamp, a flag indicating whether delivery was automatic, and the customer who confirmed (if manually confirmed). If the shipment has not yet been delivered, this endpoint returns null or a not-found response.
   *
   * Related operations: View shipments via shipment endpoints, confirm delivery via POST delivery confirmation endpoint.
   *
   * @param connection
   * @param shipmentId Unique identifier of the shipment to retrieve delivery information for
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor seller
     * @x-autobe-specification Query the ecommerce_mall_shipment_deliveries
     *   table using the provided shipmentId as the foreign key.
   *
   * Implementation steps:
   * 1. Validate shipmentId is a valid UUID
   * 2. Query shipment_deliveries where shipment_id equals the path parameter
   * 3. Join with shipments table to verify the shipment exists
   * 4. Join with customers table (optional) to include confirmor details when is_auto_delivered is false
   * 5. Return the delivery record with fields: id, delivered_at, is_auto_delivered, customer (if present)
   *
   * Edge cases:
   * - If shipment exists but no delivery record exists (not yet delivered), return 404 or appropriate empty response
   * - If shipment doesn't exist, return 404
   * - Soft-deleted shipments may still have delivery records for historical purposes
   *
   * Security: Verify the requesting customer is either the order owner (customer_id matches shipment's order.customer_id) or the shipment seller (seller_id matches shipment's seller_id). Administrators can view any shipment delivery.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string & tags.Format<"uuid">,
  ): Promise<IEcommerceMallShipmentDelivery> {
    try {
      return await getEcommerceMallSellerShipmentsShipmentIdDelivery({
        seller,
        shipmentId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
