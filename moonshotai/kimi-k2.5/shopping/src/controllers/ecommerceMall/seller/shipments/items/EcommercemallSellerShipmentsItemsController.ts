import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerShipmentsShipmentIdItems } from "../../../../../providers/patchEcommerceMallSellerShipmentsShipmentIdItems";

@Controller("/ecommerceMall/seller/shipments/:shipmentId/items")
export class EcommercemallSellerShipmentsItemsController {
  /**
   * Retrieve a paginated list of order items contained within a specific shipment.
   *
   * This operation allows sellers and authorized users to view which order items are grouped together in a single shipment package. Each order item in the response represents a purchased product variant with its quantity, price at time of purchase, and current fulfillment status.
   *
   * The shipment item relationship is established through the ecommerce_mall_shipment_items junction table, where each order item can belong to exactly one shipment. This query traverses that relationship to return all order items associated with the specified shipment ID.
   *
   * Order items within a shipment all belong to the same seller and share the same tracking information (carrier name and tracking number) recorded at the shipment level. The items may have different products and variants but are packaged and shipped together as one physical package.
   *
   * This endpoint supports pagination to handle shipments containing many items, and allows filtering by item status (e.g., shipped, delivered) to help sellers track fulfillment progress. The response includes the order item details as well as the associated shipment context.
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment to query items for
   * @param body Search criteria, filters, and pagination parameters for listing order items within the shipment
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query order items associated with a specific shipment by joining through the ecommerce_mall_shipment_items junction table.
   *
   * 1. Validate that the shipmentId path parameter exists
   * 2. Verify the requesting user has permission to view this shipment (seller who created it, customer who owns the order, or admin)
   * 3. Join ecommerce_mall_order_items with ecommerce_mall_shipment_items on order_item_id
   * 4. Filter by shipment_id matching the path parameter
   * 5. Support filtering by order item status (paid, shipped, delivered, cancelled, refunded)
   * 6. Support filtering by product name (partial match)
   * 7. Support sorting by created_at (asc/desc) and status
   * 8. Apply cursor-based pagination with configurable page size
   * 9. Return paginated order item summaries including: id, order_id, product_id, variant_id, seller_id, quantity, price_at_purchase, status, created_at
   * 10. Include the associated order, product, and variant information through nested relations
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
