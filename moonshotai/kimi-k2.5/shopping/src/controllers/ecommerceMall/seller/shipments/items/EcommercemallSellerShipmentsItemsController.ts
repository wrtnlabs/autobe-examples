import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallOrderItem } from "../../../../../api/structures/IEcommerceMallOrderItem";
import { IPageIEcommerceMallOrderItem } from "../../../../../api/structures/IPageIEcommerceMallOrderItem";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { patchEcommerceMallSellerShipmentsShipmentIdItems } from "../../../../../providers/patchEcommerceMallSellerShipmentsShipmentIdItems";

@Controller("/ecommerceMall/seller/shipments/:shipmentId/items")
export class EcommercemallSellerShipmentsItemsController {
  /**
   * Retrieve a paginated list of order items contained within a specific shipment.
   *
   * This operation allows customers and sellers to view which order items are grouped together in a shipment. Each order item represents a purchased product variant with its quantity, price at purchase, and current status. The items are linked to the shipment through the shipment_items junction table.
   *
   * @param connection
   * @param shipmentId The unique identifier of the shipment (UUID format)
   * @param body Pagination and filtering criteria for shipment items
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the shipment_items junction table joined with order_items to retrieve all items belonging to the specified shipment.
   *
   * Validate that the authenticated user has permission to view this shipment (customer who owns the order, or seller who created the shipment, or administrator).
   *
   * Join with order_items to get item details including product name, variant options, quantity, and status.
   * Support pagination with configurable page size (default 20, max 100).
   * Sort by created_at descending by default.
   *
   * Return paginated list of order item summaries with their associated shipment information.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("shipmentId")
    shipmentId: string,
    @TypedBody()
    body: IEcommerceMallOrderItem.IRequest,
  ): Promise<IPageIEcommerceMallOrderItem.ISummary> {
    try {
      return await patchEcommerceMallSellerShipmentsShipmentIdItems({
        seller,
        shipmentId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
