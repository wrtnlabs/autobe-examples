import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { SellerAuth } from "../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../decorators/payload/SellerPayload";
import { deleteEcommerceMallSellerAccount } from "../../../../providers/deleteEcommerceMallSellerAccount";

@Controller("/ecommerceMall/seller/account")
export class EcommercemallSellerAccountController {
  /**
   * Permanently delete the authenticated customer's account from the e-commerce platform.
   *
   * When a customer chooses to delete their account, the following data handling rules apply:
   *
   * **Profile Information Removal**
   * All customer profile information including display name and phone number is permanently deleted from the ecommerce_mall_customer_profiles table.
   *
   * **Order History Preservation**
   * All order records and order history associated with the customer account are retained for legal compliance and seller record purposes. Orders remain accessible to sellers and administrators. Order items preserve their relationship to the customer through snapshots while the customer identity is anonymized.
   *
   * **Review Handling**
   * All reviews submitted by the customer are preserved and remain visible on product pages. However, these reviews are attributed to "deleted user" rather than the customer's identity, maintaining product rating integrity while removing personal attribution.
   *
   * **Cart and Wishlist Cleanup**
   * All items in the customer's shopping cart (ecommerce_mall_cart_items) and wishlist (ecommerce_mall_wishlist_items) are permanently removed from the system.
   *
   * **Address Removal**
   * All shipping addresses associated with the customer's address book are permanently deleted as part of the account deletion workflow.
   *
   * **Authentication Invalidation**
   * The customer account is soft-deleted by setting the deleted_at timestamp in the ecommerce_mall_customers table. This invalidates authentication credentials and marks the account as deleted while preserving necessary transactional records.
   *
   * The deletion process is irreversible. Once completed, the customer cannot recover their account or personal data, though they may register a new account using the same email address if desired.
   *
   * @param connection
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Delete the authenticated customer's account using their session token for identification.
   *
   * 1. Identify the customer from the authentication context (customer_id from JWT/session)
   * 2. Load the customer record from ecommerce_mall_customers where deleted_at is null
   * 3. If customer not found or already deleted, return 404 error
   * 4. Execute the following operations in a database transaction:
   *    - Delete all records from ecommerce_mall_customer_profiles where customer_id matches
   *    - Delete all records from ecommerce_mall_wishlist_items where customer_id matches
   *    - Delete all records from ecommerce_mall_cart_items where customer_id matches
   *    - Delete all records from ecommerce_mall_addresses where customer_id matches (addresses table per requirements)
   *    - Update all reviews in ecommerce_mall_reviews where customer_id matches to attribute to "deleted user"
   *    - Update ecommerce_mall_customers set deleted_at = CURRENT_TIMESTAMP where id = customer_id
   * 5. Commit the transaction
   * 6. Invalidate any active customer sessions after successful deletion
   *
   * **Edge Cases:**
   * - If customer has pending orders in paid/shipped status, the deletion should still proceed (this is different from seller deletion which blocks on pending orders)
   * - Cart and wishlist deletions should cascade properly per foreign key constraints
   * - Review snapshots are preserved per the snapshot immutability rule (section 410)
   * - Soft delete preserves order records via the deleted_at column
   *
   * **Authorization:**
   * Only the authenticated customer themselves can delete their own account. Administrators cannot delete customer accounts through this endpoint.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @SellerAuth()
    seller: SellerPayload,
  ): Promise<void> {
    try {
      return await deleteEcommerceMallSellerAccount({
        seller,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
