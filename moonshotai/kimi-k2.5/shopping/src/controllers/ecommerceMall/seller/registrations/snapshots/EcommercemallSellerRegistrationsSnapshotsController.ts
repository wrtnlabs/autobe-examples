import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IEcommerceMallSellerRegistrationSnapshot } from "../../../../../api/structures/IEcommerceMallSellerRegistrationSnapshot";
import { IPageIEcommerceMallSellerRegistrationSnapshot } from "../../../../../api/structures/IPageIEcommerceMallSellerRegistrationSnapshot";
import { SellerAuth } from "../../../../../decorators/SellerAuth";
import { SellerPayload } from "../../../../../decorators/payload/SellerPayload";
import { getEcommerceMallSellerRegistrationsRegistrationIdSnapshotsSnapshotId } from "../../../../../providers/getEcommerceMallSellerRegistrationsRegistrationIdSnapshotsSnapshotId";
import { patchEcommerceMallSellerRegistrationsRegistrationIdSnapshots } from "../../../../../providers/patchEcommerceMallSellerRegistrationsRegistrationIdSnapshots";

@Controller("/ecommerceMall/seller/registrations/:registrationId/snapshots")
export class EcommercemallSellerRegistrationsSnapshotsController {
  /**
   * Retrieve a paginated list of seller registration snapshots for a specific registration.
   *
   * This operation provides administrators with a complete audit trail of all review events performed on a specific seller registration. Each snapshot represents a point-in-time record capturing when an administrator reviewed the registration and any state changes that occurred.
   *
   * Snapshots are immutable append-only records that serve as authoritative evidence for dispute resolution. They cannot be modified or deleted once created.
   *
   * Results are returned in chronological order (newest first) and can be filtered by administrator or time range.
   *
   * @param connection
   * @param registrationId The unique identifier of the seller registration whose snapshots are being retrieved
   * @param body Search criteria and pagination parameters for filtering registration snapshots
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification registrations.id`.
   *
   * Default sort order is `created_at DESC` (newest snapshots first).
   *
   * Pagination uses cursor-based pagination for efficient navigation through large audit trails.
   *
   * Access control: Only administrators and super administrators can access registration snapshots. The requesting administrator must have appropriate privileges to view the registration's audit trail.
   *
   * Error handling:
   * - Return 404 if registrationId does not exist
   * - Return 403 if requesting user lacks administrator privileges
   * - Return 400 for invalid pagination parameters
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("registrationId")
    registrationId: string,
    @TypedBody()
    body: IEcommerceMallSellerRegistrationSnapshot.IRequest,
  ): Promise<IPageIEcommerceMallSellerRegistrationSnapshot.ISummary> {
    try {
      return await patchEcommerceMallSellerRegistrationsRegistrationIdSnapshots(
        {
          seller,
          registrationId,
          body,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a specific seller registration snapshot.
   *
   * This operation returns the complete details of a single immutable snapshot in the seller registration audit history. Snapshots capture review events performed by administrators when processing seller registration applications, preserving who reviewed the registration and when for compliance and dispute resolution purposes.
   *
   * Snapshots are created automatically whenever an administrator reviews a registration (approving or rejecting the application). They serve as append-only historical records that cannot be modified or deleted.
   *
   * Access permissions:
   * - Administrators can view any registration snapshot on the platform
   * - Sellers can view snapshots of their own registration history only
   *
   * The response includes the snapshot identifier, parent registration reference, reviewing administrator details (when applicable), and the precise timestamp when the review event was recorded. This data supports audit trail requirements and enables sellers to track their registration processing timeline.
   *
   * @param connection
   * @param registrationId The UUID of the parent seller registration (global scope)
   * @param snapshotId The UUID of the specific snapshot to retrieve (scoped to the registration)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor seller
   * @x-autobe-specification Query the ecommerce_mall_seller_registration_snapshots table by snapshotId UUID.
   *
   * Join with ecommerce_mall_admins to retrieve reviewer details when ecommerce_mall_admin_id is present. Include the related ecommerce_mall_seller_registrations record to provide registration context.
   *
   * Validation rules:
   * 1. Verify snapshotId exists in the database
   * 2. Confirm snapshot belongs to the registrationId specified in path
   * 3. Return 404 Not Found if either validation fails
   *
   * Authorization checks:
   * - Admin users: Grant access to all snapshots
   * - Seller users: Verify current seller_id matches the registration's seller_id
   * - Return 403 Forbidden for unauthorized cross-seller access
   * - Return 401 Unauthorized for unauthenticated requests
   *
   * Return the snapshot entity with these fields:
   * - id: UUID primary key
   * - ecommerce_mall_seller_registration_id: Parent registration reference
   * - registration: Embedded IEcommerceMallSellerRegistration summary
   * - ecommerce_mall_admin_id: Reviewer administrator UUID (nullable)
   * - reviewer: Embedded IEcommerceMallAdmin reviewer details (nullable)
   * - created_at: Timestamp when snapshot was created
   *
   * The snapshot data is immutable per section 409-410 requirements; no modification or deletion endpoints exist.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":snapshotId")
  public async at(
    @SellerAuth()
    seller: SellerPayload,
    @TypedParam("registrationId")
    registrationId: string,
    @TypedParam("snapshotId")
    snapshotId: string,
  ): Promise<IEcommerceMallSellerRegistrationSnapshot> {
    try {
      return await getEcommerceMallSellerRegistrationsRegistrationIdSnapshotsSnapshotId(
        {
          seller,
          registrationId,
          snapshotId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
