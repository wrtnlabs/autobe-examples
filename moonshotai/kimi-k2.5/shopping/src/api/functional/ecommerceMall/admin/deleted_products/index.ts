/**
 * Retrieve a filtered and paginated list of deleted (soft-deleted) products for administrative oversight.
 *
 * This operation allows administrators to browse products that have been removed from active listings through soft deletion. Deleted products remain in the database with their deleted_at timestamp populated, preserving referential integrity with historical orders and snapshots.
 *
 * Administrators can filter by product name, seller, category, and deletion date range. This supports audit workflows, dispute resolution, and recovery planning. Deleted products retain all their original data and can be viewed in full detail via the product snapshot history.
 *
 * Products cascade to remove variants and inventory records upon deletion, but order history is preserved through order item snapshots.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for filtering deleted products
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_mall_products table where deleted_at IS NOT NULL.
 *
 * Join with ecommerce_mall_sellers to get seller shop name information.
 * Join with ecommerce_mall_categories to get category names.
 *
 * Support filters:
 * - name: partial text match using GIN index on name(ops: gin_trgm_ops)
 * - seller_id: exact match filter
 * - category_id: exact match filter
 * - deleted_at_from / deleted_at_to: date range filtering on deletion timestamp
 *
 * Support sorting:
 * - deleted_at: DESC (newest deletions first) or ASC
 * - created_at: DESC or ASC
 * - name: ASC or DESC
 *
 * Return paginated results with:
 * - Product ID, name, description, base_price
 * - Category ID and name
 * - Seller ID and shop name (from seller profile)
 * - created_at, updated_at, deleted_at timestamps
 * - Snapshot count for the product
 *
 * Use cursor-based or offset pagination with configurable page size (default 20, max 100).
 *
 * Authorization: Admin or SuperAdmin only. Regular sellers and customers cannot access this endpoint.
 * @path /ecommerceMall/admin/deleted-products
 * @accessor api.functional.ecommerceMall.admin.deleted_products.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for filtering deleted products
     */
    body: IEcommerceMallProduct.IDeletedRequest;
  };
  export type Body = IEcommerceMallProduct.IDeletedRequest;
  export type Response = IPageIEcommerceMallProduct.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/deleted-products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/deleted-products";
  export const random = (): IPageIEcommerceMallProduct.ISummary =>
    typia.random<IPageIEcommerceMallProduct.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
