/**
 * Retrieve a paginated list of order items contained within a specific shipment.
 *
 * This operation allows customers and sellers to view which order items are grouped together in a shipment. Each order item represents a purchased product variant with its quantity, price at purchase, and current status. The items are linked to the shipment through the shipment_items junction table.
 *
 * @param props.connection
 * @param props.shipmentId The unique identifier of the shipment (UUID format)
 * @param props.body Pagination and filtering criteria for shipment items
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query the shipment_items junction table joined with order_items to retrieve all items belonging to the specified shipment.
 *
 * Validate that the authenticated user has permission to view this shipment (customer who owns the order, or seller who created the shipment, or administrator).
 *
 * Join with order_items to get item details including product name, variant options, quantity, and status.
 * Support pagination with configurable page size (default 20, max 100).
 * Sort by created_at descending by default.
 *
 * Return paginated list of order item summaries with their associated shipment information.
 * @path /ecommerceMall/admin/shipments/:shipmentId/items
 * @accessor api.functional.ecommerceMall.admin.shipments.items.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * The unique identifier of the shipment (UUID format)
     */
    shipmentId: string;

    /**
     * Pagination and filtering criteria for shipment items
     */
    body: IEcommerceMallOrderItem.IRequest;
  };
  export type Body = IEcommerceMallOrderItem.IRequest;
  export type Response = IPageIEcommerceMallOrderItem.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/shipments/:shipmentId/items",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/admin/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/items`;
  export const random = (): IPageIEcommerceMallOrderItem.ISummary =>
    typia.random<IPageIEcommerceMallOrderItem.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
