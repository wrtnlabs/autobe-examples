/**
 * Retrieve a paginated list of snapshots for a specific review, showing the complete edit history.
 *
 * This operation returns all snapshots created for a review, ordered by creation time. Each snapshot captures the rating and text content of the review at the moment it was edited, creating an immutable audit trail.
 *
 * Snapshots are automatically created whenever a customer modifies their review. The snapshot preserves the previous state before the changes were applied, including the rating value and text content. This historical record is valuable for dispute resolution and maintaining transparency in customer feedback.
 *
 * Only the original review author and administrators can access the review's snapshot history. The response includes pagination controls for navigating through potentially many edits.
 *
 * @param props.connection
 * @param props.reviewId The unique identifier of the review whose snapshots are being retrieved
 * @param props.body Search criteria and pagination parameters for filtering and sorting review snapshots
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_mall_review_snapshots table filtering
 *   by the reviewId path parameter. Join with ecommerce_mall_reviews to verify
 *   the review exists and check access permissions. Sort results by created_at
 *   in descending order (newest snapshots first). Apply standard cursor-based
 *   pagination using the search criteria in the request body. Return snapshot
 *   fields: id, rating, content, created_at. Verify that the requesting
 *   customer is the review author before returning snapshots. Administrators
 *   can view snapshots of any review. Snapshots are immutable - only read
 *   operations are permitted.
 * @path /ecommerceMall/admin/reviews/:reviewId/snapshots
 * @accessor api.functional.ecommerceMall.admin.reviews.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * The unique identifier of the review whose snapshots are being retrieved
     */
    reviewId: string & tags.Format<"uuid">;

    /**
     * Search criteria and pagination parameters for filtering and sorting review snapshots
     */
    body: IEcommerceMallReviewSnapshot.IRequest;
  };
  export type Body = IEcommerceMallReviewSnapshot.IRequest;
  export type Response = IPageIEcommerceMallReviewSnapshot;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/reviews/:reviewId/snapshots",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/admin/reviews/${encodeURIComponent(props.reviewId ?? "null")}/snapshots`;
  export const random = (): IPageIEcommerceMallReviewSnapshot =>
    typia.random<IPageIEcommerceMallReviewSnapshot>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("reviewId")(() => typia.assert(props.reviewId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

