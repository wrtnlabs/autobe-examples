/**
 * Retrieve a filtered and paginated list of archived (soft-deleted) seller accounts.
 *
 * This operation allows administrators to view seller accounts that have been deleted by the sellers themselves. Archived sellers remain in the system to preserve order history and snapshots for legal and compliance purposes.
 *
 * Supports filtering by deletion date range, original approval status, and email address. Results are ordered by deletion date (newest first) by default. Only sellers with deleted_at timestamp set are included in the results.
 *
 * This is an admin-only operation requiring administrator authentication.
 *
 * @param props.connection
 * @param props.body Search criteria and pagination parameters for archived sellers
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Query ecommerce_mall_sellers table filtering for
 *   records where deleted_at IS NOT NULL.
 *
 * Apply filters from request:
 * - deletedAtFrom/deletedAtTo: Filter by deletion date range
 * - approvalStatus: Filter by original approval status (pending, approved, rejected, suspended)
 * - email: Partial email matching (LIKE %email%)
 * - createdAtFrom/createdAtTo: Filter by account creation date
 *
 * Join with ecommerce_mall_seller_registrations to get registration status context if needed.
 *
 * Return paginated results with cursor-based pagination. Include summary fields: id, email, approval_status, created_at, deleted_at.
 *
 * Sort by deleted_at DESC (newest deletions first) by default.
 * @path /ecommerceMall/admin/archived-sellers
 * @accessor api.functional.ecommerceMall.admin.archived_sellers.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * Search criteria and pagination parameters for archived sellers
     */
    body: IEcommerceMallSeller.IArchiveRequest;
  };
  export type Body = IEcommerceMallSeller.IArchiveRequest;
  export type Response = IPageIEcommerceMallSeller.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/admin/archived-sellers",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = () => "/ecommerceMall/admin/archived-sellers";
  export const random = (): IPageIEcommerceMallSeller.ISummary =>
    typia.random<IPageIEcommerceMallSeller.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(),
      contentType: "application/json",
    });
    try {
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
