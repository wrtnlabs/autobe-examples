    `/ecommerceMall/products/${encodeURIComponent(props.productId ?? "null")}/variants`;
  export const random = (): IPageIEcommerceMallProductVariant.ISummary =>
    typia.random<IPageIEcommerceMallProductVariant.ISummary>();
