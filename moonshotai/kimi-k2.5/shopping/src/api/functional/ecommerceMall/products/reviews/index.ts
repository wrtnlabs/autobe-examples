/**
 * Retrieve a paginated and filtered list of reviews for a specific product.
 *
 * This operation allows customers and administrators to browse all reviews submitted for a particular product. Reviews contain star ratings (1-5) and optional written feedback from customers who have purchased and received the product.
 *
 * The operation supports advanced filtering including rating range filters, date range filtering, customer-specific filtering, and text search on review content. Results are sorted by creation time with newest reviews displayed first.
 *
 * Deleted reviews are automatically excluded from the results. The review count and average rating calculation also exclude deleted reviews. Each review in the response includes the customer identifier (anonymized if customer account was deleted), rating value, content, and submission timestamp.
 *
 * This operation is available to all authenticated users including customers, sellers, and administrators. Authorization middleware ensures proper access control based on user roles.
 *
 * @param props.connection
 * @param props.productId UUID of the product to retrieve reviews for (global scope)
 * @param props.body Search filters and pagination parameters for product reviews
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor null
 * @x-autobe-specification Query ecommerce_mall_reviews table filtering by
 *   product_id matching the path parameter.
 *
 * Filtering capabilities:
 * - Filter by customer_id to see reviews from a specific customer
 * - Filter by rating range (minRating, maxRating) to find reviews within a star rating range
 * - Filter by date range (createdAfter, createdBefore) for time-based filtering
 * - Text search on content field using full-text search (gin_trgm_ops index)
 * - Exclude soft-deleted reviews (deleted_at IS NULL)
 *
 * Sorting: By created_at DESC (newest first) by default. Support optional sort field override.
 *
 * Pagination: Cursor-based or offset-based pagination with configurable page size.
 *
 * Join with ecommerce_mall_customers for customer display name (handle anonymization for deleted accounts where display name shows as 'deleted user').
 *
 * Join with ecommerce_mall_customer_profiles for customer profile information.
 *
 * Response includes review summary fields optimized for list display: id, rating, content excerpt (truncated if long), customer display name, created_at timestamp.
 *
 * Error handling: Return 404 if product_id does not exist in ecommerce_mall_products table.
 * @path /ecommerceMall/products/:productId/reviews
 * @accessor api.functional.ecommerceMall.products.reviews.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * UUID of the product to retrieve reviews for (global scope)
     */
    productId: string & tags.Format<"uuid">;

    /**
     * Search filters and pagination parameters for product reviews
     */
    body: IEcommerceMallReview.IRequest;
  };
  export type Body = IEcommerceMallReview.IRequest;
  export type Response = IPageIEcommerceMallReview.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/products/:productId/reviews",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/products/${encodeURIComponent(props.productId ?? "null")}/reviews`;
  export const random = (): IPageIEcommerceMallReview.ISummary =>
    typia.random<IPageIEcommerceMallReview.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
