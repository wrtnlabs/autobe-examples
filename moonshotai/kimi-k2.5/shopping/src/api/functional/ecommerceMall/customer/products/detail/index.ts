import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceMallProduct } from "../../../../../structures/IEcommerceMallProduct";

/**
 * Retrieve complete product details for a single product.
 *
 * This operation returns comprehensive product information including all images, category details, seller shop information, available variants with prices and stock status, and customer reviews. The first image in the sequence serves as the main thumbnail.
 *
 * Products without any variants are displayed but marked as unavailable for purchase. Out-of-stock variants are visually distinguished from available variants. The response includes the average customer rating and total review count calculated from all non-deleted reviews.
 *
 * If the product has been deleted (soft-deleted), it will not be returned. This endpoint is accessible to authenticated customers.
 *
 * @param props.connection
 * @param props.productId Product unique identifier (global scope)
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the ecommerce_mall_products table by id where deleted_at is null.
 *
 * Fetch the following related data:
 * 1. Product images from ecommerce_mall_product_images ordered by display_order ascending
 * 2. Category details from ecommerce_mall_categories (name, description)
 * 3. Seller information from ecommerce_mall_sellers joined with ecommerce_mall_seller_profiles (shop_name, logo_image_url, shop_description)
 * 4. All product variants from ecommerce_mall_product_variants where deleted_at is null
 * 5. For each variant, calculate current stock by summing quantities from ecommerce_mall_inventory_records
 * 6. All reviews from ecommerce_mall_reviews where deleted_at is null, ordered by created_at descending
 * 7. Calculate average rating and review count from non-deleted reviews
 *
 * Return a 404 error if the product does not exist or is deleted.
 * Return all data in a single response with nested relations.
 * @path /ecommerceMall/customer/products/:productId/detail
 * @accessor api.functional.ecommerceMall.customer.products.detail.at
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function at(
  connection: IConnection,
  props: at.Props,
): Promise<at.Response> {
  return true === connection.simulate
    ? at.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...at.METADATA,
          path: at.path(props),
          status: null,
        },
      );
}
export namespace at {
  export type Props = {
    /**
     * Product unique identifier (global scope)
     */
    productId: string;
  };
  export type Response = IEcommerceMallProduct;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/customer/products/:productId/detail",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/customer/products/${encodeURIComponent(props.productId ?? "null")}/detail`;
  export const random = (): IEcommerceMallProduct =>
    typia.random<IEcommerceMallProduct>();
  export const simulate = (
    connection: IConnection,
    props: at.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: at.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
