import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia from "typia";

import { IEcommerceMallCancellationRequestSnapshot } from "../../../../../structures/IEcommerceMallCancellationRequestSnapshot";
import { IPageIEcommerceMallCancellationRequestSnapshot } from "../../../../../structures/IPageIEcommerceMallCancellationRequestSnapshot";

/**
 * Retrieve paginated list of cancellation request snapshots for a specific cancellation request.
 *
 * This endpoint allows authorized parties - the customer who submitted the cancellation request, the seller who responded to it, or administrators - to view the immutable historical record of the request state.
 *
 * Snapshots are created automatically by the system when a seller responds to a cancellation request (either approving or rejecting). Each snapshot captures the state at the moment of response, including the original reason, decision, rejection reason (if applicable), timestamps, and status transitions. These snapshots serve as permanent audit trail records for dispute resolution.
 *
 * Snapshots are immutable and cannot be modified or deleted. They remain accessible even if the original cancellation request reaches a final state.
 *
 * @param props.connection
 * @param props.cancellationRequestId ID of the cancellation request to retrieve snapshots for
 * @param props.body Pagination and sorting parameters for snapshot list
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Query the ecommerce_mall_cancellation_request_snapshots table where cancellationRequestId matches the path parameter.
 *
 * Authorization verification:
 * 1. Verify the cancellation request exists via cancellation_request_id
 * 2. Join with order_items to get the order context
 * 3. Allow access if caller is:
 *    - The customer who owns the order containing this order item
 *    - The seller who owns the product in this order item
 *    - An administrator or super administrator
 *
 * Return 403 Forbidden if authorization fails.
 *
 * Return 404 Not Found if cancellation request doesn't exist.
 *
 * Apply pagination with configurable page size and sorting. Default sort by snapshot_timestamp ascending (earliest first).
 * @path /ecommerceMall/customer/cancellationRequests/:cancellationRequestId/snapshots
 * @accessor api.functional.ecommerceMall.customer.cancellationRequests.snapshots.index
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * ID of the cancellation request to retrieve snapshots for
     */
    cancellationRequestId: string;

    /**
     * Pagination and sorting parameters for snapshot list
     */
    body: IEcommerceMallCancellationRequestSnapshot.IRequest;
  };
  export type Body = IEcommerceMallCancellationRequestSnapshot.IRequest;
  export type Response =
    IPageIEcommerceMallCancellationRequestSnapshot.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/customer/cancellationRequests/:cancellationRequestId/snapshots",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/customer/cancellationRequests/${encodeURIComponent(props.cancellationRequestId ?? "null")}/snapshots`;
  export const random =
    (): IPageIEcommerceMallCancellationRequestSnapshot.ISummary =>
      typia.random<IPageIEcommerceMallCancellationRequestSnapshot.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("cancellationRequestId")(() =>
        typia.assert(props.cancellationRequestId),
      );
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
