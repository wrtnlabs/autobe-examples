export async function index(
  connection: IConnection,
  props: index.Props,
): Promise<index.Response> {
  return true === connection.simulate
    ? index.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...index.METADATA,
          path: index.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace index {
  export type Props = {
    /**
     * The unique identifier of the shipment to query items for
     */
    shipmentId: string;

    /**
     * Search criteria, filters, and pagination parameters for listing order items within the shipment
     */
    body: IEcommerceMallOrderItem.IRequest;
  };
  export type Body = IEcommerceMallOrderItem.IRequest;
  export type Response = IPageIEcommerceMallOrderItem.ISummary;

  export const METADATA = {
    method: "PATCH",
    path: "/ecommerceMall/seller/shipments/:shipmentId/items",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/ecommerceMall/seller/shipments/${encodeURIComponent(props.shipmentId ?? "null")}/items`;
  export const random = (): IPageIEcommerceMallOrderItem.ISummary =>
    typia.random<IPageIEcommerceMallOrderItem.ISummary>();
  export const simulate = (
    connection: IConnection,
    props: index.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: index.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("shipmentId")(() => typia.assert(props.shipmentId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
