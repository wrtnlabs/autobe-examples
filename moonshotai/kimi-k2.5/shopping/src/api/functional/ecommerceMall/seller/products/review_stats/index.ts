import {
  HttpError,
  IConnection,
  NestiaSimulator,
  PlainFetcher,
} from "@nestia/fetcher";
import typia, { tags } from "typia";

import { IEcommerceMallProductReviewStat } from "../../../../../structures/IEcommerceMallProductReviewStat";

/**
 * Retrieve review statistics for a specific product, including average rating, total review count, and rating distribution breakdown.
 *
 * This endpoint provides aggregated review data suitable for product listing pages and statistics displays. The average rating is calculated from all non-deleted reviews for the product, expressed as a numeric value from 1.0 to 5.0 with one decimal precision.
 *
 * The key statistics returned include:
 * - Average rating: The arithmetic mean of all non-deleted review ratings
 * - Total review count: The number of reviews (non-deleted) contributing to the average
 * - Rating distribution: A breakdown showing how many reviews fall into each star rating (1-5 stars)
 *
 * This data is used to display star ratings, review counts, and distribution charts on product detail pages. Snapshots of deleted reviews are excluded from the calculation as they are preserved for audit purposes but not considered in the average rating.
 *
 * Related operations:
 * - GET /products/{productId}/reviews - Retrieve the actual review content and details
 * - GET /products/{productId} - Product detail which may include basic rating summary
 *
 * @param props.connection
 * @param props.productId The unique identifier of the product to get review statistics for
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor seller
 * @x-autobe-specification Query the ecommerce_mall_reviews table filtered by
 *   product_id and where deleted_at is null. Calculate the average rating and
 *   count. Also query the distribution of ratings grouped by rating value
 *   (1-5).
 *
 * Return an object containing:
 * - averageRating: float rounded to 1 decimal place (calculated from non-deleted reviews)
 * - totalCount: integer count of non-deleted reviews for this product
 * - distribution: object with keys '1', '2', '3', '4', '5' representing count of reviews for each star rating
 *
 * The endpoint is read-only and must support efficient caching since product statistics are frequently accessed. Consider implementing materialized view or caching strategy for common products. If the product has no reviews, return averageRating of 0 and totalCount of 0 with all distribution counts at 0.
 * @path /ecommerceMall/seller/products/:productId/review-stats
 * @accessor api.functional.ecommerceMall.seller.products.review_stats.reviewStats
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function reviewStats(
  connection: IConnection,
  props: reviewStats.Props,
): Promise<reviewStats.Response> {
  return true === connection.simulate
    ? reviewStats.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...reviewStats.METADATA,
          path: reviewStats.path(props),
          status: null,
        },
      );
}
export namespace reviewStats {
  export type Props = {
    /**
     * The unique identifier of the product to get review statistics for
     */
    productId: string & tags.Format<"uuid">;
  };
  export type Response = IEcommerceMallProductReviewStat;

  export const METADATA = {
    method: "GET",
    path: "/ecommerceMall/seller/products/:productId/review-stats",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Props) =>
    `/ecommerceMall/seller/products/${encodeURIComponent(props.productId ?? "null")}/review-stats`;
  export const random = (): IEcommerceMallProductReviewStat =>
    typia.random<IEcommerceMallProductReviewStat>();
  export const simulate = (
    connection: IConnection,
    props: reviewStats.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: reviewStats.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("productId")(() => typia.assert(props.productId));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}
