/**
 * Creates a new administrator account with email and password credentials, assigning regular administrator privileges by default.
 *
 * This endpoint allows platform setup of initial administrators or creation by existing administrators. The email must be unique across all administrator accounts. Upon successful registration, the administrator receives JWT tokens for immediate authentication.
 *
 * The registration process validates email format, enforces password complexity requirements (minimum 8 characters with mixed case, numbers, and symbols), and creates an active account with 'regular' grade. Super administrator privileges require separate promotion workflow via admin promotion requests.
 *
 * Related tables:
 * - ecommerce_mall_admins: Stores credential and identity information
 * - ecommerce_mall_admin_sessions: Records the initial login session with connection metadata
 *
 * Security considerations:
 * - Passwords are hashed using BCrypt before storage
 * - Token expiration is enforced for both access and refresh tokens
 * - Email uniqueness is strictly enforced at database level with @@unique constraint
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Administrator registration credentials with email and password
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor admin
 * @x-autobe-specification Implement administrator registration by validating the request body contains both email and password conforming to platform standards. Check email uniqueness against ecommerce_mall_admins.email field using case-insensitive comparison. Hash the password using BCrypt with a work factor of 10-12 and store in password_hash field. Set grade to 'regular' for initial administrator creation (super admin promotion requires separate approval workflow). Set status to 'active' by default. Create initial session record in ecommerce_mall_admin_sessions capturing IP address, href, and referrer from request metadata. Generate JWT access token and refresh token with appropriate expiration times. Return IEcommerceMallAdmin.IAuthorized containing the tokens and administrator profile information including the assigned grade and status.
 * @path /ecommerceMall/auth/admin/join
 * @accessor api.functional.ecommerceMall.auth.admin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
