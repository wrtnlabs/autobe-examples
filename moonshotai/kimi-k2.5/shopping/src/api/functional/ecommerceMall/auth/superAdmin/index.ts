/**
 * Register a new super administrator account.
 *
 * Creates a new super administrator account with email-based authentication. The super administrator represents the highest privilege level in the platform hierarchy with abilities to approve admin promotion requests, promote/demote administrators, and manage the admin hierarchy.
 *
 * Email must be unique across all super admin accounts. Password is securely hashed before storage. Upon successful registration, a JWT session is established with both access and refresh tokens returned. The session metadata including IP address and request context is recorded for audit purposes.
 *
 * This operation is available publicly for initial super admin creation and requires no authentication.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Super administrator registration credentials containing email and password for new account creation.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor superAdmin
 * @x-autobe-specification Super administrator registration operation. Creates a
 *   new super admin account with email and password. Implementation steps: 1)
 *   Validate request body contains email and password meeting business rules
 *   (email format, password complexity). 2) Check email uniqueness against
 *   ecommerce_mall_super_admins table - reject if exists. 3) Hash password
 *   using secure algorithm (bcrypt/Argon2). 4) Generate UUID for new record. 5)
 *   Insert into ecommerce_mall_super_admins with grade='super_admin',
 *   created_at/updated_at current timestamp. 6) Generate JWT access and refresh
 *   tokens. 7) Create session record in ecommerce_mall_super_admin_sessions
 *   with token metadata (IP, href, referrer from request context, created_at,
 *   expired_at). 8) Return IEcommerceMallSuperAdmin.IAuthorized containing
 *   tokens and super admin identity.
 * @path /ecommerceMall/auth/superAdmin/join
 * @accessor api.functional.ecommerceMall.auth.superAdmin.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
