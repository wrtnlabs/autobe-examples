/**
 * Creates a new guest session for unauthenticated visitors.
 *
 * This endpoint allows unauthenticated visitors to obtain a temporary JWT session before accessing registration or login endpoints. The platform requires authentication for all features, so guests must first establish a session token to proceed with account creation.
 *
 * The operation generates fresh access and refresh tokens, stores the session record in the database with expiration timestamps, and returns the tokens to the client. The returned access token should be included in the Authorization header for subsequent API calls.
 *
 * This is typically the first API call made by a visitor to the platform. Once a guest has tokens, they can use them to access the customer or seller registration endpoints.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Optional metadata for the guest session creation. No credentials are required for guest sessions.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Implementation: Generate a new JWT access token and
 *   refresh token pair for an unauthenticated visitor. Create a guest session
 *   record in the database with the refresh token hash, expiration timestamps,
 *   and client metadata. Return both tokens in the response. No input
 *   credentials required since this creates a temporary anonymous session. The
 *   access token should have a short expiration (e.g., 15 minutes) and the
 *   refresh token longer (e.g., 7 days) to allow session persistence.
 * @path /ecommerceMall/auth/guest/join
 * @accessor api.functional.ecommerceMall.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
