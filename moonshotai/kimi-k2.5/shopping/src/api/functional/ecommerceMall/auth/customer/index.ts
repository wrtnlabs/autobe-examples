/**
 * Register a new customer account with email and password.
 *
 * Creates a new customer record in the ecommerce_mall_customers table with the provided email address and hashed password. Validates that the email address is unique across all customer accounts. Upon successful registration, establishes a new authenticated session and returns JWT access and refresh tokens.
 *
 * The session is recorded in ecommerce_mall_customer_sessions with connection context including IP address, referring page, and timestamps for security auditing. Customers can immediately use their credentials to access protected endpoints after registration.
 *
 * This endpoint establishes the customer's identity in the system and issues authentication credentials for subsequent API access.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Customer registration credentials containing email address and password for the new account.
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor customer
 * @x-autobe-specification Implementation notes: Validate email uniqueness
 *   against ecommerce_mall_customers table. Hash password using bcrypt/argon2.
 *   Create customer record with email and password_hash. Generate JWT access
 *   and refresh tokens. Create session record in
 *   ecommerce_mall_customer_sessions with ip, href, referrer, and expiration
 *   timestamp. Return tokens in IEcommerceMallCustomer.IAuthorized response.
 * @path /ecommerceMall/auth/customer/join
 * @accessor api.functional.ecommerceMall.auth.customer.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
