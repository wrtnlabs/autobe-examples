export async function test_api_customer_wishlist_item_removal_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // Step 2: Create product category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(category);
  // Step 3: Create seller and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(sellerAuth);
  // Step 4: Create product in the category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"float"> & tags.Minimum<1>
        >(),
      },
    },
  );
  typia.assert(product);
  // Step 5: Create customer and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(customerAuth);
  // Step 6: Add product to customer's wishlist
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_items_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
        },
      },
    );
  typia.assert(wishlistItem);
  // Verify the wishlist item was created successfully
  TestValidator.predicate(
    "wishlist item created with correct product",
    wishlistItem.productId === product.id,
  );
  TestValidator.predicate(
    "wishlist item belongs to authenticated customer",
    wishlistItem.customerId === customerAuth.id,
  );
  // Step 7: Delete the wishlist item (should succeed with 204 No Content)
  const deleteResult =
    await api.functional.ecommerceMall.customer.wishlist_items.erase(
      customerConnection,
      {
        wishlistItemId: wishlistItem.id,
      },
    );
  typia.assert(deleteResult); // Should be void/undefined for 204 No Content
  // Step 8: Verify the item is permanently removed by trying to delete again (should get 404)
  await TestValidator.error(
    "deleted wishlist item should return 404",
    async () => {
      await api.functional.ecommerceMall.customer.wishlist_items.erase(
        customerConnection,
        {
          wishlistItemId: wishlistItem.id,
        },
      );
    },
  );
}
