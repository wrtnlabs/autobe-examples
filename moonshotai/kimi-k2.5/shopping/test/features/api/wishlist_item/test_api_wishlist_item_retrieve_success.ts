export async function test_api_wishlist_item_retrieve_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Customer setup and wishlist creation
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: undefined,
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // Add product to wishlist
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_items_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // 4. Retrieve wishlist item
  const retrievedWishlistItem =
    await api.functional.ecommerceMall.customer.wishlist_items.at(
      customerConnection,
      { wishlistItemId: wishlistItem.id },
    );
  typia.assert(retrievedWishlistItem);
  // 5. Validate retrieved data
  TestValidator.equals(
    "wishlist item ID matches",
    retrievedWishlistItem.id,
    wishlistItem.id,
  );
  TestValidator.equals(
    "customer ID matches",
    retrievedWishlistItem.customerId,
    customerAuth.id,
  );
  TestValidator.equals(
    "product ID matches",
    retrievedWishlistItem.productId,
    product.id,
  );
  TestValidator.equals(
    "product name matches",
    retrievedWishlistItem.product.name,
    product.name,
  );
  TestValidator.equals(
    "product description matches",
    retrievedWishlistItem.product.description,
    product.description,
  );
  TestValidator.equals(
    "product base price matches",
    retrievedWishlistItem.product.basePrice,
    product.base_price,
  );
  TestValidator.equals(
    "product category ID matches",
    retrievedWishlistItem.product.category.id,
    category.id,
  );
}