export async function test_api_product_image_retrieval_by_customer(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin user and category (required for product creation)
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
      },
    },
  );
  typia.assert(category);
  // Step 2: Create seller user and product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
        categoryId: category.id,
        basePrice: typia.random<number>(),
      },
    },
  );
  typia.assert(product);
  // Step 3: Upload image to product
  const image =
    await generate_random_ecommerce_mall_seller_products_images_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          imageUrl: typia.random<string & tags.Format<"uri">>(),
        },
      },
    );
  typia.assert(image);
  // Step 4: Retrieve image as customer (public endpoint, no auth required)
  const retrievedImage = await api.functional.ecommerceMall.products.images.at(
    connection,
    {
      productId: product.id,
      imageId: image.id,
    },
  );
  typia.assert(retrievedImage);
  // Step 5: Validate response structure and values
  TestValidator.equals("image id matches", retrievedImage.id, image.id);
  TestValidator.equals(
    "imageUrl matches",
    retrievedImage.imageUrl,
    image.imageUrl,
  );
  TestValidator.equals(
    "displayOrder is 0 for first image",
    retrievedImage.displayOrder,
    0,
  );
  TestValidator.equals(
    "product reference is populated",
    retrievedImage.product.id,
    product.id,
  );
  TestValidator.equals(
    "product name in reference matches",
    retrievedImage.product.name,
    product.name,
  );
}
