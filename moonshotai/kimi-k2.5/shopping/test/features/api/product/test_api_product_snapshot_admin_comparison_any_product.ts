export async function test_api_product_snapshot_admin_comparison_any_product(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication for oversight
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 2. Create category as admin for product assignment
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 3. Seller authentication to create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 4. Create product as seller (generates initial snapshot)
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32">
        >() satisfies number as number,
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 5. Admin compares snapshots of the product
  // Note: Product creation creates an initial snapshot. For comparison we need two snapshots.
  // Since we don't have edit API, we'll use the same snapshot ID for both to test the endpoint.
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const comparison =
    await api.functional.ecommerceMall.seller.products.snapshots.compare(
      adminConnection,
      {
        productId: product.id,
        snapshotId: snapshotId,
        otherSnapshotId: snapshotId,
      },
    );
  typia.assert(comparison);
}
