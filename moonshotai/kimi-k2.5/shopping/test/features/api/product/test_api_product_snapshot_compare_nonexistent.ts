export async function test_api_product_snapshot_compare_nonexistent(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Primary seller setup and create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await api.functional.ecommerceMall.auth.seller.join(
    sellerConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: typia.random<string & tags.Format<"password">>(),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: null,
      } satisfies IEcommerceMallSeller.IJoin,
    },
  );
  typia.assert(sellerAuthorized);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<100>
        >(),
      },
    },
  );
  typia.assert(product);
  // 3. Test: Different seller (non-owner) attempting comparison - should get permission error
  const otherSellerConnection: api.IConnection = { host: connection.host };
  await api.functional.ecommerceMall.auth.seller.join(otherSellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  await TestValidator.error(
    "non-owner seller should get permission error when trying to compare snapshots",
    async () => {
      await api.functional.ecommerceMall.seller.products.snapshots.compare(
        otherSellerConnection,
        {
          productId: product.id,
        },
      );
    },
  );
  // 4. Test: Non-existent product ID - should get not found error
  const nonExistentProductId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "should throw error for non-existent product",
    async () => {
      await api.functional.ecommerceMall.seller.products.snapshots.compare(
        sellerConnection,
        {
          productId: nonExistentProductId,
        },
      );
    },
  );
}
