export async function test_api_product_inactive_visibility(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category for product
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product with no variants (inactive)
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    },
  });
  typia.assert(sellerAuth);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: typia.random<string>(),
        description: typia.random<string>(),
        categoryId: category.id,
        basePrice: typia.random<number & tags.Type<"double">>(),
      },
    },
  );
  typia.assert(product);
  // 3. Customer setup
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    },
  });
  // 4. Test: Customer cannot retrieve inactive product (404)
  await TestValidator.httpError(
    "customer cannot access inactive product",
    404,
    async () => {
      await api.functional.ecommerceMall.products.at(customerConnection, {
        productId: product.id,
      });
    },
  );
  // 5. Test: Admin can retrieve inactive product
  const retrievedProduct = await api.functional.ecommerceMall.products.at(
    adminConnection,
    {
      productId: product.id,
    },
  );
  typia.assert(retrievedProduct);
  // 6. Validate product data
  TestValidator.equals("product ID matches", retrievedProduct.id, product.id);
  TestValidator.equals(
    "product name matches",
    retrievedProduct.name,
    product.name,
  );
  TestValidator.equals(
    "product has no variants",
    retrievedProduct.variants.length,
    0,
  );
}
