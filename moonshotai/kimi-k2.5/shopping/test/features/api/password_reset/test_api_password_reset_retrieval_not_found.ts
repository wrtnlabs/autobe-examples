export async function test_api_password_reset_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Generate a random UUID that does not exist as a password reset record
  const nonExistentResetId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve the non-existent password reset and verify 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent password reset ID",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.password_resets.at(
        adminConnection,
        {
          resetId: nonExistentResetId,
        },
      );
    },
  );
}
