export async function test_api_cancellation_request_admin_retrieve_pending_for_review(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Setup seller with authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // Step 2: Create product and variant (seller needs to own a product for orders)
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          options: [
            { optionName: "Color", optionValue: "Red" },
            { optionName: "Size", optionValue: "Large" },
          ] satisfies IEcommerceMallProductVariantOption.ICreate[],
        },
      },
    );
  typia.assert(variant);
  // Step 3: Setup customer with authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  await authorize_customer_join(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // Step 4: Create cancellation request as customer
  // Note: In a complete scenario, this would require:
  // customer creates order → order is paid → then cancellation request
  // Due to available API limitations, we test with the cancellation request generation utility
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {},
    );
  typia.assert(cancellationRequest);
  // Step 5: Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  const adminEmail = typia.random<string & tags.Format<"email">>();
  const adminPassword = RandomGenerator.alphaNumeric(16);
  await authorize_admin_join(adminConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Step 6: Admin retrieves the cancellation request by ID
  const retrievedRequest =
    await api.functional.ecommerceMall.admin.cancellation_requests.at(
      adminConnection,
      {
        cancellationRequestId: cancellationRequest.id,
      },
    );
  typia.assert(retrievedRequest);
  // Step 7: Validate response content
  TestValidator.equals(
    "cancellation request ID matches",
    retrievedRequest.id,
    cancellationRequest.id,
  );
  TestValidator.predicate(
    "reason exists",
    () => typeof retrievedRequest.reason === "string",
  );
  TestValidator.predicate(
    "status exists",
    () => typeof retrievedRequest.status === "string",
  );
  TestValidator.predicate(
    "customer info populated",
    () =>
      retrievedRequest.customer !== undefined &&
      retrievedRequest.customer !== null,
  );
  TestValidator.predicate(
    "order item exists",
    () =>
      retrievedRequest.orderItem !== undefined &&
      retrievedRequest.orderItem !== null,
  );
  TestValidator.predicate("snapshots array exists", () =>
    Array.isArray(retrievedRequest.snapshots),
  );
}
