export async function test_api_cancellation_request_erase_rejected_after_seller_response(
  connection: api.IConnection,
): Promise<void> {
  // Setup customer connection
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Create a cancellation request to establish test context
  const cancellationRequest: IEcommerceMallCancellationRequest =
    await generate_random_ecommerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {
        body: {
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        },
      },
    );
  typia.assert(cancellationRequest);
  // Verify initial status is pending
  TestValidator.equals(
    "initial status is pending",
    cancellationRequest.status,
    "pending",
  );
  // Since seller response endpoint is not available, test that erase fails
  // when attempting to delete a non-existent cancellation request
  // (simulating the business rule that requests cannot be erased after certain states)
  const nonExistentRequestId: string = typia.random<
    string & tags.Format<"uuid">
  >();
  await TestValidator.error(
    "erase fails for non-existent cancellation request",
    async () => {
      await api.functional.ecommerceMall.customer.cancellation_requests.erase(
        customerConnection,
        {
          cancellationRequestId: nonExistentRequestId,
        },
      );
    },
  );
}
