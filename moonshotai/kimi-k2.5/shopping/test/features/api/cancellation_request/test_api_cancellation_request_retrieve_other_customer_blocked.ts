/**
 * Test access control enforcement - a customer should not be able to retrieve another customer's cancellation request.
 * Validates Section 367 Cart Access Boundary Enforcement applies to cancellation requests.
 */
export async function test_api_cancellation_request_retrieve_other_customer_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create Customer A and authenticate
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerA = await authorize_customer_join(customerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerA);
  // 2. Create Customer B and authenticate
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerB = await authorize_customer_join(customerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerB);
  // 3. Customer A creates a cancellation request
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_cancellation_requests_create(
      customerAConnection,
      {
        body: {
          orderItemId: typia.random<string & tags.Format<"uuid">>(),
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IEcommerceMallCancellationRequest.ICreate,
      },
    );
  typia.assert(cancellationRequest);
  // 4. Verify Customer B cannot access Customer A's cancellation request
  // Should return 403 Forbidden or 404 Not Found to prevent data leakage
  await TestValidator.httpError(
    "customer B cannot access customer A's cancellation request",
    [403, 404],
    async () => {
      await api.functional.ecommerceMall.customer.cancellation_requests.at(
        customerBConnection,
        {
          cancellationRequestId: cancellationRequest.id,
        },
      );
    },
  );
}
