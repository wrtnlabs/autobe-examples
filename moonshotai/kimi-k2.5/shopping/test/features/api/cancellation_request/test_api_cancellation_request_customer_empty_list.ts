export async function test_api_cancellation_request_customer_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate a new customer (no cancellation history)
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
    },
  });
  // 2. Query cancellation requests for this new customer
  const response =
    await api.functional.ecommerceMall.customer.cancellation_requests.index(
      customerConnection,
      {
        body: {
          page: 1,
          limit: 10,
        } satisfies IEcommerceMallCancellationRequest.IRequest,
      },
    );
  // 3. Validate the response structure and empty state
  typia.assert(response);
  // Verify pagination metadata shows empty result
  TestValidator.equals(
    "pagination shows empty",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination current page",
    response.pagination.current,
    1,
  );
  TestValidator.equals("pagination limit", response.pagination.limit, 10);
  TestValidator.equals("pagination pages", response.pagination.pages, 0);
  // Verify data is empty array
  TestValidator.equals("data is empty array", response.data.length, 0);
}
