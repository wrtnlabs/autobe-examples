export async function test_api_product_snapshot_images_cross_seller_access_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  typia.assert(admin);
  // 2. Admin creates product category (required for product creation)
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
      },
    },
  );
  typia.assert(category);
  // 3. Create seller1 connection and authenticate
  const seller1Connection: api.IConnection = { host: connection.host };
  const seller1 = await authorize_seller_join(seller1Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller1);
  // 4. Seller1 creates a product (generating snapshot)
  const product = await generate_random_ecommerce_mall_seller_products_create(
    seller1Connection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 1 }),
        description: RandomGenerator.paragraph(),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 5. Create seller2 connection and authenticate (different seller who should NOT have access)
  const seller2Connection: api.IConnection = { host: connection.host };
  const seller2 = await authorize_seller_join(seller2Connection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller2);
  // 6. Verify seller1 and seller2 are different sellers
  TestValidator.notEquals(
    "sellers should be different",
    seller1.id,
    seller2.id,
  );
  // 7. Seller2 attempts to access seller1's product snapshot images
  // This should be rejected with 403 Forbidden since seller2 doesn't own the product
  await TestValidator.httpError(
    "cross-seller snapshot image access should be blocked with 403 Forbidden",
    403,
    async () => {
      await api.functional.ecommerceMall.seller.productSnapshots.images.index(
        seller2Connection,
        {
          snapshotId: product.id, // Using product ID as snapshot reference
          body: {
            // Empty request body is valid as all fields in IRequest are optional
          } satisfies IEcommerceMallProductSnapshotImage.IRequest,
        },
      );
    },
  );
}
