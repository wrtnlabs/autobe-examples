export async function test_api_product_snapshot_retrieval_by_admin(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {},
  });
  typia.assert(adminAuth);
  // 2. Create a category as admin - product needs a category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {},
    },
  );
  typia.assert(category);
  // 3. Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {},
  });
  typia.assert(sellerAuth);
  // 4. Create a product in the category as seller - generates initial snapshot
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 5. Retrieve the product snapshot by admin
  // The snapshot ID would typically be obtained from a list endpoint, but we test the retrieval
  // In simulate mode, typia.random generates appropriate test data
  const snapshot =
    await api.functional.ecommerceMall.admin.products.snapshots.at(
      adminConnection,
      {
        productId: product.id,
        snapshotId: typia.random<string>(),
      },
    );
  // Validate complete snapshot structure with typia.assert
  // This validates all required fields: id, name, description, basePrice,
  // createdAt, category (ISummary), images (array of ISummary)
  typia.assert(snapshot);
}
