export async function test_api_admin_promotion_request_snapshot_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as superAdmin
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdmin = await authorize_super_admin_join(superAdminConnection, {});
  typia.assert(superAdmin);
  // 2. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Seller submits admin promotion request
  const promotionRequest =
    await generate_random_ecommerce_mall_seller_admin_promotion_requests_create(
      sellerConnection,
      {},
    );
  typia.assert(promotionRequest);
  // 4. SuperAdmin retrieves the snapshot
  const requestId = promotionRequest.id;
  const snapshotId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.ecommerceMall.superAdmin.admin_promotion_requests.snapshots.at(
      superAdminConnection,
      {
        requestId,
        snapshotId,
      },
    );
  typia.assert(snapshot);
  // 5. Validate business logic - verify snapshot belongs to the requested promotion request
  TestValidator.equals(
    "snapshot requestId matches",
    snapshot.adminPromotionRequestId,
    requestId,
  );
  TestValidator.equals(
    "snapshot id matches requested",
    snapshot.id,
    snapshotId,
  );
  TestValidator.equals(
    "snapshot admin promotion request id matches",
    snapshot.adminPromotionRequest.id,
    requestId,
  );
}
