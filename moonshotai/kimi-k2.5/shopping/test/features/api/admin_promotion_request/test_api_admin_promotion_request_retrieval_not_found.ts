/**
 * Test the error handling when attempting to retrieve a non-existent administrator promotion request.
 *
 * 1. Authenticate as a super administrator using POST /ecommerceMall/auth/superAdmin/join
 * 2. Call GET /ecommerceMall/seller/admin-promotion-requests/{promotionRequestId} with a randomly generated UUID that does not exist in the system
 * 3. Verify that the response returns 404 Not Found status
 */
export async function test_api_admin_promotion_request_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as super administrator
  const superAdminConnection: api.IConnection = { host: connection.host };
  await api.functional.ecommerceMall.auth.superAdmin.join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
        href: typia.random<string & tags.Format<"uri">>(),
        referrer: typia.random<string & tags.Format<"uri">>(),
        ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
      } satisfies IEcommerceMallSuperAdmin.IJoin,
    },
  );
  // 2. Generate a random UUID that does not exist in the system
  const nonExistentId = typia.random<string & tags.Format<"uuid">>();
  // 3. Verify 404 error is returned for non-existent promotion request
  await TestValidator.httpError(
    "non-existent promotion request returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.seller.admin_promotion_requests.at(
        superAdminConnection,
        {
          promotionRequestId: nonExistentId,
        },
      );
    },
  );
}
