/**
 * Test that requesting a non-existent snapshot ID returns an appropriate 404 error.
 * This validates proper error handling when administrators attempt to access snapshots
 * that don't exist or snapshots for products they cannot access. The system should
 * return a clear error indicating the snapshot was not found rather than exposing
 * information about snapshot existence through different error types.
 */
export async function test_api_admin_product_snapshot_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
    },
  });
  // 2. Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
    },
  });
  // 3. Admin creates a category for the product
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 4. Seller creates a product to establish a valid productId
  const product: IEcommerceMallProduct =
    await generate_random_ecommerce_mall_seller_products_create(
      sellerConnection,
      {
        body: {
          categoryId: category.id,
        },
      },
    );
  typia.assert(product);
  // 5. Admin attempts to retrieve a non-existent snapshot for the valid product
  // Using a random UUID that doesn't exist as the snapshotId
  const nonExistentSnapshotId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "should return 404 for non-existent snapshot",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.products.snapshots.at(
        adminConnection,
        {
          productId: product.id,
          snapshotId: nonExistentSnapshotId,
        },
      );
    },
  );
}
