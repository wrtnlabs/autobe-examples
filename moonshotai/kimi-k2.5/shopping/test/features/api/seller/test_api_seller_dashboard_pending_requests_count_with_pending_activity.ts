export async function test_api_seller_dashboard_pending_requests_count_with_pending_activity(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create a seller connection with authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // Step 2: Create a product to establish business activity context
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: typia.random<string & tags.Format<"uuid">>(),
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<100>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // Step 3: Retrieve pending requests count from dashboard
  const pendingCount: IEcommerceMallPendingRequestsCount =
    await api.functional.ecommerceMall.seller.pending_requests_count.pendingRequestsCount(
      sellerConnection,
    );
  typia.assert(pendingCount);
  // Step 4: Validate the count is a non-negative integer
  TestValidator.predicate(
    "pending requests count is non-negative",
    pendingCount.count >= 0,
  );
}
