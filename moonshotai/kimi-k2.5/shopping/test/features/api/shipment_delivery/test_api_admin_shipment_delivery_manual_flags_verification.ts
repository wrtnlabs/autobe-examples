/**
 * Test admin confirming delivery and verify that the delivery timestamp reflects the manual confirmation and that the isAutoDelivered flag is false.
 * When an admin confirms delivery before the automatic 14-day window expires, the system should record the manual confirmation timestamp, set isAutoDelivered to false indicating manual (not automatic) confirmation, and items become eligible for refunds starting from this delivery date.
 * Verify the delivery record contains the correct timestamps and the boolean flag distinguishes manual from automatic delivery.
 */
export async function test_api_admin_shipment_delivery_manual_flags_verification(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(admin);
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 2. Seller setup - create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          options: [
            { optionName: "Color", optionValue: "Red" },
            { optionName: "Size", optionValue: "Large" },
          ] satisfies IEcommerceMallProductVariantOption.ICreate[],
          price: typia.random<number & tags.Minimum<1000>>() satisfies number as number,
          stock: typia.random<number & tags.Type<"int32"> & tags.Minimum<10>>(),
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 3. Customer setup - add to cart and checkout
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customer);
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: RandomGenerator.name(),
        postalCode: RandomGenerator.alphaNumeric(5),
        country: RandomGenerator.name(),
      } satisfies IEcommerceMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Get the order item ID from the created order
  const orderItemId = (order.orderItems[0] as IEntity).id;
  // 4. Seller creates shipment
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        orderItemIds: [orderItemId],
        carrierName: "FedEx",
        trackingNumber: RandomGenerator.alphaNumeric(12),
      } satisfies IEcommerceMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 5. Admin confirms delivery manually (before 14-day auto-delivery window)
  const confirmedShipment =
    await api.functional.ecommerceMall.admin.shipments.deliveries.confirmDelivery(
      adminConnection,
      { shipmentId: shipment.id },
    );
  typia.assert(confirmedShipment);
  // 6. Verify delivery flags and timestamps
  TestValidator.predicate(
    "delivery record exists",
    confirmedShipment.delivery !== null,
  );
  if (confirmedShipment.delivery) {
    TestValidator.predicate(
      "isAutoDelivered is false for manual confirmation",
      confirmedShipment.delivery.isAutoDelivered === false,
    );
    TestValidator.predicate(
      "deliveredAt timestamp exists",
      confirmedShipment.delivery.deliveredAt !== null,
    );
    TestValidator.predicate(
      "deliveredAt is valid ISO timestamp",
      !isNaN(Date.parse(confirmedShipment.delivery.deliveredAt)),
    );
    TestValidator.predicate(
      "createdAt timestamp exists",
      confirmedShipment.delivery.createdAt !== null,
    );
    TestValidator.predicate(
      "shipmentId matches",
      confirmedShipment.delivery.shipmentId === shipment.id,
    );
    TestValidator.predicate(
      "customerId is null for admin-confirmed delivery",
      confirmedShipment.delivery.customerId === null,
    );
  }
}