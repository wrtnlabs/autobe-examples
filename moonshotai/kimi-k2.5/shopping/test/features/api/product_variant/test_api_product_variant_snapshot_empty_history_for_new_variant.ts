export async function test_api_product_variant_snapshot_empty_history_for_new_variant(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin connection and authenticate for category creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // Step 2: Admin creates a category for the product
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 3: Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Step 4: Seller creates a product under the category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // Step 5: Seller creates a variant for the product (newly created, no edit history)
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // Step 6: Query snapshots for the newly created variant
  const requestBody = {
    page: 1,
    limit: 10,
  } satisfies IEcommerceMallProductVariantSnapshot.IRequest;
  const response: IPageIEcommerceMallProductVariantSnapshot.ISummary =
    await api.functional.ecommerceMall.seller.product_variants.snapshots.index(
      sellerConnection,
      {
        variantId: variant.id,
        body: requestBody,
      },
    );
  typia.assert(response);
  // Step 7: Verify response shows empty data array with total count of 0
  TestValidator.equals("data array is empty", response.data, []);
  TestValidator.equals(
    "pagination records is 0",
    response.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination current page",
    response.pagination.current,
    1,
  );
  TestValidator.equals("pagination limit", response.pagination.limit, 10);
  TestValidator.equals("pagination pages is 0", response.pagination.pages, 0);
}
