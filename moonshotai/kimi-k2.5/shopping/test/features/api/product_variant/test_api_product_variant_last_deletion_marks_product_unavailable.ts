export async function test_api_product_variant_last_deletion_marks_product_unavailable(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Create product with the category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Create exactly one variant for the product (the last/only variant scenario)
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          skuCode: typia.random<string & tags.MinLength<1>>(),
          options: [
            {
              optionName: "Color",
              optionValue: "Red",
            },
          ] satisfies IEcommerceMallProductVariantOption.ICreate[],
        },
      },
    );
  typia.assert(variant);
  // 5. Verify the variant exists and is linked to the product
  TestValidator.equals(
    "variant belongs to product",
    variant.product.id,
    product.id,
  );
  // 6. Delete the only variant (this should succeed and mark product as unavailable)
  await api.functional.ecommerceMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      productVariantId: variant.id,
    },
  );
  // 7. Verify attempting to delete the same variant again fails
  await TestValidator.error(
    "delete already deleted variant fails",
    async () => {
      await api.functional.ecommerceMall.seller.products.variants.erase(
        sellerConnection,
        {
          productId: product.id,
          productVariantId: variant.id,
        },
      );
    },
  );
}
