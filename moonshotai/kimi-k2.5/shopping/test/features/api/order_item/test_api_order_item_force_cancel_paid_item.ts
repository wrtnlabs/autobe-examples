/**
 * Test the force-cancel functionality for a paid order item.
 * This scenario validates that a seller can administratively cancel an order item that is in 'paid' status.
 * The test flows through: admin creates category -> seller creates product with variant -> customer creates cart
 * -> attempts seller force-cancel on the order item.
 */
export async function test_api_order_item_force_cancel_paid_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin and generate category
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(admin);
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Create seller and generate product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(seller);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 3. Create customer and add variant to cart
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(customer);
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 4. As seller, call the patch endpoint to force-cancel an order item
  // Validating the API structure - this endpoint allows administrative status changes
  // Note: In production flow, the order item id would come from customer order lookup
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const updatedItem: IEcommerceMallOrderItem =
    await api.functional.ecommerceMall.seller.items.update(sellerConnection, {
      itemId: orderItemId,
      body: {
        status: "cancelled",
      } satisfies IEcommerceMallOrderItem.IUpdate,
    });
  typia.assert(updatedItem);
}
