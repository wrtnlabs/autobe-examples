export async function test_api_admin_order_item_delete_shipped_status_blocked(
  connection: api.IConnection,
): Promise<void> {
  // Actor connections
  const adminConnection: api.IConnection = { host: connection.host };
  const customerConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  // 1. All actors join
  await authorize_admin_join(adminConnection, {});
  await authorize_customer_join(customerConnection, {});
  await authorize_seller_join(sellerConnection, {});
  // 2. Admin creates category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
      },
    },
  );
  typia.assert(category);
  // 3. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          stock: 100 satisfies number as number,
        },
      },
    );
  typia.assert(variant);
  // 5. Customer adds variant to cart
  await generate_random_ecommerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: typia.random<number & tags.Type<"int32"> & tags.Minimum<1>>(),
      },
    },
  );
  // 6. Customer checkout creates order
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.alphaNumeric(10),
        city: "Seoul",
        state: "Seoul",
        postalCode: "12345",
        country: "South Korea",
      },
    },
  );
  typia.assert(order);
  TestValidator.predicate(
    "order has at least one item",
    order.orderItems.length >= 1,
  );
  const orderItem = typia.assert<IEcommerceMallOrderItem & IEntity>(order.orderItems[0]);
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 7. Seller creates shipment for the order item (status becomes shipped)
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        orderItemIds: [orderItem.id],
        carrierName: RandomGenerator.name(),
        trackingNumber: RandomGenerator.alphaNumeric(12),
      },
    },
  );
  typia.assert(shipment);
  // 8. Admin attempts to delete shipped order item - should be rejected
  await TestValidator.error(
    "deletion of shipped order item should be rejected",
    async () => {
      await api.functional.ecommerceMall.admin.orders.items.erase(
        adminConnection,
        {
          orderId: order.id,
          itemId: orderItem.id,
        },
      );
    },
  );
}