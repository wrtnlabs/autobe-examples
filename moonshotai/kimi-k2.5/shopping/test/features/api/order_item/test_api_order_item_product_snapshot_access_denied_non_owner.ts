export async function test_api_order_item_product_snapshot_access_denied_non_owner(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as Seller A to establish product ownership
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create product as Seller A
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {},
  );
  typia.assert(product);
  // 3. Create product variant as Seller A
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 4. Authenticate as Customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5. Add Seller A's product variant to customer cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Authenticate as Seller B (non-owner)
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 7. As Seller B, attempt to access order item product snapshot (order item ID is random since checkout endpoint unavailable)
  // This validates the permission boundary - Seller B should be denied access regardless of order item existence
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  // 8. Validate access is denied with 403 Forbidden or 404 Not Found
  await TestValidator.httpError(
    "Seller B should be denied access to order item product snapshot",
    [403, 404],
    () =>
      api.functional.ecommerceMall.seller.orderItems.productSnapshot.atProductSnapshot(
        sellerBConnection,
        { orderItemId },
      ),
  );
}
