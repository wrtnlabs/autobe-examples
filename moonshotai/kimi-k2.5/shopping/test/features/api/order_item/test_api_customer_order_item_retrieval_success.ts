type IOrderItemWithId = IEcommerceMallOrderItem & IEntity & { quantity: number; priceAtPurchase: number };

export async function test_api_customer_order_item_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 2: Create seller and product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<number>(),
      },
    },
  );
  typia.assert(product);
  // Step 3: Create product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          options: [
            {
              optionName: "Color",
              optionValue: "Red",
            } satisfies IEcommerceMallProductVariantOption.ICreate,
          ],
          price: typia.random<number>(),
          stock: 100,
        },
      },
    );
  typia.assert(variant);
  // Step 4: Create customer and add to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  // Step 5: Checkout to create order
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: null,
        postalCode: RandomGenerator.alphaNumeric(5),
        country: RandomGenerator.name(),
      },
    },
  );
  typia.assert(order);
  // Verify we have order items
  TestValidator.predicate(
    "order has at least one order item",
    order.orderItems.length > 0,
  );
  const orderItem = order.orderItems[0] as IOrderItemWithId;
  // Step 6: Retrieve specific order item
  const retrievedOrderItem =
    await api.functional.ecommerceMall.customer.orders.items.at(
      customerConnection,
      {
        orderId: order.id,
        itemId: orderItem.id,
      },
    ) as IOrderItemWithId;
  typia.assert(retrievedOrderItem);
  // Business logic validation - verify the retrieved item matches what we created
  TestValidator.equals(
    "order item ID matches",
    retrievedOrderItem.id,
    orderItem.id,
  );
  TestValidator.equals(
    "order item quantity matches",
    retrievedOrderItem.quantity,
    orderItem.quantity,
  );
  TestValidator.equals(
    "price at purchase matches",
    retrievedOrderItem.priceAtPurchase,
    orderItem.priceAtPurchase,
  );
}