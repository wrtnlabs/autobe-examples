export async function test_api_variant_snapshot_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Create authenticated admin connection for snapshot retrieval
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Retrieve variant snapshot using order item ID
  // Response type IEcommerceMallProductVariantSnapshot includes:
  // - id, productVariantId, skuCode, price, createdAt, optionValues[]
  const snapshot =
    await api.functional.ecommerceMall.admin.orderItems.variantSnapshot.at(
      adminConnection,
      {
        orderItemId: typia.random<string & tags.Format<"uuid">>(),
      },
    );
  // Complete response validation - checks all DTO fields including
  // immutable snapshot data (SKU, price, option values at purchase time)
  typia.assert(snapshot);
}
