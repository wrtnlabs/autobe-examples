/**
 * Test admin order retrieval when requesting a non-existent order ID.
 * Validates that the system properly returns a 404 error response when
 * an administrator attempts to retrieve an order that does not exist.
 * This ensures proper error handling and prevents information leakage.
 */
export async function test_api_admin_order_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      href: "https://example.com/admin/orders" satisfies string as string,
      referrer:
        "https://example.com/admin/dashboard" satisfies string as string,
    },
  });
  // 2. Generate a valid UUID that does not exist in the system
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve order with non-existent ID
  // Expect 404 Not Found error
  await TestValidator.httpError(
    "should return 404 for non-existent order",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.orders.at(adminConnection, {
        orderId: nonExistentOrderId,
      });
    },
  );
}
