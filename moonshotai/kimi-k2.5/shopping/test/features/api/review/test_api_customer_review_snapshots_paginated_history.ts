export async function test_api_customer_review_snapshots_paginated_history(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connection for customer
  const customerConnection: api.IConnection = { host: connection.host };
  // 1. Authenticate as customer
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Create a review (creates initial snapshot)
  const review = await generate_random_ecommerce_mall_customer_reviews_create(
    customerConnection,
    {
      body: typia.random<IEcommerceMallReview.ICreate>(),
    },
  );
  typia.assert(review);
  // 3. Retrieve paginated snapshots for the review
  const snapshots =
    await api.functional.ecommerceMall.customer.reviews.snapshots.index(
      customerConnection,
      {
        reviewId: review.id,
        body: {
          page: 1,
          limit: 10,
          sort: {
            field: "created_at",
            direction: "desc",
          },
        } satisfies IEcommerceMallReview.ISnapshotRequest,
      },
    );
  typia.assert(snapshots);
}
