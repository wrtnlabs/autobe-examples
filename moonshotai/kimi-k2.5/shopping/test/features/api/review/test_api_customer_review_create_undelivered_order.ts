export async function test_api_customer_review_create_undelivered_order(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Attempt to create a review for an undelivered order item
  // Using a random UUID that doesn't exist or references a non-delivered order item
  // This should fail with 422 Unprocessable Entity - order item not delivered
  await TestValidator.httpError(
    "should reject review creation for undelivered order item",
    422,
    async () => {
      await api.functional.ecommerceMall.customer.reviews.create(
        customerConnection,
        {
          body: {
            orderItemId: typia.random<string & tags.Format<"uuid">>(),
            rating: typia.random<
              number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
            >(),
            content: RandomGenerator.paragraph({ sentences: 3 }),
          } satisfies IEcommerceMallReview.ICreate,
        },
      );
    },
  );
}
