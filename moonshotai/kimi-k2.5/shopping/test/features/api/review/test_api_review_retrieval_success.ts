export async function test_api_review_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create and authenticate a customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerAuth);
  // Step 2: Create a review for a delivered order item
  // The utility handles the preparation of valid review data including orderItemId
  const review = await generate_random_ecommerce_mall_customer_reviews_create(
    customerConnection,
    {
      body: {
        rating: typia.random<
          number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<5>
        >(),
        content: RandomGenerator.paragraph({ sentences: 3 }),
      } satisfies Partial<IEcommerceMallReview.ICreate>,
    },
  );
  typia.assert(review);
  // Step 3: Retrieve the review by ID
  const retrievedReview = await api.functional.ecommerceMall.reviews.at(
    customerConnection,
    { reviewId: review.id },
  );
  typia.assert(retrievedReview);
  // Step 4: Validate the retrieved review matches the original
  TestValidator.equals("review id matches", retrievedReview.id, review.id);
  TestValidator.equals("rating matches", retrievedReview.rating, review.rating);
  TestValidator.equals(
    "content matches",
    retrievedReview.content,
    review.content,
  );
  TestValidator.equals(
    "customer reference matches",
    (retrievedReview.customer as IEntity).id,
    (review.customer as IEntity).id,
  );
  TestValidator.equals(
    "product reference matches",
    retrievedReview.product.id,
    review.product.id,
  );
  TestValidator.equals(
    "order reference matches",
    retrievedReview.order.id,
    review.order.id,
  );
  TestValidator.predicate(
    "created_at is valid",
    retrievedReview.createdAt !== null,
  );
  TestValidator.predicate(
    "updated_at is valid",
    retrievedReview.updatedAt !== null,
  );
}
