/**
 * Test cart item quantity update when the referenced product variant becomes unavailable (soft-deleted).
 *
 * This test validates the business rule that unavailable variants cannot have their cart quantities increased.
 * According to section 365 'Unavailable Variant Handling', when a variant is soft-deleted after being added
 * to a cart, quantity modifications should be blocked and return appropriate error messaging.
 *
 * Test Flow:
 * 1. Administrator creates a product category
 * 2. Seller creates a product with an initial stock variant in that category
 * 3. Customer adds the variant to their shopping cart
 * 4. Seller soft-deletes the variant (making it unavailable via deleted_at timestamp)
 * 5. Customer attempts to increase the cart item quantity
 * 6. System rejects the update with 422 Unprocessable Entity (or equivalent error)
 */
export async function test_api_customer_cart_item_quantity_unavailable_variant(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Admin creates category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 2: Seller creates product and variant with stock
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      } satisfies Partial<IEcommerceMallProduct.ICreate>,
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          stock: 100,
        } satisfies Partial<IEcommerceMallProductVariant.ICreate>,
      },
    );
  typia.assert(variant);
  // Step 3: Customer adds variant to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 2,
        } satisfies Partial<IEcommerceMallCartItem.ICreate>,
      },
    );
  typia.assert(cartItem);
  TestValidator.equals("initial cart quantity", cartItem.quantity, 2);
  // Step 4: Seller soft-deletes the variant (making it unavailable)
  await api.functional.ecommerceMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: variant.productId,
      variantId: variant.id,
    },
  );
  // Step 5: Customer attempts to increase quantity - should fail since variant is unavailable
  await TestValidator.error(
    "increase quantity on unavailable variant",
    async () => {
      await api.functional.ecommerceMall.customer.cartItems.update(
        customerConnection,
        {
          cartItemId: cartItem.id,
          body: {
            quantity: cartItem.quantity + 1,
          } satisfies IEcommerceMallCartItem.IUpdate,
        },
      );
    },
  );
}
