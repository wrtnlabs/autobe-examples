export async function test_api_cart_item_access_boundary_enforcement(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category for product
  const adminConnection: api.IConnection = { host: connection.host };
  const adminCredentials = await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerCredentials = await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 3. First customer setup - create cart item
  const customer1Connection: api.IConnection = { host: connection.host };
  const customer1Credentials = await authorize_customer_join(
    customer1Connection,
    {},
  );
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customer1Connection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 4. Second customer setup - attempt to update first customer's cart item
  const customer2Connection: api.IConnection = { host: connection.host };
  const customer2Credentials = await authorize_customer_join(
    customer2Connection,
    {},
  );
  // 5. Attempt unauthorized update - should be rejected
  await TestValidator.error(
    "customer 2 should not be able to update customer 1's cart item",
    async () => {
      await api.functional.ecommerceMall.customer.cart_items.update(
        customer2Connection,
        {
          cartItemId: cartItem.id,
          body: {
            quantity: 5,
          } satisfies IEcommerceMallCartItem.IUpdate,
        },
      );
    },
  );
}
