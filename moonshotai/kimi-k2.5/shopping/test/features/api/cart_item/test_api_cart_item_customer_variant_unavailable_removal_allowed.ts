export async function test_api_cart_item_customer_variant_unavailable_removal_allowed(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin: Create product category
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller: Create product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.paragraph({ sentences: 5 }),
        categoryId: category.id,
        basePrice: typia.random<number & tags.Minimum<100>>(),
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(8),
          price: typia.random<number & tags.Minimum<100>>() satisfies number as number,
          options: ArrayUtil.repeat(2, () => ({
            optionName: RandomGenerator.alphabets(5),
            optionValue: RandomGenerator.alphabets(5),
          })),
          stock: 10,
        },
      },
    );
  typia.assert(variant);
  // 3. Customer: Add variant to cart
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  TestValidator.equals(
    "cart item added",
    cartItem.productVariant.id,
    variant.id,
  );
  // 4. Seller: Delete the variant to make it unavailable
  await api.functional.ecommerceMall.seller.products.variants.erase(
    sellerConnection,
    {
      productId: product.id,
      variantId: variant.id,
    },
  );
  // 5. Customer: Delete cart item - should succeed even though variant is unavailable
  await api.functional.ecommerceMall.customer.cartItems.erase(
    customerConnection,
    {
      cartItemId: cartItem.id,
    },
  );
  // If we reach here, deletion succeeded as expected
  TestValidator.predicate("cart item deletion succeeded", true);
}