export async function test_api_order_item_product_snapshot_access_boundary_enforcement(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create seller and product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Step 2: Authenticate as Customer A (order owner from seeded data)
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  // Step 3: Customer A retrieves their order item product snapshot
  // Using UUIDs representing seeded order data
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.ecommerceMall.customer.orders.items.productSnapshot.at(
      customerAConnection,
      { orderId, orderItemId },
    );
  typia.assert(snapshot);
  // Step 4 & 5: Authenticate as Customer B and attempt unauthorized access
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // Customer B should be denied access to Customer A's order items
  await TestValidator.httpError(
    "customer B gets 403 when accessing other customer's order item",
    [403, 404],
    async () => {
      await api.functional.ecommerceMall.customer.orders.items.productSnapshot.at(
        customerBConnection,
        { orderId, orderItemId },
      );
    },
  );
}
