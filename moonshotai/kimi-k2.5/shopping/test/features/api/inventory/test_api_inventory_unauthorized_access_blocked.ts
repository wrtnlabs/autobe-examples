export async function test_api_inventory_unauthorized_access_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create Seller A connection and authenticate
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {});
  // 3. Admin creates category (required for product creation)
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 4. Seller A creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  // 5. Seller A creates variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: {
          productId: product.id,
        },
        body: {},
      },
    );
  // 6. Create Seller B connection and authenticate
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {});
  // 7. Seller B attempts to access Seller A's variant inventory - should fail with 403
  await TestValidator.httpError(
    "seller B cannot access seller A's variant inventory",
    403,
    async () => {
      await api.functional.ecommerceMall.variants.inventory.index(
        sellerBConnection,
        {
          variantId: variant.id,
          body: {},
        },
      );
    },
  );
}
