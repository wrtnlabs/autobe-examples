export async function test_api_seller_refund_request_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create seller-specific connection
  const sellerConnection: api.IConnection = { host: connection.host };
  // 1. Authenticate as seller
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. Attempt to retrieve a non-existent refund request
  // Use a non-existent UUID to trigger 404
  const nonExistentRefundRequestId = "00000000-0000-0000-0000-000000000000";
  await TestValidator.error(
    "should throw error for non-existent refund request",
    async () => {
      await api.functional.ecommerceMall.seller.refund_requests.at(
        sellerConnection,
        {
          refundRequestId: nonExistentRefundRequestId,
        },
      );
    },
  );
}
