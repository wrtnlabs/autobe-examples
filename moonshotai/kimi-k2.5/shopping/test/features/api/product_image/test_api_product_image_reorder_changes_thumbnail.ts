export async function test_api_product_image_reorder_changes_thumbnail(
  connection: api.IConnection,
): Promise<void> {
  // Setup admin and create category (required for product creation)
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Setup seller and create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // Upload first image - automatically becomes main thumbnail with displayOrder=0
  const firstImage =
    await generate_random_ecommerce_mall_seller_products_images_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(firstImage);
  TestValidator.equals(
    "first image initial displayOrder should be 0",
    firstImage.displayOrder,
    0,
  );
  // Upload second image - gets displayOrder=1
  const secondImage =
    await generate_random_ecommerce_mall_seller_products_images_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(secondImage);
  TestValidator.equals(
    "second image initial displayOrder should be 1",
    secondImage.displayOrder,
    1,
  );
  // Reorder: Update second image to displayOrder=0 to make it the new main thumbnail
  const updatedImage =
    await api.functional.ecommerceMall.seller.products.images.update(
      sellerConnection,
      {
        productId: product.id,
        imageId: secondImage.id,
        body: {
          displayOrder: 0,
        } satisfies IEcommerceMallProductImage.IUpdate,
      },
    );
  typia.assert(updatedImage);
  // Validate the update succeeded and the image now has displayOrder=0
  TestValidator.equals(
    "updated image displayOrder should be 0",
    updatedImage.displayOrder,
    0,
  );
  TestValidator.equals(
    "image id should match",
    updatedImage.id,
    secondImage.id,
  );
}
