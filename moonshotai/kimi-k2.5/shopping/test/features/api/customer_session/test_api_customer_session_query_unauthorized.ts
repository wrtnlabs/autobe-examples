export async function test_api_customer_session_query_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // Attempt to query sessions as a customer (should fail - admin only endpoint)
  await TestValidator.httpError(
    "customer should be forbidden from accessing session query endpoint",
    403,
    async () => {
      await api.functional.ecommerceMall.customer.sessions.index(
        customerConnection,
        {
          body: {
            limit: 10,
          } satisfies IEcommerceMallCustomerSession.IRequest,
        },
      );
    },
  );
}
