export async function test_api_seller_registration_snapshot_filtered_by_registration(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Generate a random registration ID for filtering
  const registrationId = typia.random<string & tags.Format<"uuid">>();
  // Create request with registrationId filter
  const requestBody = {
    registrationId,
    page: 1,
    limit: 20,
  } satisfies IEcommerceMallSellerRegistrationSnapshot.IRequest;
  // Call the registration snapshots endpoint with filter
  const response =
    await api.functional.ecommerceMall.admin.seller.registration_snapshots.index(
      adminConnection,
      { body: requestBody },
    );
  typia.assert(response);
}
