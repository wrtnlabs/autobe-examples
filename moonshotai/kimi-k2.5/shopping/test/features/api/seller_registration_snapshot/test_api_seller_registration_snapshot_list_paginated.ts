export async function test_api_seller_registration_snapshot_list_paginated(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection following isolation pattern
  const adminConnection: api.IConnection = { host: connection.host };
  // Authenticate as administrator using utility function
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Retrieve paginated seller registration snapshots with default filters
  const response =
    await api.functional.ecommerceMall.admin.seller.registration_snapshots.index(
      adminConnection,
      {
        body: {
          page: 1,
          limit: 20,
          sortBy: "created_at",
          sortDirection: "desc",
        } satisfies IEcommerceMallSellerRegistrationSnapshot.IRequest,
      },
    );
  // Validate complete response structure
  typia.assert(response);
  // Validate pagination metadata structure
  TestValidator.predicate(
    "pagination object exists",
    response.pagination !== undefined,
  );
  TestValidator.predicate("data array exists", Array.isArray(response.data));
  TestValidator.predicate(
    "current page is non-negative",
    response.pagination.current >= 0,
  );
  TestValidator.predicate("limit is positive", response.pagination.limit > 0);
  TestValidator.predicate(
    "records count is non-negative",
    response.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pages count is non-negative",
    response.pagination.pages >= 0,
  );
}
