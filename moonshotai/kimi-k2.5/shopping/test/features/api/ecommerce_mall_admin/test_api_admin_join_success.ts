/**
 * Test successful admin join authentication workflow.
 *
 * Validates that an administrator can successfully authenticate using the join
 * endpoint with valid credentials and session context. The operation should
 * return a complete authorization response containing admin profile, JWT tokens,
 * and expiration metadata.
 */
export async function test_api_admin_join_success(
  connection: api.IConnection,
): Promise<void> {
  const adminConnection: api.IConnection = { host: connection.host };
  const authorized = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(authorized);
}
