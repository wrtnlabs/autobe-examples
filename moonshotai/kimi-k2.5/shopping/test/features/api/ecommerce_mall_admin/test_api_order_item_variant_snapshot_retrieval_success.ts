export async function test_api_order_item_variant_snapshot_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as admin
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Query existing orders
  const ordersPage = await api.functional.ecommerceMall.admin.orders.index(
    adminConnection,
    {
      body: {
        page: 1,
        limit: 20,
      } satisfies IEcommerceMallOrder.IRequest,
    },
  );
  typia.assert(ordersPage);
  // 3. Generate test data for order and order item IDs
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  // 4. Retrieve variant snapshot
  const snapshot =
    await api.functional.ecommerceMall.admin.orders.items.variantSnapshot.invert(
      adminConnection,
      {
        orderId: orderId,
        orderItemId: orderItemId,
      },
    );
  typia.assert(snapshot);
}
