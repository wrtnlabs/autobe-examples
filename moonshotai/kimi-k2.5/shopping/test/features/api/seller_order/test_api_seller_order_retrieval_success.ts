export async function test_api_seller_order_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {},
  });
  typia.assert(sellerAuth);
  // 2. Create a product as seller
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {},
  });
  typia.assert(customerAuth);
  // 4. Add product variant to cart as customer
  const variantId = product.variants[0]?.id;
  if (variantId) {
    const cartItem =
      await generate_random_ecommerce_mall_customer_cart_items_create(
        customerConnection,
        {
          body: {
            productVariantId: variantId,
            quantity: 1 satisfies number as number,
          },
        },
      );
    typia.assert(cartItem);
  }
  // 5. Retrieve order using seller connection
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const order = await api.functional.ecommerceMall.seller.orders.at(
    sellerConnection,
    { orderId },
  );
  typia.assert(order);
}
