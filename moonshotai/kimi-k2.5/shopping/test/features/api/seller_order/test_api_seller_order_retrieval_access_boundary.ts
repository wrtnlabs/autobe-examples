/**
 * Test that a seller cannot access order details belonging to another seller (access boundary enforcement).
 *
 * Steps:
 * 1. Authenticate as Seller A using /auth/seller/join
 * 2. Authenticate as a customer using /auth/customer/join
 * 3. Since product creation and order placement endpoints are not available in the SDK,
 *    we use a random UUID as an order ID that would belong to a different seller context
 * 4. Authenticate as Seller B using /auth/seller/join
 * 5. Attempt to retrieve the order using GET /ecommerceMall/seller/orders/{orderId}
 * 6. Verify the system denies access with an appropriate error (403 Forbidden or 404 Not Found)
 */
export async function test_api_seller_order_retrieval_access_boundary(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create Seller A connection and authenticate
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 2. Create a customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 3. Use a random order ID that doesn't belong to Seller B
  // Since product/order creation endpoints are not available in SDK,
  // we use a random UUID that represents an order that would belong to another seller
  const orderId = typia.random<string & tags.Format<"uuid">>();
  // 4. Create Seller B connection and authenticate
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // 5, 6. Attempt to retrieve the order as Seller B and verify access is denied
  await TestValidator.error(
    "Seller B should not access Seller A's order",
    async () => {
      await api.functional.ecommerceMall.seller.orders.at(sellerBConnection, {
        orderId,
      });
    },
  );
}
