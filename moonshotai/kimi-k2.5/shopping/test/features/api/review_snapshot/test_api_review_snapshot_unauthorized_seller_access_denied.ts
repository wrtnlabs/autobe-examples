export async function test_api_review_snapshot_unauthorized_seller_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create and authenticate Seller A (the product owner)
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. Create and authenticate Seller B (the unauthorized seller)
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 3. Generate random review and snapshot IDs
  const reviewId: string = typia.random<string & tags.Format<"uuid">>();
  const snapshotId: string = typia.random<string & tags.Format<"uuid">>();
  // 4. Attempt to access review snapshot as unauthorized Seller B
  // Should receive 403 Forbidden or 404 Not Found due to lack of ownership
  await TestValidator.httpError(
    "unauthorized seller access should return 403",
    [403, 404],
    async () => {
      await api.functional.ecommerceMall.seller.reviews.snapshots.at(
        sellerBConnection,
        {
          reviewId,
          snapshotId,
        },
      );
    },
  );
}
