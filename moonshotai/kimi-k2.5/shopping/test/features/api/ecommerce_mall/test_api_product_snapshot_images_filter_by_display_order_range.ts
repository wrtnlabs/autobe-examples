export async function test_api_product_snapshot_images_filter_by_display_order_range(
  connection: api.IConnection,
): Promise<void> {
  // Setup admin connection and create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Setup seller connection and create product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // Verify product has at least 3 images for meaningful range test
  TestValidator.predicate(
    "product has at least 3 images",
    product.images.length >= 3,
  );
  // Filter snapshot images by display order range (2-3)
  const result =
    await api.functional.ecommerceMall.seller.productSnapshots.images.index(
      sellerConnection,
      {
        snapshotId: product.id,
        body: {
          displayOrderMin: 2,
          displayOrderMax: 3,
          page: 1,
          limit: 10,
        } satisfies IEcommerceMallProductSnapshotImage.IRequest,
      },
    );
  typia.assert(result);
  // Verify all returned images have display_order within range [2, 3]
  for (const image of result.data) {
    TestValidator.predicate(
      `image ${image.id} has display_order >= 2`,
      image.display_order >= 2,
    );
    TestValidator.predicate(
      `image ${image.id} has display_order <= 3`,
      image.display_order <= 3,
    );
  }
  // Verify pagination reflects filtered count (should be exactly 2 images: positions 2 and 3)
  TestValidator.equals("filtered records count", result.pagination.records, 2);
  TestValidator.equals("current page", result.pagination.current, 1);
  TestValidator.predicate(
    "total records non-negative",
    result.pagination.records >= 0,
  );
}
