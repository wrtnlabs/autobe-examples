export async function test_api_product_review_stats_with_existing_reviews(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 3. Authenticate as customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Since order and review APIs are not available in the provided SDK,
  //    we proceed to test the review-stats endpoint with the current state
  // 5. Seller retrieves review stats for the product
  const reviewStats =
    await api.functional.ecommerceMall.seller.products.review_stats.reviewStats(
      sellerConnection,
      { productId: product.id },
    );
  typia.assert(reviewStats);
  // Business logic validation: distribution counts should sum to total
  TestValidator.equals(
    "distribution sum equals totalCount",
    reviewStats.distribution["1"] +
      reviewStats.distribution["2"] +
      reviewStats.distribution["3"] +
      reviewStats.distribution["4"] +
      reviewStats.distribution["5"],
    reviewStats.totalCount,
  );
}
