export async function test_api_seller_snapshot_historical_accuracy_after_profile_change(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // Step 2: Create seller and capture original shop name
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  const originalShopName = sellerAuth.shopName;
  // Create product with category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: { categoryId: category.id },
    },
  );
  // Create variant with stock
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: { stock: 100 },
      },
    );
  // Step 3: Create customer, add to cart, and checkout
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  await generate_random_ecommerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: { productVariantId: variant.id, quantity: 1 },
    },
  );
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {},
  );
  typia.assert(order);
  // Step 4: Extract order and item information
  const orderId = order.id;
  const orderItem = order.orderItems[0];
  const assertedOrderItem = typia.assert<IEcommerceMallOrderItem & IEntity>(orderItem);
  const itemId = assertedOrderItem.id;
  // Step 5: Retrieve seller snapshot using admin connection
  // The snapshot ID is accessed from the order item structure
  const snapshotId = (
    orderItem as {
      sellerSnapshotId: string;
    }
  ).sellerSnapshotId;
  const snapshot =
    await api.functional.ecommerceMall.admin.orders.items.seller.snapshots.at(
      adminConnection,
      {
        orderId,
        itemId,
        snapshotId,
      },
    );
  typia.assert(snapshot);
  // Step 6: Validate snapshot preserves original shop name
  // This verifies Section 306: Historical Order Shop Name Retention
  TestValidator.equals(
    "snapshot shopName matches original seller shop name",
    snapshot.shopName,
    originalShopName,
  );
}