export async function test_api_customer_snapshot_preserves_seller_identity_at_purchase(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Admin setup - create category for product
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 2: Seller setup - create product with variant and capture profile
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          stock: 100,
        },
      },
    );
  typia.assert(variant);
  // Capture seller profile at order time
  const sellerProfile =
    await api.functional.ecommerceMall.seller.profile.at(sellerConnection);
  typia.assert(sellerProfile);
  // Step 3: Customer setup - register, add to cart, and checkout
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  await generate_random_ecommerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1,
      },
    },
  );
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(1),
        state: null,
        postalCode: RandomGenerator.alphaNumeric(5),
        country: RandomGenerator.name(1),
      },
    },
  );
  typia.assert(order);
  // Step 4: Query seller profile snapshots for the order item
  const orderItem = order.orderItems[0];
  const snapshots =
    await api.functional.ecommerceMall.customer.orders.items.seller.snapshots.index(
      customerConnection,
      {
        orderId: order.id,
        itemId: (orderItem as IEntity).id,
        body: {},
      },
    );
  typia.assert(snapshots);
  // Step 5: Verify snapshot preserves seller identity exactly as at order time
  TestValidator.predicate(
    "at least one snapshot exists",
    snapshots.data.length > 0,
  );
  const snapshot = snapshots.data[0];
  TestValidator.equals(
    "snapshot shop name matches seller profile at order time",
    snapshot.shopName,
    sellerProfile.shopName ?? "",
  );
  TestValidator.equals(
    "snapshot logo URL matches seller profile at order time",
    snapshot.logoUrl,
    sellerProfile.logoImageUrl,
  );
}