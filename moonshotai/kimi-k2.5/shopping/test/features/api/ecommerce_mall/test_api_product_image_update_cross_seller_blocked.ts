export async function test_api_product_image_update_cross_seller_blocked(
  connection: api.IConnection,
): Promise<void> {
  // Setup: Create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies Partial<IEcommerceMallAdmin.IJoin>,
  });
  typia.assert(admin);
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Seller A: Create product and upload image
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies Partial<IEcommerceMallSeller.IJoin>,
  });
  typia.assert(sellerA);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {
      body: {
        categoryId: category.id,
      } satisfies Partial<IEcommerceMallProduct.ICreate>,
    },
  );
  typia.assert(product);
  const image =
    await generate_random_ecommerce_mall_seller_products_images_create(
      sellerAConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(image);
  // Seller B: Attempt cross-seller image update
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies Partial<IEcommerceMallSeller.IJoin>,
  });
  typia.assert(sellerB);
  // Verify 403 Forbidden error when Seller B tries to update Seller A's image
  await TestValidator.httpError(
    "cross-seller image update blocked with 403",
    403,
    async () => {
      await api.functional.ecommerceMall.seller.products.images.update(
        sellerBConnection,
        {
          productId: product.id,
          imageId: image.id,
          body: {
            displayOrder: 1,
          } satisfies IEcommerceMallProductImage.IUpdate,
        },
      );
    },
  );
}
