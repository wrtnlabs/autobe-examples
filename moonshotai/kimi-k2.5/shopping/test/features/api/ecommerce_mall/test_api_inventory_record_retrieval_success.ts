export async function test_api_inventory_record_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // Step 2: Generate random inventory record ID for retrieval
  const inventoryRecordId = typia.random<string & tags.Format<"uuid">>();
  // Step 3: Retrieve inventory record
  const record = await api.functional.ecommerceMall.seller.inventory_records.at(
    sellerConnection,
    {
      inventoryRecordId,
    },
  );
  // Step 4: Validate response structure
  typia.assert(record);
}
