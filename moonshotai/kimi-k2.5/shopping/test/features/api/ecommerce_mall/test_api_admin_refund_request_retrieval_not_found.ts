export async function test_api_admin_refund_request_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
    },
  });
  // Step 2: Generate a random UUID that doesn't exist in the database
  const nonExistentRefundRequestId = typia.random<
    string & tags.Format<"uuid">
  >();
  // Step 3: Attempt to retrieve the non-existent refund request and expect 404
  await TestValidator.httpError(
    "should return 404 for non-existent refund request",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.refundRequests.at(
        adminConnection,
        {
          refundRequestId: nonExistentRefundRequestId,
        },
      );
    },
  );
}
