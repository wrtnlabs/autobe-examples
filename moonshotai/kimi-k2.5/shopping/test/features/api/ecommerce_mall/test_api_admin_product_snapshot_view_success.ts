export async function test_api_admin_product_snapshot_view_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 3. Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 4. Admin creates category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 5. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  // 6. Seller creates product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  // 7. Customer adds item to cart
  await generate_random_ecommerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1,
      },
    },
  );
  // 8. Customer completes checkout to create order with snapshots
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: "Test Recipient",
        recipientPhone: "01012345678",
        streetAddress: "123 Test Street",
        city: "Test City",
        state: null,
        postalCode: "12345",
        country: "Test Country",
      },
    },
  );
  // 9. Extract orderId, itemId, and snapshotId from the created order
  const orderId = order.id;
  const orderItem = order.orderItems[0] as IEcommerceMallOrderItem.ISummary;
  const itemId = orderItem.id;
  // The snapshotId is retrieved from the order item's product snapshot reference
  const snapshotId = orderItem.product.id;
  // 10. Admin views the product snapshot
  const snapshot =
    await api.functional.ecommerceMall.admin.orders.items.product.snapshots.at(
      adminConnection,
      {
        orderId,
        itemId,
        snapshotId,
      },
    );
  // 11. Validate the snapshot response
  typia.assert(snapshot);
}
