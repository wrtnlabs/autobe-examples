export async function test_api_guest_join_with_full_context(
  connection: api.IConnection,
): Promise<void> {
  // Create a fresh connection for guest session with full context metadata
  const guestConnection: api.IConnection = { host: connection.host };
  const guest = await authorize_guest_join(guestConnection, {
    body: {
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallGuest.IJoin,
  });
  // Validate complete response structure including token metadata
  typia.assert(guest);
}
