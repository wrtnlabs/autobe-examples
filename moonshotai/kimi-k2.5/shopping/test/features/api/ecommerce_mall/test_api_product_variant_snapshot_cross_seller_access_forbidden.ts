/**
 * Test that seller B is forbidden from accessing seller A's variant snapshot.
 * Validates proper authorization isolation between seller accounts.
 */
export async function test_api_product_variant_snapshot_cross_seller_access_forbidden(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Admin authentication and category creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 2: Seller A authentication and resource creation
  const sellerAConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerAConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // Step 3: Seller B authentication (different seller)
  const sellerBConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerBConnection, {});
  // Step 4: Attempt cross-seller access - should return 403 Forbidden
  await TestValidator.httpError(
    "cross-seller variant snapshot access should be forbidden",
    403,
    async () => {
      await api.functional.ecommerceMall.seller.productVariants.snapshots.at(
        sellerBConnection,
        {
          variantId: variant.id,
          snapshotId: typia.random<string & tags.Format<"uuid">>(),
        },
      );
    },
  );
}
