export async function test_api_customer_shipment_delivery_confirm_cross_customer_blocked(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Admin authentication and category creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 2: Seller authentication, product and variant creation
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      } satisfies Partial<IEcommerceMallProduct.ICreate>,
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {},
      },
    );
  typia.assert(variant);
  // Step 3: Customer1 (legitimate owner) authentication and cart addition
  const customer1Connection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customer1Connection, {});
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customer1Connection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        } satisfies Partial<IEcommerceMallCartItem.ICreate>,
      },
    );
  typia.assert(cartItem);
  // Step 4: Customer2 (unauthorized actor) authentication
  const customer2Connection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customer2Connection, {});
  // Step 5: Seller creates shipment for the order
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {},
    },
  );
  typia.assert(shipment);
  // Step 6: Verify cross-customer access is blocked
  await TestValidator.error(
    "cross-customer shipment delivery confirm should be blocked",
    async () => {
      await api.functional.ecommerceMall.customer.shipments.delivery.confirm(
        customer2Connection,
        {
          shipmentId: shipment.id,
        },
      );
    },
  );
}
