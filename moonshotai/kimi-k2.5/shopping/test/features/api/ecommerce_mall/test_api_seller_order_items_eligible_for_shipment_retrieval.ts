export async function test_api_seller_order_items_eligible_for_shipment_retrieval(
  connection: api.IConnection,
): Promise<void> {
  // Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // Retrieve order items eligible for shipment
  const response =
    await api.functional.ecommerceMall.seller.orderItems.eligibleForShipment.index(
      sellerConnection,
      {
        body: {
          status: "paid",
          page: 1,
          limit: 10,
          sort: "created_at",
          order: "desc",
        } satisfies IEcommerceMallOrderItem.IRequest,
      },
    );
  // Validate response structure - typia.assert validates everything including pagination and data array
  typia.assert(response);
}
