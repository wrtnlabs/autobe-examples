export async function test_api_seller_order_access_blocked_for_unapproved_seller(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register as seller (creates account with pending approval status)
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // Verify seller has pending status (unapproved)
  TestValidator.equals(
    "seller approval status is pending",
    seller.approvalStatus,
    "pending",
  );
  // 2. Attempt to access seller orders - should be blocked
  await TestValidator.error(
    "unapproved seller cannot access orders",
    async () => {
      await api.functional.ecommerceMall.seller.orders.index(sellerConnection, {
        body: {} satisfies IEcommerceMallOrder.IRequest,
      });
    },
  );
}
