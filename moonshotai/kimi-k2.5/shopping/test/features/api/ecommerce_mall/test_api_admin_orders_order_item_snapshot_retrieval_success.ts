/**
 * Test admin order item snapshot retrieval workflow.
 * This test validates the audit trail functionality for dispute resolution by:
 * 1. Authenticating as seller and creating product inventory
 * 2. Authenticating as customer and placing an order
 * 3. Authenticating as admin and retrieving the order item snapshot
 * 4. Verifying the immutable snapshot contains product, variant, and seller data
 */
export async function test_api_admin_orders_order_item_snapshot_retrieval_success(
  connection: api.IConnection,
) {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_login(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } as { email: string & tags.Format<"email">; password: string },
  });
  // 2. Seller authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 3. Customer authentication
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 4. Admin retrieves order item snapshot
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const orderItemId = typia.random<string & tags.Format<"uuid">>();
  const snapshot =
    await api.functional.ecommerceMall.admin.orders.items.snapshot.at(
      adminConnection,
      {
        orderId,
        orderItemId,
      },
    );
  typia.assert(snapshot);
  // 5. Verify snapshot structure
  TestValidator.predicate("snapshot has product", snapshot.product !== null);
  TestValidator.predicate("snapshot has variant", snapshot.variant !== null);
  TestValidator.predicate("snapshot has seller", snapshot.seller !== null);
  TestValidator.equals(
    "order item ID matches",
    snapshot.orderItemId,
    orderItemId,
  );
  TestValidator.predicate("snapshot has created date", !!snapshot.createdAt);
}