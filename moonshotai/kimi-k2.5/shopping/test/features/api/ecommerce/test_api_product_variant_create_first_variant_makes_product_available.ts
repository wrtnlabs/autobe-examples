export async function test_api_product_variant_create_first_variant_makes_product_available(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      href: "http://localhost:3000/admin/join",
      referrer: "http://localhost:3000/",
      ip: null,
    },
  });
  // 2. Create seller and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(12),
      href: "http://localhost:3000/seller/join",
      referrer: "http://localhost:3000/",
      ip: null,
    },
  });
  // 3. Create category (admin only)
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
      },
    },
  );
  typia.assert(category);
  // 4. Create product without variants
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
        categoryId: category.id,
        basePrice: 10000,
      },
    },
  );
  typia.assert(product);
  // 5. Verify product initially has no variants (unavailable for purchase)
  TestValidator.equals(
    "product initially has no variants",
    product.variants.length,
    0,
  );
  // 6. Create first variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          skuCode: "SKU-AVAIL-001",
          options: [
            {
              optionName: "color",
              optionValue: "Black",
            } satisfies IEcommerceMallProductVariantOption.ICreate,
          ],
          stock: 50,
        },
      },
    );
  // 7. Validate variant creation and product availability
  typia.assert(variant);
  TestValidator.equals(
    "variant SKU matches input",
    variant.skuCode,
    "SKU-AVAIL-001",
  );
  TestValidator.equals(
    "variant has correct option name",
    variant.optionValues[0].optionName,
    "color",
  );
  TestValidator.equals(
    "variant has correct option value",
    variant.optionValues[0].optionValue,
    "Black",
  );
  TestValidator.equals("variant stock is correct", variant.stockQuantity, 50);
  TestValidator.equals(
    "variant belongs to correct product",
    variant.productId,
    product.id,
  );
}
