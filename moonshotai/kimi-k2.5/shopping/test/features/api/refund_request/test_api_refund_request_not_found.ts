/**
 * Test retrieval of a non-existent refund request returns 404 Not Found error.
 *
 * Flow:
 * 1. Authenticate as a customer
 * 2. Generate a non-existent UUID refund request ID
 * 3. Call refund request at endpoint with non-existent ID
 * 4. Validate 404 HTTP error is returned
 */
export async function test_api_refund_request_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Generate a non-existent UUID for refund request
  const nonExistentRefundRequestId: string = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to retrieve non-existent refund request and expect 404
  await TestValidator.httpError(
    "non-existent refund request returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.refund_requests.at(
        customerConnection,
        {
          refundRequestId: nonExistentRefundRequestId,
        },
      );
    },
  );
}
