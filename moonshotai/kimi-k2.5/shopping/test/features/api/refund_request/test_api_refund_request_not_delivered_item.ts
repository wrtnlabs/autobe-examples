export async function test_api_refund_request_not_delivered_item(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create customer-specific connection for authentication
  const customerConnection: api.IConnection = { host: connection.host };
  // 2. Authenticate as customer using utility function
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 3. Attempt to create refund request for an order item that is not delivered
  // Since we can't easily create a non-delivered order item, we attempt with a random UUID
  // This should fail because either:
  // - The order item doesn't exist, OR
  // - The order item exists but is not in 'delivered' status
  // Both cases should result in a 400/422 error
  await TestValidator.error(
    "should reject refund request for non-delivered order item",
    async () => {
      await api.functional.ecommerceMall.customer.refund_requests.create(
        customerConnection,
        {
          body: {
            orderItemId: typia.random<string & tags.Format<"uuid">>(),
            reason: RandomGenerator.paragraph({ sentences: 2 }),
          } satisfies IEcommerceMallRefundRequest.ICreate,
        },
      );
    },
  );
}
