/**
 * Test successful retrieval of a pending refund request by the authenticated seller.
 * 1. Authenticate as a seller using authorize_seller_join utility
 * 2. Retrieve a refund request by ID
 * 3. Validate the response structure matches IEcommerceMallRefundRequest
 */
export async function test_api_seller_refund_request_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a seller
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: "https://test.com/register",
      referrer: "https://test.com",
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. Retrieve a refund request
  const refundRequestId = typia.random<string & tags.Format<"uuid">>();
  const refundRequest =
    await api.functional.ecommerceMall.seller.refund_requests.at(
      sellerConnection,
      { refundRequestId },
    );
  // 3. Validate the response
  typia.assert(refundRequest);
}
