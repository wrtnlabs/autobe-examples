export async function test_api_seller_refund_request_retrieval_resolved_status(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  typia.assert(seller);
  // 2. Retrieve refund request (simulation generates random data including resolved status)
  const refundRequestId: string = typia.random<string & tags.Format<"uuid">>();
  const response: IEcommerceMallRefundRequest =
    await api.functional.ecommerceMall.seller.refund_requests.at(
      sellerConnection,
      {
        refundRequestId,
      },
    );
  typia.assert(response);
  // 3. Validate resolved status specific fields
  if (response.status === "approved" || response.status === "rejected") {
    TestValidator.predicate(
      "respondedAt is populated for resolved request",
      response.respondedAt !== null,
    );
    TestValidator.predicate(
      "snapshots exist for resolved request",
      response.snapshots.length > 0,
    );
    // Check that at least one snapshot has the response reason
    const hasResponseReason = response.snapshots.some(
      (snapshot) =>
        snapshot.status === response.status && snapshot.responseReason !== null,
    );
    TestValidator.predicate(
      "at least one snapshot contains response reason",
      hasResponseReason,
    );
  }
}
