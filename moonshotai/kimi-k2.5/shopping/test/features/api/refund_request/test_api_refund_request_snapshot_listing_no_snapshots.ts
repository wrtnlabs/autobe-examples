/**
 * Tests viewing a refund request that has no snapshots yet because the seller has not responded.
 *
 * This scenario validates that when a refund request is created by a customer with 'pending' status,
 * the seller can query the snapshots endpoint and receive an empty list with correct pagination metadata.
 * Snapshots are only created when the seller responds to the refund request.
 */
export async function test_api_refund_request_snapshot_listing_no_snapshots(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup: Create admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(admin);
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      },
    },
  );
  typia.assert(category);
  // 2. Setup: Create seller and product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(seller);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: 10000,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          options: [
            {
              optionName: "Color",
              optionValue: RandomGenerator.pick(["Red", "Blue", "Green"]),
            },
          ],
          price: 10000,
          stock: 100,
        },
        params: { productId: product.id },
      },
    );
  typia.assert(variant);
  // 3. Setup: Create customer, add to cart, checkout
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(customer);
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: null,
        postalCode: RandomGenerator.alphaNumeric(6),
        country: RandomGenerator.pick(["Korea", "USA", "Japan"]),
      },
    },
  );
  typia.assert(order);
  // 4. Setup: Get the order item for the shipped product
  const orderItem = order.orderItems[0] as IEcommerceMallOrderItem.ISummary;
  typia.assertGuard(orderItem);
  // 5. Setup: Seller creates shipment for the order item
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        orderItemIds: [orderItem.id],
        carrierName: RandomGenerator.pick(["FedEx", "UPS", "DHL"]),
        trackingNumber: RandomGenerator.alphaNumeric(20),
      },
    },
  );
  typia.assert(shipment);
  // 6. Setup: Customer confirms delivery
  const delivery =
    await api.functional.ecommerceMall.customer.shipments.delivery.confirm.confirmDelivery(
      customerConnection,
      {
        shipmentId: shipment.id,
      },
    );
  typia.assert(delivery);
  // 7. Setup: Customer creates refund request (without seller response)
  const refundRequest =
    await generate_random_ecommerce_mall_customer_refund_requests_create(
      customerConnection,
      {
        body: {
          orderItemId: orderItem.id,
          reason: RandomGenerator.paragraph({ sentences: 2 }),
        },
      },
    );
  typia.assert(refundRequest);
  // 8. Test: Seller queries snapshots for the refund request (should have none)
  const snapshotsPage =
    await api.functional.ecommerceMall.seller.refundRequests.snapshots.index(
      sellerConnection,
      {
        refundRequestId: refundRequest.id,
        body: {},
      },
    );
  typia.assert(snapshotsPage);
  // 9. Validation: Verify empty snapshots list
  TestValidator.equals(
    "snapshots data array is empty",
    snapshotsPage.data.length,
    0,
  );
  TestValidator.equals(
    "pagination records is 0",
    snapshotsPage.pagination.records,
    0,
  );
  TestValidator.equals(
    "pagination pages is 0",
    snapshotsPage.pagination.pages,
    0,
  );
  TestValidator.equals(
    "pagination current is 0",
    snapshotsPage.pagination.current,
    0,
  );
}
