/**
 * Test successful retrieval of a customer's own refund request.
 *
 * Validates that a customer can retrieve complete details of their refund request
 * including order item information, reason, status, seller response, and audit timestamps.
 */
export async function test_api_refund_request_retrieve_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create customer connection and authenticate
  const customerConnection: api.IConnection = {
    host: connection.host,
  };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // Step 2: Generate a refund request ID for retrieval
  const refundRequestId = typia.random<string & tags.Format<"uuid">>();
  // Step 3: Retrieve the refund request by ID
  const refundRequest =
    await api.functional.ecommerceMall.customer.refund_requests.at(
      customerConnection,
      {
        refundRequestId,
      },
    );
  // Step 4: Validate the response structure using typia
  // This validates all DTO constraints: UUID formats, enum values, ISO timestamps,
  // nested object structures, and required properties
  typia.assert(refundRequest);
}
