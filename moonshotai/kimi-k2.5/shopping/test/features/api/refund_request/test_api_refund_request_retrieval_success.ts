export async function test_api_refund_request_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Step 2: Generate a random refund request ID
  const refundRequestId = typia.random<string & tags.Format<"uuid">>();
  // Step 3: Retrieve the refund request as admin
  const refundRequest =
    await api.functional.ecommerceMall.admin.refund_requests.at(
      adminConnection,
      { refundRequestId },
    );
  // Step 4: Validate the response structure
  typia.assert(refundRequest);
}
