import { authorize_admin_join } from "../../../authorize/authorize_admin_join";
import { authorize_admin_login } from "../../../authorize/authorize_admin_login";
import { authorize_admin_refresh } from "../../../authorize/authorize_admin_refresh";

export async function test_api_admin_refund_request_listing_basic_query(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // Call PATCH /ecommerceMall/admin/refundRequests with empty filters (default pagination)
  const response =
    await api.functional.ecommerceMall.admin.refundRequests.index(
      adminConnection,
      {
        body: {} satisfies IEcommerceMallRefundRequest.IRequest,
      },
    );
  // Verify response contains IPageIEcommerceMallRefundRequest.ISummary structure
  typia.assert(response);
  // Validate pagination metadata includes current page, limit, total records, and total pages
  TestValidator.predicate(
    "pagination current is non-negative",
    response.pagination.current >= 0,
  );
  TestValidator.predicate(
    "pagination limit is positive",
    response.pagination.limit > 0,
  );
  TestValidator.predicate(
    "pagination records is non-negative",
    response.pagination.records >= 0,
  );
  TestValidator.predicate(
    "pagination pages is non-negative",
    response.pagination.pages >= 0,
  );
  // Verify data array exists
  TestValidator.predicate("data is an array", Array.isArray(response.data));
  // If no refund requests exist, verify empty data array with proper pagination
  if (response.pagination.records === 0) {
    TestValidator.equals(
      "data array empty when no records",
      response.data.length,
      0,
    );
  }
}
