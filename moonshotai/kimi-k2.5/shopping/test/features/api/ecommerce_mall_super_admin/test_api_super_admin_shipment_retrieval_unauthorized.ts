export async function test_api_super_admin_shipment_retrieval_unauthorized(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as superAdmin to create a shipment
  const superAdminConnection: api.IConnection = { host: connection.host };
  const superAdminAuth = await authorize_super_admin_join(
    superAdminConnection,
    {
      body: {
        email: typia.random<string & tags.Format<"email">>(),
        password: RandomGenerator.alphaNumeric(16),
      },
    },
  );
  typia.assert(superAdminAuth);
  // 2. Create a shipment to get valid shipmentId
  const shipment =
    await generate_random_ecommerce_mall_super_admin_shipments_create(
      superAdminConnection,
      {},
    );
  typia.assert(shipment);
  // 3. Authenticate as regular admin
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  typia.assert(adminAuth);
  // 4. Attempt to retrieve shipment with admin connection - should fail with authorization error
  await TestValidator.error(
    "admin should not access superAdmin shipment endpoint",
    async () => {
      await api.functional.ecommerceMall.superAdmin.shipments.at(
        adminConnection,
        {
          shipmentId: shipment.id,
        },
      );
    },
  );
}
