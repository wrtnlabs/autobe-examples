export async function test_api_shipment_admin_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin-specific connection
  const adminConnection: api.IConnection = { host: connection.host };
  // 2. Authenticate as admin
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 3. Generate non-existent shipment ID
  const nonExistentShipmentId = typia.random<string & tags.Format<"uuid">>();
  // 4. Attempt to fetch non-existent shipment and expect 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent shipment",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.shipments.at(adminConnection, {
        shipmentId: nonExistentShipmentId,
      });
    },
  );
}
