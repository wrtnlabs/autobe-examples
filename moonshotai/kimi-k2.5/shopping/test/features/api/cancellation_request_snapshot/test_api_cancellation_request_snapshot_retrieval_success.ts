export async function test_api_cancellation_request_snapshot_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  /**
   * Test successful retrieval of paginated cancellation request snapshots as a seller.
   * This validates the primary success path where a seller views the complete audit
   * trail of state changes for a cancellation request.
   */
  // 1. Create and authenticate seller connection
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // 2. Create and authenticate customer connection
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // 3. Create product as seller
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  typia.assert(product);
  // 4. Create variant as seller
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 5. Create cart item as customer to establish order context
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 6. Create cancellation request as customer (generates initial snapshot)
  const cancellationRequest =
    await generate_random_ecommerce_mall_customer_cancellation_requests_create(
      customerConnection,
      {},
    );
  typia.assert(cancellationRequest);
  // 7. Seller retrieves snapshots for the cancellation request
  const snapshotsPage =
    await api.functional.ecommerceMall.seller.cancellation_requests.snapshots.index(
      sellerConnection,
      {
        cancellationRequestId: cancellationRequest.id,
        body: {
          page: 1,
          limit: 20,
          createdAtFrom: null,
          createdAtTo: null,
          statusBefore: null,
          statusAfter: null,
          sortField: "created_at",
          sortOrder: "desc",
        },
      },
    );
  typia.assert(snapshotsPage);
}
