export async function test_api_product_variant_option_successful_deletion(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuth = await authorize_admin_join(adminConnection, {});
  typia.assert(adminAuth);
  // Step 2: Create product category (requires admin authentication)
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    { body: {} },
  );
  typia.assert(category);
  // Step 3: Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {});
  typia.assert(sellerAuth);
  // Step 4: Create product owned by authenticated seller
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // Step 5: Create product variant under the product
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        body: {},
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // Step 6: Create product variant option that will be deleted
  const option =
    await generate_random_ecommerce_mall_seller_products_variants_options_create(
      sellerConnection,
      {
        body: {},
        params: {
          productId: product.id,
          productVariantId: variant.id,
        },
      },
    );
  typia.assert(option);
  // Step 7: Delete the variant option (target endpoint)
  // The erase endpoint returns void on successful deletion
  // Successful execution without throwing error confirms deletion was processed
  await api.functional.ecommerceMall.seller.products.variants.options.erase(
    sellerConnection,
    {
      productId: product.id,
      productVariantId: variant.id,
      productVariantOptionId: option.id,
    },
  );
}
