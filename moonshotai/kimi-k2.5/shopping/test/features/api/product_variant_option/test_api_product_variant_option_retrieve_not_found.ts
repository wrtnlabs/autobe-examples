export async function test_api_product_variant_option_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates a category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller creates a product
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({
          sentences: 2,
          wordMin: 2,
          wordMax: 5,
        }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<100> & tags.Maximum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create a product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          price: typia.random<
            number &
              tags.Type<"uint32"> &
              tags.Minimum<100> &
              tags.Maximum<2000>
          >(),
          options: [
            {
              optionName: RandomGenerator.name(1),
              optionValue: RandomGenerator.name(1),
            } satisfies IEcommerceMallProductVariantOption.ICreate,
          ],
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Create an option to establish the option collection exists
  const option =
    await generate_random_ecommerce_mall_seller_products_variants_options_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
          productVariantId: variant.id,
        },
        body: {
          optionName: RandomGenerator.name(1),
          optionValue: RandomGenerator.name(1),
        } satisfies IEcommerceMallProductVariantOption.ICreate,
      },
    );
  typia.assert(option);
  // 5. Test retrieving a non-existent option (random UUID guaranteed not to exist)
  const nonExistentOptionId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.httpError(
    "non-existent product variant option returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.products.variants.options.at(
        sellerConnection,
        {
          productId: product.id,
          productVariantId: variant.id,
          productVariantOptionId: nonExistentOptionId,
        },
      );
    },
  );
}
