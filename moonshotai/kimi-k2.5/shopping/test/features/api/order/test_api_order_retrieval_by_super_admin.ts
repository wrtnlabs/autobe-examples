export async function test_api_order_retrieval_by_super_admin(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Authenticate as superAdmin
  const superAdminConnection: api.IConnection = { host: connection.host };
  await authorize_super_admin_join(superAdminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // Step 2: Create customer account for prerequisite data
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    },
  });
  // Step 3: Retrieve order as superAdmin
  // Note: In a complete flow, an order would be created first via customer checkout APIs
  const orderId = typia.random<string & tags.Format<"uuid">>();
  const order = await api.functional.ecommerceMall.superAdmin.orders.at(
    superAdminConnection,
    { orderId },
  );
  // Step 4: Validate response structure
  // typia.assert performs complete validation of IEcommerceMallOrder including all properties,
  // nested entities (customer, orderItems, shipments), timestamps, and shipping address
  typia.assert(order);
}
