/**
 * Test that an authenticated administrator can successfully retrieve detailed information about a specific order.
 *
 * 1. Admin authentication: Create a dedicated admin connection and authenticate using join endpoint.
 * 2. Order retrieval: Call the admin order detail endpoint with a valid order ID.
 * 3. Response validation: Verify the response contains complete order information including order items,
 *    shipments, customer info, and fulfillment status using typia.assert.
 */
export async function test_api_admin_order_detail_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin-specific connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    },
  });
  // 2. Retrieve order details as admin
  const order = await api.functional.ecommerceMall.admin.orders.at(
    adminConnection,
    {
      orderId: typia.random<string & tags.Format<"uuid">>(),
    },
  );
  // 3. Validate response structure
  typia.assert(order);
}
