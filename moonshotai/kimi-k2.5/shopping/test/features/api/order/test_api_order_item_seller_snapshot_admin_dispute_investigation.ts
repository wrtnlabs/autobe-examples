export async function test_api_order_item_seller_snapshot_admin_dispute_investigation(
  connection: api.IConnection,
): Promise<void> {
  // Create actor-specific connections
  const adminConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  const customerConnection: api.IConnection = { host: connection.host };
  // 1. Admin joins
  await authorize_admin_join(adminConnection, {});
  // 2. Seller joins and submits registration
  await authorize_seller_join(sellerConnection, {});
  const registration =
    await generate_random_ecommerce_mall_seller_registrations_create(
      sellerConnection,
      {},
    );
  // 3. Admin approves seller
  await api.functional.ecommerceMall.admin.sellers.registrations.review(
    adminConnection,
    {
      registrationId: typia.assert<IEntity>(registration).id,
      body: {
        status: "approved",
        rejection_reason: null,
      } satisfies IEcommerceMallSellerRegistration.IReview,
    },
  );
  // 4. Customer joins
  await authorize_customer_join(customerConnection, {});
  // 5. Seller creates product, variant, and adds inventory
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {},
  );
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
      },
    );
  await generate_random_ecommerce_mall_seller_variants_inventory_create(
    sellerConnection,
    {
      params: { variantId: variant.id },
      body: {
        quantity: 100,
        reason: "Initial stock for dispute test",
      } satisfies IEcommerceMallInventoryRecord.ICreate,
    },
  );
  // 6. Customer adds item to cart
  await generate_random_ecommerce_mall_customer_cart_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1,
      } satisfies IEcommerceMallCartItem.ICreate,
    },
  );
  // 7. Customer checkout to create order with seller snapshots
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: "Test Customer",
        recipientPhone: "01012345678",
        streetAddress: "123 Test Avenue",
        city: "Seoul",
        state: null,
        postalCode: "04536",
        country: "South Korea",
      } satisfies IEcommerceMallOrder.ICreate,
    },
  );
  typia.assert(order);
  // Verify order has items
  TestValidator.predicate("order has items", order.orderItems.length > 0);
  const orderItem = order.orderItems[0];
  // 8. Admin retrieves seller profile snapshots for dispute investigation
  const snapshotsPage =
    await api.functional.ecommerceMall.admin.orders.items.seller.snapshots.index(
      adminConnection,
      {
        orderId: order.id,
        itemId: typia.assert<IEntity>(orderItem).id,
        body: {} satisfies IEcommerceMallOrderItemSellerSnapshot.IRequest,
      },
    );
  typia.assert(snapshotsPage);
  // Validate historical seller data preservation
  TestValidator.predicate("snapshots exist", snapshotsPage.data.length > 0);
  const snapshot = snapshotsPage.data[0];
  TestValidator.equals(
    "snapshot shopName exists",
    typeof snapshot.shopName,
    "string",
  );
  TestValidator.predicate(
    "snapshot createdAt exists",
    snapshot.createdAt !== null && snapshot.createdAt !== undefined,
  );
}