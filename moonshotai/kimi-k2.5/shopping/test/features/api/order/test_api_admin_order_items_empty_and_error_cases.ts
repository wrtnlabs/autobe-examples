export async function test_api_admin_order_items_empty_and_error_cases(
  connection: api.IConnection,
): Promise<void> {
  // 1. Setup: Create actor-specific connections (base connection isolation pattern)
  const adminConnection: api.IConnection = { host: connection.host };
  const sellerConnection: api.IConnection = { host: connection.host };
  const customerConnection: api.IConnection = { host: connection.host };
  // 2. Register actors using utility functions
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  // 3. Create category as admin
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
      },
    },
  );
  // 4. Create product as seller
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: 10000,
      },
    },
  );
  // 5. Create variant as seller
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: RandomGenerator.alphaNumeric(8).toUpperCase(),
          options: [
            { optionName: "Color", optionValue: "Red" },
            { optionName: "Size", optionValue: "Large" },
          ],
          price: 15000,
          stock: 100,
        },
      },
    );
  // 6. Add item to cart as customer
  await generate_random_ecommerce_mall_customer_cart_items_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 2,
      },
    },
  );
  // 7. Checkout to create order
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: RandomGenerator.name(),
        recipientPhone: RandomGenerator.mobile(),
        streetAddress: RandomGenerator.paragraph({ sentences: 1 }),
        city: RandomGenerator.name(),
        state: RandomGenerator.name(),
        postalCode: RandomGenerator.alphaNumeric(5),
        country: "US",
      },
    },
  );
  typia.assert(order);
  // 8. Test: Query order items with filter returning no matches (refunded status)
  // Order items are created with "paid" status, so filtering by "refunded" returns empty
  const emptyResult =
    await api.functional.ecommerceMall.admin.orders.items.index(
      adminConnection,
      {
        orderId: order.id,
        body: {
          status: "refunded",
          page: 1,
          limit: 10,
        },
      },
    );
  typia.assert(emptyResult);
  // Verify empty pagination structure maintains IPageIEcommerceMallOrderItem.ISummary format
  TestValidator.equals(
    "empty result pagination records",
    emptyResult.pagination.records,
    0,
  );
  TestValidator.equals(
    "empty result pagination pages",
    emptyResult.pagination.pages,
    0,
  );
  TestValidator.equals(
    "empty result data array length",
    emptyResult.data.length,
    0,
  );
  TestValidator.predicate(
    "empty result data is array",
    Array.isArray(emptyResult.data),
  );
  // 9. Test: Query with valid status should return results
  const paidResult =
    await api.functional.ecommerceMall.admin.orders.items.index(
      adminConnection,
      {
        orderId: order.id,
        body: {
          status: "paid",
          page: 1,
          limit: 10,
        },
      },
    );
  typia.assert(paidResult);
  TestValidator.predicate("paid result has items", paidResult.data.length > 0);
  TestValidator.equals(
    "paid result pagination records matches data length",
    paidResult.pagination.records,
    paidResult.data.length,
  );
  // 10. Test: Query with non-existent order ID should return 404 error
  const nonExistentOrderId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error("non-existent order returns 404", async () => {
    await api.functional.ecommerceMall.admin.orders.items.index(
      adminConnection,
      {
        orderId: nonExistentOrderId,
        body: {
          page: 1,
          limit: 10,
        },
      },
    );
  });
}
