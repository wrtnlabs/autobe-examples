export async function test_api_order_item_seller_snapshot_customer_view(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  typia.assert(admin);
  // 2. Create seller
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      href: "https://test.ecommerceMall.com/seller/join",
      referrer: "https://test.ecommerceMall.com",
      ip: "127.0.0.1",
    },
  });
  typia.assert(seller);
  // 3. Admin creates category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 4. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 5. Seller creates product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          stock: 100,
        },
      },
    );
  typia.assert(variant);
  // 6. Create customer
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 7. Customer adds product to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // 8. Customer checks out
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: "Test Customer",
        recipientPhone: "010-1234-5678",
        streetAddress: "123 Test Street",
        city: "Seoul",
        state: null,
        postalCode: "12345",
        country: "South Korea",
      },
    },
  );
  typia.assert(order);
  // 9. Verify order has items
  TestValidator.predicate(
    "order should have items",
    order.orderItems.length > 0,
  );
  // 10. Get first order item and its seller snapshot
  const orderItem = order.orderItems[0] as IEcommerceMallOrderItem.ISummary;
  typia.assert(orderItem);
  // Extract seller snapshot ID from order item (using seller ID as snapshot ID for test)
  const snapshotId = orderItem.seller.id;
  // 11. Retrieve seller snapshot for the order item
  const snapshot =
    await api.functional.ecommerceMall.customer.orders.items.seller.snapshots.at(
      customerConnection,
      {
        orderId: order.id,
        itemId: orderItem.id,
        snapshotId: snapshotId,
      },
    );
  typia.assert(snapshot);
  // 12. Verify snapshot structure
  TestValidator.equals("snapshot id matches", snapshot.id, snapshotId);
  TestValidator.equals(
    "snapshot shopName matches order item seller",
    snapshot.shopName,
    orderItem.seller.shopName,
  );
}
