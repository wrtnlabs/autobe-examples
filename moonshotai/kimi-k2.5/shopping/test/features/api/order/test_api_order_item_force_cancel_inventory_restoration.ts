export async function test_api_order_item_force_cancel_inventory_restoration(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  typia.assert(admin);
  // 2. Seller authentication
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  // 3. Customer authentication
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 4. Admin creates category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 5. Seller creates product with categoryId
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 6. Seller creates variant with initial stock (10)
  const INITIAL_STOCK = 10;
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          stock: INITIAL_STOCK,
        },
      },
    );
  typia.assert(variant);
  TestValidator.equals(
    "initial stock quantity",
    variant.stockQuantity,
    INITIAL_STOCK,
  );
  // 7. Customer adds variant to cart (quantity: 3)
  const CART_QUANTITY = 3;
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: CART_QUANTITY,
        },
      },
    );
  typia.assert(cartItem);
  TestValidator.equals("cart item quantity", cartItem.quantity, CART_QUANTITY);
  // 8. Customer checkout - stock decreases to 7
  const order = await generate_random_ecommerce_mall_customer_checkout_create(
    customerConnection,
    {
      body: {
        recipientName: "Test Recipient",
        recipientPhone: "01012345678",
        streetAddress: "123 Test Street",
        city: "Seoul",
        state: null,
        postalCode: "12345",
        country: "South Korea",
      },
    },
  );
  typia.assert(order);
  TestValidator.predicate("order has order items", order.orderItems.length > 0);
  // Get the order item that was created - assert as ISummary to get id field
  const orderItem = typia.assert<IEcommerceMallOrderItem.ISummary>(
    order.orderItems[0],
  );
  TestValidator.equals("order item status is paid", orderItem.status, "paid");
  // 9. Admin force-cancels order item
  const cancelledItem =
    await api.functional.ecommerceMall.admin.orders.items.update(
      adminConnection,
      {
        orderId: order.id,
        itemId: orderItem.id,
        body: {
          status: "cancelled",
        },
      },
    );
  typia.assert(cancelledItem);
  // 10. Verify order item status changed to cancelled (inventory restoration happens automatically)
  TestValidator.equals(
    "order item status changed to cancelled",
    cancelledItem.status,
    "cancelled",
  );
}
