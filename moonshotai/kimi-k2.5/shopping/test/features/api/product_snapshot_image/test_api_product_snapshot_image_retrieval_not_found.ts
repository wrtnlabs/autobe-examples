export async function test_api_product_snapshot_image_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Authenticate as seller to access the endpoint
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  // Use random UUIDs that don't correspond to any real snapshot/image
  const nonExistentSnapshotId = typia.random<string & tags.Format<"uuid">>();
  const nonExistentImageId = typia.random<string & tags.Format<"uuid">>();
  // Test that retrieving a non-existent snapshot image returns 404
  await TestValidator.error(
    "non-existent snapshot image should return 404 error",
    async () => {
      await api.functional.ecommerceMall.seller.productSnapshots.images.at(
        sellerConnection,
        {
          snapshotId: nonExistentSnapshotId,
          imageId: nonExistentImageId,
        },
      );
    },
  );
}
