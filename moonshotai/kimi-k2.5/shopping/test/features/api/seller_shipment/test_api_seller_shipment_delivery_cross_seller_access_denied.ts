export async function test_api_seller_shipment_delivery_cross_seller_access_denied(
  connection: api.IConnection,
): Promise<void> {
  // Step 1: Setup Seller A (legitimate owner)
  const sellerAConnection: api.IConnection = { host: connection.host };
  const sellerA = await authorize_seller_join(sellerAConnection, {});
  typia.assert(sellerA);
  // Step 2: Setup Admin for category creation
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {});
  typia.assert(admin);
  // Step 3: Admin creates product category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Step 4: Seller A creates product in the category
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerAConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // Step 5: Seller A creates product variant (SKU)
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerAConnection,
      {
        params: { productId: product.id },
        body: {
          options: [{ optionName: "Color", optionValue: "Blue" }],
        },
      },
    );
  typia.assert(variant);
  // Step 6: Setup Customer to place order
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // Step 7: Customer adds variant to cart (order prerequisite)
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 1,
        },
      },
    );
  typia.assert(cartItem);
  // Step 8: Setup Seller B (unauthorized actor attempting cross-seller access)
  const sellerBConnection: api.IConnection = { host: connection.host };
  const sellerB = await authorize_seller_join(sellerBConnection, {});
  typia.assert(sellerB);
  // Step 9: Attempt cross-seller access using valid UUID format
  // Since order/shipment creation utilities are unavailable, we use a valid UUID
  // representing a shipment that would belong to Seller A
  const sellerAShipmentId = typia.random<string & tags.Format<"uuid">>();
  // Seller B attempts to access Seller A's shipment delivery details
  await TestValidator.httpError(
    "seller B cannot access seller A's shipment delivery",
    [403, 404],
    async () => {
      await api.functional.ecommerceMall.seller.shipments.delivery.at(
        sellerBConnection,
        { shipmentId: sellerAShipmentId },
      );
    },
  );
}
