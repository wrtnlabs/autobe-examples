export async function test_api_cart_quantity_access_boundary_rejection(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - for seller approval and category creation
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  // 2. Seller setup - for product creation
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {});
  // 3. Admin approves seller
  await api.functional.ecommerceMall.admin.sellers.registrations.review(
    adminConnection,
    {
      registrationId: sellerAuthorized.id,
      body: {
        status: "approved",
        rejection_reason: null,
      } satisfies IEcommerceMallSellerRegistration.IReview,
    },
  );
  // 4. Create category using admin
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 5. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      } satisfies Partial<IEcommerceMallProduct.ICreate>,
    },
  );
  // 6. Seller creates variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  // 7. First customer joins and adds item to cart
  const customer1Connection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customer1Connection, {});
  const cartItem = await generate_random_ecommerce_mall_customer_cart_create(
    customer1Connection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1,
      } satisfies Partial<IEcommerceMallCartItem.ICreate>,
    },
  );
  // 8. Second customer joins
  const customer2Connection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customer2Connection, {});
  // 9. Second customer attempts to update first customer's cart item - should fail with 403
  await TestValidator.httpError(
    "second customer cannot modify first customer's cart item",
    403,
    async () => {
      await api.functional.ecommerceMall.customer.cart.update(
        customer2Connection,
        {
          cartItemId: cartItem.id,
          body: {
            quantity: 5,
          } satisfies IEcommerceMallCartItem.IUpdate,
        },
      );
    },
  );
}
