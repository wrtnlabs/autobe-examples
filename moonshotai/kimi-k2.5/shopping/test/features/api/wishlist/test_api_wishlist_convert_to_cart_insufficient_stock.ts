export async function test_api_wishlist_convert_to_cart_insufficient_stock(
  connection: api.IConnection,
): Promise<void> {
  const LIMITED_STOCK = 5;
  const EXCESSIVE_QUANTITY = 10;
  // 1. Admin creates category
  const adminConnection: IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller creates product
  const sellerConnection: IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 3 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<1000>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: `SKU-${RandomGenerator.alphaNumeric(8)}`,
          options: [
            {
              optionName: "Color",
              optionValue: "Red",
            } satisfies IEcommerceMallProductVariantOption.ICreate,
          ],
          price: null,
          stock: 0,
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Add limited inventory (5 units)
  const inventory =
    await generate_random_ecommerce_mall_seller_variants_inventory_create(
      sellerConnection,
      {
        params: { variantId: variant.id },
        body: {
          quantity: LIMITED_STOCK,
          reason: "Initial stock",
        } satisfies IEcommerceMallInventoryRecord.ICreate,
      },
    );
  typia.assert(inventory);
  TestValidator.equals(
    "inventory quantity added",
    inventory.quantityChange,
    LIMITED_STOCK,
  );
  // 5. Customer setup and add to wishlist
  const customerConnection: IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // 6. Test: excessive quantity should fail with 422
  await TestValidator.httpError(
    "should return 422 when quantity exceeds available stock",
    422,
    async () => {
      await api.functional.ecommerceMall.customer.wishlist.convert_to_cart.convertToCart(
        customerConnection,
        {
          body: {
            wishlistItemId: wishlistItem.id,
            variantId: variant.id,
            quantity: EXCESSIVE_QUANTITY,
          } satisfies IEcommerceMallWishlistItem.IConvertToCart,
        },
      );
    },
  );
  // 7. Test: exact stock boundary should succeed
  const cartItem =
    await api.functional.ecommerceMall.customer.wishlist.convert_to_cart.convertToCart(
      customerConnection,
      {
        body: {
          wishlistItemId: wishlistItem.id,
          variantId: variant.id,
          quantity: LIMITED_STOCK,
        } satisfies IEcommerceMallWishlistItem.IConvertToCart,
      },
    );
  typia.assert(cartItem);
  TestValidator.equals(
    "cart quantity matches",
    cartItem.quantity,
    LIMITED_STOCK,
  );
  TestValidator.equals(
    "cart variant matches",
    cartItem.productVariant.id,
    variant.id,
  );
  TestValidator.equals("cart product matches", cartItem.product.id, product.id);
}
