export async function test_api_wishlist_item_unavailable_product_indication(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product that will become unavailable
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerCreds = {
    email: typia.random<string & tags.Format<"email">>(),
    password: RandomGenerator.alphaNumeric(16),
    href: typia.random<string & tags.Format<"uri">>(),
    referrer: typia.random<string & tags.Format<"uri">>(),
    ip: null,
  } satisfies IEcommerceMallSeller.IJoin;
  await authorize_seller_join(sellerConnection, { body: sellerCreds });
  // Re-login for approved status if needed (depending on business rules)
  await authorize_seller_login(sellerConnection, {
    body: {
      email: sellerCreds.email,
      password: sellerCreds.password,
    } satisfies IEcommerceMallSeller.ILogin,
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<100>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Customer setup - add product to wishlist
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_items_create(
      customerConnection,
      {
        body: {
          product_id: product.id,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // 4. Make product unavailable - seller deletes it
  await api.functional.ecommerceMall.seller.products.erase(sellerConnection, {
    productId: product.id,
  });
  // 5. Customer retrieves wishlist item and verifies unavailable status
  const retrievedWishlistItem =
    await api.functional.ecommerceMall.customer.wishlist_items.at(
      customerConnection,
      {
        wishlistItemId: wishlistItem.id,
      },
    );
  typia.assert(retrievedWishlistItem);
  // 6. Verify that the wishlist item exists and product shows as unavailable
  TestValidator.equals(
    "wishlist item id matches",
    retrievedWishlistItem.id,
    wishlistItem.id,
  );
  TestValidator.equals(
    "product id matches",
    retrievedWishlistItem.product.id,
    product.id,
  );
  TestValidator.equals(
    "product availability status is unavailable",
    retrievedWishlistItem.product.availabilityStatus,
    "unavailable",
  );
}
