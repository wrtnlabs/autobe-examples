export async function test_api_wishlist_cross_customer_access_blocked(
  connection: api.IConnection,
): Promise<void> {
  // 1. Customer A setup - joins and authenticates
  const customerAConnection: api.IConnection = { host: connection.host };
  const customerAEmail = typia.random<string & tags.Format<"email">>();
  const customerAPassword = RandomGenerator.alphaNumeric(16);
  await authorize_customer_join(customerAConnection, {
    body: {
      email: customerAEmail,
      password: customerAPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Admin setup - joins, authenticates, and creates category
  const adminConnection: api.IConnection = { host: connection.host };
  const adminEmail = typia.random<string & tags.Format<"email">>();
  const adminPassword = RandomGenerator.alphaNumeric(16);
  await authorize_admin_join(adminConnection, {
    body: {
      email: adminEmail,
      password: adminPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 3. Seller setup - joins, authenticates, and creates product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<
          number & tags.Type<"uint32"> & tags.Minimum<100>
        >(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 4. Customer A adds product to wishlist
  const wishlistItem =
    await generate_random_ecommerce_mall_customer_wishlist_items_create(
      customerAConnection,
      {
        body: {
          product_id: product.id,
        } satisfies IEcommerceMallWishlistItem.ICreate,
      },
    );
  typia.assert(wishlistItem);
  // Verify Customer A can access their own wishlist item
  const customerAOwnItem =
    await api.functional.ecommerceMall.customer.wishlist_items.at(
      customerAConnection,
      { wishlistItemId: wishlistItem.id },
    );
  typia.assert(customerAOwnItem);
  TestValidator.equals(
    "wishlist item belongs to customer A",
    customerAOwnItem.id,
    wishlistItem.id,
  );
  TestValidator.equals(
    "wishlist item product matches",
    customerAOwnItem.productId,
    product.id,
  );
  // 5. Customer B setup - joins and authenticates
  const customerBConnection: api.IConnection = { host: connection.host };
  const customerBEmail = typia.random<string & tags.Format<"email">>();
  const customerBPassword = RandomGenerator.alphaNumeric(16);
  await authorize_customer_join(customerBConnection, {
    body: {
      email: customerBEmail,
      password: customerBPassword,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 6. Customer B attempts to access Customer A's wishlist item - should fail
  await TestValidator.httpError(
    "cross-customer wishlist access should be blocked with 403 or 404",
    [403, 404],
    async () => {
      await api.functional.ecommerceMall.customer.wishlist_items.at(
        customerBConnection,
        { wishlistItemId: wishlistItem.id },
      );
    },
  );
}
