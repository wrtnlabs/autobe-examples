export async function test_api_wishlist_item_product_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Register and authenticate as a customer
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // 2. Attempt to add a non-existent product to wishlist
  const nonExistentProductId = typia.random<string & tags.Format<"uuid">>();
  // 3. Validate that the request is rejected with 404 error
  await TestValidator.error(
    "adding non-existent product to wishlist should throw error",
    async () => {
      await api.functional.ecommerceMall.customer.wishlist.create(
        customerConnection,
        {
          body: {
            product_id: nonExistentProductId,
          } satisfies IEcommerceMallWishlistItem.ICreate,
        },
      );
    },
  );
}
