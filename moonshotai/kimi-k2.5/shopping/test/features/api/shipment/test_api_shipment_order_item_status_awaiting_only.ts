export async function test_api_shipment_order_item_status_awaiting_only(
  connection: api.IConnection,
): Promise<void> {
  // Note: The scenario expects order items with specific statuses (AWAITING_SHIPMENT, SHIPPED, CANCELLED)
  // However, the available APIs don't include order creation endpoints.
  // This test validates the shipment creation API's rejection of non-eligible order items.
  // 1. Create seller and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerEmail = typia.random<string & tags.Format<"email">>();
  const sellerPassword = RandomGenerator.alphaNumeric(16);
  await authorize_seller_join(sellerConnection, {
    body: {
      email: sellerEmail,
      password: sellerPassword,
    } satisfies DeepPartial<IEcommerceMallSeller.IJoin>,
  });
  // 2. Create product as seller
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.paragraph({ sentences: 2 }),
        description: RandomGenerator.content({ paragraphs: 2 }),
        basePrice: typia.random<
          number &
            tags.Type<"uint32"> &
            tags.Minimum<1000> &
            tags.Maximum<100000>
        >(),
        categoryId: typia.random<string & tags.Format<"uuid">>(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 3. Create variant for the product
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: { productId: product.id },
        body: {
          skuCode: `SKU-${RandomGenerator.alphaNumeric(8).toUpperCase()}`,
          price: product.base_price,
          options: [
            { optionName: "Color", optionValue: "Red" },
            { optionName: "Size", optionValue: "Large" },
          ] satisfies IEcommerceMallProductVariantOption.ICreate[],
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 4. Create customer and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  const customerEmail = typia.random<string & tags.Format<"email">>();
  const customerPassword = RandomGenerator.alphaNumeric(16);
  const customer = await authorize_customer_join(customerConnection, {
    body: {
      email: customerEmail,
      password: customerPassword,
    } satisfies DeepPartial<IEcommerceMallCustomer.IJoin>,
  });
  typia.assert(customer);
  // 5. Customer adds cart items (this creates order items)
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: typia.random<
            number & tags.Type<"uint32"> & tags.Minimum<1> & tags.Maximum<5>
          >(),
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 6. Test: Create shipment with non-existent order items
  // The system should reject shipment creation for items that don't exist
  // (which simulates items with non-AWAITING_SHIPMENT status)
  const invalidOrderItemId = typia.random<string & tags.Format<"uuid">>();
  await TestValidator.error(
    "should reject shipment with non-existent or invalid status order items",
    async () => {
      await generate_random_ecommerce_mall_seller_shipments_create(
        sellerConnection,
        {
          body: {
            orderItemIds: [invalidOrderItemId],
            carrierName: "FedEx",
            trackingNumber: `TRK-${RandomGenerator.alphaNumeric(10).toUpperCase()}`,
          } satisfies IEcommerceMallShipment.ICreate,
        },
      );
    },
  );
}
