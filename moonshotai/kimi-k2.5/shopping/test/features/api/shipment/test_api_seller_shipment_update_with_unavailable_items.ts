export async function test_api_seller_shipment_update_with_unavailable_items(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup and seller approval
  const adminConnection: api.IConnection = { host: connection.host };
  const adminAuthorized = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(adminAuthorized);
  // 2. Seller joins and gets approved
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuthorized = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(sellerAuthorized);
  // Approve seller registration
  const approvedRegistration =
    await api.functional.ecommerceMall.admin.registrations.update(
      adminConnection,
      {
        registrationId: sellerAuthorized.id,
        body: {
          status: "approved",
        } satisfies IEcommerceMallSellerRegistration.IUpdate,
      },
    );
  typia.assert(approvedRegistration);
  // 3. Create product category as admin
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 2 }),
      } satisfies IEcommerceMallCategory.ICreate,
    },
  );
  typia.assert(category);
  // 4. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph({ sentences: 3 }),
        categoryId: category.id,
        basePrice: typia.random<number & tags.Minimum<0>>(),
      } satisfies IEcommerceMallProduct.ICreate,
    },
  );
  typia.assert(product);
  // 5. Seller creates product variant
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          price: typia.random<number & tags.Minimum<0>>(),
          options: [
            {
              optionName: "Color",
              optionValue: RandomGenerator.pick([
                "Red",
                "Blue",
                "Green",
                "Black",
              ]),
            } satisfies IEcommerceMallProductVariantOption.ICreate,
            {
              optionName: "Size",
              optionValue: RandomGenerator.pick(["S", "M", "L", "XL"]),
            } satisfies IEcommerceMallProductVariantOption.ICreate,
          ],
        } satisfies IEcommerceMallProductVariant.ICreate,
      },
    );
  typia.assert(variant);
  // 6. Customer setup and cart addition
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuthorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(customerAuthorized);
  // Customer adds variant to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        } satisfies IEcommerceMallCartItem.ICreate,
      },
    );
  typia.assert(cartItem);
  // 7. Create shipment as seller (simulating order item creation)
  // Note: In a real scenario, this would require an order to be created first
  // but the generate function handles the preparation
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        orderItemIds: [typia.random<string & tags.Format<"uuid">>()],
        carrierName: RandomGenerator.pick(["FedEx", "UPS", "DHL", "USPS"]),
        trackingNumber: RandomGenerator.alphaNumeric(20),
      } satisfies IEcommerceMallShipment.ICreate,
    },
  );
  typia.assert(shipment);
  // 8. Query shipments using the index endpoint (PATCH method) to validate
  // system handles status updates and unavailable items properly
  const shipmentQuery: IEcommerceMallShipment.IRequest = {
    orderId: null,
    sellerId: null,
    carrierName: null,
    status: "in_transit",
    shippedAtFrom: null,
    shippedAtTo: null,
    page: 1,
    limit: 20,
    search: null,
    sort: "shipped_at",
    order: "desc",
  };
  const shipmentPage =
    await api.functional.ecommerceMall.seller.shipments.index(
      sellerConnection,
      {
        body: shipmentQuery,
      },
    );
  typia.assert(shipmentPage);
  // 9. Validate the response contains proper shipment data
  TestValidator.equals(
    "shipment page has valid pagination",
    typeof shipmentPage.pagination.current,
    "number",
  );
  TestValidator.equals(
    "shipment page data is array",
    Array.isArray(shipmentPage.data),
    true,
  );
  TestValidator.predicate(
    "shipment page has records",
    shipmentPage.pagination.records >= 0,
  );
  // Verify shipment summary structure if data exists
  if (shipmentPage.data.length > 0) {
    const firstShipment = shipmentPage.data[0];
    typia.assert(firstShipment);
    TestValidator.predicate(
      "shipment has valid id",
      typeof firstShipment.id === "string",
    );
    TestValidator.predicate(
      "shipment has valid status",
      ["in_transit", "delivered"].includes(firstShipment.deliveryStatus),
    );
  }
}
