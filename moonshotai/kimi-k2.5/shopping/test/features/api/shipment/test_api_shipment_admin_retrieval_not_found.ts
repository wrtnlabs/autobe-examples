export async function test_api_shipment_admin_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
    },
  });
  // 2. Generate a random UUID that was never created as a shipment
  const nonExistentShipmentId = typia.random<string & tags.Format<"uuid">>();
  // 3. Attempt to retrieve the non-existent shipment and verify 404 error
  await TestValidator.httpError(
    "should return 404 Not Found for non-existent shipment",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.shipments.at(adminConnection, {
        shipmentId: nonExistentShipmentId,
      });
    },
  );
}
