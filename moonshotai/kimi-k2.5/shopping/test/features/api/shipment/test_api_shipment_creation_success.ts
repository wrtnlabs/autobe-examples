export async function test_api_shipment_creation_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Seller setup - authenticate and create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const sellerAuth = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    },
  });
  typia.assert(sellerAuth);
  // Create a product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        name: RandomGenerator.name(),
        description: RandomGenerator.paragraph(),
        basePrice: typia.random<number & tags.Minimum<1>>(),
      },
    },
  );
  typia.assert(product);
  // Create a product variant with inventory
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          skuCode: RandomGenerator.alphaNumeric(10),
          price: product.base_price,
          options: [
            {
              optionName: "Color",
              optionValue: "Red",
            },
          ],
        },
      },
    );
  typia.assert(variant);
  // 2. Customer setup - authenticate and add to cart
  const customerConnection: api.IConnection = { host: connection.host };
  const customerAuth = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    },
  });
  typia.assert(customerAuth);
  // Add variant to cart
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: typia.random<
            number & tags.Type<"int32"> & tags.Minimum<1>
          >(),
        },
      },
    );
  typia.assert(cartItem);
  // 3. Create shipment for order items using utility function
  // The utility handles the underlying logic for creating orders and preparing shipment data
  const shipment = await generate_random_ecommerce_mall_seller_shipments_create(
    sellerConnection,
    {
      body: {
        carrierName: RandomGenerator.pick(["FedEx", "UPS", "DHL", "USPS"]),
        trackingNumber: RandomGenerator.alphaNumeric(12),
      },
    },
  );
  typia.assert(shipment);
  // Verify shipment response structure
  TestValidator.equals(
    "shipment carrier name is string",
    typeof shipment.carrier_name,
    "string",
  );
  TestValidator.equals(
    "shipment tracking number is string",
    typeof shipment.tracking_number,
    "string",
  );
  TestValidator.predicate(
    "shipment status is valid",
    shipment.status === "in_transit" || shipment.status === "delivered",
  );
  TestValidator.predicate(
    "shipment has shipment items",
    Array.isArray(shipment.shipment_items) &&
      shipment.shipment_items.length > 0,
  );
  TestValidator.equals(
    "shipment seller matches",
    shipment.seller.id,
    sellerAuth.id,
  );
  // Verify each shipment item
  for (const shipmentItem of shipment.shipment_items) {
    TestValidator.equals(
      "shipment item order item status is shipped",
      shipmentItem.orderItem.status,
      "shipped",
    );
    typia.assert<IEcommerceMallShipmentItem>(shipmentItem);
  }
}
