/**
 * Test that querying snapshots for a newly created variant that has never been edited returns an empty list.
 * This edge case verifies the system correctly handles variants with no edit history.
 *
 * Test Steps:
 * 1. Authenticate as admin and create a category
 * 2. Authenticate as seller and create a product
 * 3. Create a variant with SKU code and option values
 * 4. Immediately query snapshots without any prior edits
 */
export async function test_api_product_variant_snapshot_empty_list(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin setup - create category for product
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
    },
  });
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 2. Seller setup - create product
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 3. Create variant (no snapshots yet since it hasn't been edited)
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // 4. Query snapshots immediately after creation - should return empty list
  const snapshots =
    await api.functional.ecommerceMall.seller.products.variants.snapshots.index(
      sellerConnection,
      {
        productId: product.id,
        variantId: variant.id,
        body: {} satisfies IEcommerceMallProductVariantSnapshot.IRequest,
      },
    );
  typia.assert(snapshots);
  // Verify empty list response
  TestValidator.equals("snapshots data is empty array", snapshots.data, []);
  TestValidator.equals(
    "pagination records is 0",
    snapshots.pagination.records,
    0,
  );
  TestValidator.equals("pagination pages is 0", snapshots.pagination.pages, 0);
  TestValidator.predicate(
    "pagination current page is valid",
    snapshots.pagination.current >= 1,
  );
  TestValidator.predicate(
    "pagination limit is valid",
    snapshots.pagination.limit >= 1,
  );
}
