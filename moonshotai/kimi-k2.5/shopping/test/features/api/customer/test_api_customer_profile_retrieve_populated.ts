export async function test_api_customer_profile_retrieve_populated(
  connection: api.IConnection,
): Promise<void> {
  // Create customer-specific connection
  const customerConnection: api.IConnection = { host: connection.host };
  // Register customer using utility function (sets up auth headers)
  const authorized = await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  typia.assert(authorized);
  // Retrieve customer profile - requires authenticated connection from join
  const profile =
    await api.functional.ecommerceMall.customer.profile.at(customerConnection);
  typia.assert(profile);
}
