/**
 * Test that already-reviewed items are excluded from the eligible review list.
 *
 * This test validates the business rule that only one review per order item is allowed.
 * Setup: A customer places an order, item gets delivered, customer writes a review,
 * then queries eligible items again to verify the reviewed item no longer appears.
 *
 * Note: The checkout endpoint is not available in the current API, so this test
 * verifies the eligibleForReview endpoint can be called successfully.
 */
export async function test_api_customer_orderitem_eligible_for_review_excludes_reviewed_items(
  connection: api.IConnection,
): Promise<void> {
  // Create customer actor
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  // Query eligible items for review - endpoint should return valid response
  // Note: Without checkout endpoint, we cannot create order items to test the full scenario
  const eligibleItems =
    await api.functional.ecommerceMall.customer.orderItems.eligibleForReview.index(
      customerConnection,
      { body: {} },
    );
  typia.assert(eligibleItems);
}
