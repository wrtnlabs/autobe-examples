/**
 * Test checkout handling when payment gateway returns failure.
 *
 * Preconditions: An authenticated customer has valid cart items with sufficient stock, but external payment fails.
 *
 * Test Steps:
 * 1. Authenticate as customer, admin, and seller using join operations
 * 2. Admin creates category, seller creates product and variant with stock
 * 3. Customer adds variant to cart with valid quantity
 * 4. Customer initiates checkout with shipping address provided in checkout request
 * 5. External payment gateway returns failure status
 *
 * Expected Results:
 * - HTTP 402 Payment Required response indicating payment failure
 * - No order is created in the system
 * - Cart items remain in customer's cart (not cleared)
 * - No inventory records are created (stock not deducted)
 * - No snapshots are captured
 * - Customer receives error with option to retry
 *
 * Validation Points:
 * - Verify payment failure response with appropriate error code
 * - Verify no order record exists in database
 * - Verify cart items are preserved unchanged
 * - Verify no inventory deduction occurred
 * - Verify variant stock levels unchanged
 * - Error response contains payment failure details
 */
export async function test_api_customer_checkout_payment_failure(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create actor-specific connections and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    },
  });
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<
        string & tags.MinLength<8> & tags.Format<"password">
      >(),
    },
  });
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
    },
  });
  // 2. Admin creates category
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Seller creates product
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  // 4. Seller creates variant with stock
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {
          stock: 100,
        },
      },
    );
  typia.assert(variant);
  // 5. Customer adds variant to cart with valid quantity
  const cartItem =
    await generate_random_ecommerce_mall_customer_cart_items_create(
      customerConnection,
      {
        body: {
          productVariantId: variant.id,
          quantity: 2,
        },
      },
    );
  typia.assert(cartItem);
  // 6. Customer initiates checkout - should fail with 402 Payment Required
  const checkoutBody = {
    recipientName: typia.random<string>(),
    recipientPhone: typia.random<string>(),
    streetAddress: typia.random<string>(),
    city: typia.random<string>(),
    state: null,
    postalCode: typia.random<string>(),
    country: typia.random<string>(),
  } satisfies IEcommerceMallOrder.ICreate;
  await TestValidator.httpError(
    "checkout should fail with 402 Payment Required when payment gateway fails",
    402,
    async () => {
      await api.functional.ecommerceMall.customer.checkout.create(
        customerConnection,
        {
          body: checkoutBody,
        },
      );
    },
  );
}
