export async function test_api_customer_session_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create customer connection and authenticate
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
    } satisfies IEcommerceMallCustomer.IJoin,
  });
  // Test retrieving non-existent session returns 404
  await TestValidator.httpError(
    "non-existent session returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.customer.sessions.at(
        customerConnection,
        {
          sessionId: "00000000-0000-0000-0000-000000000000",
        },
      );
    },
  );
}
