export async function test_api_inventory_record_not_found_returns_error(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin authentication setup
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: typia.random<string & tags.Format<"password">>(),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Test that fetching a non-existent inventory record returns 404
  await TestValidator.httpError(
    "non-existent inventory record returns HTTP 404",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.inventory_records.at(
        adminConnection,
        {
          inventoryRecordId: "00000000-0000-0000-0000-000000000000",
        },
      );
    },
  );
}
