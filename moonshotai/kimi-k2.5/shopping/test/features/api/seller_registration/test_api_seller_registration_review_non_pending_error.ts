/**
 * Test that attempting to review a registration that is not in 'pending' status
 * results in a business logic error. After an admin approves a registration,
 * try to review it again with status 'rejected'. Verify that:
 * 1. The second review attempt fails with a business error indicating the
 *    registration is not in a reviewable state
 * 2. Only registrations with 'pending' status can be reviewed
 * 3. Once approved or rejected, the registration status is final
 * 4. This enforces the business rule that each registration receives exactly
 *    one review decision
 */
export async function test_api_seller_registration_review_non_pending_error(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(admin);
  // Create seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<(string & tags.Format<"ipv4">) | null>(),
    } satisfies IEcommerceMallSeller.IJoin,
  });
  typia.assert(seller);
  // Create seller registration
  const registration =
    await generate_random_ecommerce_mall_seller_registrations_create(
      sellerConnection,
      {
        body: {
          taxIdentificationNumber: RandomGenerator.alphaNumeric(10),
          businessRegistrationNumber: RandomGenerator.alphaNumeric(10),
          businessName: RandomGenerator.name(),
          businessAddress: RandomGenerator.paragraph({ sentences: 2 }),
        } satisfies IEcommerceMallSellerRegistration.ICreate,
      },
    );
  typia.assert(registration);
  // First review - approve the registration
  const approvedRegistration =
    await api.functional.ecommerceMall.admin.sellers.registrations.review(
      adminConnection,
      {
        registrationId: (registration as any).id,
        body: {
          status: "approved",
          rejection_reason: null,
        } satisfies IEcommerceMallSellerRegistration.IReview,
      },
    );
  typia.assert(approvedRegistration);
  // Second review attempt - should fail since registration is already approved
  await TestValidator.error(
    "review already approved registration",
    async () => {
      await api.functional.ecommerceMall.admin.sellers.registrations.review(
        adminConnection,
        {
          registrationId: (registration as any).id,
          body: {
            status: "rejected",
            rejection_reason: "Duplicate application",
          } satisfies IEcommerceMallSellerRegistration.IReview,
        },
      );
    },
  );
}
