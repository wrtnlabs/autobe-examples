export async function test_api_seller_registration_submission_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create a new seller connection and authenticate
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: "Password123!",
      href: "https://example.com/seller/join",
      referrer: "https://example.com",
      ip: null,
    } satisfies IEcommerceMallSeller.IJoin,
  });
  // 2. Submit seller registration with unique business identification information
  const registration =
    await generate_random_ecommerce_mall_seller_registrations_create(
      sellerConnection,
      {
        body: {
          taxIdentificationNumber: RandomGenerator.alphaNumeric(10),
          businessRegistrationNumber: RandomGenerator.alphaNumeric(12),
          businessName: RandomGenerator.name(3),
          businessAddress: RandomGenerator.paragraph({ sentences: 2 }),
          reason: RandomGenerator.paragraph({ sentences: 3 }),
        },
      },
    );
  // 3. Validate the registration response structure
  typia.assert(registration);
}
