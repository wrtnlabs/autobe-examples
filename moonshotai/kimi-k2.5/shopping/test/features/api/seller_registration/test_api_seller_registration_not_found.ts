export async function test_api_seller_registration_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Generate a non-existent registration ID (random UUID)
  const nonExistentRegistrationId = typia.random<
    string & tags.Format<"uuid">
  >();
  // 3. Attempt to fetch non-existent registration and expect 404
  await TestValidator.httpError(
    "should return 404 for non-existent registration",
    404,
    async () => {
      await api.functional.ecommerceMall.seller.registrations.at(
        adminConnection,
        {
          registrationId: nonExistentRegistrationId,
        },
      );
    },
  );
}
