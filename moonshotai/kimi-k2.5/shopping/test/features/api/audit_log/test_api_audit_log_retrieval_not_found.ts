export async function test_api_audit_log_retrieval_not_found(
  connection: api.IConnection,
): Promise<void> {
  // Create admin connection and authenticate
  const adminConnection: api.IConnection = { host: connection.host };
  const admin = await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"url">>(),
      referrer: typia.random<string & tags.Format<"url">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  typia.assert(admin);
  // Generate a random UUID for a non-existent audit log
  const nonExistentLogId = typia.random<string & tags.Format<"uuid">>();
  // Attempt to retrieve non-existent audit log and verify 404 error
  await TestValidator.httpError(
    "non-existent audit log returns 404",
    404,
    async () => {
      await api.functional.ecommerceMall.admin.audit_logs.at(adminConnection, {
        logId: nonExistentLogId,
      });
    },
  );
}
