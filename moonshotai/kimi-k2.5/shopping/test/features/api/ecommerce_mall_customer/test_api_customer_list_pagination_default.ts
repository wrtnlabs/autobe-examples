export async function test_api_customer_list_pagination_default(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as administrator
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: typia.random<string & tags.Format<"ipv4">>(),
    } satisfies IEcommerceMallAdmin.IJoin,
  });
  // 2. Call customer list endpoint with default parameters (empty request body)
  const response = await api.functional.ecommerceMall.customers.index(
    adminConnection,
    {
      body: {} satisfies IEcommerceMallCustomer.IRequest,
    },
  );
  // 3. Validate response structure including pagination metadata
  typia.assert(response);
}
