export async function test_api_cart_item_retrieval_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Admin creates category (prerequisite for product)
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  // 2. Seller creates product and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {},
      },
    );
  // 3. Customer adds variant to cart
  const customerConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerConnection, {});
  const quantity = typia.random<
    number & tags.Type<"int32"> & tags.Minimum<1> & tags.Maximum<10>
  >();
  const cartItem = await generate_random_ecommerce_mall_customer_cart_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: quantity,
      },
    },
  );
  // 4. Retrieve the specific cart item
  const retrieved = await api.functional.ecommerceMall.customer.cart.at(
    customerConnection,
    {
      cartItemId: cartItem.id,
    },
  );
  typia.assert(retrieved);
  // 5. Validate business logic and data integrity
  TestValidator.equals("cart item id matches input", retrieved.id, cartItem.id);
  TestValidator.equals(
    "quantity preserved correctly",
    retrieved.quantity,
    quantity,
  );
  TestValidator.equals(
    "product variant id matches",
    retrieved.productVariant.id,
    variant.id,
  );
  TestValidator.equals("product id matches", retrieved.product.id, product.id);
  TestValidator.equals(
    "seller info matches",
    retrieved.product.seller.id,
    product.seller.id,
  );
  TestValidator.equals(
    "subtotal calculation correct",
    retrieved.subtotal,
    retrieved.unitPrice * retrieved.quantity,
  );
}
