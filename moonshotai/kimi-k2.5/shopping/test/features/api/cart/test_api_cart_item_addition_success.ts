/**
 * Test adding a product variant to a customer's shopping cart.
 *
 * This validates the core cart functionality where customers can add items
 * with specific quantities for purchase.
 *
 * Test Steps:
 * 1. Authenticate as Customer A using POST /ecommerceMall/auth/customer/join
 * 2. Authenticate as admin using POST /ecommerceMall/auth/admin/join and create a product category
 * 3. Authenticate as seller using POST /ecommerceMall/auth/seller/join, create a product with the category, and create a variant
 * 4. Add the variant to Customer A's cart with quantity 2 using POST /ecommerceMall/customer/cart
 * 5. Verify the response contains the cart item with correct product variant details, quantity, and pricing information
 */
export async function test_api_cart_item_addition_success(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as Customer A
  const customerConnection: api.IConnection = { host: connection.host };
  const customer = await authorize_customer_join(customerConnection, {});
  typia.assert(customer);
  // 2. Authenticate as admin and create category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // 3. Authenticate as seller and create product with variant
  const sellerConnection: api.IConnection = { host: connection.host };
  const seller = await authorize_seller_join(sellerConnection, {});
  typia.assert(seller);
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      },
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
        body: {},
      },
    );
  typia.assert(variant);
  // 4. Add variant to Customer A's cart with quantity 2
  const cartItem = await generate_random_ecommerce_mall_customer_cart_create(
    customerConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 2,
      } satisfies IEcommerceMallCartItem.ICreate,
    },
  );
  typia.assert(cartItem);
  // 5. Verify cart item details
  TestValidator.equals("quantity matches input", cartItem.quantity, 2);
  TestValidator.equals(
    "product variant ID matches",
    cartItem.productVariant.id,
    variant.id,
  );
  TestValidator.equals("product ID matches", cartItem.product.id, product.id);
  TestValidator.equals(
    "seller ID matches",
    cartItem.product.seller.id,
    seller.id,
  );
  TestValidator.predicate(
    "subtotal equals unit price times quantity",
    cartItem.subtotal === cartItem.unitPrice * cartItem.quantity,
  );
  TestValidator.predicate("item is available", cartItem.isAvailable);
}
