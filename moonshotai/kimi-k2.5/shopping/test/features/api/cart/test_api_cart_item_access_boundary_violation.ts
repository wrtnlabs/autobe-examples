/**
 * Test that cart access boundaries are strictly enforced between customers.
 *
 * Setup involves: Customer A registers and adds a product variant to their cart.
 * Customer B registers separately. Customer B then attempts to retrieve Customer A's
 * cart item using the cartItemId. Per the business rules, the system SHALL reject
 * access attempts to another customer's cart items. The specification states this
 * returns 404 (not 403) to prevent information leakage about whether the cart item exists.
 * This validates data isolation between customers.
 */
export async function test_api_cart_item_access_boundary_violation(
  connection: api.IConnection,
): Promise<void> {
  // Setup admin and category
  const adminConnection: api.IConnection = { host: connection.host };
  await authorize_admin_join(adminConnection, {});
  const category = await generate_random_ecommerce_mall_admin_categories_create(
    adminConnection,
    {},
  );
  typia.assert(category);
  // Setup seller, product, and variant
  const sellerConnection: api.IConnection = { host: connection.host };
  await authorize_seller_join(sellerConnection, {});
  const product = await generate_random_ecommerce_mall_seller_products_create(
    sellerConnection,
    {
      body: {
        categoryId: category.id,
      } satisfies DeepPartial<IEcommerceMallProduct.ICreate>,
    },
  );
  typia.assert(product);
  const variant =
    await generate_random_ecommerce_mall_seller_products_variants_create(
      sellerConnection,
      {
        params: {
          productId: product.id,
        },
      },
    );
  typia.assert(variant);
  // Customer A creates cart item
  const customerAConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerAConnection, {});
  const cartItem = await generate_random_ecommerce_mall_customer_cart_create(
    customerAConnection,
    {
      body: {
        productVariantId: variant.id,
        quantity: 1,
      } satisfies DeepPartial<IEcommerceMallCartItem.ICreate>,
    },
  );
  typia.assert(cartItem);
  // Customer B attempts to access Customer A's cart item
  const customerBConnection: api.IConnection = { host: connection.host };
  await authorize_customer_join(customerBConnection, {});
  // Verify access is rejected (404 to prevent information leakage)
  await TestValidator.error(
    "Customer B cannot access Customer A's cart item",
    async () => {
      await api.functional.ecommerceMall.customer.cart.at(customerBConnection, {
        cartItemId: cartItem.id,
      });
    },
  );
}
