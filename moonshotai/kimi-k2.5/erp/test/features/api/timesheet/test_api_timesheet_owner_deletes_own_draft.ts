export async function test_api_timesheet_owner_deletes_own_draft(
  connection: api.IConnection,
): Promise<void> {
  // 1. Authenticate as a member
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {
    body: {
      email: typia.random<string & tags.Format<"email">>(),
      password: RandomGenerator.alphaNumeric(16),
      firstName: RandomGenerator.name(1),
      lastName: RandomGenerator.name(1),
      avatarUrl: null,
      timezone: null,
      locale: null,
      href: typia.random<string & tags.Format<"uri">>(),
      referrer: typia.random<string & tags.Format<"uri">>(),
      ip: null,
    } satisfies IErpHrmMember.IJoin,
  });
  // 2. Create a draft timesheet for the current week
  const now = new Date();
  const weekStart = new Date(now);
  weekStart.setDate(now.getDate() - now.getDay());
  weekStart.setHours(0, 0, 0, 0);
  const timesheet = await generate_random_erp_hrm_member_timesheets_create(
    memberConnection,
    {
      body: {
        weekStartDate: weekStart.toISOString(),
      } satisfies IErpHrmTimesheet.ICreate,
    },
  );
  typia.assert(timesheet);
  // Verify timesheet is in draft status
  TestValidator.equals(
    "timesheet status should be draft",
    timesheet.status,
    "draft",
  );
  TestValidator.equals(
    "timesheet should not be deleted yet",
    timesheet.deletedAt,
    null,
  );
  // 3. Delete the timesheet (should return 204 No Content)
  await api.functional.erpHrm.member.timesheets.erase(memberConnection, {
    timesheetId: timesheet.id,
  });
  // 4. Verify deletion by attempting to delete again - should fail
  await TestValidator.error(
    "deleting already deleted timesheet should fail",
    async () => {
      await api.functional.erpHrm.member.timesheets.erase(memberConnection, {
        timesheetId: timesheet.id,
      });
    },
  );
}
