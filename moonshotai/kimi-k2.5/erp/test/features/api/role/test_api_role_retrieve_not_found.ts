export async function test_api_role_retrieve_not_found(
  connection: api.IConnection,
): Promise<void> {
  // 1. Member joins the system via /auth/member/join
  const memberConnection: api.IConnection = { host: connection.host };
  const member = await authorize_member_join(memberConnection, {});
  typia.assert(member);
  // 2. Member creates an organization via /member/organizations
  const organization =
    await generate_random_erp_hrm_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Generate a valid UUID that doesn't exist in the system
  const nonExistentRoleId = typia.random<string & tags.Format<"uuid">>();
  // 4. Attempt to retrieve the non-existent role and verify 404 error
  await TestValidator.httpError(
    "should return 404 for non-existent role",
    404,
    async () => {
      await api.functional.erpHrm.member.roles.at(memberConnection, {
        roleId: nonExistentRoleId,
      });
    },
  );
}
