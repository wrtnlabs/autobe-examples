export async function test_api_project_reactivate_already_active_fails(
  connection: api.IConnection,
): Promise<void> {
  // 1. Create authenticated member connection
  const memberConnection: api.IConnection = { host: connection.host };
  await authorize_member_join(memberConnection, {});
  // 2. Create organization context
  const organization =
    await generate_random_erp_hrm_member_organizations_create(
      memberConnection,
      {},
    );
  typia.assert(organization);
  // 3. Create project with default 'active' status
  const project = await generate_random_erp_hrm_member_projects_create(
    memberConnection,
    {},
  );
  typia.assert(project);
  // Verify initial status is active
  TestValidator.equals(
    "project initial status is active",
    project.status,
    "active",
  );
  // 4. Attempt to reactivate already active project - should fail with error
  await TestValidator.error(
    "reactivate already active project should fail",
    async () => {
      await api.functional.erpHrm.member.projects.reactivate(memberConnection, {
        projectId: project.id,
      });
    },
  );
}
