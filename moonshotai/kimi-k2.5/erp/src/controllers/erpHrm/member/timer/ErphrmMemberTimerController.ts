import { TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmTimer } from "../../../../api/structures/IErpHrmTimer";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberTimer } from "../../../../providers/getErpHrmMemberTimer";

@Controller("/erpHrm/member/timer")
export class ErphrmMemberTimerController {
  /**
   * Retrieve the current running timer for the authenticated employee.
   *
   * This operation retrieves the active timer session that the currently authenticated employee has running. Timer tracking enables employees to capture work duration in real-time as it happens, complementing manual timelog entry.
   *
   * When a timer is active, the system provides continuous elapsed time tracking starting from the recorded start timestamp. The timer status includes the selected project (required when starting), optionally associated task, and any entered work description. The elapsed duration represents the time difference between the start timestamp and current time.
   *
   * Timer status is only visible to the employee who owns it. Users with time view all permission may be able to view running timers of other employees within the same organization context.
   *
   * The timer runs indefinitely with no automatic timeout (per section 277 - Forgotten Timer Indefinite Runtime). Employees are responsible for monitoring and stopping their own timers. If no timer is active, this operation indicates no timer is running.
   *
   * Related operations:
   * - POST /timer to start a new timer session
   * - PUT /timer/stop to stop the active timer and create a timelog entry
   * - DELETE /timer to discard the active timer without creating a timelog
   * - PATCH /timers for listing historical timer entries
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_timers table for a record where
     *   organization_member_id matches the current authenticated employee's
     *   membership ID.
   *
   * Implementation steps:
   * 1. Identify the current authenticated member's organization context from the session
   * 2. Look up the organization_member record for this user in the current organization
   * 3. Query erp_hrm_timers for any record with matching organization_member_id
   * 4. Since an employee can have at most one active timer at any moment (per section 193), there should be at most one result
   * 5. Return the complete timer record with all fields
   * 6. If no timer exists, return null or appropriate response indicating no active timer
   *
   * Security considerations:
   * - The timer must belong to the current organization context
   * - Only the timer owner can view their own timer, or users with appropriate 'time view all' permission
   * - Authorization checks must verify the member has access to view timer data
   *
   * Data returned includes:
   * - id: The timer's unique identifier
   * - organization_member_id: The employee who owns this timer
   * - project_id: The selected project for work tracking
   * - task_id: Optional task reference within the project
   * - started_at: Timestamp when timer began
   * - description: Work description entered when starting
   *
   * Response preparation:
   * - Calculate elapsed_duration on-the-fly as current time minus started_at
   * - Round to the nearest minute as per standard duration calculation
   * - Include full project and task details via appropriate joins if requested
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get()
  public async at(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<IErpHrmTimer> {
    try {
      return await getErpHrmMemberTimer({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
