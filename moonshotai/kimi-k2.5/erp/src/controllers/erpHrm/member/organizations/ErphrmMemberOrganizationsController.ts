import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmOrganization } from "../../../../api/structures/IErpHrmOrganization";
import { IPageIErpHrmOrganization } from "../../../../api/structures/IPageIErpHrmOrganization";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberOrganizationsOrganizationId } from "../../../../providers/deleteErpHrmMemberOrganizationsOrganizationId";
import { getErpHrmMemberOrganizationsOrganizationId } from "../../../../providers/getErpHrmMemberOrganizationsOrganizationId";
import { patchErpHrmMemberOrganizations } from "../../../../providers/patchErpHrmMemberOrganizations";
import { postErpHrmMemberOrganizations } from "../../../../providers/postErpHrmMemberOrganizations";
import { putErpHrmMemberOrganizationsOrganizationId } from "../../../../providers/putErpHrmMemberOrganizationsOrganizationId";

@Controller("/erpHrm/member/organizations")
export class ErphrmMemberOrganizationsController {
  /**
   * Create a new organization in the erpHrm system.
   *
   * This operation establishes a new tenant organization that serves as the aggregate root for all organization-scoped data isolation. The authenticated user becomes the organization owner and is granted full administrative privileges.
   *
   * Upon creation, the system initializes the organization with the provided identity information (name, description, optional logo URL) and operational configuration (currency in ISO 4217 format, IANA timezone identifier, and fiscal year starting month). The organization's deleted_at field remains null indicating active status.
   *
   * The created organization automatically links to the authenticated user via owner_id. All subsequent entities (departments, roles, projects, members, etc.) will belong to this organization and remain isolated from other organizations.
   *
   * Multi-tenancy is enforced at the database level through organization_id foreign keys across all related entities. The new organization is immediately available for member invitations and operational use.
   *
   * Returns the complete organization record including server-generated id and timestamps.
   *
   * @param connection
   * @param body Organization creation data including name, description, logo, currency, timezone, and fiscal year settings
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation steps:
   *
   * 1. Extract authenticated user ID from JWT session token
   * 2. Validate required fields from IErpHrmOrganization.ICreate:
   *    - name: non-empty string, unique across all organizations (check @@unique constraint)
   *    - currency: ISO 4217 format (e.g., 'USD', 'EUR', 'KRW')
   *    - timezone: valid IANA timezone string (e.g., 'America/New_York', 'Asia/Seoul')
   *    - fiscal_year_start_month: integer 1-12 representing month
   *    - description: optional string
   *    - logo_url: optional URL string, validate format
   *
   * 3. Check for duplicate organization name violation against erp_hrm_organizations table
   * 4. Generate UUID for new organization id
   * 5. Set timestamps: created_at = updated_at = CURRENT_TIMESTAMP
   * 6. Set owner_id to authenticated user ID
   * 7. Set deleted_at = null
   * 8. Insert record into erp_hrm_organizations table
   * 9. Return complete IErpHrmOrganization DTO
   *
   * Database operations:
   * - INSERT INTO erp_hrm_organizations (id, owner_id, name, description, logo_url, currency, timezone, fiscal_year_start_month, created_at, updated_at, deleted_at)
   * - SELECT to verify unique name constraint before insert
   *
   * Error handling:
   * - Duplicate name: return 409 Conflict
   * - Invalid currency format: return 400 Bad Request
   * - Invalid timezone: return 400 Bad Request
   * - Invalid fiscal_year_start_month (not 1-12): return 400 Bad Request
   * - Unauthenticated: return 401 Unauthorized
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmOrganization.ICreate,
  ): Promise<IErpHrmOrganization> {
    try {
      return await postErpHrmMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of organizations accessible to the current user.
   *
   * This operation provides advanced search capabilities for organizations including partial name matching, currency filtering, timezone filtering, and creation date ranges. It supports the multi-organization membership model where users can belong to multiple organizations simultaneously.
   *
   * The response includes organization summary information optimized for list displays, showing key identity and configuration fields (name, description, logo, currency, timezone, fiscal settings) without exposing full detailed data.
   *
   * Results are scoped to organizations the authenticated user has access to - either organizations they own or organizations where they have an active membership. Data isolation between organizations is strictly enforced at the API level.
   *
   * Supports comprehensive pagination with configurable page sizes and multiple sorting options. Use this endpoint to populate organization selection interfaces, dashboard overviews, and administrative organization management screens.
   *
   * @param connection
   * @param body Search criteria and pagination parameters for filtering organizations
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_organizations table with pagination
     *   and filtering support.
   *
   * Filter capabilities:
   * - name: partial text search on organization name
   * - ownerId: filter by organization owner
   * - currency: filter by ISO 4217 currency code
   * - timezone: filter by IANA timezone
   * - createdAt range: filter by creation date
   * - Include deleted organizations option (for admin/owner recovery scenarios)
   *
   * Join with erp_hrm_members to include owner information in response.
   *
   * Authorization:
   * - Members can only view organizations they belong to (via erp_hrm_organization_members)
   * - Organization owners can view their owned organizations
   * - System administrators may view all organizations
   *
   * Sorting options:
   * - createdAt (default, descending)
   * - name (alphabetical)
   * - updatedAt
   *
   * Pagination:
   * - Cursor-based pagination for large result sets
   * - Configurable page size (default 20, max 100)
   *
   * Returns summary fields: id, name, description, logoUrl, currency, timezone, fiscalYearStartMonth, createdAt, owner summary.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmOrganization.IRequest,
  ): Promise<IPageIErpHrmOrganization.ISummary> {
    try {
      return await patchErpHrmMemberOrganizations({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific organization by its ID.
   *
   * This operation returns complete organization details including identity information (name, description, logo) and configuration settings (currency, timezone, fiscal year start month). It serves the organization context selection workflow where members view available organizations and their details before selecting one to work in.
   *
   * Members can only retrieve organizations they are members of. The returned data includes the organization owner's ID for reference. Configuration fields like currency, timezone, and fiscal_year_start_month are essential for displaying organization settings in the UI.
   *
   * Related operations include PATCH /organizations for listing user's organizations with filtering, and PUT /organizations/{organizationId} for updating organization settings (requires appropriate permissions).
   *
   * @param connection
   * @param organizationId Target organization's ID (global scope)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_organizations table by id field
     *   using the provided organizationId path parameter.
   *
   * 1. Verify the organization exists and deleted_at is null (not soft-deleted)
   * 2. Verify the requesting user has membership in the target organization (check erp_hrm_organization_members where organization_id matches and user_id matches the authenticated user)
   * 3. Return the full organization record including all columns
   *
   * Join with erp_hrm_members table to include owner information if needed for display purposes.
   *
   * Authorization: Only members of the organization can view its details. Non-members receive 403 Forbidden.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":organizationId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmOrganization> {
    try {
      return await getErpHrmMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing organization's details and settings.
   *
   * This operation allows authorized members to modify organization attributes such as name, description, and configuration settings. The organization serves as the root container for all business data within the platform, including employees, departments, projects, and roles.
   *
   * The operation requires the caller to have appropriate permissions within the organization context. Upon successful update, the system returns the complete updated organization record with all current field values. The organization identity and its relationships to child entities remain intact during the update process.
   *
   * @param connection
   * @param organizationId Unique identifier of the organization to update (UUID format)
   * @param body Organization update data containing fields to modify
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implement organization update by querying
     *   erp_hrm_organizations table using provided organizationId UUID.
     *   Validate that the caller has organization:update permission. Update
     *   only provided fields in the request body (partial update support).
     *   Common updatable fields include name, description, settings,
     *   configuration. Return the complete updated organization record joined
     *   with related owner information if applicable. Handle edge cases:
     *   non-existent organization (404), insufficient permissions (403),
     *   duplicate organization names if uniqueness constraint exists (409).
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":organizationId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string,
    @TypedBody()
    body: IErpHrmOrganization.IUpdate,
  ): Promise<IErpHrmOrganization> {
    try {
      return await putErpHrmMemberOrganizationsOrganizationId({
        member,
        organizationId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Delete an organization permanently from the platform.
   *
   * This operation permanently removes an organization and all its associated data from the system. Deletion is subject to strict business constraints to ensure data integrity and proper business closure procedures.
   *
   * Before deletion, the system validates that there are no pending timesheets awaiting approval or rejection, and that there are no active employee contracts remaining. These checks ensure proper business closure procedures before an organization is dissolved.
   *
   * When deletion is permitted, the operation performs a CASCADE DELETE that permanently removes all associated data including:
   * - All employee records and their memberships
   * - All departments and hierarchies
   * - All projects, tasks, and project memberships
   * - All timelogs, timesheets, and activity logs
   * - All roles and contracts
   *
   * The organization owner's user account is preserved but disassociated from the deleted organization. This deletion is irreversible and cannot be undone.
   *
   * @param connection
   * @param organizationId Target organization's ID (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation must verify the requesting user is
     *   the organization owner before allowing deletion. Query
     *   erp_hrm_timesheets table to check for pending status timesheets - if
     *   any exist, reject with error indicating pending timesheets must be
     *   resolved first. Query erp_hrm_contracts table to check for is_active =
     *   true records - if any exist, reject with error indicating active
     *   contracts must be terminated first. If validation passes, perform soft
     *   delete by setting deleted_at = current_timestamp on the organization
     *   record. Cascade the soft delete to all child entities:
     *   erp_hrm_organization_members (cascade), erp_hrm_roles (cascade),
     *   erp_hrm_departments (cascade), erp_hrm_projects (cascade),
     *   erp_hrm_tasks (cascade), erp_hrm_timelogs (cascade), erp_hrm_timesheets
     *   (cascade). Preserve owner user account but remove organization
     *   association. Return the soft-deleted organization record including the
     *   deleted_at timestamp.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":organizationId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("organizationId")
    organizationId: string,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberOrganizationsOrganizationId({
        member,
        organizationId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
