@Controller("/erpHrm/member/timelogs")
export class ErphrmMemberTimelogsController {
  /**
   * Create a new timelog entry recording a work session performed by the authenticated employee.
   *
   * A timelog represents a continuous period of time spent on work activities and serves as the foundational record for time tracking, payroll calculations, and project cost analysis. Each timelog captures when work began (start time), when it concluded (end time), the calculated duration, and what project or task the time was spent on.
   *
   * The employee creating the timelog is automatically recorded as the owner based on their authenticated session. Employees can only create timelogs for projects they are assigned to as members. If specifying a task, it must belong to the selected project.
   *
   * The duration is automatically calculated from the start and end timestamps and rounded to the nearest minute. Timelogs can be marked as billable or non-billable to distinguish between client-chargeable work and internal activities.
   *
   * Once created, the timelog exists in an editable state until it becomes associated with a submitted or approved timesheet, at which point modification restrictions apply.
   *
   * @param connection
   * @param body Timelog creation data containing project association, time range, billable status, and optional description
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Create a new timelog recording a work session for the authenticated employee.
   *
   * Validation Rules:
   * 1. Verify the authenticated user's organizationMemberId matches the request context (employees can only create timelogs for themselves).
   * 2. Validate that the specified projectId exists and the employee is assigned to it via erp_hrm_project_members.
   * 3. If taskId is provided, validate that the task exists and belongs to the specified project (task.project_id == projectId).
   * 4. Validate start_time is before end_time.
   * 5. Calculate duration_minutes as the rounded difference between end_time and start_time in minutes.
   * 6. Reject if duration_minutes <= 0.
   * 7. Set billable based on request (default false if not provided).
   *
   * Database Operations:
   * - Insert new record into erp_hrm_timelogs with:
   *   - id: generated UUID
   *   - organization_member_id: from authenticated user context
   *   - project_id: from request
   *   - task_id: from request (nullable)
   *   - start_time: from request
   *   - end_time: from request
   *   - duration_minutes: calculated
   *   - billable: from request
   *   - description: from request (nullable)
   *   - created_at: current timestamp
   *   - updated_at: current timestamp
   *   - deleted_at: null
   *
   * Authorization:
   * - Only authenticated members can create timelogs.
   * - Members can only create timelogs for their own organizationMemberId.
   * - Members must be assigned to the project specified in projectId.
   *
   * Edge Cases:
   * - If project doesn't exist: return 404
   * - If employee not assigned to project: return 403 Forbidden
   * - If task doesn't belong to project: return 400 Bad Request
   * - If start_time >= end_time: return 400 Bad Request
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimelog.ICreate,
  ): Promise<IErpHrmTimelog> {
    try {
      return await postErpHrmMemberTimelogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered and paginated list of timelog entries.
   *
   * This operation provides advanced search capabilities for time tracking data, supporting multiple filter criteria including date range, project association, task assignment, and billable status classification.
   *
   * **Viewing Modes:**
   * - **Personal View:** All employees can view their own timelog history across all time periods
   * - **Organization-Wide View:** Users with view-all-time permission can access every employee's timelogs within the organization for oversight and auditing purposes
   *
   * **Supported Filters:**
   * | Filter | Purpose |
   * |--------|---------|
   * | **Date range** | View timelogs between specific start and end dates |
   * | **Project** | Show only timelogs for a selected project |
   * | **Task** | Display timelogs associated with a specific task |
   * | **Billable status** | Filter to show only billable, only non-billable, or all timelogs |
   *
   * **Timelog Data Structure:**
   * Each timelog represents a discrete work session with:
   * - Start and end timestamps
   * - Duration calculated in minutes
   * - Project and optional task associations
   * - Billable status classification (true for client-chargeable hours)
   * - Optional description documenting work performed
   *
   * **Timesheet Status Impact:**
   * Timelogs included in submitted or approved timesheets are locked and cannot be modified by their creators, though they remain visible in listings.
   *
   * **Related Operations:**
   * - Use `POST /timelogs` to create new time entries
   * - Use `GET /timelogs/{timelogId}` to retrieve a specific timelog detail
   * - Use `PUT /timelogs/{timelogId}` to modify timelogs not in approved timesheets
   *
   * Results are paginated to handle large datasets efficiently.
   *
   * @param connection
   * @param body Search criteria including filters for date range, project, task, billable status, and pagination parameters
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Query erp_hrm_timelogs table with comprehensive filtering and pagination.
   *
   * **Authorization Logic:**
   * - Extract current user's organization_member_id from session
   * - If user has view-all-time permission: query all timelogs in the organization
   * - If user lacks view-all-time permission: restrict to timelogs where organization_member_id matches current user
   *
   * **Filter Processing:**
   * - Apply date range filter on start_time field (inclusive)
   * - Apply project_id filter when specified
   * - Apply task_id filter when specified
   * - Apply billable boolean filter when specified
   * - Apply organization_id scope filter (always enforced from session context)
   * - Include soft-deleted check: deleted_at IS NULL
   *
   * **Joins for Response Data:**
   * - Join with erp_hrm_projects to get project name and color_code
   * - Join with erp_hrm_tasks (optional) to get task title
   * - Join with erp_hrm_organization_members to get employee name
   * - Join with erp_hrm_timesheets (optional) to get timesheet status
   *
   * **Sorting:**
   * - Default sort by start_time DESC (most recent first)
   * - Support optional sort by created_at, duration_minutes, project name
   *
   * **Pagination:**
   * - Support cursor-based or offset pagination based on request
   * - Default page size: 20, max: 100
   * - Return total count for pagination metadata
   *
   * **Response Construction:**
   * - Map timelog entity to IErpHrmTimelog.ISummary DTO
   * - Include related project summary (id, name, color_code)
   * - Include related task summary if present (id, title)
   * - Include timesheet status if timelog is associated with a timesheet
   * - Calculate billable hours total for summary display
   *
   * **Business Rules Enforced:**
   * - Data isolation by organization_id (mandatory)
   * - Permission-based access control (personal vs organization-wide)
   * - Handle empty result sets gracefully
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimelog.IRequest,
  ): Promise<IPageIErpHrmTimelog.ISummary> {
    try {
      return await patchErpHrmMemberTimelogs({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information for a specific timelog entry.
   *
   * This operation fetches complete details about an individual timelog record, including its duration, description, log date, project association, optional task assignment, billable status, and the organization member who created it. Timelogs that have been soft-deleted (where deleted_at is not null) are excluded from retrieval and will result in a 404 response.
   *
   * Access to timelog details follows permission-based rules: employees can view their own timelogs, while users with time:manage permission can view any employee's timelogs across the organization. This supports personal time tracking review as well as administrative oversight for payroll, billing, and compliance purposes.
   *
   * The response includes the timelog's current state regarding timesheet inclusion. If the timelog is part of a submitted or approved timesheet, the locked status is indicated, which affects subsequent modification permissions as enforced by the system's data integrity rules.
   *
   * When a task is associated with the timelog, both the task and its parent project information are included in the response. The organization member who created the timelog is represented with summary information including their name and department context.
   *
   * This endpoint is typically called after retrieving a timelog list to display detailed information for a specific entry, or when navigating directly to a timelog record from other parts of the application such as timesheet views or project time reports.
   *
   * @param connection
   * @param timelogId The unique identifier of the timelog to retrieve
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification 1. Path parameter timelogId validation:
   *    - Validate that timelogId is a valid UUID format
   *    - Return 400 if malformed UUID
   *
   * 2. Timelog retrieval:
   *    - Query erp_hrm_timelogs table by id
   *    - Return 404 if timelog not found
   *    - Join with erp_hrm_projects for project name
   *    - Left join with erp_hrm_tasks for task details
   *    - Join with erp_hrm_organization_members for creator info
   *    - Join with erp_hrm_members for global user details
   *    - Left join with erp_hrm_timesheets to determine locking status
   *
   * 3. Permission verification:
   *    - Current user's organizationMemberId must match timelog's organizationMemberId (own timelog), OR
   *    - Current user must have time:manage permission
   *    - Verify same organization context
   *    - Return 403 if unauthorized
   *
   * 4. Timesheet status calculation:
   *    - Check if timelog is included in any timesheet via timesheetId foreign key
   *    - If timesheet.status is 'submitted' or 'approved', mark timelog as locked for editing
   *    - Include timesheet information in response if present
   *
   * 5. Response assembly:
   *    - Map timelog fields: id, description, logDate, durationMinutes, durationHours, isBillable
   *    - Include project: id, name
   *    - Include task: id, title (if taskId exists)
   *    - Include organizationMember: id, user (with email, firstName, lastName), department
   *    - Include timesheet: id, status (if timesheetId exists)
   *
   * 6. Performance optimization:
   *    - Use single query with joins to minimize database round-trips
   *    - Index on timelog(id) for fast lookup
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":timelogId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timelogId")
    timelogId: string,
  ): Promise<IErpHrmTimelog> {
    try {
      return await getErpHrmMemberTimelogsTimelogId({
        member,
        timelogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update an existing timelog record with modified attributes.
   *
   * This operation allows employees to correct errors or add missing details to their previously recorded timelogs. Users may modify the date/time range, project assignment, optional task association, description, and billable status.
   *
   * **Critical Business Rules:**
   *
   * **Self-Editing Only**: Employees can only edit their own timelogs. Attempting to edit another employee's timelog without time management permission results in rejection.
   *
   * **Timesheet Lock Constraint**: Timelogs included in timesheets with "submitted" or "approved" status cannot be edited by the employee who created them. This protects historical records from alteration during the review process. Users with the `time:manage` permission can override this restriction and edit locked timelogs for audit and correction purposes.
   *
   * **Project Assignment Validation**: When changing the project, the system validates the employee is assigned to the new project. The request is rejected if the employee is not a member of the target project.
   *
   * **Task-to-Project Consistency**: When specifying a task, the system validates the task belongs to the selected project. Requests with mismatched task/project combinations are rejected.
   *
   * **Duration Validation**: The calculated duration must be greater than zero minutes. Requests resulting in zero or negative duration are rejected.
   *
   * When successfully updated, the operation returns the complete updated timelog with recalculated duration_minutes and refreshed timestamps.
   *
   * @param connection
   * @param timelogId UUID of the timelog to update
   * @param body Timelog update data containing modifiable fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   *
   * 1. **Authorization Check**: Verify requester has permission to edit this timelog
   *    - Fetch the timelog by timelogId
   *    - If requester is not the organizationMemberId AND lacks time:manage permission → reject with 403
   *
   * 2. **Timesheet Lock Check**:
   *    - If timelog.timesheetId is not null:
   *      - Fetch the associated timesheet
   *      - If timesheet.status is 'submitted' or 'approved' AND requester lacks time:manage permission → reject with 403 (timesheet locked)
   *
   * 3. **Project Assignment Validation** (if projectId changed):
   *    - Verify requester (by organizationMemberId) is a member of the new project via erp_hrm_project_members
   *    - If not → reject with 400 (not a project member)
   *
   * 4. **Task Validation** (if taskId provided):
   *    - Verify task exists and belongs to the selected projectId
   *    - If not → reject with 400 (task not in project)
   *
   * 5. **Duration Calculation**:
   *    - Calculate duration_minutes from startTime and endTime
   *    - If duration_minutes <= 0 → reject with 400 (invalid duration)
   *
   * 6. **Permission-Based Field Update**:
   *    - If requester has time:manage permission AND organizationMemberId is provided: update organization_member_id
   *    - Otherwise: preserve original organization_member_id
   *
   * 7. **Update Fields**: project_id, task_id, start_time, end_time, duration_minutes, billable, description
   *
   * 8. **Return Complete Timelog**: Join with project, task tables and return full IErpHrmTimelog
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timelogId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timelogId")
    timelogId: string,
    @TypedBody()
    body: IErpHrmTimelog.IUpdate,
  ): Promise<IErpHrmTimelog> {
    try {
      return await putErpHrmMemberTimelogsTimelogId({
        member,
        timelogId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes a timelog from the system.
   *
   * This operation allows employees to delete their own timelog entries that were created in error or are no longer relevant. Deletion permanently removes the timelog record from the database along with any associations to timesheets.
   *
   * Access is governed by permission rules:
   *
   * 1. Self-Service Deletion: Employees may delete their own timelogs only when those entries are NOT included in any submitted or approved timesheet. This restriction protects timesheet integrity during the review process and preserves historical records that have been supervisor-approved.
   *
   * 2. Administrative Override: Users holding the time:manage permission may delete any employee's timelogs regardless of timesheet status. This capability enables administrators to remove duplicate entries, correct significant errors, or clean up test data without requiring employee action.
   *
   * When a timelog is deleted, the system emits a timelog deleted event to notify relevant parties. Deleted timelogs are permanently removed and cannot be recovered.
   *
   * This operation requires authentication and organization context selection. The caller must have appropriate permissions based on their role and the timelog's ownership and status.
   *
   * @param connection
   * @param timelogId UUID identifier of the timelog to delete (global scope)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implement DELETE operation for erp_hrm_timelogs table by UUID identifier.
   *
   * **Authorization Logic:**
   * 1. Extract authenticated organization member ID from JWT context
   * 2. Load the target timelog by timelogId path parameter
   * 3. Check if timelog belongs to current organization context
   * 4. Verify ownership: timelog.organization_member_id matches caller
   * 5. Check timesheet association: If timelog.timesheet_id exists, load the timesheet
   * 6. If timelog is in submitted or approved timesheet AND caller does not have time:manage permission: REJECT with 403 Forbidden
   * 7. If timelog belongs to another employee AND caller does not have time:manage permission: REJECT with 403 Forbidden
   *
   * **Database Operations:**
   * - DELETE FROM erp_hrm_timelogs WHERE id = {timelogId}
   * - Cascades: Soft delete via deleted_at timestamp update (actual record retained for audit)
   *
   * **Event Emission:**
   * - Emit timelog deleted event payload:
   *   - timelog_id: deleted timelog UUID
   *   - organization_member_id: original owner
   *   - project_id: associated project
   *   - deleted_by: caller organization member ID
   *   - deleted_at: timestamp
   *   - duration_minutes: for record
   *
   * **Edge Cases:**
   * - Timelog already deleted (deleted_at not null): Return 404 Not Found
   * - Timelog not found: Return 404 Not Found
   * - Timelog in approved timesheet without time:manage: 403 Forbidden
   * - Caller's organization context mismatch: 403 Forbidden
   *
   * **Permissions Required:**
   * - Must be member actor with organization context
   * - time:manage permission OR ownership of the timelog with no locked timesheet association
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete(":timelogId")
  public async erase(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timelogId")
    timelogId: string & tags.Format<"uuid">,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberTimelogsTimelogId({
        member,
        timelogId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
