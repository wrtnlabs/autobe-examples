import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTimelog } from "../../../../api/structures/IErpHrmTimelog";
import { IPageIErpHrmTimelog } from "../../../../api/structures/IPageIErpHrmTimelog";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberTimelogsTimelogId } from "../../../../providers/deleteErpHrmMemberTimelogsTimelogId";
import { getErpHrmMemberTimelogsTimelogId } from "../../../../providers/getErpHrmMemberTimelogsTimelogId";
