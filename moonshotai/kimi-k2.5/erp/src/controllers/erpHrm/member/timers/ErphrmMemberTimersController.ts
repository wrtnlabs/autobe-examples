import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia, { tags } from "typia";

import { IErpHrmTimer } from "../../../../api/structures/IErpHrmTimer";
import { IPageIErpHrmTimer } from "../../../../api/structures/IPageIErpHrmTimer";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { patchErpHrmMemberTimers } from "../../../../providers/patchErpHrmMemberTimers";
import { postErpHrmMemberTimers } from "../../../../providers/postErpHrmMemberTimers";
import { postErpHrmMemberTimersTimerIdStop } from "../../../../providers/postErpHrmMemberTimersTimerIdStop";
import { putErpHrmMemberTimersTimerId } from "../../../../providers/putErpHrmMemberTimersTimerId";

@Controller("/erpHrm/member/timers")
export class ErphrmMemberTimersController {
  /**
   * Stop an active timer and convert it into a timelog entry.
   *
   * This operation allows employees to end their live time tracking session. When stopped, the timer calculates the elapsed duration from when it was started to the current moment, rounding to the nearest minute. The system then creates a permanent timelog record containing the project, optional task, and description from the timer session.
   *
   * The timer record is removed after successful conversion to timelog. The resulting timelog is subject to all standard timelog business rules and can be included in timesheets for approval workflows. The billable status is determined based on project defaults or organizational settings.
   *
   * This operation enforces that only the timer owner can stop their timer. Managers or admins with appropriate time management permissions may also stop timers on behalf of other employees. After successful stop, the timer ceases to exist and only the timelog remains for historical tracking.
   *
   * The response includes the created timelog with all associated data including the calculated duration, project and task references, and the description carried over from the timer session.
   *
   * @param connection
   * @param timerId The unique identifier of the active timer to stop (UUID format)
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Validate that the timer exists by querying
     *   erp_hrm_timers table with the provided timerId. Verify that the
     *   requesting user has permission to stop this timer - either as the owner
     *   (matching organization_member_id) or having time management permission
     *   for the organization. Calculate duration_minutes as the difference
     *   between the timer's started_at timestamp and current server time,
     *   rounded to nearest minute (standard rounding: 0.5 and above rounds up).
     *   Create a new erp_hrm_timelogs record with: id = new UUID,
     *   organization_member_id = timer.organization_member_id, project_id =
     *   timer.project_id, task_id = timer.task_id, timesheet_id = null,
     *   start_time = timer.started_at, end_time = current timestamp,
     *   duration_minutes = calculated duration, billable = true (default, or
     *   derived from project settings), description = timer.description,
     *   created_at/updated_at = current timestamp. Delete the timer record from
     *   erp_hrm_timers after successful timelog creation. Return the created
     *   timelog with all relationships populated. Handle error cases: timer not
     *   found (404), timer doesn't belong to user and caller lacks management
     *   permissions (403), database transaction failures (500). Transaction
     *   must be atomic - timelog creation and timer deletion succeed together
     *   or fail together.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post(":timerId/stop")
  public async stop(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
  ): Promise<IErpHrmTimer.IStop> {
    try {
      return await postErpHrmMemberTimersTimerIdStop({
        member,
        timerId,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Start a new timer to track work time in real-time.
   *
   * This operation creates an active timer session for the authenticated employee, enabling live tracking of work duration as it occurs. The timer begins counting immediately upon creation and continues running until explicitly stopped via the timer stop endpoint or discarded.
   *
   * Each employee can have at most one active timer at any given time. If the employee already has a running timer, this operation will reject the request with an appropriate error.
   *
   * The timer must be associated with a project that the employee is a member of. Optionally, a specific task within that project can be selected for more granular time tracking. An optional description can be provided to document the activity being performed.
   *
   * When the timer is eventually stopped, the system automatically calculates the elapsed duration and creates a timelog entry containing the project, task, description, and duration information.
   *
   * Timers persist across sessions and logouts - a running timer will continue tracking time even if the employee logs out and back in. There is no automatic timeout or maximum duration limit for timers.
   *
   * @param connection
   * @param body Timer creation information including project, optional task, and optional description
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Create a new timer for the authenticated employee
     *   with the following validations and behaviors:
   *
   * 1. Single Active Timer Check: Query erp_hrm_timers to verify the employee does not already have an active timer (unique constraint on organization_member_id). If an active timer exists, reject with error indicating only one timer allowed.
   *
   * 2. Project Membership Validation: Verify the provided project_id exists and the employee is a member via erp_hrm_project_members table. If not a project member, reject the request.
   *
   * 3. Task Validation (if provided): If task_id is specified, verify the task exists in erp_hrm_tasks and belongs to the selected project (task.project_id == project_id). If task belongs to a different project, reject.
   *
   * 4. Timer Creation: Insert record into erp_hrm_timers with:
   *    - organization_member_id: current authenticated employee's member ID
   *    - project_id: from request
   *    - task_id: from request (nullable)
   *    - description: from request (nullable)
   *    - started_at: CURRENT_TIMESTAMP
   *    - created_at/updated_at: CURRENT_TIMESTAMP
   *
   * 5. Return the created timer record including calculated current duration based on started_at.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async create(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.ICreate,
  ): Promise<IErpHrmTimer> {
    try {
      return await postErpHrmMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve a filtered, paginated list of active timer sessions.
   *
   * Timers represent live time tracking sessions initiated by employees. Each timer records the exact moment tracking began and associates the session with a project and optionally a specific task within that project. When stopped, timers automatically convert to timelog entries, meaning only actively running timers appear in this endpoint.
   *
   * Per business rules, each employee may have at most one active timer at any given time, enforced by the database unique constraint. Timers persist indefinitely until explicitly stopped or discarded by the employee. There is no automatic timeout or expiration mechanism for running timers.
   *
   * This operation provides advanced filtering capabilities including partial text matching on timer descriptions, filtering by specific projects or tasks, and time range queries based on when the timer was started. Results are returned in paginated format optimized for dashboard and time-tracking interface displays.
   *
   * Access is restricted to authenticated members; users with time view all permission may see timers across all organization members, while regular members can only view their own active timer.
   *
   * @param connection
   * @param body Timer search criteria with filters and pagination parameters
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_timers table with
     *   organization-scoped filtering and pagination.
   *
   * 1. Authorization: Validate member authentication token. Apply data isolation based on organization context from session.
   *
   * 2. Query Logic:
   * - Join with erp_hrm_organization_members to get employee context
   * - Join with erp_hrm_projects to include project details in summary
   * - Optional join with erp_hrm_tasks to include task details
   * - Filter by organization_id from session context
   * - Apply filters from request: project_id, task_id, description partial match (gin_trgm index), started_at range
   *
   * 3. Search/Filters:
   * - projectId: Filter timers for specific project
   * - taskId: Filter timers for specific task
   * - description: Partial text search using trigram matching
   * - startedAtFrom/startedAtUntil: Time range filtering
   *
   * 4. Sorting: By started_at DESC (most recent first) or specified sort field
   *
   * 5. Pagination: Cursor-based or offset-based per request parameters
   *
   * 6. Response: Return paginated timer summaries with related project/task data. The unique constraint on organization_member_id ensures at most one timer per employee.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmTimer.IRequest,
  ): Promise<IPageIErpHrmTimer.ISummary> {
    try {
      return await patchErpHrmMemberTimers({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Update the details of an active running timer.
   *
   * This operation allows employees to modify their running timer's categorization while tracking is in progress. The description, project assignment, and optional task association can be updated to correct mistakes made during initial timer creation.
   *
   * The timer must belong to the requesting employee. The new project must be one the employee is assigned to. If a task is specified, it must belong to the selected project. Setting task_id to null removes the task association.
   *
   * The started_at timestamp and owner (organization_member_id) cannot be changed once the timer is created.
   *
   * @param connection
   * @param timerId Target timer's ID
   * @param body Timer update fields
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update an existing active timer while it is
     *   running. Query the erp_hrm_timers table by id to verify the timer
     *   exists and belongs to the requesting organization member. Validate that
     *   the provided project_id exists and the employee is a member of that
     *   project (check erp_hrm_project_members). If task_id is provided,
     *   validate it belongs to the selected project (check erp_hrm_tasks).
     *   Update the description, project_id, and task_id fields. Return the
     *   complete updated timer record. The started_at and
     *   organization_member_id fields are immutable.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put(":timerId")
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("timerId")
    timerId: string & tags.Format<"uuid">,
    @TypedBody()
    body: IErpHrmTimer.IUpdate,
  ): Promise<IErpHrmTimer> {
    try {
      return await putErpHrmMemberTimersTimerId({
        member,
        timerId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
