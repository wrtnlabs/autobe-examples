import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../../api/structures/IErpHrmMember";
import { MemberAuth } from "../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../decorators/payload/MemberPayload";
import { deleteErpHrmMemberProfileAvatar } from "../../../../../providers/deleteErpHrmMemberProfileAvatar";
import { postErpHrmMemberProfileAvatar } from "../../../../../providers/postErpHrmMemberProfileAvatar";

@Controller("/erpHrm/member/profile/avatar")
export class ErphrmMemberProfileAvatarController {
  /**
   * Upload or update the authenticated user's global profile avatar image.
   *
   * This endpoint allows authenticated members to upload a new avatar image to their global profile. Avatar images serve as visual identification of the user throughout the platform and are shared across all organizations the user belongs to.
   *
   * To upload an avatar, the client first uploads the image file to storage to obtain a URI, then submits that URI to this endpoint. The system validates the image format (JPEG, PNG, GIF), checks file size limits, and ensures the file is not corrupted. Images with transparency are preserved where the format supports it.
   *
   * Upon successful upload, the system processes the image to generate appropriately sized variants for different display contexts including user listings, profile views, and small icon contexts. When a new avatar is uploaded, the previous avatar image is replaced with the new one.
   *
   * After successful avatar update, the system emits an avatar image updated notification in real-time via WebSocket or Server-Sent Events to all active sessions belonging to the user. This ensures that avatar changes are immediately reflected across all organization contexts where the user is active.
   *
   * Users can also remove their avatar entirely by submitting a null or empty value, reverting to a default placeholder image.
   *
   * @param connection
   * @param body Avatar image file URI reference for association with user profile
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Receive the uploaded avatar image file from the
     *   multipart/form-data request. Validate the file type against allowed
     *   formats (JPEG, PNG, GIF). Validate the file size against maximum limits
     *   defined in the media processing rules. Perform virus scanning and
     *   content validation to ensure the file is not malicious or corrupted.
   *
   * Store the validated image file and generate thumbnail variants for different display contexts (small icons, profile views, user listings). Process images with transparency preservation and proper color profile handling to ensure consistent display across devices.
   *
   * Update the erp_hrm_members table to set the avatar field with the URI reference to the stored image. The operation should use the authenticated user's member ID from the session context.
   *
   * If a previous avatar exists, mark it for cleanup or replacement based on storage policies. Emit an avatar image updated notification event via WebSocket or Server-Sent Events to all active sessions belonging to the user as specified in section [301].
   *
   * Return the updated member record with the new avatar URI in the response.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post()
  public async updateAvatar(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMember.IAvatarUpload,
  ): Promise<IErpHrmMember> {
    try {
      return await postErpHrmMemberProfileAvatar({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Permanently removes the authenticated user's profile avatar.
   *
   * This operation clears the avatar field from the user's profile, effectively removing their profile picture. When an avatar exists, the operation will trigger file storage cleanup for the associated image resource and notify relevant parties of the avatar change.
   *
   * The operation acts as a hard delete - the avatar file reference is permanently removed from the profile. If no avatar is currently set, the operation returns a 404 Not Found response.
   *
   * @param connection
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Authenticate the member via their session token.
     *   Retrieve the member's profile and check if an avatar exists. If an
     *   avatar URI is present, clear the avatar field in the profile record.
     *   Trigger file cleanup for the associated storage resource per storage
     *   management rules (section 386). Send avatar update notification to
     *   relevant parties per notification rules (section 301). Return 204 No
     *   Content on success, or 404 if no avatar exists to remove.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Delete()
  public async erase(
    @MemberAuth()
    member: MemberPayload,
  ): Promise<void> {
    try {
      return await deleteErpHrmMemberProfileAvatar({
        member,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
