import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { MemberAuth } from "../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../decorators/payload/MemberPayload";
import { putErpHrmMemberProfile } from "../../../../providers/putErpHrmMemberProfile";

@Controller("/erpHrm/member/profile")
export class ErphrmMemberProfileController {
  /**
   * Update the global profile information of the currently authenticated member.
   *
   * This operation allows members to modify their personal profile information that is shared across all organizations they belong to. The profile includes the display name shown throughout the interface, an optional avatar image for visual identification, and an optional phone number for contact purposes.
   *
   * Members have exclusive rights to modify their own global profile. No other user, including organization owners or administrators, can modify another user's global profile. Profile modifications take effect immediately across all organization contexts where the user is a member.
   *
   * The display name appears in place of the email address throughout the system, providing a more personalized experience. Avatar images provide visual identification, while phone numbers serve as supplementary contact information. All profile fields are optional and can be added, modified, or removed at any time.
   *
   * @param connection
   * @param body Profile update data with optional displayName, avatar, and phoneNumber fields
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Update the erp_hrm_members record for the currently authenticated user. Validate that displayName (if provided) is a non-empty string. Validate that phoneNumber (if provided) follows acceptable phone number format. Handle avatar image update through file upload URL reference if changed. Update only the fields provided in the request body - partial updates are allowed. Ensure member is authenticated and has an active session before processing. Return the complete updated member profile with all global profile fields.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Put()
  public async update(
    @MemberAuth()
    member: MemberPayload,
    @TypedBody()
    body: IErpHrmMember.IUpdate,
  ): Promise<IErpHrmMember> {
    try {
      return await putErpHrmMemberProfile({
        member,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
