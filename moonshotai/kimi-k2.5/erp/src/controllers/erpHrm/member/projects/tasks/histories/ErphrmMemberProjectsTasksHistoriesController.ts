import { TypedBody, TypedParam, TypedRoute } from "@nestia/core";
import { Controller } from "@nestjs/common";
import typia from "typia";

import { IErpHrmTaskHistory } from "../../../../../../api/structures/IErpHrmTaskHistory";
import { IPageIErpHrmTaskHistory } from "../../../../../../api/structures/IPageIErpHrmTaskHistory";
import { MemberAuth } from "../../../../../../decorators/MemberAuth";
import { MemberPayload } from "../../../../../../decorators/payload/MemberPayload";
import { getErpHrmMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId } from "../../../../../../providers/getErpHrmMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId";
import { patchErpHrmMemberProjectsProjectIdTasksTaskIdHistories } from "../../../../../../providers/patchErpHrmMemberProjectsProjectIdTasksTaskIdHistories";

@Controller("/erpHrm/member/projects/:projectId/tasks/:taskId/histories")
export class ErphrmMemberProjectsTasksHistoriesController {
  /**
   * Retrieve a paginated list of task history entries for a specific task within a project.
   *
   * This operation returns the complete audit trail showing all status changes made to the task throughout its lifecycle. Each history entry includes the previous status, new status, timestamp of the change, and the user who made the change.
   *
   * **Access Control:** Users can only view task history if they have permission to view the parent task itself. Project members can view history for tasks within their assigned projects. Users with project view permissions can access history for all tasks in those projects.
   *
   * **Filtering Options:** The request supports filtering by status, date ranges, and user. Results can be sorted by timestamp (default: descending) to show most recent changes first.
   *
   * @param connection
   * @param projectId Project unique identifier (global scope)
   * @param taskId Task unique identifier (scoped to project)
   * @param body Search criteria and pagination parameters for task history listing
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query erp_hrm_task_histories table joining with
     *   erp_hrm_tasks and erp_hrm_projects for access control validation.
   *
   * **Access Control:**
   * - Validate projectId exists and is accessible to current user
   * - Validate taskId exists within the specified project
   * - Verify current user has task view permission for this project
   * - Reject if user cannot view the parent task
   *
   * **Query Logic:**
   * - Filter by taskId (exact match from path parameter)
   * - Apply optional filters: status transitions, date ranges, changedBy user
   * - Sort by createdAt desc (newest first) by default
   * - Support pagination (cursor-based or offset-based)
   * - Join with erp_hrm_members and erp_hrm_users for user details
   * - Join with erp_hrm_tasks for task context
   *
   * **Permissions:**
   * - Project members: view history for tasks in their projects
   * - Users with project:view permission: view all task history
   * - Users with project-lead role in project: view history for their project tasks
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Patch()
  public async index(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedParam("taskId")
    taskId: string,
    @TypedBody()
    body: IErpHrmTaskHistory.IRequest,
  ): Promise<IPageIErpHrmTaskHistory.ISummary> {
    try {
      return await patchErpHrmMemberProjectsProjectIdTasksTaskIdHistories({
        member,
        projectId,
        taskId,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Retrieve detailed information about a specific task history entry.
   *
   * TaskHistory represents an immutable audit trail recording status changes for tasks. Each entry captures the complete history of a task state transition including previous and new status values, the user who performed the change, an optional reason for the change, and precise timestamp.
   *
   * This operation enables retrospective analysis and compliance documentation by returning the full details of a status change record. It supports bottleneck identification by revealing where tasks tend to stall, and provides permanent audit trails satisfying compliance requirements.
   *
   * A user can only view a task's history entries if they have permission to view the parent task itself. Project members can view history for tasks within their assigned projects. Users with project view permissions can access history for all tasks in those projects.
   *
   * The operation requires all three path parameters to precisely identify the history entry within its project and task context. If the historyId does not exist, or if it does not belong to the specified taskId, or if the task does not belong to the specified projectId, the request will return a not found error.
   *
   * @param connection
   * @param projectId Target project's ID
   * @param taskId Target task's ID
   * @param historyId Target history entry's ID
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Query the erp_hrm_task_histories table by primary
     *   key id matching the historyId path parameter. Validate that the
     *   retrieved history record has erp_hrm_task_id matching the taskId path
     *   parameter. Additionally, verify the task belongs to the specified
     *   projectId through join with erp_hrm_tasks table - the task's
     *   erp_hrm_project_id must match the provided projectId. This nested
     *   validation ensures users cannot access history entries outside their
     *   authorized project scope.
   *
   * Join with erp_hrm_tasks to include task context information in the response. Join with erp_hrm_members to include the member information who performed the change (changedByMember relation). Apply authorization check: verify the requesting member has permission to view the parent task - this can be checked by confirming the member is either assigned to view tasks in this project or has explicit project view permission.
   *
   * Return the complete history record including: id, erp_hrm_task_id (as taskId), erp_hrm_member_id (as changedByMemberId), previous_status, new_status, change_reason, created_at. Include nested task information and changedBy member information to provide full context for the status change.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Get(":historyId")
  public async at(
    @MemberAuth()
    member: MemberPayload,
    @TypedParam("projectId")
    projectId: string,
    @TypedParam("taskId")
    taskId: string,
    @TypedParam("historyId")
    historyId: string,
  ): Promise<IErpHrmTaskHistory> {
    try {
      return await getErpHrmMemberProjectsProjectIdTasksTaskIdHistoriesHistoryId(
        {
          member,
          projectId,
          taskId,
          historyId,
        },
      );
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
