  /**
   * Transition a project from active to completed status.
   *
   * This operation marks the completion of a project work initiative. Once completed, a project preserves all existing data including timelogs and task history, but cannot receive new timelogs (as constrained by business rules in section 246). The transition is irreversible from a workflow perspective.
   *
   * ## Permission Requirements
   *
   * Users with project management permission within the organization can complete projects. The requesting member must have appropriate role permissions to modify project status.
   *
   * ## Project Status Lifecycle
   *
   * Projects progress through defined lifecycle states (section 158):
   * - **active**: Project is operational and can receive new timelogs and tasks
   * - **archived**: Project is temporarily inactive, preserves data but blocks new timelogs
   * - **completed**: Project work is finished, preserves all data but blocks new timelogs
   *
   * From active status, projects can be transitioned to either archived or completed status. Completed projects represent final closure of project work.
   *
   * ## Business Constraints
   *
   * - Only projects in 'active' status can be transitioned to 'completed'
   * - The project must belong to the requesting member's current organization context (enforced via organization isolation)
   * - Completed projects cannot receive new timelogs
   *
   * ## Related Operations
   *
   * - `PATCH /projects/{projectId}/archive` - Transitions active projects to archived status
   * - `PUT /projects/{projectId}` - General project update for other attributes
   * - `GET /projects/{projectId}` - Retrieve project details before/after transition
   *
   * @param connection
   * @param projectId Target project's unique identifier (UUID format)
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation should validate:
   * 1. The requesting member has project management permission in their current organization context
   * 2. The project exists in erp_hrm_projects table and organization_id matches the member's current organization
   * 3. The project is currently in 'active' status (not already archived or completed)
   * 4. Update the status field from 'active' to 'completed' in a single transaction
   * 5. Update the updated_at timestamp to current time
   *
   * Database query:
   * - UPDATE erp_hrm_projects SET status = 'completed', updated_at = NOW() WHERE id = {projectId} AND organization_id = {currentOrganizationId} AND status = 'active' AND deleted_at IS NULL
   *
   * Return the complete updated project record using IErpHrmProject type. Include all related data: organization, project members, tasks, etc.
   *
   * Error handling:
   * - 404: Project not found or belongs to different organization
   * - 403: Member lacks project management permission
   * - 409: Project is already archived or completed (invalid state transition)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
