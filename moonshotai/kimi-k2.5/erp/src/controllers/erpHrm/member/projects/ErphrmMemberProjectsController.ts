  /**
   * Reactivate an archived project, transitioning its status from 'archived' to 'active'.
   *
   * This operation allows users with project management permissions to restore an archived project to active status, making it available for new timelog entries, task creation, and member assignments again.
   *
   * Only projects in 'archived' status can be reactivated. Attempting to reactivate a project in 'active' or 'completed' status will result in a validation error.
   *
   * When reactivated, the project's status is changed to 'active', and the updated_at timestamp is refreshed to reflect the status change. All project data including tasks, memberships, and historical timelogs remain intact.
   *
   * This operation is the inverse of the archive operation and provides a way to temporarily suspend and later resume project work without losing any data.
   *
   * @param connection
   * @param projectId UUID of the project to reactivate
   * @x-autobe-authorization-type null
   * @x-autobe-authorization-actor member
   * @x-autobe-specification Implementation steps:
   *
   * 1. Validate that the authenticated user has project management permission for the organization
   *
   * 2. Find the project by projectId:
   *    - Query erp_hrm_projects table where id = projectId AND deleted_at IS NULL
   *    - If not found, throw PROJECT_NOT_FOUND error
   *
   * 3. Validate current status:
   *    - If project.status != 'archived', throw INVALID_STATUS_TRANSITION error
   *    - Only archived projects can be reactivated; completed projects must use reopen instead
   *
   * 4. Update the project:
   *    - Set status = 'active'
   *    - Set updated_at = current timestamp
   *    - Save changes
   *
   * 5. Return the updated project entity
   *
   * Edge cases:
   * - Project is soft-deleted (deleted_at not null): Return PROJECT_NOT_FOUND
   * - Project is already active: Return ALREADY_ACTIVE error
   * - Project is completed: Return INVALID_STATUS_TRANSITION error
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
