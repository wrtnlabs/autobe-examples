  /**
   * Soft deletes a specific task from a project.
   *
   * This operation marks a task as deleted by populating the deleted_at timestamp. Soft-deleted tasks are not permanently removed from the database; they are flagged to exclude them from standard query results while preserving the data for audit and historical purposes.
   *
   * Tasks can be recovered before final cleanup through appropriate administrative operations if needed.
   *
   * Before deletion, the system verifies that the requesting user has appropriate permissions - either project-lead role for this specific project or organization-level project management permissions. This implements the task management authority rules defined in the business documentation.
   *
   * When a task is soft-deleted, associated task history records remain in the system unchanged for audit purposes. Any timelogs that were logged against this task are preserved but will reference a deleted task. Child subtasks (tasks with parent_task_id referencing this task) will cascade delete as defined in the database schema with onDelete: Cascade configuration.
   *
   * The task must exist within the specified project and not already be soft-deleted. Attempting to delete a task that does not exist, is already deleted, or belongs to a different project will result in a not found error.
   *
   * @param connection
   * @param projectId Project unique identifier (UUID format) - the project containing the task to delete
   * @param taskId Task unique identifier (UUID format) - the task to be deleted
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Service Implementation Requirements:
   *
   * 1. Authorization Validation:
   *    - Verify the requesting member has permission to delete tasks in this project
   *    - Accept if: member has 'project:manage' permission at organization level
   *    - Accept if: member has 'project-lead' role for this specific project (check erp_hrm_project_members table)
   *    - Reject with 403 Forbidden if neither condition is met
   *
   * 2. Task Retrieval and Validation:
   *    - Query erp_hrm_tasks table by taskId (UUID)
   *    - Verify task exists and belongs to the specified projectId
   *    - Verify task.deleted_at is null (not already deleted)
   *    - Return 404 Not Found if task doesn't exist, is already deleted, or belongs to different project
   *
   * 3. Soft Delete Execution:
   *    - Update erp_hrm_tasks record setting deleted_at = NOW()
   *    - The database has @@index([project_id, status]) and other indexes that remain valid
   *    - Cascade delete is configured for child tasks via @relation("recursive") with onDelete: Cascade
   *
   * 4. Activity Logging (if activity log system is integrated):
   *    - Log the task deletion event with task ID, project ID, and member who performed deletion
   *
   * 5. Return the soft-deleted task entity including the now-populated deleted_at timestamp
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
