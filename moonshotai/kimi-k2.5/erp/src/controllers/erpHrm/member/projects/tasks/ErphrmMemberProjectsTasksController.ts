  /**
   * Update an existing task within a project.
   *
   * This operation allows authorized users to modify task details including title, description, status, priority, due date, estimated hours, and assignment. Task updates are subject to authorization rules based on the user's role within the project.
   *
   * Authorization is checked in the following order:
   * 1. Users with organization-level project management permission can update any task
   * 2. Users assigned the project-lead role for this specific project can update tasks within that project
   * 3. Users without either of these permissions receive an authorization error
   *
   * Project leads have task management authority limited strictly to the projects where they hold the lead designation. They can edit existing tasks including modifying task details and reassigning tasks to other project members. However, project leads cannot manage tasks in projects where they are only regular members.
   *
   * When updating task status changes (e.g., from Open to In-Progress, or In-Progress to Completed), the system automatically records the status change in the task history for audit purposes. The assigned employee must be a member of the project.
   *
   * The operation performs validation to ensure:
   * - The task exists within the specified project
   * - The assigned employee (if provided) is a member of the project
   * - The parent task relationship (if modified) maintains single-level nesting constraint
   * - Status transitions follow the allowed workflow states
   *
   * If the task is being reassigned, the new assignee is validated to ensure they are a project member.
   *
   * @param connection
   * @param projectId The unique identifier of the project containing the task (global scope)
   * @param taskId The unique identifier of the task to update (scoped to project)
   * @param body Task update information with optional fields for partial updates
     * @x-autobe-authorization-type null
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Update operation for erp_hrm_tasks table.
   *
   * 1. Authorization Validation:
   *    - Check if current user has organization-level project management permission
   *    - If not, verify user is assigned project-lead role for this specific project via erp_hrm_project_members
   *    - Reject with 403 Forbidden if neither condition is met
   *
   * 2. Resource Lookup:
   *    - Query erp_hrm_tasks by taskId and projectId (composite lookup for security)
   *    - Verify task exists and belongs to the specified project
   *    - Return 404 Not Found if task doesn't exist
   *
   * 3. Update Processing:
   *    - Validate assigned_to_id: if provided, check erp_hrm_project_members that user is member of this project
   *    - Validate parent_task_id: if provided, ensure parent task exists in same project and doesn't exceed nesting depth
   *    - Update allowed fields: title, description, status, priority, due_date, estimated_hours, assigned_to_id
   *    - If status changes: automatically insert record into erp_hrm_task_histories with old_status, new_status, changed_by_id, and changed_at timestamp
   *    - Update updated_at timestamp automatically
   *
   * 4. Return updated task entity with all relations populated (project, assignee, parentTask)
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
