import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmMember } from "../../../../api/structures/IErpHrmMember";
import { postErpHrmAuthMemberJoin } from "../../../../providers/postErpHrmAuthMemberJoin";
import { postErpHrmAuthMemberLogin } from "../../../../providers/postErpHrmAuthMemberLogin";
import { postErpHrmAuthMemberRefresh } from "../../../../providers/postErpHrmAuthMemberRefresh";

@Controller("/erpHrm/auth/member")
export class ErphrmAuthMemberController {
  /**
   * Registers a new member account in the erpHrm system.
   *
   * This operation creates a new member identity with email/password credentials. It validates that the email is unique and properly formatted, hashes the password securely using bcrypt, and creates the member record in the erp_hrm_members table. Upon successful registration, the system generates email verification tokens stored in erp_hrm_member_email_verifications table and creates a new authenticated session.
   *
   * The registration flow includes: email validation, password strength verification, member record creation, session token generation, and email verification token issuance. The returned IErpHrmMember.IAuthorized contains both access_token for immediate API use and refresh_token for token renewal.
   *
   * This is a public endpoint that requires no authentication. The authorizationActor is "member", indicating this operation is for the member actor type. After registration, members can proceed to log in and access organization features.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member registration credentials including email, password, first name, and last name.
     * @x-autobe-authorization-type join
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation: 1) Validate email format and
     *   uniqueness against erp_hrm_members table; 2) Hash password using bcrypt
     *   with salt rounds; 3) Create member record with provided email,
     *   password_hash, first_name, last_name; 4) Generate email verification
     *   token and store in erp_hrm_member_email_verifications; 5) Send
     *   verification email; 6) Generate JWT access_token and refresh_token,
     *   store session in erp_hrm_member_sessions; 7) Return
     *   IErpHrmMember.IAuthorized with tokens and member info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.IJoin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Authenticates an existing member with email and password credentials.
   *
   * This operation validates member credentials by looking up the email in erp_hrm_members table and verifying the bcrypt password hash. It ensures the account is active (deleted_at is null). Upon successful authentication, a new session is created in erp_hrm_member_sessions table storing the JWT tokens along with connection metadata (IP address, referrer, href).
   *
   * The login flow generates fresh access_token and refresh_token pair for the authenticated session. The access_token is used for subsequent API requests, while the refresh_token allows obtaining new access tokens when the current one expires without requiring re-authentication.
   *
   * This is a public endpoint requiring no prior authentication. The authorizationActor is "member", indicating this operation is for the member actor type. Failed attempts should not reveal whether email or password was incorrect for security. The returned IErpHrmMember.IAuthorized includes complete member profile information along with the authentication tokens.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Member login credentials with email and password.
     * @x-autobe-authorization-type login
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation: 1) Lookup member by email in
     *   erp_hrm_members table; 2) Verify bcrypt password hash matches; 3) Check
     *   if account is not soft-deleted (deleted_at is null); 4) Generate new
     *   JWT access_token and refresh_token; 5) Create session record in
     *   erp_hrm_member_sessions with ip, href, referrer metadata; 6) Return
     *   IErpHrmMember.IAuthorized with tokens and member profile data.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("login")
  public async login(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmMember.ILogin,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberLogin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Refreshes an expired access token using a valid refresh token.
   *
   * This operation allows extending authentication sessions without requiring the member to re-enter credentials. The refresh_token from the request is validated against the erp_hrm_member_sessions table to ensure it exists and has not expired (expired_at > current time). If valid, a new token pair is generated and the session record is updated.
   *
   * Token refresh is essential for maintaining secure long-lived sessions. The access_token typically has a short lifetime (e.g., 15 minutes) while the refresh_token remains valid longer (e.g., 7 days). When the access_token expires, clients can call this endpoint to obtain fresh tokens.
   *
   * The operation requires a valid refresh token but no active access token (authorizationType: refresh). The authorizationActor is "member", indicating this operation is for the member actor type. Invalid or expired refresh tokens result in authentication errors requiring the member to log in again. The returned IErpHrmMember.IAuthorized contains the new token pair with updated expiration times.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Refresh token used to obtain new access token.
     * @x-autobe-authorization-type refresh
     * @x-autobe-authorization-actor member
     * @x-autobe-specification Implementation: 1) Validate the provided
     *   refresh_token; 2) Lookup existing session in erp_hrm_member_sessions by
     *   refresh_token; 3) Verify session is not expired (compare expired_at
     *   with current time); 4) Generate new JWT access_token and refresh_token
     *   pair; 5) Update session record with new tokens; 6) Return
     *   IErpHrmMember.IAuthorized with updated tokens and member info.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmMember.IRefresh,
  ): Promise<IErpHrmMember.IAuthorized> {
    try {
      return await postErpHrmAuthMemberRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
