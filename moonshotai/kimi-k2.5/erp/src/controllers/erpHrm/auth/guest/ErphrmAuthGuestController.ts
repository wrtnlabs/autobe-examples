import { TypedBody, TypedRoute } from "@nestia/core";
import { Controller, Ip } from "@nestjs/common";
import typia from "typia";

import { IErpHrmGuest } from "../../../../api/structures/IErpHrmGuest";
import { postErpHrmAuthGuestJoin } from "../../../../providers/postErpHrmAuthGuestJoin";
import { postErpHrmAuthGuestRefresh } from "../../../../providers/postErpHrmAuthGuestRefresh";

@Controller("/erpHrm/auth/guest")
export class ErphrmAuthGuestController {
  /**
   * Initialize guest access by creating a guest account identified by device fingerprint.
   *
   * This endpoint creates a temporary guest session for unauthenticated visitors. The device fingerprint uniquely identifies the visitor's browser/device. Upon successful creation, a guest record is established in erp_hrm_guests and a session is created in erp_hrm_guest_sessions with generated JWT tokens.
   *
   * The session includes access and refresh tokens for subsequent API calls. Client metadata (IP address, current href, referrer) is captured for audit purposes. The session has an expiration time after which it becomes invalid.
   *
   * No authentication is required - this is a public endpoint for first-time visitors.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest initialization request with device fingerprint and client metadata
   * @x-autobe-authorization-type join
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Service implementation: Validate the device fingerprint from request. Create or find existing guest record by device fingerprint. Generate new guest session with JWT access and refresh tokens. Store session in erp_hrm_guest_sessions with IP, href, referrer tracking. Set expiration based on schema's expired_at pattern. Return tokens in IErpHrmGuest.IAuthorized format.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("join")
  public async join(
    @Ip()
    ip: string,
    @TypedBody()
    body: IErpHrmGuest.IJoin,
  ): Promise<IErpHrmGuest.IAuthorized> {
    try {
      return await postErpHrmAuthGuestJoin({
        ip,
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }

  /**
   * Extend guest session validity by refreshing authentication tokens.
   *
   * This endpoint allows an active guest session to obtain new access tokens before expiration. The existing refresh token is validated against the erp_hrm_guest_sessions table, checking that the session exists and has not expired (expired_at timestamp validation).
   *
   * Upon successful validation, new tokens are generated with refreshed expiration times. The session record is updated with the new token information. This maintains continuous guest access without requiring re-initialization.
   *
   * No actor authentication required - the refresh token itself provides sufficient verification for this public endpoint.
   *
   * @setHeader token.access Authorization
   *
   * @param connection
   * @param body Guest token refresh request containing the current refresh token
   * @x-autobe-authorization-type refresh
   * @x-autobe-authorization-actor guest
   * @x-autobe-specification Service implementation: Validate the provided refresh token. Look up existing guest session in erp_hrm_guest_sessions. Verify session is not expired (check expired_at field). Generate new access token with extended expiration. Update session record with new token values and refresh expiration. Return updated IErpHrmGuest.IAuthorized tokens.
   * @nestia Generated by Nestia - https://github.com/samchon/nestia
   */
  @TypedRoute.Post("refresh")
  public async refresh(
    @TypedBody()
    body: IErpHrmGuest.IRefresh,
  ): Promise<IErpHrmGuest.IAuthorized> {
    try {
      return await postErpHrmAuthGuestRefresh({
        body,
      });
    } catch (error) {
      console.log(error);
      throw error;
    }
  }
}
