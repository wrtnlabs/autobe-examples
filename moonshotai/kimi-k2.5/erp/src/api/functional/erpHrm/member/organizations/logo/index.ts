/**
 * Upload or update an organization's logo image.
 *
 * Organizations have exactly one logo attachment that represents the organization visually across the platform interface. This endpoint accepts a logo image file and associates it with the specified organization.
 *
 * When a logo is uploaded, the system stores the file in organization-scoped cloud storage and records the storage reference in the organization's logo_url field. If the organization previously had a logo, the old file is replaced and removed from storage after the new file is successfully stored.
 *
 * Organization logo images are accessible to all users who have access to the organization, including members of the organization and contexts where the organization is referenced. File access is validated on each retrieval request.
 *
 * Upon successful upload, the system broadcasts a confirmation event to organization owners containing the timestamp of successful upload.
 *
 * @param props.connection
 * @param props.organizationId Organization ID (UUID) to update logo
 * @param props.body Logo file URI to upload
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Receive logo image URI in request body. Validate organization exists and belongs to requesting member's organization context. Update organization's logo_url field with new file URI. If previous logo_url exists, schedule old file removal. Update updated_at timestamp. Broadcast logo.upload.success event to organization owners with timestamp.
 * @path /erpHrm/member/organizations/:organizationId/logo
 * @accessor api.functional.erpHrm.member.organizations.logo.uploadLogo
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function uploadLogo(
  connection: IConnection,
  props: uploadLogo.Props,
): Promise<uploadLogo.Response> {
  return true === connection.simulate
    ? uploadLogo.simulate(connection, props)
    : await PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...uploadLogo.METADATA,
          path: uploadLogo.path(props),
          status: null,
        },
        props.body,
      );
}
export namespace uploadLogo {
  export type Props = {
    /**
     * Organization ID (UUID) to update logo
     */
    organizationId: string;

    /**
     * Logo file URI to upload
     */
    body: IErpHrmOrganization.ILogoUpload;
  };
  export type Body = IErpHrmOrganization.ILogoUpload;
  export type Response = IErpHrmOrganization;

  export const METADATA = {
    method: "POST",
    path: "/erpHrm/member/organizations/:organizationId/logo",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
  } as const;

  export const path = (props: Omit<Props, "body">) =>
    `/erpHrm/member/organizations/${encodeURIComponent(props.organizationId ?? "null")}/logo`;
  export const random = (): IErpHrmOrganization =>
    typia.random<IErpHrmOrganization>();
  export const simulate = (
    connection: IConnection,
    props: uploadLogo.Props,
  ): Response => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: uploadLogo.path(props),
      contentType: "application/json",
    });
    try {
      assert.param("organizationId")(() => typia.assert(props.organizationId));
      assert.body(() => typia.assert(props.body));
    } catch (exp) {
      if (!typia.is<HttpError>(exp)) throw exp;
      return {
        success: false,
        status: exp.status,
        headers: exp.headers,
        data: exp.toJSON().message,
      } as any;
    }
    return random();
  };
}

/**
 * Remove the logo image from an organization, reverting to the default placeholder.
 *
 * This operation permanently removes the organization's current logo attachment from storage and reverts the organization's visual identity to the default placeholder image. Only organization owners have permission to remove the organization logo.
 *
 * When the logo is removed:
 * - The logo file is deleted from cloud storage
 * - The organization's logo_url field in erp_hrm_organizations is cleared
 * - The system displays a default placeholder image for the organization
 * - This action is irreversible; a new logo must be uploaded to restore visual identity
 *
 * The operation ensures atomic handling - the file removal and entity update succeed together or fail together, preventing orphaned files or broken references.
 *
 * @param props.connection
 * @param props.organizationId Target organization's ID
 * @x-autobe-authorization-type null
 * @x-autobe-authorization-actor member
 * @x-autobe-specification Implement DELETE operation to remove organization logo attachment.
 *
 * Database operations:
 * 1. Verify requesting user has Owner role for the specified organization
 * 2. Retrieve organization record by organizationId
 * 3. If organization has no logo (logo is null), return organization as-is
 * 4. Otherwise:
 *    - Extract current logo storage reference
 *    - Update organization record: set logo field to null
 *    - Delete the logo file from cloud storage using the storage reference
 *    - Commit transaction
 *
 * Authorization:
 * - Only members with Owner role for the organization can remove the logo
 * - Return 403 Forbidden if user lacks ownership
 *
 * Edge cases:
 * - Organization not found: return 404
 * - User not member of organization: return 403
 * - Logo already null (no logo): return organization without modification
 * - Storage deletion failure: transaction rollback, return 500 error
 *
 * The operation follows the attachment lifecycle pattern where logo deletion is permanent and cannot be undone.
 * @path /erpHrm/member/organizations/:organizationId/logo
 * @accessor api.functional.erpHrm.member.organizations.logo.erase
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
