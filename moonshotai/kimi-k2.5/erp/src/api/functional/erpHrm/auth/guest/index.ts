/**
 * Initialize guest access by creating a guest account identified by device fingerprint.
 *
 * This endpoint creates a temporary guest session for unauthenticated visitors. The device fingerprint uniquely identifies the visitor's browser/device. Upon successful creation, a guest record is established in erp_hrm_guests and a session is created in erp_hrm_guest_sessions with generated JWT tokens.
 *
 * The session includes access and refresh tokens for subsequent API calls. Client metadata (IP address, current href, referrer) is captured for audit purposes. The session has an expiration time after which it becomes invalid.
 *
 * No authentication is required - this is a public endpoint for first-time visitors.
 *
 * @setHeader token.access Authorization
 *
 * @param props.connection
 * @param props.body Guest initialization request with device fingerprint and client metadata
 * @x-autobe-authorization-type join
 * @x-autobe-authorization-actor guest
 * @x-autobe-specification Service implementation: Validate the device
 *   fingerprint from request. Create or find existing guest record by device
 *   fingerprint. Generate new guest session with JWT access and refresh tokens.
 *   Store session in erp_hrm_guest_sessions with IP, href, referrer tracking.
 *   Set expiration based on schema's expired_at pattern. Return tokens in
 *   IErpHrmGuest.IAuthorized format.
 * @path /erpHrm/auth/guest/join
 * @accessor api.functional.erpHrm.auth.guest.join
 * @autobe Generated by AutoBE - https://github.com/wrtnlabs/autobe
 */
export async function join(
  connection: IConnection,
  props: join.Props,
): Promise<join.Response> {
  const output: join.Response =
    true === connection.simulate
      ? join.simulate(connection, props)
      : await PlainFetcher.fetch(
          {
            ...connection,
            headers: {
              ...connection.headers,
              "Content-Type": "application/json",
            },
          },
          {
            ...join.METADATA,
            path: join.path(),
            status: null,
          },
          props.body,
        );
  connection.headers ??= {};
  connection.headers.Authorization = output.token.access;
  return output;
}
